import io

p = 'src/wxhl-combat/engine/loop.ts'
s = io.open(p, encoding='utf-8').read()

# ---------- 1) 回合开始：行动槽与移动额度 吃「反应动作 / 次要行动 / 移动距离」修正 ----------
anchor = "/**\n * 冷却递减（回合开始时调，与行动槽重置同处）。"
if s.count(anchor) != 1:
    anchor = "// ==================== 生死判定（世界书原文） ===================="
assert s.count(anchor) == 1, 'anchor'

helper = """/**
 * 回合开始时的**行动槽**：基础各 1 次，再加上状态携带的「反应动作」「次要行动」修正。
 * 世界书里血统/职业特性常写"额外获得一次反应动作"——那类效果就落在 `数值修正 目标 反应动作`。
 */
export function 回合开始行动槽(单位: 战斗单位) {
  const 槽 = 行动槽重置(单位.行动槽);
  return {
    ...槽,
    反应: Math.max(0, 槽.反应 + 常驻修正(单位, '反应动作')),
    次要: Math.max(0, 槽.次要 + 常驻修正(单位, '次要行动')),
  };
}

/**
 * 回合开始时的**移动额度**：本回合【移动距离】+ 状态携带的「移动距离」修正。
 * （面板值已含装备与「移动距离额外加成」；这里再叠加规则带来的临时增减。）
 */
export function 回合开始额度(单位: 战斗单位): number {
  const 面板移动距离 = (单位.移动距离 ?? 0) > 0 ? 单位.移动距离! : 移动距离计算(单位.属性.实际.AGI, 单位.阶位, 0);
  return Math.max(0, 移动额度重置(面板移动距离) + 常驻修正(单位, '移动距离'));
}

// ==================== 生死判定（世界书原文） ===================="""
s = s.replace(anchor, helper, 1)

# 导入 行动槽重置 / 移动距离计算 / 移动额度重置
s = s.replace("import { 冷却回合数, 解析消耗, 连击词条, 免冷却词条 } from './actionOptions';",
              "import { 冷却回合数, 解析消耗, 连击词条, 免冷却词条 } from './actionOptions';\nimport { 行动槽重置 } from './actionEconomy';\nimport { 移动距离计算, 移动额度重置 } from './distance';", 1)

# ---------- 2) 攻击倍率 / 基础伤害骰 ----------
old = """    const 武器 = 武器伤害(骰值总和, 手持武器?.强化等级 ?? 0, 武器位阶序数(手持武器, 攻击阶位), 属性修正, 手持武器?.倍率 ?? 0.5);"""
new = """    // 「基础伤害骰」= 加在伤害骰总和上的修正（"武器伤害骰+2"这类）；
    // 「攻击倍率」= 加在武器倍率上的修正（"武器威力+30%"这类）。
    // 两者都只取**攻方**身上状态携带的量。
    const 骰值总和_含修正 = 骰值总和 + 常驻修正(攻方, '基础伤害骰');
    const 武器倍率 = (手持武器?.倍率 ?? 0.5) + 常驻修正(攻方, '攻击倍率');
    const 武器 = 武器伤害(
      骰值总和_含修正,
      手持武器?.强化等级 ?? 0,
      武器位阶序数(手持武器, 攻击阶位),
      属性修正,
      武器倍率,
    );"""
assert s.count(old) == 1, 'weapon'
s = s.replace(old, new, 1)

io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('loop ok')
