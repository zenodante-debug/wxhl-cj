// ==================== 领域 ====================

export interface 领域 {
  id: string;
  名: string;
  持续: number;
  中心: string | { x: number };   // 可以是单位 id，也可以是固定坐标
  范围?: string;                   // "半径15米"
  规则: 规则[];
}

// ==================== 待决点 ====================

export type 待决点 =
  | { 类: '打断'; 攻方: string; 守方: string; 技能: 战斗解释 }
  | { 类: '防御'; 攻方: string; 守方: string; 伤害: number }
  | { 类: '转阶段'; id: string; 阈值: string }
  | { 类: '濒死'; id: string; 已成功: number; 已失败: number }
  /**
   * 某单位获得了**额外行动回合**：轮次在这里停下，等我方玩家为它重新指定一轮行动
   * （敌方不参与追加回合 —— 玩家口径「追加回合敌人不出招」）。
   */
  | { 类: '额外行动回合'; id: string };

// ==================== 战斗事件 ====================

export type 战斗事件 =
  | { 类: '开始回合' }
  | { 类: '进入单位'; id: string }
  | { 类: '声明行动'; id: string; 行动: 行动声明 }
  | { 类: '玩家决策'; 选择: any }
  | { 类: '结束回合' };

export interface 行动声明 {
  类型: '主要行动' | '次要行动' | '移动' | '反应动作' | '免费行动';
  技能?: string;
  /** 基础武器攻击用哪把武器（省略技能键时生效）。省略 = 主武器 */
  武器?: '主武器' | '副武器';
  目标?: string;
  距离?: number;      // 移动时的目标距离
}

// ==================== 结算步骤 ====================

export interface 结算步骤 {
  类: string;
  内容: string;
  单位?: string;
}
