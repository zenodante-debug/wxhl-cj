// ==================== 战斗状态 ====================

export interface 战斗状态 {
  进行中: boolean;
  回合: number;
  先攻: string[];                       // 单位 id，按先攻降序
  单位: Record<string, 战斗单位>;
  待决: 待决点 | null;                  // 非空 = 暂停中
  领域: 领域[];                         // 战场上的领域（元素禁区/保存神域…）
}

export interface 战斗单位 {
  id: string;        // 变量路径键：'契约者' | '小队.成员.白露露' | '副本角色.骨卫兵'
  /** 显示名（变量里的 头部.姓名；缺省/老存档退回 id 末段）。界面/日志一律用它，不要把「契约者」当名字。 */
  名称?: string;
  阵营: '我方' | '敌方';
  类型: string;      // 杂兵/精英/BOSS/… → 决定 HP 系数与致命效果分层
  属性: { 实际: { STR: number; AGI: number; CON: number; PER: number } };
  阶位: string;      // 一阶/二阶/… → 决定修正系数与基础DC
  HP_当前: number;
  HP_最大: number;
  MP_当前: number;
  MP_最大: number;
  耐力_当前: number;
  耐力_最大: number;
  防御: number;
  闪避值: number;
  /** 移动距离（= 每回合移动额度上限，读自 衍生属性.移动距离，含额外加成；缺省/老存档按公式现算） */
  移动距离?: number;
  距离: number;      // 距玩家米数；-1 = 已脱离
  行动槽: 行动槽;
  额度: number;      // 本回合剩余移动额度（米），每回合重置为【移动距离】
  冷却: Record<string, number>;         // 技能名 → 剩余回合
  护盾: number;
  架势: { 类型: string; 层数: number } | null;
  状态: 状态条目[];  // 流血/灼烧/破甲… 含层数与剩余回合
  濒死: { 成功: number; 失败: number } | null;
  资源: Record<string, number>;         // 任意命名资源（保存/充能/加护/冻结标记…）
  词条: Set<string>; // 标签（不可被常规攻击命中/禁位移/禁回复…）
  技能: Record<string, 战斗解释>; // 一次性翻译出的「技能名 → 战斗解释」；无技能时为空对象 {}
  /** 主武器（开战时从 `实体.装备.主武器` 读入）；缺省 = 徒手（骰式随阶位 d4→11d4、倍率 0.5、强化 0） */
  主武器?: { 伤害骰: string; 倍率: number; 强化等级: number; 阶位?: string };
  /** 副武器（`实体.装备.副武器`）；次要行动的「副武器攻击」用它，缺省则次要行动没有基础攻击 */
  副武器?: { 伤害骰: string; 倍率: number; 强化等级: number; 阶位?: string };
  /** 已装备的东西（开战时从卡里拍平，**只用于界面展示**，引擎不读它做判定） */
  装备?: Array<{ 槽: string; 名称: string; 摘要: string }>;
  /**
   * 本回合还欠着的**额外行动回合**次数（`数值修正 目标 额外行动回合` 落上来的）。
   *
   * 玩家口径：「额外行动次数也是创造额外回合了，也就是在这一轮中，行动完了，
   * 能够再多一个行动回合」+「多一个回合的本质是多一倍的行动槽」——
   * 一次追加回合 = 一整套行动槽（主/次/移/反各 +1）+ 再一份移动额度，且**当场打断**让玩家重选。
   * 每次消耗 1 层；上限见 `追加回合上限`（防跑飞）。
   */
  追加行动?: number;
  /**
   * 本回合**预置的反应技能**（技能名）。被攻击时自动使用（玩家裁决：「有预置就自动用，
   * 没预置就跳过」）—— 不再有预设的招架/识破，**必须是学过的、行动类型为反应动作的技能**。
   * 每次被命中消耗一个反应槽，并照常进冷却、扣资源。
   */
  预置反应?: string;
  /** 本场各技能的**已用次数**（配合 `战斗解释.每场限次`；随战斗快照持久化） */
  已用次数?: Record<string, number>;
  /**
   * **技能词条**：挂在"技能"这一层（不是单位身上）的标签，供条件 `{源:'技能词条'}` 读。
   * 用途：「该技能下一次释放×2 伤害」这类连携（先挂标签，再让带条件的规则认出来）。
   * 存成数组（不是 Set）—— 它要随战斗快照走，JSON 里没有 Set。
   */
  技能词条?: Record<string, string[]>;
  /**
   * **技能加成**：给某技能的**下一次**释放加数值修正（目标 → 量），用完即清。
   * 用途：「使下一个伤害技能伤害 +50%」—— 被加成的技能自己卡面上并不知道这件事，
   * 所以只能记在单位身上、由 `结算技能` 读进来并清掉。
   */
  技能加成?: Record<string, Record<string, number>>;
}

export interface 行动槽 {
  主要: number;
  次要: number;
  移动: number;
  反应: number;
  免费: number;      // Infinity 语义，实际存储为大数
}

export interface 状态条目 {
  名: string;
  持续: number;
  层数?: number;
  词条?: string[];
  /**
   * 状态携带的数值修正（伤害/减伤/命中/闪避…）。
   * 由 `规则.动作.数值修正` 落成状态时写入 —— 引擎没有别的字段能承载"给友军 +30% 伤害"
   * 这类效果，`常驻修正` 在读数值时会把它一并算入。
   */
  数值修正?: Record<string, number>;
}

// ==================== 战斗解释 ====================

export interface 战斗解释 {
  // 直读字段 —— 技能自带，不用 AI
  /**
   * **行动类型**（主要行动/次要行动/反应动作/免费行动/无）—— 注意它**不是**资源消耗 `消耗`。
   * 允许**数组**：一条技能可以挂多个类型（卡面「【八咫镜·光行】(次要行动 **或** 反应动作)」），
   * 于是它在每个匹配的下拉里都出现，用掉时扣**所选**那个槽。
   * 也容忍「次要行动/反应动作」这种串 —— 归一化在 `actionOptions.规范行动消耗列表`（全引擎一份）。
   */
  行动消耗: string | string[];
  射程: string;
  目标: string;
  消耗: string;
  /** 冷却（回合数）。玩家口径：**技能最小 1 回合**，没写/写 0 都按 1 算（见 冷却回合数） */
  冷却: number;
  分类: string;
  类型: string;
  可预判: boolean;

  // 六步伤害与命中要用的数值 —— 由翻译器从技能实体的真实字段读出（可选：老存档缺省时按兜底走）
  /** 关联属性（近战物理=STR / 远程物理=AGI / 魔法=PER）；决定命中与技能伤害用哪一维修正值 */
  关联属性?: 'STR' | 'AGI' | 'CON' | 'PER';
  /** 技能阶位序数 1~5（命中公式的成长项与技能伤害的 `(1+(阶位−1)/2)`） */
  技能阶位?: number;
  /** 伤害倍率：世界书 <技能模版和限制>，技能伤害 = 关联属性修正值 × 伤害倍率 */
  伤害倍率?: number;
  /**
   * **多属性加权伤害**：卡面写「造成 PER×3.6 + AGI×3.2 的伤害」这种，一条
   * `关联属性 × 伤害倍率` 表达不了。
   *
   * 写了它 → 技能伤害的基础值 = **Σ(该属性修正值 × 系数)**（再按技能阶位成长），
   * 此时 `伤害倍率` 不再叠加（两者取一个，别重复计一次伤害）。
   * 不写 → 完全照旧走 `关联属性修正 × 伤害倍率`（老存档行为不变）。
   */
  属性加权?: { 属性: 'STR' | 'AGI' | 'CON' | 'PER'; 系数: number }[];
  /** 声明攻击部位（第二步_部位锁定）；不声明 = 无部位加成 */
  部位?: 攻击部位;
  /**
   * **这个技能/装备自己的伤害骰**（卡面里写了「伤害骰：20d40」的装备，比如零号超巨星机甲）。
   * 写了它 → 武器部分用它的骰子（不是主武器的）；没写 → 退回主武器（老行为）。
   */
  伤害骰?: string;
  /**
   * **这个技能/装备自己的倍率**（卡面里写了「倍率：20.0」的装备，比如零号超巨星机甲）。
   * 写了它 → 武器部分用它的倍率（不是主武器的）；没写 → 退回释放来源的武器（老行为）。
   */
  倍率?: number;
  /**
   * **这条子技能自己的名字**（技能表里的键）—— 只在"一个卡面条目拆出好几招"时有意义。
   * 由翻译层按命名约定填：卡面自带名优先（`八咫镜·光行`），否则 `母技能·说明`。
   */
  名称?: string;
  /**
   * **母条目**：这条子技能是从哪个卡面条目拆出来的（如 `光子化身`）。
   * **只用于界面分组**（"这几招同源"），不参与任何判定。由引擎填，不信模型。
   */
  母条目?: string;

  // AI 翻译出的规则列表 —— 引擎按触发点跑
  规则: 规则[];

  // 翻译不了的，原文留底 + 指定触发点，走托管
  托管: 托管[];
  /**
   * **拆解清单**：翻译时模型对卡面效果的逐句枚举（"会产生效果的句子"，不含气氛描写）。
   *
   * 为什么要有：卡片的效果原文常是一大段散文（还夹着「极意」段），模型容易整体放弃、
   * 只回一个最小骨架（`伤害倍率 5.5` + `规则: []`）—— 卡面里五件事全部蒸发。
   * 让它**先枚举再映射**，既提高拆全的概率，也给了我们一个校验信号：
   * **列了却一条规则都没有 → 判失败进复核**（原因里点名它自己列的条目）。
   */
  拆解?: string[];
  /**
   * **每场限次**：整场战斗最多用几次（"每场限2次"这种）。省略 = 不限次。
   * 用尽后该技能直接从行动里被拦下（日志写明"本场已用尽 N/N"）。
   */
  每场限次?: number;
  /**
   * 翻译时被**丢掉**的规则条数（结构不完整：没触发点 / 空动作 / 动作不是对象）。
   * 详情面板会显示一行提示 —— 静默少几条效果比报错更糟（玩家实测丢过整件装备的被动）。
   */
  忽略的规则?: number;
}

export interface 规则 {
  触发: 触发点;
  条件?: 条件;
  作用域: 作用域;
  动作: 动作[];
}

export type 触发点 =
  | '常驻'
  | '进入战斗'
  | '回合开始'
  | '回合结束'
  | '攻击时'
  | '命中时'
  | '受击时'
  | '被命中后'
  | '击杀时'
  | '资源变化时'
  | '使用时'
  /**
   * **转阶段**：BOSS/隐藏BOSS 当前 HP **首次**降到阶段线（70%/40%/20%）或被打到 0 时，
   * 立即跑它自己的这条规则（世界书 <combat_driver> 阶段D：清负面、回 HP/MP、拿护盾/无敌）。
   * 非 BOSS 不触发 —— 这是 BOSS 的机制。
   */
  | '转阶段';

export type 作用域 =
  | '自身'
  | '我方全体'
  | '敌方全体'
  | '攻击目标'
  | '攻击者'
  | '命中点'
  /**
   * **范围内全体** —— 只在**领域**里有意义：领域半径内的所有单位，不分阵营
   * （卡面「领域内所有单位每回合…」）。别的作用域在领域里也认，但会**再按半径筛一次**。
   */
  | '范围内全体';

export interface 条件 {
  左: 取值;
  比较: '≥' | '>' | '≤' | '<' | '=';
  右: 取值;
}

export interface 取值 {
  源:
    | '资源'
    | '属性'
    | '常数'
    | '层数'
    | '最终伤害'
    | '溢出伤害'
    | '目标HP'
    | '目标词条'
    /** **技能词条**：读"正在释放的那个技能"身上的标签（连携：「如果某技能被强化过就…」）*/
    | '技能词条'
    | '表达式';
  名?: string;       // 资源名/属性名/词条名
  系数?: number;
  取整?: '下取整' | '上取整';
  式?: string;       // 表达式（如 "(最大HP+最大MP)×PER修正×2"）
}

export type 动作 =
  | { 类: '资源'; 名: string; 操作: '获得' | '消耗' | '设为' | '恢复'; 量: 取值; 衰减?: 取值 }
  | { 类: '护盾'; 量: 取值 }
  /**
   * 数值修正。**持续**可选：不写按默认 2 回合；变身/觉醒这类"整场生效"的写 999。
   * （状态名 = 技能名，同名后覆盖先 —— 一次性变身建议配合「词条 + 条件分支」做唯一触发）
   */
  | { 类: '数值修正'; 目标: 数值修正目标; 量: 取值; 不可净化?: boolean; 持续?: number }
  | { 类: '施加状态'; 名: string; 持续: number; 层数?: 取值; 词条?: string[] }
  | { 类: '词条'; 名: string; 操作?: '附加' | '移除' }
  | { 类: '领域'; 名: string; 持续: number; 范围?: string; 规则: 规则[] }
  | { 类: '切换形态'; 到: string }
  | { 类: '追加攻击'; 次数: number }
  | { 类: '范围伤害'; 中心: string; 半径: number; 量: 取值 }
  | { 类: '条件分支'; 条件: 条件; 真: 动作[]; 假: 动作[] }
  /**
   * **技能级作用**（能力连携，2026-10-09 玩家追加需求）。
   *
   * 玩家口径：「还有能力与能力之间的连携，比如，一个技能是取消一个可选技能的冷却」+
   * 「冷却只是一个例子，还可能有伤害连携、什么乱七八糟的联动」——
   * 所以这不是"一个清冷却的动作"，而是**作用于"技能"这一层**的动作族：
   * 改它的冷却、改它的每场限次、给它挂标签（供条件读）、或给它下一次释放加数值。
   *
   * | 操作 | 干什么 |
   * | :--- | :--- |
   * | `清冷却` | 剩余冷却清零 |
   * | `减冷却` | 冷却 − 量（下限 0） |
   * | `重置次数` | 每场限次的"已用"清零 |
   * | `加次数` | 已用 − 量（下限 0）= 多几次 |
   * | `挂词条` / `移除词条` | 给该技能挂/摘标签，供条件 `{源:'技能词条'}` 读 |
   * | `技能加成` | 给它**下一次**释放加数值修正（目标 + 量），用完即清 |
   *
   * 认不得的 `操作` → 战报里记一行跳过（不静默）。
   */
  | {
      类: '技能作用';
      操作: '清冷却' | '减冷却' | '重置次数' | '加次数' | '挂词条' | '移除词条' | '技能加成';
      /**
       * 作用对象：`选中技能`（玩家在下拉里选的）／`当前技能`（正在放的这一条）／
       * `全部`（该单位所有技能）／**具体技能名**。省略 = `当前技能`。
       */
      名?: string;
      /** `减冷却` 的回合数 / `加次数` 的量 / `技能加成` 的数值 */
      量?: 取值;
      /** `技能加成` 加在哪个数值修正目标上（伤害/命中/减伤…） */
      目标?: 数值修正目标;
      /** `挂词条` / `移除词条` 的词条名 */
      词条?: string;
    }
  | {
      类: '规则系判定';
      效果: 规则系效果;
      目标: string;
      /**
       * **程度**（0~1）：`穿透` 用 —— 0.5 = 无视目标 50% 的防御与抗性；
       * 省略或 1 = 全穿（防御归 0、护盾与减伤一并跳过，即旧行为）。
       */
      程度?: number;
      /**
       * **限定**：`免疫`/`无敌` 用 —— 例如「常规物理」只挡物理（STR/AGI 攻击），魔法照旧打得进；
       * 省略 = 全免。
       */
      限定?: string;
    };

export type 数值修正目标 =
  | '伤害'
  /** 真·最终伤害倍率（增量写法：填 4 = 最终伤害 ×5）。
   *  与「伤害」的区别：「伤害」进**效果乘区**（世界书的递减曲线，×5 表达不出来），
   *  「最终乘区」是直接乘在最终伤害上 —— 卡面写"该次攻击最终伤害×N"就该用它。 */
  | '最终乘区'
  | '减伤'
  | '命中'
  | '闪避'
  | '反应动作'
  | '次要行动'
  /** 每回合的主要行动**次数**（"额外获得一次主要行动"这类，与反应/次要行动同理） */
  | '主要行动'
  /** **额外行动回合**：给一整套行动槽（主/次/移/反各 +1）并当场打断重选 ——
   *  与「主要行动/次要行动」（回合开始只给那一个类型 +1 个槽）是两条并存的写法，
   *  按卡面文本分流：「额外一次主要行动」用前者，「额外行动回合/额外行动次数」用这个。 */
  | '额外行动回合'
  | '移动距离'
  | '攻击倍率'
  | '基础伤害骰'
  | '最大HP上限'
  | '全元素抗性'
  /** 平砍值（第六步之前从混合伤害里减掉的那个）—— 「清空防御」「防御+X」用它 */
  | '防御'
  /**
   * **锁血下限**（比例，0.5 = 最大HP的 50%）：一次攻击把 HP 打到低于这条线时，
   * 只锁在线上（玩家口径：「无法一次跌入 50% 以下的血量，必须当前回合先锁在最低 50%」）。
   * 与规则系「锁血」（HP 不低于 1）是两回事，可同时存在。
   */
  | '锁血下限'
  /**
   * 四维**属性点**增量（不是修正值）：引擎会按位阶系数换算成修正值，
   * 所以卡面写「STR+10」就直接填 10，不用自己乘系数。
   * 用途：「献祭防御换取等量 STR/AGI」这类换属性效果。
   */
  | 'STR'
  | 'AGI'
  | 'CON'
  | 'PER'
  /**
   * 四维**修正值**直接增量（不再乘位阶系数）—— 卡面写「STR修正+20」「全属性修正-30%」
   * 这类**直接动修正值**的效果用它。所有判定与伤害用的都是修正值（世界书：
   * 「属性修正值 =（实际属性值−5）×位阶系数，用于所有判定与伤害」），
   * 所以"真正重要的是属性修正值而不是属性"——直接改修正值才是有意义的写法。
   * 与 STR/AGI/CON/PER（属性点，×位阶系数换算）是两条独立通道，可叠加。
   */
  | 'STR修正'
  | 'AGI修正'
  | 'CON修正'
  | 'PER修正';

