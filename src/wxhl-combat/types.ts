import type { 攻击部位 } from './engine/damage';

// ==================== 战斗状态 ====================

export interface 战斗状态 {
  进行中: boolean;
  回合: number;
  先攻: string[];                       // 单位 id，按先攻降序
  单位: Record<string, 战斗单位>;
  待决: 待决点 | null;                  // 非空 = 暂停中
  领域: 领域[];                         // 战场上的领域（元素禁区/保存神域…）
}

export interface 战斗单位 {
  id: string;        // 变量路径键：'契约者' | '小队.成员.白露露' | '副本角色.骨卫兵'
  阵营: '我方' | '敌方';
  类型: string;      // 杂兵/精英/BOSS/… → 决定 HP 系数与致命效果分层
  属性: { 实际: { STR: number; AGI: number; CON: number; PER: number } };
  阶位: string;      // 一阶/二阶/… → 决定修正系数与基础DC
  HP_当前: number;
  HP_最大: number;
  MP_当前: number;
  MP_最大: number;
  耐力_当前: number;
  耐力_最大: number;
  防御: number;
  闪避值: number;
  距离: number;      // 距玩家米数；-1 = 已脱离
  行动槽: 行动槽;
  额度: number;      // 本回合剩余移动额度（米），每回合重置为【移动距离】
  冷却: Record<string, number>;         // 技能名 → 剩余回合
  护盾: number;
  架势: { 类型: string; 层数: number } | null;
  状态: 状态条目[];  // 流血/灼烧/破甲… 含层数与剩余回合
  濒死: { 成功: number; 失败: number } | null;
  资源: Record<string, number>;         // 任意命名资源（保存/充能/加护/冻结标记…）
  词条: Set<string>; // 标签（不可被常规攻击命中/禁位移/禁回复…）
  技能: Record<string, 战斗解释>; // 一次性翻译出的「技能名 → 战斗解释」；无技能时为空对象 {}
  /** 主武器（开战时从 `实体.装备.主武器` 读入）；缺省 = 徒手（1d4、倍率 0.5、强化 0） */
  主武器?: { 伤害骰: string; 倍率: number; 强化等级: number; 阶位?: string };
}

export interface 行动槽 {
  主要: number;
  次要: number;
  移动: number;
  反应: number;
  免费: number;      // Infinity 语义，实际存储为大数
}

export interface 状态条目 {
  名: string;
  持续: number;
  层数?: number;
  词条?: string[];
  /**
   * 状态携带的数值修正（伤害/减伤/命中/闪避…）。
   * 由 `规则.动作.数值修正` 落成状态时写入 —— 引擎没有别的字段能承载"给友军 +30% 伤害"
   * 这类效果，`常驻修正` 在读数值时会把它一并算入。
   */
  数值修正?: Record<string, number>;
}

// ==================== 战斗解释 ====================

export interface 战斗解释 {
  // 直读字段 —— 技能自带，不用 AI
  行动消耗: string;
  射程: string;
  目标: string;
  消耗: string;
  冷却: number;
  分类: string;
  类型: string;
  可预判: boolean;

  // 六步伤害与命中要用的数值 —— 由翻译器从技能实体的真实字段读出（可选：老存档缺省时按兜底走）
  /** 关联属性（近战物理=STR / 远程物理=AGI / 魔法=PER）；决定命中与技能伤害用哪一维修正值 */
  关联属性?: 'STR' | 'AGI' | 'CON' | 'PER';
  /** 技能阶位序数 1~5（命中公式的成长项与技能伤害的 `(1+(阶位−1)/2)`） */
  技能阶位?: number;
  /** 伤害倍率：世界书 <技能模版和限制>，技能伤害 = 关联属性修正值 × 伤害倍率 */
  伤害倍率?: number;
  /** 声明攻击部位（第二步_部位锁定）；不声明 = 无部位加成 */
  部位?: 攻击部位;

  // AI 翻译出的规则列表 —— 引擎按触发点跑
  规则: 规则[];

  // 翻译不了的，原文留底 + 指定触发点，走托管
  托管: 托管[];
}

export interface 规则 {
  触发: 触发点;
  条件?: 条件;
  作用域: 作用域;
  动作: 动作[];
}

export type 触发点 =
  | '常驻'
  | '进入战斗'
  | '回合开始'
  | '回合结束'
  | '攻击时'
  | '命中时'
  | '受击时'
  | '被命中后'
  | '击杀时'
  | '资源变化时'
  | '使用时';

export type 作用域 =
  | '自身'
  | '我方全体'
  | '敌方全体'
  | '攻击目标'
  | '攻击者'
  | '命中点';

export interface 条件 {
  左: 取值;
  比较: '≥' | '>' | '≤' | '<' | '=';
  右: 取值;
}

export interface 取值 {
  源: '资源' | '属性' | '常数' | '层数' | '最终伤害' | '溢出伤害' | '目标HP' | '目标词条' | '表达式';
  名?: string;       // 资源名/属性名/词条名
  系数?: number;
  取整?: '下取整' | '上取整';
  式?: string;       // 表达式（如 "(最大HP+最大MP)×PER修正×2"）
}

export type 动作 =
  | { 类: '资源'; 名: string; 操作: '获得' | '消耗' | '设为' | '恢复'; 量: 取值; 衰减?: 取值 }
  | { 类: '护盾'; 量: 取值 }
  | { 类: '数值修正'; 目标: 数值修正目标; 量: 取值; 不可净化?: boolean }
  | { 类: '施加状态'; 名: string; 持续: number; 层数?: 取值; 词条?: string[] }
  | { 类: '词条'; 名: string; 操作?: '附加' | '移除' }
  | { 类: '领域'; 名: string; 持续: number; 范围?: string; 规则: 规则[] }
  | { 类: '切换形态'; 到: string }
  | { 类: '追加攻击'; 次数: number }
  | { 类: '范围伤害'; 中心: string; 半径: number; 量: 取值 }
  | { 类: '条件分支'; 条件: 条件; 真: 动作[]; 假: 动作[] }
  | { 类: '规则系判定'; 效果: 规则系效果; 目标: string };

export type 数值修正目标 =
  | '伤害'
  | '减伤'
  | '命中'
  | '闪避'
  | '反应动作'
  | '次要行动'
  | '移动距离'
  | '攻击倍率'
  | '基础伤害骰'
  | '最大HP上限'
  | '全元素抗性';

export type 规则系效果 =
  | '穿透'
  | '必中'
  | '必暴'
  | '即死'
  | '无敌'
  | '锁血'
  | '无视';

export interface 托管 {
  原文: string;
  触发点: 触发点[];
}

// ==================== 领域 ====================

export interface 领域 {
  id: string;
  名: string;
  持续: number;
  中心: string | { x: number };   // 可以是单位 id，也可以是固定坐标
  范围?: string;                   // "半径15米"
  规则: 规则[];
}

// ==================== 待决点 ====================

export type 待决点 =
  | { 类: '打断'; 攻方: string; 守方: string; 技能: 战斗解释 }
  | { 类: '防御'; 攻方: string; 守方: string; 伤害: number }
  | { 类: '转阶段'; id: string; 阈值: string }
  | { 类: '濒死'; id: string; 已成功: number; 已失败: number };

// ==================== 战斗事件 ====================

export type 战斗事件 =
  | { 类: '开始回合' }
  | { 类: '进入单位'; id: string }
  | { 类: '声明行动'; id: string; 行动: 行动声明 }
  | { 类: '玩家决策'; 选择: any }
  | { 类: '结束回合' };

export interface 行动声明 {
  类型: '主要行动' | '次要行动' | '移动' | '反应动作' | '免费行动';
  技能?: string;
  目标?: string;
  距离?: number;      // 移动时的目标距离
}

// ==================== 结算步骤 ====================

export interface 结算步骤 {
  类: string;
  内容: string;
  单位?: string;
}
