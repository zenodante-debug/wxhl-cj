import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 玩家实测（2026-10-10）：「现在的技能伤害是不包括武器骰的，应该加进去」
//
// 根因：`结算技能` 里 `基础伤害 = 武器 + 技能`，但 `武器` 用的是**主武器**的骰值 ——
// 卡面里写了「伤害骰：20d40」的装备（零号超巨星机甲），它的骰值根本没进伤害。
// 且：技能释放来源没有"选武器/徒手"这一栏 —— 武器骰该算哪一把，现在没得选。
//
// 修法：
// - `结算技能` 里读 `解释.伤害骰`（卡面里写了就优先用它，否则退回主武器）；
// - **释放来源**：`行动声明` 加一个 `武器来源?: '主武器' | '副武器' | '徒手'`，
//   界面上技能释放时让玩家选（默认主武器）；没选就用主武器（老行为）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };
// ⚠️ 注入的 `伤害骰: [6]` 是**骰值数组，求和 = 6**（不是"20 颗骰子各 6 点"）。
// STR 10 一阶 → 修正值 (10−5)×1 = 5。武器伤害 = ⌈(骰值总和 + 强化)×1 + 修正⌉ × 倍率。

describe('技能伤害含武器骰 + 释放来源（玩家实测：技能伤害不含武器骰）', () => {
  it('卡面写了「伤害骰：20d40」的装备 → 武器部分用它的骰子（不是主武器的）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
      技能: {
        主炮直击: 造解释({
          伤害骰: '20d40', // 卡面写了 —— 该用它，不是主武器的 2d6
          倍率: 20.0,
          伤害倍率: 0,
        }),
      },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '主炮直击', 目标: '骨卫兵' }, 骰);

    // 骰值总和 6 → 武器 = ⌈(6+0)×1 + 5⌉ × 20.0 = 220
    // （若是主武器的 2d6 倍率 1.0，只会是 11 —— 差一个数量级，一眼就能看出用没用对）
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(10000 - 220);
  });

  it('没写「伤害骰」的技能 → 武器部分用主武器的骰子（老行为）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
      技能: { 斩击: 造解释({ 伤害倍率: 0 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    // 主武器 2d6 → 武器 = ⌈(6+0)×1 + 5⌉ × 1.0 = 11
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(10000 - 11);
  });

  it('释放来源选了「徒手」→ 武器部分用徒手骰（**不能落回主武器**）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
      技能: { 斩击: 造解释({ 伤害倍率: 0 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(
      状态,
      状态.单位.契约者,
      { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵', 武器来源: '徒手' },
      骰,
    );

    // 徒手（一阶 1d4、倍率 0.5）→ 武器 = ⌈(6+0)×1 + 5⌉ × 0.5 = ⌈5.5⌉ = 6
    // （早先这里会落回主武器 → 打出 11）
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(10000 - 6);
  });

  it('释放来源选了「副武器」→ 武器部分用副武器的骰子', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
      副武器: { 伤害骰: '1d8', 倍率: 0.8, 强化等级: 0, 阶位: '一阶' },
      技能: { 斩击: 造解释({ 伤害倍率: 0 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(
      状态,
      状态.单位.契约者,
      { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵', 武器来源: '副武器' },
      骰,
    );

    // 副武器 1d8 × 0.8 → 武器 = ⌈(6+0)×1 + 5⌉ × 0.8 = ⌈8.8⌉ = 9
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(10000 - 9);
  });

  it('没写「释放来源」→ 用主武器（老行为）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
      副武器: { 伤害骰: '1d8', 倍率: 0.8, 强化等级: 0, 阶位: '一阶' },
      技能: { 斩击: 造解释({ 伤害倍率: 0 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    // 主武器 2d6 → 武器 = ⌈(6+0)×1 + 5⌉ × 1.0 = 11
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(10000 - 11);
  });
});
