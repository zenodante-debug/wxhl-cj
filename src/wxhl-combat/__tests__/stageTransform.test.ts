import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动, 跑一个回合 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家设计的角色（原文）：
//   「血量归零时进入二阶段，回满血并且全属性翻倍。注意，这种变身类技能只能触发一次。」
//
// 这张卡需要的引擎能力：
//   - `资源变化时` 触发 + `当前HP ≤ 0` 条件（已存在）
//   - **一次触发**：`条件分支` + `目标词条`（变身挂「已二阶段」，第二次归零走空分支）
//   - **回满血**：`资源` 动作的 `HP/MP/耐力` 映射到真实字段（本次新增 —— 以前只进资源池）
//   - **全属性翻倍**：`数值修正 目标 STR修正`，量 = 当前修正值（修正值翻倍 ≈ 战斗意义的全属性翻倍）
//   - **整场持续**：`数值修正.持续`（本次新增 —— 以前只能默认 2 回合）
//   - 回血超过 0 → 清濒死标记（复活语义）
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 200,
    HP_最大: 200,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 30,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [敌方.id, 我方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 这张卡的技能：血量归零时进入二阶段（回满血 + 全属性翻倍，只触发一次） */
const 二阶段技能: 战斗解释 = {
  行动消耗: '无',
  射程: '自身',
  目标: '自身',
  消耗: '无',
  冷却: 0,
  分类: '基础',
  类型: '被动',
  可预判: false,
  伤害倍率: 0,
  规则: [
    {
      触发: '资源变化时',
      条件: { 左: { 源: '表达式', 式: '当前HP' }, 比较: '≤', 右: { 源: '常数', 系数: 0 } },
      作用域: '自身',
      动作: [
        {
          类: '条件分支',
          条件: { 左: { 源: '目标词条', 名: '已二阶段' }, 比较: '=', 右: { 源: '常数', 系数: 0 } },
          真: [
            { 类: '资源', 名: 'HP', 操作: '设为', 量: { 源: '表达式', 式: '最大HP' } },
            { 类: '数值修正', 目标: 'STR修正', 量: { 源: '属性', 名: 'STR' }, 持续: 999 },
            { 类: '数值修正', 目标: 'AGI修正', 量: { 源: '属性', 名: 'AGI' }, 持续: 999 },
            { 类: '数值修正', 目标: 'CON修正', 量: { 源: '属性', 名: 'CON' }, 持续: 999 },
            { 类: '数值修正', 目标: 'PER修正', 量: { 源: '属性', 名: 'PER' }, 持续: 999 },
            { 类: '切换形态', 到: '二阶段' },
            { 类: '词条', 名: '已二阶段' },
          ],
          假: [],
        },
      ],
    } as 规则,
  ],
  托管: [],
};

const 骰 = { 命中: 18, 伤害骰: [20] };

/** 敌方打一发：高伤害，能把角色打到 0 */
function 敌方打(状态: 战斗状态) {
  const r = 结算行动(状态, 状态.单位.骨卫兵, { 类型: '主要行动', 技能: '重击', 目标: '契约者' }, 骰);
  return r.状态;
}

function 造局面(HP = 5): 战斗状态 {
  const 角色 = 造单位({ id: '契约者', 阵营: '我方', HP_当前: HP, 主武器: { 伤害骰: '2d6', 倍率: 1, 强化等级: 0 }, 技能: { 二阶段觉醒: 二阶段技能 } });
  const 敌 = 造单位({
    id: '副本角色.骨卫兵',
    阵营: '敌方',
    属性: { 实际: { STR: 30, AGI: 10, CON: 20, PER: 10 } },
    技能: {
      重击: {
        行动消耗: '主要行动',
        射程: '近战',
        目标: '单体',
        消耗: '无',
        冷却: 0,
        分类: '基础',
        类型: '主动',
        可预判: true,
        关联属性: 'STR',
        技能阶位: 1,
        伤害倍率: 3,
        规则: [],
        托管: [],
      },
    },
  });
  return 开战规则结算(造状态(角色, 敌));
}

describe('二阶段变身角色（血量归零 → 回满血 + 全属性翻倍，只触发一次）', () => {
  it('HP 被打到 0 的瞬间：回满血、清濒死、挂形态与「已二阶段」词条', () => {
    const 后 = 敌方打(造局面());
    const 角色 = 后.单位.契约者;

    expect(角色.HP_当前).toBe(角色.HP_最大); // 回满血
    expect(角色.濒死).toBe(null); // 复活：濒死标记清掉
    expect(角色.状态.some(s => s.名 === '形态：二阶段')).toBe(true);
    expect(角色.词条.has('已二阶段')).toBe(true);
  });

  it('**全属性翻倍**：四个修正值都翻倍，且持续是整场（999）', () => {
    const 后 = 敌方打(造局面());
    const 角色 = 后.单位.契约者;
    const 翻倍 = 角色.状态.find(s => s.名 === '二阶段觉醒');

    // 一阶 STR 20 → 修正值 15；翻倍 = 再 +15
    expect(翻倍?.数值修正?.STR修正).toBe(15);
    expect(翻倍?.数值修正?.CON修正).toBe(15);
    expect(翻倍?.数值修正?.AGI修正).toBe(5);
    expect(翻倍?.数值修正?.PER修正).toBe(5);
    expect(翻倍?.持续).toBe(999); // 整场，不是默认 2 回合
  });

  it('翻倍**真的进伤害**：变身后反打的伤害比变身前高', () => {
    const 打一发 = (状态: 战斗状态) => {
      const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' }, { 命中: 18, 伤害骰: [6] });
      return { 伤害: r.状态.单位.骨卫兵.HP_当前, 状态: r.状态 };
    };
    const 角色 = 造单位({ id: '契约者', 阵营: '我方', 主武器: { 伤害骰: '2d6', 倍率: 1, 强化等级: 0 }, 技能: { 二阶段觉醒: 二阶段技能 } });
    const 敌满血 = () => 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 100000, HP_最大: 100000 });

    // 变身前
    const 前 = 打一发(开战规则结算(造状态(角色, 敌满血())));
    // 变身后（手搓一个已变身的状态：HP 满 + 翻倍状态在身）
    const 已变身局面 = 敌方打(造局面(5));
    const 后 = 打一发({ ...已变身局面, 单位: { ...已变身局面.单位, 骨卫兵: 敌满血() } });

    const 变身前伤害 = 100000 - 前.伤害;
    const 变身后伤害 = 100000 - 后.伤害;
    expect(变身后伤害).toBeGreaterThan(变身前伤害);
  });

  it('**只能触发一次**：再次归零不重复变身，正常进濒死', () => {
    let 状态 = 敌方打(造局面());
    expect(状态.单位.契约者.HP_当前).toBe(状态.单位.契约者.HP_最大); // 第一次：变身成功

    // 第二次被打到 0（手动把血压回低位再挨打；第一击已经把敌方的主要槽扣掉，重置它）
    状态.单位.契约者 = { ...状态.单位.契约者, HP_当前: 5 };
    状态.单位.骨卫兵 = { ...状态.单位.骨卫兵, 行动槽: { ...状态.单位.骨卫兵.行动槽, 主要: 1 }, 冷却: {} };
    状态 = 敌方打(状态);
    const 角色 = 状态.单位.契约者;

    expect(角色.HP_当前).toBe(0); // 没有再回血
    expect(角色.濒死).not.toBe(null); // 正常进濒死
    // 翻倍状态只有一条（没有叠第二次）
    expect(角色.状态.filter(s => s.名 === '二阶段觉醒')).toHaveLength(1);
  });

  it('普通掉血（没到 0）不触发（条件就是"归零才变"）', () => {
    const 状态 = 造局面(100); // HP 100/200，挨一发重击（修正 25×3 + 骰，掉血但死不了）
    const 后 = 敌方打(状态);
    const 角色 = 后.单位.契约者;

    expect(角色.HP_当前).toBeGreaterThan(0);
    expect(角色.HP_当前).toBeLessThan(角色.HP_最大); // 挨了打
    expect(角色.词条.has('已二阶段')).toBe(false);
    expect(角色.状态.some(s => s.名 === '形态：二阶段')).toBe(false);
  });

  it('跑一个回合里敌方出手也能触发（不是只在单独结算时生效）', () => {
    const 状态 = 造局面(5);
    const r = 跑一个回合(状态, {}, [{ 单位: '骨卫兵', 行动: [{ 类型: '主要行动', 技能: '重击', 目标: '契约者' }] }]);

    expect(r.状态.单位.契约者.HP_当前).toBe(r.状态.单位.契约者.HP_最大);
    expect(r.步骤.some(s => s.内容.includes('已二阶段') || s.内容.includes('形态：二阶段') || s.内容.includes('HP →'))).toBe(true);
  });
});
