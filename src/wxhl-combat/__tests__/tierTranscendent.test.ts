import { describe, expect, it } from 'vitest';
import { 属性修正值, 宽容属性修正值, 归一阶位, 阶位序数 } from '../engine/rules';
import { 重算实体衍生属性 } from '../engine/derived';

// ================================================================
// 玩家口径（最终裁决）：
//   「超脱的修正系数是 20」
//   「超脱也算位阶，超脱、超脱阶、超脱者，都算"超脱"」
//
// 之前只有写「超脱」两个字的认 —— 「超脱者」会直接抛「未知阶位」，
// 而**卡面里写的就是「超脱者」**（wxhl-003 状态栏的系数表也认这个词）。
// 现在三种写法统一归一，系数一律 20。
// ================================================================

describe('超脱 · 三种写法都归一（玩家裁决）', () => {
  it("'超脱' / '超脱阶' / '超脱者' 都归一成 '超脱'", () => {
    expect(归一阶位('超脱')).toBe('超脱');
    expect(归一阶位('超脱阶')).toBe('超脱');
    expect(归一阶位('超脱者')).toBe('超脱');
  });

  it('前后空白也算（变量里手写的空格）', () => {
    expect(归一阶位(' 超脱者 ')).toBe('超脱');
  });

  it('一到五阶原样返回，认不出的保持原样（交给严格层去抛错）', () => {
    expect(归一阶位('三阶')).toBe('三阶');
    expect(归一阶位('莫名其妙阶')).toBe('莫名其妙阶');
  });
});

describe('超脱 · 属性修正值系数 20', () => {
  it('三种写法算出来完全一样：(实际−5)×20', () => {
    expect(属性修正值(25, '超脱')).toBe(400);
    expect(属性修正值(25, '超脱者')).toBe(400);
    expect(属性修正值(25, '超脱阶')).toBe(400);
  });

  it('一~五阶系数不变（1/2/4/7/11）', () => {
    expect(属性修正值(25, '一阶')).toBe(20);
    expect(属性修正值(25, '二阶')).toBe(40);
    expect(属性修正值(25, '三阶')).toBe(80);
    expect(属性修正值(25, '四阶')).toBe(140);
    expect(属性修正值(25, '五阶')).toBe(220);
  });

  it('**真的认不出的**阶位仍然抛错（严格层不变），宽容版按一阶兜底', () => {
    expect(() => 属性修正值(25, '超脱者·究极')).toThrow('未知阶位');
    expect(宽容属性修正值(25, '超脱者·究极')).toBe(20);
  });
});

describe('超脱 · 阶位序数（部位DC / 技能成长用）', () => {
  it('超脱序数 6，三种写法一致', () => {
    expect(阶位序数('超脱')).toBe(6);
    expect(阶位序数('超脱者')).toBe(6);
    expect(阶位序数('超脱阶')).toBe(6);
  });

  it('一到五阶序数 1~5；认不出的退回 1', () => {
    expect(阶位序数('一阶')).toBe(1);
    expect(阶位序数('五阶')).toBe(5);
    expect(阶位序数('怪阶')).toBe(1);
  });
});

describe('超脱 · 面板代算吃同一套口径（不再依赖小手机的 16）', () => {
  it('超脱者单位的衍生属性按系数 20 算（闪避 = 10 + AGI修正×0.5）', () => {
    const stat: any = {
      契约者: {
        头部: { 姓名: '超脱者', 阶位: '超脱者', 等级: 100 },
        // 实际值由 基础 + 加成 算出来（代算会重算它，所以基础必须给）
        属性: { 基础: { STR: 25, AGI: 25, CON: 25, PER: 25 }, 加成: {}, 自定义加成: {} },
        衍生属性: {},
        装备: {},
        状态: {},
        类型: '玩家',
      },
    };

    重算实体衍生属性(stat, '契约者');

    // AGI 25 → 修正 (25−5)×20 = 400 → 闪避 10 + 400×0.5 = 210
    expect(stat.契约者.衍生属性.闪避值).toBe(210);
    // CON 25 → 修正 400 → 防御 ⌊(400+5)×0.2⌋ = 81
    expect(stat.契约者.衍生属性.防御).toBe(81);
  });
});
