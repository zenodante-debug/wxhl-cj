import { describe, expect, it } from 'vitest';
import {
  归一化名,
  编辑距离相似度,
  相似度,
  解析名字引用,
  type 候选组,
} from '../engine/nameMatch';

// ================================================================
// 中文名字适配（实战反馈：快路模型把「工蜂异形幼体」写成「工蜂异形ㄧㄡˋ体」）
//
// 关键认知：这是**替换**不是夹注 —— 原来那个「幼」已经不在了，
// 删掉注音只能得到「工蜂异形体」（比本尊少一个字）。把注音还原成汉字原理上做不到
// （ㄧㄡˋ 对应 幼/又/右/佑/宥/诱… 一对多）。所以：先去注音把距离拉近，再在候选集里绑回去。
// ================================================================

describe('归一化名', () => {
  it('NFKC：全角字母数字 → 半角', () => {
    expect(归一化名('ＡＢＣ１２３')).toBe('ABC123');
  });

  it('去掉空白（含全角空格 U+3000）', () => {
    expect(归一化名('工蜂 异形　幼体')).toBe('工蜂异形幼体');
  });

  it('去掉装饰性引号/书名号/括号', () => {
    expect(归一化名('「工蜂异形幼体」')).toBe('工蜂异形幼体');
    expect(归一化名('《工蜂异形幼体》')).toBe('工蜂异形幼体');
    expect(归一化名('工蜂异形幼体（精英）')).toBe('工蜂异形幼体精英');
  });

  it('**去注音字母与调号**：工蜂异形ㄧㄡˋ体 → 工蜂异形体', () => {
    expect(归一化名('工蜂异形ㄧㄡˋ体')).toBe('工蜂异形体');
  });

  it('汉字名里的拼音夹注被剥掉：幼(yòu) → 幼', () => {
    expect(归一化名('工蜂异形幼(yòu)体')).toBe('工蜂异形幼体');
    expect(归一化名('工蜂异形幼yòu体')).toBe('工蜂异形幼体');
  });

  it('**纯拉丁/数字名字不被破坏**（没有汉字 → 不剥拉丁）', () => {
    expect(归一化名('T-800')).toBe('T800');
    expect(归一化名('MK-II')).toBe('MKII');
  });

  it('西里尔/希腊等非汉字字符不动', () => {
    expect(归一化名('β型工蜂')).toBe('β型工蜂');
  });
});

describe('相似度', () => {
  it('不做归一时，坏串离本尊很远（0.625）—— 证明"先去注音"是必需的', () => {
    expect(编辑距离相似度('工蜂异形ㄧㄡˋ体', '工蜂异形幼体')).toBeCloseTo(0.625, 3);
  });

  it('归一化之后够得着（0.833）', () => {
    expect(相似度('工蜂异形ㄧㄡˋ体', '工蜂异形幼体')).toBeCloseTo(0.833, 2);
  });

  it('两字名 vs 三字名只有 0.667 —— 低于阈值，靠长度规则再兜一层', () => {
    expect(相似度('卫兵', '骨卫兵')).toBeCloseTo(0.667, 2);
  });

  it('完全无关 → 0 附近；完全相同 → 1', () => {
    expect(相似度('工蜂异形幼体', '工蜂异形幼体')).toBe(1);
    expect(相似度('工蜂异形幼体', '岩壳爬行者')).toBeLessThan(0.4);
  });

  it('任一侧归一化后为空 → 0（不除零）', () => {
    expect(相似度('「」', '工蜂异形幼体')).toBe(0);
    expect(相似度('   ', '   ')).toBe(0);
  });
});

describe('解析名字引用 · 三层', () => {
  const 幼体: 候选组 = {
    归属: '副本角色.工蜂异形幼体',
    别名: ['工蜂异形幼体', '副本角色.工蜂异形幼体'],
  };
  const 兵体: 候选组 = {
    归属: '副本角色.工蜂异形兵体',
    别名: ['工蜂异形兵体', '副本角色.工蜂异形兵体'],
  };

  it('第 1 层：逐字精确（任一别名）', () => {
    const r = 解析名字引用([幼体, 兵体], '副本角色.工蜂异形幼体');
    expect(r.命中).toBe('副本角色.工蜂异形幼体');
    expect(r.方式).toBe('精确');
  });

  it('第 2 层：归一化后精确（带装饰、全角空格照样命中）', () => {
    const r = 解析名字引用([幼体, 兵体], '「工蜂异形幼体」');
    expect(r.命中).toBe('副本角色.工蜂异形幼体');
    expect(r.方式).toBe('归一化');
  });

  it('第 3 层：唯一最近似 → 绑定到注音污染的那一个（这就是实战的 bug）', () => {
    const r = 解析名字引用([幼体], '工蜂异形ㄧㄡˋ体');

    expect(r.命中).toBe('副本角色.工蜂异形幼体');
    expect(r.方式).toBe('近似');
    expect(r.相似度).toBeCloseTo(0.833, 2);
  });

  it('**两个候选打平 → 拒绝绑定**，并返回候选与相似度（宁可空过，不打错人）', () => {
    const r = 解析名字引用([幼体, 兵体], '工蜂异形ㄧㄡˋ体');

    expect(r.命中).toBeUndefined();
    expect(r.方式).toBe('未命中');
    expect(r.候选.map(c => c.名)).toContain('工蜂异形幼体');
    expect(r.候选.map(c => c.名)).toContain('工蜂异形兵体');
  });

  it('两字名不参与近似（「卫兵」不能绑到「骨卫兵」—— 守住既有裁决）', () => {
    const 骨卫兵: 候选组 = { 归属: '副本角色.骨卫兵', 别名: ['骨卫兵'] };
    const r = 解析名字引用([骨卫兵], '卫兵');

    expect(r.命中).toBeUndefined();
  });

  it('长度差超过 2 → 不参与近似（哪怕相似度刚好达标）', () => {
    // 12 字的名字被截成 9 字：距离 3、相似度 1−3/12 = 0.75（刚好过阈值），
    // 只有长度差这一条能挡住它 —— 长名字被"砍掉一截"不该当成同一个人
    const 长名: 候选组 = { 归属: '副本角色.甲乙丙丁戊己庚辛壬癸子丑', 别名: ['甲乙丙丁戊己庚辛壬癸子丑'] };
    const r = 解析名字引用([长名], '甲乙丙丁戊己庚辛壬');

    expect(r.方式).toBe('未命中');
  });

  it('截断一个字（长度差 1）→ 允许绑定（相似度 0.833）', () => {
    const r = 解析名字引用([幼体], '工蜂异形幼');
    expect(r.命中).toBe('副本角色.工蜂异形幼体');
  });

  it('同一单位的多个别名**不会让它和自己打平**（别名必须先按归属归组）', () => {
    const 三别名: 候选组 = {
      归属: '副本角色.工蜂异形幼体',
      别名: ['工蜂异形幼体', '副本角色.工蜂异形幼体', '工蜂异形幼体'],
    };
    const r = 解析名字引用([三别名], '工蜂异形ㄧㄡˋ体');

    expect(r.命中).toBe('副本角色.工蜂异形幼体');
  });

  it('空引用 / 纯装饰引用 → 未命中，不抛错', () => {
    expect(解析名字引用([幼体], '').命中).toBeUndefined();
    expect(解析名字引用([幼体], '　　').命中).toBeUndefined();
    expect(解析名字引用([幼体], '「」').命中).toBeUndefined();
  });

  it('空候选集 → 未命中', () => {
    expect(解析名字引用([], '工蜂异形幼体').命中).toBeUndefined();
  });

  it('完全不像 → 未命中，但候选仍按相似度排序返回（供日志诊断）', () => {
    const r = 解析名字引用([幼体, 兵体], '岩壳爬行者');

    expect(r.命中).toBeUndefined();
    expect(r.候选.length).toBeGreaterThan(0);
    expect(r.候选[0].相似度).toBeLessThan(0.75);
  });
});
