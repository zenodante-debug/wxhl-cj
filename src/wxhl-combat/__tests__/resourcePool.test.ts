import { describe, expect, it } from 'vitest';
import { 资源操作, 资源衰减 } from '../engine/resourcePool';

describe('resourcePool · 资源管理', () => {
  it('获得资源：保存 +10', () => {
    const 资源 = {};
    const 新资源 = 资源操作(资源, '保存', '获得', 10);

    expect(新资源['保存']).toBe(10);
  });

  it('消耗资源：保存 -15', () => {
    const 资源 = { 保存: 10 };
    const 新资源 = 资源操作(资源, '保存', '消耗', 15);

    expect(新资源['保存']).toBe(0); // 不能为负
  });

  it('设为资源：冻结标记 = 3', () => {
    const 资源 = { 冻结标记: 1 };
    const 新资源 = 资源操作(资源, '冻结标记', '设为', 3);

    expect(新资源['冻结标记']).toBe(3);
  });

  it('恢复资源：星幕护盾 +5', () => {
    const 资源 = { 星幕护盾: 10 };
    const 新资源 = 资源操作(资源, '星幕护盾', '恢复', 5);

    expect(新资源['星幕护盾']).toBe(15);
  });

  it('资源衰减：保存每回合 -15', () => {
    const 资源 = { 保存: 20 };
    const 衰减表 = { 保存: 15 };
    const 新资源 = 资源衰减(资源, 衰减表);

    expect(新资源['保存']).toBe(5);
  });

  it('资源衰减：多个资源同时衰减', () => {
    const 资源 = { 保存: 20, 充能: 10 };
    const 衰减表 = { 保存: 15, 充能: 5 };
    const 新资源 = 资源衰减(资源, 衰减表);

    expect(新资源['保存']).toBe(5);
    expect(新资源['充能']).toBe(5);
  });
});
