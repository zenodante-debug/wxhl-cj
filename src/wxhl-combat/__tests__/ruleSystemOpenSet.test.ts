import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动, 跑一个回合 } from '../engine/loop';
import { 校验战斗解释 } from '../ai/skillInterpreter';
import { 构造行动声明 } from '../engine/actionInput';
import { 归一化规则 } from '../engine/ruleShape';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家反馈（第二轮）：
//   1. 「规则系能力五花八门，不是这几个能够完全涵盖的，深度思考一下」
//      —— 世界书写的是「必中、必定暴击、即死、免疫、无敌、锁血、必中核心弱点、无视**等**」，
//         那个"等"就是开放集合。上一版拿七个名字当白名单**丢弃**未知效果 = 把卡面能力删掉，改错方向了。
//      正确做法：**引擎认得的效果**才机械执行；**认不得的照旧掷判定**，过了就交给叙事/AI（托管），
//         并在日志里说清"这是哪个技能的能力"。
//   2. 「我说的名字是，这个规则系能力来源的具体名称」—— 日志要带**来源技能名**。
//
//   3. 移动不能选负数（向后移动）—— 目标距离本来可以是负的（身后）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 100,
    MP_最大: 100,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 30,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

const 规则系动作 = (效果: any) => ({ 类: '规则系判定', 效果, 目标: '攻击目标' }) as any;

describe('规则系能力 · 引擎认不得的也照旧判定（不再丢弃）', () => {
  it('校验：名称是**任意非空字符串**都保留（五花八门的能力不该被白名单砍掉）', () => {
    const 解释 = 校验战斗解释({
      行动消耗: '主要行动',
      类型: '主动',
      规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系动作('绝对冻结')] }],
    });

    expect((解释.规则[0].动作[0] as any).效果).toBe('绝对冻结');
  });

  it('校验：**没名字**（undefined/空串/非字符串）才丢（那才是真正的坏数据）', () => {
    const { 规则, 丢弃动作 } = 归一化规则([
      { 触发: '使用时', 作用域: '自身', 动作: [规则系动作(undefined), 规则系动作(''), 规则系动作(123)] },
    ]);

    expect(规则).toEqual([]); // 动作被剪光 → 整条丢
    expect(丢弃动作).toBe(3);
  });

  it('引擎认不得的效果：**过判定** → 日志里点名（效果 + 来源技能名）并交给叙事', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      技能: {
        镜花水月: 造解释({ 规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系动作('绝对冻结')] } as 规则] }),
      },
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '镜花水月', 目标: '骨卫兵' }, 骰);
    const 文 = r.步骤.map(s => s.内容).join('\n');

    expect(文).toContain('绝对冻结'); // 效果名
    expect(文).toContain('镜花水月'); // **来源技能名**（玩家要的"具体名称"）
    expect(文).toMatch(/通过/); // 过判定了
    expect(文).toMatch(/叙事|托管/); // 交给叙事，而不是静默消失
  });

  it('引擎认不得的效果：**没过判定** → 照旧写"未通过"（带来源名）', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      属性: { 实际: { STR: 5, AGI: 10, CON: 20, PER: 10 } }, // 修正很小 → 过不了
      技能: { 弱能力: 造解释({ 规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系动作('因果逆转')] } as 规则] }) },
    });
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      类型: 'BOSS',
      属性: { 实际: { STR: 10, AGI: 10, CON: 200, PER: 10 } },
    });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '弱能力', 目标: '骨卫兵' }, 骰);
    const 文 = r.步骤.map(s => s.内容).join('\n');

    expect(文).toContain('因果逆转');
    expect(文).toContain('弱能力');
    expect(文).toMatch(/未通过/);
  });

  it('引擎**认得**的效果照旧机械执行（必中 → 高闪避也命中），日志同样带来源', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      技能: { 必中之刃: 造解释({ 规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系动作('必中')] } as 规则] }) },
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 闪避值: 99999 });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '必中之刃', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.骨卫兵.HP_当前).toBeLessThan(1000); // 必中生效
    const 文 = r.步骤.map(s => s.内容).join('\n');
    expect(文).toContain('必中');
    expect(文).toContain('必中之刃'); // 来源
  });
});

describe('移动 · 目标距离可以是负数（向后移动）', () => {
  it('构造行动声明：负距离照样产出「移动」', () => {
    const r = 构造行动声明({ 移动: -15 }, '');

    expect(r.行动).toEqual([{ 类型: '移动', 距离: -15 }]);
    expect(可提交(r)).toBe(true); // 只移动也算出手
  });

  function 可提交(x: ReturnType<typeof 构造行动声明>) {
    return x.行动.length > 0;
  }

  it('结算：向后移动 20 米 → 距离变负、消耗额度按绝对值算', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 距离: 0, 额度: 30 });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 距离: 10 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 跑一个回合(状态, { 契约者: [{ 类型: '移动', 距离: -20 }] }, [], 骰);

    expect(r.状态.单位.契约者.距离).toBe(-20);
    expect(r.状态.单位.契约者.额度).toBe(10); // 30 − 20
  });

  it('原地不动（位移 0）→ 不消耗移动槽、也不写日志里的"移动 0 米"', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 距离: 5, 额度: 30 });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 距离: 10 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    // 移动填的是**位移量**（2026-10-10 修订）：0 = 原地不动
    const r = 跑一个回合(状态, { 契约者: [{ 类型: '移动', 距离: 0 }] }, [], 骰);

    expect(r.状态.单位.契约者.行动槽.移动).toBe(1); // 没扣
    expect(r.状态.单位.契约者.额度).toBe(30); // 没消耗
  });
});
