import { describe, expect, it } from 'vitest';
import { 构建敌方意图提示词, 解析敌方意图 } from '../ai/enemyTactics';
import type { 战斗状态 } from '../types';

describe('enemyTactics · 敌方意图', () => {
  it('构建敌方意图提示词：包含战场状态', () => {
    const 状态: 战斗状态 = {
      进行中: true,
      回合: 3,
      先攻: ['骨卫兵', '玩家'],
      单位: {
        骨卫兵: {
          id: '骨卫兵',
          阵营: '敌方',
          类型: '精英',
          属性: { 实际: { STR: 18, AGI: 8, CON: 16, PER: 6 } },
          阶位: '一阶',
          HP_当前: 120,
          HP_最大: 120,
          MP_当前: 20,
          MP_最大: 20,
          耐力_当前: 80,
          耐力_最大: 80,
          防御: 5,
          闪避值: 10,
          距离: 0,
          行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
          额度: 0,
          冷却: {},
          护盾: 0,
          架势: null,
          状态: [],
          濒死: null,
          资源: {},
          词条: new Set(),
          技能: {},
        },
        玩家: {
          id: '玩家',
          阵营: '我方',
          类型: '玩家',
          属性: { 实际: { STR: 25, AGI: 20, CON: 20, PER: 15 } },
          阶位: '二阶',
          HP_当前: 100,
          HP_最大: 100,
          MP_当前: 50,
          MP_最大: 50,
          耐力_当前: 100,
          耐力_最大: 100,
          防御: 0,
          闪避值: 10,
          距离: 0,
          行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
          额度: 0,
          冷却: {},
          护盾: 0,
          架势: null,
          状态: [],
          濒死: null,
          资源: {},
          词条: new Set(),
          技能: {},
        },
      },
      待决: null,
      领域: [],
    };

    const 提示词 = 构建敌方意图提示词(状态);

    expect(提示词).toContain('骨卫兵');
    expect(提示词).toContain('玩家');
    expect(提示词).toContain('第 3 回合');
  });

  it('解析敌方意图：合法的意图列表', () => {
    const json = JSON.stringify([
      {
        单位: '骨卫兵',
        行动: [
          { 类型: '移动', 目标: '玩家', 距离: 0 },
          { 类型: '主要行动', 技能: '骨爪撕裂', 目标: '玩家' },
        ],
      },
    ]);

    const 结果 = 解析敌方意图(json);

    expect(结果.length).toBe(1);
    expect(结果[0].单位).toBe('骨卫兵');
    expect(结果[0].行动.length).toBe(2);
  });

  it('解析敌方意图：非法 JSON 应该抛错', () => {
    expect(() => 解析敌方意图('not json')).toThrow();
  });

  it('解析敌方意图：不是数组应该抛错', () => {
    expect(() => 解析敌方意图('{}')).toThrow();
  });
});
