import { describe, expect, it } from 'vitest';
import { 构建敌方意图提示词, 解析敌方意图, 敌方意图_SCHEMA } from '../ai/enemyTactics';
import type { 战斗状态, 战斗解释, 战斗单位 } from '../types';

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: 'MP 3',
    冷却: 3,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 2,
    伤害倍率: 1.4,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

