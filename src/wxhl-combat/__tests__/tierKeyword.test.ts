import { describe, expect, it } from 'vitest';
import { 属性修正值, 归一阶位, 阶位序数, 是超脱 } from '../engine/rules';
import { 重算实体衍生属性 } from '../engine/derived';

// ================================================================
// 玩家口径（2026-10-08 第二次放宽）：
//   「更加宽泛一点吧，位阶的判定用关键词筛选模式，含有一就是一阶，含有二就是二阶，
//     含有"超脱"就是超脱阶。不仅是契约者玩家、还有其他契约者、副本角色都是同理，
//     这样能减少报错。不仅是汉字，阿拉伯数字也行。」
//
// 实战里阶位字段长这样：「一阶 · 初始契约者」「五阶巅峰 · 镇国剑尊」「四转 (隐藏转职)」
// 「超脱者」「1阶」—— 以前精确匹配，多一个字就抛「未知阶位」。
// 现在：**关键词筛选**（超脱优先 → 五/四/三/二/一 与 5/4/3/2/1 降序），
// 真的一个关键词都没有才交给严格层抛错。
// ================================================================

describe('位阶关键词筛选 · 汉字', () => {
  it('带修饰的写法都认得（卡面里就是这么写的）', () => {
    expect(归一阶位('一阶 · 初始契约者')).toBe('一阶');
    expect(归一阶位('五阶巅峰 · 镇国剑尊')).toBe('五阶');
    expect(归一阶位('四转 (隐藏转职)')).toBe('四阶');
    expect(归一阶位('第三阶')).toBe('三阶');
    expect(归一阶位('二阶·觉醒')).toBe('二阶');
  });

  it('光是一个汉字也算', () => {
    expect(归一阶位('二')).toBe('二阶');
    expect(归一阶位('伍'.replace('伍', '五'))).toBe('五阶');
  });

  it('出现多个汉字时取**最高**那阶（降序匹配，"一至三阶" → 三阶）', () => {
    expect(归一阶位('一至三阶')).toBe('三阶');
  });
});

describe('位阶关键词筛选 · 阿拉伯数字', () => {
  it('1~5 认，带"阶"不带"阶"都认', () => {
    expect(归一阶位('1阶')).toBe('一阶');
    expect(归一阶位('3')).toBe('三阶');
    expect(归一阶位('Lv.5 阶')).toBe('五阶');
    expect(归一阶位('2阶精英')).toBe('二阶');
    expect(归一阶位('4')).toBe('四阶');
  });
});

describe('位阶关键词筛选 · 超脱优先', () => {
  it('含「超脱」一律超脱（三种旧写法 + 带修饰的）', () => {
    for (const 文 of ['超脱', '超脱阶', '超脱者', '超脱 · 虚空', '接近超脱者']) {
      expect(归一阶位(文)).toBe('超脱');
      expect(是超脱(文)).toBe(true);
    }
  });

  it('「超脱」与数字混写时也优先超脱（不会被 1/2 抢走）', () => {
    expect(归一阶位('超脱1')).toBe('超脱');
  });
});

describe('位阶关键词筛选 · 认不出的仍抛错（严格层不变）', () => {
  it('一个关键词都没有 → 原样返回；属性修正值 抛「未知阶位」', () => {
    expect(归一阶位('怪阶')).toBe('怪阶');
    expect(归一阶位('')).toBe('');
    expect(() => 属性修正值(25, '怪阶')).toThrow('未知阶位');
  });
});

describe('放宽后各处口径一致', () => {
  it('属性修正值：带修饰的写法按对应系数算', () => {
    expect(属性修正值(25, '五阶巅峰 · 镇国剑尊')).toBe(220); // (25−5)×11
    expect(属性修正值(25, '1阶')).toBe(20);
    expect(属性修正值(25, '超脱者')).toBe(400);
  });

  it('阶位序数同样吃关键词', () => {
    expect(阶位序数('五阶巅峰')).toBe(5);
    expect(阶位序数('3')).toBe(3);
    expect(阶位序数('超脱者')).toBe(6);
  });

  it('面板代算：卡面写「一阶 · 初始契约者」按一阶算（软上限 25）', () => {
    const stat: any = {
      契约者: {
        头部: { 姓名: '白露露', 阶位: '一阶 · 初始契约者' },
        属性: { 基础: { STR: 5, AGI: 11, CON: 15, PER: 20 }, 加成: {}, 自定义加成: {} },
        衍生属性: {},
        装备: {},
        状态: {},
        类型: '玩家',
      },
    };

    重算实体衍生属性(stat, '契约者');

    // AGI 11 → 修正 (11−5)×1 = 6 → 闪避 10 + ⌊6×0.5⌋ = 13
    expect(stat.契约者.衍生属性.闪避值).toBe(13);
  });
});
