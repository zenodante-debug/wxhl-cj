import { describe, expect, it } from 'vitest';
import { 执行规则 } from '../engine/combatInterpreter';
import { 归一化规则 } from '../engine/ruleShape';
import type { 战斗单位, 规则 } from '../types';

// ================================================================
// 玩家实测 2026-10-11（plan §19 R3 的邻居）：
//   「职业特性、传承技能、被动等等，一大堆增加乘区的能力、增加倍率的能力，都读不到」
//
// 一部分「读不到」是**静默丢**：模型把 `量` 写成了**裸数字**（`"量": 0.1`）
// 而不是 `"量": {"源":"常数","系数":0.1}`。
// 提示词里 `量` 一律画成 `{...}`，但模型经常省成裸数字 ——
// 而 `求值` 是 `switch (取值.源)`：裸数字的 `.源` 是 undefined → 走完 switch 返回 undefined
// → `数值修正` 记成 NaN → `净化数值修正` 一句"有非有限值"就把它丢了。效果消失，只有战报角落一行字。
//
// 修法：`求值` 宽容接受**裸数字 / 纯数字字符串**当常数 ——
//   这是**宽容输入**（让效果真的生效），不是**放宽校验**（那才会造出安静的空壳）。
// ================================================================

function 造单位(): 战斗单位 {
  return {
    id: '契约者',
    阵营: '我方',
    名称: '契约者',
    类型: '玩家',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 5,
    闪避值: 10,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 100,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
  };
}

const 跑 = (动作: any) => 执行规则({ 触发: '常驻', 作用域: '自身', 动作: [动作] } as 规则, 造单位(), 造单位());

describe('取值宽容 · 裸数字 / 数字字符串当常数', () => {
  it('`量: 0.3`（裸数字）→ 伤害 +0.3，不再是 NaN', () => {
    expect(跑({ 类: '数值修正', 目标: '伤害', 量: 0.3 }).数值修正!.伤害).toBe(0.3);
  });

  it('`量: "0.3"`（数字字符串）→ 同上', () => {
    expect(跑({ 类: '数值修正', 目标: '伤害', 量: '0.3' }).数值修正!.伤害).toBe(0.3);
  });

  it('负数 / 科学计数法也认', () => {
    expect(跑({ 类: '数值修正', 目标: '伤害', 量: -0.5 }).数值修正!.伤害).toBe(-0.5);
    expect(跑({ 类: '数值修正', 目标: '伤害', 量: '1e2' }).数值修正!.伤害).toBe(100);
  });

  it('`量: 0`（合法的"没有加成"）→ 记 0，不是丢', () => {
    expect(跑({ 类: '数值修正', 目标: '伤害', 量: 0 }).数值修正!.伤害).toBe(0);
  });

  it('护盾 / 资源 的 `量` 同样宽容', () => {
    expect(跑({ 类: '护盾', 量: 30 }).护盾).toBe(30);
    // 资源的 `量` 宽容体现在「变动」上（绝对值由 落效果 按落点单位算，见 plan §21.5）
    expect(跑({ 类: '资源', 名: 'HP', 操作: '恢复', 量: 25 }).资源变动).toEqual([
      { 名: 'HP', 操作: '恢复', 量: 25 },
    ]);
  });

  it('确实不是数字的字符串 → **明确报错**（不静默变 0，那才是安静的空壳）', () => {
    expect(() => 跑({ 类: '数值修正', 目标: '伤害', 量: '很高' })).toThrow(/量/);
  });

  it('`量` 整个缺失 → **明确报错**（以前是 TypeError: Cannot read properties of undefined）', () => {
    expect(() => 跑({ 类: '数值修正', 目标: '伤害' })).toThrow(/量/);
  });
});

describe('宽容的是"形状"，不是"垃圾" —— 归一化仍会挡住坏规则', () => {
  it('裸数字的 量 不会被当成坏动作剪掉（它现在是合法的）', () => {
    const { 规则, 丢弃动作 } = 归一化规则([
      { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '伤害', 量: 0.1 }] },
    ]);
    expect(丢弃动作).toBe(0);
    expect(规则).toHaveLength(1);
  });
});
