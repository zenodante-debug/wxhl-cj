import { describe, expect, it } from 'vitest';
import { 执行规则 } from '../engine/combatInterpreter';
import type { 规则, 战斗单位, 取值 } from '../types';

function 造单位(id: string, 覆盖: Partial<战斗单位> = {}): 战斗单位 {
  return {
    id,
    阵营: id === '玩家' ? '我方' : '敌方',
    类型: id === '玩家' ? '玩家' : '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 10,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 0,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

/** 造一条「使用时 → 护盾 = 量」的规则，用护盾值把 求值 的结果照出来。 */
function 单动作规则(量: 取值): 规则 {
  return { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '护盾', 量 }] };
}

describe('combatInterpreter · 领域动作', () => {
  it('领域动作 → 返回领域对象', () => {
    const 规则: 规则 = {
      触发: '使用时',
      作用域: '自身',
      动作: [{ 类: '领域', 名: '保存神域', 持续: 3, 范围: '半径15米', 规则: [] }],
    };
    const 结果 = 执行规则(规则, 造单位('玩家'), 造单位('敌人'));
    expect(结果.领域).toBeDefined();
    expect(结果.领域?.[0].名).toBe('保存神域');
    expect(结果.领域?.[0].持续).toBe(3);
    expect(结果.领域?.[0].范围).toBe('半径15米');
    expect(结果.领域?.[0].中心).toBe('玩家');
  });
});

describe('combatInterpreter · 其余动作', () => {
  it('切换形态 → 结果.形态 = 目标形态', () => {
    const 规则: 规则 = {
      触发: '使用时',
      作用域: '自身',
      动作: [{ 类: '切换形态', 到: '第二形态' }],
    };
    const 结果 = 执行规则(规则, 造单位('玩家'), 造单位('敌人'));
    expect(结果.形态).toBe('第二形态');
  });

  it('追加攻击 → 结果.追加攻击 = 次数（多次累加）', () => {
    const 规则: 规则 = {
      触发: '命中时',
      作用域: '自身',
      动作: [
        { 类: '追加攻击', 次数: 2 },
        { 类: '追加攻击', 次数: 1 },
      ],
    };
    const 结果 = 执行规则(规则, 造单位('玩家'), 造单位('敌人'));
    expect(结果.追加攻击).toBe(3);
  });

  it('范围伤害 → 结果.范围伤害 记录中心/半径/已求值的量', () => {
    const 规则: 规则 = {
      触发: '使用时',
      作用域: '命中点',
      动作: [{ 类: '范围伤害', 中心: '命中点', 半径: 5, 量: { 源: '常数', 系数: 30 } }],
    };
    const 结果 = 执行规则(规则, 造单位('玩家'), 造单位('敌人'));
    expect(结果.范围伤害?.[0]).toEqual({ 中心: '命中点', 半径: 5, 量: 30 });
  });

  it('条件分支：条件成立走「真」分支', () => {
    const 来源 = 造单位('玩家');
    来源.资源 = { 保存: 10 };
    const 规则: 规则 = {
      触发: '命中时',
      作用域: '自身',
      动作: [
        {
          类: '条件分支',
          条件: { 左: { 源: '资源', 名: '保存' }, 比较: '>', 右: { 源: '常数', 系数: 0 } },
          真: [{ 类: '护盾', 量: { 源: '常数', 系数: 5 } }],
          假: [{ 类: '护盾', 量: { 源: '常数', 系数: 1 } }],
        },
      ],
    };
    const 结果 = 执行规则(规则, 来源, 造单位('敌人'));
    expect(结果.护盾).toBe(5);
  });

  it('条件分支：条件不成立走「假」分支', () => {
    const 来源 = 造单位('玩家');
    来源.资源 = { 保存: 0 };
    const 规则: 规则 = {
      触发: '命中时',
      作用域: '自身',
      动作: [
        {
          类: '条件分支',
          条件: { 左: { 源: '资源', 名: '保存' }, 比较: '>', 右: { 源: '常数', 系数: 0 } },
          真: [{ 类: '护盾', 量: { 源: '常数', 系数: 5 } }],
          假: [{ 类: '护盾', 量: { 源: '常数', 系数: 1 } }],
        },
      ],
    };
    const 结果 = 执行规则(规则, 来源, 造单位('敌人'));
    expect(结果.护盾).toBe(1);
  });

  it('规则系判定 → 结果.规则系判定 记录效果与目标', () => {
    const 规则: 规则 = {
      触发: '攻击时',
      作用域: '攻击目标',
      动作: [{ 类: '规则系判定', 效果: '穿透', 目标: '攻击目标' }],
    };
    const 结果 = 执行规则(规则, 造单位('玩家'), 造单位('敌人'));
    expect(结果.规则系判定?.[0]).toEqual({ 效果: '穿透', 目标: '攻击目标' });
  });
});

describe('combatInterpreter · 求值六来源', () => {
  it('属性来源 → 属性修正值（不是实际值）：二阶 STR=25 → (25-5)×2 = 40', () => {
    const 来源 = 造单位('玩家', { 阶位: '二阶', 属性: { 实际: { STR: 25, AGI: 10, CON: 10, PER: 10 } } });
    const 结果 = 执行规则(单动作规则({ 源: '属性', 名: 'STR' }), 来源, 造单位('敌人'));
    expect(结果.护盾).toBe(40);
  });

  it('层数来源 → 来源身上同名状态的层数（3 层 → 3）', () => {
    const 来源 = 造单位('玩家', { 状态: [{ 名: '灼烧', 持续: 3, 层数: 3 }] });
    const 结果 = 执行规则(单动作规则({ 源: '层数', 名: '灼烧' }), 来源, 造单位('敌人'));
    expect(结果.护盾).toBe(3);
  });

  it('层数来源 → 没有该状态时为 0', () => {
    const 结果 = 执行规则(单动作规则({ 源: '层数', 名: '灼烧' }), 造单位('玩家'), 造单位('敌人'));
    expect(结果.护盾).toBe(0);
  });

  it('目标HP 来源 → 缺省回退到 目标.HP_当前', () => {
    const 目标 = 造单位('敌人', { HP_当前: 42 });
    const 结果 = 执行规则(单动作规则({ 源: '目标HP' }), 造单位('玩家'), 目标);
    expect(结果.护盾).toBe(42);
  });

  it('目标HP 来源 → 有上下文时优先用上下文', () => {
    const 结果 = 执行规则(单动作规则({ 源: '目标HP' }), 造单位('玩家'), 造单位('敌人'), { 目标HP: 7 });
    expect(结果.护盾).toBe(7);
  });

  it('最终伤害 来源 → 从上下文取；无上下文 → 0', () => {
    const 规则 = 单动作规则({ 源: '最终伤害' });
    expect(执行规则(规则, 造单位('玩家'), 造单位('敌人'), { 最终伤害: 33 }).护盾).toBe(33);
    expect(执行规则(规则, 造单位('玩家'), 造单位('敌人')).护盾).toBe(0);
  });

  it('溢出伤害 来源 → 从上下文取；无上下文 → 0', () => {
    const 规则 = 单动作规则({ 源: '溢出伤害' });
    expect(执行规则(规则, 造单位('玩家'), 造单位('敌人'), { 溢出伤害: 9 }).护盾).toBe(9);
    expect(执行规则(规则, 造单位('玩家'), 造单位('敌人')).护盾).toBe(0);
  });
});

describe('combatInterpreter · 受限表达式求值', () => {
  const 大单位 = 造单位('玩家', {
    HP_最大: 200,
    MP_最大: 50,
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
  }); // PER 修正 = 5

  it('全角 ×： (最大HP+最大MP)×PER修正×2 = (200+50)×5×2 = 2500', () => {
    const 结果 = 执行规则(单动作规则({ 源: '表达式', 式: '(最大HP+最大MP)×PER修正×2' }), 大单位, 造单位('敌人'));
    expect(结果.护盾).toBe(2500);
  });

  it('半角 *： (最大HP+最大MP)*PER修正*2 = 2500（与全角等价）', () => {
    const 结果 = 执行规则(单动作规则({ 源: '表达式', 式: '(最大HP+最大MP)*PER修正*2' }), 大单位, 造单位('敌人'));
    expect(结果.护盾).toBe(2500);
  });

  it('未知标识符 → 抛错（绝不静默返回 0）', () => {
    const 规则 = 单动作规则({ 源: '表达式', 式: '未知量×2' });
    expect(() => 执行规则(规则, 大单位, 造单位('敌人'))).toThrow();
  });

  it('语法错误（括号不匹配）→ 抛错', () => {
    const 规则 = 单动作规则({ 源: '表达式', 式: '(最大HP+最大MP' });
    expect(() => 执行规则(规则, 大单位, 造单位('敌人'))).toThrow();
  });
});
