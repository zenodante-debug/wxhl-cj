import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动, 阶段A规则结算, 阶段F规则结算 } from '../engine/loop';
import { 造场地条目 } from '../engine/viewModel';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家追加需求（2026-10-09）：
//   「还有环境、场地 buff 这种，目前也没有实现。」→ 裁决：「就算领域吧」
//
// 现状：`{类:'领域'}` 在翻译层能产出、引擎里**根本没有落地**（`落效果` 里连日志都没有），
// 所以「森罗古界：敌方治疗降低 70%」这类场地效果完全是空话。
//
// 口径（§5.3）：
//   - 落进 `状态.领域`（名 / 中心距离 / 半径 / 持续 / 内部规则），**同名后覆盖先**；
//   - **每回合开始**对**半径内**的每个单位跑内部规则 —— 按距离**实时**判定，
//     单位走进走出自然受影响，不是"施法时圈定名单"；
//   - 到期（阶段F 递减）移除并留一条日志。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

/** 一条「回合开始」的领域内部规则：给受影响的人叠一条减伤 buff（好断言、不碰资源语义） */
const 领域内规则 = (作用域: string, 量 = 0.3): 规则 =>
  ({
    触发: '回合开始',
    作用域,
    动作: [{ 类: '数值修正', 目标: '减伤', 量: { 源: '常数', 系数: 量 } }],
  }) as 规则;

/** 展开领域的技能：一直开着，方便反复触发 */
const 开领域 = (规则: 规则[], 持续 = 3, 范围 = '半径20米'): 战斗解释 =>
  造解释({
    规则: [
      {
        触发: '使用时',
        作用域: '自身',
        动作: [{ 类: '领域', 名: '森罗古界', 持续, 范围, 规则 }],
      } as 规则,
    ],
  });

/** 契约者(0m) / 白露露(3m, 友) / 骨卫兵(5m, 敌) / 骨卫兵乙(50m, 敌) */
function 造战场(领域技能: 战斗解释): 战斗状态 {
  const 契约者 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 森罗古界: 领域技能 } });
  const 白露露 = 造单位({ id: '小队.成员.白露露', 阵营: '我方', 距离: 3 });
  const 骨卫兵 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 距离: 5 });
  const 骨卫兵乙 = 造单位({ id: '副本角色.骨卫兵乙', 阵营: '敌方', 距离: 50 });

  return {
    进行中: true,
    回合: 1,
    先攻: [契约者.id, 白露露.id, 骨卫兵.id, 骨卫兵乙.id],
    单位: { 契约者, 白露露, 骨卫兵, 骨卫兵乙 },
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 展开领域 → 回传结算后的状态 */
function 展开(领域技能: 战斗解释) {
  const 状态 = 开战规则结算(造战场(领域技能));
  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '森罗古界', 目标: '契约者' }, 骰);
  return { 状态: r.状态, 文本: r.步骤.map(s => s.内容).join('\n') };
}

const 中了 = (状态: 战斗状态, 键: string) =>
  状态.单位[键].状态.some(s => s.名 === '领域·森罗古界');

describe('1 · 领域真的落进场（以前是彻底的空话）', () => {
  it('落进 状态.领域：名字 / 中心距离 / 半径 / 持续 / 内部规则', () => {
    const { 状态, 文本 } = 展开(开领域([领域内规则('敌方全体')]));

    expect(状态.领域).toHaveLength(1);
    const 域 = 状态.领域[0];
    expect(域.名).toBe('森罗古界');
    expect(域.持续).toBe(3);
    expect(域.中心距离).toBe(0); // 契约者在 0 米
    expect(域.半径).toBe(20);
    expect(域.规则).toHaveLength(1);
    expect(文本).toContain('森罗古界');
  });

  it('同名后覆盖先（不叠成两个同名领域）', () => {
    const 状态 = 开战规则结算(造战场(开领域([领域内规则('敌方全体')])));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '森罗古界', 目标: '契约者' }, 骰);
    const r2 = 结算行动(r.状态, r.状态.单位.契约者, { 类型: '主要行动', 技能: '森罗古界', 目标: '契约者' }, 骰);

    expect(r2.状态.领域).toHaveLength(1);
  });

  it('范围写成「15米」「半径15米」都解析得出来', () => {
    expect(展开(开领域([领域内规则('敌方全体')], 3, '半径15米')).状态.领域[0].半径).toBe(15);
    expect(展开(开领域([领域内规则('敌方全体')], 3, '15米')).状态.领域[0].半径).toBe(15);
    expect(展开(开领域([领域内规则('敌方全体')], 3, '')).状态.领域[0].半径).toBeGreaterThan(0);
  });
});

describe('2 · 每回合开始，半径内的人真的吃到', () => {
  it('半径内的敌人吃到；半径外的没吃到', () => {
    const { 状态 } = 展开(开领域([领域内规则('敌方全体')]));
    const 后 = 阶段A规则结算(状态, []);

    expect(中了(后, '骨卫兵')).toBe(true); // 5 米，在 20 米半径内
    expect(中了(后, '骨卫兵乙')).toBe(false); // 50 米，在外面
  });

  it('作用域「我方全体」只给队友；「范围内全体」两边都给', () => {
    const 只队友 = 阶段A规则结算(展开(开领域([领域内规则('我方全体')])).状态, []);
    expect(中了(只队友, '白露露')).toBe(true);
    expect(中了(只队友, '骨卫兵')).toBe(false);

    const 全都 = 阶段A规则结算(展开(开领域([领域内规则('范围内全体')])).状态, []);
    expect(中了(全都, '白露露')).toBe(true);
    expect(中了(全都, '骨卫兵')).toBe(true);
    expect(中了(全都, '骨卫兵乙')).toBe(false); // 半径外，照样不吃
  });

  it('**走进走出**：距离一变，下回合的受影响名单就跟着变（不是施法时圈定的名单）', () => {
    const { 状态 } = 展开(开领域([领域内规则('敌方全体')]));

    const 在场外 = 阶段A规则结算({ ...状态, 单位: { ...状态.单位, 骨卫兵: { ...状态.单位.骨卫兵, 状态: [] } } }, []);
    expect(中了(在场外, '骨卫兵')).toBe(true);

    // 骨卫兵跑到 100 米外 → 下回合就不再吃
    const 跑远了 = 阶段A规则结算(
      { ...状态, 单位: { ...状态.单位, 骨卫兵: { ...状态.单位.骨卫兵, 状态: [], 距离: 100 } } },
      [],
    );
    expect(中了(跑远了, '骨卫兵')).toBe(false);
  });

  it('领域不碰已经倒地的人（倒地后回血 = 「永远杀不死」那类坏味道）', () => {
    const { 状态 } = 展开(开领域([领域内规则('范围内全体')]));
    const 状态2 = { ...状态, 单位: { ...状态.单位, 骨卫兵: { ...状态.单位.骨卫兵, HP_当前: 0 } } };

    expect(中了(阶段A规则结算(状态2, []), '骨卫兵')).toBe(false);
  });

  it('战报里看得出效果来自哪个领域', () => {
    const { 状态 } = 展开(开领域([领域内规则('敌方全体')]));
    const 步骤: any[] = [];
    阶段A规则结算(状态, 步骤);

    expect(步骤.map(s => s.内容).join('\n')).toContain('领域·森罗古界');
  });
});

describe('4 · 面板上的「场地」（以前根本没有这一块）', () => {
  it('造场地条目：名字 / 剩余回合 / 半径 / 中心距离 / 内部规则人话', () => {
    const { 状态 } = 展开(开领域([领域内规则('敌方全体')], 4));
    const [条] = 造场地条目(状态.领域);

    expect(条.名).toBe('森罗古界');
    expect(条.持续).toBe(4);
    expect(条.半径).toBe(20);
    expect(条.中心距离).toBe(0);
    expect(条.摘要).toContain('回合开始');
    expect(条.摘要).toContain('敌方全体');
    expect(条.摘要).toContain('减伤');
  });

  it('没有领域 → 空数组（模板 v-if 直接判长度）', () => {
    expect(造场地条目(undefined)).toEqual([]);
    expect(造场地条目([])).toEqual([]);
  });
});

describe('5 · 到期消散（阶段F 递减）', () => {
  it('持续 3 → 每回合 F 递减；减到 0 就移除并留日志', () => {
    let 状态 = 展开(开领域([领域内规则('敌方全体')], 3)).状态;

    状态 = 阶段F规则结算(状态, []);
    expect(状态.领域[0].持续).toBe(2);
    状态 = 阶段F规则结算(状态, []);
    expect(状态.领域[0].持续).toBe(1);

    const 步骤: any[] = [];
    状态 = 阶段F规则结算(状态, 步骤);
    expect(状态.领域).toHaveLength(0);
    expect(步骤.map(s => s.内容).join('\n')).toContain('森罗古界');
  });

  it('消散之后不再影响任何人', () => {
    let 状态 = 展开(开领域([领域内规则('敌方全体')], 1)).状态;
    状态 = { ...状态, 单位: { ...状态.单位, 骨卫兵: { ...状态.单位.骨卫兵, 状态: [] } } };
    状态 = 阶段F规则结算(状态, []);

    expect(中了(阶段A规则结算(状态, []), '骨卫兵')).toBe(false);
  });
});
