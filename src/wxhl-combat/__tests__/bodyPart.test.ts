import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 构造行动声明 } from '../engine/actionInput';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 玩家实测（2026-10-10）：「现在的攻击没有部位选择的功能，这是个很严重的失误。」
// 玩家裁决：「行动释放时供玩家选择部位」。
//
// 现状：`部位` 只是 `战斗解释` 里的字段（模型写死），界面上**没得选**。
// 修法：`行动声明.部位` 优先（玩家这次选的），没选才用技能自己声明的（老行为）。
//
// 世界书第二步_部位锁定：头部 ×1.5（DC+10×敌方阶位）/ 臂部·腿部 ×0.75（DC+5）/
//                        眼部·核心 ×2（DC+20）/ 未声明 ×1。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100000,
    HP_最大: 100000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 打一发，返回掉血 */
function 打(技能部位: '头部' | undefined, 行动部位?: '头部' | '臂部' | '眼部/核心') {
  const 解释: 战斗解释 = {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    ...(技能部位 ? { 部位: 技能部位 } : {}),
    规则: [],
    托管: [],
  };
  const 我 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩: 解释 } });
  const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
  const 状态 = 开战规则结算({
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: { 契约者: 我, 骨卫兵: 敌 },
    待决: null,
    领域: [],
  } as 战斗状态);

  const r = 结算行动(
    状态,
    状态.单位.契约者,
    { 类型: '主要行动', 技能: '斩', 目标: '骨卫兵', ...(行动部位 ? { 部位: 行动部位 } : {}) },
    骰,
  );
  return { 掉血: 100000 - r.状态.单位.骨卫兵.HP_当前, 文本: r.步骤.map(s => s.内容).join('\n') };
}

describe('部位选择 · 玩家为这次释放选（第二步_部位锁定）', () => {
  it('不指定部位 → ×1（对照组）', () => {
    const 无 = 打(undefined);
    expect(无.掉血).toBeGreaterThan(0);
    expect(无.文本).toContain('部位 1');
  });

  it('玩家选「头部」→ 部位倍率 ×1.5', () => {
    const 无 = 打(undefined);
    const 头 = 打(undefined, '头部');

    expect(头.掉血).toBeGreaterThan(无.掉血);
    expect(头.文本).toContain('部位 1.5');
  });

  it('玩家选「眼部/核心」→ ×2（更疼）', () => {
    const 头 = 打(undefined, '头部');
    const 眼 = 打(undefined, '眼部/核心');

    expect(眼.掉血).toBeGreaterThan(头.掉血);
    expect(眼.文本).toContain('部位 2');
  });

  it('**玩家选的优先于技能自己声明的**（技能写了头部，玩家改打臂部）', () => {
    const 技能头 = 打('头部');
    const 玩家改臂部 = 打('头部', '臂部');

    expect(技能头.文本).toContain('部位 1.5');
    expect(玩家改臂部.文本).toContain('部位 0.75');
  });

  it('玩家没选 → 用技能自己声明的（老行为，回归）', () => {
    expect(打('头部').文本).toContain('部位 1.5');
  });

  it('部位也进命中 DC（头部 DC +10×敌人位阶）', () => {
    const 无 = 打(undefined);
    const 头 = 打(undefined, '头部');

    // 命中 DC 从 0（闪避 0）变成 10×一阶 = 10；骰值 18 仍能命中，但日志里的 DC 变了
    expect(无.文本).toMatch(/≥ 0\b/);
    expect(头.文本).toMatch(/≥ 10\b/);
  });

  it('构造行动声明：填写的部位进得了行动声明', () => {
    const r = 构造行动声明({ 主要: { 值: '斩', 目标: '骨卫兵', 部位: '头部' } }, '');

    expect(r.行动[0].部位).toBe('头部');
  });

  it('构造行动声明：没填部位就不带这个键（老形状一字不变）', () => {
    const r = 构造行动声明({ 主要: '斩' }, '骨卫兵');

    expect(r.行动[0]).not.toHaveProperty('部位');
  });
});
