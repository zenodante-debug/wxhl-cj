describe('随机意图 · 不调 AI，掷骰子抽（反馈 2）', () => {
  const 掷固定 = (值: number) => (_面数: number) => 值;

  it('主要行动：按选项数掷骰子抽（3 个选项 → 1d3 的第 2 个）', () => {
    const 状态 = 造状态();
    // 主要选项：[骨刺射击, 骨爪撕裂, 主武器攻击]（按名字排序）+ 近战要贴身的移动
    const 意图 = 随机意图(状态, 掷固定(2));

    const 主 = 意图[0].行动.find(a => a.类型 === '主要行动');
    expect(主).toBeDefined();
    expect(意图[0].行动[0].类型).toBe('移动'); // 抽到的可能是近战技 → 先贴身
    expect(主!.目标).toBe('玩家');
  });

  it('抽到近战技能且距离 > 2 → 前面插一条移动贴身', () => {
    const 状态 = 造状态();
    const 选项 = 列行动选项(状态.单位['骨卫兵'], '主要行动');
    const 近战序号 = 选项.findIndex(o => o.值 === '骨爪撕裂') + 1; // 1dN 是 1 起

    const 意图 = 随机意图(状态, 掷固定(近战序号));
    const 行动 = 意图[0].行动;

    expect(行动[0]).toEqual({ 类型: '移动', 目标: '玩家', 距离: 0 });
    expect(行动[1].技能).toBe('骨爪撕裂');
  });

  it('抽到远程技能 → 不移动，直接打', () => {
    const 状态 = 造状态();
    const 选项 = 列行动选项(状态.单位['骨卫兵'], '主要行动');
    const 远程序号 = 选项.findIndex(o => o.值 === '骨刺射击') + 1;

    const 行动 = 随机意图(状态, 掷固定(远程序号))[0].行动;

    expect(行动).toHaveLength(2); // 主要 + 次要，没有移动
    expect(行动[0].技能).toBe('骨刺射击');
  });

  it('辅助类技能 → 目标给自己（不是打玩家）', () => {
    const 状态 = 造状态();
    // 次要选项只有 [战意号令, 副武器攻击]；掷 1 → 战意号令（辅助，自身）
    const 意图 = 随机意图(状态, 掷固定(1));
    const 次 = 意图[0].行动.find(a => a.类型 === '次要行动');

    expect(次!.技能).toBe('战意号令');
    expect(次!.目标).toBe('副本角色.骨卫兵');
  });

  it('**一次 AI 都不调**（纯函数，没有网络）：生成的意图结构完整', () => {
    const 状态 = 造状态();
    const 意图 = 随机意图(状态, 掷固定(1));

    expect(意图).toHaveLength(1);
    expect(意图[0].单位).toBe('副本角色.骨卫兵');
    expect(意图[0].行动.length).toBeGreaterThan(0);
  });

  it('打死的敌人不出现在意图里；我方全灭 → 空意图', () => {
    const 状态 = 造状态();
    状态.单位['骨卫兵'].HP_当前 = 0;
    expect(随机意图(状态, 掷固定(1))).toHaveLength(0);

    const 状态2 = 造状态();
    状态2.单位['契约者'].HP_当前 = 0;
    expect(随机意图(状态2, 掷固定(1))).toEqual([]);
  });

  it('说明文案能生成（面板日志用）', () => {
    const 状态 = 造状态();
    const 行 = 随机意图说明(随机意图(状态, 掷固定(1)), 状态);

    expect(行).toHaveLength(1);
    expect(行[0]).toContain('【随机】');
    expect(行[0]).toContain('骨卫兵');
  });
});

describe('冷却在引擎里真的生效（问题 4：以前只是写了个字段，从没被读过）', () => {
  /** 让攻击必中必伤的战场 */
  function 靶场(冷却值: number): 战斗状态 {
    const 状态 = 造状态();
    状态.单位['骨卫兵'].距离 = 0;
    状态.单位['骨卫兵'].技能 = { 骨爪撕裂: 造解释({ 射程: '近战', 冷却: 冷却值 }) };
    状态.单位['契约者'].闪避值 = 0;
    状态.单位['契约者'].防御 = 0;
    return 状态;
  }
  const 骰 = { 命中: 18, 伤害骰: [6] }; // 18 < 暴击范围(19) → 不暴击，算式干净
  const 打 = (状态: 战斗状态) =>
    结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '骨爪撕裂', 目标: '玩家' }, 骰);

  it('用过的技能进入冷却，冷却中再用会被跳过（不扣槽、不造成伤害）', () => {
    const 第一次 = 打(靶场(3));
    expect(第一次.状态.单位.骨卫兵.冷却['骨爪撕裂']).toBe(3);
    expect(第一次.状态.单位.契约者.HP_当前).toBeLessThan(200);

    // 模拟下一回合：行动槽重置（但冷却还在）
    第一次.状态.单位.骨卫兵.行动槽 = { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 };
    const HP前 = 第一次.状态.单位.契约者.HP_当前;
    const 第二次 = 打(第一次.状态);

    expect(第二次.步骤.some(x => x.内容.includes('还在冷却'))).toBe(true);
    expect(第二次.状态.单位.契约者.HP_当前).toBe(HP前); // 没打出去
    expect(第二次.状态.单位.骨卫兵.行动槽.主要).toBe(1); // 也没白扣槽
  });

  it('冷却每回合 -1，走完就能再用（冷却3 → 第 4 回合可用）', () => {
    let 状态 = 打(靶场(3)).状态;
    expect(状态.单位.骨卫兵.冷却['骨爪撕裂']).toBe(3);

    状态 = { ...状态, 单位: { ...状态.单位, 骨卫兵: 冷却递减(状态.单位.骨卫兵) } };
    expect(状态.单位.骨卫兵.冷却['骨爪撕裂']).toBe(2);
    状态 = { ...状态, 单位: { ...状态.单位, 骨卫兵: 冷却递减(状态.单位.骨卫兵) } };
    expect(状态.单位.骨卫兵.冷却['骨爪撕裂']).toBe(1);
    状态 = { ...状态, 单位: { ...状态.单位, 骨卫兵: 冷却递减(状态.单位.骨卫兵) } };
    expect(状态.单位.骨卫兵.冷却['骨爪撕裂']).toBeUndefined(); // 到 0 就删掉，不留垃圾键

    // 行动槽重置后可以再用
    状态.单位.骨卫兵.行动槽 = { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 };
    const 再打 = 打(状态);
    expect(再打.步骤.some(x => x.内容.includes('还在冷却'))).toBe(false);
  });

  it('没写冷却的技能也按 1 回合算（不会变成"永远可用"的漏洞）', () => {
    const r = 打(靶场(undefined as any));
    expect(r.状态.单位.骨卫兵.冷却['骨爪撕裂']).toBe(1);
  });
});

describe('基础武器攻击 · 主武器 / 副武器（问题 1 的后半句）', () => {
  function 靶场(): 战斗状态 {
    const 状态 = 造状态();
    状态.单位['骨卫兵'].距离 = 0;
    状态.单位['骨卫兵'].技能 = {};
    状态.单位['契约者'].闪避值 = 0;
    状态.单位['契约者'].防御 = 0;
    return 状态;
  }
  const 骰 = { 命中: 18, 伤害骰: [6] }; // 非暴击

  it('主要行动的主武器攻击：用主武器的骰与倍率（1d8 ×1.2 → 26）', () => {
    const 状态 = 靶场();
    const r = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 武器: '主武器', 目标: '玩家' }, 骰);

    expect(200 - r.状态.单位.契约者.HP_当前).toBe(26); // ⌈((6+0)×1 + 15) × 1.2⌉
    expect(r.步骤.some(x => x.内容.includes('基础攻击'))).toBe(true);
  });

  it('次要行动的副武器攻击：用副武器的骰与倍率（1d6 ×0.8 → 17），扣的是次要槽', () => {
    const 状态 = 靶场();
    const r = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '次要行动', 武器: '副武器', 目标: '玩家' }, 骰);

    expect(200 - r.状态.单位.契约者.HP_当前).toBe(17); // ⌈((6+0)×1 + 15) × 0.8⌉
    expect(r.状态.单位.骨卫兵.行动槽.次要).toBe(0);
    expect(r.状态.单位.骨卫兵.行动槽.主要).toBe(1);
  });
});
