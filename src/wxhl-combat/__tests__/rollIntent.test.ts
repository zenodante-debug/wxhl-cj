// 1. 「敌人的行动意图提供两个模式：AI 生成 / **按行动选项 roll 骰子抽**（不需要额外调 AI）」
// 2. 「各种行动选项太重复 —— 技能不是有行动类型吗？按行动类型匹配，别把所有选项适配所有类型」
