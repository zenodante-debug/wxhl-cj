import type { 战斗状态, 战斗解释, 战斗单位 } from '../types';

// ================================================================
// 回归：**一个回合里敌人到底出没出招**
//
// 这个 bug 的三种死法（全部都让敌人一次也不出手）：
// 1. AI 不知道该用什么技能名 → 编了一个 → 引擎按「没有该技能」跳过；
// 2. 模型漏了某个单位 → 该单位凭空空过，日志里什么都没有；
// 3. 接线写在 `.vue` 里 → 没有 vue-tsc，这类坏在 UI 层测不到。
// 本文件把「跑一个回合」变成纯函数后逐一钉死。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    类型: '精英',
    属性: { 实际: { STR: 18, AGI: 8, CON: 16, PER: 6 } },
    阶位: '一阶',
    HP_当前: 120,
    HP_最大: 120,
    MP_当前: 20,
    MP_最大: 20,
    耐力_当前: 80,
    耐力_最大: 80,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

/** 骨卫兵在 10 米外、有「骨爪撕裂」（近战）；契约者在 0 米 */
function 造状态(骨卫兵覆盖: Partial<战斗单位> = {}): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: ['契约者', '副本角色.骨卫兵'],
    单位: {
      契约者: 造单位({
        id: '契约者',
        阵营: '我方',
        类型: '玩家',
        阶位: '二阶',
        距离: 0,
        HP_当前: 100,
        HP_最大: 100,
        闪避值: 10,
        技能: { 裂骨重击: 造解释({ 射程: '视线内', 伤害倍率: 1.8 }) },
      }),
      骨卫兵: 造单位({
        id: '副本角色.骨卫兵',
        阵营: '敌方',
        距离: 10,
        HP_当前: 120,
        HP_最大: 120,
        闪避值: 10,
        技能: { 骨爪撕裂: 造解释() },
        ...骨卫兵覆盖,
      }),
    },
    待决: null,
    领域: [],
  };
}

/** 骨卫兵突进到 0 米再挥爪 */
const 骨卫兵意图 = [
  {
    单位: '副本角色.骨卫兵',
    行动: [
      { 类型: '移动' as const, 目标: '玩家', 距离: 0 },
      { 类型: '主要行动' as const, 技能: '骨爪撕裂', 目标: '玩家' },
    ],
  },
];

describe('跑一个回合 · 敌人必须真的出手', () => {
  it('回归：敌方意图里的技能名与技能表一致 → 敌人真的打中玩家（以前整轮空过）', () => {
    const 状态 = 造状态();

    const r = 跑一个回合(
      状态,
      [{ 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' }],
      骨卫兵意图,
      { 命中: 20, 伤害骰: [6] },
    );

    expect(r.步骤.some(s => s.类 === '敌方行动')).toBe(true);
    expect(r.步骤.some(s => s.内容.includes('「骨卫兵」的「骨爪撕裂」命中「契约者」'))).toBe(true);
    // 契约者的 HP 真的掉了
    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(100);
  });

  it('技能名带「」书名号 → 归一化后仍然命中技能表（模型爱加装饰）', () => {
    const 状态 = 造状态();

    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵', 行动: [{ 类型: '移动', 目标: '玩家', 距离: 0 }, { 类型: '主要行动', 技能: '「骨爪撕裂」', 目标: '玩家' }] }], {
      命中: 20,
      伤害骰: [6],
    });

    expect(r.步骤.some(s => s.内容.includes('没有技能'))).toBe(false);
    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(100);
  });

  it('主要行动没写技能 → 按基础攻击结算（不再「没有声明技能」直接跳过）', () => {
    const 状态 = 造状态();

    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵', 行动: [{ 类型: '移动', 目标: '玩家', 距离: 0 }, { 类型: '主要行动', 目标: '玩家' }] }], {
      命中: 20,
      伤害骰: [4],
    });

    expect(r.步骤.some(s => s.内容.includes('按基础攻击结算'))).toBe(true);
    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(100);
  });

  it('模型漏了这个单位 → 明写「没有收到任何意图，空过」（不静默，可诊断）', () => {
    const r = 跑一个回合(造状态(), [], []);

    expect(r.步骤.some(s => s.内容.includes('没有收到任何意图'))).toBe(true);
  });

  it('意图里的单位不在战场上 → 记日志，不抛错', () => {
    const r = 跑一个回合(造状态(), [], [{ 单位: '不存在的人', 行动: [] }]);

    expect(r.步骤.some(s => s.内容.includes('不在战场上'))).toBe(true);
  });

  it('交错结算：先手把敌人打死 → 该敌人本回合不再出手', () => {
    const 状态 = 造状态({ HP_当前: 1 });

    const r = 跑一个回合(
      状态,
      [{ 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' }],
      骨卫兵意图,
      { 命中: 20, 伤害骰: [6] },
    );

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(r.步骤.some(s => s.内容.includes('已失去战斗力'))).toBe(true);
    expect(r.状态.单位.契约者.HP_当前).toBe(100); // 没被反击
  });

  it('意图里目标缺省 → 走「目标不在战场上」而不抛错（模型偶尔省字段）', () => {
    const r = 跑一个回合(造状态(), [], [{ 单位: '骨卫兵', 行动: [{ 类型: '主要行动', 技能: '骨爪撕裂' }] }]);

    expect(r.步骤.some(s => s.内容.includes('不在战场上') || s.内容.includes('目标'))).toBe(true);
  });
});

describe('跑一个回合 · 玩家侧也必须有交代', () => {
  it('契约者不在先攻里 → 明说「本轮玩家行动未执行」', () => {
    const 状态 = 造状态();
    状态.先攻 = ['副本角色.骨卫兵'];

    const r = 跑一个回合(状态, [{ 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' }], []);
    expect(r.步骤.some(s => s.内容.includes('玩家行动未执行'))).toBe(true);
  });

  it('玩家先手命中 → 敌人掉血（玩家侧与敌方侧同一套结算）', () => {
    const r = 跑一个回合(造状态(), [{ 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' }], [], {
      命中: 20,
      伤害骰: [6],
    });

    expect(r.状态.单位.骨卫兵.HP_当前).toBeLessThan(120);
  });
});

describe('匹配技能名 · 只剥装饰，不做模糊', () => {
  const 表 = { 骨爪撕裂: 造解释(), '长剑（主武器）': 造解释() };

  it('逐字命中', () => {
    expect(匹配技能名(表, '骨爪撕裂')).toBe('骨爪撕裂');
  });

  it('剥掉书名号/引号/空格后命中', () => {
    expect(匹配技能名(表, '「骨爪撕裂」')).toBe('骨爪撕裂');
    expect(匹配技能名(表, '“骨爪 撕裂”')).toBe('骨爪撕裂');
  });

  it('部分名不匹配（「骨爪」≠「骨爪撕裂」）—— 不做模糊匹配', () => {
    expect(匹配技能名(表, '骨爪')).toBeUndefined();
  });

  it('完全不存在 → undefined', () => {
    expect(匹配技能名(表, '斩击')).toBeUndefined();
  });

  it('归一化只去装饰：空串与纯装饰名不匹配', () => {
    expect(归一化名('「」')).toBe('');
    expect(匹配技能名(表, '「」')).toBeUndefined();
  });
});

describe('基础攻击解释', () => {
  it('徒手 → 近战、倍率 0（伤害全靠徒手 1d4）', () => {
    const 解释 = 基础攻击解释(false);
    expect(解释.射程).toBe('近战');
    expect(解释.伤害倍率).toBe(0);
  });

  it('有主武器 → 射程留空（卡里没记武器类型，交由引擎跳过距离门禁并记说明）', () => {
    const 解释 = 基础攻击解释(true);
    expect(解释.射程).toBe('');
    expect(解释.伤害倍率).toBe(0);
  });
});

describe('跑一个回合 · 中文适配（AI 把名字里的字串成注音）', () => {
  /** 契约者 + 一只 6 字名的敌人（3 字名进不了近似层：长度规则要求 ≥3 且相似度 ≥0.75） */
  function 造异形状态(额外: 战斗单位[] = []): 战斗状态 {
    const 单位: Record<string, 战斗单位> = {
      契约者: 造单位({
        id: '契约者',
        阵营: '我方',
        类型: '玩家',
        阶位: '二阶',
        距离: 0,
        HP_当前: 100,
        HP_最大: 100,
        闪避值: 10,
        技能: {},
      }),
      工蜂异形幼体: 造单位({
        id: '副本角色.工蜂异形幼体',
        阵营: '敌方',
        距离: 10,
        HP_当前: 80,
        HP_最大: 80,
        闪避值: 10,
        技能: { 撕咬: 造解释() },
      }),
    };
    for (const u of 额外) 单位[u.id.split('.').pop()!] = u;

    return {
      进行中: true,
      回合: 1,
      先攻: ['契约者', ...Object.values(单位).filter(u => u.阵营 === '敌方').map(u => u.id)],
      单位,
      待决: null,
      领域: [],
    };
  }

  /** 意图里的单位/目标都被写成注音：「幼」→「ㄧㄡˋ」 */
  const 注音意图 = [
    {
      单位: '工蜂异形ㄧㄡˋ体',
      行动: [
        { 类型: '移动' as const, 目标: '玩家', 距离: 0 },
        { 类型: '主要行动' as const, 技能: '撕咬', 目标: '玩家' },
      ],
    },
  ];

  it('回归：意图里的单位名被写成注音 → 意图照样挂到正确单位，敌人照样打中', () => {
    const r = 跑一个回合(造异形状态(), [], 注音意图, { 命中: 20, 伤害骰: [6] });

    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(100);
    expect(r.步骤.some(s => s.内容.includes('按最近似绑定'))).toBe(true);
    expect(r.步骤.some(s => s.内容.includes('没有收到任何意图'))).toBe(false);
  });

  it('回归：意图里的**目标**被写成注音 → 照样绑回契约者并命中', () => {
    const r = 跑一个回合(
      造异形状态(),
      [],
      [
        {
          单位: '工蜂异形幼体',
          行动: [
            { 类型: '移动' as const, 目标: '玩家', 距离: 0 },
            { 类型: '主要行动' as const, 技能: '撕咬', 目标: '工蜂异形ㄧㄡˋ体' },
          ],
        },
      ],
      { 命中: 20, 伤害骰: [6] },
    );

    // 「工蜂异形ㄧㄡˋ体」是敌方自己 —— 绑到自己身上就是支援行动（不掉血），
    // 关键是**不能**因为认不出来而空过
    expect(r.步骤.some(s => s.内容.includes('不在战场上'))).toBe(false);
  });

  it('同场有相似的第二人 → **拒绝绑定**，列出两个候选，不误伤', () => {
    const 兵体 = 造单位({
      id: '副本角色.工蜂异形兵体',
      阵营: '敌方',
      距离: 10,
      HP_当前: 80,
      HP_最大: 80,
      技能: {},
    });

    const r = 跑一个回合(造异形状态([兵体]), [], [
      {
        单位: '工蜂异形ㄧㄡˋ体',
        行动: [{ 类型: '主要行动' as const, 技能: '撕咬', 目标: '玩家' }],
      },
    ], { 命中: 20, 伤害骰: [6] });

    expect(r.状态.单位.契约者.HP_当前).toBe(100); // 没打
    const 日志 = r.步骤.map(s => s.内容).join('\n');
    expect(日志).toContain('工蜂异形幼体');
    expect(日志).toContain('工蜂异形兵体');
  });

  it('技能名被串成注音 → 绑回技能表原名并留痕', () => {
    const 状态 = 造异形状态();
    状态.单位.工蜂异形幼体.技能 = { 骨爪撕裂: 造解释() };

    const r = 跑一个回合(状态, [], [
      {
        单位: '工蜂异形幼体',
        行动: [
          { 类型: '移动' as const, 目标: '玩家', 距离: 0 },
          { 类型: '主要行动' as const, 技能: '骨爪撕列', 目标: '玩家' }, // 列 ≠ 裂
        ],
      },
    ], { 命中: 20, 伤害骰: [6] });

    expect(r.步骤.some(s => s.内容.includes('技能名') && s.内容.includes('按最近似绑定'))).toBe(true);
    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(100);
  });
});
