import { describe, expect, it } from 'vitest';
import { 构造行动声明, 可提交 } from '../engine/actionInput';

describe('actionInput · 行动槽 → 行动声明', () => {
  it('空槽 → 无行动，不可提交', () => {
    const r = 构造行动声明({}, '骨卫兵');
    expect(r.行动).toEqual([]);
    expect(r.预置反应).toBeUndefined();
    expect(可提交({})).toBe(false);
  });

  it('主要行动 + 次要行动 + 移动 → 三条声明', () => {
    const r = 构造行动声明({ 主要: '裂骨重击', 次要: '瞄准', 移动: 12 }, '骨卫兵');
    expect(r.行动).toEqual([
      { 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' },
      { 类型: '次要行动', 技能: '瞄准', 目标: '骨卫兵' },
      { 类型: '移动', 距离: 12 },
    ]);
  });

  it('反应是预置，不进本轮行动（交待决点消费）', () => {
    const r = 构造行动声明({ 主要: '裂骨重击', 反应: '招架' }, '骨卫兵');
    expect(r.行动).toHaveLength(1);
    expect(r.预置反应).toBe('招架');
  });

  it('只有移动也算可提交', () => {
    expect(可提交({ 移动: 5 })).toBe(true);
    expect(可提交({ 反应: '招架' })).toBe(false); // 只预置反应、不出手 → 不算出手
  });

  it('移动距离非正数 → 不产生移动声明', () => {
    expect(构造行动声明({ 移动: 0 }, '骨卫兵').行动).toEqual([]);
    expect(构造行动声明({ 移动: -3 }, '骨卫兵').行动).toEqual([]);
  });

  it('空字符串技能名 → 视为未填', () => {
    expect(构造行动声明({ 主要: '   ' }, '骨卫兵').行动).toEqual([]);
  });

  it('技能名两端空白被去掉；非有限移动距离被忽略', () => {
    expect(构造行动声明({ 主要: ' 裂骨重击 ' }, '骨卫兵').行动).toEqual([
      { 类型: '主要行动', 技能: '裂骨重击', 目标: '骨卫兵' },
    ]);
    expect(构造行动声明({ 移动: NaN }, '骨卫兵').行动).toEqual([]);
    expect(构造行动声明({ 移动: Infinity }, '骨卫兵').行动).toEqual([]);
  });
});
