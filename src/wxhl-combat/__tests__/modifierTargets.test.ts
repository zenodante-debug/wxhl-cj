import { describe, expect, it } from 'vitest';
import {
  开战规则结算,
  回合开始行动槽,
  回合开始额度,
  结算行动,
} from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则, 数值修正目标 } from '../types';

// ================================================================
// 数值修正目标 —— 12 个全部都要被引擎真的读到
//
// 「数值修正目标」是**改哪个人物面板/公式里的数字**的白名单：
//   { 类: "数值修正", 目标: "伤害", 量: { 源: "常数", 系数: 0.3 } }
//                   ↑ 改哪个数              ↑ 改多少
// 卡面写"攻击力+30%""防御减半""额外一次反应动作"，模型都要收敛到这张表上的某一项。
// 早先有 5 个（反应动作/次要行动/移动距离/攻击倍率/基础伤害骰）**声明了却没人读** —— 写了不生效。
// 本文件把它们逐条钉死。（另外 7 个：伤害/最终乘区/减伤/命中/闪避/防御/四维，各有专门测试。）
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 30, PER: 40 } },
    阶位: '五阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 500,
    MP_最大: 500,
    耐力_当前: 200,
    耐力_最大: 200,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 100,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 100,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 一条常驻的数值修正（被动/装备写法） */
const 常驻修正规则 = (目标: 数值修正目标, 量: number): 规则 =>
  ({ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标, 量: { 源: '常数', 系数: 量 } }] }) as 规则;

/** 开战结算后的单位（被动/装备的常驻效果会落成状态 —— 真实流程就是开战时落的） */
function 开战后(单位: 战斗单位): 战斗单位 {
  const 空 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
  return 开战规则结算(造状态(单位, 空)).单位.契约者;
}

describe('数值修正目标 · 行动资源类', () => {
  it('**主要行动**：「额外获得一次主要行动」→ 主要槽 1 → 2', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 天赋·连击: 技能只带(常驻修正规则('主要行动', 1)) } });

    expect(回合开始行动槽(开战后(甲)).主要).toBe(2);
  });

  it('**反应动作**：「额外获得一次反应动作」→ 反应槽 1 → 2', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 血统·疾影: 技能只带(常驻修正规则('反应动作', 1)) } });

    expect(回合开始行动槽(开战后(甲)).反应).toBe(2);
  });

  it('**次要行动**：「额外获得一次次要行动」→ 次要槽 1 → 2', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 职业·双持: 技能只带(常驻修正规则('次要行动', 1)) } });

    expect(回合开始行动槽(开战后(甲)).次要).toBe(2);
  });

  it('没有修正时槽位就是基础值（不误伤）', () => {
    const 甲 = 开战后(造单位({ id: '契约者', 阵营: '我方' }));
    const 槽 = 回合开始行动槽(甲);

    expect(槽.主要).toBe(1);
    expect(槽.次要).toBe(1);
    expect(槽.反应).toBe(1);
  });

  it('**移动距离**：「移动距离+30米」→ 本回合移动额度 100 → 130', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 天赋·疾行: 技能只带(常驻修正规则('移动距离', 30)) } });

    expect(回合开始额度(开战后(甲))).toBe(130);
  });
});

describe('数值修正目标 · 武器类', () => {
  const 骰 = { 命中: 18, 伤害骰: [6] };

  /** 打一发，返回造成的基础伤害（不含技能部分：用基础攻击） */
  function 打一发(规则: 规则[]): number {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1, 强化等级: 0, 阶位: '五阶' },
      技能: 规则.length ? { 武器精通: 技能只带(...规则) } : {},
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', 阶位: '一阶', HP_当前: 100000, HP_最大: 100000, 属性: { 实际: { STR: 5, AGI: 10, CON: 10, PER: 10 } } });

    const 状态 = 开战规则结算(造状态(攻, 守));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' }, 骰);
    return 100000 - r.状态.单位.骨卫兵.HP_当前;
  }

  it('**基础伤害骰**：「武器伤害骰+4」→ 骰值总和 6 → 10，伤害变大', () => {
    const 基准 = 打一发([]);
    const 强化 = 打一发([常驻修正规则('基础伤害骰', 4)]);

    expect(基准).toBeGreaterThan(0);
    expect(强化).toBeGreaterThan(基准);
  });

  it('**攻击倍率**：「武器威力+50%」→ 倍率 1 → 1.5，伤害变大', () => {
    const 基准 = 打一发([]);
    const 强化 = 打一发([常驻修正规则('攻击倍率', 0.5)]);

    expect(强化).toBeGreaterThan(基准);
  });

  it('两个武器类修正叠加时按各自的口径算（不是笼统乘一下）', () => {
    const 只加骰 = 打一发([常驻修正规则('基础伤害骰', 4)]);
    const 只加倍率 = 打一发([常驻修正规则('攻击倍率', 0.5)]);
    const 两者都有 = 打一发([常驻修正规则('基础伤害骰', 4), 常驻修正规则('攻击倍率', 0.5)]);

    expect(两者都有).toBeGreaterThan(只加骰);
    expect(两者都有).toBeGreaterThan(只加倍率);
  });
});

describe('数值修正目标 · 属性修正值通道（真正重要的是修正值而不是属性）', () => {
  const 骰 = { 命中: 18, 伤害骰: [6] };

  function 打一发(规则: 规则[]): number {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      主武器: { 伤害骰: '2d6', 倍率: 1, 强化等级: 0, 阶位: '五阶' },
      技能: 规则.length ? { 剑意: 技能只带(...规则) } : {},
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', 阶位: '一阶', HP_当前: 100000, HP_最大: 100000, 属性: { 实际: { STR: 5, AGI: 10, CON: 10, PER: 10 } } });

    const 状态 = 开战规则结算(造状态(攻, 守));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' }, 骰);
    return 100000 - r.状态.单位.骨卫兵.HP_当前;
  }

  it('**STR修正**：「STR修正+11」直接加在修正值上（不再乘位阶系数）→ 伤害变大', () => {
    const 基准 = 打一发([]);
    const 强化 = 打一发([常驻修正规则('STR修正', 11)]);

    expect(基准).toBeGreaterThan(0);
    expect(强化).toBeGreaterThan(基准);
  });

  it('修正值通道与属性点通道的换算关系：五阶「STR+1」 == 「STR修正+11」（位阶系数 11）', () => {
    const 属性点通道 = 打一发([常驻修正规则('STR', 1)]);
    const 修正值通道 = 打一发([常驻修正规则('STR修正', 11)]);

    // 两条通道殊途同归 → 伤害完全一致（证明修正值通道没被再乘一次系数）
    expect(修正值通道).toBe(属性点通道);
  });

  it('**CON修正**：守方「CON修正+50」→ 防御 +10（(CON修正+5)×0.2 口径），伤害变少', () => {
    const 打 = (守规则: 规则[]) => {
      const 攻 = 造单位({
        id: '契约者',
        阵营: '我方',
        主武器: { 伤害骰: '2d6', 倍率: 1, 强化等级: 0, 阶位: '五阶' },
      });
      const 守 = 造单位({
        id: '副本角色.骨卫兵',
        阵营: '敌方',
        类型: '杂兵',
        阶位: '一阶',
        HP_当前: 100000,
        HP_最大: 100000,
        属性: { 实际: { STR: 5, AGI: 10, CON: 10, PER: 10 } },
        技能: 守规则.length ? { 硬化: 技能只带(...守规则) } : {},
      });
      const 状态 = 开战规则结算(造状态(攻, 守));
      const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' }, 骰);
      return 100000 - r.状态.单位.骨卫兵.HP_当前;
    };

    const 基准 = 打([]);
    const 硬化后 = 打([常驻修正规则('CON修正', 50)]); // → 防御 +10

    expect(硬化后).toBe(基准 - 10);
  });

  it('**AGI修正**：状态增量会折算进移动额度（移动距离 = 5 + AGI修正 口径）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 疾风: 技能只带(常驻修正规则('AGI修正', 30)) } });

    expect(回合开始额度(开战后(甲))).toBe(130); // 面板 100 + 修正值增量 30
  });

  it('两条通道可以叠加（属性点 + 修正值一起算）', () => {
    const 只属性点 = 打一发([常驻修正规则('STR', 1)]);
    const 叠加 = 打一发([常驻修正规则('STR', 1), 常驻修正规则('STR修正', 22)]);

    expect(叠加).toBeGreaterThan(只属性点);
  });
});

/** 造一个只用来挂规则的技能解释（被动，不参与行动） */
