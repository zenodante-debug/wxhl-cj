import { describe, expect, it } from 'vitest';
import { 构造行动声明, 列行动条目, 可提交 } from '../engine/actionInput';
import { 主武器攻击, 需要选技能, 技能候选 } from '../engine/actionOptions';
import type { 战斗单位, 战斗解释, 规则 } from '../types';

/** 造一条最小可用的战斗解释 */
function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

// ================================================================
// 玩家追加需求（2026-10-09）：
//   「应该每个行动都增加可选目标吧，现在是所有行动都是一个目标，
//     而且，现在的免费行动无法选择目标。」
//
// 现状：界面上每个单位只有**一个**目标下拉，主要/次要/免费共用；
// 免费行动是一组复选框（`免费: string[]`），**根本没有目标** ——
// 想"次要给自己上 buff、主要打敌人"做不到。
//
// 口径（§5.1）：每个槽各自带目标；免费行动从"一串技能名"变成"条目（值+目标）"；
// 老形状（单一目标 / `免费: string[]`）**照样认**，用统一目标当缺省。
// 引擎侧不用改 —— `行动声明` 本来就每条自带 `目标`。
// ================================================================

describe('1 · 每个槽各带各的目标（引擎侧原来就支持，缺的是数据形状）', () => {
  it('主要打敌人、次要给自己上 buff —— 两条行动各带各的目标', () => {
    const r = 构造行动声明(
      {
        主要: { 值: '大招', 目标: '骨卫兵' },
        次要: { 值: '上buff', 目标: '契约者' },
      },
      '骨卫兵',
    );

    expect(r.行动).toEqual([
      { 类型: '主要行动', 技能: '大招', 目标: '骨卫兵' },
      { 类型: '次要行动', 技能: '上buff', 目标: '契约者' },
    ]);
  });

  it('免费行动也带目标（以前根本没有这一栏）', () => {
    const r = 构造行动声明(
      {
        免费: [
          { 值: '战吼', 目标: '骨卫兵' },
          { 值: '护盾术', 目标: '契约者' },
        ],
      },
      '骨卫兵',
    );

    expect(r.行动).toEqual([
      { 类型: '免费行动', 技能: '战吼', 目标: '骨卫兵' },
      { 类型: '免费行动', 技能: '护盾术', 目标: '契约者' },
    ]);
  });

  it('条目没写目标 → 用统一缺省目标；统一目标也没有 → 用传进来的兜底', () => {
    const 有统一 = 构造行动声明({ 主要: { 值: '大招' }, 目标: '骨卫兵' }, '');
    expect(有统一.行动[0].目标).toBe('骨卫兵');

    const 无统一 = 构造行动声明({ 主要: { 值: '大招' } }, '契约者');
    expect(无统一.行动[0].目标).toBe('契约者');
  });

  it('槽级目标**盖过**统一目标', () => {
    const r = 构造行动声明({ 主要: { 值: '大招', 目标: '骨卫兵' }, 目标: '契约者' }, '');

    expect(r.行动[0].目标).toBe('骨卫兵');
  });

  it('基础武器攻击也能各带目标（哨兵照旧翻译成 `武器`）', () => {
    const r = 构造行动声明(
      { 主要: { 值: 主武器攻击, 目标: '骨卫兵' }, 次要: { 值: '上buff', 目标: '契约者' } },
      '',
    );

    expect(r.行动[0]).toEqual({ 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' });
  });
});

describe('2 · 老形状一个字都不变（向后兼容）', () => {
  it('`主要: "大招"` 字符串 + 统一目标 → 老行为', () => {
    const r = 构造行动声明({ 主要: '大招', 次要: '上buff', 目标: '骨卫兵' }, '');

    expect(r.行动).toEqual([
      { 类型: '主要行动', 技能: '大招', 目标: '骨卫兵' },
      { 类型: '次要行动', 技能: '上buff', 目标: '骨卫兵' },
    ]);
  });

  it('`免费: ["战吼"]`（老形状的一串技能名）照样认', () => {
    const r = 构造行动声明({ 免费: ['战吼', '护盾术'], 目标: '骨卫兵' }, '');

    expect(r.行动.map(a => a.目标)).toEqual(['骨卫兵', '骨卫兵']);
  });

  it('连统一目标都没有 → 用第二个参数（老调用点一个字不改）', () => {
    const r = 构造行动声明({ 主要: '大招' }, '骨卫兵');

    expect(r.行动[0].目标).toBe('骨卫兵');
  });

  it('两种形状可以混着用（新条目 + 老字符串）', () => {
    const r = 构造行动声明({ 主要: { 值: '大招', 目标: '甲' }, 免费: ['战吼'], 目标: '乙' }, '');

    expect(r.行动).toEqual([
      { 类型: '主要行动', 技能: '大招', 目标: '甲' },
      { 类型: '免费行动', 技能: '战吼', 目标: '乙' },
    ]);
  });
});

describe('3 · 顺序表里的显示行看得出目标是谁', () => {
  it('带了目标就写出来（↑↓ 排序时才分得清两条同名行动）', () => {
    const 条目 = 列行动条目(
      {
        主要: { 值: '大招', 目标: '骨卫兵' },
        免费: [
          { 值: '战吼', 目标: '骨卫兵' },
          { 值: '战吼', 目标: '骨卫兵乙' },
        ],
      },
      '',
    );

    expect(条目[0].显示).toBe('主要：大招 → 骨卫兵');
    expect(条目[1].显示).toBe('免费：战吼 → 骨卫兵');
    expect(条目[2].显示).toBe('免费：战吼 → 骨卫兵乙');
  });

  it('**没目标就照旧不写**「→」（老形状的显示行一个字不变）', () => {
    const 条目 = 列行动条目({ 主要: '大招', 次要: '上buff', 免费: ['战吼'], 移动: 10 }, '');

    expect(条目.map(x => x.显示)).toEqual(['主要：大招', '次要：上buff', '免费：战吼', '移动 10 米']);
  });

  it('两个同名免费行动**各有各的键**（排序不会被吞成一条）', () => {
    const 条目 = 列行动条目(
      { 免费: [{ 值: '战吼', 目标: '甲' }, { 值: '战吼', 目标: '乙' }] },
      '',
    );

    expect(条目.map(x => x.键)).toEqual(['免费:战吼', '免费:战吼#2']);
  });
});

describe('4 · 可提交照旧', () => {
  it('只填了新增式条目也算数；什么都没填不算', () => {
    expect(可提交({ 主要: { 值: '大招', 目标: '甲' } })).toBe(true);
    expect(可提交({ 免费: [{ 值: '战吼' }] })).toBe(true);
    expect(可提交({ 反应: '招架' })).toBe(false);
    expect(可提交({ 主要: { 值: '   ' } })).toBe(false);
  });
});

describe('5 · 「选择目标技能」下拉（连携要用：取消"某个可选技能"的冷却）', () => {
  const 带技能作用 = (名: string | undefined) =>
    造解释({ 规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '技能作用', 操作: '清冷却', 名 }] } as 规则] });

  it('规则里写了「选中技能」→ 界面要摆下拉（读规则本身，老缓存的翻译也认）', () => {
    expect(需要选技能(带技能作用('选中技能'))).toBe(true);
    expect(需要选技能(带技能作用('斩击'))).toBe(false);
    expect(需要选技能(造解释({ 规则: [] }))).toBe(false);
    expect(需要选技能(undefined)).toBe(false);
  });

  it('候选 = 该单位学过的技能（按名字排序，界面顺序稳定）', () => {
    const 单位 = {
      技能: { 丙: 造解释(), 甲: 造解释(), 乙: 造解释() },
    } as unknown as 战斗单位;

    expect(技能候选(单位).map(x => x.值)).toEqual(['丙', '乙', '甲'].sort((a, b) => a.localeCompare(b)));
    expect(技能候选({ 技能: {} } as unknown as 战斗单位)).toEqual([]);
  });

  it('选中的技能随行动一起交给引擎（引擎侧早就认 `选择技能`）', () => {
    const r = 构造行动声明({ 主要: { 值: '时之楔', 目标: '甲', 选择技能: '格挡' } }, '');

    expect(r.行动[0]).toEqual({ 类型: '主要行动', 技能: '时之楔', 目标: '甲', 选择技能: '格挡' });
  });

  it('没选 → **不带这个键**（老行为的行动声明一个字段都不多）', () => {
    const r = 构造行动声明({ 主要: { 值: '大招', 目标: '甲' } }, '');

    expect(r.行动[0]).not.toHaveProperty('选择技能');
  });
});
