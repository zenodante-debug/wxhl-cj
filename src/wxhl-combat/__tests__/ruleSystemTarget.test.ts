import { describe, expect, it } from 'vitest';
import { 动作结构完好, 归一化规则 } from '../engine/ruleShape';
import { 效果预览 } from '../engine/effectPreview';

// ================================================================
// 玩家实测（2026-10-10）：点开战 → 详情里刷出一屏
//   「规则系「穿透」→ undefined（需过规则系判定，未过则无效）」
//
// 根因：`规则系判定` 动作的 `目标` 字段没写 —— 校验器只查了「效果」非空，
// 没查「目标」非空；预览函数里也没兜底。于是模型少写一个字段就能过，
// 跑起来 `动作.目标` 是 undefined，玩家看到的是一屏 `undefined`。
//
// 修法：校验器拦（缺目标 = 结构不完好 = 进复核重翻）+ 预览兜底（缺目标写「目标未指定」）。
// ================================================================

describe('规则系判定 · 目标必须非空（缺了不许过校验）', () => {
  it('缺目标 → 结构不完好（该条规则判失败，进复核）', () => {
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透' }),
    ).toBe(false);
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '' }),
    ).toBe(false);
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '   ' }),
    ).toBe(false);
  });

  it('有目标 → 结构完好', () => {
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '攻击目标' }),
    ).toBe(true);
  });

  it('整条规则因为缺目标而被判失败（不漏、不静默）', () => {
    const { 规则, 丢弃, 丢弃动作 } = 归一化规则([
      { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '规则系判定', 效果: '穿透' }] },
    ]);

    expect(规则).toHaveLength(0);
    // 动作被剪掉 → 记 `丢弃动作`（整条被丢只发生在"本来就是空动作"时）
    expect(丢弃 + 丢弃动作).toBe(1);
  });
});

describe('预览兜底：缺目标写「目标未指定」，不写「undefined」', () => {
  it('缺目标的规则系判定 → 预览里写「目标未指定」', () => {
    const 预览 = 效果预览({
      行动消耗: '主要行动',
      射程: '近战',
      目标: '单体',
      消耗: '无',
      冷却: 1,
      分类: '基础',
      类型: '主动',
      可预判: true,
      规则: [
        // 这条规则的 `目标` 是缺的 —— 校验器会把它剪掉，但预览里**不能直接打 undefined**
        { 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 效果: '穿透', 目标: '' }] },
      ],
      托管: [],
    });

    const 行 = 预览.行.join('\n');
    expect(行).not.toContain('undefined');
  });
});
