import { describe, expect, it } from 'vitest';
import { 动作结构完好, 归一化规则 } from '../engine/ruleShape';
import { 效果预览 } from '../engine/effectPreview';

// ================================================================
// 玩家实测（2026-10-10）：点开战 → 详情里刷出一屏
//   「规则系「穿透」→ undefined（需过规则系判定，未过则无效）」
// 根因：`规则系判定` 动作的 `目标` 没写，预览里打出 undefined。
//
// 当时的修法：`动作结构完好` 要求 目标 非空 → 缺了就把**这个动作**剪掉。
//
// ⚠️ 2026-10-11 修订 —— 那个修法**代价太大，改掉**：
//   玩家实测的 43 项可疑清单里有 **~25 项**带着「忽略了 1 条规则（字段不完整）」，
//   那个数就是 `丢弃 + 丢弃动作` —— 模型少写一个 `目标`，这条**规则里的效果就整条没了**
//   （巨剑精通的「无视30%物理防御」、圣裁护手的「武器不可剥夺」都是这么丢的）。
//   而 `规则系` 本来就是**开放集合**（见 `引擎认得的规则系效果` 的注释、世界书原文），
//   "宁可丢掉也不猜"在这里是过度收紧 —— 丢掉的正是玩家说的「读不到」。
//
// 新口径：**缺 `目标` 就按规则的作用域补一个默认**（作用域说的本来就是"打谁"），
//   补完照样结构完好、照样生效。真正无法执行时才丢。
//   `动作结构完好` 作为"结构谓词"仍要求 目标 非空 —— 但 `归一化规则` 会先补、再判。
// ================================================================

describe('规则系判定 · 目标必须非空（结构谓词本身）', () => {
  it('缺目标 → 结构不完好（谓词不改：补默认是 归一化规则 的事）', () => {
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透' }),
    ).toBe(false);
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '' }),
    ).toBe(false);
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '   ' }),
    ).toBe(false);
  });

  it('有目标 → 结构完好', () => {
    expect(
      动作结构完好({ 类: '规则系判定', 效果: '穿透', 目标: '攻击目标' }),
    ).toBe(true);
  });
});

describe('规则系判定 · 缺目标 → 按作用域补默认（**不再剪掉整条效果**）', () => {
  const 归一 = (作用域: any) =>
    归一化规则([{ 触发: '使用时', 作用域, 动作: [{ 类: '规则系判定', 效果: '穿透' }] }]);

  it('作用域「自身」→ 目标补「自身」，规则**留下来**', () => {
    const { 规则, 丢弃, 丢弃动作 } = 归一('自身');
    expect(规则).toHaveLength(1);
    expect((规则[0].动作[0] as any).目标).toBe('自身');
    expect(丢弃 + 丢弃动作).toBe(0);
  });

  it('作用域「我方全体」/「敌方全体」→ 照抄同名的目标', () => {
    expect(((归一('我方全体').规则[0].动作[0]) as any).目标).toBe('我方全体');
    expect(((归一('敌方全体').规则[0].动作[0]) as any).目标).toBe('敌方全体');
  });

  it('打人的作用域（攻击目标 / 命中点 / 攻击者 / 缺省）→ 目标补「攻击目标」', () => {
    for (const 作用域 of ['攻击目标', '命中点', '攻击者', undefined, '不认识的']) {
      expect(((归一(作用域).规则[0].动作[0]) as any).目标, String(作用域)).toBe('攻击目标');
    }
  });

  it('**同一条规则里的兄弟动作一起活下来**（这才是玩家丢效果的地方）', () => {
    const { 规则, 丢弃动作 } = 归一化规则([
      {
        触发: '常驻',
        作用域: '自身',
        动作: [
          { 类: '数值修正', 目标: '基础伤害骰', 量: { 源: '常数', 系数: 4 } },
          { 类: '规则系判定', 效果: '穿透' }, // 缺目标 —— 以前会把整条规则拖下水
        ],
      },
    ]);

    expect(丢弃动作).toBe(0);
    expect(规则).toHaveLength(1);
    expect(规则[0].动作).toHaveLength(2);
    expect((规则[0].动作[1] as any).目标).toBe('自身');
  });

  it('已经写了目标的一个字都不动', () => {
    const { 规则 } = 归一化规则([
      { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '规则系判定', 效果: '穿透', 目标: '敌方全体' }] },
    ]);
    expect((规则[0].动作[0] as any).目标).toBe('敌方全体');
  });

  it('缺「效果」名仍然要丢（那是「规则系「undefined」」刷屏的根源，不能一起放过）', () => {
    const { 规则, 丢弃, 丢弃动作 } = 归一化规则([
      { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '规则系判定' }] },
    ]);
    expect(规则).toHaveLength(0);
    expect(丢弃 + 丢弃动作).toBe(1);
  });
});

describe('预览兜底：缺目标写「目标未指定」，不写「undefined」', () => {
  it('缺目标的规则系判定 → 预览里写「目标未指定」', () => {
    const 预览 = 效果预览({
      行动消耗: '主要行动',
      射程: '近战',
      目标: '单体',
      消耗: '无',
      冷却: 1,
      分类: '基础',
      类型: '主动',
      可预判: true,
      规则: [
        // `目标` 是空串 —— 预览里**不能直接打 undefined**
        { 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 效果: '穿透', 目标: '' }] },
      ],
      托管: [],
    });

    const 行 = 预览.行.join('\n');
    expect(行).not.toContain('undefined');
  });
});
