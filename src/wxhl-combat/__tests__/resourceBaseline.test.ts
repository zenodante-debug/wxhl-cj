import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import type { 战斗解释, 战斗状态, 战斗单位, 作用域 } from '../types';

// ================================================================
// 「资源」动作的**基准单位**修正（2026-10-11，plan §21.5）
//
// 玩家实测时（做快捷物品栏、喝药水）发现的既有重伤：
// `执行动作` 过去拿 `来源.资源[名] || 0` 当基准算**绝对值**，
// 而对 HP/MP/耐力 来说 `来源.资源['HP']` **永远是 undefined**（真实血条在 `单位.HP_当前`）。
// 于是：
//   「恢复 50 点 HP」  → 0 + 50 = 50 → 落效果把 HP **设成 50**（不是 +50）；
//   「消耗 8% 最大HP」 → max(0 − 量, 0) = 0 → 落效果把 HP **设成 0**（**当场打死**）。
// 而且 `执行规则` 的"来源"是**施法者** —— 给队友回血时连基准单位都是错的。
//
// 修法：`执行动作` 只记「名 + 操作 + 量」，绝对值交给 `落效果` **按落点单位自己的当前值**算。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 100,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 把一条规则挂成「使用时」的技能，跑一次，返回战斗状态 */
function 跑一次(规则: any, 覆盖: { 攻?: Partial<战斗单位>; 守?: Partial<战斗单位>; 作用域?: 作用域 } = {}) {
  const 攻 = 造单位({
    id: '契约者',
    阵营: '我方',
    技能: { 招式: 造解释({ 规则: [{ 触发: '使用时', 作用域: 覆盖.作用域 ?? '自身', 动作: [规则] }] }) },
    ...覆盖.攻,
  });
  const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', ...覆盖.守 });
  const 状态 = 开战规则结算(造状态(攻, 守));
  // 自身技能会强制指向自己；攻击目标类要显式给目标
  const r = 结算行动(
    状态,
    状态.单位.契约者,
    { 类型: '主要行动', 技能: '招式', 目标: (覆盖.作用域 ?? '自身') === '自身' ? '契约者' : '骨卫兵' },
    { 命中: 18, 伤害骰: [0] },
  );
  return { 契约者: r.状态.单位.契约者, 骨卫兵: r.状态.单位.骨卫兵, 文本: r.步骤.map(s => s.内容).join('\n') };
}

describe('「恢复 N 点 HP」是**加法**，不是"把 HP 设成 N"', () => {
  it('50/100 的契约者恢复 30 → 80（以前会被设成 30）', () => {
    const { 契约者 } = 跑一次({ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 30 } }, { 攻: { HP_当前: 50 } });
    expect(契约者.HP_当前).toBe(80);
  });

  it('回血封顶在 HP_最大（不会超）', () => {
    const { 契约者 } = 跑一次({ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 999 } }, { 攻: { HP_当前: 90, HP_最大: 100 } });
    expect(契约者.HP_当前).toBe(100);
  });

  it('MP / 耐力 同理', () => {
    const r = 跑一次(
      { 类: '资源', 名: 'MP', 操作: '恢复', 量: { 源: '常数', 系数: 20 } },
      { 攻: { MP_当前: 30, MP_最大: 50 } },
    );
    expect(r.契约者.MP_当前).toBe(50);
  });
});

describe('「消耗 / 抽离 N 点 HP」是**减法**，不是"把 HP 归零"', () => {
  it('100/100 的目标被抽 8% 最大HP → 92（以前会被当场打到 0）', () => {
    const { 骨卫兵 } = 跑一次(
      { 类: '资源', 名: 'HP', 操作: '消耗', 量: { 源: '表达式', 式: '最大HP*0.08' } },
      { 守: { HP_当前: 100, HP_最大: 100 }, 作用域: '攻击目标' },
    );
    expect(骨卫兵.HP_当前).toBeGreaterThan(0);
    expect(骨卫兵.HP_当前).toBeLessThan(100);
  });

  it('扣不成负数', () => {
    const { 骨卫兵 } = 跑一次(
      { 类: '资源', 名: 'HP', 操作: '消耗', 量: { 源: '常数', 系数: 999 } },
      { 守: { HP_当前: 30, HP_最大: 100 }, 作用域: '攻击目标' },
    );
    expect(骨卫兵.HP_当前).toBe(0);
  });
});

describe('基准是**落点单位自己**，不是施法者', () => {
  it('给队友回血：按队友的血算（不是按施法者的）', () => {
    // 施法者满血 100，队友只剩 10 —— 恢复 30 应该让队友到 40
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 100,
      技能: {
        治疗术: 造解释({
          规则: [
            { 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 30 } }] },
          ],
        }),
      },
    });
    const 队友 = 造单位({ id: '小队.成员.白露露', 阵营: '我方', HP_当前: 10, HP_最大: 100 });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算({
      进行中: true,
      回合: 1,
      先攻: [我.id, 队友.id, 敌.id],
      单位: { 契约者: 我, 白露露: 队友, 骨卫兵: 敌 },
      待决: null,
      领域: [],
    });

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '治疗术', 目标: '白露露' }, { 命中: 18 });

    expect(r.状态.单位.白露露.HP_当前).toBe(40);
    expect(r.状态.单位.契约者.HP_当前).toBe(100); // 施法者自己不动
  });

  it('同一条规则里对同一个字段**多次变动按顺序累加**（先恢复 30 再扣 10 = 净 +20）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 50,
      HP_最大: 100,
      技能: {
        换血: 造解释({
          规则: [
            {
              触发: '使用时',
              作用域: '自身',
              动作: [
                { 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 30 } },
                { 类: '资源', 名: 'HP', 操作: '消耗', 量: { 源: '常数', 系数: 10 } },
              ],
            },
          ],
        }),
      },
    });
    const 状态 = 开战规则结算(造状态(我, 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' })));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '换血', 目标: '契约者' }, { 命中: 18 });

    // 50 + 30 − 10 = 70（若每次都从"原始 50"重算，会得到 80 或 40 —— 都不对）
    expect(r.状态.单位.契约者.HP_当前).toBe(70);
  });

  it('自定义资源同样按落点结算（攒层 +1 是在已有层数上累加）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      资源: { 愤怒: 3 },
      技能: {
        挨打: 造解释({
          规则: [
            { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '资源', 名: '愤怒', 操作: '获得', 量: { 源: '常数', 系数: 1 } }] },
          ],
        }),
      },
    });
    const 状态 = 开战规则结算(造状态(我, 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' })));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '挨打', 目标: '契约者' }, { 命中: 18 });

    expect(r.状态.单位.契约者.资源.愤怒).toBe(4);
  });
});
