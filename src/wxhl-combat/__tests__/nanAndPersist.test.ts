import { 构建战斗状态快照, 恢复战斗状态 } from '../engine/persist';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家实战日志暴露的问题（逐条）：
//
// A. **NaN 伤害 → HP 变 NaN → 谁也打不死**（「乌尔奇奥拉和蓝染赖着不死」）
//    日志：`受到 NaN 伤害（… × 终伤倍率 NaN − 护盾 NaN − 减伤 NaN），HP 209 → NaN`
//    一旦 HP 是 NaN，`HP_当前 <= 0` 恒为 false —— 单位永远"活着"。
//
// B. **规则系判定动作没有效果名 → 刷屏**：
//    日志：`规则系「undefined」：判定 178 vs 对抗目标 952.8`、
//         `受到技能效果：规则系效果 （由防火墙在攻击阶段判定；此处不重复落地）`
//    根因：翻译器给了 `{类:'规则系判定'}` 却没给 `效果`（或给了不认识的效果）。
//
// C. 意图模式在**恢复战斗**时被重置成 ai（玩家选了骰子却还在调 AI）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 500,
    HP_最大: 500,
    MP_当前: 100,
    MP_最大: 100,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

describe('A · NaN 不许污染 HP（"赖着不死"的根因）', () => {
  /** 把 0/0 变成 NaN 的表达式（HP比例，而最大HP 是 0）——最容易产生 NaN 的现实来源 */
  const 坏修正 = 造解释({
    行动消耗: '无',
    类型: '被动',
    伤害倍率: 0,
    规则: [
      {
        触发: '常驻',
        作用域: '自身',
        动作: [{ 类: '数值修正', 目标: '减伤', 量: { 源: '表达式', 式: '当前HP/最大HP' } } as any],
      } as 规则,
    ],
  });

  it('状态里带了 NaN 的数值修正 → 读的时候按 0 处理（不污染伤害管线）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      HP_当前: 100,
      HP_最大: 0, // 0/0 → NaN
      状态: [{ 名: '坏状态', 持续: 99, 数值修正: { 减伤: Number.NaN, 最终乘区: Number.NaN } }],
    });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 技能: { 斩击: 造解释() } });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    const hp = r.状态.单位.骨卫兵.HP_当前;
    expect(Number.isFinite(hp)).toBe(true); // **绝不许是 NaN**
    expect(hp).toBeLessThan(100); // 伤害照常落地
  });

  it('伤害管线自己遇到非有限值 → 不写 HP、留一条看得见的日志', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      技能: {
        崩坏斩: 造解释({
          规则: [
            {
              触发: '使用时',
              作用域: '自身',
              // 写成表达式直接相除 → 最大HP 为 0 时就是 0/0 = NaN（HP比例 那个标识符有除零保护，这里故意绕开）
              动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '表达式', 式: '当前HP/最大HP' } } as any],
            } as 规则,
          ],
        }),
      },
      HP_最大: 0, // 让 当前HP/最大HP 变 NaN
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '崩坏斩', 目标: '骨卫兵' }, 骰);

    const hp = r.状态.单位.骨卫兵.HP_当前;
    expect(Number.isFinite(hp)).toBe(true); // 关键：不是 NaN
    expect(r.步骤.map(s => s.内容).join('\n')).toMatch(/非有限|NaN/); // 且说明白了
  });

  it('落效果：非有限的数值修正/护盾不进状态（不让 NaN 生根）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      HP_最大: 0,
      技能: { 坏被动: 坏修正 },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 后 = 开战规则结算(造状态(我, 敌));
    const 状态们 = 后.单位.契约者.状态;

    for (const s of 状态们) {
      for (const v of Object.values(s.数值修正 ?? {})) expect(Number.isFinite(v)).toBe(true);
    }
  });
});

describe('B · 规则系判定动作必须有认识的效果名（不再刷「规则系「undefined」」）', () => {
  const 基础 = {
    行动消耗: '无',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '被动',
    可预判: false,
  };

  it('没有效果名 / 不认识的效果 → 丢掉这条动作（整条规则没别的内容就一起丢）', () => {
    const 解释 = 校验战斗解释({
      ...基础,
      规则: [
        { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '规则系判定', 目标: '攻击目标' }] },
        { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '防御', 量: { 源: '常数', 系数: 3 } }, { 类: '规则系判定', 效果: '瞎编的效果', 目标: '攻击目标' }] },
      ],
    });

    // 第一条全是无效动作 → 整条丢掉；第二条保住有效的数值修正，只丢掉那个瞎编的规则系动作
    expect(解释.规则).toHaveLength(1);
    expect(解释.规则[0].动作).toHaveLength(1);
    expect((解释.规则[0].动作[0] as any).类).toBe('数值修正');
  });

  it('认识的七个效果（穿透/必中/必暴/即死/无敌/锁血/无视）原样保留', () => {
    const 解释 = 校验战斗解释({
      ...基础,
      规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 效果: '穿透', 目标: '攻击目标' }] }],
    });

    expect((解释.规则[0].动作[0] as any).效果).toBe('穿透');
  });

  it('实战：无效的规则系动作不再产出「规则系「undefined」」日志', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
      技能: { 坏技能: 造解释({ 规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 目标: '攻击目标' }] } as any] }) },
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '坏技能', 目标: '骨卫兵' }, 骰);

    expect(r.步骤.map(s => s.内容).join('\n')).not.toContain('undefined');
  });
});

describe('C · 战斗持久化带上意图模式与日志（切页签/重开面板不丢）', () => {
  it('快照里带 意图模式 与 日志（恢复后仍是当初的模式、日志还在）', () => {
    const 状态 = 造状态(造单位({ id: '契约者', 阵营: '我方', 类型: '玩家' }), 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));

    const 快照 = 构建战斗状态快照(状态, { 意图模式: '随机', 日志: ['第一行', '第二行'] });

    expect(快照.意图模式).toBe('随机');
    expect(快照.日志).toEqual(['第一行', '第二行']);
    const 恢复 = 恢复战斗状态(快照 as any);
    expect(恢复?.状态.进行中).toBe(true);
    expect(恢复?.意图模式).toBe('随机');
    expect(恢复?.日志).toEqual(['第一行', '第二行']);
  });

  it('老存档（没有 意图模式/日志）→ 意图模式按 ai 兜底、日志给空数组（向后兼容）', () => {
    const 状态 = 造状态(造单位({ id: '契约者', 阵营: '我方', 类型: '玩家' }), 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));
    const 快照: any = 构建战斗状态快照(状态, { 意图模式: '随机', 日志: ['x'] });
    delete 快照.意图模式;
    delete 快照.日志;

    const 恢复 = 恢复战斗状态(快照);

    expect(恢复?.意图模式).toBe('ai');
    expect(恢复?.日志).toEqual([]);
  });
});
