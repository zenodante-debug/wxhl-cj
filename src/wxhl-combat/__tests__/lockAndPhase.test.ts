import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 判定转阶段 } from '../engine/turn';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家问（第 2 条尾）：
//   「boss 会有转阶段的能力，比如濒死了回满血。一些角色还有锁血的能力，
//     比如无法一次跌入 50% 以下的血量，必须当前回合先锁在最低 50%，这种实现了么？」
// 查证：**两个都没实现** ——
//   - 锁血只有"HP 不低于 1"的平口径，没有"锁在最大HP的 N%"；
//   - `判定转阶段` 是个**只有测试在调**的空函数，从来没接进伤害结算。
//
// 世界书 <combat_driver> 阶段D：BOSS 当前 HP **首次**降到阶段阈值（70%/40%/20%）
// 立即转阶段 → 清负面、按面板回 HP/MP、获得护盾或 1 回合无敌、解锁阶段技能。
// 玩家口径：被打到 0 也算一条阈值（濒死回满血）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 100,
    MP_最大: 100,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [20] };

/** 打一发（打骨卫兵），返回结算后的状态与步骤文本 */
function 打(守方: 战斗单位, 伤害骰: number[] = 骰.伤害骰) {
  const 攻 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 技能: { 斩击: 造解释({ 伤害倍率: 1 }) } });
  const 状态 = 开战规则结算(造状态(攻, 守方));
  const 守方键 = 守方.id.split('.').pop()!;
  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: 守方键 }, { 命中: 18, 伤害骰 });
  return { 状态: r.状态, 文本: r.步骤.map(s => s.内容).join('\n'), 步骤: r.步骤 };
}

/** 数值修正（常驻） */
const 常驻数值 = (目标: string, 量: number): 规则 =>
  ({ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标, 量: { 源: '常数', 系数: 量 } }] }) as 规则;

describe('锁血 · 锁在最大HP的 N%（玩家问的"锁在最低 50%"）', () => {
  it('一击要打到 10%，实际停在 50%（锁血下限 0.5）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      HP_当前: 1000,
      HP_最大: 1000,
      技能: { 不灭之躯: 造解释({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [常驻数值('锁血下限', 0.5)] }) },
    });

    const { 状态, 文本 } = 打(守, [2500]); // ≈1273 伤害：远超 1000，真能一击打穿

    expect(状态.单位.骨卫兵.HP_当前).toBe(500); // 锁在 50%
    expect(文本).toContain('锁血');
    expect(文本).toContain('50%');
  });

  it('没有这条的同一个单位 → 正常被打到 0（锁血不是白送的）', () => {
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 1000, HP_最大: 1000 });

    const { 状态 } = 打(守, [2500]);

    expect(状态.单位.骨卫兵.HP_当前).toBe(0);
  });

  it('伤害不足以跌到 50% → 不触发锁血，老老实实掉（锁血只在真跌穿时才兜）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      HP_当前: 1000,
      HP_最大: 1000,
      技能: { 不灭之躯: 造解释({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [常驻数值('锁血下限', 0.5)] }) },
    });

    const { 状态 } = 打(守, [1]); // 小伤害

    expect(状态.单位.骨卫兵.HP_当前).toBeLessThan(1000);
    expect(状态.单位.骨卫兵.HP_当前).toBeGreaterThan(500);
  });
});

describe('BOSS 转阶段 · 濒死回满血（玩家问的"boss 濒死了回满血"）', () => {
  /** BOSS 的转阶段技能：回满血 + 清负面（世界书阶段D 的第 1 步） */
  const 转阶段技能 = 造解释({
    行动消耗: '无',
    类型: '被动',
    伤害倍率: 0,
    规则: [
      {
        触发: '转阶段',
        作用域: '自身',
        动作: [{ 类: '资源', 名: 'HP', 操作: '设为', 量: { 源: '表达式', 式: '最大HP' } } as any],
      } as 规则,
    ],
  });

  it('BOSS 被打到 0 → 转阶段回满血，**不进濒死**（永远杀不死的正解是让转阶段是有限次的）', () => {
    const boss = 造单位({
      id: '副本角色.影',
      阵营: '敌方',
      类型: 'BOSS',
      HP_当前: 60,
      HP_最大: 1000,
      技能: { 第二阶段: 转阶段技能 },
    });

    const { 状态, 文本 } = 打(boss, [2500]);

    expect(状态.单位.影.HP_当前).toBe(1000); // 回满
    expect(状态.单位.影.濒死).toBe(null); // 不进濒死
    expect(文本).toContain('转阶段');
  });

  it('BOSS 越过 70% 线 → 也转阶段（世界书的三条阈值）', () => {
    const boss = 造单位({
      id: '副本角色.影',
      阵营: '敌方',
      类型: 'BOSS',
      HP_当前: 1000,
      HP_最大: 1000,
      技能: { 第二阶段: 转阶段技能 },
    });

    const { 文本 } = 打(boss, [700]); // ≈373 伤害：1000 → 627（越过 70% 线）

    expect(文本).toContain('转阶段');
  });

  it('**普通副本角色**被打到 0 → 直接死，没有转阶段（转阶段是 BOSS 的）', () => {
    const 杂兵 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      HP_当前: 60,
      HP_最大: 1000,
      技能: { 第二阶段: 转阶段技能 }, // 就算翻了转阶段技能，非 BOSS 也不该触发
    });

    const { 状态, 文本 } = 打(杂兵, [2500]);

    expect(状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(文本).not.toContain('转阶段');
  });

  it('**转阶段救回来的不算击倒**：击杀时奖励不白送（日志也不写"被击倒"）', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      技能: {
        斩击: 造解释({ 伤害倍率: 1 }),
        猎杀: 造解释({
          行动消耗: '无',
          类型: '被动',
          伤害倍率: 0,
          规则: [
            { 触发: '击杀时', 作用域: '自身', 动作: [{ 类: '资源', 名: '击杀点', 操作: '获得', 量: { 源: '常数', 系数: 1 } } as any] } as 规则,
          ],
        }),
      },
    });
    const boss = 造单位({
      id: '副本角色.影',
      阵营: '敌方',
      类型: 'BOSS',
      HP_当前: 60,
      HP_最大: 1000,
      技能: { 第二阶段: 转阶段技能 },
    });
    const 状态 = 开战规则结算(造状态(攻, boss));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '影' }, { 命中: 18, 伤害骰: [2500] });
    const 文本 = r.步骤.map(s => s.内容).join('\n');

    expect(r.状态.单位.影.HP_当前).toBe(1000); // 转阶段回满
    expect(文本).not.toContain('被「契约者」击倒'); // 没算击倒
    expect(r.状态.单位.契约者.资源['击杀点'] ?? 0).toBe(0); // 击杀时奖励没白送
  });

  it('没有转阶段技能的 BOSS 被打到 0 → 照常死（不强制）', () => {
    const boss = 造单位({ id: '副本角色.影', 阵营: '敌方', 类型: 'BOSS', HP_当前: 60, HP_最大: 1000 });

    const { 状态 } = 打(boss, [2500]);

    expect(状态.单位.影.HP_当前).toBe(0);
    expect(状态.单位.影.濒死).toBe(null); // 副本角色没有濒死 → 死透
  });
});

describe('判定转阶段（纯函数）', () => {
  const boss = (类型 = 'BOSS') => 造单位({ id: '副本角色.影', 阵营: '敌方', 类型, HP_当前: 0, HP_最大: 1000 });

  it('越过 70 / 40 / 20 三条线各返回对应阈值；一次跨多条取最深那条', () => {
    expect(判定转阶段(boss(), 1000, 650)).toEqual({ 阈值: '70%' });
    expect(判定转阶段(boss(), 650, 350)).toEqual({ 阈值: '40%' });
    expect(判定转阶段(boss(), 350, 150)).toEqual({ 阈值: '20%' });
    expect(判定转阶段(boss(), 1000, 100)).toEqual({ 阈值: '20%' }); // 一次跨三条 → 最深
  });

  it('被打到 0 → 返回「濒死」阈值（BOSS 的濒死回满血靠这条）', () => {
    expect(判定转阶段(boss(), 100, 0)).toEqual({ 阈值: '濒死' });
  });

  it('没越线 / 非 BOSS → null', () => {
    expect(判定转阶段(boss(), 900, 800)).toBe(null);
    expect(判定转阶段(boss('杂兵'), 100, 0)).toBe(null);
    expect(判定转阶段(boss('精英'), 1000, 100)).toBe(null);
  });

  it('隐藏BOSS 也算 BOSS（转阶段同样适用）', () => {
    expect(判定转阶段(boss('隐藏BOSS'), 100, 0)).toEqual({ 阈值: '濒死' });
  });
});
