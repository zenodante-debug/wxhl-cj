import { describe, expect, it } from 'vitest';
import { 造我方条目, 造技能展示, 显示名 } from '../engine/viewModel';
import type { 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 视图模型：`.vue` 模板读的属性必须真的存在
//
// 实战踩过的坑：行动区条目本来是 `{键, 名称, 单位, 技能}`（单位被包了一层），
// 而模板里写的是 `u.行动槽.主要` —— `u.行动槽` 是 undefined，读 `.主要` 直接抛，
// **整个组件渲染崩掉、面板一片空白**。`.vue` 模板的属性访问没有任何自动检查
// （无 vue-tsc、vitest 没装 vue 插件、compiler-sfc 不查属性），所以形状必须在纯模块里钉死。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> = {}): 战斗单位 {
  return {
    id: '契约者',
    名称: '青空黎',
    阵营: '我方',
    类型: '玩家',
    属性: { 实际: { STR: 25, AGI: 20, CON: 20, PER: 15 } },
    阶位: '二阶',
    HP_当前: 171,
    HP_最大: 270,
    MP_当前: 30,
    MP_最大: 40,
    耐力_当前: 90,
    耐力_最大: 200,
    防御: 12,
    闪避值: 18,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

describe('造我方条目 · 模板读的字段必须在条目上', () => {
  it('**条目继承战斗单位**：行动槽 / HP / 距离 / 额度 / 属性 直接可读（不要再 `.单位.` 一层）', () => {
    const [条目] = 造我方条目({ 契约者: 造单位() });

    // 这几个正是模板里读的、也是那次崩溃的元凶
    expect(条目.行动槽).toBeDefined();
    expect(条目.行动槽.主要).toBe(1);
    expect(条目.HP_当前).toBe(171);
    expect(条目.HP_最大).toBe(270);
    expect(条目.距离).toBe(0);
    expect(条目.额度).toBe(45);
    expect(条目.属性.实际.STR).toBe(25);
    expect(条目.防御).toBe(12);
    expect(条目.闪避值).toBe(18);
    expect(条目.id).toBe('契约者');
    // 额外给的
    expect(条目.键).toBe('契约者');
    expect(条目.名称).toBe('青空黎');
    expect(条目.技能).toEqual({});
  });

  it('只挑我方（按阵营，不是按类型）—— 杂兵/精英是敌人，不进来', () => {
    const 条目 = 造我方条目({
      契约者: 造单位(),
      骨卫兵: 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英' }),
      江薇芷: 造单位({ id: '小队.成员.江薇芷', 阵营: '我方', 类型: '小队成员' }),
    });

    expect(条目.map(x => x.键).sort()).toEqual(['契约者', '江薇芷']);
  });

  it('名称缺省时退回 id 末段；技能表缺省时给空对象（模板要能安全遍历）', () => {
    const [条目] = 造我方条目({
      骨卫兵: 造单位({ id: '小队.成员.白露露', 名称: undefined, 技能: undefined as any }),
    });

    expect(条目.名称).toBe('白露露');
    expect(条目.技能).toEqual({});
  });

  it('空表 / undefined 不抛错', () => {
    expect(造我方条目({})).toEqual([]);
    expect(造我方条目(undefined as any)).toEqual([]);
  });
});

describe('显示名', () => {
  it('优先 头部.姓名，其次 id 末段', () => {
    expect(显示名(造单位())).toBe('青空黎');
    expect(显示名(造单位({ 名称: '', id: '副本角色.乌尔奇奥拉·西法' }))).toBe('乌尔奇奥拉·西法');
    expect(显示名(造单位({ 名称: undefined, id: '骨卫兵' }))).toBe('骨卫兵');
  });
});

describe('造技能展示', () => {
  const 解释 = (覆盖: Partial<战斗解释> = {}): 战斗解释 => ({
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: 'MP 5',
    冷却: 3,
    分类: '基础',
    类型: '主动',
    可预判: true,
    伤害倍率: 1.4,
    规则: [],
    托管: [],
    ...覆盖,
  });

  it('下拉摘要带上关键字段（光看名字选不了行动）', () => {
    const [展示] = 造技能展示({ 月牙天冲: 解释() });

    expect(展示.摘要).toBe('月牙天冲（主要行动 · 近战 · ×1.4）');
  });

  it('没有伤害的技能显示「无伤害」（如纯 buff / 装备）', () => {
    const [展示] = 造技能展示({ 死霸装: 解释({ 伤害倍率: 0, 射程: '自身', 目标: '自身' }) });

    expect(展示.倍率).toBe('无伤害');
    expect(展示.摘要).toContain('无伤害');
  });

  it('详情表要的字段都在，且规则数是**有效条目**数（过滤掉模型塞的 null）', () => {
    const [展示] = 造技能展示({
      甲: 解释({ 规则: [{ 触发: '命中时', 作用域: '攻击目标', 动作: [] } as any, null as any] }),
    });

    expect(展示.行动消耗).toBe('主要行动');
    expect(展示.射程).toBe('近战');
    expect(展示.目标).toBe('单体');
    expect(展示.消耗).toBe('MP 5');
    expect(展示.冷却).toBe(3);
    expect(展示.规则数).toBe(1);
  });

  it('按名字排序（界面顺序稳定，不随对象键序抖动）', () => {
    const 展示 = 造技能展示({ 丙: 解释(), 甲: 解释(), 乙: 解释() });

    expect(展示.map(x => x.名)).toEqual(['丙', '乙', '甲'].sort((a, b) => a.localeCompare(b)));
  });

  it('字段缺失 / 空技能表 → 给空串，模板不会读到 undefined', () => {
    expect(造技能展示(undefined)).toEqual([]);
    const [展示] = 造技能展示({ 怪: {} as any });
    expect(展示.行动消耗).toBe('');
    expect(展示.射程).toBe('');
    expect(展示.规则数).toBe(0);
  });
});
