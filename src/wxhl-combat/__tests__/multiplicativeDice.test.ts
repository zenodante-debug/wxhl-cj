import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 效果预览 } from '../engine/effectPreview';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家实测 2026-10-11（plan §19 R3）：
//   加百列「巨剑精通：使用双手重型武器时，**基础伤害骰强制翻倍**，并无视目标30%的物理防御」
//   → 效果**完全没生效**。
//
// 根因链条（实测确认）：
//   1. `数值修正` 的所有目标**只有加法**（基础伤害骰 / 攻击倍率 都是"加多少"）；
//   2. 模型要表达"翻倍"，自己发明了 `量: {源:'表达式', 式:'基础伤害骰'}`
//      （"加上它自己" = 翻倍）—— 这其实是个很聪明的写法；
//   3. 但表达式求值器的标识符表（combatInterpreter.ts）里**没有** `基础伤害骰`
//      → 抛「表达式里的未知标识符: 基础伤害骰」；
//   4. `开战规则结算` 捕获异常 → **整条规则丢弃**。
//   实测战报：`忽略：「契约者」的常驻规则「巨剑精通」求值失败：表达式里的未知标识符: 基础伤害骰`
//
// 修法：给引擎补一条**乘法通道** —— `数值修正 目标 '基础伤害骰倍率'`
//   （量 1 = 骰值总和 ×2，量 0.5 = ×1.5），在 `骰值总和_含修正` 处乘。
//   同时提示词里教这一条，模型就不用再自己发明写法了（见 §19.3 F6）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };
// ⚠️ 注入的 `伤害骰: [6]` 是**骰值数组，求和 = 6**（不是"20 颗骰子各 6 点"）。
// STR 10、一阶 → 属性修正 (10−5)×1 = 5。
// 一阶武器伤害 = ⌈((骰值总和 + 强化) × (1 + (1−1)/2) + 属性修正) × 倍率⌉
//              = ⌈(骰值总和 + 5) × 倍率⌉

/** 打一发「斩击」（伤害倍率 0 → 只吃武器部分），返回实际扣掉的 HP */
function 打(规则: 规则[] = []): number {
  const 我 = 造单位({
    id: '契约者',
    阵营: '我方',
    主武器: { 伤害骰: '2d6', 倍率: 1.0, 强化等级: 0, 阶位: '一阶' },
    技能: { 斩击: 造解释({ 伤害倍率: 0, 规则 }) },
  });
  const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000, 防御: 0 });
  const 状态 = 开战规则结算(造状态(我, 敌));
  return 10000 - 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰).状态.单位.骨卫兵.HP_当前;
}

const 常驻倍率 = (量: number): 规则[] => [
  { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '基础伤害骰倍率', 量: { 源: '常数', 系数: 量 } }] },
];

describe('「基础伤害骰翻倍」有了乘法通道（数值修正 目标 基础伤害骰倍率）', () => {
  it('基线：主武器 2d6 × 倍率 1.0，骰值总和 6 → ⌈(6+5)×1.0⌉ = 11', () => {
    expect(打()).toBe(11);
  });

  it('「基础伤害骰翻倍」（量 1）→ 骰值总和 6→12 → ⌈(12+5)×1.0⌉ = 17', () => {
    expect(打(常驻倍率(1))).toBe(17);
  });

  it('「基础伤害骰 +50%」（量 0.5）→ 骰值总和 6→9 → ⌈(9+5)×1.0⌉ = 14', () => {
    expect(打(常驻倍率(0.5))).toBe(14);
  });

  it('只乘**武器骰**，不乘属性修正（翻倍后 17 而不是 ⌈(6+5)×2⌉=22）', () => {
    expect(打(常驻倍率(1))).not.toBe(22);
  });

  it('「基础伤害骰倍率」与加法通道「基础伤害骰」可叠加：先加后乘', () => {
    // 骰值总和 6 → +4 → 10 → ×2 → 20 → ⌈(20+5)×1.0⌉ = 25
    const 规则: 规则[] = [
      {
        触发: '常驻',
        作用域: '自身',
        动作: [
          { 类: '数值修正', 目标: '基础伤害骰', 量: { 源: '常数', 系数: 4 } },
          { 类: '数值修正', 目标: '基础伤害骰倍率', 量: { 源: '常数', 系数: 1 } },
        ],
      },
    ];
    expect(打(规则)).toBe(25);
  });

  it('量 0（或没有这条修正）→ 老实等于基线，不改变老行为', () => {
    expect(打(常驻倍率(0))).toBe(11);
  });
});

describe('「基础伤害骰倍率」在效果预览里说人话', () => {
  it('预览写「基础伤害骰 ×2」而不是原始键名', () => {
    const 预览 = 效果预览(
      造解释({
        规则: [
          /** 预览不吃状态，直接看规则 */
          { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '基础伤害骰倍率', 量: { 源: '常数', 系数: 1 } }] },
        ],
      }),
    );
    const 行 = 预览.行.join('\n');
    expect(行).toContain('基础伤害骰');
    expect(行).not.toContain('基础伤害骰倍率'); // 原始键名别漏到界面上
  });
});
