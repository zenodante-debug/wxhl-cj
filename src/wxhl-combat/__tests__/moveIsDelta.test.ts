import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位 } from '../types';

// ================================================================
// 玩家实测（2026-10-10）：「现在的移动，输入移动多少，结果是移动到对应的坐标，
//   比如我在"9"，输入个"10"，应该是执行的 +10，也就是移动到"19"，
//   结果会给我移动到 10。也就是说，现在的移动不是做加减法，而是直接坐标替换。」
//
// 玩家裁决：「输入的是**位移量**！这才是移动距离的意义！」
//
// 修法：`结算移动` 里 `目标距离 = 当前.距离 + 位移`（原来是 `= 行动.距离`，直接替换坐标）。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 1000,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

describe('移动是位移量（加减法），不是目标坐标', () => {
  const 走 = (起点: number, 位移: number) => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 距离: 起点, 额度: 1000 });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 距离: 999 });
    const 状态 = 开战规则结算(造状态(我, 敌));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '移动', 距离: 位移 }, 骰);
    return { 距离: r.状态.单位.契约者.距离, 额度: r.状态.单位.契约者.额度, 文本: r.步骤.map(s => s.内容).join('\n') };
  };

  it('在 9 米输入 +10 → 到 **19** 米（不是 10）', () => {
    expect(走(9, 10).距离).toBe(19);
  });

  it('在 9 米输入 -5 → 到 **4** 米（不是 -5）', () => {
    expect(走(9, -5).距离).toBe(4);
  });

  it('额度按**位移量**扣（+10 扣 10，不是按坐标扣）', () => {
    expect(走(9, 10).额度).toBe(1000 - 10);
  });

  it('输入 0 → 原地不动：不扣槽、不扣额度，并说明', () => {
    const r = 走(9, 0);
    expect(r.距离).toBe(9);
    expect(r.额度).toBe(1000);
    expect(r.文本).toContain('原地不动');
  });

  it('日志写的是"移动 N 米：起点 → 终点"，N 是位移量', () => {
    expect(走(9, 10).文本).toContain('移动 10 米：9 → 19 米');
  });
});
