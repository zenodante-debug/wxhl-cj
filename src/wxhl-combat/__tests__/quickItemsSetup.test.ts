import { describe, expect, it } from 'vitest';
import { 快捷栏位数, 造空栏位, 显示快捷栏, 收集快捷物品, 快捷物品初始数量, 快捷物品消耗, 快捷物品写回表 } from '../engine/quickItems';

// ================================================================
// 快捷物品栏 · 准备页的纯逻辑（plan §21）
//
// 为什么这一段单独测：`.vue` 在测试里是 **SSR** 渲染的 —— `onMounted` 不跑、
// 名单永远是空的，槽位 UI 根本渲染不出来。所以判断一律放 `engine/quickItems.ts`。
//
// 玩家裁定：**每个我方单位各 3 个**；下拉列**该单位自己背包里全部**物品；敌方没有栏位。
// ================================================================

describe('栏位是什么样', () => {
  it('3 个空栏位', () => {
    expect(快捷栏位数).toBe(3);
    expect(造空栏位()).toEqual(['', '', '']);
  });
});

describe('哪些单位有快捷物品栏', () => {
  it('选中 + 我方 → 有', () => {
    expect(显示快捷栏(true, '我方')).toBe(true);
  });

  it('敌方 / 不参战 / 没勾选 → 没有', () => {
    expect(显示快捷栏(true, '敌方')).toBe(false);
    expect(显示快捷栏(true, '待定')).toBe(false);
    expect(显示快捷栏(false, '我方')).toBe(false);
    expect(显示快捷栏(true, undefined)).toBe(false);
  });
});

describe('收集要带进战斗的快捷物品', () => {
  const 名单 = [{ id: '契约者' }, { id: '小队.成员.白露露' }, { id: '副本角色.骨卫兵' }];

  it('每个我方单位各收一份（3 个都选了就收 3 个）', () => {
    const 出 = 收集快捷物品(
      名单,
      { 契约者: true, '小队.成员.白露露': true, '副本角色.骨卫兵': true },
      { 契约者: '我方', '小队.成员.白露露': '我方', '副本角色.骨卫兵': '敌方' },
      {
        契约者: ['绷带', '恢复药水', 'MP 恢复药剂'],
        '小队.成员.白露露': ['她的箭'],
        '副本角色.骨卫兵': ['不该出现'],
      },
    );

    expect(出.契约者).toEqual(['绷带', '恢复药水', 'MP 恢复药剂']);
    expect(出['小队.成员.白露露']).toEqual(['她的箭']);
    // 敌方没有栏位
    expect(出['副本角色.骨卫兵']).toBeUndefined();
  });

  it('空格子 / 重复选择 / 前后空白都清掉', () => {
    const 出 = 收集快捷物品(
      [{ id: '契约者' }],
      { 契约者: true },
      { 契约者: '我方' },
      { 契约者: ['绷带', '', '绷带', '  恢复药水  '] },
    );

    expect(出.契约者).toEqual(['绷带', '恢复药水']);
  });

  it('一个都没选 → 这个单位不出现在结果里（别塞个空数组进去）', () => {
    const 出 = 收集快捷物品([{ id: '契约者' }], { 契约者: true }, { 契约者: '我方' }, { 契约者: ['', '', ''] });
    expect(出.契约者).toBeUndefined();
  });

  it('**中途把单位改成敌方 / 取消勾选 → 之前选的物品不跟着进战斗**', () => {
    const 栏位 = { 契约者: ['绷带'] };
    expect(收集快捷物品([{ id: '契约者' }], { 契约者: true }, { 契约者: '敌方' }, 栏位).契约者).toBeUndefined();
    expect(收集快捷物品([{ id: '契约者' }], { 契约者: false }, { 契约者: '我方' }, 栏位).契约者).toBeUndefined();
  });
});

describe('折算成开战时要灌进 `单位.快捷物品` 的初始数量', () => {
  const 背包 = [
    { 名称: '绷带', 数量: 99 },
    { 名称: '恢复药水', 数量: 3 },
  ];

  it('按背包数量灌进去（这就是"还剩几个"的起点）', () => {
    expect(快捷物品初始数量(['绷带', '恢复药水'], 背包)).toEqual({ 绷带: 99, 恢复药水: 3 });
  });

  it('背包里没有的 / 数量非法的 → 跳过（改名、删掉了都不该炸）', () => {
    expect(快捷物品初始数量(['绷带', '已经没有的'], 背包)).toEqual({ 绷带: 99 });
    expect(快捷物品初始数量(['绷带'], [{ 名称: '绷带', 数量: 0 }])).toEqual({});
    expect(快捷物品初始数量(undefined, 背包)).toEqual({});
  });
});

describe('算这一场用掉了几个（收尾写回背包）', () => {
  it('初始 99、结束 97 → 用掉 2', () => {
    expect(快捷物品消耗({ 绷带: 99, 药水: 3 }, { 绷带: 97, 药水: 3 })).toEqual({ 绷带: 2 });
  });

  it('一个都没用 → 空表（**别去白写一次背包**）', () => {
    expect(快捷物品消耗({ 绷带: 99 }, { 绷带: 99 })).toEqual({});
    expect(快捷物品消耗({}, undefined)).toEqual({});
  });

  it('剩的比初始还多（资源被别的规则改了）→ 当 0 用掉，**不许算出负数去加背包**', () => {
    expect(快捷物品消耗({ 愤怒: 3 }, { 愤怒: 9 })).toEqual({});
  });

  it('结束时找不到这个资源（状态被换掉了）→ **一个都不扣**（不确定就别动玩家的背包）', () => {
    expect(快捷物品消耗({ 绷带: 5 }, {})).toEqual({});
    expect(快捷物品消耗({ 绷带: 5 }, undefined)).toEqual({});
  });
});

describe('收尾写回表：单位id → 用掉几个', () => {
  it('按住 `单位.id` 对号入座（不是按短名/下标——一波两只同名兵会串）', () => {
    const 单位表 = {
      骨卫兵: { id: '副本角色.骨卫兵', 快捷物品: { 绷带: 98 } },
      契约者: { id: '契约者', 快捷物品: { 绷带: 97, 药水: 3 } },
    };

    expect(快捷物品写回表({ 契约者: { 绷带: 99, 药水: 3 } }, 单位表)).toEqual({ 契约者: { 绷带: 2 } });
  });

  it('一个都没用 → 空表（别去白写一次背包）', () => {
    expect(快捷物品写回表({ 契约者: { 绷带: 99 } }, { 契约者: { id: '契约者', 快捷物品: { 绷带: 99 } } })).toEqual({});
    expect(快捷物品写回表(undefined, {})).toEqual({});
  });

  it('单位在战斗里找不到（没参战 / 被移出）→ 跳过，不许瞎扣', () => {
    expect(快捷物品写回表({ 契约者: { 绷带: 99 } }, {})).toEqual({});
  });
});
