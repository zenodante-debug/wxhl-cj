import { describe, expect, it } from 'vitest';
import { 归一化规则, 规则结构完好 } from '../engine/ruleShape';
import { 校验战斗解释 } from '../ai/skillInterpreter';
import { 开战常驻结算 } from '../engine/loop';
import { 效果预览 } from '../engine/effectPreview';
import type { 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家反馈（附了一整屏实际输出）：
//   「角色的详情有很大问题，效果不仅解析不出来，还有乱码，然后，有时候一些技能的效果不会写进状态里」
// 实际输出长这样：
//   崩玉核心宿体（饰品） · 非行动效果 · 自身 · 自身
//   undefined → undefined：（无动作）   ← 重复 9 次
//
// 根因：**规则条目从来没做结构校验** —— `有效规则` 只滤掉 null，`{}` 与空动作的垃圾规则照样通过。
// 后果有两层：预览打出 `undefined → undefined`；引擎那边 `执行规则` 得到空结果 → **静默什么都不落**
//（于是"技能的效果不会写进状态里"，而且没有任何提示）。
//
// 修法：统一的结构判定（`engine/ruleShape`）——
//   翻译时归一化（垃圾规则丢掉、全丢则整条判失败进复核）；
//   引擎消费时同样只认结构完好的规则，并在开战时把"被忽略几条"写进日志。
// ================================================================

const 合法规则: 规则 = {
  触发: '常驻',
  作用域: '自身',
  动作: [{ 类: '数值修正', 目标: '防御', 量: { 源: '常数', 系数: 5 } } as any],
};

describe('规则结构判定（engine/ruleShape）', () => {
  it('结构完好的规则认；垃圾规则不认', () => {
    expect(规则结构完好(合法规则)).toBe(true);
    expect(规则结构完好({} as any)).toBe(false); // 玩家截图里那种
    expect(规则结构完好({ 触发: '常驻', 作用域: '自身', 动作: [] } as any)).toBe(false); // 空动作
    expect(规则结构完好({ 触发: '常驻' } as any)).toBe(false); // 没动作
    expect(规则结构完好({ 作用域: '自身', 动作: [{ 类: '护盾', 量: {} }] } as any)).toBe(false); // 没触发
    expect(规则结构完好({ 触发: '开打时', 作用域: '自身', 动作: [{ 类: '护盾', 量: {} }] } as any)).toBe(false); // 触发点不认识
    expect(规则结构完好(null as any)).toBe(false);
    expect(规则结构完好('常驻' as any)).toBe(false);
  });

  it('归一化：丢掉坏的、留下好的，并报出丢了几条', () => {
    const { 规则, 丢弃 } = 归一化规则([合法规则, {} as any, null as any, { 触发: '常驻', 动作: [] } as any]);

    expect(规则).toHaveLength(1);
    expect(规则[0]).toBe(合法规则);
    expect(丢弃).toBe(3);
  });

  it('不是数组 / 空 → 空结果、丢弃 0（合法的"没有效果"）', () => {
    expect(归一化规则(undefined)).toEqual({ 规则: [], 丢弃: 0 });
    expect(归一化规则([])).toEqual({ 规则: [], 丢弃: 0 });
    expect(归一化规则('常驻' as any)).toEqual({ 规则: [], 丢弃: 0 });
  });
});

describe('翻译校验：垃圾规则不再假装成功（改为进复核）', () => {
  const 基础 = {
    行动消耗: '无',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '被动',
    可预判: false,
  };

  it('全是被截图中那种空规则 → **整条判失败**，玩家能在复核里重翻', () => {
    expect(() => 校验战斗解释({ ...基础, 规则: [{}, {}, {}] })).toThrow(/不完整|重翻/);
  });

  it('部分坏部分好 → 保留好的，并记下忽略了几条（详情面板要显示）', () => {
    const 解释 = 校验战斗解释({ ...基础, 规则: [合法规则, {} as any] });

    expect(解释.规则).toHaveLength(1);
    expect(解释.忽略的规则).toBe(1);
  });

  it('干干净净的规则 → 忽略数为 0（不进详情面板的提示）', () => {
    const 解释 = 校验战斗解释({ ...基础, 规则: [合法规则] });

    expect(解释.忽略的规则).toBe(0);
  });

  it('压根没写规则 → 照样成功（合法的"没有额外效果"）', () => {
    const 解释 = 校验战斗解释({ ...基础 });

    expect(解释.规则).toEqual([]);
    expect(解释.忽略的规则).toBe(0);
  });
});

describe('预览：不再出现 undefined → undefined', () => {
  it('结构不完好的规则不产生预览行（旧缓存里的垃圾数据也不再打出乱码行）', () => {
    const 解释 = { ...({} as 战斗解释), 规则: [{}, null] as any, 托管: [], 伤害倍率: 0 } as 战斗解释;

    const 预览 = 效果预览(解释);

    expect(预览.行.join('\n')).not.toContain('undefined');
    expect(预览.行.join('\n')).toContain('没有额外效果');
  });

  it('有被忽略的规则时明确写出来（而不是静默少几条）', () => {
    const 解释 = { 规则: [合法规则], 忽略的规则: 2, 托管: [], 伤害倍率: 0 } as unknown as 战斗解释;

    expect(效果预览(解释).行.join('\n')).toContain('2 条');
  });
});

describe('引擎：结构不完好的规则不会被当成有效规则', () => {
  it('开战时把"该技能的效果字段不完整"写进日志（不再静默什么都不发生）', () => {
    const 单位: 战斗单位 = {
      id: '契约者',
      名称: '青空黎',
      阵营: '我方',
      类型: '玩家',
      属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
      阶位: '一阶',
      HP_当前: 100,
      HP_最大: 100,
      MP_当前: 50,
      MP_最大: 50,
      耐力_当前: 100,
      耐力_最大: 100,
      防御: 0,
      闪避值: 0,
      距离: 0,
      行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
      额度: 30,
      冷却: {},
      护盾: 0,
      架势: null,
      状态: [],
      濒死: null,
      资源: {},
      词条: new Set(),
      技能: {
        // 旧缓存里的坏数据：规则字段是空对象
        崩玉神化之痕: { ...({} as 战斗解释), 规则: [{}] as any, 托管: [], 类型: '被动', 行动消耗: '无' },
      } as any,
    };
    const 步骤: any[] = [];

    const 后 = 开战常驻结算(
      { 进行中: true, 回合: 1, 先攻: [], 单位: { 契约者: 单位 }, 待决: null, 领域: [] },
      步骤,
    );

    expect(后.单位.契约者.状态).toHaveLength(0); // 没落状态（本来就没有有效效果）
    expect(步骤.map(s => s.内容).join('\n')).toContain('效果字段不完整'); // 但**说了出来**
  });
});
