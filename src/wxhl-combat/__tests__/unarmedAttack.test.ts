import { describe, expect, it } from 'vitest';
import { 徒手伤害骰 } from '../engine/damage';
import { 开战规则结算, 跑一个回合 } from '../engine/loop';
import { 列行动选项 } from '../engine/actionOptions';
import type { 战斗状态, 战斗单位 } from '../types';

// ================================================================
// 玩家提问：「徒手攻击怎么着也得带上 str 修正吧？还是说在你这里的武器攻击都不附加修正？」
//
// 答案（照世界书原文核过）：
//   - 公式：`武器伤害 = ((武器伤害骰 + 强化等级) × (1+(阶位−1)/2) + **属性修正**) × 武器倍率`
//     —— 属性修正**在 ×倍率 里面**，所以徒手（倍率 0.5）的 STR 修正只算一半；
//     这不是漏了修正，是世界书就这么写的。
//   - **徒手时阶位 = 人物阶位、强化 = 0**（世界书原文）。
//
// 但顺手查出**一个真 bug**：世界书速查表里徒手的伤害骰**按阶位长**——
//   一阶 d4 / 二阶 3d4 / 三阶 5d4 / 四阶 7d4 / 五阶 11d4，
//   而代码里写死了 `1d4`，五阶角色徒手被少算了 11 倍骰值。
// ================================================================

describe('徒手伤害骰 · 按阶位取（世界书白色品质速查表）', () => {
  it('一~五阶：d4 / 3d4 / 5d4 / 7d4 / 11d4', () => {
    expect(徒手伤害骰('一阶')).toBe('1d4');
    expect(徒手伤害骰('二阶')).toBe('3d4');
    expect(徒手伤害骰('三阶')).toBe('5d4');
    expect(徒手伤害骰('四阶')).toBe('7d4');
    expect(徒手伤害骰('五阶')).toBe('11d4');
  });

  it('超脱（与更高写法）按五阶档；认不出的按一阶（绝不让徒手变成 0 伤害）', () => {
    expect(徒手伤害骰('超脱')).toBe('11d4');
    expect(徒手伤害骰('超脱者')).toBe('11d4');
    expect(徒手伤害骰('怪阶')).toBe('1d4');
  });
});

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 100,
    MP_最大: 100,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

describe('徒手攻击 · 实战（STR 修正真的进了伤害）', () => {
  const 打一拳 = (阶位: string, STR实际 = 20) => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 阶位, 属性: { 实际: { STR: STR实际, AGI: 10, CON: 20, PER: 10 } } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 100000, HP_最大: 100000, 阶位: '一阶' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 跑一个回合(状态, { 契约者: [{ 类型: '主要行动', 武器: '主武器', 目标: '骨卫兵' }] }, []);
    return { 伤害: 100000 - r.状态.单位.骨卫兵.HP_当前, 步骤: r.步骤.map(s => s.内容).join('\n') };
  };

  it('**STR 修正进了徒手伤害**：STR 20 → STR 200（超脱）徒手明显更疼', () => {
    const 弱 = 打一拳('一阶', 20); // STR修正 15
    const 强 = 打一拳('超脱', 200); // STR修正 (200−5)×20 = 3900

    expect(强.伤害).toBeGreaterThan(弱.伤害);
  });

  it('五阶徒手用的是 11d4（不是写死的 1d4）', () => {
    const r = 打一拳('五阶');

    // 日志里能看到按阶位取的骰式
    expect(r.步骤).toContain('11d4');
  });

  it('行动下拉里徒手标签也按阶位显示骰式', () => {
    const 五阶 = 造单位({ id: '契约者', 阵营: '我方', 阶位: '五阶' });

    const 主要 = 列行动选项(五阶, '主要行动');
    const 徒手 = 主要.find(o => o.值.includes('主武器攻击'))!;

    expect(徒手.标签).toContain('11d4');
  });
});
