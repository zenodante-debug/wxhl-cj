import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 解析消耗 } from '../engine/actionOptions';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家补充（2026-10-09）：
//   「穿透、免疫、都是**规则系**（补充知识）」
//   「【八咫镜·光行】(次要行动/反应动作，**每场限2次**)」
//   「【八尺琼勾玉·净世天光】(主要行动，消耗**最大MP的8%**)」
//
// 三块地基（判定与对抗照旧由规则系防火墙负责，这里只补"程度/限定"与两个小缺口）：
//   1. `规则系判定` 加 **程度**（穿透 0.5 = 无视 50% 防御与抗性）与 **限定**（免疫只挡某一类）；
//   2. **每场限次**（次数用尽 → 跳过并说明）；
//   3. **按最大值的比例消耗**（最大MP的 8%）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 200,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 规则系动作 */
const 规则系 = (效果: string, 额外: Record<string, any> = {}) =>
  ({ 类: '规则系判定', 效果, 目标: '攻击目标', ...额外 }) as any;

describe('1 · 规则系程度：穿透 50%（无视一半防御与抗性）', () => {
  const 打 = (攻方规则: 规则[], 守方覆盖: Partial<战斗单位> = {}) => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
      技能: { 斩击: 造解释({ 规则: 攻方规则 }) },
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 防御: 200, HP_当前: 1000, HP_最大: 1000, ...守方覆盖 });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);
    return { 伤害: 1000 - r.状态.单位.骨卫兵.HP_当前, 文本: r.步骤.map(s => s.内容).join('\n') };
  };

  it('不写程度 = 全穿（防御归 0，与之前行为一致）', () => {
    const 无 = 打([]);
    const 全穿 = 打([{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系('穿透')] } as 规则]);

    expect(全穿.伤害).toBeGreaterThan(无.伤害);
    expect(全穿.文本).toContain('穿透');
  });

  it('**程度 0.5 → 只无视一半防御**，伤害介于"无"与"全穿"之间', () => {
    const 无 = 打([]);
    const 半穿 = 打([{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系('穿透', { 程度: 0.5 })] } as 规则]);
    const 全穿 = 打([{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系('穿透')] } as 规则]);

    expect(半穿.伤害).toBeGreaterThan(无.伤害);
    expect(半穿.伤害).toBeLessThan(全穿.伤害);
    expect(半穿.文本).toContain('50%');
  });

  it('程度写疯了（1.5 / -1 / NaN）→ 夹到 0~1，不炸', () => {
    for (const 程度 of [1.5, -1, Number.NaN]) {
      const r = 打([{ 触发: '使用时', 作用域: '攻击目标', 动作: [规则系('穿透', { 程度 })] } as 规则]);
      expect(Number.isFinite(r.伤害)).toBe(true);
    }
  });
});

describe('2 · 规则系限定：免疫只挡「常规物理」时，魔法照样打得进', () => {
  const 被 = (攻击属性: 'STR' | 'PER', 限定?: string) => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      属性: { 实际: { STR: 200, AGI: 200, CON: 20, PER: 200 } },
      技能: { 打: 造解释({ 关联属性: 攻击属性 }) },
    });
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      技能: {
        光子化身: 造解释({
          行动消耗: '无',
          类型: '被动',
          伤害倍率: 0,
          规则: [{ 触发: '常驻', 作用域: '自身', 动作: [规则系('免疫', 限定 ? { 限定 } : {})] } as 规则],
        }),
      },
    });
    const 状态 = 开战规则结算(造状态(攻, 守));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '打', 目标: '骨卫兵' }, 骰);
    return { 伤害: 1000 - r.状态.单位.骨卫兵.HP_当前, 文本: r.步骤.map(s => s.内容).join('\n') };
  };

  it('免疫（限定：常规物理）→ 物理攻击免伤', () => {
    const r = 被('STR', '常规物理');
    expect(r.伤害).toBe(0);
    expect(r.文本).toMatch(/免疫|无敌/);
  });

  it('免疫（限定：常规物理）→ **魔法攻击照样打进去**（限定不匹配就不免伤）', () => {
    const r = 被('PER', '常规物理');
    expect(r.伤害).toBeGreaterThan(0);
  });

  it('不写限定 = 全免（与现在的"无敌"一致）', () => {
    expect(被('STR').伤害).toBe(0);
    expect(被('PER').伤害).toBe(0);
  });
});

describe('3 · 每场限次（八咫镜·光行 每场 2 次）', () => {
  const 技能 = 造解释({ 行动消耗: '次要行动', 伤害倍率: 0, 每场限次: 2 });

  const 打三次 = () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: { '八咫镜·光行': 技能 },
      冷却: {},
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    let 状态 = 开战规则结算(造状态(我, 敌));
    const 文本: string[] = [];
    for (let i = 0; i < 3; i++) {
      // 每次前清掉冷却（本用例只验"限次"，不混冷却干扰）
      状态.单位.契约者 = { ...状态.单位.契约者, 冷却: {} };
      const r = 结算行动(状态, 状态.单位.契约者, { 类型: '次要行动', 技能: '八咫镜·光行', 目标: '骨卫兵' }, 骰);
      状态 = r.状态;
      文本.push(r.步骤.map(s => s.内容).join('\n'));
    }
    return { 状态, 文本 };
  };

  it('前两次能用，第三次被拦（并说明"本场已用尽 2/2"）', () => {
    const { 状态, 文本 } = 打三次();

    expect(状态.单位.契约者.已用次数?.['八咫镜·光行']).toBe(2);
    expect(文本[0]).not.toContain('已用尽');
    expect(文本[1]).not.toContain('已用尽');
    expect(文本[2]).toContain('已用尽');
  });

  it('没写每场限次 → 不限次（已用次数照记，供界面显示）', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 平砍: 造解释({ 行动消耗: '次要行动', 伤害倍率: 0 }) } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '次要行动', 技能: '平砍', 目标: '骨卫兵' }, 骰);

    expect(r.步骤.map(s => s.内容).join('\n')).not.toContain('已用尽');
  });
});

describe('4 · 按最大值的比例消耗（最大MP的 8%）', () => {
  it('解析消耗：认得「最大MP的8%」与几种写法', () => {
    expect(解析消耗('最大MP的8%')).toEqual({ 资源: 'MP', 比例: 0.08 });
    expect(解析消耗('最大MP 8%')).toEqual({ 资源: 'MP', 比例: 0.08 });
    expect(解析消耗('MP上限的2%')).toEqual({ 资源: 'MP', 比例: 0.02 });
    expect(解析消耗('最大耐力的5%')).toEqual({ 资源: '耐力', 比例: 0.05 });
    expect(解析消耗('MP 60')).toEqual({ 资源: 'MP', 量: 60 });
  });

  it('结算：按最大值扣（1000 上限 × 8% = 80）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      MP_当前: 1000,
      MP_最大: 1000,
      技能: { 净世天光: 造解释({ 消耗: '最大MP的8%', 伤害倍率: 1 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '净世天光', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.契约者.MP_当前).toBe(920);
  });

  it('不够扣 → 跳过（不白扣也不放出来）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      MP_当前: 50,
      MP_最大: 1000,
      技能: { 净世天光: 造解释({ 消耗: '最大MP的8%', 伤害倍率: 1 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '净世天光', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.契约者.MP_当前).toBe(50);
    expect(r.步骤.map(s => s.内容).join('\n')).toMatch(/MP 80|只剩/);
  });
});
