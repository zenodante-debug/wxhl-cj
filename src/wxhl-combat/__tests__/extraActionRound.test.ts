// ================================================================
// 「额外行动回合」（玩家本轮反馈）：
//   「一些技能是能够创造额外回合，或者额外行动次数的，额外行动次数也是创造额外回合了，
//     也就是在这一轮中，行动完了，能够再多一个行动回合」
//   「你实现了『选择行动后，进入计算，在战斗中释放技能，技能加额外行动次数，当场打断行动，
//     选择额外行动选项』的这个步骤吗？」→ 以前没有，这次补上。
//   「多一个回合的本质是多一倍的行动槽嘛（多一个主要、一个次要、移动、反应、免费等等）」
//   「追加回合敌人不出招，是玩家自己的追加回合」
//
// 实现：轮次拆成 `开一轮` / `走一步`（可暂停）/ `提交追加行动`（恢复），
// `跑一个回合` 保持为一跑到底的兼容封装（无人可问时放弃追加，并留痕）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 16, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 30,
    MP_最大: 30,
    耐力_当前: 50,
    耐力_最大: 50,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 30,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位[], 敌方: 战斗单位[] = []): 战斗状态 {
  const 全部 = [...我方, ...敌方];
  return {
    进行中: true,
    回合: 1,
    先攻: 全部.map(u => u.id),
    单位: Object.fromEntries(全部.map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 数值 = (目标: string, 量: number) => ({
  类: '数值修正' as const,
  目标: 目标 as any,
  量: { 源: '常数' as const, 系数: 量 },
});

/** 一个给自己加「额外行动回合」的技能（无伤害，次要行动，避免占主要槽） */
const 追加回合技能 = 造解释({
  行动消耗: '次要行动',
  伤害倍率: 0,
  规则: [{ 触发: '使用时', 作用域: '自身', 动作: [数值('额外行动回合', 1)] } as 规则],
});

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 一直走，直到走完或停在待决点上（`走一步` 一步只结算一个行动/一个敌人的意图段） */
function 走到底(轮: ReturnType<typeof 开一轮>) {
  let r = 轮;
  for (let i = 0; i < 50 && !r.完成 && !r.待决; i++) r = 走一步(r);
  return r;
}

describe('额外行动回合 · 落效果', () => {
  it('用掉技能后，单位欠下 1 个追加回合（不是状态，是欠账）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 时之楔: 追加回合技能 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 轮 = 开一轮(造状态([甲], [敌]), { 契约者: [{ 类型: '次要行动', 技能: '时之楔', 目标: '骨卫兵' }] }, []);

    const 后 = 走到底(轮); // 走完契约者的（唯一）行动

    expect(后.状态.单位.契约者.追加行动).toBe(1);
    expect(后.步骤.some(s => s.内容.includes('额外行动回合 ×1'))).toBe(true);
  });

  it('**当场打断**：该单位行动走完后轮次停住，待决点是「额外行动回合」', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 时之楔: 追加回合技能 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 后 = 走到底(开一轮(造状态([甲], [敌]), { 契约者: [{ 类型: '次要行动', 技能: '时之楔', 目标: '骨卫兵' }] }, []));

    expect(后.待决).toEqual({ 类: '额外行动回合', id: '契约者' });
    expect(后.完成).toBe(false); // 没走完：敌人还没轮到
  });

  it('**敌人不会被打断**，也不会在追加回合里出招（追加回合只属我方）', () => {
    const 敌 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      技能: { 异变: 追加回合技能 },
    });
    const 状态 = 造状态([], [敌]);

    // 敌人自己用出"额外行动回合" → 也不产生待决点（第一期：只服务我方）
    const 后 = 走到底(开一轮(状态, {}, [{ 单位: '骨卫兵', 行动: [{ 类型: '次要行动', 技能: '异变', 目标: '自身' }] }]));

    expect(后.待决).toBe(null);
    expect(后.完成).toBe(true);
  });
});

describe('额外行动回合 · 提交后是「一整套槽」', () => {
  function 到待决点(): ReturnType<typeof 开一轮> {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      额度: 30,
      技能: { 时之楔: 追加回合技能 },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    return 走到底(开一轮(造状态([甲], [敌]), { 契约者: [{ 类型: '次要行动', 技能: '时之楔', 目标: '骨卫兵' }] }, []));
  }

  it('槽位重置成**一套新的**（主/次/移/反各 1）+ 再给一份移动额度', () => {
    const 轮 = 到待决点();
    // 消耗掉原来的槽，模拟"这一轮已经用过了"
    轮.状态.单位.契约者.行动槽 = { 主要: 0, 次要: 0, 移动: 0, 反应: 0, 免费: 999 };

    const 后 = 提交追加行动(轮, [{ 类型: '主要行动', 技能: '斩击' }]);

    expect(后.状态.单位.契约者.行动槽).toEqual({ 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 });
    expect(后.状态.单位.契约者.额度).toBe(60); // 30 + 30（再一份面板移动距离）
    expect(后.状态.单位.契约者.追加行动).toBe(0); // 消耗一层
    expect(后.待决).toBe(null);
  });

  it('追加回合的行动**紧接着执行**（位置不动），走完才轮到后面的单位', () => {
    const 轮 = 到待决点();
    // ⚠️ 不能再用「时之楔」—— 它在冷却里（引擎如实拦），换第二个技能续追加
    轮.状态.单位.契约者.技能['时之楔·二'] = 追加回合技能;
    const 后 = 提交追加行动(轮, [{ 类型: '次要行动', 技能: '时之楔·二', 目标: '骨卫兵' }]);

    const 走完 = 走一步(后);

    // 追加行动结算了（又欠下 1 个回合 → 再次停下）
    expect(走完.状态.单位.契约者.追加行动).toBe(1);
    expect(走完.待决).toEqual({ 类: '额外行动回合', id: '契约者' });
  });

  it('追加回合一旦走完，**继续走剩下的先攻**（敌人仍然出招一次）', () => {
    // 手搓一个只有 1 次追加的轮次，提交一个不产生新追加的行动
    const 轮 = 到待决点();
    const 甲无技能 = 提交追加行动(轮, []);
    // 空行动 → 该段长度为 0 → 直接越过该单位，轮到敌人
    const 后 = 走到底(甲无技能);

    expect(后.完成).toBe(true);
    expect(后.步骤.some(s => s.单位 === '骨卫兵' || s.内容.includes('骨卫兵'))).toBe(true);
  });

  it('上限：每回合最多 追加回合上限 次，超过记日志忽略（防跑飞）', () => {
    let 轮 = 到待决点();
    // 每轮换一个技能（同一技能在冷却里，引擎会如实拦住 —— 那条规则另有测试）
    for (let i = 0; i < 追加回合上限 + 1; i++) {
      const 技能名 = `时之楔·续${i}`;
      轮.状态.单位.契约者.技能[技能名] = 追加回合技能;
      轮 = 提交追加行动(轮, [{ 类型: '次要行动', 技能: 技能名, 目标: '骨卫兵' }]);
      轮 = 走一步(轮);
      if (!轮.待决) break;
    }

    expect(轮.追加已用.get('契约者')).toBe(追加回合上限);
    expect(轮.待决).toBe(null); // 到上限后不再打断
    expect(轮.步骤.some(s => s.内容.includes('已达上限'))).toBe(true);
  });
});

describe('额外行动回合 · 与既有机制的关系', () => {
  it('「主要行动 +1」仍是**回合开始加槽**（老机制，不打断）—— 两条并存', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: {
        连击: 造解释({
          行动消耗: '无',
          类型: '被动',
          规则: [{ 触发: '常驻', 作用域: '自身', 动作: [数值('主要行动', 1)] } as 规则],
        }),
      },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态([甲], [敌]));

    const 行动: 意图行动[] = [{ 类型: '主要行动', 技能: '斩击' }];
    const 后 = 走到底(开一轮(状态, { 契约者: 行动 }, []));

    expect(后.待决).toBe(null); // 不打断
    expect(后.完成).toBe(true);
  });

  it('常驻被动「每回合额外一个行动回合」→ 回合开始时就欠 1 个', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: {
        时之血脉: 造解释({
          行动消耗: '无',
          类型: '被动',
          规则: [{ 触发: '常驻', 作用域: '自身', 动作: [数值('额外行动回合', 1)] } as 规则],
        }),
      },
    });

    const 后 = 开战规则结算(造状态([甲], []));

    expect(回合开始追加行动(后.单位.契约者)).toBe(1);
  });

  it('**空段也要查追加**：有追加但没被下命令的单位，追加不能静默蒸发（代码评审 #5a）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 追加行动: 1 });

    const 后 = 走一步(开一轮(造状态([甲], []), {}, []));

    expect(后.待决).toEqual({ 类: '额外行动回合', id: '契约者' });
    expect(后.完成).toBe(false);
  });

  it('**倒地的单位不给追加**（玩家不该被提示给一具尸体指定行动，代码评审 #9）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 追加行动: 1 });

    const 后 = 走一步(开一轮(造状态([甲], []), {}, []));

    expect(后.待决).toBe(null);
    expect(后.完成).toBe(true);
  });

  it('`跑一个回合`（兼容层）无人可问 → 放弃追加并**留痕**，其余单位照常走完', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 时之楔: 追加回合技能 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const r = 跑一个回合(造状态([甲], [敌]), { 契约者: [{ 类型: '次要行动', 技能: '时之楔', 目标: '骨卫兵' }] }, []);

    expect(r.步骤.some(s => s.内容.includes('放弃这次追加'))).toBe(true);
    expect(r.状态.单位.契约者.追加行动).toBe(0);
    // 敌人照旧动了（这一轮该出招还是出招）
    expect(r.步骤.some(s => s.单位 === '骨卫兵' || s.内容.includes('骨卫兵'))).toBe(true);
  });

  it('没有任何追加时，`跑一个回合` 与旧行为一致（纯回归）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释({ 伤害倍率: 1 }) } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 500, HP_最大: 500 });

    const r = 跑一个回合(造状态([甲], [敌]), { 契约者: [{ 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }] }, [], 骰);

    expect(r.状态.单位.骨卫兵.HP_当前).toBeLessThan(500);
    expect(r.步骤.some(s => s.内容.includes('额外行动回合'))).toBe(false);
  });
});

