import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 演出事件提取 } from '../engine/showEvents';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 决斗场美术 · Task 4：演出事件提取（纯函数）
//
// 演出层（飘字/轨迹/变身/打断/濒死）**不解析日志文本** ——
// 文本是给玩家看的、随时会改；演出只认 `结算步骤` 上的结构化标记
// （`事件` / `数值` / `攻方` / `守方` / `形态` / `效果`，在产生步骤的地方打上）。
// 这个文件把"真实结算 → 提得出事件"钉死。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 30,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

function 打一发(攻方: 战斗单位, 守方: 战斗单位, 技能 = '斩击', 注入: any = {}) {
  const 状态 = 开战规则结算(造状态(攻方, 守方));
  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能, 目标: '骨卫兵' }, { ...骰, ...注入 });
  return 演出事件提取(r.步骤);
}

describe('演出事件提取（结算步骤 → 结构化演出事件）', () => {
  it('命中 → 「命中」事件：带伤害数值与攻守双方', () => {
    const 事件 = 打一发(造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释() } }), 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));

    const 命中 = 事件.find(e => e.类 === '命中');
    expect(命中).toBeDefined();
    expect(命中!.伤害).toBeGreaterThan(0);
    expect(命中!.守方).toBe('骨卫兵');
  });

  it('未命中 → 「未命中」事件（轨迹画灰）', () => {
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 闪避值: 99999 });
    const 事件 = 打一发(造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释() } }), 守, '斩击', { 命中: 1 });

    expect(事件.some(e => e.类 === '未命中' && e.守方 === '骨卫兵')).toBe(true);
    expect(事件.some(e => e.类 === '命中')).toBe(false);
  });

  it('打断成功 → 「打断成功」事件；打断失败 → 「打断失败」', () => {
    const 击溃 = 造解释({
      行动消耗: '反应动作',
      伤害倍率: 0,
      规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '词条', 名: '打断' } as any] } as 规则],
    });
    const 守 = (力量 = 60) =>
      造单位({
        id: '副本角色.骨卫兵',
        阵营: '敌方',
        属性: { 实际: { STR: 力量, AGI: 10, CON: 20, PER: 10 } },
        预置反应: '击溃',
        技能: { 击溃 },
      });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释() } });

    // 打断值 = 骰 + ⌊关联修正×0.75⌋，要 ≥ 攻方命中 37
    expect(打一发(攻, 守(60), '斩击', { 反应: 20 }).some(e => e.类 === '打断成功')).toBe(true);
    expect(打一发(攻, 守(20), '斩击', { 反应: 1 }).some(e => e.类 === '打断失败')).toBe(true);
  });

  it('变身 → 「变身」事件：带形态名', () => {
    const 变身 = 造解释({
      伤害倍率: 0,
      规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '切换形态', 到: '二阶段·觉醒' } as any] } as 规则],
    });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 卍解: 变身 } });
    const 状态 = 开战规则结算(造状态(攻, 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' })));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '卍解', 目标: '骨卫兵' }, 骰);

    const 事件 = 演出事件提取(r.步骤);
    const 变 = 事件.find(e => e.类 === '变身');
    expect(变).toBeDefined();
    expect(变!.形态).toBe('二阶段·觉醒');
    expect(变!.单位).toBe('契约者');
  });

  it('把守方打到 0 → 「濒死」事件（棋子倒扣）', () => {
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 1 });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释() } });
    const 事件 = 打一发(攻, 守);

    expect(事件.some(e => e.类 === '濒死' && e.守方 === '骨卫兵')).toBe(true);
  });

  it('规则系生效（必中）→ 「规则系」事件：带效果名', () => {
    const 必中 = 造解释({
      规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 效果: '必中', 目标: '攻击目标' } as any] } as 规则],
    });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } }, 技能: { 斩击: 必中 } });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', 阶位: '一阶', 闪避值: 99999 });
    const 事件 = 打一发(攻, 守);

    expect(事件.some(e => e.类 === '规则系' && e.效果 === '必中')).toBe(true);
  });

  it('没有事件标记的步骤不产出事件（支持/移动/跳过 不进演出）', () => {
    expect(演出事件提取([{ 类: '跳过', 内容: '跳过：测试' }])).toEqual([]);
    expect(演出事件提取([])).toEqual([]);
  });
});
