import { describe, expect, it } from 'vitest';
import { 构建批量翻译提示词, 校验战斗解释 } from '../ai/skillInterpreter';

// ================================================================
// 玩家实测（2026-10-10，零号超巨星机甲）：「战甲着装没有算上！
//   很多装备等等的效果，可能是包含这种本质「变身」、「二阶段」的效果的。」
//
// 现状：提示词里只有【变身 / 形态类主动技能】（卍解/万解），那是**技能**的场合。
// 装备卡面写「一旦进入展开着装状态，机甲将直接提供 CON+500, PER+400…」这类
// **涉及属性和衍生属性向上增长**的效果，没有被教 —— 模型只会把它们塞进托管。
//
// 口径（玩家原话）：「模型只需要检测效果里有"属性和衍生属性向上增长"，就能确认」——
// 变身/变形/形态变化/阶段变化，统称**形态变化**。
// ================================================================

describe('形态变化（变身/变形/阶段变化/战甲着装）的提示词配方', () => {
  const 提示词 = 构建批量翻译提示词([]);

  it('有「形态变化」专段，且教的是**按"属性和衍生属性向上增长"检测**（不是只认"变身"这个词）', () => {
    expect(提示词).toContain('形态变化');
    expect(提示词).toContain('属性和衍生属性向上增长');
  });

  it('形态变化**也覆盖装备**（战甲着装这类）—— 不是只教技能', () => {
    // 装备的场合要单独点到，否则模型只会把它用在技能上
    expect(提示词).toMatch(/装备|战甲|着装/);
  });

  it('形态变化的写法：拆出一个切换形态的**主动**技能（主要行动）', () => {
    expect(提示词).toContain('切换形态');
  });

  it('校验器认切换形态（不判失败）—— 别把本来就合法的形态变化拦下来', () => {
    const 解释 = 校验战斗解释({
      行动消耗: '主要行动',
      类型: '主动',
      规则: [
        {
          触发: '使用时',
          作用域: '自身',
          动作: [
            { 类: '切换形态', 到: '展开状态' },
            { 类: '数值修正', 目标: 'CON修正', 量: { 源: '常数', 系数: 495 }, 持续: 999 },
            { 类: '数值修正', 目标: 'PER修正', 量: { 源: '常数', 系数: 390 }, 持续: 999 },
          ],
        },
      ],
      托管: [],
    });

    expect(解释.规则).toHaveLength(1);
    expect(解释.行动消耗).toBe('主要行动');
  });
});
