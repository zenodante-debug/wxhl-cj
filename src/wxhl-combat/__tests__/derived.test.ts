import { describe, expect, it } from 'vitest';
import { 重算实体衍生属性, 重算全部实体 } from '../engine/derived';
import { 属性修正值 } from '../engine/rules';

// ================================================================
// 衍生属性代算（移植自小手机状态栏）
//
// 为什么战斗脚本要自己算：这些衍生值是"小手机"在变量更新时算出来落盘的 ——
// 玩家不开一次小手机就不会算，战斗里读到的是过期甚至为 0 的防御/闪避。
// 实战反馈：命中 DC 473、混合伤害 93133，而 HP 只有 6690 —— 面板两边根本不是一个时代的。
// ================================================================

/** 造一份 stat_data：契约者 + 一个可选实体 */
function 造数据(实体: any = {}, 路径 = '契约者'): any {
  const 底 = {
    头部: { 姓名: '青空黎', 阶位: '一阶' },
    属性: { 基础: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    衍生属性: {},
    装备: {},
    状态: {},
  };
  const 合并 = { ...底, ...实体 };
  if (路径 === '契约者') return { 契约者: 合并 };
  return { 契约者: { ...底, ...实体.__父, 副本角色: { [路径]: 合并 } } };
}

describe('derived · 四维与加成', () => {
  it('装备的主/副属性加成进 属性.实际', () => {
    const d = 造数据({
      装备: { 主武器: { 主属性: 'STR', 主属性加成: 5 }, 躯干: { 副属性: 'CON', 副属性加成: 3 } },
    });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.属性.实际.STR).toBe(15); // 10 + 5
    expect(d.契约者.属性.实际.CON).toBe(13); // 10 + 3
    expect(d.契约者.属性.加成.STR).toBe(5);
  });

  it('职业 / 天赋 / 血统 的加成一起进 属性.实际', () => {
    const d = 造数据({
      职业: { 主属性加成: { 属性: 'PER', 值: 4 }, 副属性加成: { 属性: 'AGI', 值: 2 } },
      头部: { 阶位: '一阶', 天赋: { 属性加成: '全属性+3' }, 血统: { 属性加成: '力量+5' } },
    });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.属性.实际.STR).toBe(18); // 10 + 3(全) + 5(力量)
    expect(d.契约者.属性.实际.PER).toBe(17); // 10 + 3 + 4
    expect(d.契约者.属性.实际.AGI).toBe(15); // 10 + 3 + 2
  });

  it('属性.属性修正值 与引擎同一张表（实际值−5）×阶位系数', () => {
    const d = 造数据({ 头部: { 阶位: '二阶' }, 属性: { 基础: { STR: 20, AGI: 10, CON: 10, PER: 10 } } });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.属性.属性修正值.STR).toBe(属性修正值(20, '二阶')); // (20-5)*2 = 30
    expect(d.契约者.属性.属性修正值.STR).toBe(30);
  });

  it('玩家模式：基础超过属性软上限 → 压到软上限（一阶 25）', () => {
    const d = 造数据({ 属性: { 基础: { STR: 99, AGI: 10, CON: 10, PER: 10 } } });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.属性.基础.STR).toBe(25);
    expect(d.契约者.属性.实际.STR).toBe(25);
  });

  it('敌人模式（杂兵/精英/BOSS）不吃软上限', () => {
    const d = 造数据({ 类型: '精英', 属性: { 基础: { STR: 99, AGI: 10, CON: 10, PER: 10 } } }, '骨卫兵');

    重算实体衍生属性(d, '契约者.副本角色.骨卫兵');

    expect(d.契约者.副本角色.骨卫兵.属性.基础.STR).toBe(99);
  });

  it('阶位写错 / 写成「超脱者」不抛错（代算不能因为一个错别字炸掉开战）', () => {
    const d1 = 造数据({ 头部: { 阶位: '超脱者' } });
    const d2 = 造数据({ 头部: { 阶位: '六阶（打错了）' } });

    expect(() => 重算实体衍生属性(d1, '契约者')).not.toThrow();
    expect(() => 重算实体衍生属性(d2, '契约者')).not.toThrow();
    expect(d2.契约者.属性.属性修正值.STR).toBe(属性修正值(10, '一阶')); // 按一阶兜底
  });
});

describe('derived · 上限与防闪', () => {
  it('HP_最大 = (CON修正+5)×类型系数 + HP额外加成（杂兵 8 / 精英 10 / BOSS 20 / 隐藏BOSS 25）', () => {
    const 造 = (类型: string, 路径: string) => {
      const d = 造数据({ 类型, 属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } } }, 路径);
      重算实体衍生属性(d, `契约者.副本角色.${路径}`);
      return d.契约者.副本角色[路径].衍生属性.HP_最大;
    };

    const 修正CON = 属性修正值(15, '一阶'); // 10
    expect(造('杂兵', '甲')).toBe((修正CON + 5) * 8);
    expect(造('精英', '乙')).toBe((修正CON + 5) * 10);
    expect(造('BOSS', '丙')).toBe((修正CON + 5) * 20);
    expect(造('隐藏BOSS', '丁')).toBe((修正CON + 5) * 25);
  });

  it('MP_最大 = PER修正×10 + 额外；耐力_最大 = (CON修正+5)×10 + 额外', () => {
    const d = 造数据({ 属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 12 } }, 衍生属性: { MP额外加成: 7 } });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.衍生属性.MP_最大).toBe(属性修正值(12, '一阶') * 10 + 7);
    expect(d.契约者.衍生属性.耐力_最大).toBe((属性修正值(15, '一阶') + 5) * 10);
  });

  it('防御 = ⌊(CON修正+5)×0.2⌋ + 防御额外加成 + 装备防御（强化等级只算防具）', () => {
    const d = 造数据({
      属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } },
      衍生属性: { 防御额外加成: 3 },
      装备: { 躯干: { 强化等级: 4, 装备防御: 2 }, 主武器: { 强化等级: 9 } },
    });

    重算实体衍生属性(d, '契约者');

    // CON 15 一阶 → 修正 10；⌊(10+5)×0.2⌋ = 3；+3 额外；+4 躯干强化；+2 躯干装备防御；
    // 主武器强化的 9 **不**算防御（世界书口径：只有防具的强化进防御）
    expect(d.契约者.衍生属性.防御).toBe(3 + 3 + 4 + 2);
  });

  it('闪避值 = ⌊10 + AGI修正×0.5 + 额外 + 装备闪避⌋；移动距离 = 5 + AGI修正 + 额外', () => {
    const d = 造数据({
      属性: { 基础: { STR: 10, AGI: 20, CON: 10, PER: 10 } },
      衍生属性: { 闪避额外加成: 2, 移动距离额外加成: 6 },
      装备: { 饰品: { 装备闪避: 3 } },
    });

    重算实体衍生属性(d, '契约者');

    const 修正AGI = 属性修正值(20, '一阶'); // 15
    expect(d.契约者.衍生属性.闪避值).toBe(Math.floor(10 + 修正AGI * 0.5 + 2 + 3));
    expect(d.契约者.衍生属性.移动距离).toBe(5 + 修正AGI + 6);
  });
});

describe('derived · 当前值与生命状态', () => {
  it('首次代算（HP_最大 本来是 0）→ HP_当前 补满', () => {
    const d = 造数据({ 属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } } });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.衍生属性.HP_当前).toBe(d.契约者.衍生属性.HP_最大);
  });

  it('旧上限非 0 且上限没变 → 当前值**原样保留**（受伤的不会被回满）', () => {
    const 满 = (属性修正值(15, '一阶') + 5) * 15; // 玩家模式默认系数 15
    const d = 造数据({
      属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } },
      衍生属性: { HP_最大: 满, HP_当前: 30 }, // 上限已经是对的
    });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.衍生属性.HP_当前).toBe(30);
  });

  it('上限变大 → 当前值补上差值（升级不该凭空掉血）', () => {
    const 新上限 = (属性修正值(15, '一阶') + 5) * 15; // 玩家模式默认系数 15
    const d = 造数据({
      属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } },
      衍生属性: { HP_最大: 100, HP_当前: 50 }, // 旧上限比新上限小
    });

    重算实体衍生属性(d, '契约者');

    expect(d.契约者.衍生属性.HP_最大).toBe(新上限);
    expect(d.契约者.衍生属性.HP_当前).toBe(50 + (新上限 - 100));
  });

  it('生命状态按 HP 比例分层（健康/受伤/重伤/濒死）', () => {
    const 满 = (属性修正值(15, '一阶') + 5) * 15; // 玩家模式默认系数 15
    const 造 = (HP当前: number) => {
      // HP_最大 必须给对，否则会走"首次代算补满"分支 —— 那就测不到分层了
      const d = 造数据({
        属性: { 基础: { STR: 10, AGI: 10, CON: 15, PER: 10 } },
        衍生属性: { HP_最大: 满, HP_当前: HP当前 },
      });
      重算实体衍生属性(d, '契约者');
      return d.契约者.状态.生命状态;
    };

    expect(造(满)).toBe('健康');
    expect(造(Math.floor(满 * 0.5))).toBe('受伤');
    expect(造(Math.floor(满 * 0.2))).toBe('重伤');
    expect(造(0)).toBe('濒死');
  });
});

describe('derived · 全体重算', () => {
  it('契约者本体 + 小队成员 + 其他契约者 + 副本角色 都算到', () => {
    const d: any = {
      契约者: {
        头部: { 阶位: '一阶' },
        属性: { 基础: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
        衍生属性: {},
        装备: {},
        状态: {},
        小队: { 成员: { 江薇芷: { 类型: '小队成员', 头部: { 阶位: '二阶' }, 属性: { 基础: { STR: 20, AGI: 20, CON: 20, PER: 20 } }, 衍生属性: {}, 装备: {}, 状态: {} } } },
        其他契约者: {},
        副本角色: { 骨卫兵: { 类型: '精英', 头部: { 阶位: '一阶' }, 属性: { 基础: { STR: 30, AGI: 10, CON: 10, PER: 10 } }, 衍生属性: {}, 装备: {}, 状态: {} } },
      },
    };

    重算全部实体(d);

    expect(d.契约者.属性.属性修正值.STR).toBe(5); // (10-5)*1
    expect(d.契约者.小队.成员.江薇芷.属性.属性修正值.STR).toBe(30); // (20-5)*2
    expect(d.契约者.副本角色.骨卫兵.属性.属性修正值.STR).toBe(25); // (30-5)*1
  });

  it('没有契约者数据 → 不抛错', () => {
    expect(() => 重算全部实体({})).not.toThrow();
    expect(() => 重算全部实体(undefined)).not.toThrow();
  });
});
