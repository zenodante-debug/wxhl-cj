    expect(持械结果.状态.单位['契约者'].HP_当前).toBe(64);
    expect(徒手结果.状态.单位['契约者'].HP_当前).toBe(91);
    expect(持械结果.状态.单位['契约者'].HP_当前).not.toBe(徒手结果.状态.单位['契约者'].HP_当前);
