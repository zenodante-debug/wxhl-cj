/**
 * 造一个技能翻译解释。
 * 数值口径由翻译器从技能实体读出：`关联属性` / `技能阶位` / `伤害倍率`（世界书 <技能模版和限制>）。
 * 默认：STR / 一阶 / 伤害倍率 0（= 纯武器攻击，技能不贡献伤害）。
 */
function 造解释(额外: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...额外,
  };
}

