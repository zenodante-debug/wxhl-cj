import { describe, expect, it } from 'vitest';
import { 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';
import type { 意图行动 } from '../ai/enemyTactics';

/**
 * 造一个技能翻译解释。
 * 伤害六步要用到的「伤害骰 / 强化等级 / 武器倍率 / 基础伤害」在 `战斗解释` 里没有正式字段
 * （翻译提示词也没要求 AI 产出），所以引擎按「能取就取、取不到用默认」读取 —— 这里用附加字段模拟。
 */
function 造解释(额外: Record<string, unknown> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    规则: [],
    托管: [],
    ...额外,
  } as unknown as 战斗解释;
}

function 造单位(覆盖: Partial<战斗单位> = {}): 战斗单位 {
  return {
    id: '契约者',
    阵营: '我方',
    类型: '玩家',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 0,
    MP_最大: 0,
    耐力_当前: 0,
    耐力_最大: 0,
    防御: 3,
    闪避值: 10,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

/** 攻方：STR20/AGI10 一阶 → STR修正 15、AGI修正 5；距离 5 米（近距）。 */
function 造攻方(覆盖: Partial<战斗单位> = {}): 战斗单位 {
  return 造单位({
    id: '副本角色.骨卫兵',
    阵营: '敌方',
    类型: '精英',
    属性: { 实际: { STR: 20, AGI: 10, CON: 10, PER: 10 } },
    距离: 5,
    防御: 0,
    技能: { 骨爪撕裂: 造解释({ 伤害骰: '2d6', 强化等级: 0, 武器倍率: 1.0, 基础伤害: 0 }) },
    ...覆盖,
  });
}

function 造状态(攻方 = 造攻方(), 守方 = 造单位()): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: ['副本角色.骨卫兵', '契约者'],
    单位: { 骨卫兵: 攻方, 契约者: 守方 },
    待决: null,
    领域: [],
  };
}

const 攻击: 意图行动 = { 类型: '主要行动', 技能: '骨爪撕裂', 目标: '玩家' };

describe('loop · 结算行动 · 移动', () => {
  it('移动：改距离、扣额度、扣移动行动槽', () => {
    const 状态 = 造状态();
    const 攻方 = 状态.单位['骨卫兵'];

    const 结果 = 结算行动(状态, 攻方, { 类型: '移动', 目标: '契约者', 距离: 12 });

    expect(结果.状态.单位['骨卫兵'].距离).toBe(12);
    expect(结果.状态.单位['骨卫兵'].额度).toBe(30 - 7);
    expect(结果.状态.单位['骨卫兵'].行动槽.移动).toBe(0);
    expect(结果.步骤.some(s => s.类 === '移动')).toBe(true);
  });

  it('移动：额度不足 → 跳过，距离与额度都不变', () => {
    const 状态 = 造状态(造攻方({ 额度: 3 }));
    const 攻方 = 状态.单位['骨卫兵'];

    const 结果 = 结算行动(状态, 攻方, { 类型: '移动', 目标: '契约者', 距离: 12 });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['骨卫兵'].距离).toBe(5);
    expect(结果.状态.单位['骨卫兵'].额度).toBe(3);
  });

  it('移动：跨带脱离近战 → 记一条借机攻击提示步骤', () => {
    const 状态 = 造状态(造攻方({ 额度: 60 }));
    const 攻方 = 状态.单位['骨卫兵'];

    // 5 米（近距）→ 20 米（中距）：脱离近战带
    const 结果 = 结算行动(状态, 攻方, { 类型: '移动', 目标: '契约者', 距离: 20 });

    expect(结果.步骤.some(s => s.内容.includes('借机'))).toBe(true);
    expect(结果.状态.单位['骨卫兵'].距离).toBe(20);
  });

  it('移动：行动槽不足 → 跳过', () => {
    const 状态 = 造状态(造攻方({ 行动槽: { 主要: 1, 次要: 1, 移动: 0, 反应: 1, 免费: 999 } }));
    const 攻方 = 状态.单位['骨卫兵'];

    const 结果 = 结算行动(状态, 攻方, { 类型: '移动', 目标: '契约者', 距离: 12 });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['骨卫兵'].距离).toBe(5);
  });

  it('纯函数：不改动入参状态（原状态的对象仍是原值）', () => {
    const 状态 = 造状态();
    const 攻方 = 状态.单位['骨卫兵'];

    结算行动(状态, 攻方, { 类型: '移动', 目标: '契约者', 距离: 12 });

    expect(状态.单位['骨卫兵'].距离).toBe(5);
    expect(状态.单位['骨卫兵'].额度).toBe(30);
    expect(状态.单位['骨卫兵'].行动槽.移动).toBe(1);
  });
});

describe('loop · 结算行动 · 技能攻击', () => {
  it('技能不存在 → 跳过（R7 在 结算行动 层的兜底）', () => {
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '不存在', 目标: '玩家' });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
  });

  it('目标不在战场上 → 跳过', () => {
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { ...攻击, 目标: '幽灵' });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
  });

  it('超程 → 跳过（近战技能在远距打不到）', () => {
    const 状态 = 造状态(造攻方({ 距离: 100 }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [6, 6] });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
    // 超程是硬门禁：这个行动不算数，主要行动槽不扣
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(1);
  });

  it('行动槽不足 → 跳过', () => {
    const 状态 = 造状态(造攻方({ 行动槽: { 主要: 0, 次要: 1, 移动: 1, 反应: 1, 免费: 999 } }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [6, 6] });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
  });

  it('命中 → 守方 HP 按六步手算的值下降，扣主要行动槽', () => {
    // 骰值 18（非暴击：暴击范围 19）；伤害骰注入 4+5=9
    // 武器伤害 = ⌈((9+0)×(1+(1−1)/2)+15)×1.0⌉ = 24；技能伤害 = 0 → 基础伤害 24
    // 混合伤害 = 24 − 守方防御 3 = 21；部位×1、暴击×1、乘区×1 → 21；护盾 0、减伤 0 → 伤害 21
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(79);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0);
    expect(结果.步骤.some(s => s.类 === '命中')).toBe(true);
    expect(结果.步骤.some(s => s.类 === '伤害' && s.内容.includes('21'))).toBe(true);
  });

  it('命中且暴击（自然20 ≥ 暴击范围）→ 伤害 ×1.5', () => {
    // 21 × 1.5 = 31.5 → 守方 100 − 31.5 = 68.5
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBeCloseTo(68.5);
  });

  it('护盾优先扣除：护盾 5 → 入血 16，护盾清零', () => {
    const 状态 = 造状态(造攻方(), 造单位({ 护盾: 5 }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(84);
    expect(结果.状态.单位['契约者'].护盾).toBe(0);
  });

  it('未命中 → HP 不变，但主要行动槽已消耗', () => {
    // 攻方 STR5/AGI5 → 修正全 0；骰值 1 < 闪避 10
    const 状态 = 造状态(造攻方({ 属性: { 实际: { STR: 5, AGI: 5, CON: 5, PER: 5 } } }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 1, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0);
    expect(结果.步骤.some(s => s.类 === '命中' && s.内容.includes('未命中'))).toBe(true);
  });

  it('自己打自己：扣槽与掉血都不丢（守方键 = 攻方键时的写回顺序）', () => {
    // 攻方 STR20 一阶 → 修正 15；骰值 18 命中；伤害骰 9 → 武器伤害 24，自身防御 0 → 混 24；非暴击
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '骨爪撕裂', 目标: '骨卫兵' }, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['骨卫兵'].HP_当前).toBe(76);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0);
  });
});

describe('loop · 结算行动 · 次要/反应', () => {
  it('次要行动：只扣次要行动槽并记步骤', () => {
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '次要行动', 技能: '骨爪撕裂', 目标: '玩家' });

    expect(结果.状态.单位['骨卫兵'].行动槽.次要).toBe(0);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(1);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
    expect(结果.步骤.some(s => s.类 === '敌方行动')).toBe(true);
  });

  it('次要行动槽为 0 → 跳过', () => {
    const 状态 = 造状态(造攻方({ 行动槽: { 主要: 1, 次要: 0, 移动: 1, 反应: 1, 免费: 999 } }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '次要行动' });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
  });
});
