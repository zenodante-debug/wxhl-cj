describe('loop · 结算行动 · 技能攻击', () => {
  it('技能不存在 → 跳过（R7 在 结算行动 层的兜底）', () => {
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '不存在', 目标: '玩家' });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
  });

  it('目标不在战场上 → 跳过', () => {
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { ...攻击, 目标: '幽灵' });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
  });

  it('超程 → 跳过（近战技能在远距打不到）', () => {
    const 状态 = 造状态(造攻方({ 距离: 100 }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [6, 6] });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
    // 超程是硬门禁：这个行动不算数，主要行动槽不扣
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(1);
  });

  it('行动槽不足 → 跳过', () => {
    const 状态 = 造状态(造攻方({ 行动槽: { 主要: 0, 次要: 1, 移动: 1, 反应: 1, 免费: 999 } }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [6, 6] });

    expect(结果.步骤.some(s => s.类 === '跳过')).toBe(true);
    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
  });

  it('命中 → 守方 HP 按六步手算的值下降，扣主要行动槽', () => {
    // 骰值 18（非暴击：暴击范围 19）；伤害骰注入 4+5=9；主武器 2d6 / 倍率 1.0 / 强化 0
    // 武器伤害 = ⌈((9+0)×(1+(1−1)/2)+15)×1.0⌉ = 24；技能伤害 = 0（伤害倍率 0）→ 基础伤害 24
    // 混合伤害 = 24 − 守方防御 3 = 21；部位×1、暴击×1、乘区×1 → 21；护盾 0、减伤 0 → 伤害 21
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(79);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0);
    expect(结果.步骤.some(s => s.类 === '命中')).toBe(true);
    expect(结果.步骤.some(s => s.类 === '伤害' && s.内容.includes('21'))).toBe(true);
  });

  it('命中且暴击（自然20 ≥ 暴击范围）→ 伤害 ×1.5', () => {
    // 21 × 1.5 = 31.5 → 守方 100 − 31.5 = 68.5
    const 状态 = 造状态();
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 20, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBeCloseTo(68.5);
  });

  it('护盾优先扣除：护盾 5 → 入血 16，护盾清零', () => {
    const 状态 = 造状态(造攻方(), 造单位({ 护盾: 5 }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(84);
    expect(结果.状态.单位['契约者'].护盾).toBe(0);
  });

  it('未命中 → HP 不变，但主要行动槽已消耗', () => {
    // 攻方 STR5/AGI5 → 修正全 0；骰值 1 < 闪避 10
    const 状态 = 造状态(造攻方({ 属性: { 实际: { STR: 5, AGI: 5, CON: 5, PER: 5 } } }));
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], 攻击, { 命中: 1, 伤害骰: [4, 5] });

    expect(结果.状态.单位['契约者'].HP_当前).toBe(100);
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0);
    expect(结果.步骤.some(s => s.类 === '命中' && s.内容.includes('未命中'))).toBe(true);
  });

  it('对自己用技能 → 支援行动：不掷命中、不自伤，但照常扣槽（R21）', () => {
    // 这条以前走攻击管线：掷命中对抗**自己的闪避值**、还打出**武器伤害**（自己打自己）。
    // 「目标: 自身」的自 buff 技能因此会自伤 —— 同阵营现在一律按支援结算。
    // 保留"扣槽不丢"的断言（守方键 = 攻方键时的写回顺序，仍是易错点）。
    const 状态 = 造状态();
    const 战前HP = 状态.单位['骨卫兵'].HP_当前;
    const 结果 = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '骨爪撕裂', 目标: '骨卫兵' }, { 命中: 18, 伤害骰: [4, 5] });

    expect(结果.状态.单位['骨卫兵'].HP_当前).toBe(战前HP); // 没掉血
    expect(结果.状态.单位['骨卫兵'].行动槽.主要).toBe(0); // 槽照扣
    expect(结果.步骤.some(s => s.内容.includes('支援行动'))).toBe(true);
  });
});

