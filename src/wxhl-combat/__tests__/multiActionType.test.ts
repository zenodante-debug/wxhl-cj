// ================================================================
// 玩家实例（2026-10-09，闪闪果实）：
//   「【八咫镜·光行】(次要行动 **或** 反应动作，每场限 2 次)」
//   —— 一条技能挂在**两个**行动类型上：轮到自己的回合当次要行动放，
//      被打的时候还能当反应动作用。一条 `行动消耗: "次要行动"` 装不下。
//
// 口径：`行动消耗` 允许**数组**（也容忍「次要行动/反应动作」这种串），
//   一条技能于是出现在**每个**匹配的下拉里；用掉时扣**所选**那个槽。
//   但**不许白嫖槽位**：声明成主要行动的次要技能要被拦下并说明。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 200,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 八咫镜·光行：次要行动 **或** 反应动作；给自己上 50 点护盾（够简单，好断言） */
const 光行 = (行动消耗: 战斗解释['行动消耗'] = ['次要行动', '反应动作']) =>
  造解释({
    行动消耗,
    射程: '自身',
    目标: '自身',
    类型: '辅助',
    伤害倍率: 0,
    规则: [
      { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '护盾', 量: { 源: '常数', 系数: 50 } }] } as 规则,
    ],
  });

const 骰 = { 命中: 18, 伤害骰: [6] };

describe('1 · 行动类型的归一化（一条技能可以挂多个）', () => {
  it('数组 / 「次要行动/反应动作」/ 「次要行动、反应动作」/ 「次要 或 反应」都认', () => {
    expect(规范行动消耗列表(造解释({ 行动消耗: ['次要行动', '反应动作'] }))).toEqual(['次要行动', '反应动作']);
    expect(规范行动消耗列表(造解释({ 行动消耗: '次要行动/反应动作' }))).toEqual(['次要行动', '反应动作']);
    expect(规范行动消耗列表(造解释({ 行动消耗: '次要行动、反应动作' }))).toEqual(['次要行动', '反应动作']);
    expect(规范行动消耗列表(造解释({ 行动消耗: '次要 或 反应' }))).toEqual(['次要行动', '反应动作']);
  });

  it('「主类型」= 列表第一个（老调用点行为不变）', () => {
    expect(规范行动消耗(造解释({ 行动消耗: ['次要行动', '反应动作'] }))).toBe('次要行动');
    expect(规范行动消耗(造解释({ 行动消耗: '主要行动' }))).toBe('主要行动');
    expect(规范行动消耗(造解释({ 类型: '被动', 行动消耗: '无' }))).toBeNull();
  });

  it('重复的只算一次；顺序按卡面写的来', () => {
    expect(规范行动消耗列表(造解释({ 行动消耗: ['次要行动', '次要行动'] }))).toEqual(['次要行动']);
    expect(规范行动消耗列表(造解释({ 行动消耗: ['反应动作', '次要行动'] }))).toEqual(['反应动作', '次要行动']);
  });

  it('显示文本用「 / 」连', () => {
    expect(行动消耗文本(造解释({ 行动消耗: ['次要行动', '反应动作'] }))).toBe('次要行动 / 反应动作');
    expect(行动消耗文本(造解释({ 行动消耗: '主要行动' }))).toBe('主要行动');
    expect(行动消耗文本(造解释({ 类型: '被动', 行动消耗: '无' }))).toBe('无');
    expect(行动消耗文本(undefined)).toBe('');
  });
});

describe('2 · 它同时出现在两个下拉里，但只在这两个里', () => {
  const 单位 = 造单位({ id: '契约者', 阵营: '我方', 技能: { '八咫镜·光行': 光行() } });
  const 有 = (类型: '主要行动' | '次要行动' | '反应动作' | '免费行动') =>
    列行动选项(单位, 类型).some(o => o.技能 === '八咫镜·光行');

  it('次要行动 ✅ / 反应动作 ✅', () => {
    expect(有('次要行动')).toBe(true);
    expect(有('反应动作')).toBe(true);
  });

  it('主要行动 ❌ / 免费行动 ❌（没写的类型不许混进来）', () => {
    expect(有('主要行动')).toBe(false);
    expect(有('免费行动')).toBe(false);
  });
});

describe('3 · 结算：当次要行动放得出来，扣的是次要槽', () => {
  const 开 = () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 技能: { '八咫镜·光行': 光行() } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    return 开战规则结算(造状态(我, 敌));
  };

  it('次要行动 → 护盾 +50、次要槽 1 → 0', () => {
    const 状态 = 开();
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '次要行动', 技能: '八咫镜·光行', 目标: '契约者' }, 骰);

    expect(r.步骤.map(s => s.内容).join('\n')).not.toContain('跳过');
    expect(r.状态.单位.契约者.护盾).toBe(50);
    expect(r.状态.单位.契约者.行动槽.次要).toBe(0);
  });

  it('**声明成主要行动 → 拦下并说明**（槽位跟着行动类型走，不许白嫖）', () => {
    const 状态 = 开();
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '八咫镜·光行', 目标: '契约者' }, 骰);
    const 文本 = r.步骤.map(s => s.内容).join('\n');

    expect(文本).toContain('跳过');
    expect(文本).toContain('次要行动'); // 说明它到底能用在哪
    expect(r.状态.单位.契约者.护盾).toBe(0); // 没放出来
    expect(r.状态.单位.契约者.行动槽.主要).toBe(1); // 也没白扣主要槽
  });
});

describe('4 · 反应动作那一路也认得它（「必须自己学」的门禁照旧）', () => {
  const 守方 = (行动消耗: 战斗解释['行动消耗']) =>
    造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '八咫镜·光行',
      技能: { '八咫镜·光行': 光行(行动消耗) },
    });

  it('行动类型含「反应动作」→ 守方反应技能认得出', () => {
    expect(守方反应技能(守方(['次要行动', '反应动作']))?.名).toBe('八咫镜·光行');
  });

  it('只有「次要行动」的技能**不算**反应动作（学没过就不算）', () => {
    expect(守方反应技能(守方('次要行动'))).toBeUndefined();
  });
});

describe('5 · 显示：预览头部写全两个类型', () => {
  it('「次要行动 / 反应动作」，不是一个', () => {
    expect(效果预览(光行()).头部.join(' · ')).toContain('次要行动 / 反应动作');
  });
});

describe('6 · 翻译层：数组归一，老形状不动', () => {
  it('数组 → 原样收下；单元素数组 → 收回字符串', () => {
    expect(校验战斗解释({ 行动消耗: ['次要行动', '反应动作'], 规则: [] }).行动消耗).toEqual(['次要行动', '反应动作']);
    expect(校验战斗解释({ 行动消耗: ['次要行动'], 规则: [] }).行动消耗).toBe('次要行动');
  });

  it('写成「次要行动/反应动作」的串 → 归一成数组', () => {
    expect(校验战斗解释({ 行动消耗: '次要行动/反应动作', 规则: [] }).行动消耗).toEqual(['次要行动', '反应动作']);
  });

  it('**老形状一个字都不动**（单值字符串照旧，「无」也不会被改写）', () => {
    expect(校验战斗解释({ 行动消耗: '主要行动', 规则: [] }).行动消耗).toBe('主要行动');
    expect(校验战斗解释({ 类型: '主动', 行动消耗: '无', 规则: [] }).行动消耗).toBe('无');
  });

  it('没写行动类型 → 老口径（被动「无」/ 主动「免费行动」）', () => {
    expect(校验战斗解释({ 类型: '被动', 规则: [] }).行动消耗).toBe('无');
    expect(校验战斗解释({ 类型: '主动', 规则: [] }).行动消耗).toBe('免费行动');
  });
});

describe('7 · 提示词告诉模型可以多行动类型', () => {
  it('「行动消耗」那一栏写了允许数组 / 卡面「次要行动或反应动作」怎么写', async () => {
    const { 构建批量翻译提示词 } = await import('../ai/skillInterpreter');
    const 提示词 = 构建批量翻译提示词([]);

    expect(提示词).toContain('多个行动类型');
    expect(提示词).toContain('反应动作');
  });
});
