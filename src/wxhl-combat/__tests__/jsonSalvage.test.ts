import { describe, expect, it } from 'vitest';
import { 提取JSON, 提取JSON宽容 } from '../ai/jsonExtract';
import { 解析批量翻译结果 } from '../ai/skillInterpreter';

// ================================================================
// 玩家反馈：「用 ds（DeepSeek）来当 api 处理，经常报错说是非法 json 什么的，会不会太严苛？」
//
// 查下来：解析本身已经宽容（直 parse → ```json 围栏 → 括号配平），逐条校验也特意容忍缺失字段。
// **真正致命的只有一种：输出被截断**（模型 max_tokens 用尽，JSON 尾巴被切掉）——
// 括号永远等不到闭合，三级兜底全部失败 → 整批丢弃 → 再重试 3 次（又截断）→ 白烧时间。
//
// 修法：**从截断的 JSON 里抢救出已经完整的元素**。反正列表型结果（翻译/意图）
// 下游是逐条按编号对号入座的，捞回 N 条就赚 N 条，剩下那几条本来就有复核重试的出路。
// ================================================================

describe('截断 JSON 的抢救（DeepSeek 长输出被切尾巴）', () => {
  it('完整的 JSON → 照常解析，标记「未截断」', () => {
    const r = 提取JSON宽容('{"解释":[{"编号":0},{"编号":1}]}');

    expect(r.截断).toBe(false);
    expect(r.值.解释).toHaveLength(2);
  });

  it('**被截断的数组：捞出已经完整的元素**（这是玩家报的「非法 JSON」的真身）', () => {
    const 原文 = '{"解释":[{"编号":0,"行动消耗":"主要行动"},{"编号":1,"行动消耗":"次要行动"},{"编号":2,"行动';

    const r = 提取JSON宽容(原文);

    expect(r.截断).toBe(true);
    expect(r.值.解释.map((x: any) => x.编号)).toEqual([0, 1]); // 完整的两条保住了
  });

  it('截断点落在**嵌套结构内部**也认得（元素里还有规则数组）', () => {
    const 原文 =
      '{"解释":[{"编号":0,"规则":[{"触发":"常驻","作用域":"自身"}]},{"编号":1,"规则":[{"触发":"使用时"';

    const r = 提取JSON宽容(原文);

    expect(r.截断).toBe(true);
    expect(r.值.解释).toHaveLength(1);
    expect(r.值.解释[0].规则[0].触发).toBe('常驻'); // 嵌套内容完整保留
  });

  it('围栏里的截断 JSON 一样救得回来', () => {
    const 原文 = '```json\n{"解释":[{"编号":0},{"编号":1},{"编号":2\n```';

    const r = 提取JSON宽容(原文);

    expect(r.截断).toBe(true);
    expect(r.值.解释).toHaveLength(2);
  });

  it('一个完整元素都没有 → 不假装成功（照旧抛错，让上层重试/记失败）', () => {
    expect(() => 提取JSON宽容('{"解释":[{"编号":0,"行动')).toThrow();
    expect(() => 提取JSON('{"解释":[{"编号":0,"行')).toThrow(); // 兼容入口同样抛
  });

  it('字符串里带括号不影响抢救（扫描器认转义与串内）', () => {
    const 原文 = '{"解释":[{"说明":"他喊了一声{呀}"},{"编号":1,"说明":"下一';

    const r = 提取JSON宽容(原文);

    expect(r.截断).toBe(true);
    expect(r.值.解释).toHaveLength(1);
    expect(r.值.解释[0].说明).toBe('他喊了一声{呀}');
  });

  it('嵌套三层的元素也能整体保住', () => {
    const 原文 = '{"解释":[{"编号":0,"规则":[{"动作":[{"类":"护盾","量":{"源":"常数","系数":5}}]}]},{"编号":1';

    const r = 提取JSON宽容(原文);

    expect(r.截断).toBe(true);
    expect(r.值.解释).toHaveLength(1);
    expect(r.值.解释[0].规则[0].动作[0].量.系数).toBe(5);
  });

  it('兼容入口 提取JSON 对截断输入返回**抢救到的值**（而不是抛错）', () => {
    const 值 = 提取JSON('{"解释":[{"编号":0},{"编号":1},{"编号":2');

    expect(值.解释).toHaveLength(2);
  });
});

// ================================================================
// 端到端：截断的批量翻译结果 → **不再整批报废**，捞回多少算多少，
// 缺的条目按「模型未返回该条」进复核（复核本来就有一条一条重试的出路）。
// 这是玩家「用 ds 经常报非法 json」的直接解法：以前这里 JSON.parse 一炸，整批全丢。
// ================================================================
describe('截断的批量翻译结果（DeepSeek 场景的端到端）', () => {
  const 合法条目 = (编号: number) => ({
    编号,
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
  });

  it('3 条里只回了 2 条完整（第 3 条被切掉）→ 2 成功 + 1 失败，不抛错', () => {
    const 原文 =
      '{"解释":[' +
      JSON.stringify(合法条目(0)) +
      ',' +
      JSON.stringify(合法条目(1)) +
      ',{"编号":2,"行动消耗":"次要';

    const 结果 = 解析批量翻译结果(原文, 3);

    expect(结果[0].成功).toBe(true);
    expect(结果[1].成功).toBe(true);
    expect(结果[2]).toEqual({ 成功: false, 原因: '模型未返回该条（漏条目）' });
  });

  it('一条完整的都没回来 → 照旧抛错（不能假装成功）', () => {
    expect(() => 解析批量翻译结果('{"解释":[{"编号":0,"行动', 1)).toThrow();
  });
});
