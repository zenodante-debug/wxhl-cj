import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { 列行动选项, 可主动使用, 规范行动消耗, 冷却回合数 } from '../engine/actionOptions';
import type { 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 玩家反馈的三条（本轮）：
// A「装备的效果，有的是能够主动触发的，但是没有行动类型。主动的效果也要能够算作行动选项吧？
//    或者算作免费行动」+「默认免费行动，冷却默认一个回合」
// B「次要行动应该具有副武器攻击的选项。如果没有武器，就不能攻击」
//    → 最终裁决：「没武器就放技能或者徒手攻击嘛，怎么都行」= 不做门禁、标签诚实
// F「反应动作不应该是有预设的那些反应动作，必须是技能的类型是反应动作才算上」
//
// 「行动类型」= 翻译结果里 `行动消耗` 那个字段（主要/次要/反应动作/免费/无）——
// 字段名是历史遗留，**不是**资源消耗 `消耗`（MP/耐力）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 16, PER: 10 } },
    阶位: '一阶',
    HP_当前: 200,
    HP_最大: 200,
    MP_当前: 30,
    MP_最大: 30,
    耐力_当前: 50,
    耐力_最大: 50,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

describe('A · 行动类型归一化（装备的主动效果进得来）', () => {
  it('装备主动效果（类型 主动 + 行动消耗写「无」）→ 归成**免费行动**', () => {
    const 装备效果 = 造解释({ 类型: '主动', 行动消耗: '无', 伤害倍率: 0 });

    expect(规范行动消耗(装备效果)).toBe('免费行动');
    expect(可主动使用(装备效果)).toBe(true);
  });

  it('装备主动效果**真的出现在免费行动列表里**（这是玩家最初的问题）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 空间宝石: 造解释({ 类型: '主动', 行动消耗: '无', 伤害倍率: 0 }) } });

    const 免费 = 列行动选项(甲, '免费行动');

    expect(免费.map(o => o.技能)).toContain('空间宝石');
  });

  it('**被动/光环仍然是「不是行动」**（数值照旧由常驻修正直接算）', () => {
    expect(规范行动消耗(造解释({ 类型: '被动', 行动消耗: '无' }))).toBeNull();
    expect(规范行动消耗(造解释({ 类型: '光环', 行动消耗: '无' }))).toBeNull();
    expect(规范行动消耗(造解释({ 类型: '制造系', 行动消耗: '无' }))).toBeNull();
  });

  it('写了行动类型的照写（主动技能不会因为兜底被塞进免费行动）', () => {
    expect(规范行动消耗(造解释({ 类型: '主动', 行动消耗: '主要行动' }))).toBe('主要行动');
    expect(规范行动消耗(造解释({ 类型: '主动', 行动消耗: '次要行动' }))).toBe('次要行动');
    expect(规范行动消耗(造解释({ 类型: '主动', 行动消耗: '免费行动' }))).toBe('免费行动');
    expect(规范行动消耗(造解释({ 类型: '主动', 行动消耗: '反应动作' }))).toBe('反应动作');
  });

  it('类型和行动类型**都缺** → 认不出来，不进任何列表（宁可不显示，也不乱塞）', () => {
    expect(规范行动消耗(造解释({ 类型: '' as any, 行动消耗: '无' }))).toBeNull();
    expect(规范行动消耗(undefined)).toBeNull();
  });

  it('免费行动**冷却默认 1 回合**（玩家口径：没写就默认一回合）', () => {
    expect(冷却回合数(造解释({ 类型: '主动', 行动消耗: '无', 冷却: undefined }))).toBe(1);
    expect(冷却回合数(造解释({ 冷却: 0 }))).toBe(1);
    expect(冷却回合数(造解释({ 冷却: 3 }))).toBe(3);
  });
});

describe('F · 反应动作只认「行动类型 = 反应动作」的已学技能', () => {
  it('反应列表只列行动类型为反应动作的技能', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: {
        招架: 造解释({ 类型: '主动', 行动消耗: '反应动作', 伤害倍率: 0 }),
        斩击: 造解释({ 类型: '主动', 行动消耗: '主要行动' }),
      },
    });

    const 反应 = 列行动选项(甲, '反应动作');

    expect(反应.map(o => o.技能)).toEqual(['招架']);
  });

  it('**没学过就没有**：技能表空 → 反应列表是空的（不再有预设的击溃/识破/招架…）', () => {
    expect(列行动选项(造单位({ id: '契约者', 阵营: '我方' }), '反应动作')).toEqual([]);
  });

  it('被动技能即使名字像反应（"识破"）也不算 —— 判定只看行动类型', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 识破: 造解释({ 类型: '被动', 行动消耗: '无', 伤害倍率: 0 }) } });

    expect(列行动选项(甲, '反应动作')).toEqual([]);
  });
});

describe('B · 基础攻击标签诚实（没武器就说徒手）', () => {
  const 武器 = { 伤害骰: '2d6', 倍率: 1, 强化等级: 0 };

  it('主要行动：有主武器 → 主武器攻击；没有 → 徒手攻击', () => {
    const 有 = 列行动选项(造单位({ id: '契约者', 阵营: '我方', 主武器: 武器 }), '主要行动');
    const 无 = 列行动选项(造单位({ id: '契约者', 阵营: '我方' }), '主要行动');

    expect(有.at(-1)!.标签).toContain('主武器攻击');
    expect(无.at(-1)!.标签).toContain('徒手攻击');
    expect(无.at(-1)!.标签).toContain('1d4');
  });

  it('次要行动：有副武器 → 副武器攻击；没有 → 徒手攻击（也能打）', () => {
    const 有 = 列行动选项(造单位({ id: '契约者', 阵营: '我方', 副武器: 武器 }), '次要行动');
    const 无 = 列行动选项(造单位({ id: '契约者', 阵营: '我方' }), '次要行动');

    expect(有.at(-1)!.标签).toContain('副武器攻击');
    expect(无.at(-1)!.标签).toContain('徒手攻击');
  });

  it('基础攻击仍然排在**最后一条**（技能在前，界面顺序稳定）', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 主武器: 武器, 技能: { 斩击: 造解释({ 行动消耗: '主要行动' }) } });

    const 选项 = 列行动选项(甲, '主要行动');

    expect(选项.at(-1)!.技能).toBeUndefined(); // 最后一条是基础攻击（无技能名）
    expect(选项[0].技能).toBe('斩击');
  });

  it('免费行动不给基础攻击（免费行动只有技能）', () => {
    expect(列行动选项(造单位({ id: '契约者', 阵营: '我方', 主武器: 武器 }), '免费行动')).toEqual([]);
  });
});

describe('UI 源码守卫 · 预设反应列表必须消失', () => {
  const 源码 = fs.readFileSync(path.resolve(import.meta.dirname, '../views/BattleView.vue'), 'utf8');

  it('BattleView 里不再有硬编码的反应名数组，也不再有绑定它的下拉', () => {
    // 旧写法：`const 反应选项 = ['击溃', '识破', …]` + `<option v-for="r in 反应选项">`
    // （注释里提这些名字是允许的 —— 守卫盯的是**代码写法**，不是历史说明）
    expect(源码).not.toMatch(/const\s+反应选项\s*=\s*\[/);
    expect(源码).not.toMatch(/v-for="r in 反应选项"/);
  });

  it('反应下拉改为走引擎的 `列行动选项(…, 反应动作)`（只列学过的）', () => {
    expect(源码).toContain("列行动选项(u, '反应动作')");
    expect(源码).toContain('反应选项(u)');
  });
});
