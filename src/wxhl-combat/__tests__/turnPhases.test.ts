import { describe, expect, it } from 'vitest';
import { 阶段F结算, 阶段A资源恢复, 判定转阶段, 濒死判定 } from '../engine/turn';
import type { 战斗单位, 状态条目 } from '../types';

function 造单位(覆盖: Partial<战斗单位> = {}): 战斗单位 {
  return {
    id: '玩家',
    阵营: '我方',
    类型: '玩家',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 270,
    HP_最大: 270,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 10,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 0,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

describe('turn · 阶段F 回合结束', () => {
  it('持续伤害按最大HP结算（流血 4%）', () => {
    const 单位 = 造单位({ 状态: [{ 名: '流血', 持续: 2 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.HP扣减).toBe(Math.floor(270 * 0.04));
  });

  it('多个持续状态扣减累加（灼烧5% + 流血4%）', () => {
    // 基数取 270：逐状态取整 = 13+10 = 23，而先合并再取整 floor(270×0.09) = 24 —— 能区分「逐状态取整」
    const 单位 = 造单位({ 状态: [{ 名: '灼烧', 持续: 2 }, { 名: '流血', 持续: 2 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.HP扣减).toBe(Math.floor(270 * 0.05) + Math.floor(270 * 0.04));
    expect(结果.HP扣减).toBe(23);
  });

  it('持续伤害按层数放大（3 层灼烧 = 3×5%）', () => {
    const 单位 = 造单位({ 状态: [{ 名: '灼烧', 持续: 3, 层数: 3 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.HP扣减).toBe(Math.floor(270 * 0.05 * 3)); // = 40；单层只有 13
    expect(结果.HP扣减).toBe(40);
  });

  it('扣减落到新状态的 HP_当前 上，且不会低于 0', () => {
    const 单位 = 造单位({ HP_当前: 3, 状态: [{ 名: '流血', 持续: 2 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.新状态.HP_当前).toBe(0);
  });

  it('无持续伤害状态 → 不扣 HP', () => {
    const 单位 = 造单位({ 状态: [{ 名: '守护', 持续: 2 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.HP扣减).toBe(0);
  });

  it('新状态里每个状态持续回合 -1', () => {
    const 单位 = 造单位({ 状态: [{ 名: '流血', 持续: 2 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.新状态.状态).toEqual([{ 名: '流血', 持续: 1 }]);
  });

  it('到期的状态被清除（持续 1 → 移除）', () => {
    const 单位 = 造单位({ 状态: [{ 名: '流血', 持续: 1 }, { 名: '灼烧', 持续: 3 }] });
    const 结果 = 阶段F结算(单位, 270);
    expect(结果.新状态.状态).toEqual([{ 名: '灼烧', 持续: 2 }]);
  });

  it('不修改原单位（纯函数）', () => {
    const 原状态: 状态条目[] = [{ 名: '流血', 持续: 2 }];
    const 单位 = 造单位({ HP_当前: 270, 状态: 原状态 });
    const 结果 = 阶段F结算(单位, 270);
    expect(单位.HP_当前).toBe(270);
    expect(原状态[0].持续).toBe(2);
    expect(结果.新状态).not.toBe(单位);
  });
});

describe('turn · 阶段A 回合开始 · 资源恢复', () => {
  it('耐力 +CON修正，MP +PER修正×0.5 向上取整', () => {
    // 二阶 CON=15 → CON修正=(15-5)×2=20；PER=14 → PER修正=(14-5)×2=18 → MP恢复=ceil(9)=9
    const 单位 = 造单位({
      阶位: '二阶',
      属性: { 实际: { STR: 10, AGI: 10, CON: 15, PER: 14 } },
      耐力_当前: 100,
      耐力_最大: 100,
      MP_当前: 50,
      MP_最大: 50,
    });
    const 新 = 阶段A资源恢复(单位);
    expect(新.耐力_当前).toBe(100); // 100 + 20 封顶到 100
    expect(新.MP_当前).toBe(50);    // 50 + 9 封顶到 50
  });

  it('未封顶时按公式增长', () => {
    const 单位 = 造单位({
      阶位: '一阶',
      属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
      耐力_当前: 50,
      耐力_最大: 200,
      MP_当前: 10,
      MP_最大: 200,
    });
    // 一阶 CON=10 → 修正 5；PER=10 → 修正 5 → MP恢复=ceil(2.5)=3
    const 新 = 阶段A资源恢复(单位);
    expect(新.耐力_当前).toBe(55);
    expect(新.MP_当前).toBe(13);
  });

  it('MP 修正×0.5 向上取整（PER=6 → 修正 1 → ceil(0.5)=1）', () => {
    const 单位 = 造单位({
      阶位: '一阶',
      属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 6 } },
      MP_当前: 0,
      MP_最大: 200,
    });
    const 新 = 阶段A资源恢复(单位);
    expect(新.MP_当前).toBe(1);
  });

  it('不修改原单位（纯函数）', () => {
    const 单位 = 造单位({ 耐力_当前: 50, 耐力_最大: 200 });
    const 新 = 阶段A资源恢复(单位);
    expect(单位.耐力_当前).toBe(50);
    expect(新).not.toBe(单位);
  });

  it('负修正（CON/PER<5）不扣耐力/MP —— 恢复下限 0', () => {
    const 单位 = 造单位({
      阶位: '一阶',
      属性: { 实际: { STR: 10, AGI: 10, CON: 1, PER: 1 } }, // 修正 = (1-5)×1 = -4
      耐力_当前: 50,
      耐力_最大: 200,
      MP_当前: 10,
      MP_最大: 200,
    });
    const 新 = 阶段A资源恢复(单位);
    expect(新.耐力_当前).toBe(50);
    expect(新.MP_当前).toBe(10);
  });
});

describe('turn · 阶段D 转阶段', () => {
  it('BOSS 首次跌破 70% → 返回转阶段（带阈值）', () => {
    // 形状从 `待决点` 改成 `{ 阈值 }`：转阶段已经**接进伤害结算**（当场跑它的「转阶段」规则），
    // 不再是一个没人消费的待决点（那个旧形状正是"声明了却没人读"）。
    const 单位 = 造单位({ id: '副本角色.骨王', 类型: 'BOSS', HP_最大: 1000, HP_当前: 690 });
    const 待决 = 判定转阶段(单位, 720, 690);
    expect(待决).toEqual({ 阈值: '70%' });
  });

  it('**被打到 0 → 返回「濒死」阈值**（玩家口径：boss 濒死了回满血）', () => {
    const 单位 = 造单位({ id: '副本角色.骨王', 类型: 'BOSS', HP_最大: 1000, HP_当前: 0 });
    expect(判定转阶段(单位, 120, 0)).toEqual({ 阈值: '濒死' });
  });

  it('未跌破阈值 → 不触发', () => {
    const 单位 = 造单位({ 类型: 'BOSS', HP_最大: 1000, HP_当前: 850 });
    expect(判定转阶段(单位, 900, 850)).toBe(null);
  });

  it('跨过阈值后再次判定 → 不重复触发（变化前已在阈值下）', () => {
    const 单位 = 造单位({ 类型: 'BOSS', HP_最大: 1000, HP_当前: 600 });
    expect(判定转阶段(单位, 680, 600)).toBe(null);
  });

  it('非 BOSS/隐藏BOSS → 永不触发', () => {
    const 单位 = 造单位({ 类型: '精英', HP_最大: 1000, HP_当前: 100 });
    expect(判定转阶段(单位, 300, 100)).toBe(null);
  });

  it('隐藏BOSS 同样触发', () => {
    const 单位 = 造单位({ id: '副本角色.影', 类型: '隐藏BOSS', HP_最大: 1000, HP_当前: 390 });
    expect(判定转阶段(单位, 410, 390)).toEqual({ 阈值: '40%' });
  });

  it('单次伤害跨多条阈值 → 返回最深那条（75%→15% 得 20%，裁决 R13a-3）', () => {
    const 单位 = 造单位({ id: '副本角色.骨王', 类型: 'BOSS', HP_最大: 1000, HP_当前: 150 });
    expect(判定转阶段(单位, 750, 150)).toEqual({ 阈值: '20%' });
  });
});

describe('turn · 濒死判定', () => {
  it('CON检定成功（1d20 + CON修正 ≥ 12）→ 成功 +1', () => {
    // 一阶 CON=10 → 修正 5；掷 10 → 15 ≥ 12 成功
    const 单位 = 造单位({ HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } });
    const { 单位: 新, 结果 } = 濒死判定(单位, 10);
    expect(结果).toBe('濒死');
    expect(新.濒死).toEqual({ 成功: 1, 失败: 0 });
  });

  it('CON检定失败（掷 1 → 6 < 12）→ 失败 +1', () => {
    const 单位 = 造单位({ HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } });
    const { 单位: 新, 结果 } = 濒死判定(单位, 1);
    expect(结果).toBe('濒死');
    expect(新.濒死).toEqual({ 成功: 0, 失败: 1 });
  });

  it('2 次成功 → 稳定（濒死清空）', () => {
    const 单位 = 造单位({ HP_当前: 0, 濒死: { 成功: 1, 失败: 0 } });
    const { 单位: 新, 结果 } = 濒死判定(单位, 20);
    expect(结果).toBe('稳定');
    expect(新.濒死).toBe(null);
  });

  it('3 次失败 → 死亡', () => {
    const 单位 = 造单位({ HP_当前: 0, 濒死: { 成功: 0, 失败: 2 } });
    const { 结果 } = 濒死判定(单位, 1);
    expect(结果).toBe('死亡');
  });

  it('首次进入濒死（濒死为 null）也能判定', () => {
    const 单位 = 造单位({ HP_当前: 0 });
    const { 单位: 新, 结果 } = 濒死判定(单位, 20);
    expect(结果).toBe('濒死');
    expect(新.濒死).toEqual({ 成功: 1, 失败: 0 });
  });
});
