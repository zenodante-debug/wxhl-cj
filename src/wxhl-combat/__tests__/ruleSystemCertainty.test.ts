import { describe, expect, it } from 'vitest';
import { 归一规则系效果 } from '../engine/ruleShape';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 构建批量翻译提示词 } from '../ai/skillInterpreter';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家口径（2026-10-10）：「"必定暴击"只是个例子，实际情况还会有很多不同类型，
//   比如必定"锁定"，必定斩杀什么的，凡是涉及"必定"，都是规则系 ——
//   做一个拆分吧，把必定和暴击/命中，什么的拆分开来，做组合。」
//
// 现状：引擎里**没有**"必定暴击 → 必暴"的归一化 —— `收集规则系` 读的是原样字符串，
// 防火墙只认 `引擎认得的规则系效果`（必暴/必中/即死…）。模型写「必定暴击」→ 认不得 →
// 判定照掷、过了交给叙事（不机械执行）→ **暴击没生效**。
//
// 修法：拆掉「必定/必然/强制/绝对」这类**前缀**，再按同义词表归一到引擎认得的名字；
// 认不出来的**原样返回**（规则系是开放集合，不能丢）。
// ================================================================

describe('1 · 「必定X」拆开再归一（必定是前缀，不是效果名的一部分）', () => {
  it('必定暴击 / 必定命中 / 必定斩杀 → 必暴 / 必中 / 即死', () => {
    expect(归一规则系效果('必定暴击')).toBe('必暴');
    expect(归一规则系效果('必然暴击')).toBe('必暴');
    expect(归一规则系效果('强制暴击')).toBe('必暴');
    expect(归一规则系效果('必定命中')).toBe('必中');
    expect(归一规则系效果('绝对命中')).toBe('必中');
    expect(归一规则系效果('必定斩杀')).toBe('即死');
    expect(归一规则系效果('必定秒杀')).toBe('即死');
  });

  it('已经是对的名字 → 原样不动', () => {
    for (const 名 of ['必暴', '必中', '即死', '穿透', '无敌', '免疫', '锁血', '无视']) {
      expect(归一规则系效果(名)).toBe(名);
    }
  });

  it('**认不出来的一律原样返回**（规则系是开放集合，不能丢）', () => {
    expect(归一规则系效果('必定锁定')).toBe('必定锁定');
    expect(归一规则系效果('因果抹杀')).toBe('因果抹杀');
    expect(归一规则系效果('')).toBe('');
  });

  it('穿透/无敌 这类也认同义写法', () => {
    expect(归一规则系效果('必定穿透')).toBe('穿透');
    expect(归一规则系效果('无视防御')).toBe('穿透');
    expect(归一规则系效果('必定无敌')).toBe('无敌');
  });
});

// ================================================================
// 端到端：卡面写「必定暴击」→ 打出去**真的必暴**（不是交给叙事）
// ================================================================
function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

describe('2 · 端到端：「必定暴击」真的必暴', () => {
  const 打 = (效果: string) => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      // STR 200（一阶修正 195）—— 规则系判定 = 1d20 + 195，稳过一阶杂兵的对抗目标
      //（世界书的 DC 很硬：一阶基础DC 35 × 杂兵系数 0.6 + 目标修正，小身板过不去）
      属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } },
      技能: {
        斩: {
          行动消耗: '主要行动',
          射程: '近战',
          目标: '单体',
          消耗: '无',
          冷却: 1,
          分类: '基础',
          类型: '主动',
          可预判: true,
          关联属性: 'STR',
          技能阶位: 1,
          伤害倍率: 1,
          规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '规则系判定', 效果, 目标: '攻击目标' }] } as 规则],
          托管: [],
        } as 战斗解释,
      },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 10000, HP_最大: 10000 });
    const 状态 = 开战规则结算({ 进行中: true, 回合: 1, 先攻: [我.id, 敌.id], 单位: { 契约者: 我, 骨卫兵: 敌 }, 待决: null, 领域: [] } as 战斗状态);
    // 命中骰 1（**绝不会自然暴击**）—— 只有"必暴"生效才会暴击
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩', 目标: '骨卫兵' }, { 命中: 1, 伤害骰: [6] });
    return r.步骤.map(s => s.内容).join('\n');
  };

  it('写「必定暴击」→ 战报里出「自然暴击」（暴击倍率 1.5 生效）', () => {
    expect(打('必定暴击')).toContain('自然暴击');
  });

  it('写「必暴」（规范名）→ 同样生效', () => {
    expect(打('必暴')).toContain('自然暴击');
  });

  it('不写规则系 → 命中骰 1 不会暴击（对照组）', () => {
    expect(打('随便什么不相关的能力')).not.toContain('自然暴击');
  });

  // 2026-10-10 顺手修：`落效果` 对 `规则系判定` 会打一行
  // 「只在这三个触发点判定，本次挂在别的触发点上 → 未生效」—— 在**攻击路径**上是**假话**
  // （这条规则明明就挂在使用时，防火墙也真的判定过了，旁边另有一行真话）。
  it('攻击路径上**不再**打那行「挂在别的触发点上 → 未生效」的假话', () => {
    const 文本 = 打('必暴');

    expect(文本).not.toContain('挂在别的触发点上');
    expect(文本).toContain('规则系「必暴」'); // 防火墙那行真话还在
  });
  it('**没被防火墙接管的触发点**照旧留痕（回归：别把留痕一起删了）', () => {
    const 文本 = 打('随便什么不相关的能力');
    // 这条走的是「规则系判定 + 认不出的效果 + 使用时」→ 攻击路径，所以也不该有假话；
    // 但"防火墙判定过"那行必须在（证明规则真的被处理了）
    expect(文本).toContain('对抗目标');
  });
});

describe('3 · 提示词教「必定X → 写 X 的规范名」', () => {
  const 提示词 = 构建批量翻译提示词([]);

  it('点了「必定」是前缀，效果要写规范名', () => {
    expect(提示词).toContain('必定');
    expect(提示词).toContain('必暴');
  });
});
