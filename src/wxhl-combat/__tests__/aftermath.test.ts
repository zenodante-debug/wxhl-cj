import { describe, expect, it } from 'vitest';
import { 构建收尾提示词, 击杀明细, 钥匙档位 } from '../ai/aftermath';
import type { 结算步骤, 战斗状态, 战斗单位 } from '../types';

const 步骤列表: 结算步骤[] = [
  { 类: '攻击', 内容: '玩家命中敌人，造成 16 点伤害', 单位: '玩家' },
  { 类: '击杀', 内容: '敌人被击杀', 单位: '敌人' },
];

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 0,
    MP_最大: 0,
    耐力_当前: 0,
    耐力_最大: 0,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 0,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(): 战斗状态 {
  return {
    进行中: false,
    回合: 5,
    先攻: ['契约者', '副本角色.骨卫兵', '副本角色.骨刃领主', '副本角色.隐形刺客'],
    单位: {
      契约者: 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 名称: '青空黎' }),
      骨卫兵: 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', HP_当前: 0 }),
      骨刃领主: 造单位({ id: '副本角色.骨刃领主', 阵营: '敌方', 类型: 'BOSS', HP_当前: 0 }),
      隐形刺客: 造单位({ id: '副本角色.隐形刺客', 阵营: '敌方', 类型: '精英', HP_当前: 37 }), // 还活着 → 不发钥匙
    },
    待决: null,
    领域: [],
  };
}

describe('aftermath · 收尾正文', () => {
  it('构建收尾提示词：包含战报', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('玩家命中敌人');
    expect(提示词).toContain('敌人被击杀');
  });

  it('按击杀发放钥匙（杂兵白/BOSS黄金/精英白银），活着的敌人不发', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('骨卫兵（杂兵）→ 获得 白色钥匙');
    expect(提示词).toContain('骨刃领主（BOSS）→ 获得 黄金钥匙');
    expect(提示词).not.toContain('隐形刺客（精英）→ 获得 白银钥匙');
  });

  it('主角用真名（头部.姓名），不是「契约者」', () => {
    expect(构建收尾提示词(步骤列表, 造状态())).toContain('「青空黎」');
  });

  it('没有击杀 → 明说没有掉落', () => {
    const 状态 = 造状态();
    状态.单位.骨卫兵.HP_当前 = 50;
    状态.单位.骨刃领主.HP_当前 = 80;

    expect(构建收尾提示词(步骤列表, 状态)).toContain('没有掉落钥匙');
  });
});

describe('钥匙档位（卡片 schema 的 类型 决定）', () => {
  const 档位 = (id: string, 类型: string) => 钥匙档位(造单位({ id, 阵营: '敌方', 类型 }));

  it('杂兵 → 白色钥匙；精英 → 白银钥匙；BOSS → 黄金钥匙；隐藏BOSS → 钻石钥匙', () => {
    expect(档位('副本角色.甲', '杂兵')).toBe('白色钥匙');
    expect(档位('副本角色.乙', '精英')).toBe('白银钥匙');
    expect(档位('副本角色.丙', 'BOSS')).toBe('黄金钥匙');
    expect(档位('副本角色.丁', '隐藏BOSS')).toBe('钻石钥匙');
  });

  it('隐藏BOSS 先判（它自己也含 BOSS）', () => {
    expect(档位('副本角色.丁', '隐藏BOSS（固有角色）')).toBe('钻石钥匙');
  });

  it('其他契约者 → 血腥钥匙', () => {
    expect(档位('其他契约者.琳琅', '杂兵')).toBe('血腥钥匙');
    expect(档位('副本角色.甲', '其他契约者')).toBe('血腥钥匙');
  });

  it('未标注类型 → 按杂兵（白色钥匙）兜底', () => {
    expect(档位('副本角色.甲', '')).toBe('白色钥匙');
  });
});

describe('击杀明细', () => {
  it('只列 HP 归零的敌方，并带上钥匙', () => {
    const 明细 = 击杀明细(造状态());

    expect(明细).toHaveLength(2);
    expect(明细.map(x => x.钥匙)).toEqual(['白色钥匙', '黄金钥匙']);
  });
});

describe('收尾提示词 · 玩家要的"完整战斗全过程"（不限字数 / 电影感 / 客观旁白）', () => {
  it('明写**篇幅不限**、要写完整过程（不再是 200~400 字的收尾）', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('完整的战斗全过程');
    expect(提示词).toContain('篇幅不限');
    expect(提示词).not.toContain('200~400字');
  });

  it('要求电影感 / 画面感，且技能效果用**客观旁白**交代', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('电影感');
    expect(提示词).toContain('客观旁白');
    expect(提示词).toContain('做了什么、产生了什么结果');
  });

  it('把战报标为**唯一事实来源**，并列出要落地的交锋细节（命中/暴击/护盾/冷却/濒死）', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('唯一的事实来源');
    for (const 点 of ['命中', '暴击', '护盾', '冷却', '濒死']) expect(提示词).toContain(点);
    expect(提示词).toContain('不要自己加战报里没有的');
  });

  it('保留冷峻白描风格与钥匙掉落结算', () => {
    const 提示词 = 构建收尾提示词(步骤列表, 造状态());

    expect(提示词).toContain('客观冷静');
    expect(提示词).toContain('获得了哪些钥匙');
    expect(提示词).toContain('白色钥匙');
  });

  it('战报过长 → 掐中间并明确标注（不把提示词撑爆）', () => {
    const 超长: 结算步骤[] = Array.from({ length: 4000 }, (_, i) => ({ 类: '日志', 内容: `第 ${i} 条：${'很长的战报内容'.repeat(3)}` }));
    const 提示词 = 构建收尾提示词(超长, 造状态());

    expect(提示词).toContain('中间省略');
    expect(提示词.length).toBeLessThan(200000);
  });
});
