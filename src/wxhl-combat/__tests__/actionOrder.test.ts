import { describe, expect, it } from 'vitest';
import { 构造行动声明, 可提交, 列行动条目 } from '../engine/actionInput';

// ================================================================
// 玩家反馈：「个人回合内行动的顺序要能够自己设定，比如我次要行动和免费行动都是上 buff，
// 那总不能等我主要行动的大招放完了再上个寂寞吧？」
//
// 引擎侧本来就**按给定数组顺序**逐个结算（`跑一个回合` 里 `for (const 行动 of 本行动)`），
// 所以这里只需要让 `构造行动声明` 尊重玩家给的顺序。
//
// 顺序键的写法：'主要' / '次要' / '移动' / `免费:<技能名>`。
// **省略 `行动顺序` 时保持历史固定顺序**（主要 → 次要 → 免费 → 移动）—— 旧调用与旧测试零改动。
// ================================================================

const 技能名 = (r: ReturnType<typeof 构造行动声明>) =>
  r.行动.filter(a => a.类型 !== '移动').map(a => a.技能);

describe('回合内行动顺序（玩家自定）', () => {
  it('没给顺序 → 保持历史固定顺序（主要 → 次要 → 免费 → 移动）', () => {
    const r = 构造行动声明(
      { 主要: '大招', 次要: '上buff', 免费: ['喊话'], 移动: 10 },
      '骨卫兵',
    );

    expect(技能名(r)).toEqual(['大招', '上buff', '喊话']);
    expect(r.行动.at(-1)).toEqual({ 类型: '移动', 距离: 10 });
  });

  it('**给了顺序 → 严格照顺序产出**（buff 先上，大招后放）', () => {
    const r = 构造行动声明(
      { 主要: '大招', 次要: '上buff', 行动顺序: ['次要', '主要'] },
      '骨卫兵',
    );

    expect(技能名(r)).toEqual(['上buff', '大招']);
  });

  it('免费行动能插到主要行动**前面**（这是玩家举的例子）', () => {
    const r = 构造行动声明(
      { 主要: '大招', 免费: ['战吼'], 行动顺序: ['免费:战吼', '主要'] },
      '骨卫兵',
    );

    expect(技能名(r)).toEqual(['战吼', '大招']);
  });

  it('移动也能排进顺序里（走位在攻击前后是两回事）', () => {
    const r = 构造行动声明(
      { 主要: '大招', 移动: 15, 行动顺序: ['移动', '主要'] },
      '骨卫兵',
    );

    expect(r.行动[0]).toEqual({ 类型: '移动', 距离: 15 });
    expect(r.行动[1].技能).toBe('大招');
  });

  it('顺序里提到、但玩家没填的槽 → 忽略（不会凭空放一个空行动）', () => {
    const r = 构造行动声明({ 主要: '大招', 行动顺序: ['次要', '主要', '移动'] }, '骨卫兵');

    expect(技能名(r)).toEqual(['大招']);
    expect(r.行动).toHaveLength(1);
  });

  it('顺序里**漏掉**的行动照样结算，只是排到最后（不能因为没排序就丢行动）', () => {
    const r = 构造行动声明(
      { 主要: '大招', 次要: '上buff', 行动顺序: ['次要'] },
      '骨卫兵',
    );

    expect(技能名(r)).toEqual(['上buff', '大招']);
  });

  it('重复的免费行动（同一个技能放两次）不互相吞掉', () => {
    const r = 构造行动声明({ 免费: ['战吼', '战吼'] }, '骨卫兵');

    expect(技能名(r)).toEqual(['战吼', '战吼']);
  });

  it('顺序不影响「算不算出手」（可提交）', () => {
    expect(可提交({ 主要: '大招', 行动顺序: ['主要'] })).toBe(true);
    expect(可提交({ 行动顺序: ['主要'] })).toBe(false); // 顺序里写了但槽是空的 → 没出手
  });
});

describe('顺序表的唯一来源：列行动条目（界面与引擎读同一份）', () => {
  it('给出键与显示行，界面的 ↑↓ 直接引用它们', () => {
    const 条目 = 列行动条目({ 主要: '大招', 次要: '上buff', 免费: ['战吼'], 移动: 10 }, '骨卫兵');

    expect(条目.map(x => x.键)).toEqual(['主要', '次要', '免费:战吼', '移动']);
    expect(条目.map(x => x.显示)).toEqual(['主要：大招', '次要：上buff', '免费：战吼', '移动 10 米']);
  });

  it('同名免费行动第二次的键带 #2（界面上也照这个键引用，两边不会走偏）', () => {
    const 条目 = 列行动条目({ 免费: ['战吼', '战吼'] }, '骨卫兵');

    expect(条目.map(x => x.键)).toEqual(['免费:战吼', '免费:战吼#2']);
  });

  it('空填写 → 空列表（不会给出幽灵条目）', () => {
    expect(列行动条目({}, '骨卫兵')).toEqual([]);
    expect(列行动条目({ 主要: '   ' }, '骨卫兵')).toEqual([]);
  });
});
