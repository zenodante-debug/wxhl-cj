// ================================================================
// 玩家追加需求（2026-10-09，第四次）：
//   「还有能力与能力之间的连携，比如，一个技能是取消一个可选技能的冷却，这种也目前实现不了」
//   「冷却连携只是一个例子，还可能有伤害连携、什么乱七八糟的联动」
//   → 所以做的不是"一个清冷却的动作"，而是**技能级作用的动作族**（§5.4）。
//
// 动作：{"类":"技能作用","操作":"清冷却|减冷却|重置次数|加次数|挂词条|移除词条|技能加成",
//        "名":"选中技能|当前技能|全部|<具体技能名>", "量":…, "目标":…, "词条":"…"}
// 条件：{"源":"技能词条","名":"强化"} —— 读**正在释放的那个技能**身上的词条。
// 认不得的 `操作` → 记日志跳过（不静默）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '免费行动',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 一条「使用时 · 作用域自身」的规则，动作随用例给 */
const 用自身 = (动作: 动作 | 动作[]): 规则 => ({
  触发: '使用时',
  作用域: '自身',
  动作: Array.isArray(动作) ? 动作 : [动作],
});

/** 释放一个自身指向的技能，返回结算后的单位与日志 */
function 放(技能表: Record<string, 战斗解释>, 技能名: string, 单位覆盖: Partial<战斗单位> = {}) {
  const 我 = 造单位({ id: '契约者', 阵营: '我方', 技能: 技能表, ...单位覆盖 });
  const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
  const 状态 = 开战规则结算(造状态(我, 敌));

  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: 技能名, 目标: '契约者' }, 骰);
  return { 我: r.状态.单位.契约者, 文本: r.步骤.map(s => s.内容).join('\n') };
}

describe('1 · 冷却连携（玩家举的那个例子）', () => {
  const 技能表 = (操作: 动作) => ({
    斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 冷却: 3 }),
    净火: 造解释({ 规则: [用自身(操作)] }),
  });

  it('清冷却：把另一条技能的剩余冷却直接抹掉', () => {
    const { 我, 文本 } = 放(技能表({ 类: '技能作用', 操作: '清冷却', 名: '斩击' }), '净火', {
      冷却: { 斩击: 3 },
    });

    expect(我.冷却['斩击']).toBe(0);
    expect(文本).toContain('斩击');
  });

  it('减冷却：冷却缩短 2 回合（减到 0 就停在 0）', () => {
    expect(放(技能表({ 类: '技能作用', 操作: '减冷却', 名: '斩击', 量: { 源: '常数', 系数: 2 } }), '净火', {
      冷却: { 斩击: 3 },
    }).我.冷却['斩击']).toBe(1);

    expect(放(技能表({ 类: '技能作用', 操作: '减冷却', 名: '斩击', 量: { 源: '常数', 系数: 9 } }), '净火', {
      冷却: { 斩击: 3 },
    }).我.冷却['斩击']).toBe(0);
  });

  it('名写「全部」→ 该单位所有技能一起清', () => {
    const { 我 } = 放(
      {
        斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 冷却: 3 }),
        格挡: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 冷却: 2 }),
        净火: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '清冷却', 名: '全部' })] }),
      },
      '净火',
      { 冷却: { 斩击: 3, 格挡: 2 } },
    );

    expect(我.冷却['斩击']).toBe(0);
    expect(我.冷却['格挡']).toBe(0);
  });

  it('名写「选中技能」→ 作用于**本次释放选中的那一条**（§5.4「选择目标技能」）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      冷却: { 斩击: 3, 格挡: 2 },
      技能: {
        斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 冷却: 3 }),
        格挡: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 冷却: 2 }),
        时之楔: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '清冷却', 名: '选中技能' })] }),
      },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 结算行动(
      状态,
      状态.单位.契约者,
      { 类型: '免费行动', 技能: '时之楔', 目标: '契约者', 选择技能: '格挡' },
      骰,
    );

    expect(r.状态.单位.契约者.冷却['格挡']).toBe(0); // 选中的那条被清
    expect(r.状态.单位.契约者.冷却['斩击']).toBe(3); // 没选的没动
  });

  it('名写「选中技能」但玩家没选 → 跳过并说明（不许悄悄清错一条）', () => {
    const { 文本 } = 放(
      {
        时之楔: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '清冷却', 名: '选中技能' })] }),
      },
      '时之楔',
      { 冷却: { 别的: 2 } },
    );

    expect(文本).toContain('选中技能');
    expect(文本).toContain('跳过');
  });

  it('名省略 / 写「当前技能」→ 作用于正在放的这一条', () => {
    const { 我 } = 放(
      { 净火: 造解释({ 冷却: 3, 规则: [用自身({ 类: '技能作用', 操作: '清冷却', 名: '当前技能' })] }) },
      '净火',
    );

    // 放完先进冷却 3，再被自己清掉
    expect(我.冷却['净火']).toBe(0);
  });
});

describe('2 · 次数连携（每场限次）', () => {
  const 八咫镜 = 造解释({ 行动消耗: '次要行动', 每场限次: 2 });

  it('重置次数：把"本场已用"清零，于是又能放', () => {
    const { 我 } = 放(
      {
        八咫镜,
        再演: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '重置次数', 名: '八咫镜' })] }),
      },
      '再演',
      { 已用次数: { 八咫镜: 2 } },
    );

    expect(我.已用次数?.['八咫镜']).toBe(0);
  });

  it('加次数：「额外使用一次」= 已用 -1（不会变成负数）', () => {
    const 表 = (量: number) => ({
      八咫镜,
      再演: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '加次数', 名: '八咫镜', 量: { 源: '常数', 系数: 量 } })] }),
    });

    expect(放(表(1), '再演', { 已用次数: { 八咫镜: 2 } }).我.已用次数?.['八咫镜']).toBe(1);
    expect(放(表(5), '再演', { 已用次数: { 八咫镜: 2 } }).我.已用次数?.['八咫镜']).toBe(0);
  });
});

describe('3 · 词条连携（挂标签 + 条件读标签）', () => {
  it('挂词条 → 该技能「使用时」的条件读得到「技能词条」', () => {
    const 带条件 = 造解释({
      伤害倍率: 1,
      规则: [
        {
          触发: '使用时',
          作用域: '自身',
          条件: { 左: { 源: '技能词条', 名: '强化' }, 比较: '=', 右: { 源: '常数', 系数: 1 } },
          动作: [{ 类: '数值修正', 目标: '伤害', 量: { 源: '常数', 系数: 1 } }],
        },
      ],
    });

    const 没挂 = 放({ 斩击: 带条件 }, '斩击');
    const 挂了 = 放(
      { 斩击: 带条件, 强化术: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '挂词条', 名: '斩击', 词条: '强化' })] }) },
      '强化术',
    );

    expect(没挂.文本).not.toContain('数值修正');
    expect(挂了.我.技能词条?.['斩击']).toContain('强化');
  });

  it('移除词条 → 摘掉标签', () => {
    const { 我 } = 放(
      { 卸甲: 造解释({ 规则: [用自身({ 类: '技能作用', 操作: '移除词条', 名: '斩击', 词条: '强化' })] }) },
      '卸甲',
      { 技能词条: { 斩击: ['强化', '别的'] } },
    );

    expect(我.技能词条?.['斩击']).toEqual(['别的']);
  });

  it('**挂着词条时那一击真的更疼**（词条不是摆设）', () => {
    const 表 = (挂: boolean) => {
      const r: Record<string, 战斗解释> = { 斩击: 造解释({ 伤害倍率: 1 }) };
      const 有词条 = 造解释({
        伤害倍率: 1,
        规则: [
          {
            触发: '使用时',
            作用域: '自身',
            条件: { 左: { 源: '技能词条', 名: '强化' }, 比较: '=', 右: { 源: '常数', 系数: 1 } },
            动作: [{ 类: '数值修正', 目标: '伤害', 量: { 源: '常数', 系数: 1 } }],
          },
        ],
      });
      if (挂) r['斩击'] = 有词条;
      else r['斩击'] = 造解释({ 伤害倍率: 1 });
      return r;
    };

    const a = 放(表(false), '斩击');
    const b = 放(表(true), '斩击', { 技能词条: { 斩击: ['强化'] } });

    expect(b.文本).toContain('数值修正');
    expect(a.文本).not.toContain('数值修正');
  });
});

describe('4 · 技能加成（「使下一个伤害技能伤害 +50%」）', () => {
  const 表 = {
    斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 伤害倍率: 1 }),
    助威: 造解释({
      规则: [用自身({ 类: '技能作用', 操作: '技能加成', 名: '斩击', 目标: '伤害', 量: { 源: '常数', 系数: 1 } })],
    }),
  };

  it('加成记在单位身上（技能 → 数值修正目标 → 量）', () => {
    const { 我 } = 放(表, '助威');

    expect(我.技能加成?.['斩击']?.['伤害']).toBe(1);
  });

  it('**下一次释放吃得到，且用完即清**（不清就变成常驻了）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: 表,
      技能加成: { 斩击: { 伤害: 1 } },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 开战规则结算(造状态(我, 敌));

    // 先助威（把加成又挂上），再用斩击 —— 斩击这一下吃完就没了
    const r1 = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '助威', 目标: '契约者' }, 骰);
    const r2 = 结算行动(r1.状态, r1.状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    expect(r2.步骤.map(s => s.内容).join('\n')).toContain('技能加成');
    expect(r2.状态.单位.契约者.技能加成?.['斩击']).toBeUndefined();
  });
});

