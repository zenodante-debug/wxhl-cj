import { describe, expect, it } from 'vitest';
import { 校验战斗解释 } from '../ai/skillInterpreter';

// ================================================================
// 玩家反馈（翻译难关）：
//   「我一个普普通通的天赋："所有最终伤害×2"，都要翻译很多遍都翻译不出来。
//     要么缺条目要么缺分类。」
//   「很多技能、装备、血统、天赋，在生成的时候就只有一个孤零零的效果，没有别的类项，
//     这种情况模型就傻眼了，是不是应该提供默认的类项，或者让模型自己理解？」
//
// 查证：
// - `分类` **全引擎没有任何地方读**（纯展示字段），却要必填 —— 纯内耗。
// - `可预判` 只在打断门禁里用一次，被动/血统/天赋根本用不到。
// - 非行动效果（被动/光环/装备常驻）的 射程/目标/消耗/冷却 都有**无歧义的默认值**。
//
// 修法（玩家的建议，双向同时上）：
//   A. 校验器给非关键字段默认值（缺了就补，不拒绝）；
//   B. 提示词里给"卡面没写就怎么填"的决定规则（让模型自己能推出来）。
// 真正需要模型理解的只有**效果结构**（触发点/动作），字段不该成为拦路虎。
// ================================================================

describe('校验战斗解释 · 非关键字段给默认值（玩家反馈）', () => {
  it('「所有最终伤害×2」这种孤零零的被动天赋：缺什么补什么，不再判失败', () => {
    const 解释 = 校验战斗解释({
      规则: [
        { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '常数', 系数: 1 } }] },
      ],
    });

    expect(解释.分类).toBe('基础'); // 全引擎没人读的字段，默认基础
    expect(解释.可预判).toBe(true);
    expect(解释.行动消耗).toBe('无'); // 没有类型 → 按被动收
    expect(解释.类型).toBe('被动');
    expect(解释.射程).toBe('自身');
    expect(解释.目标).toBe('自身');
    expect(解释.消耗).toBe('无');
    expect(解释.冷却).toBe(0); // 被动没有冷却
  });

  it('只写了行动类型的主动技能：缺的字段按主动口径补，且不把默认补错方向', () => {
    const 解释 = 校验战斗解释({
      行动消耗: '主要行动',
      伤害倍率: 1.4,
      规则: [],
    });

    expect(解释.类型).toBe('主动');
    expect(解释.行动消耗).toBe('主要行动'); // 不被动摇
    expect(解释.射程).toBe('视线内'); // 主动没写射程 → 最不拦截的默认（引擎本来就不拦这种）
    expect(解释.目标).toBe('单体');
    expect(解释.可预判).toBe(true); // 偷袭/瞬发卡面会自己写 false
    expect(解释.分类).toBe('基础');
  });

  it('**主动类型但没写行动类型**：按引擎自己的归一化规则补「免费行动」（两边一致）', () => {
    const 解释 = 校验战斗解释({
      类型: '主动',
      规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '护盾', 量: { 源: '常数', 系数: 100 } }] }],
    });

    expect(解释.行动消耗).toBe('免费行动'); // 与 engine/actionOptions.规范行动消耗 同一口径
    expect(解释.类型).toBe('主动');
  });

  it('装备常驻效果（类型被动）补上自身口径 —— 不再需要模型凭空编', () => {
    const 解释 = 校验战斗解释({
      类型: '被动',
      规则: [{ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '防御', 量: { 源: '常数', 系数: 3 } }] }],
    });

    expect(解释.射程).toBe('自身');
    expect(解释.目标).toBe('自身');
    expect(解释.行动消耗).toBe('无');
  });

  it('写了的字段一律不动（默认只补缺，不覆盖）', () => {
    const 解释 = 校验战斗解释({
      行动消耗: '次要行动',
      射程: '50米',
      目标: '单体',
      消耗: 'MP 30',
      冷却: 3,
      分类: '高级',
      类型: '主动',
      可预判: false,
      伤害倍率: 2,
      规则: [],
    });

    expect(解释.分类).toBe('高级');
    expect(解释.可预判).toBe(false);
    expect(解释.射程).toBe('50米');
    expect(解释.消耗).toBe('MP 30');
    expect(解释.冷却).toBe(3);
  });

  it('技能阶位 / 关联属性 / 伤害倍率 缺失也有默认（下游公式不炸）', () => {
    const 解释 = 校验战斗解释({ 行动消耗: '主要行动', 伤害倍率: 1, 规则: [] });

    expect(解释.技能阶位).toBe(1);
    expect(解释.关联属性).toBe('STR');
  });

  it('**该拦的还是拦**：完全不是对象才判失败；坏规则只记忽略数', () => {
    expect(() => 校验战斗解释(null)).toThrow();
    expect(校验战斗解释({ 行动消耗: '无', 规则: [{}, {}] }).忽略的规则).toBe(2);
  });
});
