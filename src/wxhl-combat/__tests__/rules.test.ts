import { describe, expect, it } from 'vitest';
import { 属性修正值 } from '../engine/rules';

describe('rules · 属性修正值', () => {
  it('一阶：实际属性值 10 → 修正值 = (10-5)×1 = 5', () => {
    expect(属性修正值(10, '一阶')).toBe(5);
  });

  it('二阶：实际属性值 25 → 修正值 = (25-5)×2 = 40', () => {
    expect(属性修正值(25, '二阶')).toBe(40);
  });

  it('三阶：实际属性值 40 → 修正值 = (40-5)×4 = 140', () => {
    expect(属性修正值(40, '三阶')).toBe(140);
  });

  it('四阶：实际属性值 55 → 修正值 = (55-5)×7 = 350', () => {
    expect(属性修正值(55, '四阶')).toBe(350);
  });

  it('五阶：实际属性值 150 → 修正值 = (150-5)×11 = 1595', () => {
    expect(属性修正值(150, '五阶')).toBe(1595);
  });

  it('超脱：实际属性值 200 → 修正值 = (200-5)×20 = 3900', () => {
    expect(属性修正值(200, '超脱')).toBe(3900);
  });

  it('实际属性值 5 → 修正值 = 0', () => {
    expect(属性修正值(5, '一阶')).toBe(0);
  });

  it('实际属性值 0 → 修正值 = -5', () => {
    expect(属性修正值(0, '一阶')).toBe(-5);
  });
});
