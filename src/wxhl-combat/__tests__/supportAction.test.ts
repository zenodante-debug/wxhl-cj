import { describe, expect, it } from 'vitest';
import { 跑一个回合, 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗解释, 战斗单位 } from '../types';

// ================================================================
// 支援行动（R21）与"上 buff 真的改数值"
//
// 两个缺口：
// 1. 同阵营目标以前走**攻击管线** —— 敌人在帮队友上 buff，引擎却去掷命中对抗队友的闪避值、
//    还打出武器伤害（把队友当敌人打）。「目标: 自身」的自 buff 技能因此会自伤。
// 2. `数值修正` 动作**没有承载字段**，被静默丢弃 —— "给友军 +30% 伤害"落进虚空。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

/** 给友军 +30% 伤害的增益（次要行动） */
const 强化咆哮 = 造解释({
  行动消耗: '次要行动',
  射程: '视线内',
  类型: '辅助',
  伤害倍率: 0,
  规则: [
    {
      触发: '使用时',
      作用域: '攻击目标',
      动作: [{ 类: '数值修正', 目标: '伤害', 量: { 源: '常数', 系数: 0.3 } }],
    },
  ],
});

/** 命中后给目标 -20% 减伤（破甲 → 易伤） */
const 破甲击 = 造解释({
  规则: [
    {
      触发: '命中时',
      作用域: '攻击目标',
      动作: [{ 类: '数值修正', 目标: '减伤', 量: { 源: '常数', 系数: -0.2 } }],
    },
  ],
});

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    类型: '精英',
    属性: { 实际: { STR: 20, AGI: 10, CON: 16, PER: 10 } },
    阶位: '一阶',
    HP_当前: 200,
    HP_最大: 200,
    MP_当前: 20,
    MP_最大: 20,
    耐力_当前: 80,
    耐力_最大: 80,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(骨卫兵甲覆盖: Partial<战斗单位> = {}): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: ['副本角色.骨卫兵甲', '副本角色.骨卫兵乙', '契约者'],
    单位: {
      契约者: 造单位({
        id: '契约者',
        阵营: '我方',
        类型: '玩家',
        HP_当前: 500,
        HP_最大: 500,
        技能: {},
      }),
      骨卫兵甲: 造单位({
        id: '副本角色.骨卫兵甲',
        阵营: '敌方',
        技能: { 强化咆哮, 骨爪撕裂: 造解释() },
        ...骨卫兵甲覆盖,
      }),
      骨卫兵乙: 造单位({
        id: '副本角色.骨卫兵乙',
        阵营: '敌方',
        技能: { 骨爪撕裂: 造解释() },
      }),
    },
    待决: null,
    领域: [],
  };
}

describe('支援行动 · 同阵营目标不走攻击管线', () => {
  it('给队友上 buff：不掷命中、不造成伤害，但照常扣次要槽', () => {
    const 状态 = 造状态();

    const r = 跑一个回合(
      状态,
      [],
      [{ 单位: '骨卫兵甲', 行动: [{ 类型: '次要行动', 技能: '强化咆哮', 目标: '骨卫兵乙' }] }],
      { 命中: 20, 伤害骰: [6] },
    );

    // 队友没掉血（以前会：掷命中 + 武器伤害）
    expect(r.状态.单位.骨卫兵乙.HP_当前).toBe(200);
    expect(r.状态.单位.骨卫兵甲.行动槽.次要).toBe(0);
    expect(r.步骤.some(s => s.内容.includes('支援行动：不掷命中、不造成伤害'))).toBe(true);
  });

  it('buff 落成一条**携带数值修正的状态**（引擎唯一能承载"上 buff"的地方）', () => {
    const 状态 = 造状态();

    const r = 跑一个回合(
      状态,
      [],
      [{ 单位: '骨卫兵甲', 行动: [{ 类型: '次要行动', 技能: '强化咆哮', 目标: '骨卫兵乙' }] }],
    );

    const buff = r.状态.单位.骨卫兵乙.状态.find(s => s.名 === '强化咆哮');
    expect(buff).toBeDefined();
    expect(buff!.数值修正).toEqual({ 伤害: 0.3 });
    expect(buff!.持续).toBe(2);
    expect(r.步骤.some(s => s.内容.includes('数值修正 伤害+0.3'))).toBe(true);
  });

  it('**buff 真的改数值**：被 buff 的敌人打玩家，伤害确实变高', () => {
    const 打玩家 = [{ 单位: '骨卫兵乙', 行动: [{ 类型: '主要行动' as const, 技能: '骨爪撕裂', 目标: '玩家' }] }];
    const 骰 = { 命中: 20, 伤害骰: [6] };

    const 未加 = 跑一个回合(造状态(), [], 打玩家, 骰);
    const 加过 = 跑一个回合(
      造状态(),
      [],
      [{ 单位: '骨卫兵甲', 行动: [{ 类型: '次要行动' as const, 技能: '强化咆哮', 目标: '骨卫兵乙' }] }, ...打玩家],
      骰,
    );

    const 未加伤害 = 500 - 未加.状态.单位.契约者.HP_当前;
    const 加过伤害 = 500 - 加过.状态.单位.契约者.HP_当前;

    expect(未加伤害).toBeGreaterThan(0);
    expect(加过伤害).toBeGreaterThan(未加伤害);
    expect(加过.步骤.some(s => s.内容.includes('乘区 1.3'))).toBe(true);
  });

  it('支援也要过射程门禁：技能写近战，队友在 30 米外 → 拒绝', () => {
    const 状态 = 造状态();
    状态.单位.骨卫兵乙.距离 = 30;
    状态.单位.骨卫兵甲.技能.强化咆哮 = 造解释({
      行动消耗: '次要行动',
      射程: '近战',
      类型: '辅助',
      伤害倍率: 0,
      规则: 强化咆哮.规则,
    });

    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵甲', 行动: [{ 类型: '次要行动', 技能: '强化咆哮', 目标: '骨卫兵乙' }] }]);

    expect(r.状态.单位.骨卫兵乙.状态).toHaveLength(0);
    expect(r.步骤.some(s => s.内容.includes('覆盖不到'))).toBe(true);
  });

  it('主要行动给友军上 buff 也走支援（不限于次要行动）', () => {
    const 状态 = 造状态();
    状态.单位.骨卫兵甲.技能.强化咆哮 = 造解释({
      射程: '视线内',
      类型: '辅助',
      伤害倍率: 0,
      规则: 强化咆哮.规则,
    });

    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵甲', 行动: [{ 类型: '主要行动', 技能: '强化咆哮', 目标: '骨卫兵乙' }] }]);

    expect(r.状态.单位.骨卫兵乙.HP_当前).toBe(200);
    expect(r.状态.单位.骨卫兵乙.状态.some(s => s.名 === '强化咆哮')).toBe(true);
  });

  it('次要行动的增益到期后消失（阶段F 递减）', () => {
    const 状态 = 造状态();
    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵甲', 行动: [{ 类型: '次要行动', 技能: '强化咆哮', 目标: '骨卫兵乙' }] }]);

    expect(r.状态.单位.骨卫兵乙.状态[0].持续).toBe(2);
  });
});

describe('命中时的数值修正 · 破甲（以前被静默丢弃）', () => {
  it('命中后给目标 -0.2 减伤 → 同一发攻击打两次，第二次更疼', () => {
    const 状态 = 造状态();
    状态.单位.骨卫兵甲.技能.破甲击 = 破甲击; // 技能必须在技能表里才会被结算
    const 骰 = { 命中: 20, 伤害骰: [6] };

    const 第一次 = 结算行动(状态, 状态.单位['骨卫兵甲'], { 类型: '主要行动', 技能: '破甲击', 目标: '玩家' }, 骰);
    const 第一次伤害 = 500 - 第一次.状态.单位.契约者.HP_当前;

    // 契约者身上现在带着「破甲击」状态（减伤 -0.2）→ 同一发攻击再打一次
    const 破甲状态 = 第一次.状态.单位.契约者.状态.find(s => s.名 === '破甲击');
    expect(破甲状态?.数值修正).toEqual({ 减伤: -0.2 });
    expect(第一次伤害).toBeGreaterThan(0);

    // 模拟下一回合：行动槽重置 + 冷却走完（技能现在**有冷却**，最小 1 回合 —— 不清会被挡住）
    第一次.状态.单位.骨卫兵甲.行动槽 = { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 };
    第一次.状态.单位.骨卫兵甲.冷却 = {};
    const 第二次 = 结算行动(
      第一次.状态,
      第一次.状态.单位['骨卫兵甲'],
      { 类型: '主要行动', 技能: '破甲击', 目标: '玩家' },
      骰,
    );
    const 第二次伤害 = 第一次.状态.单位.契约者.HP_当前 - 第二次.状态.单位.契约者.HP_当前;

    expect(第二次伤害).toBeGreaterThan(第一次伤害);
  });

  it('数值修正叠加：两层 buff 相加（常驻修正逐条累加）', () => {
    const 状态 = 造状态();
    状态.单位.骨卫兵乙.状态 = [
      { 名: '强化咆哮', 持续: 2, 数值修正: { 伤害: 0.3 } },
      { 名: '战意', 持续: 2, 数值修正: { 伤害: 0.2 } },
    ];

    const r = 跑一个回合(状态, [], [{ 单位: '骨卫兵乙', 行动: [{ 类型: '主要行动', 技能: '骨爪撕裂', 目标: '玩家' }] }], {
      命中: 20,
      伤害骰: [6],
    });

    expect(r.步骤.some(s => s.内容.includes('乘区 1.5'))).toBe(true);
  });
});
