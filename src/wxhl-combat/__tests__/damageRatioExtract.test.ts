import { describe, expect, it } from 'vitest';
import { 构建批量翻译提示词 } from '../ai/skillInterpreter';

// ================================================================
// 玩家实测（2026-10-10）：「伤害倍率，这个不知道为什么读不出来，
//   进入战斗后，战斗效果那边全写着伤害倍率0」
//
// 查证：`单位效果源` 接口里**本来就没有 `伤害倍率` 这个字段**（只有名称/类型/行动类型/
// 关联属性/阶位/消耗/冷却/射程/目标/效果）—— 模型只能从「效果」文本里推。
// 玩家口径：「我想的是，让模型根据效果来提取」。
//
// 所以修法在**提示词**：教它"卡面直接写了系数就照抄"（最准），并强调
// "造成伤害的技能，伤害倍率必须是非 0 的数"（一排 0 等于没翻）。
// ================================================================

describe('伤害倍率的提示词口径（让模型从效果文本里提取）', () => {
  const 提示词 = 构建批量翻译提示词([]);

  it('教「卡面直接写了系数就照抄」，并给例子（比按区间猜准）', () => {
    expect(提示词).toContain('先看卡面有没有直接写系数');
    expect(提示词).toContain('5.5×PER修正值');
    expect(提示词).toContain('照抄');
  });

  it('强调「造成伤害的技能，伤害倍率必须是非 0 的数」（一排 0 等于没翻）', () => {
    expect(提示词).toContain('必须是非 0 的数');
    // 只有确实不造成伤害的才填 0
    expect(提示词).toMatch(/不造成伤害.*填 0|填 0.*不造成伤害/);
  });

  it('同阶区间表还在（卡面没写系数时的兜底）', () => {
    expect(提示词).toContain('一阶 0.3~0.9');
  });
});
