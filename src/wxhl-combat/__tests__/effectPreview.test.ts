import { describe, expect, it } from 'vitest';
import { 动作人话, 效果预览, 条件人话, 预览摘要 } from '../engine/effectPreview';
import type { 动作, 战斗解释 } from '../types';

// ================================================================
// 玩家反馈：「每个具体的行动选项，应该能够看到产生的具体的预期效果啊！
// 现在点技能完全不知道有什么用，比如一个二阶段变身技能，完全不知道能干什么。」
//
// 这里钉的是**人话**：头部（行动类型/射程/目标/消耗/倍率/冷却）+ 规则逐条
// 「触发点（条件）→ 作用域：效果」。不改数值，只是看得懂。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 2,
    分类: '高级',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 3,
    伤害倍率: 1.4,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

const 常数 = (n: number) => ({ 源: '常数' as const, 系数: n });

describe('效果预览 · 头部', () => {
  it('元信息一眼看全：行动类型 / 射程 / 目标 / 消耗 / 倍率 / 冷却', () => {
    const 预览 = 效果预览(造解释({ 消耗: 'MP 15', 射程: '视线内' }));

    expect(预览.头部).toEqual(['主要行动', '视线内', '单体', '消耗 MP 15', '伤害 ×1.4', '冷却 2 回合']);
  });

  it('装备的主动效果（行动类型没写）在头部显示为**免费行动**，冷却默认 1', () => {
    const 预览 = 效果预览(造解释({ 类型: '主动', 行动消耗: '无', 冷却: undefined, 伤害倍率: 0 }));

    expect(预览.头部).toContain('免费行动');
    expect(预览.头部).toContain('冷却 1 回合');
  });

  it('被动效果标注「非行动效果」，且不显示冷却（它不占行动）', () => {
    const 预览 = 效果预览(造解释({ 类型: '被动', 行动消耗: '无', 伤害倍率: 0 }));

    expect(预览.头部[0]).toBe('非行动效果');
    expect(预览.头部.some(s => s.includes('冷却'))).toBe(false);
  });
});

describe('效果预览 · 二阶段变身技能（玩家点名的例子）', () => {
  const 变身 = 造解释({
    行动消耗: '次要行动',
    冷却: 5,
    伤害倍率: 0,
    规则: [
      {
        触发: '使用时',
        作用域: '自身',
        动作: [
          { 类: '切换形态', 到: '二阶段·觉醒' },
          { 类: '施加状态', 名: '觉醒', 持续: 3 },
          { 类: '数值修正', 目标: 'STR修正', 量: 常数(50) },
          { 类: '数值修正', 目标: '攻击倍率', 量: 常数(1) },
        ],
      },
    ],
  });

  it('能看出"切成什么形态、拿到什么状态、加了哪些数值"', () => {
    const 预览 = 效果预览(变身);
    const 全文 = 预览.行.join('\n');

    expect(全文).toContain('切换到形态「二阶段·觉醒」');
    expect(全文).toContain('施加状态「觉醒」3回合');
    expect(全文).toContain('STR修正值 +50');
    expect(全文).toContain('武器倍率 +100%');
  });

  it('每条规则带上触发点与作用域（玩家才知道什么时候生效、作用在谁身上）', () => {
    const 预览 = 效果预览(变身);

    expect(预览.行[0]).toMatch(/^使用时 → 自身：/);
  });

  it('有条件的规则把条件翻成人话（HP 低于 50%）', () => {
    const 血怒 = 造解释({
      伤害倍率: 0,
      规则: [
        {
          触发: '资源变化时',
          条件: { 左: { 源: '资源', 名: 'HP比例' }, 比较: '<', 右: 常数(0.5) },
          作用域: '自身',
          动作: [{ 类: '数值修正', 目标: '攻击倍率', 量: 常数(0.5) }],
        },
      ],
    });

    expect(效果预览(血怒).行[0]).toContain('自身HP低于50%');
  });

  it('没有规则、也没有倍率 → 明说"没有额外效果"（而不是空白让人以为坏了）', () => {
    const 空 = 造解释({ 伤害倍率: 0, 规则: [] });

    expect(效果预览(空).行.join()).toContain('没有额外效果');
  });

  it('托管文本留底也显示出来（翻译不了的部分不能人间蒸发）', () => {
    const 怪 = 造解释({
      伤害倍率: 0,
      规则: [],
      托管: [{ 原文: '每次攻击后额外投一次命运骰', 触发点: ['命中时'] }],
    });

    expect(效果预览(怪).行.join()).toContain('命运骰');
  });
});

describe('效果预览 · 各种动作都能翻成人话', () => {
  const 案例: Array<[动作, string]> = [
    [{ 类: '资源', 名: 'MP', 操作: '消耗', 量: 常数(15) }, '消耗 15 MP'],
    [{ 类: '资源', 名: 'HP', 操作: '恢复', 量: 常数(50) }, '恢复 50 HP'],
    [{ 类: '护盾', 量: 常数(200) }, '获得护盾 200'],
    [{ 类: '数值修正', 目标: '减伤', 量: 常数(0.2) }, '减伤 +20%'],
    [{ 类: '数值修正', 目标: '防御', 量: 常数(10) }, '防御 +10'],
    [{ 类: '数值修正', 目标: '最终乘区', 量: 常数(4) }, '最终伤害 ×5'],
    [{ 类: '施加状态', 名: '灼烧', 持续: 3, 层数: 常数(2) }, '施加状态「灼烧」3回合 ×2层'],
    [{ 类: '词条', 名: '不可被常规攻击命中' }, '附加词条「不可被常规攻击命中」'],
    [{ 类: '词条', 名: '禁位移', 操作: '移除' }, '移除词条「禁位移」'],
    [{ 类: '切换形态', 到: '卍解' }, '切换到形态「卍解」'],
    [{ 类: '追加攻击', 次数: 2 }, '追加攻击 2 次'],
    [{ 类: '范围伤害', 中心: '攻击目标', 半径: 10, 量: 常数(80) }, '半径 10 米'],
    [{ 类: '规则系判定', 效果: '即死', 目标: '攻击目标' }, '规则系「即死」'],
  ];

  for (const [动作, 期望] of 案例) {
    it(`${动作.类} → ${期望}`, () => {
      expect(动作人话(动作)).toContain(期望);
    });
  }

  it('条件分支把真假两支都写出来', () => {
    const 话 = 动作人话({
      类: '条件分支',
      条件: { 左: { 源: '资源', 名: 'HP比例' }, 比较: '<', 右: 常数(0.3) },
      真: [{ 类: '数值修正', 目标: '伤害', 量: 常数(1) }],
      假: [],
    });

    expect(话).toContain('自身HP低于30%');
    expect(话).toContain('伤害 +100%');
    expect(话).toContain('否则');
  });

  it('未知动作不崩、也不静默（返回"未知效果"）', () => {
    expect(动作人话({ 类: '来自未来的新动作' } as any)).toContain('未知效果');
  });

  it('条件：非 HP 比例的条件按「左 比较 右」直译', () => {
    expect(条件人话({ 左: { 源: '资源', 名: 'MP' }, 比较: '≥', 右: 常数(100) })).toBe('MP ≥ 100');
  });

  it('没给解释 → 明确说没有可展示的效果（模板不会拿到 undefined 崩掉）', () => {
    expect(效果预览(undefined).行[0]).toContain('没有可展示的效果');
  });

  it('摘要单行拼接，给下拉标签用', () => {
    expect(预览摘要(造解释())).toBe('主要行动 · 近战 · 单体 · 伤害 ×1.4 · 冷却 2 回合');
  });
});
