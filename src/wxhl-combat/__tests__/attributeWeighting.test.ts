import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 归一属性键, 解析属性加权 } from '../engine/rules';
import { 效果预览 } from '../engine/effectPreview';
import { 校验战斗解释 } from '../ai/skillInterpreter';
import { 列行动选项 } from '../engine/actionOptions';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 玩家补充（2026-10-09）：
//   「光子镭射（主动轰击）……造成 PER×3.6 + AGI×3.2 的伤害」
//   —— 卡面直接写「多属性加权」，一条 `关联属性 × 伤害倍率` 表达不了这一招。
//
// 口径（plan §8.3 第 1 项）：
//   `属性加权` 存在时，技能伤害的基础值 = **Σ(该属性修正值 × 系数)**（再按技能阶位成长）；
//   不写 `属性加权` 时，**完全照旧**走 `关联属性修正 × 伤害倍率`（老存档行为不变）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 200, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 200,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/**
 * 攻方四维：STR 5 / AGI 100 / CON 5 / PER 200（一阶 → 系数 1）
 * → 修正值 STR 0 / AGI 95 / CON 0 / PER 195
 */
const 攻方属性 = { 实际: { STR: 5, AGI: 100, CON: 5, PER: 200 } };

// 命中骰固定 10：低于暴击下限（AGI 100 → 暴击范围 15），所以永远不暴击，伤害可心算；
// 伤害骰固定 6。
const 骰 = { 命中: 10, 伤害骰: [6] };

/** 打一拳，返回掉的血与战斗日志 */
function 打(解释: 战斗解释, 守方覆盖: Partial<战斗单位> = {}) {
  const 我 = 造单位({ id: '契约者', 阵营: '我方', 属性: 攻方属性, 技能: { 镭射: 解释 } });
  // HP 给足（十万），免得伤害被"打到 0 就停"截断 —— 这些用例要看的是**算出来多少**伤害
  const 敌 = 造单位({
    id: '副本角色.骨卫兵',
    阵营: '敌方',
    HP_当前: 100000,
    HP_最大: 100000,
    防御: 0,
    闪避值: 0,
    技能: {},
    ...守方覆盖,
  });
  const 状态 = 开战规则结算(造状态(我, 敌));

  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '镭射', 目标: '骨卫兵' }, 骰);
  return { 伤害: 100000 - r.状态.单位.骨卫兵.HP_当前, 文本: r.步骤.map(s => s.内容).join('\n') };
}

/**
 * 一次技能攻击的总伤害（本用例的守方防御 0、无减伤护盾、不暴击 → 就是 武器 + 技能）：
 *   徒手部分 = ceil((伤害骰 6 + 属性修正) × 0.5)
 *   技能部分 = ceil(技能基础值 × (1 + (阶位−1)/2))
 */
const 徒手部分 = (属性修正: number) => Math.ceil((6 + 属性修正) * 0.5);

describe('1 · 多属性加权伤害：PER×3.6 + AGI×3.2', () => {
  const 加权 = [{ 属性: 'PER' as const, 系数: 3.6 }, { 属性: 'AGI' as const, 系数: 3.2 }];

  it('技能基础值 = Σ(属性修正值 × 系数)，再按技能阶位成长', () => {
    const r = 打(造解释({ 属性加权: 加权, 伤害倍率: 0 }));

    // 徒手部分按「系数最大」的 PER（修正 195）：ceil((6 + 195) × 0.5) = 101
    // 技能部分：ceil((195 × 3.6 + 95 × 3.2) × 1) = ceil(702 + 304) = 1006
    expect(r.伤害).toBe(徒手部分(195) + Math.ceil(195 * 3.6 + 95 * 3.2));
    expect(r.伤害).toBe(101 + 1006);
  });

  it('伤害日志把加权明细写出来（玩家看得见钱花在哪）', () => {
    const r = 打(造解释({ 属性加权: 加权, 伤害倍率: 0 }));

    expect(r.文本).toContain('PER修正 195');
    expect(r.文本).toContain('AGI修正 95');
    expect(r.文本).toContain('3.6');
    expect(r.文本).toContain('3.2');
  });

  it('技能阶位成长照旧吃（阶位 3 → ×2）', () => {
    const r = 打(造解释({ 属性加权: [{ 属性: 'PER', 系数: 1 }], 技能阶位: 3, 伤害倍率: 0 }));

    expect(r.伤害).toBe(徒手部分(195) + Math.ceil(195 * 1 * 2));
  });

  it('**不写 属性加权 → 行为完全不变**（关联属性修正 × 伤害倍率）', () => {
    const r = 打(造解释({ 关联属性: 'PER', 伤害倍率: 3.6 }));

    expect(r.伤害).toBe(徒手部分(195) + Math.ceil(195 * 3.6));
  });

  it('写了 属性加权 就以它为准，不再叠加 伤害倍率（不重复计一次伤害）', () => {
    const 只加权 = 打(造解释({ 属性加权: [{ 属性: 'PER', 系数: 3.6 }], 伤害倍率: 0 }));
    const 两个都写 = 打(造解释({ 属性加权: [{ 属性: 'PER', 系数: 3.6 }], 伤害倍率: 3.6 }));

    expect(两个都写.伤害).toBe(只加权.伤害);
  });
});

describe('2 · 多属性攻击的「用哪一维掷命中」', () => {
  // 守方闪避 100：只有按 PER（修正 195）算命中才够得着；按 STR（修正 0）必然落空
  const 硬目标 = { 闪避值: 100 };

  it('关联属性没写 → 取系数最大的那一维（PER，不是默认的 STR）', () => {
    const r = 打(造解释({ 属性加权: [{ 属性: 'AGI', 系数: 1 }, { 属性: 'PER', 系数: 3.6 }] }), 硬目标);

    expect(r.文本).not.toContain('未命中');
    expect(r.伤害).toBeGreaterThan(0);
  });

  it('显式写了 关联属性 → 以它为准（属性加权只管伤害，不改命中）', () => {
    const r = 打(造解释({ 关联属性: 'STR', 属性加权: [{ 属性: 'PER', 系数: 3.6 }] }), 硬目标);

    expect(r.文本).toContain('未命中');
    expect(r.伤害).toBe(0);
  });
});

describe('3 · 属性名归一化与属性加权的宽容解析', () => {
  it('属性名中英文写法都认', () => {
    expect(归一属性键('PER')).toBe('PER');
    expect(归一属性键('per')).toBe('PER');
    expect(归一属性键('感知')).toBe('PER');
    expect(归一属性键('敏捷')).toBe('AGI');
    expect(归一属性键('力量')).toBe('STR');
    expect(归一属性键('体质')).toBe('CON');
    expect(归一属性键('幸运')).toBeNull();
    expect(归一属性键('')).toBeNull();
    expect(归一属性键(undefined)).toBeNull();
  });

  it('认数组，也认卡面那种字符串写法', () => {
    expect(解析属性加权([
      { 属性: 'PER', 系数: 3.6 },
      { 属性: '敏捷', 系数: 3.2 },
    ])).toEqual([
      { 属性: 'PER', 系数: 3.6 },
      { 属性: 'AGI', 系数: 3.2 },
    ]);
    expect(解析属性加权('PER×3.6 + AGI×3.2')).toEqual([
      { 属性: 'PER', 系数: 3.6 },
      { 属性: 'AGI', 系数: 3.2 },
    ]);
    expect(解析属性加权('造成 感知*2 的伤害')).toEqual([{ 属性: 'PER', 系数: 2 }]);
  });

  it('单个对象也收（模型常这么写）', () => {
    expect(解析属性加权({ 属性: 'PER', 系数: 3.6 })).toEqual([{ 属性: 'PER', 系数: 3.6 }]);
  });

  it('非法条目丢掉（认不出的属性 / 负系数 / 缺系数 / null）', () => {
    expect(解析属性加权([
      { 属性: '幸运', 系数: 3 },
      { 属性: 'AGI', 系数: -1 },
      { 属性: 'PER' },
      null,
    ])).toEqual([]);
  });

  it('同一维重复只取第一条（不偷偷翻倍）', () => {
    expect(解析属性加权([
      { 属性: 'PER', 系数: 2 },
      { 属性: 'PER', 系数: 9 },
    ])).toEqual([{ 属性: 'PER', 系数: 2 }]);
  });

  it('空的 / 认不出来 → 空数组（调用方退回 关联属性 × 伤害倍率）', () => {
    expect(解析属性加权(undefined)).toEqual([]);
    expect(解析属性加权([])).toEqual([]);
    expect(解析属性加权('无')).toEqual([]);
  });
});

describe('4 · 预览里看得出这是加权伤害', () => {
  it('头部把加权写成人话（不再是光秃秃的"无伤害"）', () => {
    const 预览 = 效果预览(造解释({ 属性加权: [{ 属性: 'PER', 系数: 3.6 }, { 属性: 'AGI', 系数: 3.2 }], 伤害倍率: 0 }));

    expect(预览.头部.join(' · ')).toContain('PER×3.6');
    expect(预览.头部.join(' · ')).toContain('AGI×3.2');
  });
});

describe('6 · 行动下拉标签也看得出加权', () => {
  it('写的是「PER×3.6 + AGI×3.2」，不是"无伤害"', () => {
    const 单位 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: { 镭射: 造解释({ 属性加权: [{ 属性: 'PER', 系数: 3.6 }, { 属性: 'AGI', 系数: 3.2 }], 伤害倍率: 0 }) },
    });

    const 选项 = 列行动选项(单位, '主要行动').find(o => o.技能 === '镭射');
    expect(选项?.标签).toContain('PER×3.6 + AGI×3.2');
    expect(选项?.标签).not.toContain('无伤害');
  });
});

describe('5 · 翻译层：属性加权要落到解释里，且不许安静地丢掉', () => {
  const 打底 = { 行动消耗: '主要行动', 规则: [] };

  it('数组写法 → 收下；伤害倍率被归 0（两者只取一个）；关联属性补成系数最大的那一维', () => {
    const 解释 = 校验战斗解释({
      ...打底,
      伤害倍率: 3.6,
      属性加权: [
        { 属性: 'PER', 系数: 3.6 },
        { 属性: '敏捷', 系数: 3.2 },
      ],
    });

    expect(解释.属性加权).toEqual([
      { 属性: 'PER', 系数: 3.6 },
      { 属性: 'AGI', 系数: 3.2 },
    ]);
    expect(解释.伤害倍率).toBe(0);
    expect(解释.关联属性).toBe('PER');
  });

  it('模型把卡面原话抄成字符串也认（「PER×3.6 + AGI×3.2」）', () => {
    const 解释 = 校验战斗解释({ ...打底, 属性加权: 'PER×3.6 + AGI×3.2' });

    expect(解释.属性加权?.length).toBe(2);
  });

  it('卡面写了 关联属性 就不动它', () => {
    const 解释 = 校验战斗解释({ ...打底, 关联属性: 'AGI', 属性加权: [{ 属性: 'PER', 系数: 9 }] });

    expect(解释.关联属性).toBe('AGI');
  });

  it('**写了却一条都解析不出来 → 判失败**（响亮失败，别退化成"无伤害"的空壳）', () => {
    expect(() => 校验战斗解释({ ...打底, 属性加权: [{ 属性: '幸运', 系数: 3 }] })).toThrow(/属性加权/);
  });

  it('空数组 / 没写 → 不留字段，老行为不受影响', () => {
    expect(校验战斗解释({ ...打底, 属性加权: [] }).属性加权).toBeUndefined();
    expect(校验战斗解释({ ...打底, 伤害倍率: 2 }).伤害倍率).toBe(2);
  });
});
