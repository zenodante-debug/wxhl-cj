import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import type { 战斗解释, 战斗状态, 战斗单位 } from '../types';

// ================================================================
// 快捷物品栏 · 引擎侧（plan §21）
//
// 玩家裁定：「用一次扣一个，**战斗中记账、收尾时写回背包**」。
//
// 做法：开战时把每件快捷物品的数量灌进 **`单位.快捷物品`**（玩家口径 2026-10-11：
//   **不能放 `资源`** —— 那是"特殊资源"（层数/状态/施法资源）的地盘，
//   放进去会显示在「资源:」那一行、还会被写回卡面的「特殊状态栏」），
//   技能上标 `解释.物品消耗 = 物品名` → `结算技能` **门禁 + 扣 1**。
//
// 为什么不用 `消耗: "绷带 1"`：那个字段的解析器只认 MP/耐力（实扣量/上限折算都绑死在那两个上），
// 硬塞进去会污染世界书的资源消耗规则。单开一个字段最干净，也最容易在战报里说清楚。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '免费行动',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '物品',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 100,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 一瓶绷带：免费行动，回 10 HP，用一次扣一个 */
const 绷带 = 造解释({
  物品消耗: '绷带',
  规则: [
    { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 10 } }] },
  ],
});

function 造场(数量: number) {
  const 我 = 造单位({
    id: '契约者',
    阵营: '我方',
    HP_当前: 50,
    快捷物品: { 绷带: 数量 },
    技能: { '绷带（快捷物品）': 绷带 },
  });
  const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
  return 开战规则结算(造状态(我, 敌));
}

describe('快捷物品 · 用一次扣一个', () => {
  it('用一次：HP 回 10，绷带 99 → 98', () => {
    const 状态 = 造场(99);
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '绷带（快捷物品）', 目标: '契约者' }, {});

    expect(r.状态.单位.契约者.HP_当前).toBe(60);
    expect(r.状态.单位.契约者.快捷物品!.绷带).toBe(98);
  });

  it('战报里说清楚用掉了什么（玩家要知道自己还剩几个）', () => {
    const 状态 = 造场(3);
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '绷带（快捷物品）', 目标: '契约者' }, {});

    expect(r.步骤.map(s => s.内容).join('\n')).toContain('绷带');
  });

  it('连用三次：第三次「用完了」—— 效果不发生，数量停在 0', () => {
    const 状态 = 造场(2);
    const 打三次 = () => {
      let s = 状态;
      const 文本: string[] = [];
      for (let i = 0; i < 3; i++) {
        const r = 结算行动(s, s.单位.契约者, { 类型: '免费行动', 技能: '绷带（快捷物品）', 目标: '契约者' }, {});
        s = r.状态;
        文本.push(...r.步骤.map(x => x.内容));
      }
      return { 状态: s, 文本: 文本.join('\n') };
    };

    const { 状态: 终, 文本 } = 打三次();

    expect(终.单位.契约者.HP_当前).toBe(70); // 只回了两次
    expect(终.单位.契约者.快捷物品!.绷带).toBe(0); // 不许扣成负数
    expect(文本).toMatch(/用完|没有|不足/);
  });

  it('数量为 0 时**一次都用不了**（第一条就拦住）', () => {
    const 状态 = 造场(0);
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '绷带（快捷物品）', 目标: '契约者' }, {});

    expect(r.状态.单位.契约者.HP_当前).toBe(50);
    expect(r.状态.单位.契约者.快捷物品!.绷带).toBe(0);
    expect(r.步骤.map(s => s.内容).join('\n')).toMatch(/用完|没有|不足/);
  });

  it('**没有 `物品消耗` 的技能不受影响**（普通免费行动照旧能用）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 50,
      快捷物品: { 绷带: 0 },
      技能: {
        应急包扎: 造解释({
          规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '常数', 系数: 7 } }] }],
        }),
      },
    });
    const 状态 = 开战规则结算(造状态(我, 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' })));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '应急包扎', 目标: '契约者' }, {});

    expect(r.状态.单位.契约者.HP_当前).toBe(57);
  });

  it('**用掉快捷物品不会唤起「资源变化时」**（它不是特殊资源，别把两件事搅在一起）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 50,
      快捷物品: { 绷带: 2 },
      技能: {
        '绷带（快捷物品）': 绷带,
        盯着资源: 造解释({
          行动消耗: '无',
          规则: [
            {
              触发: '资源变化时',
              作用域: '自身',
              条件: { 左: { 源: '常数', 系数: 1 }, 比较: '=', 右: { 源: '常数', 系数: 1 } },
              动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '常数', 系数: 1 } }],
            },
          ],
        }),
      },
    });
    const 状态 = 开战规则结算(造状态(我, 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' })));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '免费行动', 技能: '绷带（快捷物品）', 目标: '契约者' }, {});

    expect(r.状态.单位.契约者.快捷物品!.绷带).toBe(1);
    expect(r.状态.单位.契约者.状态.some(s => (s.数值修正?.最终乘区 ?? 0) > 0)).toBe(false);
  });
});
