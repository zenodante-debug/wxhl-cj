import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 阶段A规则结算 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家实测（2026-10-10）：「锁血机制有大问题，经常会出现锁在 15% 不死的情况，
// 不管过了多少个回合都不死」
//
// 根因：「锁血下限」（比例，如 0.15 = 最大HP 的 15%）是**常驻修正**（被动/装备/血统里写
// 「无法一次跌入 15% 以下」→ `量 0.15`），但实现里它**没有"回合"这个概念** ——
// **每一次受击都拉**（`结算后HP < 下限 → 结算后HP = 下限`），于是 HP 掉到 15% 之后，
// 下一击本该打死它，又被拉回到 15% —— **永远锁在 15% 不死**。
//
// 世界书原文的意图：**一次攻击不能把 HP 打穿到 N% 以下**（「无法一次跌入 50% 以下的血量，
// 必须当前回合先锁在最低 50%」）—— 关键词是**"一次攻击"**与**"当前回合"**，不是"每次受击"。
//
// 修法：锁血下限只在**当前回合**生效 —— 一次攻击把 HP 打到低于 N% 时，**这一回合**锁在 N%；
// **下一回合**重新计算（HP 若仍低于 N%，就该死的时候死）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '无',
    射程: '自身',
    目标: '自身',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '被动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 9, 次要: 9, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我: 战斗单位, 敌: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我.id, 敌.id],
    单位: Object.fromEntries([我, 敌].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 锁血下限 0.15 = 最大HP 的 15%（150 血） */
const 锁血下限 = 造解释({
  规则: [
    { 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '锁血下限', 量: { 源: '常数', 系数: 0.15 } }] } as 规则,
  ],
});

/** 打一发（能打死的那种）；连续打两发时把冷却清掉 —— 这些用例只验锁血，不混冷却干扰 */
function 打(状态: 战斗状态, 目标键 = '骨卫兵') {
  const 状态2 = { ...状态, 单位: { ...状态.单位, 契约者: { ...状态.单位.契约者, 冷却: {} } } };
  const r = 结算行动(状态2, 状态2.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: 目标键 }, 骰);
  return { 状态: r.状态, 文本: r.步骤.map(s => s.内容).join('\n') };
}

describe('锁血下限 · 只在当前回合生效（玩家实测：锁在 15% 不死）', () => {
  // 攻方 STR 200 一阶 → 修正 195；徒手 1d4（注入 6）+ 伤害倍率 2：
  // 武器 ⌈(6+195)×0.5⌉ = 101；技能 ⌈195×2⌉ = 390 → 基础 491（守方 200 血，一发必然打穿到 0）
  const 开 = () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } },
      技能: { 斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 伤害倍率: 2 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 200, HP_最大: 1000, 技能: { 锁血下限 } });
    return 开战规则结算(造状态(我, 敌));
  };

  it('同一回合内：一次攻击把 HP 打穿到 15% 以下 → 锁在 15%（这一回合不死）', () => {
    const 状态 = 开();
    const r = 打(状态);

    // 1000 血 × 0.15 = 150；打穿到 150 以下 → 锁在 150
    expect(r.状态.单位.骨卫兵.HP_当前).toBe(150);
    expect(r.文本).toContain('锁血生效');
    expect(r.文本).toContain('15%');
  });

  it('**下一回合**：HP 仍低于 15% → 该死的时候死（不是又拉回 15%）', () => {
    let 状态 = 开();

    // 第一回合：打穿到 15% 以下 → 锁在 150
    const r1 = 打(状态);
    状态 = r1.状态;
    expect(状态.单位.骨卫兵.HP_当前).toBe(150);

    // 回合开始（阶段A）→ 锁血标记清掉
    状态 = 阶段A规则结算(状态, []);

    // 第二回合：再打一发 → 该死的时候死
    const r2 = 打(状态);
    expect(r2.状态.单位.骨卫兵.HP_当前).toBe(0);
  });

  it('没有「锁血下限」的单位 → 行为不变（该死的时候死）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } },
      技能: { 斩击: 造解释({ 行动消耗: '主要行动', 射程: '近战', 目标: '单体', 伤害倍率: 2 }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 200, HP_最大: 1000 });
    const 状态 = 开战规则结算(造状态(我, 敌));

    const r = 打(状态);

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(r.文本).not.toContain('锁血生效');
  });

  it('**同一回合**的下一击也能打死（锁的是"从线上打穿到线下"，不是"永远在线上"）', () => {
    let 状态 = 开();

    // 第一击：200 → 打穿到 150 以下 → 锁在 150
    const r1 = 打(状态);
    状态 = r1.状态;
    expect(状态.单位.骨卫兵.HP_当前).toBe(150);

    // 不经过阶段A，紧接着第二击：当前 HP 已在线下 → 锁血下限不再生效 → 死
    const r2 = 打(状态);
    expect(r2.状态.单位.骨卫兵.HP_当前).toBe(0);
  });
});
