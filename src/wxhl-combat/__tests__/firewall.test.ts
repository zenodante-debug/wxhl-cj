import { describe, expect, it } from 'vitest';
import { 开战规则结算, 跑一个回合, 结算行动, 词条_不可被常规攻击命中, 词条_禁位移 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 规则系防火墙（spec §3）—— 接线验收
//
// 设计口径（照世界书 <规则系能力判定>）：
//   判定值 = 1d20 + 关联属性修正
//   对抗目标 =（基础DC + 目标属性修正）× 类型系数 + 目标属性修正
// - 攻方**主动**的规则系效果必须过判定（没过当没这条）
// - 守方**被动**的规则系效果一直生效，只在被穿透/无视时参与对抗
// - 双方都过 → 拼属性修正值；持平 → 1d2（1=攻方，2=守方）
// **敌我一视同仁**，谁都没有"直接生效"的特权。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 30, PER: 40 } },
    阶位: '五阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 500,
    MP_最大: 500,
    耐力_当前: 200,
    耐力_最大: 200,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

function 技能(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

/** 攻方：STR 200 五阶 → STR修正 2145（足够过"弱"对手的判定，过不了"强"对手的） */
const 强攻 = (规则: 规则[] = []) =>
  造单位({ id: '契约者', 阵营: '我方', 属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } }, 技能: { 一击: 技能({ 规则 }) } });

/** 守方（弱）：一阶杂兵 CON 10 → 对抗目标 29 → 攻方必过 */
const 弱守 = (覆盖: Partial<战斗单位> = {}) =>
  造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', 阶位: '一阶', HP_当前: 100000, HP_最大: 100000, 属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } }, ...覆盖 });

/** 守方（强）：五阶 BOSS CON 200 → 对抗目标 7029 → 攻方必不过 */
const 强守 = (覆盖: Partial<战斗单位> = {}) =>
  造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: 'BOSS', HP_当前: 100000, HP_最大: 100000, 属性: { 实际: { STR: 10, AGI: 10, CON: 200, PER: 10 } }, ...覆盖 });

const 规则系 = (效果: string, 触发 = '使用时'): 规则 =>
  ({ 触发, 作用域: '攻击目标', 动作: [{ 类: '规则系判定', 效果, 目标: '攻击目标' }] }) as 规则;

/** 守方的常驻减伤（用来观察穿透是否跳过了它） */
const 常驻减伤 = (量: number): 规则 => ({ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '减伤', 量: { 源: '常数', 系数: 量 } }] });

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 打一发，返回（伤害, 步骤文本） */
function 打(守方: 战斗单位, 攻方规则: 规则[] = [], 注入 = {}) {
  const 攻 = 强攻(攻方规则);
  const 状态 = 开战规则结算(造状态(攻, 守方));
  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '一击', 目标: '骨卫兵' }, { ...骰, ...注入 });
  return { 伤害: 守方.HP_当前 - r.状态.单位.骨卫兵.HP_当前, 步骤: r.步骤.map(s => `[${s.类}] ${s.内容}`), 状态: r.状态 };
}

describe('规则系防火墙 · 攻方主动效果必须过判定', () => {
  it('**没声明规则系 → 完全不判定**（普通攻击照旧，不输出规则系日志）', () => {
    const r = 打(弱守({ 防御: 100 }));

    expect(r.伤害).toBeGreaterThan(0);
    expect(r.步骤.some(s => s.includes('规则系'))).toBe(false);
  });

  it('**穿透过了判定** → 防御 / 护盾 / 减伤全部跳过（伤害显著更高）', () => {
    const 有防御 = { 防御: 100, 护盾: 500, 技能: { 铁壁: 技能({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [常驻减伤(0.4)] }) } };
    const 无规则系 = 打(弱守(有防御));
    const 穿透 = 打(弱守(有防御), [规则系('穿透')]);

    expect(穿透.伤害).toBeGreaterThan(无规则系.伤害);
    expect(穿透.步骤.some(s => s.includes('规则系「穿透」') && s.includes('通过'))).toBe(true);
  });

  it('**穿透没过判定** → 当没这条，正常吃防御/护盾/减伤，且日志写明未通过', () => {
    const 有防御 = { 防御: 100, 护盾: 500 };
    const 无规则系 = 打(强守(有防御));
    const 穿透 = 打(强守(有防御), [规则系('穿透')]);

    expect(穿透.伤害).toBe(无规则系.伤害); // 一模一样
    expect(穿透.步骤.some(s => s.includes('未通过'))).toBe(true);
  });

  it('**必中**：闪避值高到普通攻击必失手 → 过了判定照样命中', () => {
    const 高闪 = 弱守({ 闪避值: 99999 });
    const 普通 = 打(高闪);
    const 必中 = 打(高闪, [规则系('必中')]);

    expect(普通.伤害).toBe(0); // 打不中
    expect(必中.伤害).toBeGreaterThan(0);
    expect(必中.步骤.some(s => s.includes('「必中」生效'))).toBe(true);
  });

  it('**即死**：过了判定 → 目标直接被抹杀', () => {
    const r = 打(弱守(), [规则系('即死')]);

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(r.步骤.some(s => s.includes('「即死」生效'))).toBe(true);
  });

  it('**无视** 可以打中带「不可被常规攻击命中」词条的目标', () => {
    // 没有规则系 → 常规攻击打不中
    const 无 = 打(弱守({ 词条: new Set([词条_不可被常规攻击命中]) }));
    expect(无.伤害).toBe(0);
    expect(无.步骤.some(s => s.includes('不可被常规攻击命中'))).toBe(true);

    // 穿透过了判定 → 打得中
    const 有 = 打(弱守({ 词条: new Set([词条_不可被常规攻击命中]) }), [规则系('穿透')]);
    expect(有.伤害).toBeGreaterThan(0);
  });
});

describe('规则系防火墙 · 守方被动一直生效，只在对抗时掷骰', () => {
  it('**无敌** 且攻方没有规则系 → 直接免伤（不用判定）', () => {
    const r = 打(弱守({ 技能: { 神域: 技能({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [规则系('无敌', '常驻')] }) } }));

    expect(r.伤害).toBe(0);
    expect(r.步骤.some(s => s.includes('「无敌」生效'))).toBe(true);
  });

  it('**穿透 vs 无敌**：攻方过、守方没过 → 攻方赢，伤害落地', () => {
    const 守 = 弱守({ 技能: { 神域: 技能({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [规则系('无敌', '常驻')] }) } });
    const r = 打(守, [规则系('穿透')]);

    expect(r.伤害).toBeGreaterThan(0);
    expect(r.步骤.some(s => s.includes('规则系对抗') && s.includes('攻击方'))).toBe(true);
  });

  it('**穿透 vs 无敌**：攻方没过判定（守方太高）→ 防御方赢（免伤）', () => {
    // ⚠️ 顺带记下一个**设计层发现**：照世界书公式，双方**同时**过判定在数学上不可能 ——
    //   攻方要过：攻修正 ≥ (基础DC + 守方修正)×守系数 + 守方修正
    //   守方要过：守修正 ≥ (基础DC + 攻修正)×攻系数 + 攻修正
    //   两式联立对正的修正值无解（对 DC 的要求互相矛盾）。所以 §3.4 的「拼修正值 / 1d2」
    //   实际只在 规则系对抗() 这个纯函数层面可达，实战里几乎不会触发。
    //   这条测试断言的因此是**实际会发生**的分支：一方过、另一方没过。
    // 守方 CON 1000 五阶 → CON修正 10945，远高于攻方 STR修正 2145
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      类型: '杂兵',
      阶位: '五阶',
      HP_当前: 100000,
      HP_最大: 100000,
      属性: { 实际: { STR: 10, AGI: 10, CON: 1000, PER: 10 } },
      技能: { 神域: 技能({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [规则系('无敌', '常驻')] }) },
    });

    const r = 打(守, [规则系('穿透')]);

    expect(r.伤害).toBe(0);
    expect(r.步骤.some(s => s.includes('「无敌」生效'))).toBe(true);
  });

  it('**锁血**：守方被动生效 → HP 锁在 1（打不死）', () => {
    const 守 = 弱守({
      HP_当前: 5,
      HP_最大: 5,
      技能: { 不灭: 技能({ 行动消耗: '无', 类型: '被动', 伤害倍率: 0, 规则: [规则系('锁血', '常驻')] }) },
    });

    const r = 打(守);

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(1);
    expect(r.步骤.some(s => s.includes('「锁血」生效'))).toBe(true);
  });
});

describe('规则系防火墙 · 与引擎其它部分的衔接', () => {
  it('「不可被常规攻击命中」是**词条**，不需要判定；穿透才需要', () => {
    const 守 = 弱守({ 词条: new Set([词条_不可被常规攻击命中]) });
    const r = 打(守);

    expect(r.步骤.some(s => s.includes('跳过'))).toBe(true);
    expect(r.步骤.some(s => s.includes('规则系「穿逤」'))).toBe(false);
  });

  it('「禁位移」词条：移动被跳过', () => {
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 词条: new Set([词条_禁位移]) });
    const 守 = 弱守();
    const 状态 = 造状态(攻, 守);

    const r = 跑一个回合(状态, { 契约者: [{ 类型: '移动', 距离: 30 }] }, []);

    expect(r.状态.单位.契约者.距离).toBe(0); // 没动
    expect(r.步骤.some(s => s.内容.includes('禁位移'))).toBe(true);
  });

  it('日志里能看出"谁过了判定、对抗谁赢了"（玩家要能读懂引擎为什么这么判）', () => {
    const r = 打(弱守(), [规则系('穿透'), 规则系('即死')]);

    const 规则系行 = r.步骤.filter(s => s.includes('规则系'));
    expect(规则系行.length).toBeGreaterThan(0);
    expect(规则系行.some(s => s.includes('判定'))).toBe(true);
    expect(规则系行.some(s => s.includes('对抗目标'))).toBe(true);
  });
});
