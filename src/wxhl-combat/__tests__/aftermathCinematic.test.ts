describe('持久化 · 开战前的上下文与开场模式（收尾要用）', () => {
  it('快照带上 开战前上下文 / 开场模式，恢复读得回来', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方' });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 快照 = 构建战斗状态快照(造状态([我, 敌]), {
      意图模式: '随机',
      日志: ['x'],
      开战前上下文: '月台的积水上浮着一层灰。骨卫兵从阴影里站了起来。',
      开场模式: '对峙/室内',
    });
    const 恢复 = 恢复战斗状态(快照);

    expect(恢复?.开战前上下文).toContain('月台的积水');
    expect(恢复?.开场模式).toBe('对峙/室内');
  });

  it('老存档（没有这两个字段）→ 给空串/undefined，不崩（向后兼容）', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方' });

    const 恢复 = 恢复战斗状态(构建战斗状态快照(造状态([我]), { 意图模式: 'ai' }));

    expect(恢复?.开战前上下文).toBe('');
    expect(恢复?.开场模式).toBe('');
  });

  // 玩家实测（2026-10-10）：「从持久化恢复战斗，会取消掉之前敌人的意图，导致没有行动」——
  // 早先只存了状态/意图模式/日志，**没存敌方意图**，重开面板后它是空的，下一回合敌人直接空过。
  it('**敌方意图也要存**，恢复读得回来（否则重开面板后敌人空过）', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方' });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 意图 = [{ 单位: '骨卫兵', 行动: [{ 类型: '主要行动' as const, 技能: '骨爪撕裂', 目标: '契约者' }] }];

    const 恢复 = 恢复战斗状态(
      构建战斗状态快照(造状态([我, 敌]), { 意图模式: '随机', 敌方意图: 意图 }),
    );

    expect(恢复?.敌方意图).toEqual(意图);
  });

  it('老存档没有敌方意图 → 给空数组（下一回合照常生成，不炸）', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方' });

    const 恢复 = 恢复战斗状态(构建战斗状态快照(造状态([我]), { 意图模式: 'ai' }));

    expect(恢复?.敌方意图).toEqual([]);
  });
});

describe('收尾提示词 · 五段输入与新口径', () => {
  const 我 = 造单位({
    id: '契约者',
    名称: '青空黎',
    阵营: '我方',
    技能: { 龟派气功·超绝: 解释({ 伤害倍率: 7.75 }), 没用过的技能: 解释() },
  });
  const 队友 = 造单位({ id: '小队.成员.江薇芷', 名称: '江薇芷', 阵营: '我方', 类型: '小队成员' });
  const 敌 = 造单位({ id: '副本角色.骨卫兵', 名称: '骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 0 });
  const 状态 = 造状态([我, 队友, 敌]);
  const 战报 = [步骤('「青空黎」的「龟派气功·超绝」命中「骨卫兵」（18 ≥ 12）')];

  const 提示词 = 构建收尾提示词(战报, 状态, {
    开战前上下文: '月台的积水上浮着一层灰。骨卫兵从阴影里站了起来。',
    开场模式: '对峙/室内',
  });

  it('五段都在：开战前的上下文 / 参战者 / 用到的技能与效果 / 战报 / 杀戮掉落', () => {
    expect(提示词).toContain('开战前的上下文');
    expect(提示词).toContain('月台的积水'); // 环境真的进来了
    expect(提示词).toContain('对峙/室内'); // 开场模式
    expect(提示词).toContain('参战者');
    expect(提示词).toContain('用到的技能与效果');
    expect(提示词).toContain('战斗战报');
    expect(提示词).toContain('击杀与掉落');
  });

  it('用到的技能带上**人话效果**；没用到的**不在里面**（省 token）', () => {
    expect(提示词).toContain('龟派气功·超绝');
    expect(提示词).toContain('伤害'); // 效果人话（效果预览）
    expect(提示词).not.toContain('没用过的技能');
  });

  it('第三方解说写进要求（并点明依据是效果人话，不是念名字）', () => {
    expect(提示词).toContain('第三方解说');
    expect(提示词).toMatch(/JOJO|咒术回战/);
    expect(提示词).toMatch(/不是念技能名|不是只念名字/);
  });

  it('心理边界：敌人队友重点写、玩家角色不写（点名主角）', () => {
    expect(提示词).toMatch(/敌人与队友[\s\S]{0,40}重点写/);
    expect(提示词).toMatch(/青空黎[\s\S]{0,60}不写心理|不写心理[\s\S]{0,60}青空黎|玩家角色[\s\S]{0,40}不写心理/);
  });

  it('事实边界两句都在：结果不许改 / 画面自由写', () => {
    expect(提示词).toContain('结果不许改');
    expect(提示词).toContain('画面自由写');
    expect(提示词).not.toContain('不要自己加战报里没有的'); // 那句禁令是复述的病根，必须删掉
  });

  it('没有上一楼上下文时，明确写「无」而不是留空（模型不会瞎补环境）', () => {
    const 无 = 构建收尾提示词(战报, 状态, {});

    expect(无).toMatch(/开战前的上下文[\s\S]{0,80}无/);
  });
});

// ================================================================
// 开战前的上下文：从酒馆读「上一楼正文」
// 玩家口径：「把模型输入的开战前的上一楼正文发过来呗」
// ================================================================
describe('读上一楼正文（开战前抓一次）', () => {
  const 装楼层 = (楼层表: Record<number, { role: string; message: string }>) => {
    (globalThis as any).getChatMessages = (深度: number) => {
      const 条 = 楼层表[深度];
      return 条 ? [条] : [];
    };
  };

  it('取最后一条 assistant 消息', async () => {
    const { 读上一楼正文 } = await import('../store');
    装楼层({ [-1]: { role: 'assistant', message: '月台的积水上浮着一层灰。' } });

    expect(await 读上一楼正文()).toContain('月台的积水');
  });

  it('最后一楼是玩家自己的发言 → 往前找（最多 3 楼）', async () => {
    const { 读上一楼正文 } = await import('../store');
    装楼层({
      [-1]: { role: 'user', message: '我砍过去。' },
      [-2]: { role: 'assistant', message: '骨卫兵从阴影里站了起来。' },
    });

    expect(await 读上一楼正文()).toContain('骨卫兵从阴影里站了起来');
  });

  it('**剥掉 MVU 变量块**（那是引擎的账本，不是场景）', async () => {
    const { 读上一楼正文 } = await import('../store');
    装楼层({
      [-1]: {
        role: 'assistant',
        message: '夜色压在走廊尽头。\n<status_current_variable>\n契约者:\n  头部:\n    姓名: 青空黎\n</status_current_variable>\n他握紧了刀。',
      },
    });

    const 文 = await 读上一楼正文();

    expect(文).toContain('夜色压在走廊尽头');
    expect(文).toContain('他握紧了刀');
    expect(文).not.toContain('status_current_variable');
    expect(文).not.toContain('青空黎'); // 变量块里的名字也不该漏进来
  });

  it('超长 → 截断到 3000 字（防撑爆提示词）', async () => {
    const { 读上一楼正文 } = await import('../store');
    装楼层({ [-1]: { role: 'assistant', message: '很长的正文。'.repeat(1000) } });

    expect((await 读上一楼正文()).length).toBeLessThanOrEqual(3000);
  });

  it('一层都没有 / API 不可用 → 空串（收尾提示词会写「（无）」）', async () => {
    const { 读上一楼正文 } = await import('../store');
    (globalThis as any).getChatMessages = () => {
      throw new Error('不在楼层里');
    };

    expect(await 读上一楼正文()).toBe('');
  });
});
