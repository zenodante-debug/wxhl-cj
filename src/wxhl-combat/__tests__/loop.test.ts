import { describe, expect, it } from 'vitest';
import { 跑敌方意图 } from '../engine/loop';
import type { 战斗状态, 战斗解释 } from '../types';

/** 造一个最简战斗解释（只有被 跑敌方意图 用到的是「技能名存在」这一点）。 */
function 造解释(): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    规则: [],
    托管: [],
  };
}

function 造状态(): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: ['骨卫兵', '契约者'],
    单位: {
      骨卫兵: { id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', 属性: { 实际: { STR: 18, AGI: 8, CON: 16, PER: 6 } }, 阶位: '一阶', HP_当前: 120, HP_最大: 120, MP_当前: 20, MP_最大: 20, 耐力_当前: 80, 耐力_最大: 80, 防御: 5, 闪避值: 10, 距离: 10, 行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 }, 额度: 45, 冷却: {}, 护盾: 0, 架势: null, 状态: [], 濒死: null, 资源: {}, 词条: new Set(), 技能: { 骨爪撕裂: 造解释() } },
      契约者: { id: '契约者', 阵营: '我方', 类型: '玩家', 属性: { 实际: { STR: 25, AGI: 20, CON: 20, PER: 15 } }, 阶位: '二阶', HP_当前: 100, HP_最大: 100, MP_当前: 50, MP_最大: 50, 耐力_当前: 100, 耐力_最大: 100, 防御: 0, 闪避值: 10, 距离: 0, 行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 }, 额度: 45, 冷却: {}, 护盾: 0, 架势: null, 状态: [], 濒死: null, 资源: {}, 词条: new Set(), 技能: {} },
    },
    待决: null,
    领域: [],
  };
}

describe('loop · 敌方意图执行', () => {
  it('意图引用了不存在的目标 → 跳过该行动并记日志（Review Focus 4）', () => {
    const 状态 = 造状态();
    const 意图 = [{ 单位: '副本角色.骨卫兵', 行动: [{ 类型: '主要行动' as const, 技能: '不存在', 目标: '不存在的单位' }] }];

    const { 步骤 } = 跑敌方意图(状态, 意图);

    expect(步骤.some(s => s.内容.includes('跳过'))).toBe(true);
  });

  it('意图里的技能不在该单位技能表 → 跳过该行动并记日志（Review Focus 4 / R7）', () => {
    const 状态 = 造状态();
    const 意图 = [{ 单位: '骨卫兵', 行动: [{ 类型: '主要行动' as const, 技能: '不存在的技能', 目标: '玩家' }] }];

    const { 步骤 } = 跑敌方意图(状态, 意图);

    expect(步骤.some(s => s.内容.includes('跳过'))).toBe(true);
    expect(步骤.some(s => s.类 === '敌方行动')).toBe(false);
  });

  it('意图里的单位不在战场上 → 跳过并记日志', () => {
    const 状态 = 造状态();
    const 意图 = [{ 单位: '不在场上', 行动: [{ 类型: '移动' as const, 目标: '契约者', 距离: 0 }] }];

    const { 步骤 } = 跑敌方意图(状态, 意图);

    expect(步骤.some(s => s.内容.includes('跳过'))).toBe(true);
  });

  it('目标写作「玩家」→ 解析到契约者本体，不跳过而是执行行动（happy path）', () => {
    const 状态 = 造状态();
    const 意图 = [{ 单位: '骨卫兵', 行动: [{ 类型: '主要行动' as const, 技能: '骨爪撕裂', 目标: '玩家' }] }];

    const { 步骤 } = 跑敌方意图(状态, 意图);

    expect(步骤.some(s => s.内容.includes('跳过'))).toBe(false);
    expect(步骤.some(s => s.类 === '敌方行动')).toBe(true);
  });

  it('单位引用一律精确匹配 → 用「卫兵」不能误配到「副本角色.骨卫兵」', () => {
    const 状态 = 造状态();
    const 意图 = [{ 单位: '卫兵', 行动: [{ 类型: '移动' as const, 目标: '契约者', 距离: 0 }] }];

    const { 步骤 } = 跑敌方意图(状态, 意图);

    expect(步骤.some(s => s.内容.includes('跳过'))).toBe(true);
  });
});
