import { describe, expect, it } from 'vitest';
import {
  判定战局,
  标记濒死,
  已稳定,
  已死亡,
  濒死检定一轮,
  阶段F结算,
  能行动,
} from '../engine/turn';
import { 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 生死判定（世界书原文）
//   健康 >70%：无惩罚。  受伤 30~70%：剧烈动作劣势。
//   重伤 1~30%：STR/AGI 劣势、移动减半。
//   濒死 0：每回合 CON 判定 DC12，2 次成功稳定 / 3 次失败死亡。
//   生死界限：HP 归零即进入濒死判定。失败达三次即宣告抹杀。
//
// 实战反馈的 bug：玩家 HP 一归零就被判「败北」直接结算 —— 世界书里那是**濒死**，
// 要连续三次失败才算抹杀。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 0,
    MP_最大: 0,
    耐力_当前: 0,
    耐力_最大: 0,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 0,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(单位: 战斗单位[]): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: 单位.map(u => u.id),
    单位: Object.fromEntries(单位.map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

describe('标记濒死 · HP 归零即进入濒死（不是死亡）', () => {
  it('HP 归零且还没有标记 → 打上 0/0 计数', () => {
    const u = 标记濒死(造单位({ id: '契约者', 阵营: '我方', HP_当前: 0 }));
    expect(u.濒死).toEqual({ 成功: 0, 失败: 0 });
  });

  it('HP 还大于 0 → 不动', () => {
    expect(标记濒死(造单位({ id: '契约者', 阵营: '我方' })).濒死).toBeNull();
  });

  it('已有计数 → 不覆盖（失败次数不能被重置）', () => {
    const u = 标记濒死(造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 1, 失败: 2 } }));
    expect(u.濒死).toEqual({ 成功: 1, 失败: 2 });
  });
});

describe('濒死检定一轮 · 每回合 DC12', () => {
  it('成功两次 → 稳定（脱离濒死，仍昏迷在 0 HP）', () => {
    const u = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 1, 失败: 0 } });
    const r = 濒死检定一轮(u, 15); // 15 + CON修正(15) ≥ 12

    expect(r!.结果).toBe('稳定');
    expect(r!.单位.濒死).toBeNull();
    expect(已稳定(r!.单位)).toBe(true);
    expect(r!.文本).toContain('脱离');
  });

  it('CON 高的人很难失败：骰 1 + CON修正 15 = 16 ≥ 12 仍是成功', () => {
    const u = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } });
    expect(濒死检定一轮(u, 1)!.结果).toBe('濒死'); // 成功 1/2，还没稳定
  });

  it('失败三次 → 死亡（抹杀）', () => {
    const 低CON = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 0,
      濒死: { 成功: 0, 失败: 2 },
      属性: { 实际: { STR: 5, AGI: 5, CON: 5, PER: 5 } },
    });
    const r = 濒死检定一轮(低CON, 1); // 1 + 0 = 1 < DC12

    expect(r!.结果).toBe('死亡');
    expect(已死亡(r!.单位)).toBe(true);
    expect(r!.文本).toContain('死亡');
  });

  it('成功/失败还没到上限 → 继续濒死，日志里带计数', () => {
    const u = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 }, 属性: { 实际: { STR: 5, AGI: 5, CON: 5, PER: 5 } } });
    const r = 濒死检定一轮(u, 5);

    expect(r!.结果).toBe('濒死');
    expect(r!.文本).toContain('成功 0/2');
    expect(r!.文本).toContain('失败 1/3');
  });

  it('HP > 0 / 已稳定 / 已死亡 → 不检定（返回 null）', () => {
    expect(濒死检定一轮(造单位({ id: '契约者', 阵营: '我方' }))).toBeNull();
    expect(濒死检定一轮(造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: null }))).toBeNull();
    expect(
      濒死检定一轮(造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 0, 失败: 3 } })),
    ).toBeNull();
  });

  it('阶位写错也不抛错（宽容修正）', () => {
    const u = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 }, 阶位: '六阶（写错了）' });
    expect(() => 濒死检定一轮(u, 5)).not.toThrow();
  });
});

describe('能行动 / 已稳定 / 已死亡', () => {
  it('HP > 0 才能行动；濒死/稳定/死亡都不能', () => {
    expect(能行动(造单位({ id: '甲', 阵营: '我方', HP_当前: 1 }))).toBe(true);
    expect(能行动(造单位({ id: '甲', 阵营: '我方', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } }))).toBe(false);
    expect(能行动(造单位({ id: '甲', 阵营: '我方', HP_当前: 0, 濒死: null }))).toBe(false);
  });
});

describe('判定战局 · 归零不等于败北（实战 bug）', () => {
  const 敌 = () => 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 80 });

  it('**契约者 HP 归零但还在濒死检定中 → 不判败北，继续打**', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } }),
      敌(),
    ]);

    expect(判定战局(状态)).toBeNull();
  });

  it('契约者濒死检定失败三次（抹杀）→ 败北', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 0, 濒死: { 成功: 0, 失败: 3 } }),
      敌(),
    ]);

    expect(判定战局(状态)).toBe('败北');
  });

  it('契约者倒下了但队友还能打 → 继续打（不是败北）', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 0, 濒死: { 成功: 0, 失败: 1 } }),
      造单位({ id: '小队.成员.江薇芷', 阵营: '我方', HP_当前: 50 }),
      敌(),
    ]);

    expect(判定战局(状态)).toBeNull();
  });

  it('我方全员倒下且都稳定了（全员昏迷，打不下去）→ 败北', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 0, 濒死: null }),
      敌(),
    ]);

    expect(判定战局(状态)).toBe('败北');
  });

  it('敌方全部不能行动 → 胜利', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 30 }),
      造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 0, 濒死: { 成功: 0, 失败: 0 } }),
    ]);

    expect(判定战局(状态)).toBe('胜利');
  });

  it('两边都还站着 → 继续', () => {
    expect(判定战局(造状态([造单位({ id: '契约者', 阵营: '我方' }), 敌()]))).toBeNull();
  });

  it('缺一方（只有自己一个人的空战场）→ 不判定', () => {
    expect(判定战局(造状态([造单位({ id: '契约者', 阵营: '我方' })]))).toBeNull();
  });
});

describe('端到端：被打到 0 血 → 状态是濒死，不是死亡', () => {
  const 攻击: 战斗解释 = {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
  };

  it('伤害把目标打到 0 时自动打上濒死标记', () => {
    const 状态 = 造状态([
      造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 5, HP_最大: 5, 闪避值: 0, 技能: {} }),
      造单位({
        id: '副本角色.骨卫兵',
        阵营: '敌方',
        HP_当前: 100,
        属性: { 实际: { STR: 40, AGI: 10, CON: 10, PER: 10 } },
        技能: { 重击: 攻击 },
      }),
    ]);

    const r = 结算行动(状态, 状态.单位['骨卫兵'], { 类型: '主要行动', 技能: '重击', 目标: '契约者' }, { 命中: 20, 伤害骰: [6] });

    expect(r.状态.单位.契约者.HP_当前).toBe(0);
    expect(r.状态.单位.契约者.濒死).toEqual({ 成功: 0, 失败: 0 });
    expect(判定战局(r.状态)).toBeNull(); // 还在濒死检定中 → 不判败北
  });

  it('持续伤害（阶段F）打到 0 也会打上濒死标记', () => {
    const u = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 3, HP_最大: 100, 状态: [{ 名: '灼烧', 持续: 2, 层数: 1 }] });
    const r = 阶段F结算(u, 100);

    expect(r.新状态.HP_当前).toBe(0);
    expect(r.新状态.濒死).toEqual({ 成功: 0, 失败: 0 });
  });
});
