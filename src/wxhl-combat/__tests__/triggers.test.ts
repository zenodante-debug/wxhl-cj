import { describe, expect, it } from 'vitest';
import { 开战规则结算, 阶段A规则结算, 阶段F规则结算, 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 补齐的触发点 + 条件词汇 + 修正目标
//
// 玩家点名的例子（重骑士）：**血量低于 50% 时才能发动**，发动后**清空防御、换成等量 STR 与 AGI**。
// 这条同时卡在三处，缺一处都写不出来：
//   1. 条件里读不到自己的 HP  → 补 表达式标识符 当前HP / HP比例
//   2. 没有「防御」这个修正目标 → 补 数值修正目标 防御
//   3. 没有四维属性目标       → 补 STR/AGI/CON/PER（属性点，引擎按位阶系数换算）
// 另外把剩下四个触发点（进入战斗 / 回合结束 / 击杀时 / 资源变化时）接上，
// 「攻击时」在攻击路径上等于「使用时」。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 30, PER: 40 } },
    阶位: '五阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 500,
    MP_最大: 500,
    耐力_当前: 200,
    耐力_最大: 200,
    防御: 50,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位[], 敌方: 战斗单位[] = []): 战斗状态 {
  const 全部 = [...我方, ...敌方];
  return {
    进行中: true,
    回合: 1,
    先攻: 全部.map(u => u.id),
    单位: Object.fromEntries(全部.map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

function 技能(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

const 骰 = { 命中: 20, 伤害骰: [6] };

/** 重骑士：血量低于 50% 才能发动；清空防御，换成等量 STR 与 AGI */
const 血怒 = 技能({
  目标: '自身',
  射程: '自身',
  类型: '辅助',
  伤害倍率: 0,
  规则: [
    {
      触发: '使用时',
      条件: { 左: { 源: '表达式', 式: 'HP比例' }, 比较: '<', 右: { 源: '常数', 系数: 0.5 } },
      作用域: '自身',
      动作: [
        { 类: '数值修正', 目标: '防御', 量: { 源: '表达式', 式: '0 - 防御' } },
        { 类: '数值修正', 目标: 'STR', 量: { 源: '表达式', 式: '防御' } },
        { 类: '数值修正', 目标: 'AGI', 量: { 源: '表达式', 式: '防御' } },
      ],
    } as 规则,
  ],
});

describe('重骑士 · 血量低于 50% 才能发动，清空防御换等量 STR/AGI', () => {
  it('血量 100% → **条件不满足**，一条修正都不落，且日志说得出来', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 血怒 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 造状态([甲], [敌]);

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '血怒', 目标: '骨卫兵' });

    expect(r.状态.单位.契约者.状态).toHaveLength(0);
    expect(r.步骤.some(s => s.内容.includes('条件不满足'))).toBe(true);
  });

  it('血量 40% → 发动：防御清零、STR/AGI 各拿到等量的属性点', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 400, 技能: { 血怒 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 造状态([甲], [敌]);

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '血怒', 目标: '骨卫兵' });
    const 修正 = r.状态.单位.契约者.状态[0]?.数值修正;

    expect(修正?.防御).toBe(-50); // 清空防御（量 = 0 − 防御）
    expect(修正?.STR).toBe(50); // 等量属性点
    expect(修正?.AGI).toBe(50);
  });

  it('换来的属性点**真的进伤害**（不是只写在状态里看）', () => {
    const 打一发 = (开血怒: boolean) => {
      const 甲 = 造单位({
        id: '契约者',
        阵营: '我方',
        HP_当前: 400,
        技能: { 血怒: 开血怒 ? 血怒 : 技能({ 目标: '自身', 射程: '自身', 类型: '辅助', 伤害倍率: 0 }), 重击: 技能() },
      });
      const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 100000, HP_最大: 100000, 防御: 50, 闪避值: 0 });
      let 状态 = 造状态([甲], [敌]);
      if (开血怒) {
        状态 = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '血怒', 目标: '骨卫兵' }).状态;
        // 模拟下一回合：行动槽与冷却重置（否则第二发攻击会被"槽已用尽"挡掉）
        状态.单位.契约者.行动槽 = { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 };
        状态.单位.契约者.冷却 = {};
      }
      const 攻击者 = 状态.单位.契约者;
      攻击者.技能.重击 = 技能();
      return 100000 - 结算行动(状态, 攻击者, { 类型: '主要行动', 技能: '重击', 目标: '骨卫兵' }, 骰).状态.单位.骨卫兵.HP_当前;
    };

    const 未开 = 打一发(false);
    const 开了 = 打一发(true);

    expect(未开).toBeGreaterThan(0);
    expect(开了).toBeGreaterThan(未开); // STR/AGI 变大 + 对方防御被清（这里吃的是自己的防御清空）
  });
});

describe('补齐的四个触发点', () => {
  const 打出 = (触发: string, 动作: any[]) =>
    技能({ 规则: [{ 触发, 作用域: '自身', 动作 } as 规则] });

  it('**进入战斗**：开战就生效（进场护盾）', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: { 装甲展开: 打出('进入战斗', [{ 类: '护盾', 量: { 源: '常数', 系数: 300 } }]) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const r = 开战规则结算(造状态([甲], [敌]));

    expect(r.单位.契约者.护盾).toBe(300);
  });

  it('**回合结束**：阶段F 才结算（每回合收尾回复）', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 500,
      技能: { 再生: 打出('回合结束', [{ 类: '资源', 名: 'HP回复', 操作: '获得', 量: { 源: '常数', 系数: 25 } }]) },
    });
    const 状态 = 造状态([甲]);

    const r = 阶段F规则结算(状态);

    expect(r.单位.契约者.资源.HP回复).toBe(25);
    expect(状态.单位.契约者.资源.HP回复).toBeUndefined(); // 纯函数，不改入参
  });

  it('**击杀时**：把目标打倒的人拿到东西', () => {
    const 甲 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 血饮: 技能({ 规则: [{ 触发: '击杀时', 作用域: '自身', 动作: [{ 类: '资源', 名: '渴血', 操作: '获得', 量: { 源: '常数', 系数: 1 } }] } as 规则] }) } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '杂兵', HP_当前: 10, HP_最大: 10, 防御: 0, 闪避值: 0 });
    const 状态 = 造状态([甲], [敌]);

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '血饮', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(r.状态.单位.契约者.资源.渴血).toBe(1);
    expect(r.步骤.some(s => s.内容.includes('击倒'))).toBe(true);
  });

  it('**资源变化时**：挨打掉血后触发，且条件用 HP比例 判断', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      HP_当前: 1000,
      技能: {
        不屈: 技能({
          规则: [
            {
              触发: '资源变化时',
              条件: { 左: { 源: '表达式', 式: 'HP比例' }, 比较: '<', 右: { 源: '常数', 系数: 0.9 } },
              作用域: '自身',
              动作: [{ 类: '施加状态', 名: '不屈', 持续: 3 }],
            } as 规则,
          ],
        }),
      },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 技能: { 骨爪: 技能({ 关联属性: 'STR', 伤害倍率: 1 }) } });
    const 状态 = 造状态([甲], [敌]);

    const r = 结算行动(状态, 状态.单位.骨卫兵, { 类型: '主要行动', 技能: '骨爪', 目标: '契约者' }, 骰);

    expect(r.状态.单位.契约者.HP_当前).toBeLessThan(1000);
    expect(r.状态.单位.契约者.状态.some(s => s.名 === '不屈')).toBe(true);
  });

  it('**攻击时** = 使用时（同一个时机，卡面两种写法都认）', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: { 突袭: 技能({ 规则: [{ 触发: '攻击时', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '常数', 系数: 1 } }] } as 规则] }) },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 100000, HP_最大: 100000, 防御: 0, 闪避值: 0 });
    const 状态 = 造状态([甲], [敌]);

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '突袭', 目标: '骨卫兵' }, 骰);

    expect(r.步骤.some(s => s.内容.includes('终伤倍率 2'))).toBe(true);
  });

  it('回合开始 / 回合结束 是**两个不同时机**（各跑各的）', () => {
    const 甲 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: {
        晨星: 打出('回合开始', [{ 类: '资源', 名: '开始', 操作: '获得', 量: { 源: '常数', 系数: 1 } }]),
        暮星: 打出('回合结束', [{ 类: '资源', 名: '结束', 操作: '获得', 量: { 源: '常数', 系数: 1 } }]),
      },
    });
    const 状态 = 造状态([甲]);

    const A = 阶段A规则结算(状态);
    const F = 阶段F规则结算(状态);

    expect(A.单位.契约者.资源.开始).toBe(1);
    expect(A.单位.契约者.资源.结束).toBeUndefined();
    expect(F.单位.契约者.资源.结束).toBe(1);
    expect(F.单位.契约者.资源.开始).toBeUndefined();
  });
});
