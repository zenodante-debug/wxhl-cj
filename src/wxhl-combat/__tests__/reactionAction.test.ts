import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动, 守方反应技能, 敌方反应预置, 词条_打断 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 反应动作真正结算（玩家本轮反馈）：
//   「1，反应动作。当前的反应动作选了完全没用，也不会实现」
//   「2，反应动作不应该是有预设的那些反应动作，必须是技能的类型是反应动作才算上。
//      取消预设的反应动作，必须要自己学。」
//   「5，有预置就自动用」「6，预置就自动用，没预置就跳过」
//
// 世界书 <核心战斗系统>【第五步敌方反应动作防御】：
//   - 打断类（击溃/识破）：打断检定 = 1d20 + 对应属性修正×3/4（下取整），**以劣势进行**，
//     与攻击方命中检定对抗；成功 → 本次攻击取消；失败 → 攻击照常结算 + 攻击方本回合命中 +2。
//   - 防御类（招架 STR / 闪避 AGI / 格挡 CON / 闪烁 PER）：防御判定值与命中检定对抗，
//     成功则减伤/护盾/反伤。减伤上限 50%、同类不叠加。
//
// 以前这两条全是空转：`预置反应` 只被拼进一句日志，没有任何结算路径读它。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 100,
    MP_最大: 100,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    移动距离: 30,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 数值 = (目标: string, 量: number) => ({
  类: '数值修正' as const,
  目标: target(目标),
  量: { 源: '常数' as const, 系数: 量 },
});
const target = (t: string) => t as any;

/** 防御类反应技能：使用时给自己减伤 */
const 招架 = (减伤量 = 0.3) =>
  造解释({
    行动消耗: '反应动作',
    伤害倍率: 0,
    规则: [{ 触发: '使用时', 作用域: '自身', 动作: [数值('减伤', 减伤量)] } as 规则],
  });

/** 打断类反应技能：带约定词条「打断」 */
const 击溃 = () =>
  造解释({
    行动消耗: '反应动作',
    伤害倍率: 0,
    规则: [
      {
        触发: '使用时',
        作用域: '自身',
        动作: [{ 类: '词条', 名: 词条_打断 } as any],
      } as 规则,
    ],
  });

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 攻方打一发（守方是 骨卫兵），返回伤害与步骤 */
function 打(守方: 战斗单位, 注入: any = {}) {
  const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释({ 伤害倍率: 1 }) } });
  const 状态 = 开战规则结算(造状态(攻, 守方));
  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, { ...骰, ...注入 });
  return { 伤害: 守方.HP_当前 - r.状态.单位.骨卫兵.HP_当前, 步骤: r.步骤.map(s => `[${s.类}] ${s.内容}`), 状态: r.状态 };
}

describe('反应动作 · 「必须自己学」（取消预设）', () => {
  it('没预置 → 完全不反应（连日志都没有）', () => {
    const r = 打(造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));

    expect(r.伤害).toBeGreaterThan(0);
    expect(r.步骤.some(s => s.includes('反应'))).toBe(false);
  });

  it('预置了一个**没学过**的名字（旧预设的「招架」）→ 不反应', () => {
    const r = 打(造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 预置反应: '招架' }));

    expect(r.步骤.some(s => s.includes('使用反应动作'))).toBe(false);
    expect(守方反应技能(造单位({ id: 'x', 阵营: '敌方', 预置反应: '招架' }))).toBeUndefined();
  });

  it('学过、但**行动类型不是反应动作**的技能 → 不能拿来反应', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '重击',
      技能: { 重击: 造解释({ 行动消耗: '主要行动' }) },
    });

    expect(守方反应技能(守)?.名).toBeUndefined();
    expect(打(守).步骤.some(s => s.includes('使用反应动作'))).toBe(false);
  });

  it('行动类型是反应动作的**已学**技能 → 认（这是唯一准入条件）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      技能: { 招架: 招架() },
    });

    expect(守方反应技能(守)?.名).toBe('招架');
  });

  it('反应槽用尽 / 冷却中 → 用不了', () => {
    const 无槽 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      技能: { 招架: 招架() },
      行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 0, 免费: 999 },
    });
    const 冷却中 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      技能: { 招架: 招架() },
      冷却: { 招架: 2 },
    });

    expect(守方反应技能(无槽)).toBeUndefined();
    expect(守方反应技能(冷却中)).toBeUndefined();
  });
});

describe('反应动作 · 防御类真的减伤', () => {
  it('预置「招架」（减伤 30%）→ 伤害明显变小，且扣反应槽、进冷却', () => {
    const 无反应 = 打(造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      技能: { 招架: 招架(0.3) },
    });
    const 有反应 = 打(守);

    expect(有反应.伤害).toBeLessThan(无反应.伤害);
    expect(有反应.步骤.some(s => s.includes('反应防御'))).toBe(true);
    expect(有反应.状态.单位.骨卫兵.行动槽.反应).toBe(0); // 消耗一个反应槽
    expect(有反应.状态.单位.骨卫兵.冷却.招架).toBeGreaterThanOrEqual(1); // 进冷却
  });

  it('减伤**封顶 50%**（世界书：减伤/反伤最高 50%）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      技能: { 招架: 招架(0.9) },
    });
    const r = 打(守);

    expect(r.步骤.some(s => s.includes('减伤 50%'))).toBe(true);
  });

  it('资源不足 → 用不出反应（并说明原因，不是静默）', () => {
    const 守 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      预置反应: '招架',
      耐力_当前: 1,
      技能: { 招架: 招架(0.3) },
    });
    守.技能.招架.消耗 = '耐力 10';

    const r = 打(守);

    expect(r.步骤.some(s => s.includes('耐力不足'))).toBe(true);
    expect(r.状态.单位.骨卫兵.行动槽.反应).toBe(1); // 没扣槽（没真的用出去）
  });
});

describe('反应动作 · 打断类取消攻击（世界书第五步）', () => {
  /**
   * 打断值 = 骰 + ⌊关联属性修正×0.75⌋，要 ≥ 攻方命中检定值。
   * 攻方（STR 20 / AGI 10，一阶）：18 + 15×1.2 + 5×0.2 = **37**。
   * → 守方得够强才打断得动：STR 60 一阶 → 修正 55 → ⌊41.25⌋=41，骰 20 → 61 ≥ 37 ✔
   */
  const 守 = (力量 = 20) =>
    造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      属性: { 实际: { STR: 力量, AGI: 10, CON: 20, PER: 10 } },
      预置反应: '击溃',
      技能: { 击溃: 击溃() },
    });

  it('打断**成功** → 本次攻击取消（一点伤害都没有）', () => {
    const r = 打(守(60), { 反应: 20 });

    expect(r.伤害).toBe(0);
    expect(r.步骤.some(s => s.includes('打断成功') && s.includes('攻击取消'))).toBe(true);
    expect(r.步骤.some(s => s.includes('命中「骨卫兵」'))).toBe(false); // 根本没走到命中
  });

  it('打断**失败** → 攻击照常结算，且攻方本次命中 +2', () => {
    const r = 打(守(20), { 反应: 1 });

    expect(r.伤害).toBeGreaterThan(0);
    expect(r.步骤.some(s => s.includes('打断失败') && s.includes('命中 +2'))).toBe(true);
  });

  it('打断是**劣势**（掷两次取低）—— 没注入骰值时用劣势骰', () => {
    // 不给 反应 骰值：引擎自己掷两次取低（这里只要求它不崩、且日志带出骰值）
    const r = 打(守(60));

    expect(r.步骤.some(s => s.includes('打断') && s.includes('打断 '))).toBe(true);
  });

  it('打断也消耗反应槽 + 进冷却（不是白嫖）', () => {
    const r = 打(守(60), { 反应: 20 });

    expect(r.状态.单位.骨卫兵.行动槽.反应).toBe(0);
    expect(r.状态.单位.骨卫兵.冷却.击溃).toBeGreaterThanOrEqual(1);
  });
});

describe('反应动作 · 打断与世界书规则的交互（代码评审 Important #2/#3）', () => {
  /** 带「追加攻击」的攻击技能：主攻击会落一个连击状态，随后再打 N 次 */
  const 双连 = 造解释({
    伤害倍率: 1,
    规则: [{ 触发: '使用时', 作用域: '自身', 动作: [{ 类: '追加攻击', 次数: 2 } as any] } as 规则],
  });

  const 守 = (力量 = 60) =>
    造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      属性: { 实际: { STR: 力量, AGI: 10, CON: 20, PER: 10 } },
      预置反应: '击溃',
      技能: { 击溃: 击溃() },
    });

  function 打双连(守方: 战斗单位, 技能: 战斗解释 = 双连, 注入: any = {}) {
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 双连: 技能 } });
    const 状态 = 开战规则结算(造状态(攻, 守方));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '双连', 目标: '骨卫兵' }, { ...骰, ...注入 });
    return { 伤害: 守方.HP_当前 - r.状态.单位.骨卫兵.HP_当前, 步骤: r.步骤.map(s => `[${s.类}] ${s.内容}`), 状态: r.状态 };
  }

  it('**打断成功 → 连击也不打**（"本次攻击取消"是整次取消，不是只少挨第一刀）', () => {
    const r = 打双连(守(60), 双连, { 反应: 20 });

    expect(r.伤害).toBe(0); // 主攻击取消 + 追加 2 次也没有
    expect(r.步骤.some(s => s.includes('打断成功'))).toBe(true);
    expect(r.步骤.some(s => s.includes('额外释放'))).toBe(false); // 连击循环没跑
    // 本 cast 落上的连击状态也拆了 —— 不然下一次技能白嫖一次连击
    expect(r.状态.单位.契约者.状态.some(st => (st.词条 ?? []).includes('连击'))).toBe(false);
  });

  it('打断**失败** → 连击照常打（追加的攻击也要落地）', () => {
    const 无反应 = 打双连(造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));
    const r = 打双连(守(20), 双连, { 反应: 1 });

    expect(r.伤害).toBeGreaterThan(0);
    expect(r.伤害).toBe(无反应.伤害); // 与没有反应时完全一致
    expect(r.步骤.some(s => s.includes('额外释放'))).toBe(true);
  });

  it('**不可预判**的攻击打断不了（世界书：仅可打断可预判攻击）', () => {
    const r = 打双连(守(60), 造解释({ ...双连, 可预判: false }), { 反应: 20 });

    expect(r.步骤.some(s => s.includes('打断'))).toBe(false); // 没结算打断
    expect(r.伤害).toBeGreaterThan(0);
    expect(r.状态.单位.骨卫兵.行动槽.反应).toBe(1); // 反应槽也没扣
  });
});

describe('敌方反应预置（plan §2.E 末条，代码评审 Important #4）', () => {
  it('学过反应技能的敌人 → 预置第一个可用的；没学过 → 不预置', () => {
    const 会反应 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 技能: { 招架: 招架() } });
    const 不会 = 造单位({ id: '副本角色.异蜂', 阵营: '敌方' });
    const 我 = 造单位({ id: '契约者', 阵营: '我方' });

    const 后 = 敌方反应预置({
      进行中: true,
      回合: 1,
      先攻: [我.id, 会反应.id, 不会.id],
      单位: { 契约者: 我, 骨卫兵: 会反应, 异蜂: 不会 },
      待决: null,
      领域: [],
    });

    expect(后.单位.骨卫兵.预置反应).toBe('招架');
    expect(后.单位.异蜂.预置反应).toBeUndefined();
    expect(后.单位.契约者.预置反应).toBeUndefined(); // 我方不被它动
  });

  it('反应技能在冷却 / 没有反应槽 → 不预置（不会白用）', () => {
    const 冷却 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 技能: { 招架: 招架() }, 冷却: { 招架: 2 } });
    const 无槽 = 造单位({
      id: '副本角色.异蜂',
      阵营: '敌方',
      技能: { 招架: 招架() },
      行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 0, 免费: 999 },
    });

    const 后 = 敌方反应预置({
      进行中: true,
      回合: 1,
      先攻: [冷却.id, 无槽.id],
      单位: { 骨卫兵: 冷却, 异蜂: 无槽 },
      待决: null,
      领域: [],
    });

    expect(后.单位.骨卫兵.预置反应).toBeUndefined();
    expect(后.单位.异蜂.预置反应).toBeUndefined();
  });

  it('预置之后被打时真的用出去（敌我一视同仁）', () => {
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 技能: { 招架: 招架(0.3) } });
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 斩击: 造解释({ 伤害倍率: 1 }) } });
    const 状态0 = 敌方反应预置(开战规则结算(造状态(攻, 守)));

    const 无反应 = 打(造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' }));
    const r = 结算行动(状态0, 状态0.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    expect(守.HP_当前 - r.状态.单位.骨卫兵.HP_当前).toBeLessThan(无反应.伤害);
    expect(r.步骤.some(s => s.内容.includes('反应防御'))).toBe(true);
  });
});
