import { describe, expect, it } from 'vitest';
import {
  解析伤害骰, 武器伤害, 技能伤害, 部位倍率, 部位DC加值,
  暴击范围, 效果乘区, 最终伤害, 命中判定, 技能命中判定,
} from '../engine/damage';

describe('damage · 六步', () => {
  it('解析伤害骰：2d8 → {骰数:2, 骰面:8}', () => {
    expect(解析伤害骰('2d8')).toEqual({ 骰数: 2, 骰面: 8 });
    expect(解析伤害骰('d6')).toEqual({ 骰数: 1, 骰面: 6 });
  });

  it('解析伤害骰：非法格式抛错', () => {
    expect(() => 解析伤害骰('无')).toThrow();
    expect(() => 解析伤害骰('2x8')).toThrow();
  });

  it('武器伤害：⌈((骰值+强化)×(1+(阶位−1)/2)+属性修正)×倍率⌉', () => {
    // (10+0)×(1+0)+12 = 22 → ×1.0 = 22
    expect(武器伤害(10, 0, 1, 12, 1.0)).toBe(22);
    // 二阶：(10+2)×(1+0.5)+12 = 30 → ×1.5 = 45
    expect(武器伤害(10, 2, 2, 12, 1.5)).toBe(45);
  });

  it('技能伤害：⌈基础×(1+(阶位−1)/2)⌉', () => {
    expect(技能伤害(20, 1)).toBe(20);
    expect(技能伤害(20, 2)).toBe(30);
  });

  it('部位倍率与 DC 加值', () => {
    expect(部位倍率(undefined)).toBe(1);
    expect(部位倍率('头部')).toBe(1.5);
    expect(部位倍率('臂部')).toBe(0.75);
    expect(部位倍率('眼部/核心')).toBe(2);
    expect(部位DC加值(undefined, 2)).toBe(0);
    expect(部位DC加值('头部', 2)).toBe(20);
    expect(部位DC加值('眼部/核心', 3)).toBe(60);
  });

  it('暴击范围：每 10 点 AGI 降 1，最低 15', () => {
    expect(暴击范围(5)).toBe(20);
    expect(暴击范围(30)).toBe(17);
    expect(暴击范围(100)).toBe(15);   // 20-10 = 10 → 夹到 15
  });

  it('效果乘区：≤1 走加法，>1 递减', () => {
    expect(效果乘区(0.8)).toBeCloseTo(1.8);
    expect(效果乘区(1.0)).toBeCloseTo(2.0);
    expect(效果乘区(1.1)).toBeCloseTo(2.025);
  });

  it('最终伤害：扣护盾与减伤，最低 0', () => {
    // 混合 13 × 部位 1 × 暴击 1 × 乘区 1 = 13；护盾 3、减伤 20% → 13-3-2.6 = 7.4
    expect(最终伤害({ 混合伤害: 13, 部位倍率: 1, 暴击倍率: 1, 效果乘区: 1, 护盾: 3, 减伤比例: 0.2 })).toBeCloseTo(7.4);
    // 护盾吃光 → 0
    expect(最终伤害({ 混合伤害: 5, 部位倍率: 1, 暴击倍率: 1, 效果乘区: 1, 护盾: 99, 减伤比例: 0 })).toBe(0);
  });

  it('命中判定：1d20 + 属性修正 + 被动 + AGI修正×0.2 ≥ 闪避', () => {
    expect(命中判定({ 骰值: 15, 属性修正: 12, 被动加成: 2, AGI修正: 10, 目标闪避值: 24 })).toBe(true);   // 15+12+2+2 = 31
    expect(命中判定({ 骰值: 1, 属性修正: 0, 被动加成: 0, AGI修正: 0, 目标闪避值: 24 })).toBe(false);
  });

  it('技能命中判定：属性修正 ×(1 + 技能阶位/5)', () => {
    // 15 + 12×(1+0.6) + 0 + 0 = 34.2 ≥ 30
    expect(技能命中判定({ 骰值: 15, 属性修正: 12, 技能阶位: 3, 被动加成: 0, AGI修正: 0, 目标闪避值: 30 })).toBe(true);
  });
});
