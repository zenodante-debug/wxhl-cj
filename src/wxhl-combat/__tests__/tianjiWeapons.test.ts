import { describe, expect, it } from 'vitest';
import { 校验战斗解释 } from '../ai/skillInterpreter';
import { 开战常驻结算, 阶段A规则结算, 结算行动 } from '../engine/loop';
import { 属性修正值 } from '../engine/rules';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';

// ================================================================
// 天基武器（终焉信标 / 星幕）—— 高复杂度装备能不能“翻译 + 落地”
//
// 这两件是拿玩家真实卡面做的压力测试：每一条效果都手写成引擎能吃的「战斗解释」，
// 再过**真实管线**（校验器 → 开战常驻结算 → 阶段A规则结算 → 结算行动）跑一遍。
// 断言写的是“引擎真的做了什么”，所以任何一条静默失效都会红。
// ================================================================

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '玩家',
    属性: { 实际: { STR: 20, AGI: 10, CON: 30, PER: 40 } },
    阶位: '五阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 500,
    MP_最大: 500,
    耐力_当前: 200,
    耐力_最大: 200,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 45,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(攻: 战斗单位, 守: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [攻.id, 守.id],
    单位: Object.fromEntries([攻, 守].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

/** 一件天基武器的基础框架 */
function 天基(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 1,
    分类: '银色',
    类型: '制造系',
    可预判: true,
    关联属性: 'PER',
    技能阶位: 5,
    伤害倍率: 6,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

/** 「该次攻击最终伤害×5」= 数值修正 最终乘区 4（增量写法） */
const 灵素合金 = {
  触发: '使用时' as const,
  作用域: '自身' as const,
  动作: [{ 类: '数值修正' as const, 目标: '最终乘区' as const, 量: { 源: '常数' as const, 系数: 4 } }],
};
/** 「每次攻击后额外自动追加两次攻击」 */
const 虚空能源 = {
  触发: '命中时' as const,
  作用域: '自身' as const,
  动作: [{ 类: '追加攻击' as const, 次数: 2 }],
};
/** 「对目标HP造成伤害时获得 5 回合剥离」 */
const 联合四维 = {
  触发: '命中时' as const,
  作用域: '攻击目标' as const,
  动作: [{ 类: '施加状态' as const, 名: '剥离', 持续: 5 }],
};
/** 「每回合蓄满 1 次能量」 */
const 蓄能 = {
  触发: '回合开始' as const,
  作用域: '自身' as const,
  动作: [{ 类: '资源' as const, 名: '能量', 操作: '获得' as const, 量: { 源: '常数' as const, 系数: 1 } }],
};

const 骰 = { 命中: 18, 伤害骰: [6] };

function 打一发(规则: any[], 守方HP = 100000) {
  const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 终焉信标: 天基({ 规则 }) } });
  const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 守方HP, HP_最大: 守方HP });
  const 状态 = 开战常驻结算(造状态(攻, 守));
  return 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '终焉信标', 目标: '骨卫兵' }, 骰);
}

describe('终焉信标 · 逐条效果能不能落地', () => {
  it('校验器接受（形状合法）', () => {
    expect(() => 校验战斗解释(天基({ 规则: [灵素合金, 虚空能源, 联合四维] }))).not.toThrow();
  });

  it('**该次攻击最终伤害×5**：真·终伤倍率，当次就生效（不是下一次）', () => {
    const 基准 = 打一发([]);
    const 强化 = 打一发([灵素合金]);
    const 基准伤害 = 100000 - 基准.状态.单位.骨卫兵.HP_当前;
    const 强化伤害 = 100000 - 强化.状态.单位.骨卫兵.HP_当前;

    expect(基准伤害).toBeGreaterThan(0);
    // 效果乘区是递减曲线（×5 表达不出来），真·×5 只能靠「最终乘区」
    expect(强化伤害).toBe(基准伤害 * 5);
    expect(强化.步骤.some(s => s.内容.includes('终伤倍率 5'))).toBe(true);
  });

  it('**追加攻击 ×2**：真的多打两次（主攻击 1 + 追加 2 = 命中 3 次）', () => {
    const r = 打一发([虚空能源]);

    expect(r.步骤.filter(s => s.内容.includes('命中「骨卫兵」')).length).toBe(3);
  });

  it('命中后给目标挂「剥离」状态', () => {
    const r = 打一发([联合四维]);

    expect(r.状态.单位.骨卫兵.状态.some(s => s.名 === '剥离' && s.持续 === 5)).toBe(true);
  });

  it('**范围伤害**：半径内的其他单位吃伤害，但施法者不吃自己的 AoE', () => {
    const 攻 = 造单位({
      id: '契约者',
      阵营: '我方',
      技能: {
        终焉信标: 天基({
          规则: [
            {
              触发: '命中时',
              作用域: '命中点',
              动作: [{ 类: '范围伤害', 中心: '命中点', 半径: 10, 量: { 源: '常数', 系数: 300 } }],
            },
          ],
        }),
      },
    });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 1000, HP_最大: 1000, 距离: 0 });
    const 旁观 = 造单位({ id: '副本角色.骨弓手', 阵营: '敌方', HP_当前: 500, HP_最大: 500, 距离: 5 });

    const 状态: 战斗状态 = {
      进行中: true,
      回合: 1,
      先攻: ['契约者', '副本角色.骨卫兵'],
      单位: { 契约者: 攻, 骨卫兵: 守, 骨弓手: 旁观 },
      待决: null,
      领域: [],
    };
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '终焉信标', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.骨弓手.HP_当前).toBe(200); // 半径 10 米内 → 吃 300
    expect(r.状态.单位.契约者.HP_当前).toBe(1000); // **施法者自己不吃**（回归：曾被自己的 AoE 砸中）
  });

  it('**回合开始**规则：每回合蓄满 1 次能量（以前这个触发点没人执行）', () => {
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 终焉信标: 天基({ 规则: [蓄能] }) } });
    const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 造状态(攻, 守);

    const 一 = 阶段A规则结算(状态);
    const 二 = 阶段A规则结算(一);

    expect(一.单位.契约者.资源.能量).toBe(1);
    expect(二.单位.契约者.资源.能量).toBe(2);
  });
});

describe('星幕 · 护盾 / 每回合回复 / 菲琳之心', () => {
  const 护盾值 = (u: 战斗单位) => (u.HP_最大 + u.MP_最大) * 属性修正值(u.属性.实际.PER, u.阶位) * 2;

  /** 「部署后立即生成护盾」+「每回合回复最大值 5%」+「被命中后给攻击者挂冻结」 */
  const 星幕 = 天基({
    行动消耗: '次要行动',
    射程: '自身',
    目标: '自身',
    类型: '辅助',
    伤害倍率: 0,
    规则: [
      {
        触发: '使用时',
        作用域: '自身',
        动作: [{ 类: '护盾', 量: { 源: '表达式' as const, 式: '(最大HP+最大MP)×PER修正×2' } }],
      },
      {
        触发: '回合开始',
        作用域: '自身',
        动作: [{ 类: '护盾', 量: { 源: '表达式' as const, 式: '(最大HP+最大MP)×PER修正×2×0.05' } }],
      },
      { 触发: '被命中后', 作用域: '攻击者', 动作: [{ 类: '施加状态' as const, 名: '冻结', 持续: 3 }] },
    ],
  });

  it('护盾 =（最大HP+最大MP）×PER修正×2，且**只加一次**（回归：支援行动曾把使用时跑两遍）', () => {
    const 樱 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 星幕 } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });
    const 状态 = 造状态(樱, 敌);

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '次要行动', 技能: '星幕', 目标: '骨卫兵' });

    expect(r.状态.单位.契约者.护盾).toBe(护盾值(樱));
    expect(护盾值(樱)).toBeGreaterThan(0);
  });

  it('每回合回复护盾最大值的 5%', () => {
    const 樱 = 造单位({ id: '契约者', 阵营: '我方', 技能: { 星幕 }, 护盾: 0 });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 一 = 阶段A规则结算(造状态(樱, 敌));

    expect(一.单位.契约者.护盾).toBeCloseTo(护盾值(樱) * 0.05);
  });

  it('**菲琳之心**：被命中后给**攻击者**挂「冻结」（不是挂自己身上）', () => {
    const 樱 = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 100000, HP_最大: 100000, 技能: { 星幕 } });
    const 敌 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      技能: { 骨爪: 天基({ 射程: '视线内', 伤害倍率: 1, 分类: '基础', 类型: '主动' }) },
    });
    const 状态 = 造状态(樱, 敌);

    const r = 结算行动(状态, 状态.单位.骨卫兵, { 类型: '主要行动', 技能: '骨爪', 目标: '契约者' }, 骰);

    expect(r.状态.单位.骨卫兵.状态.some(s => s.名 === '冻结')).toBe(true); // 打人的人被标记
    expect(r.状态.单位.契约者.状态.some(s => s.名 === '冻结')).toBe(false);
  });

  it('没有「被命中后」这条规则时，攻击者身上干干净净（确认上一条不是碰巧）', () => {
    const 樱 = 造单位({ id: '契约者', 阵营: '我方', HP_当前: 100000, HP_最大: 100000 });
    const 敌 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      技能: { 骨爪: 天基({ 射程: '视线内', 伤害倍率: 1, 分类: '基础', 类型: '主动' }) },
    });
    const 状态 = 造状态(樱, 敌);

    const r = 结算行动(状态, 状态.单位.骨卫兵, { 类型: '主要行动', 技能: '骨爪', 目标: '契约者' }, 骰);

    expect(r.状态.单位.骨卫兵.状态).toHaveLength(0);
  });
});

describe('两个「声明了却没人读」的数值修正目标（顺手补上）', () => {
  it('**常驻的「最终乘区」**也要生效（被动/装备写「你的伤害×N」）', () => {
    const 打 = (带被动: boolean) => {
      const 攻 = 造单位({
        id: '契约者',
        阵营: '我方',
        技能: {
          终焉信标: 天基({
            规则: 带被动
              ? [{ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '常数', 系数: 1 } }] }]
              : [],
          }),
        },
      });
      const 守 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', 类型: '精英', HP_当前: 100000, HP_最大: 100000 });
      const 状态 = 开战常驻结算(造状态(攻, 守));
      return 100000 - 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '终焉信标', 目标: '骨卫兵' }, 骰).状态.单位.骨卫兵.HP_当前;
    };

    expect(打(true)).toBe(打(false) * 2); // 系数 1 = ×2
  });

  it('**状态携带的「闪避」修正**进命中 DC（上 buff 提闪避）', () => {
    const 打 = (带闪避buff: boolean) => {
      const 攻 = 造单位({ id: '契约者', 阵营: '我方', 技能: {} });
      const 守 = 造单位({
        id: '副本角色.骨卫兵',
        阵营: '敌方',
        类型: '精英',
        HP_当前: 1000,
        HP_最大: 1000,
        状态: 带闪避buff ? [{ 名: '疾风', 持续: 999, 数值修正: { 闪避: 1000 } }] : [],
      });
      const 状态 = 造状态(攻, 守);
      攻.技能 = { 骨爪: 天基({ 射程: '视线内', 关联属性: 'STR', 伤害倍率: 1, 分类: '基础', 类型: '主动' }) };
      return 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '骨爪', 目标: '骨卫兵' }, { 命中: 20, 伤害骰: [6] });
    };

    // 攻方修正约 229；闪避 +1000 后 DC 远超它 → 应当未命中（伤害 0）
    expect(打(true).状态.单位.骨卫兵.HP_当前).toBe(1000);
    expect(打(false).状态.单位.骨卫兵.HP_当前).toBeLessThan(1000);
  });
});
