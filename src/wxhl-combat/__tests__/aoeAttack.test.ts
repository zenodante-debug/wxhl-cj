import { describe, expect, it } from 'vitest';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家追加需求（2026-10-09）：
//   「另外，现在 aoe 技能无法实现！」→ 裁决：「AoE 肯定也是要骰命中，你的方案很合理」
//
// 现状（两处都不对）：
//   1. `范围伤害` 只有"按固定量直接扣血" —— **不走六步**（无命中、不吃防御/减伤/暴击），
//      与「大范围混合魔法穿透伤害」这种卡面语义对不上；
//   2. 中心取的是"效果落在的那个单位"的距离，`中心` 字段根本没被读。
//
// 口径（§8.3 第 6 项）：**门禁只走一遍，伤害管线按目标走 N 遍** ——
//   半径内的每个敌对单位**各掷一次命中 + 各走一遍完整六步**；
//   槽位/冷却/每场限次**只算一次**（所以展开必须在 `结算技能` 里做，不能在 `结算行动` 里拆行动）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '视线内',
    目标: '单体',
    消耗: '无',
    冷却: 3,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 2,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 10, AGI: 10, CON: 10, PER: 10 } },
    阶位: '一阶',
    HP_当前: 1000,
    HP_最大: 1000,
    MP_当前: 1000,
    MP_最大: 1000,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

/** 一条 `范围伤害` 动作（`量` 填个夸张的数：它**不该**被用上，伤害走六步） */
const 范围动作 = (半径: number): 规则 => ({
  触发: '使用时',
  作用域: '攻击目标',
  动作: [{ 类: '范围伤害', 中心: '攻击目标', 半径, 量: { 源: '常数', 系数: 9999 } } as any],
});

/** 契约者(0m) / 白露露(3m, 友) / 骨卫兵甲(5m, 敌) / 骨卫兵乙(15m, 敌) / 骨卫兵丙(60m, 敌) */
function 造战场(技能: 战斗解释): 战斗状态 {
  const 契约者 = 造单位({
    id: '契约者',
    阵营: '我方',
    属性: { 实际: { STR: 200, AGI: 10, CON: 10, PER: 10 } },
    技能: { 木遁: 技能 },
  });
  return {
    进行中: true,
    回合: 1,
    先攻: ['契约者'],
    单位: {
      契约者,
      白露露: 造单位({ id: '小队.成员.白露露', 阵营: '我方', 距离: 3 }),
      骨卫兵甲: 造单位({ id: '副本角色.骨卫兵甲', 阵营: '敌方', 距离: 5, 防御: 300 }),
      骨卫兵乙: 造单位({ id: '副本角色.骨卫兵乙', 阵营: '敌方', 距离: 15 }),
      骨卫兵丙: 造单位({ id: '副本角色.骨卫兵丙', 阵营: '敌方', 距离: 60 }),
    },
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [6] };

/** 打一发（目标 = 骨卫兵甲）；半径 20 时：甲(0m)、乙(10m) 在圈里，丙(55m) 在外面 */
function 打(半径: number | null, 目标 = '骨卫兵甲') {
  const 技能 = 造解释(半径 === null ? {} : { 规则: [范围动作(半径)] });
  const 状态 = 开战规则结算(造战场(技能));

  const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标 }, 骰);
  const 掉血 = (键: string) => 1000 - r.状态.单位[键].HP_当前;
  return { 状态: r.状态, 掉血, 文本: r.步骤.map(s => s.内容).join('\n') };
}

describe('1 · 半径内每个敌对单位各走一遍完整六步', () => {
  it('圈里的两个敌人都掉血；**伤害吃防御**（证明走的是六步，不是那个 9999 的固定量）', () => {
    const r = 打(20);

    // 徒手(注入 6) + PER/STR 修正 195 → 武器 ceil((6+195)×0.5)=101；技能 ceil(195×2)=390 → 基础 491
    expect(r.掉血('骨卫兵甲')).toBe(491 - 300); // 甲有 300 防御 → 混合 191
    expect(r.掉血('骨卫兵乙')).toBe(491); // 乙没防御 → 全额
  });

  it('半径外的敌人不掉血', () => {
    expect(打(20).掉血('骨卫兵丙')).toBe(0);
  });

  it('**打不到自己人**：施法者与队友都不掉血', () => {
    const r = 打(20);

    expect(r.掉血('契约者')).toBe(0);
    expect(r.掉血('白露露')).toBe(0); // 同阵营不进 AoE（那是支援）
  });

  it('每个目标各有一条命中日志', () => {
    const r = 打(20);

    expect(r.文本).toContain('骨卫兵甲');
    expect(r.文本).toContain('骨卫兵乙');
    expect(r.文本).toContain('范围攻击');
  });

  it('半径写大一点 → 圈里的人跟着变多', () => {
    expect(打(100).掉血('骨卫兵丙')).toBeGreaterThan(0);
  });
});

describe('2 · 门禁/槽位/冷却/限次**只算一次**（这条是 AoE 最容易做错的地方）', () => {
  const 带限次 = 造解释({ 每场限次: 2, 规则: [范围动作(20)] });

  it('行动槽只扣一次', () => {
    const 状态 = 开战规则结算(造战场(带限次));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);

    expect(r.状态.单位.契约者.行动槽.主要).toBe(0);
  });

  it('每场限次只 +1（不是每个目标 +1）', () => {
    const 状态 = 开战规则结算(造战场(带限次));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);

    expect(r.状态.单位.契约者.已用次数?.['木遁']).toBe(1);
  });

  it('冷却只写一次（写的是冷却回合数，不是"目标数 × 冷却"）', () => {
    const 状态 = 开战规则结算(造战场(造解释({ 冷却: 3, 规则: [范围动作(20)] })));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);

    expect(r.状态.单位.契约者.冷却['木遁']).toBe(3);
  });

  it('「使用时」的自增伤**只算一次**（不是每目标重算一遍）', () => {
    const 技能 = 造解释({
      规则: [
        范围动作(20),
        // 该次攻击最终伤害 ×2（增量写法）
        { 触发: '使用时', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '最终乘区', 量: { 源: '常数', 系数: 1 } }] },
      ],
    });
    const 状态 = 开战规则结算(造战场(技能));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);

    // 491 × 2 = 982（若每目标重算一遍乘区也不会变，但「使用时」落的状态会叠两层 —— 那才是错）
    expect(1000 - r.状态.单位.骨卫兵乙.HP_当前).toBe(982);
  });
});

describe('3 · 没有「范围伤害」动作的技能：行为逐字不变', () => {
  it('单目标，只打选中的那一个', () => {
    const r = 打(null);

    expect(r.掉血('骨卫兵甲')).toBe(491 - 300);
    expect(r.掉血('骨卫兵乙')).toBe(0);
    expect(r.文本).not.toContain('范围攻击');
  });
});

describe('3b · 「伤害倍率 0 + 只有一个量」的老写法：仍旧按固定量扣血（别把它变成 0 伤害）', () => {
  it('不展开成六步，圈里每个人吃那个固定量；施法者照样不挨', () => {
    // 卡面「使用：对范围内所有敌方造成 50 点伤害」——`量` 是它唯一的伤害来源
    const 技能 = 造解释({
      伤害倍率: 0,
      规则: [
        {
          触发: '使用时',
          作用域: '攻击目标',
          动作: [{ 类: '范围伤害', 中心: '攻击目标', 半径: 20, 量: { 源: '常数', 系数: 50 } } as any],
        },
      ],
    });
    const 状态 = 开战规则结算(造战场(技能));
    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);
    const 掉血 = (键: string) => 1000 - r.状态.单位[键].HP_当前;

    expect(掉血('骨卫兵乙')).toBe(50); // 圈里的**旁观者**吃固定量（这一条就是老行为）
    expect(掉血('骨卫兵丙')).toBe(0); // 半径外
    expect(掉血('契约者')).toBe(0); // 施法者不吃自己的 AoE
    // 被选中的那个目标本来就吃主攻击（不是吃那个固定量）—— 老代码也一直是这个分工
    expect(掉血('骨卫兵甲')).toBe(1); // 101 基础 − 300 防御 → 混合下限 1
    expect(r.步骤.map(s => s.内容).join('\n')).not.toContain('范围攻击');
  });
});

describe('4 · 命中判定真的在掷（不是必中）', () => {
  it('闪避值高到打不中 → 圈里的人一个都不掉血', () => {
    const 技能 = 造解释({ 规则: [范围动作(20)] });
    const 状态 = 开战规则结算(造战场(技能));
    状态.单位.骨卫兵甲 = { ...状态.单位.骨卫兵甲, 闪避值: 9999 };
    状态.单位.骨卫兵乙 = { ...状态.单位.骨卫兵乙, 闪避值: 9999 };

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '木遁', 目标: '骨卫兵甲' }, 骰);

    expect(1000 - r.状态.单位.骨卫兵甲.HP_当前).toBe(0);
    expect(1000 - r.状态.单位.骨卫兵乙.HP_当前).toBe(0);
    expect(r.步骤.map(s => s.内容).join('\n')).toContain('未命中');
  });
});
