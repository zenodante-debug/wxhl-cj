import { describe, expect, it } from 'vitest';
import { 校验战斗解释, 解析批量翻译结果, 构建批量翻译提示词 } from '../ai/skillInterpreter';
import { 效果预览 } from '../engine/effectPreview';
import type { 战斗解释 } from '../types';

/** 新签名要的是「条目名数组」（子技能兜底命名 + 填 `母条目`）；这里只关心编号对号入座 */
const 条目名 = (n: number) => Array.from({ length: n }, (_, i) => `条目${i + 1}`);

// ================================================================
// 玩家反馈（2026-10-09）：**技能被翻译成空壳**
//
//   例 1（复杂）：木遁·(花)树界降诞 —— 卡面写了五件事
//     （80 米范围伤害 / 每回合抽 8%最大HP+50MP 并反哺自身 / DC40 豁免→麻痹+眩晕 /
//       森罗古界领域 / 极意分裂毒花），翻译只回了「PER伤害X5.5（一次普通攻击，无额外效果）」
//   例 2（极简）：神圣祷告「选择目标恢复 per×0.25 的 hp」
//     —— 这种一眼就懂的，也被翻成「没有额外效果：纯粹的伤害/无效技能」
//
// 查证：输入没问题（卡面字段与效果原文都发过去了）；问题在
//   a) 提示词**没有"治疗/支援类怎么写"的配方** —— 模型看到不造成伤害的技能无从下笔，就退回空壳；
//   b) 提示词不要求模型**先枚举卡面里的效果** —— 它索性整体放弃；
//   c) 校验**不会因此报错** —— "没有规则"是合法的（普通攻击就是这样），于是静默丢效果。
//
// 玩家裁决：拆不动就**判失败进复核**（和现有失败模式一致），但**原因要说清"拆了几条、映射了几条"**。
// ================================================================

const 基础 = {
  行动消耗: '主要行动',
  射程: '视线内',
  目标: '单体',
  消耗: '无',
  冷却: 1,
  分类: '基础',
  类型: '主动',
  可预判: true,
};

describe('拆解清单 · 先枚举再映射（拆解是提示，不是合同）', () => {
  // 2026-10-10 修订：玩家实测 42 条全部失败，绝大多数是"拆解列了、规则没有" ——
  // 那不是翻译漏效果，是模型把卡面里**所有**句子都列进拆解（包括纯文本描述），
  // 然后一条规则都不给（它根本不知道这些该怎么写成规则）。
  // 修法：**不判失败**，把拆解写进**托管**（原文留底，复核界面看得见）。
  it('**拆了 5 条却一条规则都没有 → 不判失败**，拆解进托管（复核界面看得见）', () => {
    const 解释 = 校验战斗解释({
      ...基础,
      伤害倍率: 5.5,
      拆解: [
        '范围内所有敌方受到 5.5×PER修正值 的穿透伤害',
        '被触碰的目标每回合被抽离 8% 最大HP 与 50 点 MP',
        '汲取的生命能量 100% 反哺施术者自身的 HP 与 MP',
        'DC40 体质豁免失败则陷入【花粉麻痹】与【深度眩晕】2 回合',
        '领域【森罗古界】：敌方治疗降低 70%，受伤时分裂【寄生毒花】',
      ],
      规则: [],
    });

    expect(解释.拆解).toHaveLength(5);
    expect(解释.托管).toHaveLength(5);
    expect(解释.托管[0].原文).toContain('范围内所有敌方');
  });

  it('拆解进托管 → 原文留底（复核界面看得见，不会静默丢）', () => {
    const 解释 = 校验战斗解释({
      ...基础,
      拆解: ['恢复 PER×0.25 的 HP'],
      规则: [],
    });

    expect(解释.托管).toHaveLength(1);
    expect(解释.托管[0].原文).toContain('恢复 PER×0.25 的 HP');
  });

  it('拆解与规则都有 → 通过，且拆解清单保留下来（详情面板要显示）', () => {
    const 解释 = 校验战斗解释({
      ...基础,
      伤害倍率: 0,
      拆解: ['恢复 PER×0.25 的 HP'],
      规则: [
        { 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '资源', 名: 'HP', 操作: '恢复', 量: { 源: '属性', 名: 'PER', 系数: 0.25 } }] },
      ],
    });

    expect(解释.拆解).toEqual(['恢复 PER×0.25 的 HP']);
    expect(解释.规则).toHaveLength(1);
  });

  it('**老缓存没有拆解字段** → 不判失败（向后兼容，不能因为加了新字段就把旧存档全判死）', () => {
    const 解释 = 校验战斗解释({ ...基础, 伤害倍率: 1, 规则: [] });

    expect(解释.拆解).toEqual([]);
  });

  it('拆解不是数组 / 里面混了 null → 归一化掉', () => {
    const 解释 = 校验战斗解释({ ...基础, 伤害倍率: 0, 拆解: ['有效的一条', null, '', 123] as any, 规则: [{ 触发: '常驻', 作用域: '自身', 动作: [{ 类: '数值修正', 目标: '防御', 量: { 源: '常数', 系数: 1 } }] }] });

    expect(解释.拆解).toEqual(['有效的一条']);
  });

  it('批量解析：拆解进托管（复核面板直接看得到原文）', () => {
    const json = JSON.stringify({
      解释: [{ 编号: 0, ...基础, 拆解: ['抽离 8% 最大HP'], 规则: [] }],
    });

    const 逐条 = 解析批量翻译结果(json, 条目名(1));

    expect(逐条[0].成功).toBe(true);
    if (逐条[0].成功 === true) {
      expect(逐条[0].技能[0].解释.托管).toHaveLength(1);
      expect(逐条[0].技能[0].解释.托管[0].原文).toContain('8% 最大HP');
    }
  });
});

describe('治疗 / 支援类技能的配方（提示词必须教）', () => {
  const 提示词 = 构建批量翻译提示词([{ 单位: '契约者', 名称: '神圣祷告', 来源: { 效果: { 描述: '选择目标恢复per×0.25的hp' } } }]);

  it('有「治疗 / 支援」专段，且给出"恢复 HP"与「属性×系数」的映射', () => {
    expect(提示词).toMatch(/治疗|恢复类/);
    expect(提示词).toMatch(/"操作"\s*:\s*"恢复"/);
    expect(提示词).toMatch(/PER.*0\.25|属性.*系数/);
  });

  it('明说"不造成伤害的技能**不能**写成空规则"', () => {
    expect(提示词).toMatch(/它也是效果|不能写成空规则|不能.*空规则/);
  });

  it('要求**先枚举再映射**（拆解字段）', () => {
    expect(提示词).toContain('拆解');
    expect(提示词).toMatch(/逐句|先列/);
  });

  it('给了"复杂技能怎么拆"的真实范例（木遁那类）', () => {
    expect(提示词).toMatch(/复杂技能|范例/);
    expect(提示词).toMatch(/每回合|抽离|反哺|领域|极意/);
  });
});

describe('详情面板要能看出"拆了几条、映射了几条"', () => {
  it('拆解多于规则时给一行提示（玩家据此决定要不要重翻）', () => {
    const 解释 = {
      规则: [{ 触发: '使用时', 作用域: '攻击目标', 动作: [{ 类: '数值修正', 目标: '伤害', 量: { 源: '常数', 系数: 0.5 } }] }],
      拆解: ['范围伤害', '每回合抽离 8% 最大HP', '反哺自身'],
      托管: [],
      伤害倍率: 5.5,
    } as unknown as 战斗解释;

    const 行 = 效果预览(解释).行.join('\n');

    expect(行).toMatch(/拆解[^\n]*3 条[\s\S]*1 条规则/);
  });
});
