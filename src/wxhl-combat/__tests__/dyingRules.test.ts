import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { 开战规则结算, 结算行动 } from '../engine/loop';
import { 濒死检定一轮, 标记濒死, 能行动, 是契约者 } from '../engine/turn';
import { 阶段A规则结算 } from '../engine/loop';
import type { 战斗状态, 战斗单位, 战斗解释, 规则 } from '../types';

// ================================================================
// 玩家反馈（第 2、3 条）：
//   「对于可以回合开始回血的敌人，被击倒后，由于回合开始时回血，会取消击倒和濒死状态。
//     等于永远杀不死。」
//   「倒地濒死状态应该无法行动了，就不会产生意图。
//     除了契约者（包括其他契约者），副本角色就不需要执行濒死检定了，濒死检定是契约者的特权。」
//
// 玩家裁决：
//   A. 副本角色 HP 归零 = 直接死亡（不打濒死标记、不做濒死检定）；
//      濒死 + 每回合 CON DC12 检定是**契约者（玩家/小队成员/其他契约者）的特权**。
//   B. HP ≤ 0 的单位不能行动 → 也不该吃「回合开始 / 回合结束」的规则
//      （回血类规则在倒地后照样跑 = 永远杀不死，就是这个）。
// ================================================================

function 造解释(覆盖: Partial<战斗解释> = {}): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 1,
    规则: [],
    托管: [],
    ...覆盖,
  };
}

function 造单位(覆盖: Partial<战斗单位> & { id: string; 阵营: '我方' | '敌方' }): 战斗单位 {
  return {
    名称: 覆盖.id.split('.').pop(),
    类型: '杂兵',
    属性: { 实际: { STR: 20, AGI: 10, CON: 20, PER: 10 } },
    阶位: '一阶',
    HP_当前: 100,
    HP_最大: 100,
    MP_当前: 50,
    MP_最大: 50,
    耐力_当前: 100,
    耐力_最大: 100,
    防御: 0,
    闪避值: 0,
    距离: 0,
    行动槽: { 主要: 1, 次要: 1, 移动: 1, 反应: 1, 免费: 999 },
    额度: 30,
    冷却: {},
    护盾: 0,
    架势: null,
    状态: [],
    濒死: null,
    资源: {},
    词条: new Set(),
    技能: {},
    ...覆盖,
  };
}

function 造状态(我方: 战斗单位, 敌方: 战斗单位): 战斗状态 {
  return {
    进行中: true,
    回合: 1,
    先攻: [我方.id, 敌方.id],
    单位: Object.fromEntries([我方, 敌方].map(u => [u.id.split('.').pop()!, u])),
    待决: null,
    领域: [],
  };
}

const 骰 = { 命中: 18, 伤害骰: [20] };

/** 回合开始回满血的被动（玩家报的"永远杀不死"） */
const 回合开始回血 = 造解释({
  行动消耗: '无',
  类型: '被动',
  伤害倍率: 0,
  规则: [
    {
      触发: '回合开始',
      作用域: '自身',
      动作: [{ 类: '资源', 名: 'HP', 操作: '设为', 量: { 源: '表达式', 式: '最大HP' } } as any],
    } as 规则,
  ],
});

describe('濒死是契约者的特权', () => {
  it('**副本角色** HP 归零 = 直接死亡：不打濒死标记、不能行动、不做濒死检定', () => {
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 0 });

    const 标记后 = 标记濒死(敌);

    expect(标记后.濒死).toBe(null); // 副本角色没有濒死
    expect(能行动(标记后)).toBe(false);
    expect(濒死检定一轮(标记后)).toBe(null); // 没有检定这回事
  });

  it('**契约者**（玩家）HP 归零 = 濒死 + 每回合 CON 检定（世界书原文）', () => {
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', HP_当前: 0 });

    const 标记后 = 标记濒死(我);

    expect(标记后.濒死).toEqual({ 成功: 0, 失败: 0 });
  });

  it('**其他契约者**（敌人里的契约者）也享有濒死检定（玩家点名包括）', () => {
    const 敌契 = 造单位({ id: '其他契约者.林千尺', 阵营: '敌方', 类型: '契约者', HP_当前: 0 });

    expect(是契约者(敌契)).toBe(true);
    expect(标记濒死(敌契).濒死).toEqual({ 成功: 0, 失败: 0 });
  });

  it('**小队成员**（队友）也享有濒死检定', () => {
    const 队友 = 造单位({ id: '小队.成员.江薇芷', 阵营: '我方', 类型: '小队成员', HP_当前: 0 });

    expect(是契约者(队友)).toBe(true);
    expect(标记濒死(队友).濒死).toEqual({ 成功: 0, 失败: 0 });
  });

  it('实战：副本角色被打到 0 之后不再站起来（没有濒死标记可清）', () => {
    const 攻 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家', 技能: { 斩击: 造解释() } });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 1 });
    const 状态 = 开战规则结算(造状态(攻, 敌));

    const r = 结算行动(状态, 状态.单位.契约者, { 类型: '主要行动', 技能: '斩击', 目标: '骨卫兵' }, 骰);

    expect(r.状态.单位.骨卫兵.HP_当前).toBe(0);
    expect(r.状态.单位.骨卫兵.濒死).toBe(null);
  });
});

describe('倒地的单位不吃回合开始/回合结束规则（"永远杀不死"的解法）', () => {
  it('**副本角色倒地后，回合开始回血不再触发**（以前倒地照样回满 = 永远杀不死）', () => {
    const 敌 = 造单位({
      id: '副本角色.骨卫兵',
      阵营: '敌方',
      HP_当前: 0, // 已经死了（副本角色没有濒死，HP 0 = 死透）
      技能: { 再生: 回合开始回血 },
    });
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家' });
    const 步骤: any[] = [];

    const 后 = 阶段A规则结算(造状态(我, 敌), 步骤);

    expect(后.单位.骨卫兵.HP_当前).toBe(0); // 没有复活
    expect(步骤.map(s => s.内容).join('\n')).not.toContain('骨卫兵」受到技能效果');
  });

  it('**活着的**敌人回合开始回血照常（健康的再生不该被误杀）', () => {
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方', HP_当前: 30, 技能: { 再生: 回合开始回血 } });
    const 我 = 造单位({ id: '契约者', 阵营: '我方', 类型: '玩家' });

    const 后 = 阶段A规则结算(造状态(我, 敌), []);

    expect(后.单位.骨卫兵.HP_当前).toBe(100); // 活着 → 照回
  });

  it('**濒死中的契约者**也不吃回合开始规则（濒死检定是他唯一的回合事件）', () => {
    const 我 = 造单位({
      id: '契约者',
      阵营: '我方',
      类型: '玩家',
      HP_当前: 0,
      濒死: { 成功: 0, 失败: 0 },
      技能: { 再生: 回合开始回血 },
    });
    const 敌 = 造单位({ id: '副本角色.骨卫兵', 阵营: '敌方' });

    const 后 = 阶段A规则结算(造状态(我, 敌), []);

    expect(后.单位.契约者.HP_当前).toBe(0); // 不靠规则回血，靠 CON 检定
  });
});

