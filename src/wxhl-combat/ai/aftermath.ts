// ================================================================
// 无限回廊 · 前端战斗引擎 · 收尾正文生成
// 战斗结束时一次 AI 调用：把战报写成有文笔的收尾叙事
//
// 收尾不只是文笔：**按击杀发放钥匙**。档位来自卡片 schema 的 `类型` 字段描述
// （副本角色 的 类型 决定钥匙类型；其他契约者 掉落血腥钥匙）：
//   杂兵 → 白色钥匙｜精英 → 白银钥匙｜BOSS → 黄金钥匙｜隐藏BOSS → 钻石钥匙｜契约者 → 血腥钥匙
// （引擎不写背包 —— 只把「获得了哪些钥匙」写进正文，由玩家/主 AI 落地）
// ================================================================

import type { 结算步骤, 战斗状态, 战斗单位 } from '../types';

/** 击杀 → 钥匙档位（见文件头注释）。BOSS 要在 隐藏BOSS 之后判断（隐藏BOSS 也含 BOSS） */
export function 钥匙档位(单位: 战斗单位): string {
  const t = String(单位.类型 ?? '');
  if (单位.id.startsWith('其他契约者.') || /契约者/.test(t)) return '血腥钥匙';
  if (/隐藏BOSS/i.test(t)) return '钻石钥匙';
  if (/BOSS/i.test(t)) return '黄金钥匙';
  if (/精英/.test(t)) return '白银钥匙';
  return '白色钥匙'; // 杂兵（含未标注）
}

/** 收尾时的击杀清单（HP 归零的敌方单位） */
export function 击杀明细(状态: 战斗状态): Array<{ 名: string; 类型: string; 钥匙: string }> {
  return Object.values(状态.单位)
    .filter(u => u.阵营 === '敌方' && u.HP_当前 <= 0)
    .map(u => ({ 名: u.名称 || u.id.split('.').pop() || u.id, 类型: u.类型, 钥匙: 钥匙档位(u) }));
}

/** 主角名（收尾叙事的主角是玩家本人，不是「契约者」这个占位） */
function 主角名(状态: 战斗状态): string {
  const 玩家 = Object.values(状态.单位).find(u => u.类型 === '玩家');
  return 玩家?.名称 || '契约者';
}

/**
 * 构建收尾提示词
 */
export function 构建收尾提示词(步骤列表: 结算步骤[], 状态: 战斗状态): string {
  const 战报 = 步骤列表.map(s => s.内容).join('\n');

  const 明细 = 击杀明细(状态);
  const 掉落段 = 明细.length
    ? 明细.map(x => `- ${x.名}（${x.类型}）→ 获得 ${x.钥匙} ×1`).join('\n')
    : '（没有击杀任何敌人，没有掉落钥匙）';

  return `请把以下战斗战报写成一段有文笔的收尾叙事（200~400字）。主角是「${主角名(状态)}」。

【战报】
${战报}

【击杀与掉落】（严格按这份清单写 —— 一具尸体一枚钥匙，别漏、别多编）
${掉落段}

【要求】
- 客观冷静，白描手法，用行为和结果展现
- 绝不使用微表情八股与极端情绪词
- 世界对契约者保持绝对中立与冷漠
- 死亡是廉价且轻易的，不要美化
- **收尾要写明「${主角名(状态)}」获得了哪些钥匙**（按上面清单），这是这场战斗的结算
- 只写正文，不要任何标题、标签、格式化标记

【示例风格】
骨刃劈开空气的尖啸在第三次交锋时终于滞了半拍。
${主角名(状态)}没有退——他向前迈了半步，把肩胛送进那道空隙，
长剑从骨卫兵的颌下自下而上擦进颈椎缝隙。

碎裂声不是从剑上传来，是从骨架内部。
它维持着挥臂的姿势僵了整整一秒，
然后从膝盖开始，一节一节跪进月台的积水里。`;
}
