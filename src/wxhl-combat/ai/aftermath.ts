// ================================================================
// 无限回廊 · 前端战斗引擎 · 收尾正文生成
// 战斗结束时一次 AI 调用：把战报写成有文笔的收尾叙事
//
// 收尾不只是文笔：**按击杀发放钥匙**。档位来自卡片 schema 的 `类型` 字段描述
// （副本角色 的 类型 决定钥匙类型；其他契约者 掉落血腥钥匙）：
//   杂兵 → 白色钥匙｜精英 → 白银钥匙｜BOSS → 黄金钥匙｜隐藏BOSS → 钻石钥匙｜契约者 → 血腥钥匙
// （引擎不写背包 —— 只把「获得了哪些钥匙」写进正文，由玩家/主 AI 落地）
// ================================================================

import type { 结算步骤, 战斗状态, 战斗单位 } from '../types';
import { 效果预览 } from '../engine/effectPreview';

/** 击杀 → 钥匙档位（见文件头注释）。BOSS 要在 隐藏BOSS 之后判断（隐藏BOSS 也含 BOSS） */
export function 钥匙档位(单位: 战斗单位): string {
  const t = String(单位.类型 ?? '');
  if (单位.id.startsWith('其他契约者.') || /契约者/.test(t)) return '血腥钥匙';
  if (/隐藏BOSS/i.test(t)) return '钻石钥匙';
  if (/BOSS/i.test(t)) return '黄金钥匙';
  if (/精英/.test(t)) return '白银钥匙';
  return '白色钥匙'; // 杂兵（含未标注）
}

/** 收尾时的击杀清单（HP 归零的敌方单位） */
export function 击杀明细(状态: 战斗状态): Array<{ 名: string; 类型: string; 钥匙: string }> {
  return Object.values(状态.单位)
    .filter(u => u.阵营 === '敌方' && u.HP_当前 <= 0)
    .map(u => ({ 名: u.名称 || u.id.split('.').pop() || u.id, 类型: u.类型, 钥匙: 钥匙档位(u) }));
}

/** 主角名（收尾叙事的主角是玩家本人，不是「契约者」这个占位） */
function 主角名(状态: 战斗状态): string {
  const 玩家 = Object.values(状态.单位).find(u => u.类型 === '玩家');
  return 玩家?.名称 || '契约者';
}

/** 单位在叙事里的名字（与 `viewModel.显示名` 同一口径：名称 → id 末段 → id） */
function 叙事名(单位: 战斗单位): string {
  return 单位.名称 || 单位.id.split('.').pop() || 单位.id;
}

/** 每个单位最多发几个"用到的效果"（防提示词被顶爆） */
const 效果上限 = 40;

export interface 用到效果 {
  单位: string;
  效果名: string;
  /** 人话（复用 `效果预览`）：头部一行 + 规则逐条 —— 模型据此**理解这是什么能力** */
  人话: string[];
}

/**
 * 从战报里扫出**真正用到的**技能/装备/血统/天赋，附上人话效果。
 *
 * 为什么只发用到的：一张卡动辄二十个效果，全发会把提示词顶到几万 token；
 * 而模型写这一场只需要理解**这一场里出现过的那几个**能力。
 * 扫法：战报里所有 `「…」` 引号内容 → 去掉单位名 → 到各单位技能表里查 → 查不到（模型瞎编）就跳过。
 */
export function 从战报提取用到的效果(步骤列表: 结算步骤[], 状态: 战斗状态): 用到效果[] {
  const 单位名 = new Set<string>();
  for (const u of Object.values(状态.单位)) {
    单位名.add(叙事名(u));
    单位名.add(u.id?.split('.').pop() ?? '');
  }

  const 候选 = new Set<string>();
  for (const s of 步骤列表 ?? []) {
    for (const m of String(s?.内容 ?? '').matchAll(/「([^」]{1,40})」/g)) {
      const 名 = m[1].trim();
      if (!名 || 单位名.has(名)) continue; // 单位名不是效果
      候选.add(名);
    }
  }

  const 出: 用到效果[] = [];
  const 见过 = new Set<string>();
  for (const u of Object.values(状态.单位)) {
    const 名 = 叙事名(u);
    for (const [效果名, 解释] of Object.entries(u.技能 ?? {})) {
      if (!候选.has(效果名)) continue;
      const 键 = `${名}|${效果名}`;
      if (见过.has(键)) continue;
      见过.add(键);
      const 预览 = 效果预览(解释);
      出.push({ 单位: 名, 效果名, 人话: [...(预览.头部.length ? [预览.头部.join(' ｜ ')] : []), ...预览.行] });
      if (出.length >= 效果上限) return 出;
    }
  }
  return 出;
}

/** 技能表里带某种后缀的条目名（`（血统）`/`（天赋）`/`（职业）`/`（称号）`） */
function 按后缀(单位: 战斗单位, 后缀: string): string[] {
  return Object.keys(单位.技能 ?? {}).filter(n => n.includes(`（${后缀}）`));
}

/**
 * 参战者构筑摘要（让模型知道"他是谁、手里有什么"）。
 * 血统/天赋/职业/称号/装备在我们的技能表里就是条目名（带 `（血统）` 这类后缀），直接列名字即可。
 */
export function 构筑摘要(单位: 战斗单位): string[] {
  const 行: string[] = [];
  行.push(`▸ ${叙事名(单位)}（${单位.类型 || '未知'} · ${单位.阶位 || '未知'}）HP 上限 ${单位.HP_最大} · 防御 ${单位.防御} · 闪避 ${单位.闪避值}`);

  const 武器: string[] = [];
  if (单位.主武器) 武器.push(`主武器 ${单位.主武器.伤害骰}×${单位.主武器.倍率}${单位.主武器.强化等级 ? ` 强化+${单位.主武器.强化等级}` : ''}`);
  if (单位.副武器) 武器.push(`副武器 ${单位.副武器.伤害骰}×${单位.副武器.倍率}`);
  if (武器.length) 行.push(`   武器：${武器.join('、')}`);

  if (单位.装备?.length) {
    行.push(`   装备：${单位.装备.map(e => `${e.槽}「${e.名称}」${e.摘要 ? `（${e.摘要}）` : ''}`).join('、')}`);
  }

  const 构筑 = [...按后缀(单位, '血统'), ...按后缀(单位, '天赋'), ...按后缀(单位, '职业'), ...按后缀(单位, '称号')];
  if (构筑.length) 行.push(`   职业/血统/天赋/称号：${构筑.join('、')}`);

  // 其它带后缀的来源（装备/部位）—— 它们不是"职业类"，但在叙事里同样是"他身上带着的东西"
  const 已列 = new Set(构筑);
  const 其它 = Object.keys(单位.技能 ?? {}).filter(n => n.includes('（') && !已列.has(n));
  if (其它.length) 行.push(`   其它效果来源：${其它.join('、')}`);

  if (单位.状态?.length) {
    行.push(`   本场结束时身上还挂着的状态：${单位.状态.map(s => `${s.名}${s.层数 ? `×${s.层数}` : ''}（剩 ${s.持续} 回合）`).join('、')}`);
  }
  if (单位.词条?.size) 行.push(`   词条：${[...单位.词条].join('、')}`);
  return 行;
}

/** 战报超过这个长度就掐中间（防止把提示词撑爆；掐了会明确标出来） */
const 战报上限 = 90000;

/** 战报太长时保留首尾、掐掉中间，并明确标注 */
function 裁剪战报(全文: string): string {
  if (全文.length <= 战报上限) return 全文;
  const 每段 = Math.floor(战报上限 / 2);
  return (
    全文.slice(0, 每段) +
    `\n\n【……中间省略 ${全文.length - 战报上限} 字（战斗过长，只保留首尾）……】\n\n` +
    全文.slice(-每段)
  );
}

/**
 * 构建收尾提示词。
 *
 * 玩家要求（2026-10-09 两轮）：
 * - 「完全没有美感，只是对战斗日志的复述。应该把**环境、角色构筑**都发给模型，
 *    让模型理解**是什么技能、产生什么效果**，而不是复述行动名字。要有电影感、小说感」
 * - 「最好是有个**第三方解说**的效果，类似 jojo 或者咒术回战，能力效果是第三方解说，
 *    敌人和队友的心理也要重点描写，但是**玩家本身不描写心理**」
 *
 * 所以这一段提示词有**五段输入**（开战前的上下文 / 参战者 / 用到的技能与效果 / 战报 / 击杀掉落）
 * 和**两句事实边界**（结果不许改、画面自由写）—— 旧的「不要自己加战报里没有的」是复述的病根，已删。
 */
export function 构建收尾提示词(
  步骤列表: 结算步骤[],
  状态: 战斗状态,
  额外: { 开战前上下文?: string; 开场模式?: string } = {},
): string {
  const 战报 = 裁剪战报(步骤列表.map(s => s.内容).join('\n'));

  const 明细 = 击杀明细(状态);
  const 掉落段 = 明细.length
    ? 明细.map(x => `- ${x.名}（${x.类型}）→ 获得 ${x.钥匙} ×1`).join('\n')
    : '（没有击杀任何敌人，没有掉落钥匙）';
  const 主 = 主角名(状态);

  const 上下文 = (额外.开战前上下文 ?? '').trim();
  const 上下文段 = 上下文
    ? `${裁剪上下文(上下文)}${额外.开场模式 ? `\n（本场开场：${额外.开场模式}）` : ''}`
    : `（无 —— 这一场没有可用的上一楼正文。环境就按战报与参战者信息写，不要凭空编造场景）`;

  const 参战者段 = Object.values(状态.单位).map(单位 => 构筑摘要(单位).join('\n')).join('\n');

  const 用到 = 从战报提取用到的效果(步骤列表, 状态);
  const 效果段 = 用到.length
    ? 用到.map(x => `- 「${x.效果名}」（${x.单位}）｜${x.人话.join('；')}`).join('\n')
    : '（这一场没有解析得到的技能/效果 —— 只有基础攻击与移动）';

  return `把下面这份战斗战报，写成一篇**完整的战斗全过程**。主角是「${主}」。

【开战前的上下文】（开打之前发生了什么 —— 环境、气氛、局势都从这里长出来）
${上下文段}

【参战者】（写谁像谁：类型/阶位决定分量，装备与血统天赋决定打法和气度）
${参战者段}

【用到的技能与效果】（引擎逐条翻译过：**先读懂它做了什么，再用解说的口吻讲出来**）
${效果段}

【战斗战报】（引擎逐条记下的实况：先攻顺序、每一击的命中与否、六步伤害、护盾与减伤、
状态与冷却、掉落。**结果是它说了算**）
${战报}

【击杀与掉落】（严格按这份清单写 —— 一具尸体一枚钥匙，别漏、别多编）
${掉落段}

【怎么写】
1. **结果不许改**：命中/未命中、伤害量级、谁倒下、掉落、胜负 —— 与战报一致。
   不许为了让场面好看把未命中写成擦伤、把重伤写成轻伤。
2. **画面自由写**：环境、天气、光线、声音、气味、动作细节、对手的反应 —— 你来写。
   战报没写的**过程**可以补，但**不能与战报冲突**。
3. **第三方解说**（这一篇的"声音"）：关键时刻**跳出画面**做全知旁白 —— 像 JOJO／咒术回战里
   那位解说：讲清「这是什么能力、为什么有效、对手为什么挡不住、这一下意味着什么」。
   语气冷静、带压迫感、有判断力，不吹不黑。依据是上面【用到的技能与效果】的人话：
   **是解说，不是念技能名，也不是复述规则条文。**
4. **心理描写**：
   - **敌人与队友**（含其他契约者）→ **重点写**：他此刻在想什么、怕什么、怎么读局势、为什么这么选。
   - **「${主}」（玩家角色）→ 不写心理**。只写他的动作与外在表现（姿态、呼吸、伤口、眼神），
     内心留给玩家自己。解说可以评价他的招式与处境，但**不许替他感受**。
5. **电影感**：镜头跟着交手走 —— 谁先动、刀锋落在哪里、护盾碎在哪一刻、距离怎么被拉开又逼近。
   数值用文学化表达（"那一记压得他掉了半条命"），**不写骰值与公式**。
6. **完整**：从开打写到收场，战报里**每一次交锋**都要落地；篇幅不限，但不重复、不凑字数。
7. **收尾**：交代「${主}」最终赢得了什么（或输在哪里），以及按上面清单**获得了哪些钥匙**。
   不写规则说明，不写「接下来会发生什么」这种预告。

【风格】
- 客观冷静，白描为主；第三方解说的语气要冷、准、有压迫感（像在看一场被剖析透的处刑）
- 世界对契约者保持绝对中立与冷漠；死亡是廉价且轻易的，不要美化
- 不用微表情八股与极端情绪词；只写正文，不要标题、标签、分隔线、格式化标记

【示例笔法】（只是笔法参考：动作白描 + 第三方解说的插入 + 敌人心理）
骨刃劈开空气的尖啸在第三次交锋时终于滞了半拍。
${主}没有退——他向前迈了半步，把肩胛送进那道空隙，长剑自下而上擦进骨卫兵的颈椎缝隙。

——那一剑的角度不对。它不该从下往上走。
解说的声音在画面之外落下：**骨卫兵的骨甲只在受击后一秒内再生，
而从下往上的刺击恰好把断面压在颈椎的接缝里——再生得再快，也得先把骨头接回去。**

骨卫兵第一次感到了恐惧。它没有痛觉，也不懂什么叫后悔，
但此刻它清楚地知道：对方已经看穿了它全部的底牌。

碎裂声不是从剑上传来，是从骨架内部。
它维持着挥臂的姿势僵了整整一秒，然后从膝盖开始，一节一节跪进月台的积水里。`;
}

/** 上下文最多带多少字（太长会把提示词顶大；超了截尾并标注） */
const 上下文上限 = 3000;

function 裁剪上下文(文: string): string {
  if (文.length <= 上下文上限) return 文;
  return `${文.slice(0, 上下文上限)}\n（……上下文过长，已截尾……）`;
}
