import type { 结算步骤 } from '../types';

/**
 * 构建收尾提示词
 */
export function 构建收尾提示词(步骤列表: 结算步骤[]): string {
  const 战报 = 步骤列表.map(s => s.内容).join('\n');

  return `请把以下战斗战报写成一段有文笔的收尾叙事（200~400字）。

【战报】
${战报}

【要求】
- 客观冷静，白描手法，用行为和结果展现
- 绝不使用微表情八股与极端情绪词
- 世界对契约者保持绝对中立与冷漠
- 死亡是廉价且轻易的，不要美化
- 只写正文，不要任何标题、标签、格式化标记

【示例风格】
骨刃劈开空气的尖啸在第三次交锋时终于滞了半拍。
青空黎没有退——他向前迈了半步，把肩胛送进那道空隙，
长剑从骨卫兵的颌下自下而上擦进颈椎缝隙。

碎裂声不是从剑上传来，是从骨架内部。
它维持着挥臂的姿势僵了整整一秒，
然后从膝盖开始，一节一节跪进月台的积水里。`;
}
