// ================================================================
// 无限回廊 · 前端战斗引擎 · 敌方意图（掷骰模式）
// 纯函数，不碰酒馆接口
//
// 玩家要的省钱模式：「敌人的行动意图提供两个模式 —— 1 AI 生成；2 根据行动选项 roll 骰子，
// 抽中具体哪个技能就怎么放（比如主要行动有三个选项，就 1d3）」。
//
// 所以这里复用 `列行动选项`（技能按**行动消耗**归类 + 每类的基础武器攻击），
// 每个行动类型掷一次骰子抽一个选项。**完全不调用 AI**。
// AI 模式失败时也用它兜底（比"只会平A"的保底强：会真的用技能、会挑辅助技给队友）。
// ================================================================

import { rollDie } from '../engine/dice';
import { 列行动选项, type 行动选项 } from '../engine/actionOptions';
import type { 战斗状态, 战斗单位, 战斗解释 } from '../types';
import type { 敌方意图, 意图行动 } from './enemyTactics';

/** 掷骰函数（测试可注入固定值） */
export type 掷骰函数 = (面数: number) => number;

/** 单位的显示名 */
function 名(u: 战斗单位): string {
  return u.名称 || u.id.split('.').pop() || u.id;
}

/** 引擎认的引用写法：契约者本体写「玩家」，其余写 id */
function 引用(u: 战斗单位 | undefined): string | undefined {
  if (!u) return undefined;
  return u.id === '契约者' ? '玩家' : u.id;
}

/** 这个选项是不是辅助类（该给友军/自己用，而不是打敌人） */
function 是辅助(单位: 战斗单位, 选项: 行动选项 | undefined): boolean {
  const 解释: 战斗解释 | undefined = 选项?.技能 ? 单位.技能?.[选项.技能] : undefined;
  if (!解释) return false;
  if (/辅助|光环|制造/.test(String(解释.类型 ?? ''))) return true;
  // 明确写了自己/友军目标的，也算支援
  const 目标 = String(解释.目标 ?? '');
  return 目标 === '自身' || 目标.includes('友');
}

/** 该选项是不是近战（只有技能才有射程文本；基础武器攻击的武器类型卡里没记，不做距离门禁） */
function 是近战(单位: 战斗单位, 选项: 行动选项 | undefined): boolean {
  if (!选项?.技能) return false;
  const 射程 = String(单位.技能?.[选项.技能]?.射程 ?? '');
  return 射程.includes('近战') && !射程.includes('视线') && !射程.includes('无限');
}

/**
 * 随机意图：**不调 AI**，每个敌方单位按行动类型掷骰子抽选项。
 *
 * 规则（尽量让"随机"也打得像样）：
 * - 主要行动：`列行动选项(单位, '主要行动')` 里 1dN 抽一个（含「主武器攻击」保底选项，所以永远有得抽）
 * - 次要行动：`次要行动` 的选项里 1dN 抽一个（没有就跳过）
 * - 抽到近战技能且距离 > 2 → 先插一条「移动」贴到目标身边（否则会被射程门禁挡住）
 * - 抽到辅助类 → 目标给自己；否则打我方（优先玩家）
 *
 * @param 掷骰 测试用注入；默认真随机
 */
export function 随机意图(状态: 战斗状态, 掷骰: 掷骰函数 = rollDie): 敌方意图[] {
  const 我方存活 = Object.values(状态.单位).filter(u => u.阵营 === '我方' && u.HP_当前 > 0);
  const 默认目标 = 我方存活.find(u => u.类型 === '玩家') ?? 我方存活[0];

  const 出: 敌方意图[] = [];
  if (!默认目标) return 出; // 没人可打

  for (const 单位 of Object.values(状态.单位)) {
    if (单位.阵营 !== '敌方' || 单位.HP_当前 <= 0) continue;

    const 行动: 意图行动[] = [];

    /** 抽一个选项 */
    const 抽 = (选项表: 行动选项[]): 行动选项 | undefined =>
      选项表.length ? 选项表[Math.min(Math.max(掷骰(选项表.length), 1), 选项表.length) - 1] : undefined;

    const 主 = 抽(列行动选项(单位, '主要行动'));

    // 近战够不着 → 先移动贴到目标所在位置（距离是"距玩家原点"，贴到目标的距离即 0 距离）
    if (主 && 是近战(单位, 主) && 单位.距离 > 2) {
      行动.push({ 类型: '移动', 目标: 引用(默认目标), 距离: 默认目标.距离 });
    }

    if (主) {
      行动.push({
        类型: '主要行动',
        ...(主.技能 ? { 技能: 主.技能 } : {}),
        ...(主.武器 ? { 武器: 主.武器 } : {}),
        目标: 是辅助(单位, 主) ? 单位.id : 引用(默认目标),
      });
    }

    const 次 = 抽(列行动选项(单位, '次要行动'));
    if (次) {
      行动.push({
        类型: '次要行动',
        ...(次.技能 ? { 技能: 次.技能 } : {}),
        ...(次.武器 ? { 武器: 次.武器 } : {}),
        目标: 是辅助(单位, 次) ? 单位.id : 引用(默认目标),
      });
    }

    出.push({ 单位: 单位.id, 行动 });
  }

  return 出;
}

/** 给日志用的一句话说明（让玩家知道随机模式抽了什么） */
export function 随机意图说明(意图: 敌方意图[], 状态: 战斗状态): string[] {
  const 行: string[] = [];
  for (const 条 of 意图) {
    const 单位 = Object.values(状态.单位).find(u => u.id === 条.单位);
    const 描述 = 条.行动
      .map(a => `${a.类型}${a.技能 ? `·${a.技能}` : a.武器 ? `·${a.武器}攻击` : ''}`)
      .join(' → ');
    行.push(`【随机】${单位 ? 名(单位) : 条.单位} → ${描述}`);
  }
  return 行;
}
