import type { 战斗解释 } from '../types';

/**
 * 构建翻译提示词
 */
export function 构建翻译提示词(技能: any): string {
  return `请把以下技能翻译成战斗解释（JSON 格式）：

技能名称: ${技能.名称}
类型: ${技能.类型}
行动类型: ${技能.行动类型}
关联属性: ${技能.关联属性}
消耗: ${技能.消耗}
冷却: ${技能.冷却}
射程: ${技能.射程}
目标: ${技能.目标}
效果: ${JSON.stringify(技能.效果, null, 2)}

输出格式（必须是合法 JSON）：
{
  "行动消耗": "主要行动|次要行动|反应动作|免费行动|无",
  "射程": "自身|近战|X米|视线内",
  "目标": "单体|范围X米|自身|全体",
  "消耗": "无|MP X|耐力 X",
  "冷却": 数字（回合数）,
  "分类": "基础|高级|银色",
  "类型": "主动|被动|光环|辅助|制造系",
  "可预判": true|false,
  "规则": [
    {
      "触发": "常驻|进入战斗|回合开始|回合结束|攻击时|命中时|受击时|被命中后|击杀时|资源变化时|使用时",
      "作用域": "自身|我方全体|敌方全体|攻击目标|攻击者|命中点",
      "条件": { "左": {...}, "比较": "≥|>|≤|<|=", "右": {...} },  // 可选
      "动作": [
        { "类": "资源", "名": "...", "操作": "获得|消耗|设为|恢复", "量": {...} },
        { "类": "护盾", "量": {...} },
        { "类": "数值修正", "目标": "伤害|减伤|命中|闪避|...", "量": {...} },
        { "类": "施加状态", "名": "...", "持续": 数字, "层数": {...} },
        { "类": "词条", "名": "...", "操作": "附加|移除" },
        { "类": "领域", "名": "...", "持续": 数字, "规则": [...] },
        ...
      ]
    }
  ],
  "托管": [
    { "原文": "...", "触发点": ["..."] }
  ]
}

规则系效果（必中/即死/无敌/锁血/穿透/无视）一律用 "规则系判定" 动作。
翻译不了的效果放进 "托管"，原文留底。`;
}

/**
 * 解析翻译结果
 */
export function 解析翻译结果(json: string): 战斗解释 {
  const obj = JSON.parse(json);

  // 校验必填字段
  if (!obj.行动消耗) throw new Error('缺少必填字段: 行动消耗');
  if (!obj.射程) throw new Error('缺少必填字段: 射程');
  if (!obj.目标) throw new Error('缺少必填字段: 目标');
  if (obj.消耗 === undefined) throw new Error('缺少必填字段: 消耗');
  if (obj.冷却 === undefined) throw new Error('缺少必填字段: 冷却');
  if (!obj.分类) throw new Error('缺少必填字段: 分类');
  if (!obj.类型) throw new Error('缺少必填字段: 类型');
  if (obj.可预判 === undefined) throw new Error('缺少必填字段: 可预判');
  if (!Array.isArray(obj.规则)) throw new Error('缺少必填字段: 规则');
  if (!Array.isArray(obj.托管)) throw new Error('缺少必填字段: 托管');

  return obj as 战斗解释;
}
