/**
 * 构建批量翻译提示词：**一条消息装下所有效果**。
 * 条目必须带上 `编号` 回传，按编号对号入座。
 */
export function 构建批量翻译提示词(条目: 待翻译条目[]): string {
  const 清单 = 条目
    .map((条, i) =>
      [
        `【编号 ${i}】${条.单位} · ${条.名称}`,
        `类型: ${条.来源?.类型 ?? ''}`,
        `行动类型: ${条.来源?.行动类型 ?? ''}`,
        `关联属性: ${条.来源?.关联属性 ?? ''}`,
        `阶位: ${条.来源?.阶位 ?? ''}`,
        `消耗: ${条.来源?.消耗 ?? ''}`,
        `冷却: ${条.来源?.冷却 ?? ''}`,
        `射程: ${条.来源?.射程 ?? ''}`,
        `目标: ${条.来源?.目标 ?? ''}`,
        `效果: ${JSON.stringify(条.来源?.效果 ?? {})}`, // 紧凑序列化（不用 null,2 缩进）—— 提示词越小越快、越不容易撞限
      ].join('\n'),
    )
    .join('\n\n');

  return `把下面**全部 ${条目.length} 条**效果一次性翻译成「战斗解释」，用一次回复全部返回。

${数值口径}

【待翻译清单】
${清单}

【常驻增益怎么填】（被动技能 / 装备效果 / 天赋 / 血统 / 职业特性的"一直生效"部分）
用 {"触发":"常驻", "作用域":..., "动作":[{"类":"数值修正","目标":"伤害","量":...}]}：
- 作用域 填 "自身"（只影响自己）或 "我方全体"（光环，影响全队）—— **两种引擎都认**，
  开战时会把它们落成状态写进「特殊状态」，面板上看得见。
- 装备/天赋/血统里纯数值的部分（加防御、加闪避、加最大HP…）通常已经算进卡面了，**不要重复填**；
  只填卡面没体现的效果（增伤、减伤、附加词条、触发型效果）。

【「下一次」类增益怎么写】
- 「下一次技能不进入冷却」→ 动作 {"类":"施加状态","名":"...","持续":2,"词条":["免冷却"]}
- 「下一次技能释放两次」  → 动作 {"类":"施加状态","名":"...","持续":2,"词条":["连击"]}
  （等价写法：{"类":"追加攻击","次数":1}）
  这两个词条名是引擎的约定，引擎会**消耗**它们。

【触发点怎么选】（这 11 个引擎都会执行，选对时机才能生效）
- 「常驻」：一直生效（被动/光环/装备）。开战时落成状态，面板与「特殊状态」都看得见。
- 「进入战斗」：开战那一下一次性生效（进场护盾/进场资源/进场标记）。
- 「回合开始」：每回合开始时跑一次（每回合蓄能、每回合回复护盾/HP、回合开始的持续增益）。
- 「回合结束」：每回合收尾时跑一次（尾结算类的回复/扣血/状态切换）。
- 「使用时」：**放出来的瞬间**。**该次攻击自身**的增减益用这个
  （例：「该次攻击最终伤害×5」→ 触发 使用时 + 作用域 自身）。
- 「攻击时」：攻击路径上等同「使用时」（卡面两种写法都认）。
- 「命中时」：**打中之后**才结算（给目标上 debuff、追加攻击、范围伤害…）。
- 「受击时」/「被命中后」：**被打的那个人的视角**，写在他自己的技能里。
  作用域「攻击者」= 打他的人（例：被命中后给攻击者挂标记），「自身」= 他自己。
- 「击杀时」：**把目标打倒的那一刻**，跑击杀者的规则（吸血/回资源/叠层…）。
- 「资源变化时」：这个单位的 HP/资源发生变化时跑（配合下面的条件做「血量低于 50% 就触发」）。

【条件怎么写】（可选；不满足时该规则不生效，引擎会在战报里写明）
条件形如 条件: { 左: {...}, 比较: "≥|>|≤|<|=", 右: {...} }，左右都用一个「取值」：
- 常数：{ 源: "常数", 系数: 0.5 }
- 自身资源：{ 源: "资源", 名: "能量" }
- **自身当前状态**用表达式：{ 源: "表达式", 式: "HP比例" }（血量百分比 0~1）
  表达式里可用的标识符：当前HP / 当前MP / 当前耐力 / HP比例 / 最大HP / 最大MP / 最大耐力 /
  STR修正 / AGI修正 / CON修正 / PER修正 / 防御 / 闪避 / 层数（配合 名 取某状态的层数）
- 例：「血量低于 50% 才能发动」→ 条件: { 左: { 源: "表达式", 式: "HP比例" }, 比较: "<", 右: { 源: "常数", 系数: 0.5 } }

【数值修正能改哪些东西】
伤害 / 最终乘区（真·最终伤害倍率，填 N−1 = ×N）/ 减伤 / 命中 / 闪避 / **防御** /
STR / AGI / CON / PER（**属性点**：填卡面写的点数，引擎按位阶系数换算成修正值，
例「清空防御换取等量 STR」→ 目标 防御 量 0−防御，目标 STR 量 防御）/
反应动作 / 次要行动 / 移动距离 / 攻击倍率 / 基础伤害骰。
⚠️ 后五个（反应动作/次要行动/移动距离/攻击倍率/基础伤害骰）引擎**还没读**，写了不生效。

【规则系效果怎么写】（必中 / 必暴 / 穿透 / 即死 / 无敌 / 锁血 / 无视）
卡面里出现"无视一切""最高优先级""必定命中""无法闪避""即死""无敌"这类**开挂式**描述时，
一律用动作 { 类: "规则系判定", 效果: "穿透|必中|必暴|即死|无敌|锁血|无视", 目标: "..." }，
**绝不要**翻译成普通的加伤/减伤（那是违规的写法）。

引擎有**防火墙**，敌我一视同仁：
- **攻方主动**的效果（穿透/必中/必暴/即死/无视）：**必须过判定**才生效，没过等于没这条。
  判定值 = 1d20 + 关联属性修正；对抗目标 =（基础DC + 目标属性修正）× 类型系数 + 目标属性修正。
- **守方被动**的效果（无敌/锁血/无视）：不用主动判定，**一直生效**；只在被穿透/无视时参与对抗。
- 双方都过 → 拼**属性修正值**（不看基础/实际属性），持平时 1d2（1=攻方，2=守方）。

引擎怎么落地：穿透 = 无视防御/护盾/减伤；必中 = 直接命中；必暴 = 直接暴击；
即死 = 直接把目标打到 0 HP；无敌 = 免除此击全部伤害；锁血 = HP 不低于 1；
无视 = 可以打中带「不可被常规攻击命中」词条的目标。

【两个约定词条】（引擎直接检查，不过判定；名字必须一字不差）
- "不可被常规攻击命中"：常规攻击打不中它（只有规则系的 穿透/无视 通过判定才打得中）。
  卡面写"无法被常规地面攻击命中""只有对空/飞行单位能打到"这类，就用它。
- "禁位移"：该单位无法移动。
用 动作 { 类: "词条", 名: "不可被常规攻击命中", 操作: "附加" } 施加。

【伤害类效果怎么写】
- 「该次攻击最终伤害×N」→ 触发 使用时 + 动作 数值修正，目标填 **最终乘区**，量填 N−1
  （填 4 = ×5）。**不要**用「伤害」：「伤害」进的是效果乘区（世界书的递减曲线），乘不到 5。
- 「伤害 +X%」这类常规增伤 → 目标填 伤害，量填 X/100。
- 「额外自动追加 N 次攻击」→ 动作 { 类: 追加攻击, 次数: N }
  （只在主攻击时计一次，追加出来的攻击不会再触发它）。
- 「半径 X 米的范围伤害」→ 动作 { 类: 范围伤害, 中心: 命中点, 半径: X, 量: {...} }
  （一维距离：距中心不超过 X 米的其他单位都吃这份伤害；施法者自己与中心目标不重复吃）。

【变身 / 形态类主动技能】（卍解、万解、界王拳、二阶段……）
用动作 {"类":"切换形态","到":"形态名"}。引擎会把它写成一条状态
（面板与写回卡里的「特殊状态」都看得见），不要只写在叙述里。

【资源消耗】
技能的 MP / 耐力消耗照实填进 "消耗"（如 "MP 5"、"耐力 10"、"无"）。
引擎在**回合开始**按 CON/PER 修正恢复，在**使用技能时**扣掉；不够就发动不了。

【输出格式】必须是合法 JSON，且**条数与上面完全一致**（每条一个对象，用 "编号" 对号入座）：
{
  "解释": [
    { "编号": 0, ...第 0 条的战斗解释... },
    { "编号": 1, ...第 1 条的战斗解释... }
  ]
}

单条战斗解释的字段：
${单条输出格式}

规则系效果（必中/即死/无敌/锁血/穿透/无视）一律用 "规则系判定" 动作。
翻译不了的效果放进 "托管"，原文留底。
**不要漏条目，不要改编号，不要额外解释。**`;
}

/** 校验一条战斗解释的必填字段（AI 返回的原始对象） */
export function 校验战斗解释(对象: any): 战斗解释 {
  if (!对象 || typeof 对象 !== 'object') throw new Error('战斗解释不是对象');
  if (!对象.行动消耗) throw new Error('缺少必填字段: 行动消耗');
  if (!对象.射程) throw new Error('缺少必填字段: 射程');
  if (!对象.目标) throw new Error('缺少必填字段: 目标');
  if (对象.消耗 === undefined) throw new Error('缺少必填字段: 消耗');
  if (对象.冷却 === undefined) throw new Error('缺少必填字段: 冷却');
  if (!对象.分类) throw new Error('缺少必填字段: 分类');
  if (!对象.类型) throw new Error('缺少必填字段: 类型');
  if (对象.可预判 === undefined) throw new Error('缺少必填字段: 可预判');
  // 规则 / 托管是**可空的列表**：模型对「没有要托管的」常会直接省略这个键。
  // 把它当必填，会让一整批明明翻对了的条目被判失败（实战：乌尔奇奥拉 15 项全因缺托管被丢）。
  if (!Array.isArray(对象.规则)) 对象.规则 = [];
  if (!Array.isArray(对象.托管)) 对象.托管 = [];
  return 对象 as 战斗解释;
}

/** 解析单条（保留给测试与单条兜底） */
export function 解析翻译结果(json: string): 战斗解释 {
  return 校验战斗解释(JSON.parse(json));
}

/** 单条解析结果 —— 失败时必须带**原因**，否则玩家只能看到「不可用」却不知道该怎么办 */
export type 条目解析结果 = { 成功: true; 解释: 战斗解释 } | { 成功: false; 原因: string };

/**
 * 解析批量翻译结果 —— 返回**与入参等长**的数组，按 `编号` 对号入座。
 * 单条不合法 / 编号越界 / 整条缺失 → 该项 `成功: false` 并带明确原因，
 * **不因为一条坏而丢掉整批**。
 */
export function 解析批量翻译结果(json: string, 条目数: number): 条目解析结果[] {
  const 解析出的 = JSON.parse(json);
  const 数组 = Array.isArray(解析出的) ? 解析出的 : 解析出的?.解释;
  if (!Array.isArray(数组)) throw new Error('批量翻译结果里没有 "解释" 数组');

  const 结果: 条目解析结果[] = new Array(条目数)
    .fill(null)
    .map(() => ({ 成功: false as const, 原因: '模型未返回该条（漏条目）' }));

  for (const 项 of 数组) {
    const 编号 = Number(项?.编号);
    if (!Number.isInteger(编号) || 编号 < 0 || 编号 >= 条目数) continue;
    try {
      结果[编号] = { 成功: true, 解释: 校验战斗解释(项) };
    } catch (e: any) {
      结果[编号] = { 成功: false, 原因: `字段不合法：${e?.message ?? e}` };
    }
  }
  return 结果;
}

/**
 * 批量翻译的 JSON Schema —— 传给 aiGenerate 以启用「非法 JSON 重试」链路。
 * 只约束「有个 解释 数组」，单条字段由 `校验战斗解释` 兜底。
 *
 * **注意：不要往 properties 里加可选键。** `sanitizeJsonSchema` 会把每个 object 的 `required`
 * 覆写成全部 property 键（见 src/wxhl-003/schemaSanitize.ts），放进去就是在 wire 上强制必填。
 */
export const 批量战斗解释_SCHEMA = {
  name: 'combat_interpretation_batch',
  value: {
    type: 'object',
    properties: {
      解释: { type: 'array' },
    },
    required: ['解释'],
  },
};
