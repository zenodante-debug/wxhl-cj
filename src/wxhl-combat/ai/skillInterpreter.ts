// 无限回廊 · 前端战斗引擎 · 效果翻译器
// **整场战斗只调 1 次 AI**（spec §10.1）：把所有参战单位的技能/装备/天赋/血统
// 一次性发给模型，拿回一张 编号 → 战斗解释 的表，再按编号回填到各单位。
//
// 为什么按**编号**回填而不是按名字：效果名会跨单位重名
// （两个敌人都叫「斩击」、玩家的「长剑」与敌人的「长剑」），按名字装表会互相覆盖。
// ================================================================

import type { 战斗解释 } from '../types';

/** 一条待翻译的效果 */
export interface 待翻译条目 {
  /** 归属单位 id（只用于回填，不影响翻译） */
  单位: string;
  /** 效果名（技能名 / `装备名（槽）` / `天赋名（天赋）`…） */
  名称: string;
  /** 发给模型的原始字段 */
  来源: Record<string, any>;
}

