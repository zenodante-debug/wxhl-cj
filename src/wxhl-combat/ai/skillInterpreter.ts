/**
 * 构建批量翻译提示词：**一条消息装下所有效果**。
 * 条目必须带上 `编号` 回传，按编号对号入座。
 */
export function 构建批量翻译提示词(条目: 待翻译条目[]): string {
  const 清单 = 条目
    .map((条, i) =>
      [
        `【编号 ${i}】${条.单位} · ${条.名称}`,
        `类型: ${条.来源?.类型 ?? ''}`,
        `行动类型: ${条.来源?.行动类型 ?? ''}`,
        `关联属性: ${条.来源?.关联属性 ?? ''}`,
        `阶位: ${条.来源?.阶位 ?? ''}`,
        `消耗: ${条.来源?.消耗 ?? ''}`,
        `冷却: ${条.来源?.冷却 ?? ''}`,
        `射程: ${条.来源?.射程 ?? ''}`,
        `目标: ${条.来源?.目标 ?? ''}`,
        `效果: ${JSON.stringify(条.来源?.效果 ?? {}, null, 2)}`,
      ].join('\n'),
    )
    .join('\n\n');

  return `把下面**全部 ${条目.length} 条**效果一次性翻译成「战斗解释」，用一次回复全部返回。

${数值口径}

【待翻译清单】
${清单}

【输出格式】必须是合法 JSON，且**条数与上面完全一致**（每条一个对象，用 "编号" 对号入座）：
{
  "解释": [
    { "编号": 0, ...第 0 条的战斗解释... },
    { "编号": 1, ...第 1 条的战斗解释... }
  ]
}

单条战斗解释的字段：
${单条输出格式}

规则系效果（必中/即死/无敌/锁血/穿透/无视）一律用 "规则系判定" 动作。
翻译不了的效果放进 "托管"，原文留底。
**不要漏条目，不要改编号，不要额外解释。**`;
}

/** 校验一条战斗解释的必填字段（AI 返回的原始对象） */
export function 校验战斗解释(对象: any): 战斗解释 {
  if (!对象 || typeof 对象 !== 'object') throw new Error('战斗解释不是对象');
  if (!对象.行动消耗) throw new Error('缺少必填字段: 行动消耗');
  if (!对象.射程) throw new Error('缺少必填字段: 射程');
  if (!对象.目标) throw new Error('缺少必填字段: 目标');
  if (对象.消耗 === undefined) throw new Error('缺少必填字段: 消耗');
  if (对象.冷却 === undefined) throw new Error('缺少必填字段: 冷却');
  if (!对象.分类) throw new Error('缺少必填字段: 分类');
  if (!对象.类型) throw new Error('缺少必填字段: 类型');
  if (对象.可预判 === undefined) throw new Error('缺少必填字段: 可预判');
  if (!Array.isArray(对象.规则)) throw new Error('缺少必填字段: 规则');
  if (!Array.isArray(对象.托管)) throw new Error('缺少必填字段: 托管');
  return 对象 as 战斗解释;
}

/** 解析单条（保留给测试与单条兜底） */
export function 解析翻译结果(json: string): 战斗解释 {
  return 校验战斗解释(JSON.parse(json));
}

/**
 * 解析批量翻译结果 —— 返回**与入参等长**的数组，按 `编号` 对号入座。
 * 单条不合法 / 编号越界 / 整条缺失 → 该位为 `null`（由调用方点名「本场不可用」），
 * **不因为一条坏而丢掉整批**。
 */
export function 解析批量翻译结果(json: string, 条目数: number): Array<战斗解释 | null> {
  const 解析出的 = JSON.parse(json);
  const 数组 = Array.isArray(解析出的) ? 解析出的 : 解析出的?.解释;
  if (!Array.isArray(数组)) throw new Error('批量翻译结果里没有 "解释" 数组');

  const 结果: Array<战斗解释 | null> = new Array(条目数).fill(null);
  for (const 项 of 数组) {
    const 编号 = Number(项?.编号);
    if (!Number.isInteger(编号) || 编号 < 0 || 编号 >= 条目数) continue;
    try {
      结果[编号] = 校验战斗解释(项);
    } catch {
      /* 单条字段不全 → 留 null，由调用方点名 */
    }
  }
  return 结果;
}

/**
 * 批量翻译的 JSON Schema —— 传给 aiGenerate 以启用「非法 JSON 重试」链路。
 * 只约束「有个 解释 数组」，单条字段由 `校验战斗解释` 兜底。
 *
 * **注意：不要往 properties 里加可选键。** `sanitizeJsonSchema` 会把每个 object 的 `required`
 * 覆写成全部 property 键（见 src/wxhl-003/schemaSanitize.ts），放进去就是在 wire 上强制必填。
 */
export const 批量战斗解释_SCHEMA = {
  name: 'combat_interpretation_batch',
  value: {
    type: 'object',
    properties: {
      解释: { type: 'array' },
    },
    required: ['解释'],
  },
};
