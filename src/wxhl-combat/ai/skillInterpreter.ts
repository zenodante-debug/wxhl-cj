/**
 * 构建批量翻译提示词：**一条消息装下所有效果**。
 * 条目必须带上 `编号` 回传，按编号对号入座。
 */
export function 构建批量翻译提示词(条目: 待翻译条目[]): string {
  const 清单 = 条目
    .map((条, i) =>
      [
        `【编号 ${i}】${条.单位} · ${条.名称}`,
        `类型: ${条.来源?.类型 ?? ''}`,
        `行动类型: ${条.来源?.行动类型 ?? ''}`,
        `关联属性: ${条.来源?.关联属性 ?? ''}`,
        `阶位: ${条.来源?.阶位 ?? ''}`,
        `消耗: ${条.来源?.消耗 ?? ''}`,
        `冷却: ${条.来源?.冷却 ?? ''}`,
        `射程: ${条.来源?.射程 ?? ''}`,
        `目标: ${条.来源?.目标 ?? ''}`,
        `效果: ${JSON.stringify(条.来源?.效果 ?? {})}`, // 紧凑序列化（不用 null,2 缩进）—— 提示词越小越快、越不容易撞限
      ].join('\n'),
    )
    .join('\n\n');

  return `把下面**全部 ${条目.length} 条**效果一次性翻译成「战斗解释」，用一次回复全部返回。

${数值口径}

【待翻译清单】
${清单}

【常驻增益怎么填】（被动技能 / 装备效果 / 天赋 / 血统 / 职业特性的"一直生效"部分）
用 {"触发":"常驻", "作用域":..., "动作":[{"类":"数值修正","目标":"伤害","量":...}]}：
- 作用域 填 "自身"（只影响自己）或 "我方全体"（光环，影响全队）—— **两种引擎都认**，
  开战时会把它们落成状态写进「特殊状态」，面板上看得见。
- 装备/天赋/血统里纯数值的部分（加防御、加闪避、加最大HP…）通常已经算进卡面了，**不要重复填**；
  只填卡面没体现的效果（增伤、减伤、附加词条、触发型效果）。

【「下一次」类增益怎么写】
- 「下一次技能不进入冷却」→ 动作 {"类":"施加状态","名":"...","持续":2,"词条":["免冷却"]}
- 「下一次技能释放两次」  → 动作 {"类":"施加状态","名":"...","持续":2,"词条":["连击"]}
  （等价写法：{"类":"追加攻击","次数":1}）
  这两个词条名是引擎的约定，引擎会**消耗**它们。

【行动类型怎么填】（「行动消耗」 这个字段装的是**行动类型**，不是资源消耗）
- 取值只有：「主要行动」 / 「次要行动」 / 「反应动作」 / 「免费行动」 / 「无」。
- **反应动作**：卡面写「反应动作」「招架/格挡/闪烁/识破/击溃」这类**被打时才能用**的技能，
  一律填 「反应动作」。引擎只在**被攻击时**自动使用（玩家预置了才用），不占主要/次要槽。
  - 其中「取消对方攻击」的（击溃/识破/打断）还要额外产出一条约定词条：
    额外加一条规则 {"触发":"使用时","作用域":"自身","动作":[{"类":"词条","名":"打断"}]}
    —— 引擎看到「打断」就走世界书的打断检定（1d20 劣势 + 属性修正×3/4 对抗攻方命中）。
- **免费行动**：卡面写「免费动作/不占行动/即时」的填 「免费行动」。
- **装备/道具的主动效果**如果卡面没写行动类型 → 填 「免费行动」（引擎也只认免费行动，
  冷却默认 1 回合，所以不会变成无限制连放）。纯被动/常驻效果填 「无」，**不要**填成行动。
- 只有填了行动类型的技能才会出现在行动下拉里；填 「无」 的只当被动算数值。

【触发点怎么选】（这 11 个引擎都会执行，选对时机才能生效）
- 「常驻」：一直生效（被动/光环/装备）。开战时落成状态，面板与「特殊状态」都看得见。
- 「进入战斗」：开战那一下一次性生效（进场护盾/进场资源/进场标记）。
- 「回合开始」：每回合开始时跑一次（每回合蓄能、每回合回复护盾/HP、回合开始的持续增益）。
- 「回合结束」：每回合收尾时跑一次（尾结算类的回复/扣血/状态切换）。
- 「使用时」：**放出来的瞬间**。**该次攻击自身**的增减益用这个
  （例：「该次攻击最终伤害×5」→ 触发 使用时 + 作用域 自身）。
- 「攻击时」：攻击路径上等同「使用时」（卡面两种写法都认）。
- 「命中时」：**打中之后**才结算（给目标上 debuff、追加攻击、范围伤害…）。
- 「受击时」/「被命中后」：**被打的那个人的视角**，写在他自己的技能里。
  作用域「攻击者」= 打他的人（例：被命中后给攻击者挂标记），「自身」= 他自己。
- 「击杀时」：**把目标打倒的那一刻**，跑击杀者的规则（吸血/回资源/叠层…）。
- 「资源变化时」：这个单位的 HP/资源发生变化时跑（配合下面的条件做「血量低于 50% 就触发」）。

【条件怎么写】（可选；不满足时该规则不生效，引擎会在战报里写明）
条件形如 条件: { 左: {...}, 比较: "≥|>|≤|<|=", 右: {...} }，左右都用一个「取值」：
- 常数：{ 源: "常数", 系数: 0.5 }
- 自身资源：{ 源: "资源", 名: "能量" }
- **自身当前状态**用表达式：{ 源: "表达式", 式: "HP比例" }（血量百分比 0~1）
  表达式里可用的标识符：当前HP / 当前MP / 当前耐力 / HP比例 / 最大HP / 最大MP / 最大耐力 /
  STR修正 / AGI修正 / CON修正 / PER修正 / 防御 / 闪避 / 层数（配合 名 取某状态的层数）
- 例：「血量低于 50% 才能发动」→ 条件: { 左: { 源: "表达式", 式: "HP比例" }, 比较: "<", 右: { 源: "常数", 系数: 0.5 } }

【数值修正怎么填】动作形如 { 类: "数值修正", 目标: "...", 量: {...} } ——
「目标」是**改哪个人物面板/公式里的数字**，「量」是改多少。各目标改什么：

| 目标 | 改的是 | 例子 |
| :--- | :--- | :--- |
| 伤害 | 第四步总增伤（进递减乘区） | 「伤害+30%」→ 量 0.3 |
| 最终乘区 | 直接乘在最终伤害上 | 「最终伤害×5」→ 量 4 |
| 减伤 | 第六步减伤比例（封顶 50%） | 「减伤 20%」→ 量 0.2 |
| 命中 | 命中判定的被动加成 | 「命中+2」→ 量 2 |
| 闪避 | 目标闪避值（即命中 DC） | 「闪避+5」→ 量 5 |
| 防御 | 混合伤害里减掉的防御 | 「防御+10」→ 量 10；「防御清零」→ 量 0−防御 |
| STR修正/AGI修正/CON修正/PER修正 | **属性修正值**直接增量（不再乘位阶系数）。判定与伤害用的都是修正值 —— 卡面写「修正+X」「全属性强制削减Y%」就用它 | 「STR修正+20」→ 目标 STR修正 量 20 |
| STR/AGI/CON/PER | **属性点**增量（引擎按位阶系数换算成修正值） | 「STR+10」→ 目标 STR 量 10 |
| 反应动作 | 每回合的反应动作**次数** | 「额外获得一次反应动作」→ 量 1 |
| 次要行动 | 每回合的次要行动**次数** | 「额外获得一次次要行动」→ 量 1 |
| 主要行动 | 每回合的主要行动**次数** | 「额外获得一次主要行动」→ 量 1 |
| 额外行动回合 | **一整套行动槽**（主/次/移/反各 +1、再给一份移动额度），且当场打断让玩家重选一轮 | 「获得一个额外行动回合」→ 量 1 |
| 移动距离 | 每回合移动**额度**（米） | 「移动距离+30」→ 量 30 |
| 攻击倍率 | 武器的**倍率** | 「武器威力+50%」→ 量 0.5 |
| 基础伤害骰 | 武器伤害**骰值总和** | 「伤害骰+4」→ 量 4 |

【变身 / 阶段切换类技能怎么写】（「血量归零时进入二阶段，回满血并且全属性翻倍，只能触发一次」这类）
- **触发**：「资源变化时」+ 条件 {"左":{"源":"表达式","式":"当前HP"},"比较":"≤","右":{"源":"常数","系数":0}}
- **只能触发一次**：动作里包一个 「条件分支」，条件查自己有没有「已X阶段」词条：
  {"类":"条件分支","条件":{"左":{"源":"目标词条","名":"已二阶段"},"比较":"=","右":{"源":"常数","系数":0}},
   "真":[...变身效果...],"假":[]}
  真分支里最后一条必须是 {"类":"词条","名":"已二阶段"} —— 第二次归零时词条已存在，走空分支，什么都不发生。
- **回满血**：「资源」 动作的名字写 HP/MP/耐力（或 当前HP）会映射到**真实数值**（不是资源池）：
  {"类":"资源","名":"HP","操作":"设为","量":{"源":"表达式","式":"最大HP"}}
- **全属性翻倍**：四条 「数值修正」，目标 STR修正/AGI修正/CON修正/PER修正，
  量 {"源":"属性","名":"STR"}（= 当前修正值，加一遍就是翻倍），并且**持续必须写 999**
  （「数值修正」 不写持续只默认 2 回合，变身是整场生效）。所有判定与伤害用的都是修正值，
  所以"修正值翻倍"就是战斗意义上的"全属性翻倍"。
- **进阶段/变身要看得见**：真分支里带 {"类":"切换形态","到":"二阶段"}（落成「形态：X」状态，面板可见）。

【「额外行动」的两种写法 —— 按卡面文本分流】
- 卡面写「**额外获得一次主要行动**（或次要行动）」→ 用「主要行动」/「次要行动」，量 1
  （引擎在**回合开始**就多给一个槽，玩家在同一轮里连打两发，不打断）。
- 卡面写「**额外行动回合**」「额外行动次数」「额外一轮」「再行动一次」→ 用「额外行动回合」，量 1
  （引擎给**一整套槽**并**当场打断**，玩家重新指定一轮行动）。
- 两者不要混用：一个技能里只写一种。

【属性点 vs 修正值 —— 别填错通道】
- 卡面写的是**属性点**（「STR+10」「力量+5」）→ 用 STR/AGI/CON/PER，引擎会乘位阶系数。
- 卡面写的是**修正值**（「STR修正+20」「全属性修正-30%」「修正值翻倍」）→ 用 STR修正/AGI修正/CON修正/PER修正，引擎**直接**加到修正值上，不再乘系数。
- 拿不准就看卡面有没有「修正」两个字；真正参与判定与伤害的是修正值，所以直接改修正值的效果一律走"修正"通道。

同一个技能的**多条常驻规则会合并成一条状态**，所以一个被动里写多个修正是安全的。
「目标」写错/编新词 → 引擎认不出，本条不生效（会记一笔跳过）。

【伤害类效果怎么写】
- 「该次攻击最终伤害×N」→ 触发 使用时 + 动作 数值修正，目标填 **最终乘区**，量填 N−1
  （填 4 = ×5）。**不要**用「伤害」：「伤害」进的是效果乘区（世界书的递减曲线），乘不到 5。
- 「伤害 +X%」这类常规增伤 → 目标填 伤害，量填 X/100。
- 「额外自动追加 N 次攻击」→ 动作 { 类: 追加攻击, 次数: N }
  （只在主攻击时计一次，追加出来的攻击不会再触发它）。
- 「半径 X 米的范围伤害」→ 动作 { 类: 范围伤害, 中心: 命中点, 半径: X, 量: {...} }
  （一维距离：距中心不超过 X 米的其他单位都吃这份伤害；施法者自己与中心目标不重复吃）。

【变身 / 形态类主动技能】（卍解、万解、界王拳、二阶段……）
用动作 {"类":"切换形态","到":"形态名"}。引擎会把它写成一条状态
（面板与写回卡里的「特殊状态」都看得见），不要只写在叙述里。

【资源消耗】
技能的 MP / 耐力消耗照实填进 "消耗"（如 "MP 5"、"耐力 10"、"无"）。
引擎在**回合开始**按 CON/PER 修正恢复，在**使用技能时**扣掉；不够就发动不了。

【输出格式】必须是合法 JSON，且**条数与上面完全一致**（每条一个对象，用 "编号" 对号入座）：
{
  "解释": [
    { "编号": 0, ...第 0 条的战斗解释... },
    { "编号": 1, ...第 1 条的战斗解释... }
  ]
}

单条战斗解释的字段：
${单条输出格式}

规则系效果（必中/即死/无敌/锁血/穿透/无视）一律用 "规则系判定" 动作。
翻译不了的效果放进 "托管"，原文留底。
**不要漏条目，不要改编号，不要额外解释。**`;
}

/** 校验一条战斗解释的必填字段（AI 返回的原始对象） */
export function 校验战斗解释(对象: any): 战斗解释 {
  if (!对象 || typeof 对象 !== 'object') throw new Error('战斗解释不是对象');
  if (!对象.行动消耗) throw new Error('缺少必填字段: 行动消耗');
  if (!对象.射程) throw new Error('缺少必填字段: 射程');
  if (!对象.目标) throw new Error('缺少必填字段: 目标');
  if (对象.消耗 === undefined) throw new Error('缺少必填字段: 消耗');
  if (对象.冷却 === undefined) throw new Error('缺少必填字段: 冷却');
  if (!对象.分类) throw new Error('缺少必填字段: 分类');
  if (!对象.类型) throw new Error('缺少必填字段: 类型');
  if (对象.可预判 === undefined) throw new Error('缺少必填字段: 可预判');
  // 规则 / 托管是**可空的列表**：模型对「没有要托管的」常会直接省略这个键。
  // 把它当必填，会让一整批明明翻对了的条目被判失败（实战：乌尔奇奥拉 15 项全因缺托管被丢）。
  const 原始规则 = Array.isArray(对象.规则) ? 对象.规则 : [];
  if (!Array.isArray(对象.托管)) 对象.托管 = [];

  // **规则结构校验**（玩家实测：详情面板一整屏 `undefined → undefined：（无动作）`）：
  // 没触发点 / 空动作 / 动作不是对象的条目，引擎执行了也是空结果 —— 留着只会让人以为"翻了"。
  const { 规则, 丢弃 } = 归一化规则(原始规则);
  if (原始规则.length > 0 && 规则.length === 0) {
    throw new Error(`规则字段结构不完整（${原始规则.length} 条都没有触发点或动作），需要重翻`);
  }
  对象.规则 = 规则;
  对象.忽略的规则 = 丢弃;
  return 对象 as 战斗解释;
}

/** 解析单条（保留给测试与单条兜底）。走**宽容提取**：截断/围栏/散文包裹都能救。 */
export function 解析翻译结果(json: string): 战斗解释 {
  return 校验战斗解释(提取JSON(json));
}

/** 单条解析结果 —— 失败时必须带**原因**，否则玩家只能看到「不可用」却不知道该怎么办 */
export type 条目解析结果 = { 成功: true; 解释: 战斗解释 } | { 成功: false; 原因: string };

/**
 * 解析批量翻译结果 —— 返回**与入参等长**的数组，按 `编号` 对号入座。
 * 单条不合法 / 编号越界 / 整条缺失 → 该项 `成功: false` 并带明确原因，
 * **不因为一条坏而丢掉整批**。
 */
export function 解析批量翻译结果(json: string, 条目数: number): 条目解析结果[] {
  // 宽容提取（含**截断抢救**）：被 max_tokens 切掉尾巴时，捞回已经完整的条目，
  // 缺的那几条按「模型未返回该条」进复核 —— 以前这里裸 JSON.parse，一炸就是整批全丢。
  const 解析出的 = 提取JSON(json);
  const 数组 = Array.isArray(解析出的) ? 解析出的 : 解析出的?.解释;
  if (!Array.isArray(数组)) throw new Error('批量翻译结果里没有 "解释" 数组');

  const 结果: 条目解析结果[] = new Array(条目数)
    .fill(null)
    .map(() => ({ 成功: false as const, 原因: '模型未返回该条（漏条目）' }));

  for (const 项 of 数组) {
    const 编号 = Number(项?.编号);
    if (!Number.isInteger(编号) || 编号 < 0 || 编号 >= 条目数) continue;
    try {
      结果[编号] = { 成功: true, 解释: 校验战斗解释(项) };
    } catch (e: any) {
      结果[编号] = { 成功: false, 原因: `字段不合法：${e?.message ?? e}` };
    }
  }
  return 结果;
}

