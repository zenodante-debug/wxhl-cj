// ================================================================
// 无限回廊 · 前端战斗引擎 · 敌方意图生成
// 每回合一次 AI 调用：为每个敌方单位决定本回合的行动意图（不掷骰）
// ================================================================

import type { 战斗状态 } from '../types';

export interface 敌方意图 {
  单位: string;
  行动: 意图行动[];
}

export interface 意图行动 {
  类型: '主要行动' | '次要行动' | '移动' | '反应动作';
  技能?: string;
  目标?: string;
  距离?: number;
}

/**
 * 构建敌方意图提示词
 */
export function 构建敌方意图提示词(状态: 战斗状态): string {
  const 敌方单位 = Object.values(状态.单位).filter(u => u.阵营 === '敌方');
  const 我方单位 = Object.values(状态.单位).filter(u => u.阵营 === '我方');

  let 提示词 = `当前是第 ${状态.回合} 回合，请为每个敌方单位决定本回合的行动意图。

【战场状态】
先攻顺序：${状态.先攻.join(' → ')}

【敌方单位】
${敌方单位.map(u => `- ${u.id}（${u.类型}）：距离 ${u.距离}米，HP ${u.护盾 > 0 ? `护盾${u.护盾}` : '满血'}，状态 ${u.状态.map(s => s.名).join(',') || '无'}`).join('\n')}

【我方单位】
${我方单位.map(u => `- ${u.id}（${u.类型}）：距离 ${u.距离}米`).join('\n')}

【任务】
以杀死玩家为目的，为每个敌方单位决定本回合的行动意图（不掷骰）。

【输出格式】（必须是合法 JSON 数组）
[
  {
    "单位": "骨卫兵",
    "行动": [
      { "类型": "移动", "目标": "玩家", "距离": 0 },
      { "类型": "主要行动", "技能": "骨爪撕裂", "目标": "玩家" }
    ]
  }
]

【原则】
- 敌人是绝顶聪明的战术大师，会主动结合技能/天赋/血统和装备进行攻击和防御，不会等死
- 行动类型只能是：主要行动/次要行动/移动/反应动作
- 每个单位每回合最多：主要行动×1、次要行动×1、移动×1、反应动作×1
- 移动时要写目标距离（米）
- 使用技能时要写技能名和目标`;

  return 提示词;
}

/**
 * 解析敌方意图
 */
export function 解析敌方意图(json: string): 敌方意图[] {
  const obj = JSON.parse(json);

  if (!Array.isArray(obj)) {
    throw new Error('敌方意图必须是数组');
  }

  for (const 意图 of obj) {
    if (!意图.单位) throw new Error('缺少必填字段: 单位');
    if (!Array.isArray(意图.行动)) throw new Error('缺少必填字段: 行动');
  }

  return obj as 敌方意图[];
}
