// ================================================================
// 无限回廊 · 前端战斗引擎 · 敌方意图生成
// 每回合一次 AI 调用：为每个敌方单位决定本回合的行动意图（不掷骰）
//
// ⚠️ 提示词里**必须**带上每个单位的技能表原名（spec §10.3 的输入要求）。
// 曾经的 bug：提示词只写了「距离/HP/状态」，却要求模型输出 `"技能": "骨爪撕裂"` ——
// 模型没有任何办法知道真名，只能瞎编，而引擎对不存在的技能名一律跳过，
// 于是**敌人的每一次主要行动都必然被跳过，整场战斗敌人一次也没出招**。
// ================================================================

import type { 战斗状态, 战斗单位, 战斗解释, 行动声明 } from '../types';
import { 距离带 } from '../engine/distance';
import { 行动消耗文本 } from '../engine/actionOptions';
import { 提取JSON } from './jsonExtract';

export interface 敌方意图 {
  单位: string;
  行动: 意图行动[];
}

/**
 * 敌方（或随机模式）产出的**一条意图** —— 与 `行动声明` 同形（引擎两边共用一条结算路径）。
 * 单独的别名是为了让 AI 侧的签名读起来清楚：这里的字段**由 AI/随机模式填**，
 * 而「主武器攻击/副武器攻击」这类只有界面才知道的东西用 `武器` 表达。
 */
export type 意图行动 = 行动声明;

/** 显示名：变量里的姓名（`头部.姓名`）；缺省退回变量路径最后一段 */
function 显示名(u: 战斗单位): string {
  return u.名称 || u.id.split('.').pop() || u.id;
}

/** 一个技能在提示词里的一行摘要 —— 只写 AI 决定行动要用的字段 */
function 技能行(名: string, 解释: 战斗解释): string {
  const 伤害 = typeof 解释.伤害倍率 === 'number' && 解释.伤害倍率 > 0 ? `｜伤害倍率 ${解释.伤害倍率}` : '';
  return `    - ${名}｜${行动消耗文本(解释) || '主要行动'}｜射程 ${解释.射程 || '未写'}｜目标 ${
    解释.目标 || '单体'
  }｜消耗 ${解释.消耗 || '无'}｜冷却 ${解释.冷却 ?? 0}｜${解释.类型 || '主动'}${伤害}`;
}

/** 技能表段：**技能名的唯一合法来源**。空表要明说，避免模型被逼着编名字 */
function 技能表段(u: 战斗单位): string {
  const 条目 = Object.entries(u.技能 ?? {});
  if (条目.length === 0) return '    （这个单位没有任何技能 —— 只能移动、或省略 "技能" 键做基础攻击）';
  return 条目.map(([名, 解释]) => 技能行(名, 解释)).join('\n');
}

/** 一个单位的完整战况块 */
function 单位块(u: 战斗单位, 标签: string): string {
  const 状态 =
    u.状态.length === 0
      ? '无'
      : u.状态.map(s => `${s.名}${s.层数 ? `×${s.层数}` : ''}（剩 ${s.持续} 回合）`).join('、');
  const 词条 = [...(u.词条 ?? [])].join('、') || '无';
  const 武器 = u.主武器
    ? `${u.主武器.伤害骰}（倍率 ${u.主武器.倍率}，强化 +${u.主武器.强化等级}）`
    : '无（徒手：骰式随阶位 d4→11d4、倍率 0.5、射程近战）';

  // 注意「距玩家原点」：全场以玩家为唯一原点（引擎按 |攻方距离 − 守方距离| 算间距），
  // 我方单位这一行也是距玩家多少米，不是距敌人。
  return `▸ ${显示名(u)}｜${标签}｜id: ${u.id}
  类型 ${u.类型}｜阶位 ${u.阶位}｜属性 STR ${u.属性.实际.STR} / AGI ${u.属性.实际.AGI} / CON ${u.属性.实际.CON} / PER ${u.属性.实际.PER}
  距玩家原点 ${u.距离} 米（${距离带(u.距离)}）｜行动槽 主要${u.行动槽.主要} 次要${u.行动槽.次要} 移动${u.行动槽.移动} 反应${u.行动槽.反应}｜移动额度 剩余 ${u.额度} 米
  HP ${u.HP_当前}/${u.HP_最大}｜MP ${u.MP_当前}/${u.MP_最大}｜耐力 ${u.耐力_当前}/${u.耐力_最大}｜防御 ${u.防御}｜闪避值 ${u.闪避值}｜护盾 ${u.护盾}
  状态：${状态}｜词条：${词条}
  主武器：${武器}
  技能表（"技能" 只能填这里的名字）：
${技能表段(u)}`;
}

/** 敌方意图的 JSON Schema —— 与技能翻译同一条「净化 + 400 降级」通道，保证拿到 JSON 而不是散文 */
export const 敌方意图_SCHEMA = {
  name: 'enemy_intent',
  value: {
    type: 'object',
    properties: {
      意图: { type: 'array' },
    },
    required: ['意图'],
  },
};

/**
 * 构建敌方意图提示词。
 *
 * 三条硬性约束写死在提示词里，因为它们各自对应一个「敌人不出招」的失败模式：
 * 1. **技能名逐字照抄技能表** —— 编名字会被引擎按「没有该技能」跳过；
 * 2. **可以省略 "技能" 键做基础攻击** —— 给模型一条永远合法的出路，否则它只能编；
 * 3. **目标写我方 id 或「玩家」** —— 目标找不到同样会被跳过。
 */
export function 构建敌方意图提示词(状态: 战斗状态): string {
  // 只给**还活着**的敌人出意图：倒地（HP ≤ 0）的单位不能行动 ——
  // 以前把尸体也列进去，模型会给它写一堆行动，白烧 token 还容易看出破绽。
  const 敌方单位 = Object.values(状态.单位).filter(u => u.阵营 === '敌方' && u.HP_当前 > 0);
  const 我方单位 = Object.values(状态.单位).filter(u => u.阵营 === '我方');

  const 敌方块 = 敌方单位.length
    ? 敌方单位.map(u => 单位块(u, '敌方')).join('\n\n')
    : '（战场上没有敌方单位 —— 请返回 {"意图": []}）';
  const 我方块 = 我方单位.length
    ? 我方单位.map(u => 单位块(u, '我方')).join('\n\n')
    : '（战场上没有我方单位）';

  return `当前是第 ${状态.回合} 回合，请为**每一个敌方单位**决定本回合的行动意图（不掷骰，掷骰由引擎做）。

【先攻顺序】
${状态.先攻.join(' → ')}

【敌方单位】（你只能为这些单位决定行动）
${敌方块}

【我方单位】（你的目标；可以打任何一个）
${我方块}

【任务】按顺序做完这三步再动手，**不要只看名字就决定行动**：
① **先把每个单位的「能力面板」读完**：属性（STR/AGI/CON/PER）、HP、防御、闪避值、
   状态与词条、行动槽与移动额度、主武器、技能表（射程/消耗/冷却/伤害倍率）。
   面板决定了它能做什么、打不打得到、扛不扛得住。
② 为每个敌方单位决定本回合行动。目标优先级：
   1. **击杀** —— 集火一击就能打死的目标（优先残血、优先低防低闪避的）
   2. **削弱** —— 上流血/灼烧/破甲/中毒、打掉资源、破坏架势，逼它把行动花在自保上
   3. **控场 / 自保 / 增益** —— 拉近或拉开距离、给自己或队友上 buff、给残血队友治疗或护盾
   打不到就**不要硬打**：先移动、先上 buff、先蓄力 —— 但**不要站着不动**。
③ **敌人之间要配合**（这条很重要，单打独斗的敌人是最好杀的）：
   - 「目标」可以直接填**同阵营队友的 id**（包括自己）。引擎按**支援行动**结算：
     不掷命中、不造成伤害，只把技能的增益效果落到队友身上（打自己人不会被当成攻击）。
   - 典型配合：给爆发手加伤害 buff、给前排上护盾/减伤、给残血队友回血、
     先手控制（定身/麻痹/击退）再让后手单位爆发、多个单位集火同一个目标、A 打降防再让 B 收人头。
   - 先攻靠前的单位先上 buff，靠后的单位就能吃到（看上面的先攻顺序决定谁先谁后）。
   - 次要行动也能带技能，**但次要行动只能做支援**（同阵营/自身目标）；
     攻击类技能必须放在主要行动，写错了会被引擎拒绝。

【输出格式】必须是合法 JSON，不要 markdown 围栏、不要任何解释文字。
**每个行动单独一行**（不要嵌套数组）—— 行序无所谓，引擎会按 移动 → 次要 → 主要 排好：
{
  "意图": [
    { "单位": "副本角色.骨卫兵", "类型": "移动", "目标": "玩家", "距离": 0 },
    { "单位": "副本角色.骨卫兵", "类型": "主要行动", "技能": "骨爪撕裂", "目标": "玩家" },
    { "单位": "副本角色.骨弓手", "类型": "次要行动", "技能": "战意号令", "目标": "副本角色.骨卫兵" }
  ]
}
（嵌套数组对小模型最难 —— 常漏括号、少层级。「一行一个行动」只要对着抄就能写对。）

【硬性要求】（违反会导致该行动被引擎跳过 —— 引擎只认真名、真 id）
1. "技能" **必须逐字照抄上面该单位「技能表」里的技能名**。
   不要加书名号/引号、不要翻译、不要改写、不要自己发明名字。
   技能表里没有合适的攻击手段、或你想让它用武器或拳头平A时：**省略 "技能" 键**
   （省略 = 基础攻击，永远可用）。
2. "单位" / "目标" 填**照抄的 id**（如 副本角色.骨卫兵）；打玩家写 "玩家"。
   省略"目标"时引擎按「打玩家」处理。
3. **名字是标识符，不是文本**：一个字都不要改，不要给汉字注读音（不要出现 ㄅㄆㄇ 注音符号、
   不要写拼音或拼音夹注如「幼(yòu)」）、不要繁简转换、不要"顺手"改错别字。
   不确定就照抄原样 —— 名字错一个字，这个行动就会被引擎丢掉。
4. "类型" 只能是：主要行动 / 次要行动 / 移动 / 反应动作（每回合各 1 次）。
5. "移动" 必须写 "距离"（= 该单位移动后距玩家的米数）。近战攻击要先把距离拉到 0~2 米。
   移动距离受「移动额度」限制，超了会被跳过。
6. 某个单位本回合不出手，就一行都不写它。
7. 每个敌方单位都要出现在数组里，**一个都不能漏**（漏掉的单位本回合只能空过）。

【原则】
- 敌人是绝顶聪明的战术大师，会主动结合技能/天赋/血统和装备进行攻击和防御，不会等死
- 以**杀死玩家为首要目标**，其次是削弱玩家（打掉资源、上负面状态、逼它防守）
- 会算账：一次打不死的目标先削弱，能一击打死的优先集火；打得中就打，打不到就先创造机会`;
}

/**
 * 解析敌方意图。
 *
 * 宽容三级：能剥 ```json 围栏与前后散文（见 `提取JSON`）。
 * **两种形状都认**：
 * - 扁平（新契约，更稳）：每行一个行动 `{单位, 类型, 技能?, 目标?, 距离?}` ——
 *   嵌套数组对小模型最难（漏括号/少层级就整场解析不出来），改成「一行一个行动」只要对着抄。
 * - 嵌套（旧契约）：`{单位, 行动: [...]}` —— 旧回复/老存档兼容。
 *
 * 两种都先**按单位分组**，再把每个单位的行动按 移动 → 次要 → 主要 → 反应 排好
 * （模型常把「移动」写在「主要行动」之后 —— 近战不先贴近会被射程门禁挡住）。
 * 单条缺字段不丢整批；缺「单位」的行留成空串，由 `跑敌方意图` 记一条可诊断日志。
 */
export function 解析敌方意图(json: string): 敌方意图[] {
  const 原始 = 提取JSON(json);

  const 数组 = Array.isArray(原始)
    ? 原始
    : Array.isArray(原始?.意图)
      ? 原始.意图
      : Array.isArray(原始?.敌方)
        ? 原始.敌方
        : null;

  if (!数组) {
    throw new Error('敌方意图里找不到意图数组（应为 [...] 或 {"意图": [...]}）');
  }

  const 按单位 = new Map<string, 意图行动[]>();
  const 记一行 = (单位: string, 行动: any) => {
    if (!行动 || typeof 行动 !== 'object') return;
    const 列表 = 按单位.get(单位) ?? [];
    列表.push({
      类型: 行动.类型,
      技能: 行动.技能,
      目标: 行动.目标,
      距离: 行动.距离,
    } as 意图行动);
    按单位.set(单位, 列表);
  };

  for (const 行 of 数组) {
    if (!行 || typeof 行 !== 'object') continue;
    // 中英文字段名都认 —— 有的模型会把键写成英文
    const 单位 = String(行.单位 ?? 行.名称 ?? 行.unit ?? 行.name ?? '');
    // 先登记这个单位（即使它的行动是空数组）：空数组 ≠ 不写它，
    // 「行动: []」是模型明说「本回合不出手」，要在结果里占一个位置
    if (!按单位.has(单位)) 按单位.set(单位, []);
    const 行动 = 行.行动 ?? 行.actions;
    if (Array.isArray(行动)) {
      for (const a of 行动) 记一行(单位, a); // 嵌套形状：{单位, 行动: [...]}
    } else if (行.类型 || 行.技能 || 行.目标 || 行.距离 !== undefined) {
      记一行(单位, 行); // 扁平形状：一行一个行动
    }
  }

  const 动作序 = (类型?: string) =>
    类型 === '移动' ? 0 : 类型 === '次要行动' ? 1 : 类型 === '主要行动' ? 2 : 3;

  return [...按单位.entries()].map(([单位, 行动]) => ({
    单位,
    行动: [...行动].sort((a, b) => 动作序(a.类型) - 动作序(b.类型)),
  }));
}
