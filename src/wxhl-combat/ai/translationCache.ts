// ================================================================
// 无限回廊 · 前端战斗引擎 · 效果翻译缓存
// 纯函数，不碰酒馆接口（读写脚本变量在 store.ts）
//
// spec §10.2：「缓存：整场战斗有效。技能升级才失效。」
// —— 「整场」早先做了，「跨场」没做：每进一次战斗都把玩家的全套技能重翻一遍。
//
// **为什么不按键名缓存**：技能升级、换装备、卡里的效果文本被改写之后，
// 同名技能的翻译就该作废。按名字存会一直喂旧翻译（而且同一名字在
// 不同单位上本来就可能不是一个东西）。所以缓存键是**内容指纹** ——
// 来源对象稳定序列化之后的串：内容一变，指纹就变，自动重翻，不用额外写
// 「技能升级才失效」的判定。
// ================================================================

/**
 * 缓存版本。**翻译口径 / 提示词 / 单条输出格式变了就 +1** ——
 * 旧缓存会整体失效（版本不符即视为空），不需要手写迁移。
 */
export const 翻译缓存版本 = 1;

/**
 * 稳定序列化：对象键排序后递归拼接，数组保序。
 * 同一份内容（即使键的书写顺序不同）永远得到同一个串 —— 这是指纹可用的前提。
 */
export function 稳定序列化(值: any): string {
  if (值 === null || typeof 值 !== 'object') {
    const 串 = JSON.stringify(值);
    return 串 === undefined ? 'null' : 串;
  }
  if (Array.isArray(值)) return `[${值.map(稳定序列化).join(',')}]`;

  const 键 = Object.keys(值)
    .filter(k => 值[k] !== undefined)
    .sort();
  return `{${键.map(k => `${JSON.stringify(k)}:${稳定序列化(值[k])}`).join(',')}}`;
}

/**
 * 一条效果源的内容指纹（含版本号）。
 * 指纹相同 = 内容相同 = 翻译可以复用，与它挂在哪个单位、叫什么名字无关。
 */
export function 效果指纹(来源: any): string {
  return `v${翻译缓存版本}:${稳定序列化(来源)}`;
}
