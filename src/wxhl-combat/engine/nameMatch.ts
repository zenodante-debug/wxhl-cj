// ================================================================
// 无限回廊 · 前端战斗引擎 · 名字解析（中文适配）
// 纯函数，不碰酒馆接口
//
// 为什么需要这一层：快路模型生成敌方意图时会把名字里的汉字换成注音符号
// （实战反馈：「工蜂异形幼体」→「工蜂异形ㄧㄡˋ体」），意图里的单位/目标于是对不上战场，
// 该行动被跳过 —— 表现成「敌人不出招」。
//
// 关键认知：那是**替换**不是夹注（原来那个「幼」已经不在了）。删掉注音只能得到
// 「工蜂异形体」（少一个字），把注音还原成汉字原理上做不到（ㄧㄡˋ 对应 幼/又/右/佑/宥/诱…
// 一对多）。所以流程是：**先去注音把编辑距离拉近 → 再在候选集里绑回唯一的那个**。
//
// 三层解析：精确 → 归一化精确 → 近似唯一。**拒绝优于错绑**：不满足唯一性就返回未命中，
// 由调用方把候选与相似度写进日志（可见、可重跑），绝不猜一个"最像的"去打。
// ================================================================

/** 允许的最小相似度。0.75 ≈ 「每 4 个字允许错 1 个字」 */
export const 近似阈值 = 0.75;

/** 第一名必须领先第二名这么多，才算"只有一个人选" */
export const 近似领先 = 0.15;

/** 归一化后短于这个长度不参与近似（两字名太容易撞，如「卫兵」vs「骨卫兵」） */
export const 最短可近似长度 = 3;

/** 长度差超过这个值不参与近似 */
export const 最大长度差 = 2;

/** 汉字（含扩展A与兼容区） */
const 汉字 = /[㐀-鿿豈-﫿]/;

/** 注音字母块（ㄅ–ㄩ）与注音调号（ˉˊˇˋ˙） */
const 注音 = /[ㄅ-ㄯˇˉˊˋ˙]/g;

/** 装饰性标点（引号/书名号/括号/逗号冒号等）—— 与技能名归一化同一套 */
const 装饰 = /[「」『』【】《》〈〉“”‘’"'`（）()\[\]{}·、,，。:：!！?？~～\-—_\/\\]/g;

/** 拉丁字母（含带声调的拼音元音），用于剥掉汉字名里的拼音夹注 */
const 拉丁 = /[A-Za-zÀ-ɏ]/g;

/**
 * 归一化名字，供比对用（**两侧都要过这一遍**）。
 *
 * 顺序：NFKC（全角→半角）→ 去空白（含全角空格）→ 去注音与调号 → 去装饰 →
 * 若这个名字里有汉字，再把拉丁字母一并剥掉（汉字名里的拉丁几乎都是拼音夹注：`幼(yòu)`）。
 *
 * **纯拉丁/数字名不剥拉丁**（`T-800`、`MK-II` 得留着），否则会把名字削成空串。
 * 归一化是**对称**的（两侧同规则），所以即使剥掉了一点东西也不会造成单侧失真。
 */
export function 归一化名(名: string): string {
  let 串 = String(名 ?? '')
    .normalize('NFKC')
    .replace(/[\s　]/g, '')
    .replace(注音, '')
    .replace(装饰, '');

  if (汉字.test(串)) 串 = 串.replace(拉丁, '');

  return 串;
}

/** 编辑距离（Levenshtein，按码点算，避免代理对被拆开） */
function 编辑距离(a: string, b: string): number {
  const x = [...a];
  const y = [...b];
  const d: number[][] = Array.from({ length: x.length + 1 }, (_, i) => [
    i,
    ...new Array<number>(y.length).fill(0),
  ]);
  for (let j = 0; j <= y.length; j++) d[0][j] = j;

  for (let i = 1; i <= x.length; i++) {
    for (let j = 1; j <= y.length; j++) {
      d[i][j] = Math.min(
        d[i - 1][j] + 1,
        d[i][j - 1] + 1,
        d[i - 1][j - 1] + (x[i - 1] === y[j - 1] ? 0 : 1),
      );
    }
  }
  return d[x.length][y.length];
}

/** 编辑距离折算成相似度（**原始串**，不做归一化 —— 归一化由 `相似度` 负责） */
export function 编辑距离相似度(a: string, b: string): number {
  const x = [...String(a ?? '')];
  const y = [...String(b ?? '')];
  if (x.length === 0 || y.length === 0) return 0;
  return 1 - 编辑距离(a, b) / Math.max(x.length, y.length);
}

/**
 * 相似度：**内部先归一化再算**（调用方不必也不该预先归一化 ——
 * 忘了归一化 = 注音没被删 = 距离回到 3 = 救不回来）。
 */
export function 相似度(a: string, b: string): number {
  const x = 归一化名(a);
  const y = 归一化名(b);
  if (!x || !y) return 0;
  return 编辑距离相似度(x, y);
}

/**
 * 一个候选单位。**同一归属的多个别名必须放在同一组里** ——
 * 若把别名摊平成多条候选，这个单位会和自己打平（差距 0 < `近似领先`），永远绑不上。
 */
export interface 候选组 {
  /** 归属标识（通常是单位 id 或技能表里的原名） */
  归属: string;
  /** 该归属的所有别名（键 / 全路径 id / 显示名…） */
  别名: string[];
}

export interface 近似候选 {
  名: string;
  相似度: number;
}

export type 名字解析结果 = {
  命中?: string;
  方式: '精确' | '归一化' | '近似' | '未命中';
  相似度?: number;
  /** 未命中时按相似度降序的前几名（供日志诊断） */
  候选: 近似候选[];
};

/** 一个归属的代表分：它所有别名里最高的那个相似度（以及是谁） */
function 该组打分(组: 候选组, 目标: string): 近似候选 {
  let 最佳: 近似候选 = { 名: 组.别名[0] ?? 组.归属, 相似度: 0 };
  for (const 别名 of 组.别名) {
    const 归一 = 归一化名(别名);
    if (!归一) continue;
    const 分 = 编辑距离相似度(归一, 目标);
    if (分 > 最佳.相似度) 最佳 = { 名: 别名, 相似度: 分 };
  }
  return 最佳;
}

/**
 * 在候选集里解析一个名字引用。三层：
 * 1. **精确** —— 任一别名逐字相等
 * 2. **归一化精确** —— 剥掉装饰/空白/注音/全角差异后相等
 * 3. **近似唯一** —— 相似度 ≥ `近似阈值`、领先第二名 ≥ `近似领先`、长度 ≥ `最短可近似长度`、
 *    长度差 ≤ `最大长度差`，全满足才绑
 *
 * 未命中时 `候选` 里带前 3 名与相似度（调用方写进日志 ——
 * 这样下一次现场就能把坏串与正确名字并排打出来，不用再猜是哪一侧坏的）。
 */
export function 解析名字引用(候选: 候选组[], 引用: string): 名字解析结果 {
  const 原始 = String(引用 ?? '').trim();

  const 打分表 = 候选
    .map(组 => ({ 组, 分: 该组打分(组, 归一化名(原始)) }))
    .sort((a, b) => b.分.相似度 - a.分.相似度);
  const 前几 = 打分表.slice(0, 3).map(x => x.分);

  if (!原始 || 候选.length === 0) return { 方式: '未命中', 候选: 前几 };

  // 第 1 层：精确
  for (const 组 of 候选) {
    if (组.别名.some(别名 => 别名 === 原始)) return { 命中: 组.归属, 方式: '精确', 候选: 前几 };
  }

  // 第 2 层：归一化精确
  const 目标 = 归一化名(原始);
  if (目标) {
    for (const 组 of 候选) {
      if (组.别名.some(别名 => 归一化名(别名) === 目标)) {
        return { 命中: 组.归属, 方式: '归一化', 候选: 前几 };
      }
    }
  }

  // 第 3 层：近似唯一
  const 最佳 = 打分表[0];
  const 次佳 = 打分表[1];
  const 领先 = 最佳.分.相似度 - (次佳?.分.相似度 ?? 0);

  const 长度够 = [...目标].length >= 最短可近似长度;
  const 长度接近 = Math.abs([...目标].length - [...归一化名(最佳.分.名)].length) <= 最大长度差;

  if (
    最佳.分.相似度 >= 近似阈值 &&
    领先 >= 近似领先 &&
    长度够 &&
    长度接近
  ) {
    return {
      命中: 最佳.组.归属,
      方式: '近似',
      相似度: 最佳.分.相似度,
      候选: 前几,
    };
  }

  return { 方式: '未命中', 候选: 前几 };
}
