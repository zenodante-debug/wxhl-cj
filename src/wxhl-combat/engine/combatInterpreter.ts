import type { 规则, 战斗单位, 动作, 取值, 条件, 状态条目, 领域, 规则系效果 } from '../types';
import { 资源操作 } from './resourcePool';
import { 属性修正值 } from './rules';

interface 执行结果 {
  数值修正?: Record<string, number>;
  资源?: Record<string, number>;
  护盾?: number;
  状态?: 状态条目[];
  词条?: Set<string>;
  领域?: 领域[];
  形态?: string;
  追加攻击?: number;
  范围伤害?: { 中心: string; 半径: number; 量: number }[];
  规则系判定?: { 效果: 规则系效果; 目标: string }[];
}

/**
 * 求值上下文：伤害结算算到一半才能填进来的量（最终伤害 / 溢出伤害 / 目标HP）。
 * 可选 —— 现有调用点（只跑「使用时/回合开始」这类规则）不用传，缺省时相关来源回退为 0 / 目标.HP_当前。
 */
export interface 求值上下文 {
  最终伤害?: number;
  溢出伤害?: number;
  目标HP?: number;
}

/**
 * 执行规则
 * 1. 判定条件（如果有）
 * 2. 按动作顺序执行
 */
export function 执行规则(
  规则: 规则,
  来源: 战斗单位,
  目标: 战斗单位,
  上下文?: 求值上下文,
): 执行结果 {
  // 判定条件
  if (规则.条件 && !判定条件(规则.条件, 来源, 目标, 上下文)) {
    return {};
  }

  const 结果: 执行结果 = {};

  for (const 动作 of 规则.动作) {
    执行动作(动作, 来源, 目标, 结果, 上下文);
  }

  return 结果;
}

/**
 * 判定条件
 */
function 判定条件(条件: 条件, 来源: 战斗单位, 目标: 战斗单位, 上下文?: 求值上下文): boolean {
  const 左值 = 求值(条件.左, 来源, 目标, 上下文);
  const 右值 = 求值(条件.右, 来源, 目标, 上下文);

  switch (条件.比较) {
    case '≥': return 左值 >= 右值;
    case '>': return 左值 > 右值;
    case '≤': return 左值 <= 右值;
    case '<': return 左值 < 右值;
    case '=': return 左值 === 右值;
  }
}

/**
 * 求值。
 *
 * 口径：
 * - `属性` 来源一律取**属性修正值**（全项目统一口径，不是实际值）。
 * - `层数` 来源取「来源」身上同名状态的层数；无该状态 → 0；有但层数未定义 → 1。
 * - `最终伤害` / `溢出伤害` / `目标HP` 从上下文取；缺省时 目标HP 回退到 目标.HP_当前，另两个回退 0。
 * - 不认识的标识符 / 属性名 / 表达式语法一律**抛错**：静默返回 0 会让规则悄悄算错，比崩溃更危险。
 */
function 求值(取值: 取值, 来源: 战斗单位, 目标: 战斗单位, 上下文?: 求值上下文): number {
  switch (取值.源) {
    case '常数':
      return 取值.系数 || 0;
    case '资源':
      return 来源.资源[取值.名 || ''] || 0;
    case '层数': {
      const 状态 = 来源.状态.find(s => s.名 === (取值.名 || ''));
      if (!状态) return 0;
      return 状态.层数 ?? 1;
    }
    case '属性':
      return 属性修正(取值.名, 来源);
    case '最终伤害':
      return 上下文?.最终伤害 ?? 0;
    case '溢出伤害':
      return 上下文?.溢出伤害 ?? 0;
    case '目标HP':
      return 上下文?.目标HP ?? 目标.HP_当前;
    case '表达式':
      return 求表达式(取值, 来源);
    case '目标词条':
      // 词条存在返回 1，不存在返回 0
      return 目标.词条.has(取值.名 || '') ? 1 : 0;
  }
}

/** 按属性名取修正值；名非法时抛错。 */
function 属性修正(名: string | undefined, 来源: 战斗单位): number {
  const 属性键: Record<string, 'STR' | 'AGI' | 'CON' | 'PER'> = { STR: 'STR', AGI: 'AGI', CON: 'CON', PER: 'PER' };
  const 键 = 属性键[名 || ''];
  if (!键) throw new Error(`未知属性: ${名}`);
  return 属性修正值(来源.属性.实际[键], 来源.阶位);
}

// ==================== 受限表达式求值器 ====================
// 只认：数字字面量 / 已知标识符 / 运算符 + - * / ( )（含全角 × ÷）。
// **手写递归下降解析，不用任何动态代码构造**（既有注入风险也难测）。语法错误或未知标识符一律抛错。

const 数字起 = /[0-9.]/;
const 标识符字符 = /[A-Za-z一-鿿]/;

function 求表达式(取值: 取值, 来源: 战斗单位): number {
  const 原文 = (取值.式 || '').trim();
  if (!原文) throw new Error('表达式为空');
  // 全角运算符归一化 —— AI 常打全角
  const 源串 = 原文.replace(/×/g, '*').replace(/÷/g, '/');

  let 位置 = 0;
  const 跳过空白 = () => {
    while (位置 < 源串.length && /\s/.test(源串[位置])) 位置++;
  };

  function 解析表达式(): number {
    跳过空白();
    let 值 = 解析项();
    跳过空白();
    while (源串[位置] === '+' || 源串[位置] === '-') {
      const 运算符 = 源串[位置++];
      值 = 运算符 === '+' ? 值 + 解析项() : 值 - 解析项();
      跳过空白();
    }
    return 值;
  }

  function 解析项(): number {
    跳过空白();
    let 值 = 解析因子();
    跳过空白();
    while (源串[位置] === '*' || 源串[位置] === '/') {
      const 运算符 = 源串[位置++];
      const 右 = 解析因子();
      值 = 运算符 === '*' ? 值 * 右 : 值 / 右;
      跳过空白();
    }
    return 值;
  }

  function 解析因子(): number {
    跳过空白();
    const 字符 = 源串[位置];

    if (字符 === '+' || 字符 === '-') {
      位置++;
      const 值 = 解析因子();
      return 字符 === '-' ? -值 : 值;
    }

    if (字符 === '(') {
      位置++;
      const 值 = 解析表达式();
      跳过空白();
      if (源串[位置] !== ')') throw new Error(`表达式括号不匹配: ${原文}`);
      位置++;
      return 值;
    }

    if (字符 !== undefined && 数字起.test(字符)) {
      const 起 = 位置;
      while (位置 < 源串.length && /[0-9.]/.test(源串[位置])) 位置++;
      const 文本 = 源串.slice(起, 位置);
      const 数 = Number(文本);
      if (!Number.isFinite(数)) throw new Error(`表达式里的非法数字: ${文本}`);
      return 数;
    }

    if (字符 !== undefined && 标识符字符.test(字符)) {
      const 起 = 位置;
      while (位置 < 源串.length && 标识符字符.test(源串[位置])) 位置++;
      return 标识符值(源串.slice(起, 位置), 取值, 来源);
    }

    throw new Error(`表达式语法错误: ${原文}（位置 ${位置}）`);
  }

  const 结果 = 解析表达式();
  跳过空白();
  if (位置 !== 源串.length) throw new Error(`表达式尾部有多余字符: ${原文}`);
  return 结果;
}

/** 表达式里的标识符取值；未知标识符抛错。 */
function 标识符值(名: string, 取值: 取值, 来源: 战斗单位): number {
  switch (名) {
    case '最大HP':
      return 来源.HP_最大;
    case '最大MP':
      return 来源.MP_最大;
    case '最大耐力':
      return 来源.耐力_最大;
    case 'STR修正':
      return 属性修正值(来源.属性.实际.STR, 来源.阶位);
    case 'AGI修正':
      return 属性修正值(来源.属性.实际.AGI, 来源.阶位);
    case 'CON修正':
      return 属性修正值(来源.属性.实际.CON, 来源.阶位);
    case 'PER修正':
      return 属性修正值(来源.属性.实际.PER, 来源.阶位);
    case '层数': {
      const 状态 = 来源.状态.find(s => s.名 === (取值.名 || ''));
      return 状态 ? (状态.层数 ?? 1) : 0;
    }
    default:
      throw new Error(`表达式里的未知标识符: ${名}`);
  }
}
// ==================== 受限表达式求值器 · 结束 ====================

/**
 * 执行动作
 */
function 执行动作(
  动作: 动作,
  来源: 战斗单位,
  目标: 战斗单位,
  结果: 执行结果,
  上下文?: 求值上下文,
): void {
  switch (动作.类) {
    case '数值修正': {
      if (!结果.数值修正) 结果.数值修正 = {};
      const 量 = 求值(动作.量, 来源, 目标, 上下文);
      结果.数值修正[动作.目标] = (结果.数值修正[动作.目标] || 0) + 量;
      break;
    }

    case '资源': {
      if (!结果.资源) 结果.资源 = {};
      const 量 = 求值(动作.量, 来源, 目标, 上下文);
      const 当前值 = 结果.资源[动作.名] || 来源.资源[动作.名] || 0;
      结果.资源[动作.名] = 资源操作({ [动作.名]: 当前值 }, 动作.名, 动作.操作, 量)[动作.名];
      break;
    }

    case '护盾': {
      const 量 = 求值(动作.量, 来源, 目标, 上下文);
      结果.护盾 = (结果.护盾 || 0) + 量;
      break;
    }

    case '施加状态': {
      if (!结果.状态) 结果.状态 = [];
      const 层数 = 动作.层数 ? 求值(动作.层数, 来源, 目标, 上下文) : undefined;
      结果.状态.push({
        名: 动作.名,
        持续: 动作.持续,
        层数,
        词条: 动作.词条,
      });
      break;
    }

    case '词条': {
      if (!结果.词条) 结果.词条 = new Set();
      if (动作.操作 === '移除') {
        结果.词条.delete(动作.名);
      } else {
        结果.词条.add(动作.名);
      }
      break;
    }

    case '领域': {
      if (!结果.领域) 结果.领域 = [];
      // 领域以来源单位为中心落场（中心是单位 id）；范围是描述性文本（"半径15米"）
      结果.领域.push({
        id: `${来源.id}#${动作.名}`,
        名: 动作.名,
        持续: 动作.持续,
        中心: 来源.id,
        范围: 动作.范围,
        规则: 动作.规则,
      });
      break;
    }

    case '切换形态': {
      结果.形态 = 动作.到;
      break;
    }

    case '追加攻击': {
      结果.追加攻击 = (结果.追加攻击 || 0) + 动作.次数;
      break;
    }

    case '范围伤害': {
      if (!结果.范围伤害) 结果.范围伤害 = [];
      结果.范围伤害.push({
        中心: 动作.中心,
        半径: 动作.半径,
        量: 求值(动作.量, 来源, 目标, 上下文),
      });
      break;
    }

    case '条件分支': {
      // 就地判定，再把命中的分支动作按同一上下文继续执行
      const 分支 = 判定条件(动作.条件, 来源, 目标, 上下文) ? 动作.真 : 动作.假;
      for (const 子动作 of 分支) 执行动作(子动作, 来源, 目标, 结果, 上下文);
      break;
    }

    case '规则系判定': {
      if (!结果.规则系判定) 结果.规则系判定 = [];
      结果.规则系判定.push({ 效果: 动作.效果, 目标: 动作.目标 });
      break;
    }
  }
}
