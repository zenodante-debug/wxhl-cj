// 无限回廊 · 前端战斗引擎 · 规则解释器
// 纯函数，不碰酒馆接口
// 引擎拿到战斗解释后，按触发点跑规则
// ================================================================

import type { 规则, 战斗单位, 动作, 取值, 条件, 状态条目 } from '../types';
import { 资源操作 } from './resourcePool';

interface 执行结果 {
  数值修正?: Record<string, number>;
  资源?: Record<string, number>;
  护盾?: number;
  状态?: 状态条目[];
  词条?: Set<string>;
}

/**
 * 执行规则
 * 1. 判定条件（如果有）
 * 2. 按动作顺序执行
 */
export function 执行规则(规则: 规则, 来源: 战斗单位, 目标: 战斗单位): 执行结果 {
  // 判定条件
  if (规则.条件 && !判定条件(规则.条件, 来源, 目标)) {
    return {};
  }

  const 结果: 执行结果 = {};

  for (const 动作 of 规则.动作) {
    执行动作(动作, 来源, 目标, 结果);
  }

  return 结果;
}

/**
 * 判定条件
 */
function 判定条件(条件: 条件, 来源: 战斗单位, 目标: 战斗单位): boolean {
  const 左值 = 求值(条件.左, 来源, 目标);
  const 右值 = 求值(条件.右, 来源, 目标);

  switch (条件.比较) {
    case '≥': return 左值 >= 右值;
    case '>': return 左值 > 右值;
    case '≤': return 左值 <= 右值;
    case '<': return 左值 < 右值;
    case '=': return 左值 === 右值;
  }
}

/**
 * 求值
 */
function 求值(取值: 取值, 来源: 战斗单位, 目标: 战斗单位): number {
  switch (取值.源) {
    case '常数':
      return 取值.系数 || 0;
    case '资源':
      return 来源.资源[取值.名 || ''] || 0;
    case '层数':
      // TODO: 从状态里读层数
      return 0;
    case '属性':
      // TODO: 从属性里读
      return 0;
    case '最终伤害':
    case '溢出伤害':
    case '目标HP':
      // TODO: 从上下文读
      return 0;
    case '表达式':
      // TODO: 解析表达式
      return 0;
    case '目标词条':
      // 词条存在返回 1，不存在返回 0
      return 目标.词条.has(取值.名 || '') ? 1 : 0;
  }
}

/**
 * 执行动作
 */
function 执行动作(动作: 动作, 来源: 战斗单位, 目标: 战斗单位, 结果: 执行结果): void {
  switch (动作.类) {
    case '数值修正': {
      if (!结果.数值修正) 结果.数值修正 = {};
      const 量 = 求值(动作.量, 来源, 目标);
      结果.数值修正[动作.目标] = (结果.数值修正[动作.目标] || 0) + 量;
      break;
    }

    case '资源': {
      if (!结果.资源) 结果.资源 = {};
      const 量 = 求值(动作.量, 来源, 目标);
      const 当前值 = 结果.资源[动作.名] || 来源.资源[动作.名] || 0;
      结果.资源[动作.名] = 资源操作({ [动作.名]: 当前值 }, 动作.名, 动作.操作, 量)[动作.名];
      break;
    }

    case '护盾': {
      const 量 = 求值(动作.量, 来源, 目标);
      结果.护盾 = (结果.护盾 || 0) + 量;
      break;
    }

    case '施加状态': {
      if (!结果.状态) 结果.状态 = [];
      const 层数 = 动作.层数 ? 求值(动作.层数, 来源, 目标) : undefined;
      结果.状态.push({
        名: 动作.名,
        持续: 动作.持续,
        层数,
        词条: 动作.词条,
      });
      break;
    }

    case '词条': {
      if (!结果.词条) 结果.词条 = new Set();
      if (动作.操作 === '移除') {
        结果.词条.delete(动作.名);
      } else {
        结果.词条.add(动作.名);
      }
      break;
    }

    // TODO: 其他动作类型
    case '领域':
    case '切换形态':
    case '追加攻击':
    case '范围伤害':
    case '条件分支':
    case '规则系判定':
      break;
  }
}
