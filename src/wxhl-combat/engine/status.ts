import type { 状态条目 } from '../types';

/** 可叠层状态表（世界书原文） */
const 可叠层状态 = new Set(['灼烧', '中毒']);

/** 层数上限表（世界书原文） */
const 层数上限: Record<string, number> = {
  灼烧: 3,
  中毒: 3,
};

/**
 * 施加状态
 * 世界书原文：同状态不叠加（后覆盖先），注明可叠层的有层数上限
 */
export function 施加状态(状态列表: 状态条目[], 新状态: 状态条目): 状态条目[] {
  const 已存在 = 状态列表.findIndex(s => s.名 === 新状态.名);

  if (已存在 >= 0) {
    const 旧状态 = 状态列表[已存在];

    // 可叠层状态：层数叠加
    if (可叠层状态.has(新状态.名)) {
      const 新层数 = (旧状态.层数 || 1) + (新状态.层数 || 1);
      const 上限 = 层数上限[新状态.名] || 99;
      const 最终层数 = Math.min(新层数, 上限);

      const 新列表 = [...状态列表];
      新列表[已存在] = {
        ...新状态,
        层数: 最终层数,
        持续: Math.max(旧状态.持续, 新状态.持续), // 持续取较大值
      };
      return 新列表;
    }

    // 不可叠层状态：后覆盖先
    const 新列表 = [...状态列表];
    新列表[已存在] = 新状态;
    return 新列表;
  }

  return [...状态列表, 新状态];
}

/**
 * 状态递减（回合结束时调用）
 * 持续回合 -1，到 0 移除
 */
export function 状态递减(状态列表: 状态条目[]): 状态条目[] {
  return 状态列表
    .map(s => ({ ...s, 持续: s.持续 - 1 }))
    .filter(s => s.持续 > 0);
}
