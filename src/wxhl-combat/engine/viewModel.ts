// ================================================================
// 无限回廊 · 前端战斗引擎 · 视图模型（`.vue` 模板要用的形状）
// 纯函数，不碰酒馆接口
//
// 为什么单独放一个模块：**`.vue` 模板里的属性访问没有任何自动检查** —— 本仓库没有 vue-tsc，
// `vue/compiler-sfc` 也只编译语法、不查属性；vitest 没装 vue 插件（连 .vue 都 import 不进来）。
// 于是"模板读了一个不存在的属性"会在运行时抛错、把整个组件渲染成**一片空白**
// （实战反馈：`u.行动槽.主要` —— 条目里根本没有 `行动槽` 这一层）。
// 把这些形状抽成纯函数并**用测试钉死**，模板就只消费被测试过的数据。
// ================================================================

import type { 战斗单位, 战斗解释 } from '../types';
import { 规范行动消耗, 是基础攻击哨兵, 副武器攻击 } from './actionOptions';
import { 徒手伤害骰 } from './damage';
import { 效果预览, type 效果预览 as 效果预览类型 } from './effectPreview';

/** 显示名：变量里的姓名（`头部.姓名`）；缺省退回变量路径最后一段 */
export function 显示名(单位: 战斗单位): string {
  return 单位.名称 || 单位.id.split('.').pop() || 单位.id;
}

/**
 * 我方行动区的一条。
 * **继承 `战斗单位`**（不是包一层 `单位`）—— 模板里就能直接 `u.HP_当前` / `u.行动槽.主要`，
 * 与单位卡用的是同一套字段，不需要记"什么时候要 `.单位.` 什么时候不要"。
 */
export interface 我方条目 extends 战斗单位 {
  /** 在 `状态.单位` 里的键（引擎认键，也认 id） */
  键: string;
  名称: string;
  技能: Record<string, 战斗解释>;
}

/** 从 `状态.单位` 里挑出我方单位（按**阵营**，不是按类型），展开成行动区条目 */
export function 造我方条目(单位表: Record<string, 战斗单位>): 我方条目[] {
  return Object.entries(单位表 ?? {})
    .filter(([, u]) => u.阵营 === '我方')
    .map(([键, u]) => ({ ...u, 键, 名称: 显示名(u), 技能: u.技能 ?? {} }));
}

/** 决斗场地面上的一个坐标点（x = 距离横向百分比，y = 车道 + 层） */
export interface 坐标点 {
  键: string;
  id: string;
  /** 横向百分比（与距离轴同一套） */
  左: number;
  /** 车道（纵轴）：横向会撞上的相邻距离组错开到不同车道 */
  车道: number;
  /** 组内层：同一距离的多个人在同一车道内上下叠 */
  层: number;
}

/**
 * 一维地图的**纵轴布局**（玩家反馈：「增加一个向上的纵轴，就不会所有角色都挤在一起了」）。
 *
 * 现状的毛病：同一距离组内上下叠，但**距离相近**的两组（5 米和 6 米）横向挨着、
 * 纵向堆叠又都从底边起 —— 横竖两向都挤成一团。
 * 这里：相邻组的横向间距小于阈值时，后者错开一条车道；同距离的多人仍在同一车道内按层叠。
 */
export function 布局分布(
  单位: Array<{ 键: string; id: string; 距离: number }>,
  距离到左: (d: number) => number,
  /** 棋子铭牌的视觉宽度（%）—— 相邻组横向间距小于它就算"撞上了"，错开一条车道 */
  阈值 = 12,
): { 点: 坐标点[]; 车道数: number } {
  // 先按距离分组（同距离的是一组，组内上下叠）
  const 按距离 = new Map<number, Array<{ 键: string; id: string }>>();
  for (const u of 单位) {
    const d = u.距离 ?? 0;
    按距离.set(d, [...(按距离.get(d) ?? []), { 键: u.键, id: u.id }]);
  }
  const 组 = [...按距离.entries()].sort((a, b) => a[0] - b[0]).map(([距离, 成员]) => ({ 左: 距离到左(距离), 成员 }));

  const 点: 坐标点[] = [];
  let 车道 = 0;
  let 上一个左 = -Infinity;
  let 最大车道 = 0;
  for (const g of 组) {
    if (g.左 - 上一个左 < 阈值) 车道++;
    else 车道 = 0;
    上一个左 = g.左;
    最大车道 = Math.max(最大车道, 车道);
    g.成员.forEach((m, 层) => 点.push({ 键: m.键, id: m.id, 左: g.左, 车道, 层 }));
  }

  return { 点, 车道数: Math.max(1, 最大车道 + 1) };
}

/** 导出给模板用的名字（模板里 `效果预览` 是类型，不能当值用） */
export const 造效果预览 = 效果预览;

/** 玩家已选中的一项行动的预览（行动区里"选了什么就摆出它干什么"） */
export interface 选中项预览 {
  槽: '主要' | '次要' | '免费';
  名: string;
  预览: 效果预览类型;
}

/**
 * 该单位**已经选中**的行动的效果预览（主要下拉 / 次要下拉 / 免费多选）。
 *
 * 基础武器攻击在下拉里是哨兵串（`（主武器攻击）`），不是技能名 —— 单独给一条武器说明。
 * 抽成纯函数的原因和 `造我方条目` 一样：`.vue` 模板没有属性检查，形状必须被测试钉死。
 */
export function 选中行动预览(
  单位: 战斗单位,
  填写: { 主要?: string; 次要?: string; 免费?: string[] },
): 选中项预览[] {
  const 出: 选中项预览[] = [];

  const 加 = (槽: 选中项预览['槽'], 值?: string) => {
    const 名 = (值 ?? '').trim();
    if (!名) return;
    if (是基础攻击哨兵(名)) {
      const 武器 = 名 === 副武器攻击 ? 单位.副武器 : 单位.主武器;
      出.push({
        槽,
        名,
        预览: {
          头部: [武器 ? '基础武器攻击' : '徒手攻击'],
          行: [
            武器
              ? `用「${武器.伤害骰}」造成武器伤害（倍率 ×${武器.倍率}${
                  武器.强化等级 ? `、强化+${武器.强化等级}` : ''
                }），再减目标防御`
              : `徒手 ${徒手伤害骰(单位.阶位)}（倍率 ×0.5、近战），再减目标防御`,
          ],
        },
      });
      return;
    }
    出.push({ 槽, 名, 预览: 效果预览(单位.技能?.[名]) });
  };

  加('主要', 填写.主要);
  加('次要', 填写.次要);
  for (const 名 of 填写.免费 ?? []) 加('免费', 名);
  return 出;
}

/** 一个技能/装备效果在界面上的展示形状（下拉摘要 + 详情表共用） */
export interface 技能展示 {
  名: string;
  /** 下拉选项里显示的摘要 */
  摘要: string;
  行动消耗: string;
  /** 归一化后的行动类型（没写行动类型的主动效果 = 免费行动；被动 = null） */
  行动类型: string;
  射程: string;
  目标: string;
  消耗: string;
  冷却?: number;
  /** 「×1.4」或「无伤害」 */
  倍率: string;
  规则数: number;
  /** 人话效果预览（头部元信息 + 规则逐条）——「点技能完全不知道有什么用」的解法 */
  预览: 效果预览类型;
}

/** 把一个单位的技能表展开成展示条目（按名字排序，界面顺序稳定） */
export function 造技能展示(技能: Record<string, 战斗解释> | undefined): 技能展示[] {
  return Object.entries(技能 ?? {})
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([名, 解释]) => {
      const 倍率 =
        typeof 解释?.伤害倍率 === 'number' && 解释.伤害倍率 > 0 ? `×${解释.伤害倍率}` : '无伤害';
      const 摘要段 = [解释?.行动消耗, 解释?.射程, 倍率].filter(Boolean).join(' · ');
      return {
        名,
        摘要: `${名}（${摘要段}）`,
        行动消耗: 解释?.行动消耗 ?? '',
        行动类型: 规范行动消耗(解释) ?? '被动/非行动',
        射程: 解释?.射程 ?? '',
        目标: 解释?.目标 ?? '',
        消耗: 解释?.消耗 ?? '',
        冷却: 解释?.冷却,
        倍率,
        规则数: (解释?.规则 ?? []).filter(Boolean).length,
        预览: 效果预览(解释),
      };
    });
}
