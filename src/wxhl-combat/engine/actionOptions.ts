// ================================================================
// 无限回廊 · 前端战斗引擎 · 行动选项目录
// 纯函数，不碰酒馆接口
//
// 玩家反馈两条，这里是它们的落点：
// 1. 「各种行动选项太重复了 —— 技能不是有行动类型吗？按行动类型匹配，别把所有选项都适配所有类型」
//    → 主要行动的下拉只列 `行动消耗: 主要行动` 的技能；次要行动只列 `次要行动` 的。
// 2. 「除了各行动类型的技能，还要有每个行动类型的基础行动：主要行动要有主武器攻击、
//     次要行动要有副武器攻击」
//    → 每个行动类型都追加一条**基础武器攻击**（省略 `技能` 键就是它，引擎已有这条兜底）。
//
// 另外过滤掉**不能主动释放**的东西：「各个行动选项里很容易混进去防具等装备，这些不能算行动，
// 除非装备有可以主动释放的效果；被动的效果应该直接计算了。」
// → 判定标准是翻译结果的 `行动消耗` 与 `类型`：被动/光环，或者行动消耗写「无」的，
//   一律不进行动选项（它们的常驻数值修正照旧由 `常驻修正` 直接算进伤害/减伤）。
// ================================================================

import type { 战斗单位, 战斗解释 } from '../types';
import { 徒手伤害骰 } from './damage';

/**
 * 行动类型（能被玩家/敌人主动选的那几类）。
 * **注意字段名**：翻译结果里承载它的字段叫 `行动消耗`（历史起名）——
 * 它是「主要行动/次要行动/反应动作/免费行动/无」，**不是**资源消耗 `消耗`（MP/耐力）。
 */
export type 可选项类型 = '主要行动' | '次要行动' | '反应动作' | '免费行动';

/**
 * 把一个效果的**行动类型**归一化。这是"它算不算一个行动、算哪种行动"的唯一判据。
 *
 * | 翻译结果 | 归一化 |
 * | :--- | :--- |
 * | 类型含 被动 / 光环 / 制造系 | `null`（不是行动，数值效果由 `常驻修正` 直接算） |
 * | 行动类型 = 主要/次要/反应动作/免费行动 | 原样 |
 * | 行动类型 = 无 / 空，但类型是**主动**（装备/道具的主动效果常这样） | `免费行动` |
 * | 两样都缺 | `null`（宁可不显示，也不乱塞） |
 *
 * 玩家口径：「装备的效果，有的是能够主动触发的，但是没有行动类型。主动的效果也要能够算作
 * 行动选项吧？或者算作免费行动」+「默认免费行动，冷却默认一个回合」。
 * 冷却由 `冷却回合数`（默认 1）+ 引擎的冷却门禁保证 —— **免费行动不等于无限连放**。
 */
export function 规范行动消耗(解释: 战斗解释 | undefined): 可选项类型 | null {
  if (!解释) return null;
  const 类型 = String(解释.类型 ?? '');
  if (/被动|光环|制造/.test(类型)) return null;

  const 行动 = String(解释.行动消耗 ?? '').trim();
  if (行动 === '主要行动' || 行动 === '次要行动' || 行动 === '反应动作' || 行动 === '免费行动') {
    return 行动;
  }

  // 行动类型没写（或写「无」），但效果本身是**主动**的 → 按免费行动收进来。
  if (/主动/.test(类型)) return '免费行动';

  return null;
}

/**
 * 这个效果能不能**主动使用**（决定它是否出现在行动下拉里）。
 *
 * 注意：**被动的数值效果不是被丢掉了** —— `常驻修正` 会直接把它们算进伤害/减伤，
 * 这里只是不让它们占一个行动位。
 */
export function 可主动使用(解释: 战斗解释 | undefined): boolean {
  return 规范行动消耗(解释) !== null;
}

/** 免费行动是**不限次数**的（世界书：免费行动不占次数） */
export function 是免费行动(解释: 战斗解释 | undefined): boolean {
  return 规范行动消耗(解释) === '免费行动';
}

/**
 * 基础武器攻击在**下拉值**里的表示（哨兵串）。
 * 下拉的 value 必须是字符串，而"基础攻击"在引擎里是**省略技能键** ——
 * 所以用一个不像技能名的固定串当哨兵，由 `构造行动声明` 翻译成 `{ 武器 }`。
 */
export const 主武器攻击 = '（主武器攻击）';
export const 副武器攻击 = '（副武器攻击）';

/** 这个下拉值是不是基础武器攻击哨兵 */
export function 是基础攻击哨兵(值: string): 值 is typeof 主武器攻击 | typeof 副武器攻击 {
  return 值 === 主武器攻击 || 值 === 副武器攻击;
}

export interface 行动选项 {
  类型: 可选项类型;
  /** 技能名；**省略 = 基础武器攻击** */
  技能?: string;
  /** 基础武器攻击用哪把武器 */
  武器?: '主武器' | '副武器';
  /** 下拉的 value（技能名，或基础攻击哨兵） */
  值: string;
  /** 下拉里显示的标签 */
  标签: string;
  /** 一句话摘要（行动/射程/倍率） */
  摘要: string;
}

/**
 * 解析技能的**资源消耗**（世界书的「资源消耗：使用技能/动作即时扣耐力、MP」）。
 * 认 `MP 5` / `MP5` / `魔力 10` / `耐力 8` / `体力 8` 这些写法；「无」或认不出来 → null。
 */
export function 解析消耗(消耗文本: unknown): 解析消耗结果 | null {
  const 文 = String(消耗文本 ?? '');
  const 资源 = (名: string): 'MP' | '耐力' => (/MP|mp|魔力/.test(名) ? 'MP' : '耐力');

  // 先认**按最大值比例**的写法（「最大MP的8%」/「MP上限的2%」/「最大耐力的5%」）——
  // 必须排在绝对值前面，否则 "8%" 会被当成 8 点。
  const 比 = /(?:最大)?(MP|mp|魔力|耐力|体力)(?:上限)?(?:的)?\s*(\d+(?:\.\d+)?)\s*%/.exec(文);
  if (比) {
    const 比例 = Number(比[2]) / 100;
    if (Number.isFinite(比例) && 比例 > 0) return { 资源: 资源(比[1]), 比例 };
  }

  const m = /(MP|mp|魔力|耐力|体力)\s*(\d+(?:\.\d+)?)/.exec(文);
  if (!m) return null;
  const 量 = Math.floor(Number(m[2]));
  if (!Number.isFinite(量) || 量 <= 0) return null;
  return { 资源: 资源(m[1]), 量 };
}

/** 解析出来的消耗：要么是**绝对值**（量），要么是**按最大值的比例**（比例，如 0.08 = 最大MP的 8%） */
export interface 解析消耗结果 {
  资源: 'MP' | '耐力';
  量?: number;
  比例?: number;
}

/** 这次消耗实际要扣多少（比例按该单位的最大值折算，向上取整） */
export function 实扣量(耗: 解析消耗结果, 上限: number): number {
  if (耗.比例 !== undefined) return Math.max(1, Math.ceil(上限 * 耗.比例));
  return Math.max(0, Math.floor(耗.量 ?? 0));
}

/**
 * 「下一次」类增益用的**约定词条** —— 翻译器按提示词约定产出，引擎在这里消费。
 * - `连击`：下一次用技能时额外释放一次（用完即消耗）
 * - `免冷却`：下一次用技能时不进入冷却（用完即消耗）
 */
export const 连击词条 = '连击';
export const 免冷却词条 = '免冷却';

/** 武器的展示摘要（没武器时按**人物阶位**给徒手骰 —— 世界书速查表里徒手是随阶位长的） */
function 武器摘要(武器: 战斗单位['主武器'], 阶位 = '一阶'): string {
  if (!武器) return `徒手 ${徒手伤害骰(阶位)} · ×0.5`;
  return `${武器.伤害骰} · ×${武器.倍率}${武器.强化等级 ? ` · 强化+${武器.强化等级}` : ''}`;
}

/**
 * 列出一个单位在某个行动类型下**能做什么**。
 * 顺序：先技能（按名字排序，界面稳定），最后一条是基础武器攻击（免费/反应动作没有这条）。
 *
 * @param 类型 主要行动 → 主武器攻击（没武器就是徒手）；次要行动 → 副武器攻击（没副武器就是徒手）；
 *             反应动作 → **只有该单位学过的、行动类型为反应动作的技能**（不再有预设的招架/识破…）；
 *             免费行动 → 只有技能。
 */
export function 列行动选项(单位: 战斗单位, 类型: 可选项类型): 行动选项[] {
  const 出: 行动选项[] = [];

  for (const [名, 解释] of Object.entries(单位.技能 ?? {}).sort((a, b) => a[0].localeCompare(b[0]))) {
    // 按**行动类型**精确匹配：主要行动的技能不进次要行动的列表，反之亦然。
    // 没写行动类型的主动效果（装备/道具）由 `规范行动消耗` 归成免费行动。
    if (规范行动消耗(解释) !== 类型) continue;

    const 倍率 = typeof 解释.伤害倍率 === 'number' && 解释.伤害倍率 > 0 ? `×${解释.伤害倍率}` : '无伤害';
    const 冷却 = 冷却回合数(解释);
    出.push({
      类型,
      技能: 名,
      值: 名,
      标签: `${名}（${[解释.射程, 倍率, `冷却${冷却}`].filter(Boolean).join(' · ')}）`,
      摘要: [解释.射程, 倍率].filter(Boolean).join(' · '),
    });
  }

  // 基础武器攻击（引擎里「省略技能键」就是它）。免费行动 / 反应动作没有基础攻击这一条。
  // **没有武器也照样列**（玩家口径：「没武器就放技能或者徒手攻击嘛，怎么都行」）——
  // 但标签必须诚实：徒手就说徒手（徒手 1d4），别让玩家以为手里有家伙。
  if (类型 === '主要行动' || 类型 === '次要行动') {
    const 武器位 = 类型 === '主要行动' ? '主武器' : '副武器';
    const 武器 = 类型 === '主要行动' ? 单位.主武器 : 单位.副武器;
    const 名义 = 武器 ? (类型 === '主要行动' ? '主武器攻击' : '副武器攻击') : '徒手攻击';
    出.push({
      类型,
      武器: 武器位,
      值: 类型 === '主要行动' ? 主武器攻击 : 副武器攻击,
      标签: `${名义}（${武器摘要(武器, 单位.阶位)}）`,
      摘要: 武器摘要(武器, 单位.阶位),
    });
  }

  return 出;
}

/**
 * 技能的实际冷却回合数。
 * 玩家口径：「技能是会有冷却的，**最小都一回合**，如果技能没写，就默认冷却一回合。」
 * → 没写 / 非数字 / ≤0 一律按 **1**；写了就取整（不小于 1）。
 */
export function 冷却回合数(解释: 战斗解释 | undefined): number {
  const 原值 = Number(解释?.冷却);
  if (!Number.isFinite(原值) || 原值 < 1) return 1;
  return Math.floor(原值);
}
