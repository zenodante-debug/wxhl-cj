//
// 演出层（飘字/攻击轨迹/变身全屏/棋子倒扣/金色裂纹）**不解析日志文本** ——
// `结算步骤.内容` 是给玩家看的、随时会改；演出只认步骤上的结构化标记
// （`事件` / `数值` / `攻方` / `守方` / `形态` / `效果`，在产生步骤的地方打上）。
// ================================================================

import type { 结算步骤 } from '../types';

/** 演出事件的类别（`结算步骤.事件` 的取值集合） */
export type 演出事件类 = '命中' | '未命中' | '变身' | '打断成功' | '打断失败' | '濒死' | '规则系' | '反应防御';

export interface 演出事件 {
  类: 演出事件类;
  /** 主语（被打中的/变身的/打断的单位的显示名） */
  单位?: string;
  /** 攻击方显示名（轨迹的起点） */
  攻方?: string;
  /** 守方显示名（飘字/轨迹/倒扣的落点） */
  守方?: string;
  /** 攻击方在 `状态.单位` 的键 —— 同名单位按名会锚错棋子，演出坐标先按键查 */
  攻方键?: string;
  /** 守方在 `状态.单位` 的键（同上） */
  守方键?: string;
  /** 主语单位在 `状态.单位` 的键（打断/反应/规则系/变身用） */
  单位键?: string;
  /** 伤害数值（飘字用；「命中」事件才有） */
  伤害?: number;
  /** 变身事件的形态名 */
  形态?: string;
  /** 规则系事件的效果名（穿透/必中/即死…） */
  效果?: string;
}

/** 从一段结算步骤里提取演出事件（顺序保留 = 发生顺序，演出按它播放） */
export function 演出事件提取(步骤: 结算步骤[]): 演出事件[] {
  const 出: 演出事件[] = [];
  for (const s of 步骤 ?? []) {
    if (!s || !s.事件) continue;
    出.push({
      类: s.事件 as 演出事件类,
      单位: s.单位,
      攻方: s.攻方,
      守方: s.守方,
      攻方键: s.攻方键,
      守方键: s.守方键,
      单位键: s.单位键,
      伤害: s.数值,
      形态: s.形态,
      效果: s.效果,
    });
  }
  return 出;
}
