/**
 * 跑敌方意图：把 AI 返回的意图落到战斗状态上。
 * 遇到不存在的单位/目标/技能 → 跳过该行动并记日志，绝不抛错中断整回合。
 * 校验通过的行动交给 `结算行动` 做真实结算（移动/技能六步伤害/扣槽）。
 */
export function 跑敌方意图(状态: 战斗状态, 意图: 敌方意图[]): {
  状态: 战斗状态;
  步骤: 结算步骤[];
} {
  const 步骤: 结算步骤[] = [];
  let 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  for (const 单位意图 of 意图) {
    if (!找单位(新状态, 单位意图.单位)) {
      步骤.push({ 类: '跳过', 内容: `跳过：单位「${单位意图.单位}」不在战场上` });
      continue;
    }

    for (const 行动 of 单位意图.行动) {
      // 每个行动前重新取一次单位：上一个行动可能已经改过它的距离/行动槽
      const 单位 = 找单位(新状态, 单位意图.单位);
      if (!单位) {
        步骤.push({ 类: '跳过', 内容: `跳过：单位「${单位意图.单位}」不在战场上` });
        continue;
      }

      // 校验目标存在
      if (行动.目标 && !找单位(新状态, 行动.目标)) {
        步骤.push({ 类: '跳过', 内容: `跳过：「${单位意图.单位}」的目标「${行动.目标}」不在战场上` });
        continue;
      }

      // 校验技能名（R7）：意图里写了技能，但该单位的技能表里没有 → 跳过该行动
      // （技能表 = 一次性翻译出的「技能名 → 战斗解释」；老存档可能缺省，兜底为空表）
      const 技能表 = 单位.技能 ?? {};
      if (行动.技能 && !技能表[行动.技能]) {
        步骤.push({ 类: '跳过', 内容: `跳过：「${单位意图.单位}」没有技能「${行动.技能}」` });
        continue;
      }

      步骤.push({ 类: '敌方行动', 内容: `「${单位意图.单位}」执行 ${行动.类型}${行动.技能 ? `·${行动.技能}` : ''}`, 单位: 单位意图.单位 });

      const 结果 = 结算行动(新状态, 单位, 行动);
      新状态 = 结果.状态;
      步骤.push(...结果.步骤);
    }
  }

  return { 状态: 新状态, 步骤 };
}
