/**
 * 测试用的掷骰注入（把随机性钉死，才能对伤害做精确断言）。
 * 生产代码不传，一律现场掷。
 */
export interface 掷骰注入 {
  命中?: number;
  伤害骰?: number[];
  /** 规则系防火墙：攻方判定 / 守方判定 / 修正持平时的 1d2 */
  规则系?: { 攻方判定?: number; 守方判定?: number; 持平?: number };
  /** 反应动作的打断检定骰（**已经是劣势后的结果**：劣势 = 掷两次取低） */
  反应?: number;
}

export interface 结算结果 {
  状态: 战斗状态;
  步骤: 结算步骤[];
  待决: 待决点[];
}

/**
 * 结算单个行动。坏输入（技能不存在/超程/槽位不足）→ 记「跳过」步骤，绝不抛错。
 *
 * 第五步（防御方反应动作）不在此处：引擎只把结果算出来，`待决` 恒为空数组，
 * 由交互层（13d）决定是否弹打断/防御。**纯函数**：不改动入参，返回新的 `战斗状态`。
 *
 * 开头有存活守卫：HP 归零（已失去战斗力）的行动者一律跳过 —— 先攻循环里本轮早些
 * 被打死的单位不该在本轮晚些再出手。玩家与敌方两条路共用这一处。
 *
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数，避免 flaky；缺省时现场掷骰。
 */
export function 结算行动(
  状态: 战斗状态,
  行动者: 战斗单位,
  行动: 意图行动,
  掷骰注入?: 掷骰注入,
): 结算结果 {
  const 步骤: 结算步骤[] = [];
  const 待决: 待决点[] = [];

  // 存活守卫：HP ≤ 0 = 已失去战斗力（濒死 CON 检定见 13f）
  if (行动者.HP_当前 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${显示名(行动者)}」已失去战斗力`, 单位: 显示名(行动者) });
    return { 状态, 步骤, 待决 };
  }

  const 键 = 找键(状态, 行动者);
  if (键 === undefined) {
    步骤.push({ 类: '跳过', 内容: `跳过：单位「${行动者.id}」不在战场上` });
    return { 状态, 步骤, 待决 };
  }

  // 我们的副本：单位对象一律「换新对象」写回，入参 状态 完全不动
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  try {
    if (行动.类型 === '移动') 结算移动(新状态, 键, 行动, 步骤);
    // 主要行动：没写技能 = 基础攻击（R20）。
    // 次要行动：写了技能或指定了武器（副武器攻击）才进结算 —— 次要行动**可以攻击**
    //          （玩家要求：次要行动要有「副武器攻击」）；没写技能也没指定武器的次要行动
    //          （「瞄准」「预备」）仍是纯扣槽，别把它变成一次失败的攻击。
    else if (
      行动.类型 === '主要行动' ||
      ((行动.类型 === '次要行动' || 行动.类型 === '免费行动') && (行动.技能 || 行动.武器))
    ) {
      结算技能(新状态, 键, 行动, 掷骰注入, 步骤);
    } else 结算槽位行动(新状态, 键, 行动, 步骤);
  } catch (e: any) {
    // 兜底：任何意外（未知阶位、骰式非法…）都降级为「跳过」，不打断整回合
    步骤.push({ 类: '跳过', 内容: `跳过：「${行动者.id}」的 ${行动.类型} 结算失败：${e?.message ?? e}` });
  }

  return { 状态: 新状态, 步骤, 待决 };
}

/** 移动：算消耗 → 扣额度 → 改距离 → 扣移动槽；跨带脱离近战 → 记借机攻击提示（真正的借机是反应动作，交 13d）。 */
function 结算移动(新状态: 战斗状态, 键: string, 行动: 意图行动, 步骤: 结算步骤[]): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 目标距离 = typeof 行动.距离 === 'number' && Number.isFinite(行动.距离) ? 行动.距离 : 当前.距离;
  const 消耗 = Math.abs(目标距离 - 当前.距离);

  // 词条门禁（spec §3.3：词条是状态标签，引擎直接检查）：「禁位移」禁止移动
  if (当前.词条?.has(词条_禁位移)) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」带词条「${词条_禁位移}」，无法移动`, 单位: 名 });
    return;
  }

  if (当前.行动槽.移动 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的移动行动槽已用尽`, 单位: 名 });
    return;
  }
  if (消耗 > 当前.额度) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」移动额度不足（需 ${消耗} 米，余 ${当前.额度} 米）`, 单位: 名 });
    return;
  }

  const 原距离 = 当前.距离;
  const 新额度 = 移动额度消耗(当前.额度, 消耗); // 已判过 消耗 ≤ 额度，不会抛
  const 新槽 = 行动槽消耗(当前.行动槽, '移动');

  写回(新状态, 键, { 距离: 目标距离, 额度: 新额度, 行动槽: 新槽 });

  步骤.push({
    类: '移动',
    内容: `「${名}」移动 ${消耗} 米：${原距离} → ${目标距离} 米（${距离带(目标距离)}），剩余额度 ${新额度} 米`,
    单位: 名,
  });

  if (借机攻击判定(原距离, 目标距离, {})) {
    步骤.push({ 类: '移动', 内容: `「${名}」脱离近战带，触发借机攻击（对方的反应动作，交待决处理）`, 单位: 名 });
  }
}

/**
 * 守方本回合**预置的反应技能**能不能用。
 * 条件：学过（在技能表里）／行动类型是「反应动作」／不在冷却／还有反应槽／还活着。
 *
 * 玩家口径：「反应动作不应该是有预设的那些反应动作，必须是技能的类型是反应动作才算上。
 * 取消预设的反应动作，必须要自己学。」→ 这就是那条「必须自己学」的门禁。
 */export function 守方反应技能(
  守方: 战斗单位,
): { 名: string; 解释: 战斗解释; 是打断: boolean } | undefined {
  const 名 = String(守方.预置反应 ?? '').trim();
  if (!名) return undefined;
  if (守方.HP_当前 <= 0) return undefined;
  if ((守方.行动槽?.反应 ?? 0) <= 0) return undefined;

  const 表 = 守方.技能 ?? {};
  const 原名 = 解析技能名(表, 名)?.命中;
  if (!原名 || !表[原名]) return undefined;
  const 解释 = 表[原名];
  if (规范行动消耗(解释) !== '反应动作') return undefined; // 不是反应动作技能 → 不能用它反应
  if ((守方.冷却?.[原名] ?? 0) > 0) return undefined; // 冷却中

  const 是打断 = (解释.规则 ?? []).some(规则 =>
    (规则?.动作 ?? []).some(动作 => !!动作 && 动作.类 === '词条' && 动作.名 === 词条_打断),
  );
  return { 名: 原名, 解释, 是打断 };
}

/**
 * 敌方反应动作预置（第一期：「有预置就自动用」—— 不额外调 AI）。
 *
 * 每个敌方单位若**学过**反应动作技能（不在冷却、还有反应槽），给它预置**第一个**可用技能；
 * 之后被攻击时走和玩家完全同一条 `守方反应技能` 路径（敌我一视同仁）。
 * 玩家裁决：「5，有预置就自动用」「6，预置就自动用，没预置就跳过」。
 */
export function 敌方反应预置(状态: 战斗状态): 战斗状态 {
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };
  for (const [键, 单位] of Object.entries(新状态.单位)) {
    if (单位.阵营 !== '敌方') continue;
    if ((单位.行动槽?.反应 ?? 0) <= 0) continue;
    const 可用 = 列行动选项(单位, '反应动作').filter(o => o.技能 && (单位.冷却?.[o.技能] ?? 0) <= 0);
    if (!可用.length) continue;
    新状态.单位[键] = { ...单位, 预置反应: 可用[0].技能! };
  }
  return 新状态;
}

interface 反应结局 {
  取消攻击: boolean;
  额外减伤: number;
  命中加值: number;
}

/**
 * 守方反应动作的完整结算（世界书 <核心战斗系统>【第五步敌方反应动作防御】）。
 *
 * - **打断类**（带约定词条「打断」，如击溃/识破）：`1d20（劣势，掷两次取低）+ 关联属性修正×3/4（下取整）`
 *   与**攻方命中检定值**对抗；成功 → 本次攻击取消；失败 → 攻击照常结算，且**攻方本次命中 +2**。
 * - **防御类**（招架/格挡/闪烁…）：按技能自己的规则落（护盾/减伤/反伤），减伤只作用于**这一次**攻击。
 *
 * 无论哪种，都消耗 1 个反应槽、按 `冷却回合数` 进冷却、扣 `消耗` 里的资源。
 * 没预置 → 不反应（玩家裁决：「预置就自动用，没预置就跳过」，不弹窗、不追问）。
 */
function 结算守方反应(
  新状态: 战斗状态,
  攻方键: string,
  守方键: string,
  /** 攻方的命中检定值（打断要跟它对抗，不是跟"命中/未命中"对抗） */
  攻方命中值: number,
  动作名: string,
  掷骰注入: 掷骰注入 | undefined,
  步骤: 结算步骤[],
): 反应结局 {
  const 空: 反应结局 = { 取消攻击: false, 额外减伤: 0, 命中加值: 0 };
  const 守方 = 新状态.单位[守方键];
  const 反应 = 守方反应技能(守方);
  if (!反应) return 空;

  const 名 = 显示名(守方);

  // ===== 消耗：反应槽 / 冷却 / 资源 =====
  const 补丁: Partial<战斗单位> = {
    行动槽: 行动槽消耗(守方.行动槽, '反应动作'),
    冷却: { ...(守方.冷却 ?? {}), [反应.名]: 冷却回合数(反应.解释) },
  };
  let 资源说明 = '';
  const 耗 = 解析消耗(反应.解释.消耗);
  if (耗) {
    const 字段 = 耗.资源 === 'MP' ? 'MP_当前' : '耐力_当前';
    const 现有 = Number((守方 as any)[字段] ?? 0);
    if (现有 < 耗.量) {
      步骤.push({
        类: '跳过',
        内容: `「${名}」想用反应动作「${反应.名}」，但${耗.资源}不足（需 ${耗.量}，余 ${现有}）`,
        单位: 名,
      });
      return 空;
    }
    (补丁 as any)[字段] = 现有 - 耗.量;
    资源说明 = `，${耗.资源} -${耗.量}`;
  }
  新状态.单位[守方键] = { ...守方, ...补丁 };

  步骤.push({
    类: '规则系',
    内容: `「${名}」使用反应动作「${反应.名}」（反应槽 ${补丁.行动槽!.反应} 个${资源说明}，冷却 ${冷却回合数(反应.解释)} 回合）`,
    单位: 名,
  });

  // ===== 打断类：命中判定之前跟攻方命中检定对抗 =====
  if (反应.是打断) {
    // 劣势 = 掷两次取低（卡面/世界书原文）
    const 骰 = 掷骰注入?.反应 ?? Math.min(rollDie(20), rollDie(20));
    const 属性键 = (反应.解释.关联属性 ?? 'STR') as 'STR' | 'AGI' | 'CON' | 'PER';
    const 属性修正 = 有效属性修正(守方, 属性键);
    const 打断值 = 骰 + Math.floor(属性修正 * 0.75);
    if (打断值 >= 攻方命中值) {
      步骤.push({
        类: '规则系',
        内容: `打断成功：「${名}」以「${反应.名}」打断「${动作名}」（打断 ${骰}+${显示数值(Math.floor(属性修正 * 0.75))} = ${显示数值(打断值)} ≥ 攻方命中 ${显示数值(攻方命中值)}）→ 本次攻击取消`,
        单位: 名,
        事件: '打断成功',
        单位键: 守方键,
      });
      return { 取消攻击: true, 额外减伤: 0, 命中加值: 0 };
    }
    步骤.push({
      类: '规则系',
      内容: `打断失败：「${名}」的「${反应.名}」（打断 ${显示数值(打断值)} < 攻方命中 ${显示数值(攻方命中值)}）→ 攻击照常结算，「${显示名(新状态.单位[攻方键] ?? 守方)}」本次命中 +2`,
      单位: 名,
      事件: '打断失败',
      单位键: 守方键,
    });
    return { 取消攻击: false, 额外减伤: 0, 命中加值: 2 };
  }

  // ===== 防御类：按技能规则落（护盾照常落地；减伤只对这一击生效）=====
  const 收集 = 应用规则(
    反应.解释,
    反应.名,
    ['使用时', '受击时'], // 卡面两种写法都认（反应技能是"被攻击时使用"）
    守方键,
    攻方键,
    {},
    新状态,
    步骤,
    true, // 受击视角：规则里的「自身」= 被打的这个
    true, // 只收集减伤，不把减伤落成持续状态（它只该管这一击）
  );
  const 额外减伤 = Math.max(0, Number(收集['减伤'] ?? 0));
  步骤.push({
    类: '规则系',
    内容: `反应防御：「${名}」的「${反应.名}」生效${额外减伤 ? `（本次减伤 ${Math.round(额外减伤 * 100)}%）` : ''}`,
    单位: 名,
    事件: '反应防御',
    单位键: 守方键,
  });
  return { 取消攻击: false, 额外减伤, 命中加值: 0 };
}

/** 主要行动 + 技能：射程 → 命中 → 六步伤害 → 写回守方 → 命中时规则落守方。 */
function 结算技能(
  新状态: 战斗状态,
  键: string,
  行动: 意图行动,
  掷骰注入: 掷骰注入 | undefined,
  步骤: 结算步骤[],
): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 技能名 = typeof 行动.技能 === 'string' ? 行动.技能.trim() : '';

  // 没写技能 = 基础攻击（世界书速查表：徒手 1d4 / 武器用武器）。
  // 这条分支是给「模型不知道该用什么技能」留的合法出路：以前这里直接跳过，
  // 于是模型一旦没写技能名，敌人就整轮空过 —— 一次也不出招。
  const 表 = 当前.技能 ?? {};
  const 技能解析 = 技能名 ? 解析技能名(表, 技能名) : undefined;
  const 原名 = 技能解析?.命中;
  const 是基础攻击 = 技能名 === '';
  const 解释: 战斗解释 | undefined = 原名
    ? 表[原名]
    : 是基础攻击
      ? 基础攻击解释(!!当前.主武器)
      : undefined;

  if (!解释) {
    // 技能名的合法来源只有单位技能表。名字对不上必须**说清可用技能与最近似候选** ——
    // 只说「没有技能」的话，玩家在面板上只看到「敌人不出招」，无从判断是不是 AI 在瞎编。
    步骤.push({
      类: '跳过',
      内容: `跳过：「${名}」没有技能「${技能名}」；该单位可用技能：${可用技能(表)}${
        技能解析?.候选.length ? `；最近似：${候选说明(技能解析.候选)}` : ''
      }`,
      单位: 名,
    });
    return;
  }

  // 技能名是被"串了字"但绑回来了（如「骨爪撕列」→「骨爪撕裂」）→ 必须留痕
  if (技能解析?.方式 === '近似') {
    步骤.push({
      类: '命中',
      内容: `技能名 ${绑定说明(技能名, 原名!, 技能解析.相似度)}`,
      单位: 名,
    });
  }

  /** 日志里显示的动作名（基础攻击时技能名是空串，不能直接打印） */
  const 动作名 = 原名 ?? (是基础攻击 ? '基础攻击' : 技能名);

  // 基础攻击用哪把武器：主要行动 = 主武器，次要行动 = 副武器
  // （由界面「主武器攻击 / 副武器攻击」选项或随机模式指定；AI 省略技能键时按主武器）。
  // 必须**先于**下面的日志与射程门禁定下来。
  const 攻击武器 = 是基础攻击 ? (行动.武器 === '副武器' ? 当前.副武器 : 当前.主武器) : 当前.主武器;

  if (是基础攻击) {
    // 日志要**诚实**：声明了副武器但手里没有 → 实际就是徒手（别写"副武器"骗玩家）
    const 用了什么 = 攻击武器 ? (行动.武器 === '副武器' ? '副武器' : '主武器') : '徒手 1d4，近战';
    步骤.push({
      类: '命中',
      内容: `「${名}」按基础攻击结算（${用了什么}）`,
      单位: 名,
    });
  }

  // 冷却门禁：还在冷却里的技能不能用（玩家口径：技能最小 1 回合冷却，没写按 1 算）。
  // **放在槽位/目标检查之前** —— "还在冷却"才是真正的拒绝原因，别被"槽已用尽"盖住。
  const 免冷却 = 当前.词条?.has(免冷却词条) ?? false; // 「取消下一次技能的冷却」这类增益
  if (原名 && !免冷却) {
    const 剩余 = 当前.冷却?.[原名] ?? 0;
    if (剩余 > 0) {
      步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的「${原名}」还在冷却（剩 ${剩余} 回合）`, 单位: 名 });
      return;
    }
  }

  // 资源消耗门禁（世界书：使用技能即时扣耐力/MP）——不够就发动不了
  const 消耗 = 原名 || 是基础攻击 ? 解析消耗(解释.消耗) : null;
  if (消耗) {
    const 存量 = 消耗.资源 === 'MP' ? 当前.MP_当前 : 当前.耐力_当前;
    if (存量 < 消耗.量) {
      步骤.push({
        类: '跳过',
        内容: `跳过：「${名}」的「${动作名}」需要 ${消耗.资源} ${消耗.量}，只剩 ${存量}`,
        单位: 名,
      });
      return;
    }
  }

  // 「目标: 自身」的技能（自 buff、变身、界王拳这类）**强制指向自己** ——
  // 界面/AI 给的目标对它们没有意义，硬按敌方结算会走成"攻击自己人"。
  const 是自身技能 = String(解释.目标 ?? '').includes('自身');
  const 目标解析 = 是自身技能
    ? { 单位: 当前, 方式: '精确' as const, 候选: [] }
    : 行动.目标
      ? 解析单位(新状态, 行动.目标)
      : undefined;
  const 目标 = 目标解析?.单位;
  if (是自身技能 && 行动.目标) {
    步骤.push({ 类: '命中', 内容: `说明：「${名}」的「${动作名}」目标为自身，忽略所选目标`, 单位: 名 });
  }
  if (!目标) {
    步骤.push({
      类: '跳过',
      内容: `跳过：「${名}」的目标「${行动.目标 ?? ''}」不在战场上；最近似候选：${候选说明(
        目标解析?.候选 ?? [],
      )}`,
      单位: 名,
    });
    return;
  }
  if (目标解析?.方式 === '近似') {
    步骤.push({
      类: '命中',
      内容: `目标 ${绑定说明(行动.目标 ?? '', 显示名(目标), 目标解析.相似度)}`,
      单位: 名,
    });
  }

  // 次要行动也能带技能（「给友军上 buff」常常是次要行动）。
  // 但**次要行动只能做支援** —— 见下面同阵营分支里的拒绝逻辑：放开次要行动攻击
  // 等于每个单位每回合多打一次，不符合世界书（攻击是主要行动）。
  const 槽型: '主要行动' | '次要行动' | '免费行动' =
    行动.类型 === '次要行动' ? '次要行动' : 行动.类型 === '免费行动' ? '免费行动' : '主要行动';
  const 剩余槽 =
    槽型 === '次要行动' ? 当前.行动槽.次要 : 槽型 === '免费行动' ? 当前.行动槽.免费 : 当前.行动槽.主要;
  if (剩余槽 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的${槽型}槽已用尽`, 单位: 名 });
    return;
  }

  // 射程硬门禁：超程 = 无法发动，不消耗行动。
  // 全场以玩家为唯一坐标原点（spec §8「单一坐标原点」）：`战斗单位.距离` = 该单位**距玩家多少米**。
  // 所以攻守间距 = |攻方.距离 − 守方.距离| —— 绝不能拿攻方距玩家的距离（玩家恒为 0，
  // 用 当前.距离 会让玩家任何近战技能都隔着整张地图命中）。
  const 攻守距离 = Math.abs(当前.距离 - 目标.距离);
  const 射程 =
    是基础攻击 && 攻击武器
      ? { 通过: true, 说明: '基础攻击：卡里未记录武器类型（近战/枪械？），不做距离门禁' }
      : 射程检查(解释.射程, 攻守距离);
  if (!射程.通过) {
    步骤.push({ 类: '跳过', 内容: `跳过：${射程.说明}`, 单位: 名 });
    return;
  }
  if (射程.说明) {
    步骤.push({ 类: '命中', 内容: `说明：「${名}」的「${动作名}」${射程.说明}`, 单位: 名 });
  }

  // 通过全部门禁 → 消耗行动槽 / 记冷却 / 扣资源（回滚时 扣槽前 会把它们一起还原）
  const 扣槽前 = 当前;
  const 补丁: Partial<战斗单位> = { 行动槽: 行动槽消耗(当前.行动槽, 槽型) };
  // 冷却：免冷却词条生效时不进冷却，并且**消耗掉**这个词条
  if (原名 && 免冷却) {
    补丁.冷却 = { ...(当前.冷却 ?? {}) };
    const 词条 = new Set(当前.词条);
    词条.delete(免冷却词条);
    补丁.词条 = 词条;
    步骤.push({ 类: '命中', 内容: `「${名}」的「${免冷却词条}」生效：本次不进入冷却`, 单位: 名 });
  } else if (原名) {
    补丁.冷却 = { ...(当前.冷却 ?? {}), [原名]: 冷却回合数(解释) };
  }
  if (消耗) {
    if (消耗.资源 === 'MP') 补丁.MP_当前 = 当前.MP_当前 - 消耗.量;
    else 补丁.耐力_当前 = 当前.耐力_当前 - 消耗.量;
  }
  写回(新状态, 键, 补丁);
  if (消耗) {
    步骤.push({ 类: '命中', 内容: `「${名}」消耗 ${消耗.资源} ${消耗.量}`, 单位: 名 });
    跑自身触发(新状态, 键, ['资源变化时'], 步骤); // 自己花掉资源也算"资源变化"
  }

  // 「使用时」规则：**在算伤害之前**落效果 —— 「该次攻击最终伤害×5」这类增伤才来得及进乘区。
  // （早先攻击路径完全不跑「使用时」，于是这类效果只能写成「命中时」，而命中时是算完伤害才跑的，
  //   结果增伤晚了一次攻击才生效。）
  try {
    const 攻方 = 新状态.单位[键];

    // 重新取守方：写回行动槽时若「打自己」会换掉同一个键的对象，用旧引用会丢改动
    const 守方键 = 找键(新状态, 目标);
    const 守方 = 守方键 === undefined ? undefined : 新状态.单位[守方键];
    if (守方键 === undefined || !守方) return;

    const 目标名 = 显示名(守方);

    // ===== 支援行动（R21）：同阵营目标不走攻击管线 =====
    // 见 `结算支援` 的注释：否则帮队友上 buff 会变成"掷命中对抗队友闪避值 + 打出武器伤害"。
    if (守方.阵营 === 攻方.阵营) {
      结算支援(新状态, 解释, 动作名, 键, 守方键, 步骤);
      return;
    }

    // 「使用时」规则：**只对攻击路径跑一次**，且在算伤害之前 ——
    // 「该次攻击最终伤害×N」这类增伤才来得及进这一次的伤害。
    // 收集模式：数值修正是**本次攻击**的临时量，不落成持续状态（落成状态会持续好几回合，语义错）。
    // （支援行动在上面的分支里走的是 结算支援，它自己会跑「使用时」，所以这里不能重复跑 ——
    //   早先放在 try 之前就踩了这个坑：星幕的护盾被加了两次。）
    // 打断取消要拆"本 cast 刚落上的"连击状态 —— 「使用时」规则在下面就会把它落上来，
    // 所以快照必须拍在 应用规则 **之前**（拍晚了就会把本 cast 的连击当"开打前就有的"留下来）。
    const 追加状态前 = new Set(
      (新状态.单位[键]?.状态 ?? []).filter(st => (st.词条 ?? []).includes(连击词条)),
    );
    const 本次修正 = 应用规则(
      解释,
      动作名,
      ['使用时', '攻击时'], // 「攻击时」在攻击路径上就等于「使用时」（卡面两种写法都认）
      键,
      守方键,
      { 目标HP: 守方.HP_当前 },
      新状态,
      步骤,
      false,
      true,
    );

    /**
     * 本轮用的解释：追加轮里**屏蔽「追加攻击」动作**。
     * 卡面写「每次进行攻击后额外追加两次」—— 追加出来的攻击如果又触发这条，
     * 就是无限递归（字面无限）。所以追加次数只在**主攻击**时读一次，追加轮不再产生新的追加。
     */
    const 解释本轮 = (收集追加: boolean): 战斗解释 =>
      收集追加
        ? 解释
        : {
            ...解释,
            规则: (解释.规则 ?? []).map(规则 => ({
              ...规则,
              动作: (规则.动作 ?? []).filter(动作 => 动作.类 !== '追加攻击'),
            })),
          };

    /** 一次完整的攻击结算（命中→六步伤害→命中时规则）。追加轮会让它多跑几次。 */
    const 打一次 = (收集追加: boolean): '打断取消' | undefined => {
      const 本轮解释 = 解释本轮(收集追加);
    const 参数 = 技能参数(解释);

    // 规则系防火墙：攻方声明的（穿透/必中/必暴/即死/无视）**必须过判定**；
    // 守方被动的（无敌/锁血/无视）一直生效，只在被穿透/无视时参与对抗。敌我一视同仁。
    const 裁决 = 规则系防火墙(攻方, 守方, 参数.属性键, 动作名, 步骤, 掷骰注入?.规则系);
    const 穿透 = 裁决.攻方生效.has('穿透');
    const 必中 = 裁决.攻方生效.has('必中');
    const 无视 = 裁决.攻方生效.has('无视');
    const 即死 = 裁决.攻方生效.has('即死');
    const 免伤 = 裁决.守方生效.has('无敌');
    const 锁血 = 裁决.守方生效.has('锁血');

    // 词条门禁（spec §3.3：词条是状态标签，引擎直接检查、不过判定）：
    // 目标带「不可被常规攻击命中」→ 常规攻击打不中；只有规则系的「穿透/无视」**过了判定**才打得中。
    if (守方.词条?.has(词条_不可被常规攻击命中) && !穿透 && !无视) {
      步骤.push({
        类: '跳过',
        内容: `跳过：「${目标名}」带词条「${词条_不可被常规攻击命中}」—— 常规攻击打不中（需要规则系的穿透/无视通过判定）`,
        单位: 名,
      });
      return;
    }

    // 用「有效属性修正」：状态携带的属性点增量（献祭防御换 STR 这类）也算进来
    const 属性修正 = 有效属性修正(攻方, 参数.属性键);
    const AGI修正 = 有效属性修正(攻方, 'AGI');
    const 被动 = 常驻修正(攻方, '命中') + (本次修正['命中'] ?? 0);
    const 骰值 = 掷骰注入?.命中 ?? rollDie(20);

    // 第二步的「DC+…×敌人位阶」加在守方 DC 上
    // 目标闪避值 = 面板值 + 部位 DC 加值 + **状态携带的闪避修正** + AGI 修正值增量×0.5
    //（面板值已含面板 AGI修正×0.5；状态再动 AGI 修正值时，只把增量按世界书口径折算进来）
    const 命中DC =
      守方.闪避值 +
      常驻修正(守方, '闪避') +
      Math.floor(状态属性修正增量(守方, 'AGI') * 0.5) +
      部位DC加值(参数.部位, 位阶序数(守方.阶位));

    const 攻方命中值 = 命中判定值({
      骰值,
      属性修正,
      技能阶位: 参数.技能阶位,
      被动加成: 被动,
      AGI修正,
    });

    // ===== 第五步（前半）：守方反应动作 =====
    // 打断类必须在**命中判定之前**结算（世界书阶段 B1 的 b2：打断拦截）；
    // 防御类只在真的被命中时结算。没预置反应 → 这里什么也不发生（玩家裁决）。
    // 世界书：仅可打断**可预判**攻击（偷袭/不可预判的技能打断不了）。
    const 反应预判 = 守方反应技能(守方);
    let 打断结果: 反应结局 | undefined;
    if (反应预判?.是打断 && 解释.可预判 !== false) {
      打断结果 = 结算守方反应(新状态, 键, 守方键, 攻方命中值, 动作名, 掷骰注入, 步骤);
      if (打断结果.取消攻击) return '打断取消'; // 攻击取消 → 后面的命中/伤害/命中时规则/连击全都不发生
    }
    const 命中加值 = 打断结果?.命中加值 ?? 0;

    const 命中 = 必中
      ? true // 规则系「必中」过了判定 → 直接命中（spec：过了才生效）
      : 攻方命中值 + 命中加值 >= 命中DC;

    if (必中) {
      步骤.push({ 类: '规则系', 内容: `规则系「必中」生效：「${名}」的「${动作名}」直接命中`, 单位: 名, 事件: '规则系', 效果: '必中', 单位键: 键 });
    }

    if (!命中) {
      const 有效修正 = 属性修正 * (1 + 参数.技能阶位 / 5);
      步骤.push({
        类: '命中',
        内容: `「${名}」的「${动作名}」未命中「${目标名}」（${骰值} + ${显示数值(有效修正)} + 被动 ${被动} + AGI×0.2 ${显示数值(AGI修正 * 0.2)}${命中加值 ? ` + 打断失败加值 ${命中加值}` : ''} = ${显示数值(骰值 + 有效修正 + 被动 + AGI修正 * 0.2 + 命中加值)} < ${命中DC}）`,
        单位: 名,
        事件: '未命中',
        攻方: 名,
        守方: 目标名,
        攻方键: 键,
        守方键,
      });
      return;
    }

    // ===== 第五步（后半）：防御类反应（护盾/减伤/反伤）=====
    let 反应减伤 = 0;
    if (反应预判 && !反应预判.是打断) {
      反应减伤 = 结算守方反应(新状态, 键, 守方键, 攻方命中值, 动作名, 掷骰注入, 步骤).额外减伤;
    }
    // 反应可能改了守方的护盾/资源 → 后面的伤害结算必须读**最新**的那一份
    const 守方最新 = 新状态.单位[守方键] ?? 守方;

    // 打断失败给的命中 +2 真的生效了 → 日志里要带出来（未命中的日志已经写了，命中的也要有）
    const 打断加值说明 = 命中加值 ? `，打断失败，攻方命中 +${命中加值} 生效` : '';

    // ===== 第一 / 三 / 四 / 六步 =====
    const 攻击阶位 = 位阶序数(攻方.阶位);
    const 手持武器 = 是基础攻击 ? 攻击武器 : 攻方.主武器; // 技能攻击仍按主武器计算武器部分
    const 骰值总和 = 掷骰注入?.伤害骰?.length
      ? 掷骰注入.伤害骰.reduce((a, b) => a + b, 0)
      // 无武器 = 徒手（世界书速查表：徒手 1d4 / 倍率 0.5 / 强化 0）
      : 掷伤害骰(手持武器?.伤害骰 ?? '1d4');

    // 「基础伤害骰」= 加在伤害骰总和上的修正（"武器伤害骰+2"这类）；
    // 「攻击倍率」= 加在武器倍率上的修正（"武器威力+30%"这类）。两者都只取**攻方**的量。
    const 骰值总和_含修正 = 骰值总和 + 常驻修正(攻方, '基础伤害骰');
    const 武器倍率 = (手持武器?.倍率 ?? 0.5) + 常驻修正(攻方, '攻击倍率');
    const 武器 = 武器伤害(
      骰值总和_含修正,
      手持武器?.强化等级 ?? 0,
      武器位阶序数(手持武器, 攻击阶位),
      属性修正,
      武器倍率,
    );
    // 世界书 <技能模版和限制>：技能伤害 = 关联属性修正值 × 伤害倍率（再按技能阶位成长）
    const 技能 = 技能伤害(属性修正 * 参数.伤害倍率, 参数.技能阶位);
    const 基础伤害 = 武器 + 技能;
    // 守方防御 = 面板值 + 状态携带的「防御」修正 + CON 修正值增量×0.2（世界书口径）
    // 规则系「穿透」过了判定 → 防御按 0 算（spec：过了就无视防御/护盾/减伤）
    const 有效防御 = 穿透
      ? 0
      : 守方.防御 + 常驻修正(守方, '防御') + Math.floor(状态属性修正增量(守方, 'CON') * 0.2);
    const 混 = 混合伤害(基础伤害, 有效防御); // 面板防御已含装备/额外加成（裁决 R15）

    const 部位倍 = 部位倍率(参数.部位); // 第二步
    const 暴击 = 裁决.攻方生效.has('必暴') || 骰值 >= 暴击范围(攻方.属性.实际.AGI); // 第三步
    const 暴击倍 = 暴击倍率(暴击);
    // 第四步：总增伤 = Σ(倍率−1) —— 取行动者身上「常驻·作用域自身」的 `数值修正[伤害]`
    const 总增伤 = 常驻修正(攻方, '伤害') + (本次修正['伤害'] ?? 0);
    const 乘区 = 效果乘区(总增伤);
    // 真·最终伤害倍率（卡面「该次攻击最终伤害×N」）：增量写法，填 4 = ×5。
    // 与「伤害」分开放：那一个进的是世界书的递减曲线（效果乘区），×5 根本表达不出来。
    // 常驻的「最终乘区」（被动/装备写"你的伤害×N"）与「使用时」的本次修正一起算。
    // 早先只读 本次修正，于是常驻写的 ×N 会被静默丢掉。
    const 终伤倍率 = 1 + 常驻修正(攻方, '最终乘区') + (本次修正['最终乘区'] ?? 0);

    const 乘区后 = 混 * 部位倍 * 暴击倍 * 乘区 * 终伤倍率;
    const 护盾消耗 = 穿透 ? 0 : Math.min(守方最新.护盾, 乘区后); // 护盾优先扣除（穿透则直接跳过）
    // 第六步：减伤比例取守方身上「常驻·作用域自身」的 `数值修正[减伤]` + **本次反应**的减伤。
    // 世界书原文「减伤/反伤最高 50%」→ 这里封顶 0.5（只封顶不封底：负值留作易伤）。
    const 减伤比例 = 穿透 ? 0 : Math.min(常驻修正(守方最新, '减伤') + 反应减伤, 0.5);
    const 伤害 = 最终伤害({
      混合伤害: 混,
      部位倍率: 部位倍,
      暴击倍率: 暴击倍,
      效果乘区: 乘区,
      护盾: 护盾消耗,
      减伤比例,
      终伤倍率, // 必须传进去 —— 最终伤害 是从各部分重算的，在外面乘局部变量没用
    });

    步骤.push({
      类: '命中',
      内容: `「${名}」的「${动作名}」命中「${目标名}」（${骰值} + ${显示数值(属性修正 * (1 + 参数.技能阶位 / 5))} + 被动 ${被动} + AGI×0.2 ${显示数值(AGI修正 * 0.2)} ≥ ${命中DC}）${暴击 ? '，自然暴击' : ''}${打断加值说明}`,
      单位: 名,
    });

    const HP变化前 = 守方最新.HP_当前;

    // 规则系落地：无敌（守方生效）→ 完全免伤；锁血 → HP 不低于 1；即死（攻方过判定）→ 直接打倒。
    // 「无敌 vs 即死」这种正面对撞由上面的对抗决定谁生效，所以这里不会两边同时成立。
    const 实收 = 免伤 ? 0 : 伤害;
    if (免伤) 步骤.push({ 类: '规则系', 内容: `规则系「无敌」生效：「${目标名}」免除此击全部伤害`, 单位: 目标名, 事件: '规则系', 效果: '无敌', 单位键: 守方键 });

    let 结算后HP = Math.max(守方最新.HP_当前 - 实收, 0);
    if (锁血 && 结算后HP < 1) {
      结算后HP = 1;
      步骤.push({ 类: '规则系', 内容: `规则系「锁血」生效：「${目标名}」HP 锁定在 1`, 单位: 目标名, 事件: '规则系', 效果: '锁血', 单位键: 守方键 });
    }
    // 「锁血下限」（比例）：一次打穿到低于 N% 最大HP 时只锁在线上
    //（玩家口径：「无法一次跌入 50% 以下的血量，必须当前回合先锁在最低 50%」）
    const 锁血下限比例 = 穿透 ? 0 : Math.max(0, Math.min(常驻修正(守方最新, '锁血下限'), 1));
    if (锁血下限比例 > 0) {
      const 下限 = Math.floor(守方最新.HP_最大 * 锁血下限比例);
      if (结算后HP < 下限) {
        结算后HP = 下限;
        步骤.push({
          类: '规则系',
          内容: `锁血生效：「${目标名}」本回合最低只能到最大HP的 ${Math.round(锁血下限比例 * 100)}%（锁在 ${下限}）`,
          单位: 目标名,
          事件: '规则系',
          效果: '锁血',
          单位键: 守方键,
        });
      }
    }
    if (即死) {
      结算后HP = 0;
      步骤.push({ 类: '规则系', 内容: `规则系「即死」生效：「${目标名}」被直接抹杀`, 单位: 目标名, 事件: '规则系', 效果: '即死', 单位键: 守方键 });
    }

    // HP 归零 → 打上濒死标记（世界书：HP 归零即进入濒死判定，不是死亡；
    // 死亡要濒死检定连续三次失败。见 turn.ts 的生死判定）
    // **副本角色没有濒死**（玩家裁决：濒死检定是契约者的特权）→ 标记濒死 会直接放行。
    const 新守方: 战斗单位 = 标记濒死({
      ...守方最新,
      HP_当前: 结算后HP,
      护盾: 守方最新.护盾 - 护盾消耗,
    });
    新状态.单位[守方键] = 新守方;

    // ===== BOSS 转阶段（世界书 <combat_driver> 阶段D）=====
    // 当前 HP 首次降到阶段线（70/40/20）或被打到 0 → 立刻跑它自己的「转阶段」规则
    //（清负面、回 HP/MP、拿护盾/1 回合无敌 —— 玩家口径：「boss 会有转阶段的能力，比如濒死了回满血」）。
    // 这就是"BOSS 濒死回满血"的正解：**转阶段是有限的阶段机制**，不是回合开始回血那种无限复活。
    {
      const 转 = 判定转阶段(新状态.单位[守方键], HP变化前, 新状态.单位[守方键].HP_当前);
      if (转) {
        步骤.push({
          类: '规则系',
          内容: `「${目标名}」进入转阶段（${转.阈值}）`,
          单位: 目标名,
          事件: '变身', // 与变身共用全屏演出
          形态: `${转.阈值} · 转阶段`,
          单位键: 守方键,
        });
        跑自身触发(新状态, 守方键, ['转阶段'], 步骤, { 最终伤害: 伤害, 目标HP: 新状态.单位[守方键].HP_当前 });
      }
    }

    // 转阶段可能已经把它回满了 —— 之后的日志 / 命中时 / 击杀时 一律读**最新**的 HP
    //（否则 BOSS 转阶段回满血之后还会被判"击倒"，击杀时奖励白送）
    const 守方终HP = 新状态.单位[守方键]?.HP_当前 ?? 新守方.HP_当前;

    步骤.push({
      类: '伤害',
      内容:
        `「${目标名}」受到 ${显示数值(实收)} 伤害（六步：基础 ${显示数值(基础伤害)} − 防御 ${显示数值(有效防御)} = 混合 ${显示数值(混)}` +
        ` × 部位 ${部位倍} × 暴击 ${暴击倍} × 乘区 ${显示数值(乘区)}${终伤倍率 !== 1 ? ` × 终伤倍率 ${显示数值(终伤倍率)}` : ''} − 护盾 ${显示数值(护盾消耗)} − 减伤 ${显示数值(乘区后 * 减伤比例)}）` +
        `，HP ${HP变化前} → ${新守方.HP_当前}` +
        (守方终HP !== 新守方.HP_当前 ? `（转阶段后 ${守方终HP}）` : '') +
        (减伤比例 ? `（目标减伤 ${Math.round(减伤比例 * 100)}%）` : ''),
      单位: 目标名,
      事件: '命中',
      数值: 实收,
      攻方: 名,
      守方: 目标名,
      攻方键: 键,
      守方键,
    });

    应用规则(本轮解释, 动作名, ['命中时'], 键, 守方键, { 最终伤害: 伤害, 目标HP: 守方终HP }, 新状态, 步骤);

    // **击杀时**：这一击把目标从"活着"打到"倒下" → 跑行动者（击杀者）的击杀时规则
    // 转阶段把它救回来的不算击倒（守方终HP > 0 → 不跑击杀时）
    if (HP变化前 > 0 && 守方终HP <= 0) {
      步骤.push({
        类: '击杀',
        内容: `「${目标名}」被「${名}」击倒`,
        单位: 目标名,
        事件: '濒死',
        守方: 目标名,
        守方键,
      });
      跑自身触发(新状态, 键, ['击杀时'], 步骤, { 最终伤害: 伤害, 目标HP: 0 });
    }
    // **资源变化时**：被命中方的 HP 变了 → 跑它自己的资源变化时规则
    //（「血量低于 50% 时触发」就靠这条 + 条件里的 HP比例 判断）
    跑自身触发(新状态, 守方键, ['资源变化时'], 步骤, { 最终伤害: 伤害, 目标HP: 新状态.单位[守方键].HP_当前 });

    // **被打的人自己的「受击时 / 被命中后」规则**（菲琳之心：被命中后给攻击者挂「冻结」）。
    // 视角是"受击"：规则主人是守方，所以「攻击者」指打它的人（见 作用域单位 的 受击视角）。
    for (const [守方技能名, 守方解释] of Object.entries(新状态.单位[守方键].技能 ?? {})) {
      应用规则(
        守方解释,
        守方技能名,
        ['受击时', '被命中后'],
        守方键,
        键,
        { 最终伤害: 伤害, 目标HP: 新状态.单位[守方键].HP_当前 },
        新状态,
        步骤,
        true, // 受击视角
      );
    }
    return undefined; // 没被打断：正常走完这一次攻击
    }; // 打一次 结束

    // 打断取消 → 连击循环**不跑**（世界书「本次攻击取消」是整次取消，不然打断只是少挨第一刀）。
    // 主攻击落下「追加攻击」的状态可能还在：本 cast 刚落上的要拆掉（否则下一次技能白嫖一次连击）；
    // 开打**之前**就有的连击来源（"下一次技能释放两次"这类）保留 —— 它的"下一次"根本没发生。
    const 主击 = 打一次(true); // 主攻击（会落「追加攻击」）
    if (主击 === '打断取消') {
      const 连击者0 = 新状态.单位[键];
      if (连击者0) {
        新状态.单位[键] = {
          ...连击者0,
          状态: 连击者0.状态.filter(st => !(st.词条 ?? []).includes(连击词条) || 追加状态前.has(st)),
        };
      }
      return;
    }

    // 「连击」：额外释放若干次。两种写法都认 ——
    //   a. 裸词条 `连击`（"下一次技能释放两次"）= 追加 1 次
    //   b. 带层数的追加状态（`追加攻击: N` 落的）= 追加 N 次
    // **只读一次**（主攻击落下的那个），追加轮不再产生新的追加 —— 否则「每次攻击追加两次」
    // 会无限递归（卡面字面就是无限的，引擎必须收口）。上限 5 次兜底。
    const 连击者 = 新状态.单位[键];
    const 追加状态 = 连击者?.状态.find(st => (st.词条 ?? []).includes(连击词条));
    const 裸词条 = 连击者?.词条?.has(连击词条) ?? false;
    const 追加次数 = Math.min(追加状态 ? Math.max(追加状态.层数 ?? 1, 1) : 裸词条 ? 1 : 0, 5);

    if (追加次数 > 0 && 连击者) {
      // 消耗掉来源（追加状态整条移除 / 裸词条删掉），免得留给下一次技能
      const 词条 = new Set(连击者.词条);
      词条.delete(连击词条);
      新状态.单位[键] = {
        ...连击者,
        词条,
        状态: 连击者.状态.filter(st => st !== 追加状态),
      };
      步骤.push({ 类: '命中', 内容: `「${名}」的「${连击词条}」生效：本次技能额外释放 ${追加次数} 次`, 单位: 名 });
      for (let i = 0; i < 追加次数; i++) 打一次(false); // 追加轮：不再产生新的追加
    }
  } catch (e) {
    // 回滚刚扣的行动槽：这一行动没结算成（未知阶位 / 非法骰式 …），不该白吃槽位
    新状态.单位[键] = 扣槽前;
    throw e;
  }
}

/**
 * 支援行动（裁决 R21）：**目标与行动者同阵营**时走这里，不走攻击管线。
 *
 * 为什么必须分支：敌人给友军上 buff 时「目标」是队友 —— 走攻击管线会去掷命中
 * **对抗队友的闪避值**（还可能"未命中"），接着打出**武器伤害**（把队友当敌人打）。
 * 支援行动：不掷命中、不造成伤害、不扣护盾，只把技能规则的效果落到目标身上。
 * 射程门禁照样走（技能写近战就不能隔 800 米给队友加 buff），行动槽照样扣。
 */
function 结算支援(
  新状态: 战斗状态,
  解释: 战斗解释,
  动作名: string,
  施方键: string,
  受方键: string,
  步骤: 结算步骤[],
): void {
  const 施方 = 新状态.单位[施方键];
  const 受方 = 新状态.单位[受方键];

  步骤.push({
    类: '命中',
    内容: `「${显示名(施方)}」对队友「${显示名(受方)}」使用「${动作名}」（支援行动：不掷命中、不造成伤害）`,
    单位: 显示名(施方),
  });

  // 支援技能的效果挂在 `使用时`（多数翻译结果）或 `命中时`（沿用攻击技的写法）
  const 上下文 = { 目标HP: 受方.HP_当前 };
  应用规则(解释, 动作名, ['使用时', '命中时'], 施方键, 受方键, 上下文, 新状态, 步骤);
}

/**
 * 把 `解释.规则` 里指定触发点的规则落到对应单位（护盾/状态/词条/资源/数值修正）。
 * 攻击管线用 `['命中时']` + 伤害上下文；支援行动用 `['使用时','命中时']`。
 */
function 应用规则(
  解释: 战斗解释,
  动作名: string,
  触发点列表: 触发点[],
  施方键: string,
  受方键: string,
  数值上下文: { 最终伤害?: number; 目标HP?: number },
  新状态: 战斗状态,
  步骤: 结算步骤[],
  /** true = 受击视角（规则主人是**被打的那个**，见 `作用域单位`） */
  受击视角 = false,
  /**
   * 收集模式：**不把 `数值修正` 落成状态**，而是把它们累加后返回。
   * 用途：「使用时」的数值修正是"**本次攻击**"的临时修正（卡面：该次攻击最终伤害×N），
   * 落成状态就会持续好几回合（语义错），所以收集起来直接喂给这一次的伤害计算。
   * 其余动作（护盾/状态/词条/资源…）照常落地。
   */
  收集数值修正 = false,
): Record<string, number> {
  const 施方 = 新状态.单位[施方键];
  const 收集: Record<string, number> = {};

  for (const 规则 of 有效规则(解释)) {
    if (!触发点列表.includes(规则.触发)) continue;

    // 条件不满足 → **留下日志**。静默什么都不发生是最难查的一种坏
    //（玩家的「血量低于 50% 才能发动」这类技能，条件不满足时必须看得出来）
    if (规则.条件) {
      let 满足 = false;
      try {
        满足 = 判定条件(规则.条件, 施方, 新状态.单位[受方键], 数值上下文);
      } catch (e: any) {
        步骤.push({
          类: '跳过',
          内容: `忽略：「${动作名}」的条件求值失败：${e?.message ?? e}`,
          单位: 显示名(施方),
        });
        continue;
      }
      if (!满足) {
        步骤.push({
          类: '跳过',
          内容: `「${动作名}」的${规则.触发}条件不满足 → 本条不生效`,
          单位: 显示名(施方),
        });
        continue;
      }
    }

    let 结果: ReturnType<typeof 执行规则>;
    try {
      结果 = 执行规则(规则, 施方, 新状态.单位[受方键], 数值上下文);
    } catch (e: any) {
      步骤.push({
        类: '跳过',
        内容: `忽略：「${显示名(施方)}」的${规则.触发}规则求值失败：${e?.message ?? e}`,
        单位: 显示名(施方),
      });
      continue;
    }

    /**
     * 「额外行动回合」**既不是状态、也不是"本次攻击"的临时量** —— 它是欠在目标身上的
     * 一个行动回合（当场要打断重选）。所以先把它从数值修正里摘出来，收集模式也不能吞掉它，
     * 之后按作用域单独落（`落效果` 认这一项）。
     */
    let 额外回合 = 0;
    if (结果.数值修正) {
      const n = Math.floor(Number(结果.数值修正['额外行动回合'] ?? 0));
      if (Number.isFinite(n) && n !== 0) 额外回合 = n;
      delete 结果.数值修正['额外行动回合'];
    }

    if (收集数值修正 && 结果.数值修正) {
      for (const [键名, 量] of Object.entries(结果.数值修正)) 收集[键名] = (收集[键名] ?? 0) + 量;
      delete 结果.数值修正;
    }

    for (const 键 of 作用域单位(新状态, 规则.作用域, 施方键, 受方键, 受击视角)) {
      落效果(新状态, 键, 结果, 动作名, 步骤, 施方键);
      if (额外回合) {
        落效果(新状态, 键, { 数值修正: { 额外行动回合: 额外回合 } }, 动作名, 步骤, 施方键);
      }
    }
  }

  return 收集;
}

/**
 * `数值修正` 类动作落成状态时的默认持续回合。
 *
 * 为什么需要一个默认值：`数值修正` 动作**本身不带持续**（只有 `施加状态` 带）。
 * 翻译器要精确控制持续就该用 `施加状态`；这里给一个"一次战斗里够用"的默认，
 * 而不是把修正静默丢掉（丢掉的后果是"给友军上 buff"完全没效果）。
 */
const 数值修正默认持续 = 2;

/**
 * 把一条规则的求值结果落到某个单位上。
 *
 * 已承载：护盾 / 状态 / 词条 / 资源 / **数值修正**（落成携带 `数值修正` 的状态）/
 * **切换形态**（落成「形态：X」状态）/ **追加攻击**（落成带层数的「连击」状态）/
 * **范围伤害**（按一维距离的半径结算）/ **规则系判定**（留痕，防火墙未接线）。
 *
 * 仍未承载：**领域**（战场级区域效果，属独立子系统）。
 */
function 落效果(
  新状态: 战斗状态,
  键: string,
  结果: ReturnType<typeof 执行规则>,
  动作名: string,
  步骤: 结算步骤[],
  /** 范围伤害要排除的人（施法者自己）—— 否则同一距离上会被自己的 AoE 波及 */
  排除键?: string,
): void {
  const 单位 = 新状态.单位[键];
  const 补丁: Partial<战斗单位> = {};
  const 应用: string[] = [];
  let 新状态列表 = 单位.状态;

  if (结果.护盾) {
    补丁.护盾 = 单位.护盾 + 结果.护盾;
    应用.push(`护盾+${显示数值(结果.护盾)}`);
  }
  if (结果.状态?.length) {
    新状态列表 = 结果.状态.reduce((列表, s) => 施加状态(列表, s), 新状态列表);
    应用.push(`状态 ${结果.状态.map(s => s.名).join('、')}`);
  }
  if (结果.数值修正 && Object.keys(结果.数值修正).length) {
    // 「额外行动回合」不是状态，而是**欠着的行动回合数**（当场要打断重选）——
    // 从数值修正里摘出来直接记在单位上；其余修正照旧落成状态。
    const 修正 = { ...结果.数值修正 };
    const 追加 = Number(修正['额外行动回合'] ?? 0);
    if (Number.isFinite(追加) && Math.floor(追加) !== 0) {
      const 层 = Math.floor(追加);
      delete 修正['额外行动回合'];
      补丁.追加行动 = (单位.追加行动 ?? 0) + 层;
      应用.push(`额外行动回合 ×${层}（本回合当场可再行动一轮）`);
    }

    if (Object.keys(修正).length) {
      // 持续：动作里显式写了就按写的（变身/觉醒这类"整场生效"写 999），没写按默认 2 回合
      const 持续 = Math.max(
        1,
        ...Object.keys(修正).map(k => Math.floor(结果.数值修正持续?.[k] ?? 数值修正默认持续)),
      );
      // 状态名用技能名：不同技能的 buff 互不覆盖（`施加状态` 同名是后覆盖先）
      新状态列表 = 施加状态(新状态列表, {
        名: 动作名,
        持续,
        数值修正: 修正,
      });
      应用.push(
        `数值修正 ${Object.entries(修正)
          .map(([k, v]) => `${k}${v >= 0 ? '+' : ''}${显示数值(v)}`)
          .join('、')}（持续 ${持续 >= 战斗内持续 ? '本场战斗' : `${持续} 回合`}）`,
      );
    }
  }
  if (结果.词条?.size) {
    const 词条 = new Set(单位.词条);
    for (const 名 of 结果.词条) 词条.add(名);
    补丁.词条 = 词条;
    应用.push(`词条 ${[...结果.词条].join('、')}`);
  }
  // 变身 / 形态（万解、界王拳…）：落成一条状态，这样**面板与写回 MVU 的「特殊状态」里都看得见**
  //（实战反馈：变身类主动技能用完什么也不显示）
  if (结果.形态) {
    新状态列表 = 施加状态(新状态列表, {
      名: `形态：${结果.形态}`,
      持续: 战斗内持续,
      词条: [`形态:${结果.形态}`],
    });
    应用.push(`切换形态「${结果.形态}」`);
  }
  // 追加攻击 → 带**层数**的状态（层数 = 追加次数），由 结算技能 逐层消费。
  // 早先只加一个「连击」词条，把 `次数` 丢了 —— 虚空能源汲取器的"追加两次"只多打一次。
  if (结果.追加攻击 && 结果.追加攻击 > 0) {
    新状态列表 = 施加状态(新状态列表, {
      名: `${动作名}·追加`,
      持续: 数值修正默认持续,
      层数: 结果.追加攻击,
      词条: [连击词条],
    });
    应用.push(`追加攻击 ×${结果.追加攻击}（下次技能逐次释放）`);
  }
  // 范围伤害：以一维距离算半径 —— 距**中心单位**不超过半径的其他单位都吃这一份伤害。
  // 中心单位自己已经吃过主伤害，不重复结算。
  if (结果.范围伤害?.length) {
    for (const 范围 of 结果.范围伤害) {
      const 半径 = Number(范围.半径) || 0;
      const 中心 = 单位.距离;
      const 波及: string[] = [];
      for (const [其他键, 其他] of Object.entries(新状态.单位)) {
        // 中心单位已吃过主伤害；**施法者自己也排除**（范围伤害不该砸到自己）
        if (其他键 === 键 || 其他键 === 排除键 || 其他.HP_当前 <= 0) continue;
        if (Math.abs((其他.距离 ?? 0) - 中心) > 半径) continue;
        const 扣 = Math.max(0, Math.min(范围.量, 其他.HP_当前));
        if (扣 <= 0) continue;
        新状态.单位[其他键] = 标记濒死({ ...其他, HP_当前: 其他.HP_当前 - 扣 });
        波及.push(`${显示名(其他)} -${显示数值(扣)}`);
      }
      if (波及.length) 应用.push(`范围伤害（半径 ${半径} 米）：${波及.join('、')}`);
    }
  }
  // 规则系效果（穿透/必中/必暴/即死/无敌/锁血/无视）由**规则系防火墙**在攻击阶段处理：
  // 攻方声明的必须过判定、守方被动的参与对抗（见 `规则系防火墙` 与战报里的「规则系」行）。
  // 这里只是不再重复落地 —— 但**留痕**，免得"挂在非攻击触发点上"的规则系效果静默消失。
  if (结果.规则系判定?.length) {
    应用.push(
      `规则系效果 ${结果.规则系判定.map(r => r.效果).join('、')}（由防火墙在攻击阶段判定；此处不重复落地）`,
    );
  }
  if (结果.资源 && Object.keys(结果.资源).length) {
    // 「HP / MP / 耐力」（含 当前HP/HP_当前 等写法）映射到**真实字段**，其余进自定义资源池。
    // 没有这层映射的话，「血量归零时回满血」（二阶段变身）写出来只会塞进资源池、完全不动真血条。
    const 真实: Array<[string[], 'HP_当前' | 'MP_当前' | '耐力_当前', 'HP_最大' | 'MP_最大' | '耐力_最大']> = [
      [['HP', '当前HP', 'HP_当前'], 'HP_当前', 'HP_最大'],
      [['MP', '当前MP', 'MP_当前'], 'MP_当前', 'MP_最大'],
      [['耐力', '当前耐力', '耐力_当前'], '耐力_当前', '耐力_最大'],
    ];
    const 自定义: Record<string, number> = {};
    for (const [名, v] of Object.entries(结果.资源)) {
      const 命中 = 真实.find(([别名]) => 别名.includes(名));
      if (!命中) {
        自定义[名] = v;
        continue;
      }
      const [, 字段, 上限字段] = 命中;
      const 上限 = Number(单位[上限字段] ?? 0);
      const 新值 = Math.max(0, Math.min(v, 上限));
      (补丁 as any)[字段] = 新值;
      应用.push(`${名} → ${显示数值(新值)}${上限 ? `（上限 ${显示数值(上限)}）` : ''}`);
      // 回血超过 0 = 复活（二阶段变身）：濒死标记清掉，濒死计数重新开始
      if (字段 === 'HP_当前' && 新值 > 0 && 单位.濒死) 补丁.濒死 = null;
    }
    if (Object.keys(自定义).length) {
      补丁.资源 = { ...单位.资源, ...自定义 };
      应用.push(`资源 ${Object.entries(自定义).map(([k, v]) => `${k}=${v}`).join('、')}`);
    }
  }

  if (!应用.length) return;

  补丁.状态 = 新状态列表;
  const 新单位 = { ...单位, ...补丁 };
  新状态.单位[键] = 新单位;
  步骤.push({
    类: '命中',
    内容: `「${显示名(新单位)}」受到技能效果：${应用.join('，')}`,
    单位: 显示名(新单位),
    // 变身 → 演出层全屏演出（切换形态落成的那一步才打这个标记）
    ...(结果.形态 ? { 事件: '变身', 形态: 结果.形态, 单位键: 键 } : {}),
  });
}

/** 次要行动 / 反应动作：只扣槽并记步骤。 */
function 结算槽位行动(新状态: 战斗状态, 键: string, 行动: 意图行动, 步骤: 结算步骤[]): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 类型 = 行动.类型;

  if (类型 !== '次要行动' && 类型 !== '反应动作' && 类型 !== '免费行动') {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」不认识的行动类型「${类型}」`, 单位: 名 });
    return;
  }

  // 免费行动不限次数（世界书：免费行动不占次数）→ 不查槽、不扣槽
  if (类型 === '免费行动') {
    步骤.push({ 类: '敌方行动', 内容: `「${名}」执行 免费行动${行动.技能 ? `·${行动.技能}` : ''}`, 单位: 名 });
    return;
  }

  const 剩余 = 类型 === '次要行动' ? 当前.行动槽.次要 : 当前.行动槽.反应;
  if (剩余 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的${类型}槽已用尽`, 单位: 名 });
    return;
  }

  写回(新状态, 键, { 行动槽: 行动槽消耗(当前.行动槽, 类型) });

  步骤.push({ 类: '敌方行动', 内容: `「${名}」执行 ${类型}${行动.技能 ? `·${行动.技能}` : ''}`, 单位: 名 });
}

// ==================== 敌方意图 ====================

/**
 * 跑敌方意图：把 AI 返回的意图落到战斗状态上。
 * 遇到不存在的单位/目标/技能 → 跳过该行动并记日志，绝不抛错中断整回合。
 * 校验通过的行动交给 `结算行动` 做真实结算（移动/技能六步伤害/扣槽）。
 *
 * 这里是**单位 id 与技能名的唯一校验入口**：意图里的引用一律经 `找单位` 归一化，
 * 技能名一律经 `匹配技能名`（剥掉书名号/引号等装饰）比对，两条都必须给出可诊断的日志 ——
 * 「敌人不出招」的每一次都发生在这些比对上，不能只留一句「跳过」。
 *
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数
 */
export function 跑敌方意图(
  状态: 战斗状态,
  意图: 敌方意图[],
  掷骰注入?: 掷骰注入,
): {
  状态: 战斗状态;
  步骤: 结算步骤[];
} {
  const 步骤: 结算步骤[] = [];
  let 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  for (const 单位意图 of 意图) {
    const 单位0解析 = 解析单位(新状态, 单位意图.单位);
    const 单位0 = 单位0解析.单位;
    if (!单位0) {
      步骤.push({
        类: '跳过',
        内容: `跳过：敌方意图里的单位「${
          单位意图.单位 || '(空)'
        }」不在战场上；最近似候选：${候选说明(单位0解析.候选)}`,
      });
      continue;
    }
    const 名 = 显示名(单位0);

    // 单位名被"串了字"但绑回来了 → 必须留痕（否则玩家不知道引擎替他改判了什么）
    if (单位0解析.方式 === '近似') {
      步骤.push({
        类: '敌方行动',
        内容: `意图里的单位 ${绑定说明(单位意图.单位, 名, 单位0解析.相似度)}`,
        单位: 名,
      });
    }

    for (const 行动 of 单位意图.行动) {
      // 每个行动前重新取一次单位：上一个行动可能已经改过它的距离/行动槽
      const 单位 = 找单位(新状态, 单位意图.单位);
      if (!单位) {
        步骤.push({ 类: '跳过', 内容: `跳过：单位「${单位意图.单位}」不在战场上` });
        continue;
      }

      // 已失去战斗力：本轮早些被打死的单位不该再出手，也不该先记一条「执行主要行动」再跳过
      if (单位.HP_当前 <= 0) {
        步骤.push({ 类: '跳过', 内容: `跳过：「${名}」已失去战斗力，本回合不再行动`, 单位: 名 });
        break;
      }

      // 校验目标存在（带候选诊断：目标对不上是「无法识别目标」的现场）
      if (行动.目标) {
        const 目标解析 = 解析单位(新状态, 行动.目标);
        if (!目标解析.单位) {
          步骤.push({
            类: '跳过',
            内容: `跳过：「${名}」的目标「${行动.目标}」不在战场上；最近似候选：${候选说明(
              目标解析.候选,
            )}`,
            单位: 名,
          });
          continue;
        }
        if (目标解析.方式 === '近似') {
          步骤.push({
            类: '敌方行动',
            内容: `目标 ${绑定说明(行动.目标, 显示名(目标解析.单位), 目标解析.相似度)}`,
            单位: 名,
          });
        }
      }

      // 校验技能名（R7）：意图里写了技能，但该单位的技能表里没有 → 跳过该行动
      // （技能表 = 一次性翻译出的「技能名 → 战斗解释」；老存档可能缺省，兜底为空表）
      // 没写技能 = 基础攻击，不算「没有技能」——交给 结算行动 走基础攻击分支。
      const 技能表 = 单位.技能 ?? {};
      if (行动.技能) {
        const 技能解析 = 解析技能名(技能表, 行动.技能);
        if (!技能解析.命中) {
          步骤.push({
            类: '跳过',
            内容: `跳过：「${名}」没有技能「${行动.技能}」；该单位可用技能：${可用技能(技能表)}${
              技能解析.候选.length ? `；最近似：${候选说明(技能解析.候选)}` : ''
            }`,
            单位: 名,
          });
          continue;
        }
        if (技能解析.方式 === '近似') {
          步骤.push({
            类: '敌方行动',
            内容: `技能名 ${绑定说明(行动.技能, 技能解析.命中, 技能解析.相似度)}`,
            单位: 名,
          });
        }
      }

      步骤.push({ 类: '敌方行动', 内容: `「${名}」执行 ${行动.类型}${行动.技能 ? `·${行动.技能}` : '·基础攻击'}`, 单位: 名 });

      const 结果 = 结算行动(新状态, 单位, 行动, 掷骰注入);
      新状态 = 结果.状态;
      步骤.push(...结果.步骤);
    }
  }

  return { 状态: 新状态, 步骤 };
}

// ==================== 一个回合（阶段B · 单位行动） ====================

/**
 * 跑一个回合的**阶段B · 单位行动**：按先攻顺序把**我方行动**与敌方意图**交错**结算。
 * （阶段A 在回合开始、阶段F 在回合结束，都在调用方 —— 见 CombatView.推进回合 / 执行本轮。）
 *
 * 为什么这一段必须是纯函数而不是写在 `.vue` 里：
 * 本仓库没有 vue-tsc，`.vue` 只做语法编译（不解析 import、跑不到运行时），
 * 于是「敌方意图没接上 / 单位 id 对不上 / 技能名对不上」这类坏在 UI 层是**测不到的** ——
 * 而「敌人完全不出招」正是死在这里。抽出来之后，「一个回合里敌人到底出没出招」
 * 就成了一条可回归的断言。
 *
 * **交错**（而不是先跑完所有敌人）是必须的：本轮早些被打死的单位不该在轮末再出手，
 * `结算行动` 的存活守卫要看得到最新 HP。
 *
 * @param 我方行动 本回合我方各单位声明的行动（来自 `构造行动声明`）。两种写法：
 *   - `意图行动[]` —— 契约者一个人的行动（简写）
 *   - `Record<单位引用, 意图行动[]>` —— **每个我方单位各自的行动**（战场上不止你一个人时必须用这个：
 *     队友也要能被指挥，而不是每逢轮空过）
 * @param 意图列表 本回合生成的敌方意图（来自 `生成敌方意图`）
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数
 */
/**
 * 一轮的**游标状态**（把"一次跑完"拆成可暂停/可恢复）。
 *
 * 为什么需要：玩家口径「技能加额外行动次数，当场打断行动，选择额外行动选项」——
 * 追加回合必须**在结算中途停下来**让我方玩家重新指定行动，所以轮次不能再是一个"一跑到底"的函数。
 * 现有调用方（与既有测试）不受影响：`跑一个回合` 仍是"开一轮 + 循环走一步"的封装。
 */
export interface 轮次状态 {
  状态: 战斗状态;
  /** 本轮执行顺序（先攻 id 列表） */
  顺序: string[];
  /** 下一个要走的单位下标 */
  位置: number;
  /** 当前单位已走到第几个行动 */
  指针: number;
  /** 我方各单位的行动声明（归一化到单位 id） */
  行动按id: Map<string, 意图行动[]>;
  /** 敌方意图（归一化到单位 id） */
  意图按id: Map<string, 敌方意图[]>;
  掷骰注入?: 掷骰注入;
  我方已出手: Set<string>;
  /** 每个单位已经用掉几个追加回合（防跑飞） */
  追加已用: Map<string, number>;
  步骤: 结算步骤[];
  /** 非空 = 停在这里等玩家（目前只有「额外行动回合」） */
  待决: 待决点 | null;
  完成: boolean;
}

/** 单个单位每回合的追加回合上限（玩家口径外的安全阀：技能写"无限额外回合"也不会把界面跑死） */
export const 追加回合上限 = 5;

/** 开一轮：归一化行动表/意图，建立先攻序列。**不动任何结算**。 */
export function 开一轮(
  状态: 战斗状态,
  我方行动: 意图行动[] | Record<string, 意图行动[]>,
  意图列表: 敌方意图[],
  掷骰注入?: 掷骰注入,
): 轮次状态 {
  const 步骤: 结算步骤[] = [];
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  // 数组写法 = 契约者一个人的行动（简写）；对象写法 = 各我方单位分别声明
  const 行动表: Record<string, 意图行动[]> = Array.isArray(我方行动) ? { 契约者: 我方行动 } : (我方行动 ?? {});

  // 行动表的键可能是短名 / 全路径 id，统一归一化成单位 id
  const 行动按id = new Map<string, 意图行动[]>();
  for (const [引用, 列表] of Object.entries(行动表)) {
    if (!Array.isArray(列表) || 列表.length === 0) continue;
    const 单位 = 找单位(新状态, 引用);
    if (!单位) {
      步骤.push({ 类: '跳过', 内容: `跳过：行动表里的单位「${引用}」不在战场上` });
      continue;
    }
    行动按id.set(单位.id, [...(行动按id.get(单位.id) ?? []), ...列表]);
  }

  // 意图里的「单位」可能是短名 / 变量路径全名 / 「玩家」，一律 找单位 归一化成 id 再挂。
  // 这里**要用带近似的那一层**：模型把单位名串了字（注音/拼音）时，意图得挂到正确的单位上，
  // 否则该单位会被判成"没有收到任何意图"而空过 —— 那就白兜底了。
  const 意图按id = new Map<string, 敌方意图[]>();
  for (const 单条 of 意图列表) {
    const 单位 = 找单位(新状态, 单条.单位);
    if (!单位) {
      步骤.push({ 类: '跳过', 内容: `跳过：敌方意图里的单位「${单条.单位 || '(空)'}」不在战场上` });
      continue;
    }
    意图按id.set(单位.id, [...(意图按id.get(单位.id) ?? []), 单条]);
  }

  return {
    状态: 新状态,
    顺序: [...状态.先攻],
    位置: 0,
    指针: 0,
    行动按id,
    意图按id,
    掷骰注入,
    我方已出手: new Set<string>(),
    追加已用: new Map<string, number>(),
    步骤,
    待决: null,
    完成: 状态.先攻.length === 0,
  };
}

/**
 * 段末 / 空段的「额外行动回合」检查：欠账就停下等玩家（设 `待决`）。
 * 返回 true = 已停下（调用方别再推进游标）。
 *
 * 三条守卫：
 * - **倒地/濒死的单位不给追加**（玩家不该被提示给一具尸体指定行动）；
 * - **空段也查**：常驻"每回合额外一个行动回合"但本回合没被下命令的单位，追加不该静默蒸发；
 * - 上限溢出时记日志并清账（`找键` 判空 —— 单位中途离场不能写出一个 `"undefined"` 键）。
 */
function 追加待决检查(轮: 轮次状态, 单位: 战斗单位): boolean {
  const 最新 = Object.values(轮.状态.单位).find(x => x.id === 单位.id);
  if (!最新) return false;
  if (最新.HP_当前 <= 0) return false;
  const 欠 = Math.floor(最新.追加行动 ?? 0);
  if (欠 <= 0) return false;

  const 已用 = 轮.追加已用.get(单位.id) ?? 0;
  if (已用 < 追加回合上限) {
    轮.待决 = { 类: '额外行动回合', id: 单位.id };
    return true;
  }

  轮.步骤.push({
    类: '跳过',
    内容: `「${显示名(最新)}」本回合的额外行动回合已达上限（${追加回合上限} 次），多余的忽略`,
    单位: 显示名(最新),
  });
  const 键 = 找键(轮.状态, 最新);
  if (键) 轮.状态.单位[键] = { ...最新, 追加行动: 0 };
  return false;
}

/** 轮次里某个单位**当前这一段**的行动列表（我方 = 玩家声明；敌方 = 意图里的一整段） */
function 本段行动(轮: 轮次状态, id: string, 单位: 战斗单位): 意图行动[] {
  return 单位.阵营 === '我方' ? (轮.行动按id.get(id) ?? []) : [];
}

/**
 * 走一步：结算**下一个单位的下一段行动**；遇到「额外行动回合」就停下，把待决点交出去。
 * 纯函数（返回新的轮次状态），所以暂停/恢复都能被单测钉住。
 */
export function 走一步(轮: 轮次状态): 轮次状态 {
  if (轮.完成 || 轮.待决) return 轮;

  const 新: 轮次状态 = {
    ...轮,
    状态: { ...轮.状态, 单位: { ...轮.状态.单位 } },
    行动按id: new Map(轮.行动按id),
    追加已用: new Map(轮.追加已用),
    我方已出手: new Set(轮.我方已出手),
    步骤: [...轮.步骤],
  };

  while (新.位置 < 新.顺序.length) {
    const id = 新.顺序[新.位置];
    // 先攻里的 id 是**我们自己**写进去的（初始化战斗状态），必须精确命中 ——
    // 用带近似的那层会让一个坏 id 悄悄指到别的单位身上
    const 单位 = 找单位精确(新.状态, id);

    if (!单位) {
      新.步骤.push({ 类: '跳过', 内容: `跳过：先攻顺序里的「${id}」不在战场上` });
      新.位置++;
      新.指针 = 0;
      continue;
    }

    // ===== 敌方：一整段意图算一步（跑敌方意图内部会逐个行动结算）=====
    // **额外行动回合只属于我方**（玩家口径：「追加回合敌人不出招」）→ 敌人不参与追加。
    if (单位.阵营 !== '我方') {
      const 本意图 = 新.意图按id.get(单位.id);
      if (!本意图 || 本意图.length === 0) {
        // 模型漏了这个单位（或整次意图调用失败）：必须明说，否则「敌人不出招」无从诊断
        新.步骤.push({
          类: '跳过',
          内容: `「${显示名(单位)}」本回合没有收到任何意图 → 空过（敌方意图由每回合 1 次 AI 调用生成：模型漏了这个单位，或那次调用整体失败）`,
          单位: 显示名(单位),
        });
      } else {
        const 结果 = 跑敌方意图(新.状态, 本意图, 新.掷骰注入);
        新.状态 = 结果.状态;
        新.步骤.push(...结果.步骤);
      }
      新.位置++;
      新.指针 = 0;
      continue;
    }

    // ===== 我方：一个行动 = 一步 =====
    const 本行动 = 本段行动(新, id, 单位);
    if (本行动.length === 0) {
      // 没给他下命令 = 本回合不出手，不用报错 —— 但**欠着的额外行动回合不能静默蒸发**
      if (追加待决检查(新, 单位)) return 新;
      新.位置++;
      新.指针 = 0;
      continue;
    }

    if (新.指针 < 本行动.length) {
      新.我方已出手.add(单位.id);
      // 每个行动前按 id 重取行动者：上一个行动可能已改了它的 HP（如一命换一命的自我代价），
      // 结算行动的存活守卫要看到最新值，不能拿本轮开头的旧引用
      const 行动者 = Object.values(新.状态.单位).find(x => x.id === 单位.id);
      if (!行动者) {
        新.位置++;
        新.指针 = 0;
        continue;
      }
      const 行动 = 本行动[新.指针];
      const 结果 = 结算行动(新.状态, 行动者, 行动, 新.掷骰注入);
      新.状态 = 结果.状态;
      新.步骤.push(...结果.步骤);
      新.指针++;
      // 这一步之后就能安全暂停了。但如果**正好是这一段的最后一条**，就顺手把段末判定
      // （追加回合 / 推进到下一个单位）也做完 —— 否则调用方要多走一次空步才看得到待决点。
      if (新.指针 < 本行动.length) return 新;
      continue;
    }

    // 这一段的行动走完了 → 看看是不是欠着一个**额外行动回合**
    if (追加待决检查(新, 单位)) return 新; // 停在原地：位置/指针不动，等玩家提交追加回合的行动

    新.位置++;
    新.指针 = 0;
  }

  新.完成 = true;
  return 新;
}

/**
 * 提交**追加行动回合**：消耗一层「追加行动」，把槽位换成**一整套新的**（主/次/移/反各 +1，
 * 免费不限次），并再给一份移动额度（否则多出来的移动槽是废的）。
 *
 * 玩家口径：「多一个回合的本质是多一倍的行动槽嘛（意思是多一个主要、一个次要、移动、反应、免费等等）」
 */
export function 提交追加行动(轮: 轮次状态, 行动: 意图行动[]): 轮次状态 {
  const 待决 = 轮.待决;
  if (!待决 || 待决.类 !== '额外行动回合') return 轮;

  const 新: 轮次状态 = {
    ...轮,
    状态: { ...轮.状态, 单位: { ...轮.状态.单位 } },
    行动按id: new Map(轮.行动按id),
    追加已用: new Map(轮.追加已用),
    步骤: [...轮.步骤],
    待决: null,
  };

  // 待决点里存的是**单位 id**（先攻序列用的就是 id），这里要换成 `状态.单位` 的键
  const 单位0 = 找单位精确(新.状态, 待决.id);
  const 键 = 单位0 ? 找键(新.状态, 单位0) : undefined;
  const 单位 = 键 ? 新.状态.单位[键] : undefined;
  if (!键 || !单位) {
    新.步骤.push({ 类: '跳过', 内容: `跳过：追加行动的单位「${待决.id}」不在战场上` });
    return 新;
  }

  const 欠 = Math.max(0, Math.floor(单位.追加行动 ?? 0) - 1);
  const 新槽 = 回合开始行动槽(单位);
  const 额度 = 单位.额度 + 回合开始额度(单位);

  // 追加回合是一个**真正的回合**（玩家裁决：「追加回合能递减冷却，而额外行动不能」——
  // 额外行动次数只是同一回合里多一个槽，同一回合本来就没有递减这回事），
  // 所以冷却照 `冷却递减` 走一遍：主回合里刚用的技能（冷却 1）在追加回合里就冷却好了。
  // 只递减**该单位**（追加回合只属它一个；阶段A 的资源恢复 / 阶段F 的持续伤害仍然不动）。
  const 单位新冷却 = 冷却递减(单位).冷却;
  const 冷却说明 = Object.keys(单位.冷却 ?? {}).length
    ? `，冷却 -1（${Object.entries(单位.冷却 ?? {})
        .map(([名, 剩]) => `${名} ${剩}→${单位新冷却[名] ?? 0}`)
        .join('、')}）`
    : '';

  新.状态.单位[键] = {
    ...单位,
    追加行动: 欠,
    行动槽: 新槽,
    额度,
    冷却: 单位新冷却,
  };
  新.追加已用.set(单位.id, (新.追加已用.get(单位.id) ?? 0) + 1);
  新.行动按id.set(单位.id, Array.isArray(行动) ? [...行动] : []);
  新.指针 = 0; // 位置不动：追加回合在**该单位原回合之后立刻**执行

  新.步骤.push({
    类: '规则系',
    内容: `「${显示名(单位)}」获得额外行动回合：槽位重置为 主${新槽.主要}/次${新槽.次要}/移${新槽.移动}/反${新槽.反应}，移动额度 +${回合开始额度(单位)}（余 ${额度} 米）${冷却说明}`,
    单位: 显示名(单位),
  });

  return 新;
}

/**
 * 跑一个回合：`开一轮` + 循环 `走一步` 直到走完。
 *
 * 兼容层 —— 现有调用方与既有测试的行为**完全不变**。唯一的例外：轮到「额外行动回合」时
 * 这里没有玩家可问，于是**记一条日志并放弃那次追加**（战斗界面用 `开一轮`/`走一步` 自己处理）。
 */
export function 跑一个回合(
  状态: 战斗状态,
  我方行动: 意图行动[] | Record<string, 意图行动[]>,
  意图列表: 敌方意图[],
  掷骰注入?: 掷骰注入,
): { 状态: 战斗状态; 步骤: 结算步骤[] } {
  let 轮 = 开一轮(状态, 我方行动, 意图列表, 掷骰注入);

  // 防死循环：一轮里的步数上限 = 顺序长度 ×（最长的行动段 + 追加上限）宽松值
  const 上限 = (轮.顺序.length + 1) * (32 + 追加回合上限 * 8);
  for (let i = 0; i < 上限 && !轮.完成; i++) {
    if (轮.待决) {
      const 待决 = 轮.待决;
      const 单位 = Object.values(轮.状态.单位).find(u => u.id === (待决 as any).id);
      轮.步骤.push({
        类: '跳过',
        内容: `「${单位 ? 显示名(单位) : (待决 as any).id}」获得额外行动回合，但当前调用方无人可问 → 放弃这次追加（战斗界面会停下来让玩家指定）`,
        单位: 单位 ? 显示名(单位) : undefined,
      });
      // 放弃：清掉计数与待决，继续走完剩下的先攻
      const 键 = 单位 ? 找键(轮.状态, 单位)! : undefined;
      if (键) 轮.状态.单位[键] = { ...轮.状态.单位[键], 追加行动: 0 };
      轮 = { ...轮, 待决: null, 位置: 轮.位置 + 1, 指针: 0 };
      continue;
    }
    轮 = 走一步(轮);
  }

  // 下了命令却没轮到出手（不在先攻里 / 已被先行击倒）→ 必须说出来，不能像没点过一样
  for (const [id, 列表] of 轮.行动按id) {
    if (轮.我方已出手.has(id) || 列表.length === 0) continue;
    const 单位 = Object.values(轮.状态.单位).find(u => u.id === id);
    轮.步骤.push({
      类: '跳过',
      内容: `跳过：「${单位 ? 显示名(单位) : id}」本回合的行动未执行（不在先攻顺序里，或被先行击倒）`,
    });
  }

  return { 状态: 轮.状态, 步骤: 轮.步骤 };
}
