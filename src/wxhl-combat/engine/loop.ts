/**
 * 解析一个"单位引用"。
 * 引用既可能是 `状态.单位` 的键（短名，如 `骨卫兵`），也可能是 `战斗单位.id`（变量路径，如 `副本角色.骨卫兵`）；
 * 敌方意图提示词里还会用固定称呼 `玩家` 指代契约者本体。
 * **一律精确匹配** —— 绝不用模糊后缀匹配：那会让「卫兵」误配到「骨卫兵」，且 Object.values 的顺序决定谁中招。
 */
function 找单位(状态: 战斗状态, 引用: string): 战斗单位 | undefined {
  if (状态.单位[引用]) return 状态.单位[引用];
  const 按id = Object.values(状态.单位).find(u => u.id === 引用);
  if (按id) return 按id;
  // 「玩家」是 敌方意图提示词 对契约者本体的固定称呼（见 ai/enemyTactics.ts 的输出格式）
  if (引用 === '玩家') return Object.values(状态.单位).find(u => u.类型 === '玩家');
  return undefined;
}

/** 把单位反查回 `状态.单位` 的键（先按对象身份，再按 id）。 */
function 找键(状态: 战斗状态, 单位: 战斗单位): string | undefined {
  for (const 键 of Object.keys(状态.单位)) {
    const u = 状态.单位[键];
    if (u === 单位 || u.id === 单位.id) return 键;
  }
  return undefined;
}

/** 写回单位：**换新对象**（绝不原地改，保证纯函数语义）。 */
function 写回(状态: 战斗状态, 键: string, 补丁: Partial<战斗单位>): void {
  状态.单位[键] = { ...状态.单位[键], ...补丁 };
}

/** 显示名：变量路径的最后一段（`副本角色.骨卫兵` → `骨卫兵`）。 */
function 显示名(单位: 战斗单位): string {
  return 单位.id.split('.').pop() || 单位.id;
}

/** 数值显示：整数原样，小数最多两位。 */
function 显示数值(值: number): number {
  return Math.round(值 * 100) / 100;
}

