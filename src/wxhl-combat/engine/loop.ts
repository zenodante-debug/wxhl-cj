/** 位阶序数：一阶=1 … 五阶=5，超脱=6（用于 `(阶位−1)/2` 与「×敌人位阶」的 DC/伤害公式） */
const 位阶序数表: Record<string, number> = { 一阶: 1, 二阶: 2, 三阶: 3, 四阶: 4, 五阶: 5, 超脱: 6 };
function 位阶序数(阶位: string): number {
  return 位阶序数表[阶位] ?? 1;
}

/** 武器的阶位序数；武器没写阶位 / 阶位非法 → 退回兜底（通常是行动者阶位）。 */
function 武器位阶序数(武器: { 阶位?: string } | undefined, 兜底: number): number {
  const 序数 = 武器?.阶位 ? 位阶序数表[武器.阶位] : undefined;
  return 序数 ?? 兜底;
}

interface 射程结论 {
  通过: boolean;
  说明?: string;
}

/**
 * 把 `战斗解释.射程` 的文本粗映射到 distance.武器类型再校验。
 * 映射不确定 / 明显不涉及距离（自身、视线内）→ 按「不校验」通过并附一条说明。
 */
function 射程检查(射程文本: string, 距离: number): 射程结论 {
  const 文 = (射程文本 ?? '').trim();
  if (!文) return { 通过: true, 说明: '技能未写明射程，按不校验处理' };
  if (文.includes('自身')) return { 通过: true, 说明: '射程为「自身」，不校验距离' };
  if (文.includes('视线') || 文.includes('无限')) return { 通过: true, 说明: `射程为「${文}」，不校验距离` };

  // 顺序讲究：先狙击（否则「狙击枪」会被「步枪」的 includes('枪') 抢走）
  const 类型 = 文.includes('狙击')
    ? '狙击枪'
    : 文.includes('弓弩') || 文.includes('弩')
      ? '弓弩'
      : 文.includes('步枪')
        ? '步枪'
        : 文.includes('投掷')
          ? '投掷'
          : 文.includes('手枪') || 文.includes('短兵器')
            ? '手枪'
            : 文.includes('近战')
              ? '近战'
              : undefined;

  if (类型) {
    return 射程校验(类型, 距离)
      ? { 通过: true }
      : { 通过: false, 说明: `技能射程「${文}」（按${类型}）覆盖不到 ${距离} 米（${距离带(距离)}）` };
  }

  // 「X米」上限写法
  const 米 = /(\d+(?:\.\d+)?)\s*米/.exec(文);
  if (米) {
    const 上限 = Number(米[1]);
    return 距离 <= 上限
      ? { 通过: true }
      : { 通过: false, 说明: `技能射程「${文}」上限 ${上限} 米，目标在 ${距离} 米` };
  }

  return { 通过: true, 说明: `技能射程「${文}」映射不到武器类型，按不校验处理` };
}

/**
 * 关联属性 → 属性键（spec B.3：近战物理=STR / 远程物理=AGI / 魔法=PER）。
 * 卡里 `关联属性` 是自由字符串（zod `z.string()`），中英文写法都认。
 */
function 关联属性键(值: unknown): 'STR' | 'AGI' | 'CON' | 'PER' {
  const 文 = String(值 ?? '').toUpperCase();
  if (文.includes('AGI') || 文.includes('敏捷')) return 'AGI';
  if (文.includes('CON') || 文.includes('体质')) return 'CON';
  if (文.includes('PER') || 文.includes('感知')) return 'PER';
  return 'STR'; // 力量 / 空 / 认不出来 → 近战物理
}

/** 六步伤害与命中要用的技能参数（由 `战斗解释` 读出）。 */
interface 技能参数 {
  属性键: 'STR' | 'AGI' | 'CON' | 'PER';
  技能阶位: number;
  伤害倍率: number;
  部位: 攻击部位 | undefined;
}

/**
 * 从 `战斗解释` 读六步伤害与命中要用的参数（字段由翻译器从技能实体读出）。
 *
 * 缺字段的口径（经裁决）：
 * - `技能阶位` 缺省按 1（brief 允许）。
 * - `伤害倍率` 缺字段/非法按 **0**（= 技能不贡献伤害）。**不按同阶区间中值兜底** ——
 *   中值兜底会让「改前翻译过的存档」里每个技能（含盾、治疗）凭空打出伤害，宁可让问题可见。
 * - 显式 `0` 同样是 0。
 */
function 技能参数(解释: 战斗解释): 技能参数 {
  const 阶位原值 = Number(解释.技能阶位);
  const 技能阶位 = Number.isFinite(阶位原值) && 阶位原值 >= 1 ? Math.floor(阶位原值) : 1;

  const 倍率原值 = 解释.伤害倍率;
  const 伤害倍率 =
    typeof 倍率原值 === 'number' && Number.isFinite(倍率原值) && 倍率原值 >= 0 ? 倍率原值 : 0;

  return {
    属性键: 关联属性键(解释.关联属性),
    技能阶位,
    伤害倍率,
    部位: 解释.部位,
  };
}

/**
 * 汇总一个单位身上（= 它所有技能解释里 `触发: '常驻'` 且 `作用域: '自身'` 的数值修正）
 * **再加上它身上状态携带的数值修正**。
 * 用途：`命中`（B.3 被动加成）/ `伤害`（第四步 总增伤）/ `减伤`（第六步 减伤比例）。
 *
 * 状态那一条是"上 buff"能生效的关键：支援行动/命中时规则里的 `数值修正` 会落成一条状态
 * （见 `落效果`），在这里被读回来，于是「给友军 +30% 伤害」真的改变了伤害数字。
 * 规则求值失败（表达式未知标识符等）→ 记一条「忽略」步骤，绝不抛错。
 */
function 常驻修正(单位: 战斗单位, 对手: 战斗单位, 键: string, 步骤: 结算步骤[]): number {
  let 和 = 0;
  for (const 解释 of Object.values(单位.技能 ?? {})) {
    for (const 规则 of 解释.规则 ?? []) {
      if (规则.触发 !== '常驻' || 规则.作用域 !== '自身') continue;
      try {
        和 += 执行规则(规则, 单位, 对手).数值修正?.[键] ?? 0;
      } catch (e: any) {
        步骤.push({ 类: '跳过', 内容: `忽略：「${显示名(单位)}」的常驻规则求值失败：${e?.message ?? e}`, 单位: 显示名(单位) });
      }
    }
  }
  for (const 状态 of 单位.状态) 和 += 状态.数值修正?.[键] ?? 0;
  return 和;
}

/** 把 `规则.作用域` 解成受影响的单位键列表（行动者 = 攻方，被攻击者 = 守方）。 */
function 作用域单位(新状态: 战斗状态, 作用域: 作用域, 攻方键: string, 守方键: string): string[] {
  const 攻方 = 新状态.单位[攻方键];
  switch (作用域) {
    case '自身':
    case '攻击者':
      return [攻方键];
    case '攻击目标':
    case '命中点':
      return [守方键];
    case '我方全体':
      return Object.keys(新状态.单位).filter(k => 新状态.单位[k].阵营 === 攻方.阵营);
    case '敌方全体':
      return Object.keys(新状态.单位).filter(k => 新状态.单位[k].阵营 !== 攻方.阵营);
    default:
      return [守方键]; // 未知作用域：保守落到被攻击者
  }
}

// ==================== 结算行动 ====================

export interface 结算结果 {
  状态: 战斗状态;
  步骤: 结算步骤[];
  待决: 待决点[];
}

/**
 * 结算单个行动。坏输入（技能不存在/超程/槽位不足）→ 记「跳过」步骤，绝不抛错。
 *
 * 第五步（防御方反应动作）不在此处：引擎只把结果算出来，`待决` 恒为空数组，
 * 由交互层（13d）决定是否弹打断/防御。**纯函数**：不改动入参，返回新的 `战斗状态`。
 *
 * 开头有存活守卫：HP 归零（已失去战斗力）的行动者一律跳过 —— 先攻循环里本轮早些
 * 被打死的单位不该在本轮晚些再出手。玩家与敌方两条路共用这一处。
 *
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数，避免 flaky；缺省时现场掷骰。
 */
export function 结算行动(
  状态: 战斗状态,
  行动者: 战斗单位,
  行动: 意图行动,
  掷骰注入?: { 命中?: number; 伤害骰?: number[] },
): 结算结果 {
  const 步骤: 结算步骤[] = [];
  const 待决: 待决点[] = [];

  // 存活守卫：HP ≤ 0 = 已失去战斗力（濒死 CON 检定见 13f）
  if (行动者.HP_当前 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${显示名(行动者)}」已失去战斗力`, 单位: 显示名(行动者) });
    return { 状态, 步骤, 待决 };
  }

  const 键 = 找键(状态, 行动者);
  if (键 === undefined) {
    步骤.push({ 类: '跳过', 内容: `跳过：单位「${行动者.id}」不在战场上` });
    return { 状态, 步骤, 待决 };
  }

  // 我们的副本：单位对象一律「换新对象」写回，入参 状态 完全不动
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  try {
    if (行动.类型 === '移动') 结算移动(新状态, 键, 行动, 步骤);
    // 主要行动：没写技能 = 基础攻击（R20）。
    // 次要行动：**写了技能**才进结算（且只能做支援，见 结算技能 的拒绝逻辑）；
    //          没写技能的次要行动（「瞄准」「预备」）仍是纯扣槽，别把它变成一次失败的攻击。
    else if (行动.类型 === '主要行动' || (行动.类型 === '次要行动' && 行动.技能)) {
      结算技能(新状态, 键, 行动, 掷骰注入, 步骤);
    } else 结算槽位行动(新状态, 键, 行动, 步骤);
  } catch (e: any) {
    // 兜底：任何意外（未知阶位、骰式非法…）都降级为「跳过」，不打断整回合
    步骤.push({ 类: '跳过', 内容: `跳过：「${行动者.id}」的 ${行动.类型} 结算失败：${e?.message ?? e}` });
  }

  return { 状态: 新状态, 步骤, 待决 };
}

/** 移动：算消耗 → 扣额度 → 改距离 → 扣移动槽；跨带脱离近战 → 记借机攻击提示（真正的借机是反应动作，交 13d）。 */
function 结算移动(新状态: 战斗状态, 键: string, 行动: 意图行动, 步骤: 结算步骤[]): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 目标距离 = typeof 行动.距离 === 'number' && Number.isFinite(行动.距离) ? 行动.距离 : 当前.距离;
  const 消耗 = Math.abs(目标距离 - 当前.距离);

  if (当前.行动槽.移动 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的移动行动槽已用尽`, 单位: 名 });
    return;
  }
  if (消耗 > 当前.额度) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」移动额度不足（需 ${消耗} 米，余 ${当前.额度} 米）`, 单位: 名 });
    return;
  }

  const 原距离 = 当前.距离;
  const 新额度 = 移动额度消耗(当前.额度, 消耗); // 已判过 消耗 ≤ 额度，不会抛
  const 新槽 = 行动槽消耗(当前.行动槽, '移动');

  写回(新状态, 键, { 距离: 目标距离, 额度: 新额度, 行动槽: 新槽 });

  步骤.push({
    类: '移动',
    内容: `「${名}」移动 ${消耗} 米：${原距离} → ${目标距离} 米（${距离带(目标距离)}），剩余额度 ${新额度} 米`,
    单位: 名,
  });

  if (借机攻击判定(原距离, 目标距离, {})) {
    步骤.push({ 类: '移动', 内容: `「${名}」脱离近战带，触发借机攻击（对方的反应动作，交待决处理）`, 单位: 名 });
  }
}

/** 主要行动 + 技能：射程 → 命中 → 六步伤害 → 写回守方 → 命中时规则落守方。 */
function 结算技能(
  新状态: 战斗状态,
  键: string,
  行动: 意图行动,
  掷骰注入: { 命中?: number; 伤害骰?: number[] } | undefined,
  步骤: 结算步骤[],
): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 技能名 = typeof 行动.技能 === 'string' ? 行动.技能.trim() : '';

  // 没写技能 = 基础攻击（世界书速查表：徒手 1d4 / 武器用武器）。
  // 这条分支是给「模型不知道该用什么技能」留的合法出路：以前这里直接跳过，
  // 于是模型一旦没写技能名，敌人就整轮空过 —— 一次也不出招。
  const 表 = 当前.技能 ?? {};
  const 技能解析 = 技能名 ? 解析技能名(表, 技能名) : undefined;
  const 原名 = 技能解析?.命中;
  const 是基础攻击 = 技能名 === '';
  const 解释: 战斗解释 | undefined = 原名
    ? 表[原名]
    : 是基础攻击
      ? 基础攻击解释(!!当前.主武器)
      : undefined;

  if (!解释) {
    // 技能名的合法来源只有单位技能表。名字对不上必须**说清可用技能与最近似候选** ——
    // 只说「没有技能」的话，玩家在面板上只看到「敌人不出招」，无从判断是不是 AI 在瞎编。
    步骤.push({
      类: '跳过',
      内容: `跳过：「${名}」没有技能「${技能名}」；该单位可用技能：${可用技能(表)}${
        技能解析?.候选.length ? `；最近似：${候选说明(技能解析.候选)}` : ''
      }`,
      单位: 名,
    });
    return;
  }

  // 技能名是被"串了字"但绑回来了（如「骨爪撕列」→「骨爪撕裂」）→ 必须留痕
  if (技能解析?.方式 === '近似') {
    步骤.push({
      类: '命中',
      内容: `技能名 ${绑定说明(技能名, 原名!, 技能解析.相似度)}`,
      单位: 名,
    });
  }

  if (是基础攻击) {
    步骤.push({
      类: '命中',
      内容: `「${名}」未指定技能 → 按基础攻击结算（${当前.主武器 ? '主武器' : '徒手 1d4，近战'}）`,
      单位: 名,
    });
  }

  /** 日志里显示的动作名（基础攻击时技能名是空串，不能直接打印） */
  const 动作名 = 原名 ?? (是基础攻击 ? '基础攻击' : 技能名);

  const 目标解析 = 行动.目标 ? 解析单位(新状态, 行动.目标) : undefined;
  const 目标 = 目标解析?.单位;
  if (!目标) {
    步骤.push({
      类: '跳过',
      内容: `跳过：「${名}」的目标「${行动.目标 ?? ''}」不在战场上；最近似候选：${候选说明(
        目标解析?.候选 ?? [],
      )}`,
      单位: 名,
    });
    return;
  }
  if (目标解析?.方式 === '近似') {
    步骤.push({
      类: '命中',
      内容: `目标 ${绑定说明(行动.目标 ?? '', 显示名(目标), 目标解析.相似度)}`,
      单位: 名,
    });
  }

  // 次要行动也能带技能（「给友军上 buff」常常是次要行动）。
  // 但**次要行动只能做支援** —— 见下面同阵营分支里的拒绝逻辑：放开次要行动攻击
  // 等于每个单位每回合多打一次，不符合世界书（攻击是主要行动）。
  const 槽型: '主要行动' | '次要行动' = 行动.类型 === '次要行动' ? '次要行动' : '主要行动';
  const 剩余槽 = 槽型 === '次要行动' ? 当前.行动槽.次要 : 当前.行动槽.主要;
  if (剩余槽 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的${槽型}槽已用尽`, 单位: 名 });
    return;
  }

  // 射程硬门禁：超程 = 无法发动，不消耗行动。
  // 全场以玩家为唯一坐标原点（spec §8「单一坐标原点」）：`战斗单位.距离` = 该单位**距玩家多少米**。
  // 所以攻守间距 = |攻方.距离 − 守方.距离| —— 绝不能拿攻方距玩家的距离（玩家恒为 0，
  // 用 当前.距离 会让玩家任何近战技能都隔着整张地图命中）。
  const 攻守距离 = Math.abs(当前.距离 - 目标.距离);
  const 射程 =
    是基础攻击 && 当前.主武器
      ? { 通过: true, 说明: '基础攻击：卡里未记录主武器类型（近战/枪械？），不做距离门禁' }
      : 射程检查(解释.射程, 攻守距离);
  if (!射程.通过) {
    步骤.push({ 类: '跳过', 内容: `跳过：${射程.说明}`, 单位: 名 });
    return;
  }
  if (射程.说明) {
    步骤.push({ 类: '命中', 内容: `说明：「${名}」的「${动作名}」${射程.说明}`, 单位: 名 });
  }

  // 通过全部门禁 → 消耗行动槽
  const 扣槽前 = 当前;
  写回(新状态, 键, { 行动槽: 行动槽消耗(当前.行动槽, 槽型) });

  try {
    const 攻方 = 新状态.单位[键];

    // 重新取守方：写回行动槽时若「打自己」会换掉同一个键的对象，用旧引用会丢改动
    const 守方键 = 找键(新状态, 目标);
    const 守方 = 守方键 === undefined ? undefined : 新状态.单位[守方键];
    if (守方键 === undefined || !守方) return;

    const 目标名 = 显示名(守方);

    // ===== 支援行动（R21）：同阵营目标不走攻击管线 =====
    // 见 `结算支援` 的注释：否则帮队友上 buff 会变成"掷命中对抗队友闪避值 + 打出武器伤害"。
    if (守方.阵营 === 攻方.阵营) {
      结算支援(新状态, 解释, 动作名, 键, 守方键, 步骤);
      return;
    }

    // 次要行动 + 敌方目标 → 拒绝。放开它等于每回合多打一次（世界书：攻击是主要行动）
    if (槽型 === '次要行动') {
      步骤.push({
        类: '跳过',
        内容: `跳过：「${名}」的次要行动不能用于攻击「${目标名}」—— 攻击类技能要走主要行动（次要行动只能做支援/自 buff）`,
        单位: 名,
      });
      // 槽已扣，回滚：这个行动没有成立（与上面 try/catch 的回滚语义一致）
      新状态.单位[键] = 扣槽前;
      return;
    }

    const 参数 = 技能参数(解释);
    const 属性修正 = 属性修正值(攻方.属性.实际[参数.属性键], 攻方.阶位);
    const AGI修正 = 属性修正值(攻方.属性.实际.AGI, 攻方.阶位);
    const 被动 = 常驻修正(攻方, 守方, '命中', 步骤);
    const 骰值 = 掷骰注入?.命中 ?? rollDie(20);

    // 第二步的「DC+…×敌人位阶」加在守方 DC 上
    const 命中DC = 守方.闪避值 + 部位DC加值(参数.部位, 位阶序数(守方.阶位));

    const 命中 = 技能命中判定({
      骰值,
      属性修正,
      技能阶位: 参数.技能阶位,
      被动加成: 被动,
      AGI修正,
      目标闪避值: 命中DC,
    });

    if (!命中) {
      const 有效修正 = 属性修正 * (1 + 参数.技能阶位 / 5);
      步骤.push({
        类: '命中',
        内容: `「${名}」的「${动作名}」未命中「${目标名}」（${骰值} + ${显示数值(有效修正)} + 被动 ${被动} + AGI×0.2 ${显示数值(AGI修正 * 0.2)} = ${显示数值(骰值 + 有效修正 + 被动 + AGI修正 * 0.2)} < ${命中DC}）`,
        单位: 名,
      });
      return;
    }

    // ===== 第一 / 三 / 四 / 六步 =====
    const 攻击阶位 = 位阶序数(攻方.阶位);
    const 手持武器 = 攻方.主武器;
    const 骰值总和 = 掷骰注入?.伤害骰?.length
      ? 掷骰注入.伤害骰.reduce((a, b) => a + b, 0)
      // 无武器 = 徒手（世界书速查表：徒手 1d4 / 倍率 0.5 / 强化 0）
      : 掷伤害骰(手持武器?.伤害骰 ?? '1d4');

    const 武器 = 武器伤害(骰值总和, 手持武器?.强化等级 ?? 0, 武器位阶序数(手持武器, 攻击阶位), 属性修正, 手持武器?.倍率 ?? 0.5);
    // 世界书 <技能模版和限制>：技能伤害 = 关联属性修正值 × 伤害倍率（再按技能阶位成长）
    const 技能 = 技能伤害(属性修正 * 参数.伤害倍率, 参数.技能阶位);
    const 基础伤害 = 武器 + 技能;
    const 混 = 混合伤害(基础伤害, 守方.防御); // 实际防御直接取守方已算好的 `防御` 字段（裁决 R15）

    const 部位倍 = 部位倍率(参数.部位); // 第二步
    const 暴击 = 骰值 >= 暴击范围(攻方.属性.实际.AGI); // 第三步：自然骰面进暴击范围
    const 暴击倍 = 暴击倍率(暴击);
    // 第四步：总增伤 = Σ(倍率−1) —— 取行动者身上「常驻·作用域自身」的 `数值修正[伤害]`
    const 总增伤 = 常驻修正(攻方, 守方, '伤害', 步骤);
    const 乘区 = 效果乘区(总增伤);

    const 乘区后 = 混 * 部位倍 * 暴击倍 * 乘区;
    const 护盾消耗 = Math.min(守方.护盾, 乘区后); // 护盾优先扣除，吃多少扣多少
    // 第六步：减伤比例取守方身上「常驻·作用域自身」的 `数值修正[减伤]`。
    // 世界书原文「减伤/反伤最高 50%」→ 这里封顶 0.5（只封顶不封底：负值留作易伤）。
    const 减伤比例 = Math.min(常驻修正(守方, 攻方, '减伤', 步骤), 0.5);
    const 伤害 = 最终伤害({
      混合伤害: 混,
      部位倍率: 部位倍,
      暴击倍率: 暴击倍,
      效果乘区: 乘区,
      护盾: 护盾消耗,
      减伤比例,
    });

    步骤.push({
      类: '命中',
      内容: `「${名}」的「${动作名}」命中「${目标名}」（${骰值} + ${显示数值(属性修正 * (1 + 参数.技能阶位 / 5))} + 被动 ${被动} + AGI×0.2 ${显示数值(AGI修正 * 0.2)} ≥ ${命中DC}）${暴击 ? '，自然暴击' : ''}`,
      单位: 名,
    });

    const HP变化前 = 守方.HP_当前;
    const 新守方: 战斗单位 = {
      ...守方,
      HP_当前: Math.max(守方.HP_当前 - 伤害, 0),
      护盾: 守方.护盾 - 护盾消耗,
    };
    新状态.单位[守方键] = 新守方;

    步骤.push({
      类: '伤害',
      内容: `「${目标名}」受到 ${显示数值(伤害)} 伤害（六步：混合 ${混} × 部位 ${部位倍} × 暴击 ${暴击倍} × 乘区 ${显示数值(乘区)} − 护盾 ${显示数值(护盾消耗)} − 减伤 ${显示数值(乘区后 * 减伤比例)}），HP ${HP变化前} → ${新守方.HP_当前}`,
      单位: 目标名,
    });

    应用规则(解释, 动作名, ['命中时'], 键, 守方键, { 最终伤害: 伤害, 目标HP: 新守方.HP_当前 }, 新状态, 步骤);
  } catch (e) {
    // 回滚刚扣的行动槽：这一行动没结算成（未知阶位 / 非法骰式 …），不该白吃槽位
    新状态.单位[键] = 扣槽前;
    throw e;
  }
}

/**
 * 支援行动（裁决 R21）：**目标与行动者同阵营**时走这里，不走攻击管线。
 *
 * 为什么必须分支：敌人给友军上 buff 时「目标」是队友 —— 走攻击管线会去掷命中
 * **对抗队友的闪避值**（还可能"未命中"），接着打出**武器伤害**（把队友当敌人打）。
 * 支援行动：不掷命中、不造成伤害、不扣护盾，只把技能规则的效果落到目标身上。
 * 射程门禁照样走（技能写近战就不能隔 800 米给队友加 buff），行动槽照样扣。
 */
function 结算支援(
  新状态: 战斗状态,
  解释: 战斗解释,
  动作名: string,
  施方键: string,
  受方键: string,
  步骤: 结算步骤[],
): void {
  const 施方 = 新状态.单位[施方键];
  const 受方 = 新状态.单位[受方键];

  步骤.push({
    类: '命中',
    内容: `「${显示名(施方)}」对队友「${显示名(受方)}」使用「${动作名}」（支援行动：不掷命中、不造成伤害）`,
    单位: 显示名(施方),
  });

  // 支援技能的效果挂在 `使用时`（多数翻译结果）或 `命中时`（沿用攻击技的写法）
  const 上下文 = { 目标HP: 受方.HP_当前 };
  应用规则(解释, 动作名, ['使用时', '命中时'], 施方键, 受方键, 上下文, 新状态, 步骤);
}

/**
 * 把 `解释.规则` 里指定触发点的规则落到对应单位（护盾/状态/词条/资源/数值修正）。
 * 攻击管线用 `['命中时']` + 伤害上下文；支援行动用 `['使用时','命中时']`。
 */
function 应用规则(
  解释: 战斗解释,
  动作名: string,
  触发点列表: 触发点[],
  施方键: string,
  受方键: string,
  数值上下文: { 最终伤害?: number; 目标HP?: number },
  新状态: 战斗状态,
  步骤: 结算步骤[],
): void {
  const 施方 = 新状态.单位[施方键];

  for (const 规则 of 解释.规则 ?? []) {
    if (!触发点列表.includes(规则.触发)) continue;

    let 结果: ReturnType<typeof 执行规则>;
    try {
      结果 = 执行规则(规则, 施方, 新状态.单位[受方键], 数值上下文);
    } catch (e: any) {
      步骤.push({
        类: '跳过',
        内容: `忽略：「${显示名(施方)}」的${规则.触发}规则求值失败：${e?.message ?? e}`,
        单位: 显示名(施方),
      });
      continue;
    }

    for (const 键 of 作用域单位(新状态, 规则.作用域, 施方键, 受方键)) {
      落效果(新状态, 键, 结果, 动作名, 步骤);
    }
  }
}

/**
 * `数值修正` 类动作落成状态时的默认持续回合。
 *
 * 为什么需要一个默认值：`数值修正` 动作**本身不带持续**（只有 `施加状态` 带）。
 * 翻译器要精确控制持续就该用 `施加状态`；这里给一个"一次战斗里够用"的默认，
 * 而不是把修正静默丢掉（丢掉的后果是"给友军上 buff"完全没效果）。
 */
const 数值修正默认持续 = 2;

/**
 * 把一条规则的求值结果落到某个单位上。
 * apply 五类：护盾 / 状态 / 词条 / 资源 / **数值修正**（后者落成一条携带 `数值修正` 的状态）。
 *
 * `数值修正` 早先是**静默丢弃**的（终审点过这条）：引擎没有承载字段，于是
 * 「给友军 +30% 伤害」「命中后破甲」这类效果落进虚空。现在把它存成状态 ——
 * `常驻修正` 在读 伤害/减伤/命中/闪避 时会一并算入，这样 buff 才真的改变数字。
 *
 * 仍未处理（无承载字段或属其他阶段）：领域 / 切换形态 / 追加攻击 / 范围伤害 / 规则系判定。
 */
function 落效果(
  新状态: 战斗状态,
  键: string,
  结果: ReturnType<typeof 执行规则>,
  动作名: string,
  步骤: 结算步骤[],
): void {
  const 单位 = 新状态.单位[键];
  const 补丁: Partial<战斗单位> = {};
  const 应用: string[] = [];
  let 新状态列表 = 单位.状态;

  if (结果.护盾) {
    补丁.护盾 = 单位.护盾 + 结果.护盾;
    应用.push(`护盾+${显示数值(结果.护盾)}`);
  }
  if (结果.状态?.length) {
    新状态列表 = 结果.状态.reduce((列表, s) => 施加状态(列表, s), 新状态列表);
    应用.push(`状态 ${结果.状态.map(s => s.名).join('、')}`);
  }
  if (结果.数值修正 && Object.keys(结果.数值修正).length) {
    // 状态名用技能名：不同技能的 buff 互不覆盖（`施加状态` 同名是后覆盖先）
    新状态列表 = 施加状态(新状态列表, {
      名: 动作名,
      持续: 数值修正默认持续,
      数值修正: 结果.数值修正,
    });
    应用.push(
      `数值修正 ${Object.entries(结果.数值修正)
        .map(([k, v]) => `${k}${v >= 0 ? '+' : ''}${显示数值(v)}`)
        .join('、')}（持续 ${数值修正默认持续} 回合）`,
    );
  }
  if (结果.词条?.size) {
    const 词条 = new Set(单位.词条);
    for (const 名 of 结果.词条) 词条.add(名);
    补丁.词条 = 词条;
    应用.push(`词条 ${[...结果.词条].join('、')}`);
  }
  if (结果.资源 && Object.keys(结果.资源).length) {
    补丁.资源 = { ...单位.资源, ...结果.资源 };
    应用.push(`资源 ${Object.entries(结果.资源).map(([k, v]) => `${k}=${v}`).join('、')}`);
  }

  if (!应用.length) return;

  补丁.状态 = 新状态列表;
  const 新单位 = { ...单位, ...补丁 };
  新状态.单位[键] = 新单位;
  步骤.push({ 类: '命中', 内容: `「${显示名(新单位)}」受到技能效果：${应用.join('，')}`, 单位: 显示名(新单位) });
}

/** 次要行动 / 反应动作：只扣槽并记步骤。 */
function 结算槽位行动(新状态: 战斗状态, 键: string, 行动: 意图行动, 步骤: 结算步骤[]): void {
  const 当前 = 新状态.单位[键];
  const 名 = 显示名(当前);
  const 类型 = 行动.类型;

  if (类型 !== '次要行动' && 类型 !== '反应动作') {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」不认识的行动类型「${类型}」`, 单位: 名 });
    return;
  }

  const 剩余 = 类型 === '次要行动' ? 当前.行动槽.次要 : 当前.行动槽.反应;
  if (剩余 <= 0) {
    步骤.push({ 类: '跳过', 内容: `跳过：「${名}」的${类型}槽已用尽`, 单位: 名 });
    return;
  }

  写回(新状态, 键, { 行动槽: 行动槽消耗(当前.行动槽, 类型) });

  步骤.push({ 类: '敌方行动', 内容: `「${名}」执行 ${类型}${行动.技能 ? `·${行动.技能}` : ''}`, 单位: 名 });
}

// ==================== 敌方意图 ====================

/**
 * 跑敌方意图：把 AI 返回的意图落到战斗状态上。
 * 遇到不存在的单位/目标/技能 → 跳过该行动并记日志，绝不抛错中断整回合。
 * 校验通过的行动交给 `结算行动` 做真实结算（移动/技能六步伤害/扣槽）。
 *
 * 这里是**单位 id 与技能名的唯一校验入口**：意图里的引用一律经 `找单位` 归一化，
 * 技能名一律经 `匹配技能名`（剥掉书名号/引号等装饰）比对，两条都必须给出可诊断的日志 ——
 * 「敌人不出招」的每一次都发生在这些比对上，不能只留一句「跳过」。
 *
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数
 */
export function 跑敌方意图(
  状态: 战斗状态,
  意图: 敌方意图[],
  掷骰注入?: { 命中?: number; 伤害骰?: number[] },
): {
  状态: 战斗状态;
  步骤: 结算步骤[];
} {
  const 步骤: 结算步骤[] = [];
  let 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  for (const 单位意图 of 意图) {
    const 单位0解析 = 解析单位(新状态, 单位意图.单位);
    const 单位0 = 单位0解析.单位;
    if (!单位0) {
      步骤.push({
        类: '跳过',
        内容: `跳过：敌方意图里的单位「${
          单位意图.单位 || '(空)'
        }」不在战场上；最近似候选：${候选说明(单位0解析.候选)}`,
      });
      continue;
    }
    const 名 = 显示名(单位0);

    // 单位名被"串了字"但绑回来了 → 必须留痕（否则玩家不知道引擎替他改判了什么）
    if (单位0解析.方式 === '近似') {
      步骤.push({
        类: '敌方行动',
        内容: `意图里的单位 ${绑定说明(单位意图.单位, 名, 单位0解析.相似度)}`,
        单位: 名,
      });
    }

    for (const 行动 of 单位意图.行动) {
      // 每个行动前重新取一次单位：上一个行动可能已经改过它的距离/行动槽
      const 单位 = 找单位(新状态, 单位意图.单位);
      if (!单位) {
        步骤.push({ 类: '跳过', 内容: `跳过：单位「${单位意图.单位}」不在战场上` });
        continue;
      }

      // 已失去战斗力：本轮早些被打死的单位不该再出手，也不该先记一条「执行主要行动」再跳过
      if (单位.HP_当前 <= 0) {
        步骤.push({ 类: '跳过', 内容: `跳过：「${名}」已失去战斗力，本回合不再行动`, 单位: 名 });
        break;
      }

      // 校验目标存在（带候选诊断：目标对不上是「无法识别目标」的现场）
      if (行动.目标) {
        const 目标解析 = 解析单位(新状态, 行动.目标);
        if (!目标解析.单位) {
          步骤.push({
            类: '跳过',
            内容: `跳过：「${名}」的目标「${行动.目标}」不在战场上；最近似候选：${候选说明(
              目标解析.候选,
            )}`,
            单位: 名,
          });
          continue;
        }
        if (目标解析.方式 === '近似') {
          步骤.push({
            类: '敌方行动',
            内容: `目标 ${绑定说明(行动.目标, 显示名(目标解析.单位), 目标解析.相似度)}`,
            单位: 名,
          });
        }
      }

      // 校验技能名（R7）：意图里写了技能，但该单位的技能表里没有 → 跳过该行动
      // （技能表 = 一次性翻译出的「技能名 → 战斗解释」；老存档可能缺省，兜底为空表）
      // 没写技能 = 基础攻击，不算「没有技能」——交给 结算行动 走基础攻击分支。
      const 技能表 = 单位.技能 ?? {};
      if (行动.技能) {
        const 技能解析 = 解析技能名(技能表, 行动.技能);
        if (!技能解析.命中) {
          步骤.push({
            类: '跳过',
            内容: `跳过：「${名}」没有技能「${行动.技能}」；该单位可用技能：${可用技能(技能表)}${
              技能解析.候选.length ? `；最近似：${候选说明(技能解析.候选)}` : ''
            }`,
            单位: 名,
          });
          continue;
        }
        if (技能解析.方式 === '近似') {
          步骤.push({
            类: '敌方行动',
            内容: `技能名 ${绑定说明(行动.技能, 技能解析.命中, 技能解析.相似度)}`,
            单位: 名,
          });
        }
      }

      步骤.push({ 类: '敌方行动', 内容: `「${名}」执行 ${行动.类型}${行动.技能 ? `·${行动.技能}` : '·基础攻击'}`, 单位: 名 });

      const 结果 = 结算行动(新状态, 单位, 行动, 掷骰注入);
      新状态 = 结果.状态;
      步骤.push(...结果.步骤);
    }
  }

  return { 状态: 新状态, 步骤 };
}

// ==================== 一个回合（阶段B · 单位行动） ====================

/** 玩家单位判定：契约者本体（`实体转战斗单位` 给它 类型: '玩家'） */
function 是玩家单位(单位: 战斗单位): boolean {
  return 单位.类型 === '玩家';
}

/**
 * 跑一个回合的**阶段B · 单位行动**：按先攻顺序把玩家行动与敌方意图**交错**结算。
 * （阶段A 在回合开始、阶段F 在回合结束，都在调用方 —— 见 CombatView.推进回合 / 执行本轮。）
 *
 * 为什么这一段必须是纯函数而不是写在 `.vue` 里：
 * 本仓库没有 vue-tsc，`.vue` 只做语法编译（不解析 import、跑不到运行时），
 * 于是「敌方意图没接上 / 单位 id 对不上 / 技能名对不上」这类坏在 UI 层是**测不到的** ——
 * 而「敌人完全不出招」正是死在这里。抽出来之后，「一个回合里敌人到底出没出招」
 * 就成了一条可回归的断言。
 *
 * **交错**（而不是先跑完所有敌人）是必须的：本轮早些被打死的单位不该在轮末再出手，
 * `结算行动` 的存活守卫要看得到最新 HP。
 *
 * @param 玩家行动 契约者本回合的行动声明（来自 `构造行动声明`）
 * @param 意图列表 本回合生成的敌方意图（来自 `生成敌方意图`）
 * @param 掷骰注入 测试用：固定命中 d20 与伤害骰点数
 */
export function 跑一个回合(
  状态: 战斗状态,
  玩家行动: 意图行动[],
  意图列表: 敌方意图[],
  掷骰注入?: { 命中?: number; 伤害骰?: number[] },
): { 状态: 战斗状态; 步骤: 结算步骤[] } {
  const 步骤: 结算步骤[] = [];
  let 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  // 意图里的「单位」可能是短名 / 变量路径全名 / 「玩家」，一律 找单位 归一化成 id 再挂。
  // 这里**要用带近似的那一层**：模型把单位名串了字（注音/拼音）时，意图得挂到正确的单位上，
  // 否则该单位会被判成"没有收到任何意图"而空过 —— 那就白兜底了。
  const 意图按id = new Map<string, 敌方意图[]>();
  for (const 单条 of 意图列表) {
    const 单位 = 找单位(新状态, 单条.单位);
    if (!单位) {
      步骤.push({ 类: '跳过', 内容: `跳过：敌方意图里的单位「${单条.单位 || '(空)'}」不在战场上` });
      continue;
    }
    意图按id.set(单位.id, [...(意图按id.get(单位.id) ?? []), 单条]);
  }

  let 玩家已出手 = false;

  for (const id of [...状态.先攻]) {
    // 先攻里的 id 是**我们自己**写进去的（初始化战斗状态），必须精确命中 ——
    // 用带近似的那层会让一个坏 id 悄悄指到别的单位身上
    const 单位 = 找单位精确(新状态, id);
    if (!单位) {
      步骤.push({ 类: '跳过', 内容: `跳过：先攻顺序里的「${id}」不在战场上` });
      continue;
    }

    if (是玩家单位(单位)) {
      if (玩家行动.length === 0) continue;
      玩家已出手 = true;
      for (const 行动 of 玩家行动) {
        // 每个行动前按 id 重取行动者：上一个行动可能已改了它的 HP（如一命换一命的自我代价），
        // 结算行动的存活守卫要看到最新值，不能拿本轮开头的旧引用
        const 行动者 = Object.values(新状态.单位).find(x => x.id === 单位.id);
        if (!行动者) break;
        const 结果 = 结算行动(新状态, 行动者, 行动, 掷骰注入);
        新状态 = 结果.状态;
        步骤.push(...结果.步骤);
      }
      continue;
    }

    const 本意图 = 意图按id.get(单位.id);
    if (!本意图 || 本意图.length === 0) {
      // 模型漏了这个单位（或整次意图调用失败）：必须明说，否则「敌人不出招」无从诊断
      步骤.push({
        类: '跳过',
        内容: `「${显示名(单位)}」本回合没有收到任何意图 → 空过（敌方意图由每回合 1 次 AI 调用生成：模型漏了这个单位，或那次调用整体失败）`,
        单位: 显示名(单位),
      });
      continue;
    }

    const 结果 = 跑敌方意图(新状态, 本意图, 掷骰注入);
    新状态 = 结果.状态;
    步骤.push(...结果.步骤);
  }

  // 玩家填了槽却没有任何出手时机（如契约者不在先攻里）→ 必须说出来，不能像没点过一样
  if (!玩家已出手 && 玩家行动.length > 0) {
    步骤.push({ 类: '跳过', 内容: '跳过：契约者不在先攻顺序里，本轮玩家行动未执行' });
  }

  return { 状态: 新状态, 步骤 };
}
