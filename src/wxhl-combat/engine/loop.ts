/**
 * 跑某个单位**自己技能表里**指定触发点的规则（主人视角：施方 = 受方 = 它自己）。
 * 用途：「击杀时」「资源变化时」这类"由这个单位自己身上发生的事"触发的规则。
 * 不递归（每次事件只跑一遍），所以「资源变化时 +1 资源」不会自我循环。
 */
function 跑自身触发(
  新状态: 战斗状态,
  键: string,
  触发点列表: 触发点[],
  步骤: 结算步骤[],
  上下文?: { 最终伤害?: number; 目标HP?: number },
): void {
  const 单位 = 新状态.单位[键];
  if (!单位) return;
  for (const [技能名, 解释] of Object.entries(单位.技能 ?? {})) {
    应用规则(解释, 技能名, 触发点列表, 键, 键, 上下文 ?? {}, 新状态, 步骤);
  }
}

/**
 * 阶段F 的**「回合结束」规则结算**：每回合收尾时跑 `触发: '回合结束'` 的规则。
 * 世界书 阶段F 的顺序：持续效果结算 → 状态判定 → **尾结算（仅"回合结束"生效的被动）** → 清理。
 * 用途：回合结束才结算的回复/扣血/状态切换。
 */
export function 阶段F规则结算(状态: 战斗状态, 步骤: 结算步骤[] = []): 战斗状态 {
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  for (const 键 of Object.keys(状态.单位)) {
    const 单位 = 新状态.单位[键];
    // 倒地（HP ≤ 0）的单位不吃阶段F规则：副本角色 HP 0 = 死透、契约者在濒死里 ——
    // 回合结束回血在倒地后照样跑 =「永远杀不死」（玩家实测），这里从根上断掉。
    if (单位.HP_当前 <= 0) continue;

    for (const [技能名, 解释] of Object.entries(单位.技能 ?? {})) {
      for (const 规则 of 有效规则(解释)) {
        if (规则.触发 !== '回合结束') continue;

        let 结果: ReturnType<typeof 执行规则>;
        try {
          结果 = 执行规则(规则, 单位, 单位);
        } catch (e: any) {
          步骤.push({
            类: '跳过',
            内容: `忽略：「${显示名(单位)}」的回合结束规则「${技能名}」求值失败：${e?.message ?? e}`,
            单位: 显示名(单位),
          });
          continue;
        }

        for (const 目标键 of 作用域单位(新状态, 规则.作用域, 键, 键)) {
          落效果(新状态, 目标键, 结果, 技能名, 步骤, 键);
        }
      }
    }
  }

  return 新状态;
}

/**
 * 阶段A 的**「回合开始」规则结算**：每回合开始时跑一遍各单位技能表里 `触发: '回合开始'` 的规则。
 *
 * 卡面上大量效果挂在"每回合"上 —— 终焉信标的「每回合蓄满 1 次能量」、星幕护盾的
 * 「每回合回复最大值 5%」、回合开始的自动增益/持续消耗……早先**没有任何东西执行这个触发点**，
 * 它们全是静默失效的（实战：天基武器的这一半字白写）。
 *
 * 视角与 `开战常驻结算` 一致（规则主人 = 施方 = 受方），作用域照常分发；
 * 真正的"跨单位"效果（给队友上 buff）用 `作用域: 我方全体` 表达。
 *
 * @param 步骤 战报日志（把每回合实际生效的东西写进面板）
 */
export function 阶段A规则结算(状态: 战斗状态, 步骤: 结算步骤[] = []): 战斗状态 {
  const 新状态: 战斗状态 = { ...状态, 单位: { ...状态.单位 } };

  for (const 键 of Object.keys(状态.单位)) {
    const 单位 = 新状态.单位[键];
    // 倒地（HP ≤ 0）的单位不吃阶段A规则：副本角色 HP 0 = 死透、契约者在濒死里 ——
    // 回合开始回血在倒地后照样跑 =「永远杀不死」（玩家实测），这里从根上断掉。
    if (单位.HP_当前 <= 0) continue;

    for (const [技能名, 解释] of Object.entries(单位.技能 ?? {})) {
      for (const 规则 of 有效规则(解释)) {
        if (规则.触发 !== '回合开始') continue;

        let 结果: ReturnType<typeof 执行规则>;
        try {
          结果 = 执行规则(规则, 单位, 单位);
        } catch (e: any) {
          步骤.push({
            类: '跳过',
            内容: `忽略：「${显示名(单位)}」的回合开始规则「${技能名}」求值失败：${e?.message ?? e}`,
            单位: 显示名(单位),
          });
          continue;
        }

        for (const 目标键 of 作用域单位(新状态, 规则.作用域, 键, 键)) {
          落效果(新状态, 目标键, 结果, 技能名, 步骤);
        }
      }
    }
  }

  return 新状态;
}

// ==================== 回合开始的行动槽 / 移动额度 ====================

/**
 * 回合开始时的**行动槽**：基础各 1 次，再加上状态携带的「主要行动」「反应动作」「次要行动」修正。
 * 世界书里血统/职业特性常写"额外获得一次反应动作"——那类效果就落在 `数值修正 目标 反应动作`。
 */
export function 回合开始行动槽(单位: 战斗单位) {
  const 槽 = 行动槽重置(单位.行动槽);
  return {
    ...槽,
    主要: Math.max(0, 槽.主要 + 常驻修正(单位, '主要行动')),
    反应: Math.max(0, 槽.反应 + 常驻修正(单位, '反应动作')),
    次要: Math.max(0, 槽.次要 + 常驻修正(单位, '次要行动')),
  };
}

/**
 * 回合开始时的**移动额度**：本回合【移动距离】+ 状态携带的「移动距离」修正 + AGI 修正值增量。
 * （面板值已含装备与「移动距离额外加成」以及面板 AGI 修正；这里再叠加规则带来的临时增减。）
 */
export function 回合开始额度(单位: 战斗单位): number {
  const 面板移动距离 =
    (单位.移动距离 ?? 0) > 0 ? 单位.移动距离! : 移动距离计算(单位.属性.实际.AGI, 单位.阶位, 0);
  return Math.max(
    0,
    移动额度重置(面板移动距离) + 常驻修正(单位, '移动距离') + 状态属性修正增量(单位, 'AGI'),
  );
}

/**
 * 回合开始时欠着的**额外行动回合**次数（常驻被动写"每回合额外一个行动回合"时走这条）。
 * 战斗中当场给的（技能/装备主动效果）走 `落效果` 直接记在单位上 —— 两条路最终都落到 `单位.追加行动`。
 */
export function 回合开始追加行动(单位: 战斗单位): number {
  return Math.max(0, Math.floor(常驻修正(单位, '额外行动回合')));
}

