/**
 * 解析一个"单位引用"。
 * 引用既可能是 `状态.单位` 的键（短名，如 `骨卫兵`），也可能是 `战斗单位.id`（变量路径，如
 * `副本角色.骨卫兵`）；敌方意图提示词里还会用固定称呼 `玩家` 指代契约者本体。
 *
 * **三层解析**（见 engine/nameMatch）：精确 → 归一化精确 → **近似唯一**。
 * 第三层是给中文适配问题兜底的：快路模型会把名字里的汉字换成注音
 * （「工蜂异形幼体」→「工蜂异形ㄧㄡˋ体」），不兜底的话意图里的单位/目标永远对不上，
 * 表现成「敌人不出招」。**只在唯一时才绑**，且调用方要把绑定写进日志（否则就是偷偷改判）。
 *
 * 注意：只给 **AI 给的引用** 用它。我们自己生成的 id（先攻顺序）走 `找单位精确`，
 * 绝不能模糊 —— 那会让一个坏 id 悄悄指到别的单位身上。
 */
export function 解析单位(
  状态: 战斗状态,
  引用: string,
): {
  单位?: 战斗单位;
  方式: 名字解析结果['方式'];
  相似度?: number;
  候选: 近似候选[];
} {
  const 候选: 候选组[] = Object.entries(状态.单位).map(([键, u]) => ({
    归属: 键,
    // 键 / 全路径 id / 显示名 都是同一个单位的别名 —— 必须放在**同一组**里，
    // 摊平成多条候选会让它和自己打平，永远绑不上（见 nameMatch 的注释）
    别名: [键, u.id, 显示名(u), ...(u.类型 === '玩家' ? ['玩家'] : [])],
  }));

  const 结果 = 解析名字引用(候选, 引用);
  const 单位 = 结果.命中 ? 状态.单位[结果.命中] : undefined;

  return { 单位, 方式: 结果.方式, 相似度: 结果.相似度, 候选: 结果.候选 };
}

/** 只要单位（不需要诊断信息时用） */
export function 找单位(状态: 战斗状态, 引用: string): 战斗单位 | undefined {
  return 解析单位(状态, 引用).单位;
}

/** 精确查找（键或 id）—— 用于**我们自己生成**的 id，不做任何模糊 */
export function 找单位精确(状态: 战斗状态, id: string): 战斗单位 | undefined {
  return 状态.单位[id] ?? Object.values(状态.单位).find(u => u.id === id);
}

/** 候选清单的日志文案（诊断用：把坏串与候选并排打出来，不用再猜是哪一侧坏的） */
function 候选说明(候选: 近似候选[]): string {
  if (!候选.length) return '（战场上没有候选）';
  return 候选.map(c => `${c.名}(${Math.round(c.相似度 * 100)}%)`).join('、');
}

/** 近似绑定的日志文案 */
function 绑定说明(原串: string, 命中名: string, 相似度?: number): string {
  return `「${原串}」按最近似绑定到「${命中名}」（相似度 ${Math.round((相似度 ?? 0) * 100)}%）`;
}

/** 把单位反查回 `状态.单位` 的键（先按对象身份，再按 id）。 */
function 找键(状态: 战斗状态, 单位: 战斗单位): string | undefined {
  for (const 键 of Object.keys(状态.单位)) {
    const u = 状态.单位[键];
    if (u === 单位 || u.id === 单位.id) return 键;
  }
  return undefined;
}

/** 写回单位：**换新对象**（绝不原地改，保证纯函数语义）。 */
function 写回(状态: 战斗状态, 键: string, 补丁: Partial<战斗单位>): void {
  状态.单位[键] = { ...状态.单位[键], ...补丁 };
}

/** 显示名：变量里的姓名（`头部.姓名`）；缺省退回变量路径最后一段。界面/日志一律用它。 */
function 显示名(单位: 战斗单位): string {
  return 单位.名称 || 单位.id.split('.').pop() || 单位.id;
}

/** 数值显示：整数原样，小数最多两位。 */
function 显示数值(值: number): number {
  return Math.round(值 * 100) / 100;
}

/**
 * 解析技能名 —— 与单位引用同一套三层解析（`engine/nameMatch`）：
 * 精确 → 归一化（剥装饰/空白/注音/拼音夹注）→ 近似唯一。
 *
 * 归一化只做**装饰剥离与注音剥离**，不做模糊匹配；近似那一层要求唯一领先，
 * 所以「斩」不会匹配到「斩击」，同一个单位有两个近似技能名时会拒绝绑定。
 */
export function 解析技能名(表: Record<string, 战斗解释>, 名字: string): 名字解析结果 {
  const 候选: 候选组[] = Object.keys(表).map(键 => ({ 归属: 键, 别名: [键] }));
  return 解析名字引用(候选, 名字);
}

/** 在技能表里找 `名字` 对应的**原名**；找不到返回 undefined */
export function 匹配技能名(表: Record<string, 战斗解释>, 名字: string): string | undefined {
  return 解析技能名(表, 名字).命中;
}

/** 单位技能表里所有可用技能名的显示串（跳过时的诊断信息用） */
function 可用技能(表: Record<string, 战斗解释>): string {
  const 名 = Object.keys(表);
  return 名.length ? 名.join('、') : '（无，可省略「技能」键做基础攻击）';
}

/**
 * 基础攻击的解释 —— 主要行动**没写技能**时的兜底
 * （世界书速查表：徒手 1d4 / 倍率 0.5 / 强化 0；有主武器则用武器自己的骰与倍率）。
 *
 * 为什么必须有：模型没写技能名时，早先的实现直接「跳过」，于是敌人整轮空过、一次也不出招。
 * 基础攻击是**任何单位任何时候都合法**的行动，给模型留一条永远走得通的出路。
 * 伤害倍率填 0 —— 基础攻击不吃技能倍率，伤害全部来自武器/徒手部分。
 *
 * 射程：徒手必须近战（世界书），照常门禁；有主武器时卡里没记武器类型、判不了射程，
 * 由 `结算技能` 跳过距离门禁并记一条说明（否则拿枪的敌人会被永远卡住）。
 */
export function 基础攻击解释(有主武器: boolean): 战斗解释 {
  return {
    行动消耗: '主要行动',
    射程: 有主武器 ? '' : '近战',
    目标: '单体',
    消耗: '无',
    冷却: 0,
    分类: '基础',
    类型: '主动',
    可预判: true,
    关联属性: 'STR',
    技能阶位: 1,
    伤害倍率: 0,
    规则: [],
    托管: [],
  };
}

