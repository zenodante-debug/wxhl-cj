/** 位阶修正值系数（世界书原文：1、2、4、7、11，对应 1~5 阶，超脱 20） */
const 位阶系数表: Record<string, number> = {
  一阶: 1,
  二阶: 2,
  三阶: 4,
  四阶: 7,
  五阶: 11,
  超脱: 20,
};

/**
 * 属性修正值 =（实际属性值 − 5）× 位阶修正值系数
 * 用于所有判定与伤害
 */
export function 属性修正值(实际属性值: number, 阶位: string): number {
  const 系数 = 位阶系数表[阶位];
  if (系数 === undefined) throw new Error(`未知阶位: ${阶位}`);
  return (实际属性值 - 5) * 系数;
}
