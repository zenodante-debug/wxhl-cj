import { rollDie } from './dice';

/** 位阶修正值系数（世界书原文：1、2、4、7、11，对应 1~5 阶，超脱 20） */
const 位阶系数表: Record<string, number> = {
  一阶: 1,
  二阶: 2,
  三阶: 4,
  四阶: 7,
  五阶: 11,
  超脱: 20,
};

/**
 * 位阶序数（1~6）—— 部位DC加值、技能伤害成长（1+(阶位−1)/2）、武器阶位都用它。
 * 超脱在五阶之上，序数 6。认不出的阶位由调用方兜底（不在这里抛错）。
 */
export const 阶位序数表: Record<string, number> = { 一阶: 1, 二阶: 2, 三阶: 3, 四阶: 4, 五阶: 5, 超脱: 6 };

/**
 * **阶位归一（关键词筛选）**：卡面里的阶位字段带各种修饰，精确匹配必然报错。
 *
 * 玩家口径（2026-10-08）：「更加宽泛一点吧，位阶的判定用关键词筛选模式，
 * 含有"一"就是一阶，含有"二"就是二阶，含有"超脱"就是超脱阶。
 * 不仅是契约者玩家、还有其他契约者、副本角色都是同理，这样能减少报错。
 * 不仅是汉字，阿拉伯数字也行。」
 *
 * 规则：
 * 1. **超脱优先**（`超脱` 里没有任何数字，放在后面会被漏掉）；
 * 2. 其余按 **五→四→三→二→一** 降序匹配汉字与阿拉伯数字 ——
 *    出现多个时取最高那阶（「一至三阶」→ 三阶，「五阶巅峰」→ 五阶）；
 * 3. 一个关键词都没有 → 返回去空白后的原文，由严格层（`属性修正值`）抛错
 *    —— 坏数据要看得见，只是"多几个字"不再算坏数据。
 *
 * 实战里的写法：「一阶 · 初始契约者」「五阶巅峰 · 镇国剑尊」「四转 (隐藏转职)」「超脱者」「1阶」。
 * 全引擎只有这一份归一（系数表 / 序数表 / 面板代算都走它）。
 */
export function 归一阶位(阶位: string): string {
  const 文 = String(阶位 ?? '').trim();
  if (文.includes('超脱')) return '超脱';

  const 关键词: [string[], string][] = [
    [['五', '5'], '五阶'],
    [['四', '4'], '四阶'],
    [['三', '3'], '三阶'],
    [['二', '2'], '二阶'],
    [['一', '1'], '一阶'],
  ];
  for (const [词表, 阶位名] of 关键词) {
    if (词表.some(词 => 文.includes(词))) return 阶位名;
  }
  return 文;
}

/** 传进来的阶位是超脱吗（三种写法都算） */
export function 是超脱(阶位: string): boolean {
  return 归一阶位(阶位) === '超脱';
}

/** 阶位 → 序数（1~6）。认不出 / 空 → 1（与武器位阶的兜底一致，绝不因为错别字炸掉结算）。 */
export function 阶位序数(阶位: string): number {
  return 阶位序数表[归一阶位(阶位)] ?? 1;
}

/**
 * 属性修正值 =（实际属性值 − 5）× 位阶修正值系数
 * 用于所有判定与伤害
 */
/**
 * 宽容版属性修正值：认不出的阶位按**一阶**处理，绝不抛错。
 *
 * `属性修正值` 对未知阶位抛错是战斗结算层的刻意设计（坏数据 → 跳过该行动，可见）。
 * 但**濒死检定 / 面板代算**这类"维护性"的地方不能因为一个错别字把整轮炸掉
 * （实战反馈：阶位写错 / 写成「超脱者」）。
 */
export function 宽容属性修正值(实际属性值: number, 阶位: string): number {
  try {
    return 属性修正值(实际属性值, 阶位);
  } catch {
    return 实际属性值 - 5;
  }
}

export function 属性修正值(实际属性值: number, 阶位: string): number {
  const 系数 = 位阶系数表[归一阶位(阶位)];
  if (系数 === undefined) throw new Error(`未知阶位: ${阶位}`);
  return (实际属性值 - 5) * 系数;
}

/**
 * 先攻判定 = 1d20 + AGI修正
 * 世界书原文：每回合开始，全体投 D20 + AGI修正；相同则AGI属性高者优先；降序排列行动顺序
 */
export function 先攻判定(AGI实际值: number, 阶位: string): number {
  return rollDie(20) + 属性修正值(AGI实际值, 阶位);
}

// ==================== 属性键与「多属性加权」 ====================

/** 四维属性键 */
export type 属性键 = 'STR' | 'AGI' | 'CON' | 'PER';

/**
 * 把一个自由字符串归一成属性键；认不出来返回 `null`（**不兜底** ——
 * 兜底是调用方的事：`关联属性` 缺省按 STR，而 `属性加权` 里认不出的条目直接丢掉）。
 * 中英文写法都认（卡面写「感知」「敏捷」的不少）。
 */
export function 归一属性键(值: unknown): 属性键 | null {
  const 文 = String(值 ?? '').toUpperCase();
  if (!文) return null;
  if (文.includes('AGI') || 文.includes('敏捷')) return 'AGI';
  if (文.includes('CON') || 文.includes('体质')) return 'CON';
  if (文.includes('PER') || 文.includes('感知')) return 'PER';
  if (文.includes('STR') || 文.includes('力量')) return 'STR';
  return null;
}

/** 一条加权项：某一维修正值乘多少 */
export interface 属性加权项 {
  属性: 属性键;
  系数: number;
}

/**
 * **多属性加权伤害**的宽容解析（卡面原话：「造成 PER×3.6 + AGI×3.2 的伤害」）。
 *
 * 认三种写法：
 * - 数组：`[{"属性":"PER","系数":3.6},{"属性":"AGI","系数":3.2}]`（提示词要求的形状）
 * - 单个对象：`{"属性":"PER","系数":3.6}`（模型图省事常这么写）
 * - **字符串**：`"PER×3.6 + AGI×3.2"`（模型直接把卡面原话抄进来 —— 白捡的容错）
 *
 * 丢掉不可用的条目：认不出的属性名、非有限/≤0 的系数、缺系数的；同一维**重复只取第一条**
 * （宁可少算，也不偷偷把同一维修正翻倍）。全丢光 → 空数组，调用方退回
 * `关联属性修正 × 伤害倍率`（老行为）。
 */
export function 解析属性加权(值: unknown): 属性加权项[] {
  // 模型有时会把数组**序列化成字符串**（`"[{\"属性\":\"PER\",\"系数\":3.6}]"`）——
  // 先试一次 JSON 解析，省得一个引号之差就整条判失败重翻。
  const 可能数组 =
    typeof 值 === 'string' && /^\s*[[{]/.test(值)
      ? (() => {
          try {
            return JSON.parse(值);
          } catch {
            return 值;
          }
        })()
      : 值;

  const 候选: unknown[] =
    typeof 可能数组 === 'string'
      ? [...可能数组.matchAll(/([一-龥A-Za-z]{1,8})\s*[×xX*]\s*(\d+(?:\.\d+)?)/g)].map(m => ({
          属性: m[1],
          系数: Number(m[2]),
        }))
      : Array.isArray(可能数组)
        ? 可能数组
        : 可能数组 && typeof 可能数组 === 'object'
          ? [可能数组]
          : [];

  const 出: 属性加权项[] = [];
  const 见过 = new Set<属性键>();
  for (const 条 of 候选) {
    if (!条 || typeof 条 !== 'object') continue;
    const 属性 = 归一属性键((条 as any).属性);
    const 系数 = Number((条 as any).系数);
    if (!属性 || 见过.has(属性)) continue;
    if (!Number.isFinite(系数) || 系数 <= 0) continue;
    见过.add(属性);
    出.push({ 属性, 系数 });
  }
  return 出;
}

/** 加权里**系数最大**的那一维（用于"关联属性没写时拿哪一维掷命中"）；空 → null */
export function 主加权属性(加权: 属性加权项[]): 属性键 | null {
  let 最佳: 属性加权项 | null = null;
  for (const 条 of 加权) if (!最佳 || 条.系数 > 最佳.系数) 最佳 = 条;
  return 最佳?.属性 ?? null;
}

/**
 * **加权的紧凑写法**（「PER×3.6 + AGI×3.2」）—— 行动下拉标签 / 技能列表 / 效果预览头部
 * 共用这一份口径，免得三处各写一套、其中一处忘了加权。没有加权 → 空串。
 * 收的是**原始字段值**（数组 / 单对象 / 字符串都行），与 `解析属性加权` 同一套容错。
 */
export function 加权摘要(值: unknown): string {
  return 解析属性加权(值)
    .map(条 => `${条.属性}×${条.系数}`)
    .join(' + ');
}
