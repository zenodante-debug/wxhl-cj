// ================================================================
// 无限回廊 · 前端战斗引擎 · 战斗持久化（纯函数，不碰酒馆接口）
//
// 为什么要单独成模块：快照形状是**契约** —— 恢复时要能读回「战斗状态 + 意图模式 + 日志」，
// 而且必须向后兼容老存档（老存档里只有状态本身）。
//
// 玩家实测的两个问题促成了它：
//   1. 切到设置页再切回来，战斗日志没了（日志原来只在组件内存里，切页签 = 组件卸载）；
//   2. 选了「掷骰」模式，重载页面恢复战斗后又开始调 AI（意图模式没被持久化，恢复时默认 ai）。
// ================================================================

import type { 战斗状态 } from '../types';

export type 意图模式 = 'ai' | '随机';

/** 存进脚本变量的形状（可 JSON 序列化：词条 Set → 数组） */
export interface 战斗快照 {
  状态: 战斗状态;
  意图模式: 意图模式;
  日志: string[];
  /** 开战那一刻的**上一楼正文**（模型当时的输入）—— 收尾正文写"环境"的唯一天然来源 */
  开战前上下文: string;
  /** 开战时选的开场模式（对峙/室内…）—— 环境的补充 */
  开场模式: string;
}

/** 战斗日志最多存多少行（防变量无限膨胀） */
export const 日志上限 = 400;

/** 战斗状态 → 可 JSON 序列化的纯对象（词条 Set → 数组） */
export function 战斗状态转纯对象(状态: 战斗状态): any {
  return {
    ...状态,
    单位: Object.fromEntries(
      Object.entries(状态.单位).map(([k, u]) => [k, { ...u, 词条: [...(u.词条 ?? [])] }]),
    ),
  };
}

/** 纯对象 → 战斗状态（词条数组 → Set） */
export function 纯对象转战斗状态(obj: any): 战斗状态 {
  return {
    ...obj,
    单位: Object.fromEntries(
      Object.entries(obj?.单位 || {}).map(([k, u]: [string, any]) => [k, { ...u, 词条: new Set(u.词条 || []) }]),
    ),
  };
}

/**
 * 造快照：状态（拍平）+ 意图模式 + 日志（截到上限，只留最近的）。
 * 意图模式与日志**平铺在同一层** —— 老存档就是把状态本身存在这一层的，
 * 恢复时按「有没有 单位 字段」区分新老，见 `恢复战斗状态`。
 */
export function 构建战斗状态快照(
  状态: 战斗状态,
  额外: {
    意图模式?: 意图模式;
    日志?: string[];
    开战前上下文?: string;
    开场模式?: string;
  } = {},
): any {
  return {
    ...战斗状态转纯对象(状态),
    意图模式: 额外.意图模式 ?? 'ai',
    日志: (额外.日志 ?? []).slice(-日志上限),
    开战前上下文: 额外.开战前上下文 ?? '',
    开场模式: 额外.开场模式 ?? '',
  };
}

/**
 * 把存下来的东西还原成 `{ 状态, 意图模式, 日志 }`。
 * - 老存档（只有状态本体，没有 意图模式/日志）→ 意图模式按 `ai`、日志给空数组（向后兼容）
 * - 不是有效快照（没有 单位 / 没在进行中）→ 返回 null
 */
export function 恢复战斗状态(原始: any): 战斗快照 | null {
  if (!原始 || typeof 原始 !== 'object' || !原始.单位) return null;
  if (!原始.进行中) return null;

  const { 意图模式, 日志, 开战前上下文, 开场模式, ...状态本体 } = 原始;
  return {
    状态: 纯对象转战斗状态(状态本体),
    意图模式: 意图模式 === '随机' ? '随机' : 'ai',
    日志: Array.isArray(日志) ? 日志.filter((x: any) => typeof x === 'string') : [],
    // 老存档没有这两样 → 空串（收尾提示词会明确写「（无）」）
    开战前上下文: typeof 开战前上下文 === 'string' ? 开战前上下文 : '',
    开场模式: typeof 开场模式 === 'string' ? 开场模式 : '',
  };
}
