/**
 * 混合伤害（最低1）= 基础伤害 − 实际防御
 * 世界书原文：第一步_基础伤害区
 */
export function 混合伤害(基础伤害: number, 实际防御: number): number {
  return Math.max(基础伤害 - 实际防御, 1);
}
