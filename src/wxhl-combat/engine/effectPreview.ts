// ================================================================
// 无限回廊 · 前端战斗引擎 · 效果预览（人话）
// 纯函数，不碰酒馆接口
//
// 玩家反馈：「每个具体的行动选项，应该能够看到产生的具体的预期效果啊！
// 现在点技能完全不知道有什么用，比如一个二阶段变身技能，完全不知道能干什么。」
//
// 翻译结果（`战斗解释`）已经很结构化 —— 这里只做一件事：把它翻成人能读的话，
// 供行动下拉选中后、单位详情面板里展示。**不改任何数值**，纯粹是"看得懂"。
// ================================================================

import type { 动作, 战斗解释, 条件, 取值 } from '../types';
import { 冷却回合数, 规范行动消耗 } from './actionOptions';

export interface 效果预览 {
  /** 一行元信息：行动类型 / 射程 / 目标 / 消耗 / 倍率 / 冷却 */
  头部: string[];
  /** 规则逐条人话（含触发点与作用域）；无规则但有伤害倍率时给一条伤害说明 */
  行: string[];
}

/** 这些目标的「量」是**比例**（0.3 = 30%），显示成百分比。
 *  注意「闪避」「防御」「命中」是**绝对值**（闪避+5 = 闪避值 +5），不在里面。 */
const 比例目标 = new Set(['伤害', '减伤', '攻击倍率', '全元素抗性']);

/** 修正目标 → 人话名字（面板/公式里那个数的名字） */
const 目标人话: Record<string, string> = {
  伤害: '伤害',
  最终乘区: '最终伤害',
  减伤: '减伤',
  命中: '命中',
  闪避: '闪避',
  反应动作: '反应动作次数',
  次要行动: '次要行动次数',
  主要行动: '主要行动次数',
  额外行动回合: '额外行动回合',
  移动距离: '移动距离',
  攻击倍率: '武器倍率',
  基础伤害骰: '武器伤害骰',
  最大HP上限: '最大HP上限',
  全元素抗性: '全元素抗性',
  防御: '防御',
  STR: 'STR（属性点）',
  AGI: 'AGI（属性点）',
  CON: 'CON（属性点）',
  PER: 'PER（属性点）',
  STR修正: 'STR修正值',
  AGI修正: 'AGI修正值',
  CON修正: 'CON修正值',
  PER修正: 'PER修正值',
};

const 作用域人话: Record<string, string> = {
  自身: '自身',
  我方全体: '我方全体',
  敌方全体: '敌方全体',
  攻击目标: '攻击目标',
  攻击者: '攻击者（打他的人）',
  命中点: '命中点',
};

function 数字(n: number): string {
  const 修 = Math.round(n * 100) / 100;
  return String(修);
}

/** 带正负号的量（+3 / -2） */
function 增减(n: number): string {
  const 修 = Math.round(n * 100) / 100;
  return `${修 >= 0 ? '+' : ''}${修}`;
}

/** 取值（量）→ 人话 */
export function 取值人话(值: 取值 | undefined): string {
  if (!值) return '0';
  const 系数 = typeof 值.系数 === 'number' ? 值.系数 : undefined;
  const 后缀 = 系数 === undefined ? '' : `×${数字(系数)}`;
  switch (值.源) {
    case '常数':
      return 数字(系数 ?? 0);
    case '资源':
      return `${值.名 ?? '资源'}${后缀}`;
    case '属性':
      return `${值.名 ?? '属性'}${后缀}`;
    case '层数':
      return 系数 === undefined ? '层数' : `层数×${数字(系数)}`;
    case '最终伤害':
      return 系数 === undefined ? '最终伤害' : `最终伤害×${数字(系数)}`;
    case '溢出伤害':
      return 系数 === undefined ? '溢出伤害' : `溢出伤害×${数字(系数)}`;
    case '目标HP':
      return 系数 === undefined ? '目标HP' : `目标HP×${数字(系数)}`;
    case '目标词条':
      return `目标词条「${值.名 ?? ''}」`;
    case '表达式':
      return 值.式 ?? '表达式';
    default:
      return '?';
  }
}

/** 条件 → 人话（HP比例 < 0.5 → 「自身HP低于50%」） */
export function 条件人话(条件: 条件 | undefined): string {
  if (!条件) return '';
  const 左 = 取值人话(条件.左);
  const 右 = 取值人话(条件.右);
  const 比 = 条件.比较;
  if (条件.左?.源 === '资源' && 条件.左.名 === 'HP比例' && 条件.右?.源 === '常数') {
    const 比字 = 比 === '<' ? '低于' : 比 === '≤' ? '不高于' : 比 === '>' ? '高于' : 比 === '≥' ? '不低于' : '等于';
    return `自身HP${比字}${数字((条件.右.系数 ?? 0) * 100)}%`;
  }
  const 比字 = 比 === '≥' ? '≥' : 比 === '≤' ? '≤' : 比;
  return `${左} ${比字} ${右}`;
}

/** 数值修正 → 人话（目标不同，单位不同） */
function 数值修正人话(目标: string, 值: 取值 | undefined, 持续?: number): string {
  const 名 = 目标人话[目标] ?? 目标;
  const 尾巴 = 持续 !== undefined ? `（持续 ${持续 >= 999 ? '本场战斗' : `${持续} 回合`}）` : '';
  if (目标 === '最终乘区') return `最终伤害 ×${数字((typeof 值?.系数 === 'number' ? 值.系数 : 0) + 1)}${尾巴}`;
  if (比例目标.has(目标)) {
    const 系数 = typeof 值?.系数 === 'number' ? 值.系数 : 0;
    return `${名} ${增减(Math.round(系数 * 1000) / 10)}%${尾巴}`;
  }
  if (目标 === '额外行动回合') return `获得 ${数字(typeof 值?.系数 === 'number' ? 值.系数 : 0)} 个额外行动回合（当场可再行动一轮）`;
  // 量不是常数（比如「= 当前修正值」）→ 把源也写出来，玩家才知道翻倍从哪来
  if (值 && 值.源 !== '常数') return `${名} +${取值人话(值)}${尾巴}`;
  return `${名} ${增减(typeof 值?.系数 === 'number' ? 值.系数 : 0)}${尾巴}`;
}

/** 一个动作 → 人话 */
export function 动作人话(动作: 动作): string {
  switch (动作.类) {
    case '资源': {
      const 词 = 动作.操作 === '获得' ? '获得' : 动作.操作 === '恢复' ? '恢复' : 动作.操作 === '设为' ? '设为' : '消耗';
      const 衰减 = 动作.衰减 ? `（每回合衰减 ${取值人话(动作.衰减)}）` : '';
      // HP/MP/耐力 映射到真实血条/资源条（「血量归零时回满血」就是这么写的）
      const 是真值 = /^(HP|MP|耐力|当前HP|当前MP|当前耐力|HP_当前|MP_当前|耐力_当前)$/.test(动作.名);
      return `${词} ${取值人话(动作.量)} ${动作.名}${是真值 ? '（真实数值）' : ''}${衰减}`;
    }
    case '护盾':
      return `获得护盾 ${取值人话(动作.量)}`;
    case '数值修正':
      return 数值修正人话(String(动作.目标), 动作.量, 动作.持续);
    case '施加状态': {
      const 层 = 动作.层数 ? ` ×${取值人话(动作.层数)}层` : '';
      const 词条 = 动作.词条?.length ? `（词条：${动作.词条.join('、')}）` : '';
      return `施加状态「${动作.名}」${动作.持续}回合${层}${词条}`;
    }
    case '词条':
      return `${动作.操作 === '移除' ? '移除' : '附加'}词条「${动作.名}」`;
    case '领域':
      return `展开领域「${动作.名}」${动作.持续}回合${动作.范围 ? `（${动作.范围}）` : ''}`;
    case '切换形态':
      return `切换到形态「${动作.到}」`;
    case '追加攻击':
      return `追加攻击 ${动作.次数} 次`;
    case '范围伤害':
      return `对「${动作.中心}」半径 ${动作.半径} 米内造成 ${取值人话(动作.量)} 伤害`;
    case '条件分支': {
      const 条件 = 条件人话(动作.条件);
      const 真 = (动作.真 ?? []).map(动作人话).join('；') || '无';
      const 假 = (动作.假 ?? []).map(动作人话).join('；') || '无';
      return `若 ${条件} → ${真}；否则 ${假}`;
    }
    case '规则系判定':
      return `规则系「${动作.效果}」→ ${动作.目标}（需过规则系判定，未过则无效）`;
    default:
      return '（未知效果）';
  }
}

/**
 * 把一份战斗解释翻成**人话预览**。
 * 头部是元信息，行是"触发点 → 作用域：效果"，一条规则一行。
 */
export function 效果预览(解释: 战斗解释 | undefined): 效果预览 {
  if (!解释) return { 头部: [], 行: ['（没有可展示的效果）'] };

  const 行动 = 规范行动消耗(解释);
  const 倍率 = typeof 解释.伤害倍率 === 'number' && 解释.伤害倍率 > 0 ? `伤害 ×${解释.伤害倍率}` : '';
  const 头部 = [
    行动 ?? '非行动效果',
    解释.射程,
    解释.目标,
    解释.消耗 && 解释.消耗 !== '无' ? `消耗 ${解释.消耗}` : '',
    倍率,
    // 冷却对**行动**才有意义（免费行动也有冷却：玩家口径「冷却默认一个回合」；被动则无关）
    行动 ? `冷却 ${冷却回合数(解释)} 回合` : '',
  ].filter((s): s is string => !!s);

  const 行: string[] = [];
  const 规则列表 = (解释.规则 ?? []).filter(Boolean);
  if (规则列表.length) {
    for (const 规则 of 规则列表) {
      const 作用域 = 作用域人话[String(规则.作用域)] ?? String(规则.作用域);
      const 条件 = 条件人话(规则.条件);
      const 动作 = (规则.动作 ?? []).filter(Boolean).map(动作人话).join('；');
      行.push(`${规则.触发}${条件 ? `（${条件}）` : ''} → ${作用域}：${动作 || '（无动作）'}`);
    }
  } else if (倍率) {
    行.push(`${解释.关联属性 ?? ''}伤害 ×${解释.伤害倍率}（一次普通攻击，无额外效果）`);
  }

  for (const t of 解释.托管 ?? []) {
    if (t?.原文) 行.push(`托管（${(t.触发点 ?? []).join('/')}）：${t.原文}`);
  }

  if (!行.length) 行.push('（没有额外效果：纯粹的伤害/无效技能）');

  return { 头部, 行 };
}

/** 预览的**单行摘要**（下拉标签用不了多行；这里给 "免费行动 · 自身 · 无伤害" 这种） */
export function 预览摘要(解释: 战斗解释 | undefined): string {
  return 效果预览(解释).头部.join(' · ');
}
