import { rollDie } from './dice';
import { 属性修正值 } from './rules';
import type { 规则系效果 } from '../types';

/** 基础DC表（世界书原文） */
const 基础DC表: Record<string, number> = {
  一阶: 35,
  二阶: 140,
  三阶: 420,
  四阶: 980,
  五阶: 1925,
};

/** 类型系数表（世界书原文） */
const 类型系数表: Record<string, number> = {
  杂兵: 0.6,
  精英: 0.9,
  BOSS: 1.2,
  隐藏BOSS: 1.5,
  契约者: 1,
};

interface 单位 {
  属性: { 实际: { STR: number; AGI: number; CON: number; PER: number } };
  阶位: string;
  类型?: string;
}

/**
 * 规则系能力判定
 * 世界书原文：
 *   判定值 = 1d20 + 关联属性修正 + 技能等额外修正
 *   对抗目标 =（基础DC + 目标对应属性修正）× 类型系数 + 目标对应属性修正
 *
 * @param 效果 规则系效果（穿透/必中/必暴/即死/无敌/锁血/无视）
 * @param 攻击方 攻击方单位
 * @param 防御方 防御方单位
 * @param 攻击属性 攻击方用的属性（默认 STR）
 * @param 防御属性 防御方用的属性（默认 CON）
 */
export function 规则系判定(
  _效果: 规则系效果,
  攻击方: 单位,
  防御方: 单位,
  攻击属性: 'STR' | 'AGI' | 'CON' | 'PER' = 'STR',
  防御属性: 'STR' | 'AGI' | 'CON' | 'PER' = 'CON',
): {
  判定值: number;
  对抗目标: number;
  成功: boolean;
} {
  // 判定值 = 1d20 + 关联属性修正
  const 攻击修正 = 属性修正值(攻击方.属性.实际[攻击属性], 攻击方.阶位);
  const 判定值 = rollDie(20) + 攻击修正;

  // 对抗目标 =（基础DC + 目标对应属性修正）× 类型系数 + 目标对应属性修正
  const 基础DC = 基础DC表[防御方.阶位];
  if (基础DC === undefined) throw new Error(`未知阶位: ${防御方.阶位}`);

  const 防御修正 = 属性修正值(防御方.属性.实际[防御属性], 防御方.阶位);
  const 类型系数 = 类型系数表[防御方.类型 || '杂兵'] || 0.6;

  const 对抗目标 = (基础DC + 防御修正) * 类型系数 + 防御修正;

  return {
    判定值,
    对抗目标,
    成功: 判定值 >= 对抗目标,
  };
}

/**
 * 规则系对抗
 * 双方都过了判定 → 拼修正值，谁的修正高谁赢；修正相等 → 掷 1d2（1=攻击方，2=防御方）
 *
 * @param 攻击方 攻击方单位
 * @param 防御方 防御方单位
 * @param 攻击属性 攻击方用的属性
 * @param 防御属性 防御方用的属性
 * @param 攻击方过了 攻击方是否过了判定
 * @param 防御方过了 防御方是否过了判定
 */
export function 规则系对抗(
  攻击方: 单位,
  防御方: 单位,
  攻击属性: 'STR' | 'AGI' | 'CON' | 'PER',
  防御属性: 'STR' | 'AGI' | 'CON' | 'PER',
  攻击方过了: boolean,
  防御方过了: boolean,
): {
  赢家: '攻击方' | '防御方' | '无';
  骰值?: number;
} {
  // 都没过 → 正常结算
  if (!攻击方过了 && !防御方过了) {
    return { 赢家: '无' };
  }

  // 只有一方过 → 那一方赢
  if (攻击方过了 && !防御方过了) {
    return { 赢家: '攻击方' };
  }
  if (!攻击方过了 && 防御方过了) {
    return { 赢家: '防御方' };
  }

  // 都过了 → 拼修正值
  const 攻击修正 = 属性修正值(攻击方.属性.实际[攻击属性], 攻击方.阶位);
  const 防御修正 = 属性修正值(防御方.属性.实际[防御属性], 防御方.阶位);

  if (攻击修正 > 防御修正) {
    return { 赢家: '攻击方' };
  }
  if (防御修正 > 攻击修正) {
    return { 赢家: '防御方' };
  }

  // 修正相等 → 掷 1d2
  const 骰值 = rollDie(2);
  return {
    赢家: 骰值 === 1 ? '攻击方' : '防御方',
    骰值,
  };
}
