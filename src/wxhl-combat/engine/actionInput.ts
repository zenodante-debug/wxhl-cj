// ================================================================
// 无限回廊 · 前端战斗引擎 · 玩家行动槽 → 行动声明
// 纯函数：把玩家在同一回合里填的四个槽翻成引擎能吃的 行动声明[]
// ================================================================

import type { 行动声明 } from '../types';
import { 是基础攻击哨兵, 副武器攻击 } from './actionOptions';

/**
 * 一条行动填写：下拉值（技能名 或 基础攻击哨兵）+ **它自己的目标**。
 * 玩家口径（2026-10-09）：「应该每个行动都增加可选目标吧，现在是所有行动都是一个目标，
 * 而且，现在的免费行动无法选择目标。」—— 想"次要给自己上 buff、主要打敌人"就得各带各的。
 */
export interface 行动填写 {
  值: string;
  /** 这一条自己的目标；省略 → 用统一缺省目标 `行动槽填写.目标`（再没有就用调用方的兜底） */
  目标?: string;
  /**
   * 这一条为本次释放**选中的技能**（§5.4「选择目标技能」下拉）——
   * 只有 `actionOptions.需要选技能` 的技能（规则里写了 `技能作用.名 = '选中技能'`）才需要它。
   */
  选择技能?: string;
  /**
   * **释放来源**：这次攻击用哪把武器（主武器/副武器/徒手）—— 玩家实测：
   * 「技能释放来源没有"选武器/徒手"这一栏 —— 武器骰该算哪一把，现在没得选」。
   * 省略 = 主武器（老行为）。
   */
  武器来源?: '主武器' | '副武器' | '徒手';
  /**
   * **攻击部位**（第二步_部位锁定）—— 玩家口径：「行动释放时供玩家选择部位」。
   * 省略 = 用技能自己声明的，再没有 = 无部位加成。
   */
  部位?: '头部' | '臂部' | '腿部' | '眼部/核心';
}

/** 玩家在同一回合里填的四个槽。主要/次要/反应 存技能名；移动 存目标距离（米）。 */
export interface 行动槽填写 {
  /** 主要/次要：老形状（字符串，目标用统一缺省）或新形状（`{值, 目标}` 自带目标） */
  主要?: string | 行动填写;
  次要?: string | 行动填写;
  移动?: number;
  反应?: string;
  /**
   * 免费行动：**不限次数**（世界书：免费行动不占次数），每条可以**自带目标**。
   * 老形状 `['战吼']`（一串技能名）仍然认，目标落回统一缺省。
   */
  免费?: (string | 行动填写)[];
  /**
   * **统一缺省目标**：所有**没自带目标**的行动都用它（老形状，保持向后兼容）。
   * 每条行动都写了自己的目标时，这一项就不起作用了。
   */
  目标?: string;
  /**
   * 本回合的**行动顺序**（玩家自定）。元素写法：
   * `'主要'` / `'次要'` / `'移动'` / `'免费:<技能名>'`。
   *
   * 玩家口径：「我次要行动和免费行动都是上 buff，那总不能等我主要行动的大招放完了再上个寂寞吧？」
   * **省略 / 为空 → 用历史固定顺序**（主要 → 次要 → 免费 → 移动），旧调用零改动。
   * 顺序里漏掉的行动不会丢，只是排到最后。
   */
  行动顺序?: string[];
}

const 非空 = (s?: string): s is string => typeof s === 'string' && s.trim().length > 0;

/** 本回合的一个行动条目（顺序表的**唯一来源**：界面与引擎都读它，避免两边各推一遍键） */
export interface 行动条目信息 {
  /** 顺序表里引用的键：'主要' / '次要' / '移动' / `免费:<技能名>`（同名多条带 `#n`） */
  键: string;
  行动: 行动声明;
  /** 界面上显示的一行（'次要：上buff' / '移动 10 米'） */
  显示: string;
}

/**
 * 把这个单位本回合**已经填了的**行动列成有序条目（历史固定顺序：主要 → 次要 → 免费 → 移动）。
 * 界面用它的 `键`/`显示` 做 ↑↓ 排序，`构造行动声明` 用它做结算顺序 —— 同一份逻辑，不会走偏。
 *
 * @param 缺省目标 没写目标的行动用它（老形状的调用点传那个唯一的目标下拉值）
 */
export function 列行动条目(填写: 行动槽填写, 缺省目标: string): 行动条目信息[] {
  // 目标优先级：**条目自己的** > 统一缺省 `填写.目标` > 调用方传进来的兜底
  const 兜底 = (非空(填写.目标) ? String(填写.目标).trim() : '') || 缺省目标;

  /** 一个槽的取值 → `{ 值, 目标, 选择技能, 武器来源, 部位 }`；空 / 非法 → null（老形状的字符串照样认） */
  const 取值 = (
    原: string | 行动填写 | undefined,
  ): {
    值: string;
    目标: string;
    选择技能: string;
    武器来源?: '主武器' | '副武器' | '徒手';
    部位?: '头部' | '臂部' | '腿部' | '眼部/核心';
  } | null => {
    if (typeof 原 === 'string') return 非空(原) ? { 值: 原.trim(), 目标: 兜底, 选择技能: '' } : null;
    if (!原 || typeof 原 !== 'object' || !非空(原.值)) return null;
    return {
      值: String(原.值).trim(),
      目标: 非空(原.目标) ? String(原.目标).trim() : 兜底,
      选择技能: 非空(原.选择技能) ? String(原.选择技能).trim() : '',
      ...(原.武器来源 ? { 武器来源: 原.武器来源 } : {}),
      ...(原.部位 ? { 部位: 原.部位 } : {}),
    };
  };

  /**
   * 一个槽的取值 → 一条行动声明。
   * 基础武器攻击在下拉里是一个**哨兵串**（`（主武器攻击）`），这里翻成 `{ 武器 }`
   * —— 引擎里"基础攻击"= 省略技能键 + 指定用哪把武器。
   */
  const 翻 = (
    类型: '主要行动' | '次要行动' | '免费行动',
    值: string,
    目标: string,
    选择技能 = '',
    武器来源?: '主武器' | '副武器' | '徒手',
    部位?: '头部' | '臂部' | '腿部' | '眼部/核心',
  ): 行动声明 => {
    const 附带 = {
      ...(选择技能 ? { 选择技能 } : {}),
      ...(武器来源 ? { 武器来源 } : {}),
      ...(部位 ? { 部位 } : {}),
    };
    return 是基础攻击哨兵(值)
      ? { 类型, 武器: 值 === 副武器攻击 ? '副武器' : '主武器', 目标, ...附带 }
      : { 类型, 技能: 值, 目标, ...附带 };
  };

  /**
   * 显示行：**只有这一条自己带了目标**才写「→ X」。
   * 落回统一缺省目标的行动不写 —— 那是这个单位的默认目标，每行都重复一遍只是噪音
   *（而且老形状的显示行因此一个字都没变）。
   */
  const 一行 = (前缀: string, 原: string | 行动填写 | undefined, 值: string): string => {
    const 自带 = typeof 原 === 'string' ? '' : String(原?.目标 ?? '').trim();
    return `${前缀}：${值}${自带 ? ` → ${自带}` : ''}`;
  };

  // 用数组而不是 Map：同一个免费技能勾两次也不能被吞成一条（第二次的键带 `#n` 后缀）
  const 条目: 行动条目信息[] = [];
  const 已用 = new Map<string, number>();
  const 取键 = (基: string): string => {
    const n = (已用.get(基) ?? 0) + 1;
    已用.set(基, n);
    return n === 1 ? 基 : `${基}#${n}`;
  };

  const 主要 = 取值(填写.主要);
  if (主要) {
    条目.push({
      键: '主要',
      行动: 翻('主要行动', 主要.值, 主要.目标, 主要.选择技能, 主要.武器来源, 主要.部位),
      显示: 一行('主要', 填写.主要, 主要.值),
    });
  }
  const 次要 = 取值(填写.次要);
  if (次要) {
    条目.push({
      键: '次要',
      行动: 翻('次要行动', 次要.值, 次要.目标, 次要.选择技能, 次要.武器来源, 次要.部位),
      显示: 一行('次要', 填写.次要, 次要.值),
    });
  }
  for (const 原 of 填写.免费 ?? []) {
    const 条 = 取值(原);
    if (!条) continue;
    条目.push({
      键: 取键(`免费:${条.值}`),
      行动: 翻('免费行动', 条.值, 条.目标, 条.选择技能, 条.武器来源, 条.部位),
      显示: 一行('免费', 原, 条.值),
    });
  }
  // 目标距离**可以是负数**（向后移动 / 撤到玩家身后）；0 也照发，
  // 由 `结算移动` 判定"和当前位置一样 = 原地不动，不扣槽"（玩家反馈：负数选不了）。
  if (typeof 填写.移动 === 'number' && Number.isFinite(填写.移动)) {
    条目.push({ 键: '移动', 行动: { 类型: '移动', 距离: 填写.移动 }, 显示: `移动 ${填写.移动} 米` });
  }

  return 条目;
}

/**
 * 把行动槽填写翻成引擎能吃的 行动声明[]，**按玩家指定的顺序**（`行动顺序`）。
 * `反应` 不进本轮行动 —— 它是给待决点用的预置（spec §9.2「关键点暂停」）。
 * 顺序里漏掉的行动不丢，只是排到最后。
 */
export function 构造行动声明(
  填写: 行动槽填写,
  目标: string,
): { 行动: 行动声明[]; 预置反应?: string; 条目: 行动条目信息[] } {
  const 全部 = 列行动条目(填写, 目标);

  const 想要 = (填写.行动顺序 ?? []).map(k => String(k).trim()).filter(Boolean);
  const 已排: 行动条目信息[] = [];
  for (const 键 of 想要) {
    const 命中 = 全部.find(x => x.键 === 键 && !已排.includes(x));
    if (命中) 已排.push(命中);
  }
  const 顺序 = 已排.length ? [...已排, ...全部.filter(x => !已排.includes(x))] : 全部;

  return {
    行动: 顺序.map(x => x.行动),
    条目: 顺序,
    预置反应: 非空(填写.反应) ? 填写.反应.trim() : undefined,
  };
}

/** 能不能点「执行本轮」：至少要真的出手一次（只预置反应不算）。 */
export function 可提交(填写: 行动槽填写): boolean {
  return 构造行动声明(填写, '').行动.length > 0;
}
