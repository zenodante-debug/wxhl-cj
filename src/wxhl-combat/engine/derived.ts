// ================================================================
// 无限回廊 · 前端战斗引擎 · 衍生属性代算（移植自小手机状态栏）
//
// 为什么战斗脚本必须自己算：HP_最大 / 防御 / 闪避值 / 移动距离 / 属性.实际 这些**衍生值**
// 是"小手机"状态栏在 `VARIABLE_UPDATE_ENDED` 上算出来落盘的。战斗脚本不内置这套计算，
// 于是：**玩家只要不开一次小手机，代算就不发生** —— 战斗里读到的是过期甚至为 0 的防御/闪避，
// 而 AI 刚把 属性.基础 写得很高，两下就对不上（实战反馈：命中 DC 473、混合伤害 93133、HP 却只有 6690）。
//
// 移植范围（刻意只做战斗需要的那部分）：四维加成扫描 → 属性.实际 → HP/MP/耐力上限 →
// 防御/闪避/移动距离/负重 → 当前值钳制 → 生命状态。
// **不碰** 等级/EXP/PEXP/RP/军衔 —— 那些是角色成长，属于小手机的职责，战斗脚本不该改。
//
// 位阶系数统一用 `rules.属性修正值`（与引擎其它地方同一张表），避免两套口径漂移。
import { 归一阶位 as 共享归一阶位, 是超脱 } from './rules';
// ⚠️ 小手机的阶位系数表把「超脱」当 **16**，本引擎与世界书一致当 **20**
//（玩家裁决 2026-10-08：「超脱的修正系数是 20」，并统一 超脱/超脱阶/超脱者 三种写法）。
// 只有超脱阶会受影响 —— 面板可能与战斗结算差一档，以本引擎为准。
// ================================================================

import { 属性修正值 } from './rules';

/**
 * 阶位归一。
 * 小手机的系数表认「超脱者」，本引擎 `属性修正值` 认「超脱」；两边都认不出来时按一阶兜底
 * —— 代算是"面板维护"，绝不能因为一个错别字抛错把整个开战流程炸掉
 * （`属性修正值` 本身对未知阶位是抛错，那是战斗结算层的设计，这里不沿用）。
 */
function 归一阶位(阶位: string): string {
  // 超脱的三种写法（超脱 / 超脱阶 / 超脱者）统一由 engine/rules 归一，这里只管兜底
  const 文 = 共享归一阶位(阶位);
  if (是超脱(文)) return '超脱';
  if (文 === '二阶' || 文 === '三阶' || 文 === '四阶' || 文 === '五阶') return 文;
  return '一阶';
}

/** 实体类型 → HP 系数（世界书：隐藏BOSS 25 / BOSS 20 / 精英 10 / 杂兵 8 / 其它 15） */
function hp系数(实体: any): number {
  const t = String(取(实体, '类型', ''));
  if (t.includes('隐藏BOSS') || t.includes('隐藏boss')) return 25;
  if (t.includes('BOSS') || t.includes('boss')) return 20;
  if (t.includes('精英')) return 10;
  if (t.includes('杂兵')) return 8;
  return 15;
}

/** 玩家模式（有成长/软上限）还是敌人模式：杂兵/精英/BOSS 是敌人 */
function 是玩家模式(实体: any): boolean {
  const t = String(取(实体, '类型', ''));
  return !(t.includes('杂兵') || t.includes('精英') || t.includes('BOSS') || t.includes('boss'));
}

/** 阶位 → 属性软上限（世界书：一阶 25 / 二阶 40 / 三阶 55 / 四阶 70 / 五阶与超脱不限） */
function 属性软上限(阶位: string): number {
  if (阶位 === '二阶') return 40;
  if (阶位 === '三阶') return 55;
  if (阶位 === '四阶') return 70;
  if (阶位 === '五阶' || 是超脱(阶位)) return 9999;
  return 25;
}

/** 路径取值/赋值（点分路径；schema 里没有带点的键，除了容器路径由调用方拼好） */
function 取(obj: any, 路径: string, 兜底?: any): any {
  let 节点 = obj;
  for (const 段 of 路径.split('.')) {
    if (节点 === null || 节点 === undefined) return 兜底;
    节点 = 节点[段];
  }
  return 节点 === undefined ? 兜底 : 节点;
}

function 放(obj: any, 路径: string, 值: any): void {
  const 段 = 路径.split('.');
  let 节点 = obj;
  for (let i = 0; i < 段.length - 1; i++) {
    if (节点[段[i]] === null || typeof 节点[段[i]] !== 'object') 节点[段[i]] = {};
    节点 = 节点[段[i]];
  }
  节点[段[段.length - 1]] = 值;
}

/** 从「属性加成」字符串里抠数值：支持「全属性+N / 力量+N / AGI+2 / 敏捷 3」 */
function 解析属性加成(文本: string): Record<string, number> {
  const 结果: Record<string, number> = { STR: 0, AGI: 0, CON: 0, PER: 0 };
  const 串 = String(文本 ?? '');
  const 全 = 串.match(/全属性\s*[+加]?\s*(\d+)/);
  if (全) {
    const v = parseInt(全[1]) || 0;
    结果.STR += v;
    结果.AGI += v;
    结果.CON += v;
    结果.PER += v;
  }
  const 表: [string, string[]][] = [
    ['STR', ['力量', 'STR']],
    ['AGI', ['敏捷', 'AGI']],
    ['CON', ['体质', '体力', 'CON']],
    ['PER', ['感知', 'PER']],
  ];
  for (const [键, 别名] of 表) {
    for (const 名 of 别名) {
      const m = 串.match(new RegExp(`(?:${名})\\s*[+加]?\\s*(\\d+)`, 'i'));
      if (m) {
        结果[键] += parseInt(m[1]) || 0;
      }
    }
  }
  return 结果;
}

/**
 * 重算一个实体的衍生属性（就地改 `stat_data`）。
 * @param stat_data MVU 的 stat_data
 * @param 路径 实体路径，如 '契约者' / '契约者.副本角色.骨卫兵'
 * 幂等：算一遍和算两遍结果一样。**调用方负责写回 MVU**。
 */
export function 重算实体衍生属性(stat_data: any, 路径: string): void {
  const 实体 = 取(stat_data, 路径);
  if (!实体 || typeof 实体 !== 'object') return;

  const 玩家 = 是玩家模式(实体);
  const 系数 = hp系数(实体);
  const 阶位 = 归一阶位(String(取(实体, '头部.阶位', '一阶')));
  const 软上限 = 属性软上限(阶位);

  // ---------- 装备扫描：属性加成 / 装备防御 / 装备闪避 / 负重 ----------
  const 属性加成: Record<string, number> = { STR: 0, AGI: 0, CON: 0, PER: 0 };
  let 装备防御 = 0;
  let 装备闪避 = 0;
  let 装备负重 = 0;
  for (const 槽 of ['头部', '躯干', '手部', '下装', '饰品', '主武器', '副武器']) {
    const 装 = 取(实体, `装备.${槽}`, {});
    const 主属 = 取(装, '主属性', '');
    const 副属 = 取(装, '副属性', '');
    if (属性加成[主属] !== undefined) 属性加成[主属] += Number(取(装, '主属性加成', 0)) || 0;
    if (属性加成[副属] !== undefined) 属性加成[副属] += Number(取(装, '副属性加成', 0)) || 0;
    // 强化等级只给非武器非饰品当防御（世界书口径，照抄状态栏）
    if (槽 !== '主武器' && 槽 !== '副武器' && 槽 !== '饰品') {
      装备防御 += Number(取(装, '强化等级', 0)) || 0;
    }
    装备防御 += Number(取(装, '装备防御', 0)) || 0;
    装备闪避 += Number(取(装, '装备闪避', 0)) || 0;
    装备负重 += Number(取(装, '负重', 0)) || 0;
  }

  // ---------- 职业 / 天赋 / 血统 加成 ----------
  const 职业加成: Record<string, number> = { STR: 0, AGI: 0, CON: 0, PER: 0 };
  const 职主 = 取(实体, '职业.主属性加成.属性', '');
  const 职副 = 取(实体, '职业.副属性加成.属性', '');
  if (职业加成[职主] !== undefined) 职业加成[职主] += Number(取(实体, '职业.主属性加成.值', 0)) || 0;
  if (职业加成[职副] !== undefined) 职业加成[职副] += Number(取(实体, '职业.副属性加成.值', 0)) || 0;

  const 天赋加成 = 解析属性加成(取(实体, '头部.天赋.属性加成', ''));
  const 血统加成 = 解析属性加成(取(实体, '头部.血统.属性加成', ''));

  // ---------- 四维：基础（玩家模式吃软上限）→ 加成 → 实际 ----------
  for (const 键 of ['STR', 'AGI', 'CON', 'PER']) {
    let 基础 = Number(取(实体, `属性.基础.${键}`, 5)) || 5;
    if (玩家 && 基础 > 软上限) {
      基础 = 软上限;
      放(实体, `属性.基础.${键}`, 基础);
    }
    const 自定义 = Number(取(实体, `属性.自定义加成.${键}`, 0)) || 0;
    const 加成 = 属性加成[键] + 职业加成[键] + 天赋加成[键] + 血统加成[键] + 自定义;
    放(实体, `属性.加成.${键}`, 加成);
    放(实体, `属性.实际.${键}`, 基础 + 加成);
  }

  const 实际 = {
    STR: Number(取(实体, '属性.实际.STR', 5)) || 5,
    AGI: Number(取(实体, '属性.实际.AGI', 5)) || 5,
    CON: Number(取(实体, '属性.实际.CON', 5)) || 5,
    PER: Number(取(实体, '属性.实际.PER', 5)) || 5,
  };
  const 修正 = {
    STR: 属性修正值(实际.STR, 阶位),
    AGI: 属性修正值(实际.AGI, 阶位),
    CON: 属性修正值(实际.CON, 阶位),
    PER: 属性修正值(实际.PER, 阶位),
  };
  放(实体, '属性.属性修正值', { ...修正 });

  // ---------- 上限（额外加成 + 装备） ----------
  const 额外 = (键: string) => Number(取(实体, `衍生属性.${键}额外加成`, 0)) || 0;
  const 旧最大 = {
    HP: Number(取(实体, '衍生属性.HP_最大', 0)) || 0,
    MP: Number(取(实体, '衍生属性.MP_最大', 0)) || 0,
    耐力: Number(取(实体, '衍生属性.耐力_最大', 0)) || 0,
  };

  const HP最大 = (修正.CON + 5) * 系数 + 额外('HP');
  const MP最大 = 修正.PER * 10 + 额外('MP');
  const 耐力最大 = (修正.CON + 5) * 10 + 额外('耐力');
  放(实体, '衍生属性.HP_最大', HP最大);
  放(实体, '衍生属性.MP_最大', MP最大);
  放(实体, '衍生属性.耐力_最大', 耐力最大);

  const 防御 = Math.floor((修正.CON + 5) * 0.2) + 额外('防御') + 装备防御;
  const 闪避值 = Math.floor(10 + 修正.AGI * 0.5 + 额外('闪避') + 装备闪避);
  const 移动距离 = 5 + 修正.AGI + 额外('移动距离');
  放(实体, '衍生属性.防御', 防御);
  放(实体, '衍生属性.闪避值', 闪避值);
  放(实体, '衍生属性.移动距离', 移动距离);
  放(实体, '衍生属性.负重_上限', 实际.STR * 5 + 额外('负重'));
  放(实体, '衍生属性.负重_当前', 装备负重);

  // ---------- 当前值：首次初始化 / 上限变大时补齐，再钳制 ----------
  let HP当前 = Number(取(实体, '衍生属性.HP_当前', 0)) || 0;
  let MP当前 = Number(取(实体, '衍生属性.MP_当前', 0)) || 0;
  let 耐力当前 = Number(取(实体, '衍生属性.耐力_当前', 0)) || 0;

  if (旧最大.HP === 0 && HP最大 > 0) HP当前 = HP最大;
  if (旧最大.MP === 0 && MP最大 > 0) MP当前 = MP最大;
  if (旧最大.耐力 === 0 && 耐力最大 > 0) 耐力当前 = 耐力最大;
  if (HP最大 > 旧最大.HP && 旧最大.HP > 0) HP当前 += HP最大 - 旧最大.HP;
  if (MP最大 > 旧最大.MP && 旧最大.MP > 0) MP当前 += MP最大 - 旧最大.MP;
  if (耐力最大 > 旧最大.耐力 && 旧最大.耐力 > 0) 耐力当前 += 耐力最大 - 旧最大.耐力;

  HP当前 = Math.min(HP当前, HP最大);
  MP当前 = Math.min(MP当前, MP最大);
  耐力当前 = Math.min(耐力当前, 耐力最大);

  放(实体, '衍生属性.HP_当前', HP当前);
  放(实体, '衍生属性.MP_当前', MP当前);
  放(实体, '衍生属性.耐力_当前', 耐力当前);

  // ---------- 生命状态（阶段A 的惩罚按它分层） ----------
  const 比例 = HP当前 / Math.max(HP最大, 1);
  const 生命状态 = HP当前 <= 0 ? '濒死' : 比例 <= 0.3 ? '重伤' : 比例 <= 0.7 ? '受伤' : '健康';
  放(实体, '状态.生命状态', 生命状态);
}

/**
 * 重算 stat_data 里所有实体的衍生属性（契约者本体 + 小队成员 + 其他契约者 + 副本角色）。
 */
export function 重算全部实体(stat_data: any): void {
  if (!stat_data?.契约者) return;
  重算实体衍生属性(stat_data, '契约者');
  for (const 容器 of ['小队.成员', '其他契约者', '副本角色']) {
    const 组 = 取(stat_data, `契约者.${容器}`, {});
    for (const 名 of Object.keys(组 ?? {})) {
      重算实体衍生属性(stat_data, `契约者.${容器}.${名}`);
    }
  }
}
