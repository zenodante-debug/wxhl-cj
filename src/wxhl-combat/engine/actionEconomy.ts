import type { 行动槽 } from '../types';

/**
 * 回合开始重置行动槽
 * 世界书原文：每回合含主要行动、次要行动、移动、反应动作各一次，免费行动不受次数限制
 */
export function 行动槽重置(槽: 行动槽): 行动槽 {
  return {
    主要: 1,
    次要: 1,
    移动: 1,
    反应: 1,
    免费: 槽.免费, // 免费行动不重置
  };
}

/**
 * 行动槽消耗
 * 使用技能按它的行动类型扣 1（免费行动不扣）
 */
export function 行动槽消耗(槽: 行动槽, 行动类型: string): 行动槽 {
  const 新槽 = { ...槽 };

  switch (行动类型) {
    case '主要行动':
      if (新槽.主要 <= 0) throw new Error('行动槽不足: 主要行动');
      新槽.主要 -= 1;
      break;
    case '次要行动':
      if (新槽.次要 <= 0) throw new Error('行动槽不足: 次要行动');
      新槽.次要 -= 1;
      break;
    case '移动':
      if (新槽.移动 <= 0) throw new Error('行动槽不足: 移动');
      新槽.移动 -= 1;
      break;
    case '反应动作':
      if (新槽.反应 <= 0) throw new Error('行动槽不足: 反应动作');
      新槽.反应 -= 1;
      break;
    case '免费行动':
      // 免费行动不扣
      break;
    default:
      throw new Error(`未知行动类型: ${行动类型}`);
  }

  return 新槽;
}
