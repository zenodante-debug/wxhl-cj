import type { 战斗状态, 战斗事件, 结算步骤, 战斗单位 } from '../types';
import { 属性修正值, 宽容属性修正值 } from './rules';
import { 状态递减 } from './status';
import { rollDie } from './dice';

/**
 * 持续伤害比例表（spec §9.3 阶段F）。
 * 世界书原文：灼烧「每回合-5%最大HP，受火系攻击叠1层（最多3层，每层+5%）」；
 * 中毒「每回合-3%最大HP，可叠3层（每层+3%）」—— **按层数放大**。
 * 单层基准值向下取整后逐状态累加。
 */
const 持续伤害比例表: Record<string, number> = {
  灼烧: 0.05,
  流血: 0.04,
  撕裂: 0.04,
  中毒: 0.03,
  腐蚀: 0.03,
};

/** 濒死 CON 检定 DC（spec 附录 B.6：濒死 0 → 每回合 CON 判定 DC12） */
const 濒死DC = 12;

/** 每回合进入濒死的成功/失败上限（spec 附录 B.6：2 次成功稳定、3 次失败死亡） */
const 濒死成功上限 = 2;
const 濒死失败上限 = 3;

/**
 * 阶段F 结算：回合结束 —— 持续伤害 + 状态递减/清理。
 * 纯函数：不改动入参，返回扣减总量与结算后的新单位。
 * @param 单位 待结算单位
 * @param 最大HP 持续伤害的百分比基数（通常 = 单位.HP_最大）
 */
export function 阶段F结算(单位: 战斗单位, 最大HP: number): { HP扣减: number; 新状态: 战斗单位 } {
  let HP扣减 = 0;
  for (const 状态 of 单位.状态) {
    const 比例 = 持续伤害比例表[状态.名];
    if (比例 === undefined) continue;
    // 世界书：灼烧/中毒等可叠层状态「每层+5%/每层+3%」—— 按层数放大（无层数字段按 1 层）
    HP扣减 += Math.floor(最大HP * 比例 * (状态.层数 ?? 1));
  }

  return {
    HP扣减,
    新状态: 标记濒死({
      ...单位,
      HP_当前: Math.max(单位.HP_当前 - HP扣减, 0),
      状态: 状态递减(单位.状态),
    }),
  };
}

/**
 * 冷却递减（回合开始时调，与行动槽重置同处）。
 * 语义：`冷却N` = **距下次可用还有 N 回合** —— 第 R 回合用过之后，第 R+N 回合才能再用。
 * 到 0 的条目直接删掉（不留下 `技能: 0` 的垃圾键）。
 */
export function 冷却递减(单位: 战斗单位): 战斗单位 {
  const 新: Record<string, number> = {};
  for (const [名, 剩余] of Object.entries(单位.冷却 ?? {})) {
    if (剩余 > 1) 新[名] = 剩余 - 1;
  }
  return { ...单位, 冷却: 新 };
}

/**
 * 阶段A 资源恢复：耐力 +CON修正；MP +PER修正×0.5（向上取整）。均封顶到上限。
 * 纯函数：返回新单位。
 */
export function 阶段A资源恢复(单位: 战斗单位): 战斗单位 {
  const CON修正 = Math.max(属性修正值(单位.属性.实际.CON, 单位.阶位), 0);
  const PER修正 = Math.max(属性修正值(单位.属性.实际.PER, 单位.阶位), 0);
  const MP恢复 = Math.ceil(PER修正 * 0.5);

  return {
    ...单位,
    耐力_当前: Math.min(单位.耐力_当前 + CON修正, 单位.耐力_最大),
    MP_当前: Math.min(单位.MP_当前 + MP恢复, 单位.MP_最大),
  };
}

/**
 * 阶段D 转阶段判定：BOSS/隐藏BOSS 当前 HP **首次**跌破阶段阈值（70%/40%/20%）时触发。
 * 只认「变化前在阈值之上、变化后到阈值之下」这一跨线瞬间；已在阈值之下不重复触发。
 * 单次伤害跨多条线时返回**最深**（比例最小）的那条 —— 状态上 boss 直接落到最深阶段，
 * 一次转阶段只发一次必杀，避免单次伤害连甩三个必杀（裁决 R13a-3）。
 * @returns 待决点；非 BOSS 或未跨线返回 null
 */
export function 判定转阶段(
  单位: 战斗单位,
  变化前HP: number,
  变化后HP: number,
): { 阈值: string } | null {
  // 转阶段是 **BOSS 的机制**（世界书 <combat_driver> 阶段D：BOSS/隐藏BOSS 专属）。
  if (!单位.类型.toUpperCase().includes('BOSS')) return null;

  // 阈值表：从高到低遍历，最后一次命中的即**最深**那条（一次跨多条只转最深的一档）
  const 阈值表: [number, string][] = [
    [0.7, '70%'],
    [0.4, '40%'],
    [0.2, '20%'],
  ];
  let 命中: { 阈值: string } | null = null;
  for (const [比例, 标签] of 阈值表) {
    const 线 = 单位.HP_最大 * 比例;
    if (变化前HP > 线 && 变化后HP <= 线) 命中 = { 阈值: 标签 };
  }

  // 被打到 0 也算一条阈值（玩家口径：「boss 会有转阶段的能力，比如濒死了回满血」）——
  // 这一条让"回满血"成为有限次的阶段机制，而不是回合开始回血那种"永远杀不死"。
  if (变化前HP > 0 && 变化后HP <= 0) 命中 = { 阈值: '濒死' };
  return 命中;
}

/**
 * 阶段F 濒死判定：HP 归零后每回合 CON 检定 DC12（1d20 + CON修正）。
 * 2 次成功 → 稳定（清空濒死）；3 次失败 → 死亡（保留计数，濒死非空）。
 * 纯函数：返回新单位与结果。
 * @param 掷骰 本次 CON 检定的 d20 点数；缺省时现场掷骰（测试可注入确定值）
 */
export function 濒死判定(
  单位: 战斗单位,
  掷骰: number = rollDie(20),
): { 单位: 战斗单位; 结果: '稳定' | '死亡' | '濒死' } {
  const 当前 = 单位.濒死 ?? { 成功: 0, 失败: 0 };
  const CON修正 = 宽容属性修正值(单位.属性.实际.CON, 单位.阶位);
  const 成功 = 掷骰 + CON修正 >= 濒死DC;

  const 计数 = 成功
    ? { 成功: 当前.成功 + 1, 失败: 当前.失败 }
    : { 成功: 当前.成功, 失败: 当前.失败 + 1 };

  if (计数.失败 >= 濒死失败上限) {
    return { 单位: { ...单位, 濒死: 计数 }, 结果: '死亡' };
  }
  if (计数.成功 >= 濒死成功上限) {
    return { 单位: { ...单位, 濒死: null }, 结果: '稳定' };
  }
  return { 单位: { ...单位, 濒死: 计数 }, 结果: '濒死' };
}

/**
 * 回合状态机：(状态, 事件) → { 新状态, 结算步骤[] }
 *
 * 状态机停下来等玩家的四个地方（待决点）：
 * - 打断（阶段B1b）
 * - 防御（阶段B2）
 * - 转阶段（阶段D）
 * - 濒死（阶段F）
 */
export function 推进(状态: 战斗状态, 事件: 战斗事件): {
  状态: 战斗状态;
  步骤: 结算步骤[];
} {
  const 步骤: 结算步骤[] = [];

  switch (事件.类) {
    case '开始回合': {
      return {
        状态: {
          ...状态,
          回合: 状态.回合 + 1,
          待决: null,
        },
        步骤,
      };
    }

    case '进入单位':
    case '声明行动':
    case '玩家决策':
    case '结束回合': {
      // TODO: 后续实现
      return { 状态, 步骤 };
    }
  }
}

// ==================== 生死判定（世界书原文） ====================
//
//   健康 >70%：无惩罚。  受伤 30~70%：剧烈动作劣势。
//   重伤 1~30%：STR/AGI 劣势、移动减半。
//   濒死 0：每回合 CON 判定 DC12，2 次成功稳定 / 3 次失败死亡。
//   生死界限：HP 归零即进入濒死判定。失败达三次即宣告抹杀。
//
// **HP 归零 ≠ 死亡**。这里把三种"倒下"的状态分清，胜负判定只看它们：
// - 濒死：HP ≤ 0 且还在检定中（濒死 非空、失败 < 3）
// - 死亡：濒死检定失败达 3 次（抹杀）
// - 稳定：检定 2 次成功，脱离濒死 —— 仍昏迷在 0 HP，但不能行动
// 三者在战场上**都不能行动**（`结算行动` 的存活守卫按 HP ≤ 0 拦）。

/** 战场显示名（引擎里多处同名逻辑，这里本地一份，避免循环依赖） */
function 名(单位: 战斗单位): string {
  return 单位.名称 || 单位.id.split('.').pop() || 单位.id;
}

/** 该单位是否已死亡（HP 归零 + 濒死检定三次失败） */
export function 已死亡(单位: 战斗单位): boolean {
  if (单位.HP_当前 > 0) return false;
  // 副本角色没有濒死检定：HP 归零即死透；契约者要濒死检定连续失败才算死亡
  if (!是契约者(单位)) return true;
  return (单位.濒死?.失败 ?? 0) >= 濒死失败上限;
}

/** 该单位是否已稳定（两次成功脱离濒死；仍昏迷在 0 HP） */
export function 已稳定(单位: 战斗单位): boolean {
  return 单位.HP_当前 <= 0 && 单位.濒死 === null;
}

/** 本回合能否行动（HP > 0）—— 濒死/稳定/死亡都不能 */
export function 能行动(单位: 战斗单位): boolean {
  return 单位.HP_当前 > 0;
}

/**
 * **是不是契约者** —— 玩家 / 小队成员（队友）/ 其他契约者（敌对的契约者）都算。
 * 判定看两条：类型写明了（玩家/小队成员/契约者/固有角色），或变量路径属于契约者一族
 * （`契约者` / `小队.*` / `其他契约者.*`）。副本角色（无论类型写杂兵/精英/BOSS）都不算。
 */
export function 是契约者(单位: 战斗单位): boolean {
  const t = String(单位.类型 ?? '');
  if (/玩家|小队成员|契约者|固有角色/.test(t)) return true;
  const id = String(单位.id ?? '');
  return id === '契约者' || id.startsWith('小队.') || id.startsWith('其他契约者.');
}

/**
 * HP 归零时打上濒死标记（首次进入）。**不覆盖**已有的计数。
 *
 * 玩家裁决：「濒死检定是契约者的特权」——
 * **副本角色 HP 归零 = 直接死亡**，不打濒死标记、不做濒死检定；
 * 只有契约者（玩家/队友/其他契约者）HP 归零才进入濒死，每回合 CON DC12。
 */
export function 标记濒死(单位: 战斗单位): 战斗单位 {
  if (单位.HP_当前 > 0 || 单位.濒死) return 单位;
  if (!是契约者(单位)) return 单位; // 副本角色没有濒死，HP 0 = 死透
  return { ...单位, 濒死: { 成功: 0, 失败: 0 } };
}

/**
 * 濒死单位的**每回合** CON 检定（阶段A「生命状态检查」里做）。
 * @returns 需要检定时返回新单位与日志；不需要（HP>0 / 已稳定 / 已死亡）返回 null
 */
export function 濒死检定一轮(
  单位: 战斗单位,
  掷骰: number = rollDie(20),
): { 单位: 战斗单位; 结果: '稳定' | '死亡' | '濒死'; 文本: string } | null {
  if (单位.HP_当前 > 0) return null; // 没倒下
  if (!是契约者(单位)) return null; // 副本角色没有濒死检定（HP 0 = 死透）
  if (单位.濒死 === null) return null; // 已稳定，不再检定
  if (已死亡(单位)) return null; // 已经抹杀，不再检定

  const CON修正 = 宽容属性修正值(单位.属性.实际.CON, 单位.阶位);
  const { 单位: 新单位, 结果 } = 濒死判定(单位, 掷骰);
  const 计数 = 新单位.濒死 ?? { 成功: 濒死成功上限, 失败: 0 };
  const 骰式 = `${掷骰}${CON修正 >= 0 ? '+' : ''}${CON修正}`;

  const 文本 =
    结果 === '死亡'
      ? `「${名(单位)}」濒死检定 ${骰式} < DC${濒死DC} → 第 ${濒死失败上限} 次失败，**死亡**`
      : 结果 === '稳定'
        ? `「${名(单位)}」濒死检定 ${骰式} ≥ DC${濒死DC} → 第 ${濒死成功上限} 次成功，脱离了濒死（仍昏迷）`
        : `「${名(单位)}」濒死检定 ${骰式} ${掷骰 + CON修正 >= 濒死DC ? '≥' : '<'} DC${濒死DC}（成功 ${计数.成功}/${濒死成功上限}，失败 ${计数.失败}/${濒死失败上限}）`;

  return { 单位: 新单位, 结果, 文本 };
}

/**
 * 把倒下的单位的濒死检定**一次算到底**（连着掷，直到"稳定"或"死亡"）。
 *
 * 用在"这仗已经打不下去"的时候 —— 关键是**我方全员倒地**时：
 * 玩家反馈「所有友方失去了行动能力，那就直接结束战斗啊，为什么还得一直推进回合调用 AI，太浪费了」。
 * 所以不再空转回合（每回合还要调一次 AI 生成敌方意图），直接把生死判完。
 *
 * @param 最大次数 保险丝：极端情况下（一直掷不出结果）也不至于死循环
 */
export function 濒死结算到底(
  单位: 战斗单位,
  最大次数 = 10,
): { 单位: 战斗单位; 日志: string[] } {
  const 日志: string[] = [];
  let 当前 = 单位;

  for (let i = 0; i < 最大次数; i++) {
    const r = 濒死检定一轮(当前);
    if (!r) break; // 没在濒死（HP>0 / 已稳定 / 已死亡）
    当前 = r.单位;
    日志.push(r.文本);
    if (r.结果 !== '濒死') break; // 稳定 或 死亡，出结果了
  }

  return { 单位: 当前, 日志 };
}

/**
 * 战局判定（结算一轮之后调用）。
 * - **胜利**：敌方全部不能行动（HP ≤ 0 —— 濒死/稳定/死亡都算不能行动）
 * - **败北**：我方全部**已死亡**（濒死检定三次失败）；或我方全员倒下且**没人在濒死检定中**
 *   （全稳定 = 全员昏迷，这仗打不下去了）
 * - **null**：继续打（比如只有契约者倒下、队友还在）
 *
 * 关键：**玩家 HP 归零不再直接判败北** —— 世界书里那是进入濒死检定，
 * 要连续三次失败才算抹杀（实战反馈：一归零就出战败结算，是这里写错了）。
 */
export function 判定战局(状态: 战斗状态): '胜利' | '败北' | null {
  const 单位列表 = Object.values(状态.单位);
  const 我方 = 单位列表.filter(u => u.阵营 === '我方');
  const 敌方 = 单位列表.filter(u => u.阵营 === '敌方');
  if (我方.length === 0 || 敌方.length === 0) return null;

  if (敌方.every(u => !能行动(u))) return '胜利';
  if (我方.every(已死亡)) return '败北';

  const 还在濒死检定 = 我方.some(u => u.HP_当前 <= 0 && u.濒死 !== null && !已死亡(u));
  if (我方.every(u => !能行动(u)) && !还在濒死检定) return '败北';

  return null;
}
