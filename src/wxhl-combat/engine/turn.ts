import type { 战斗状态, 战斗事件, 结算步骤 } from '../types';

/**
 * 回合状态机：(状态, 事件) → { 新状态, 结算步骤[] }
 *
 * 状态机停下来等玩家的四个地方（待决点）：
 * - 打断（阶段B1b）
 * - 防御（阶段B2）
 * - 转阶段（阶段D）
 * - 濒死（阶段F）
 */
export function 推进(状态: 战斗状态, 事件: 战斗事件): {
  状态: 战斗状态;
  步骤: 结算步骤[];
} {
  const 步骤: 结算步骤[] = [];

  switch (事件.类) {
    case '开始回合': {
      return {
        状态: {
          ...状态,
          回合: 状态.回合 + 1,
          待决: null,
        },
        步骤,
      };
    }

    case '进入单位':
    case '声明行动':
    case '玩家决策':
    case '结束回合': {
      // TODO: 后续实现
      return { 状态, 步骤 };
    }
  }
}
