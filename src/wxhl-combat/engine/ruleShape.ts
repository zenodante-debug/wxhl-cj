// ================================================================
// 无限回廊 · 前端战斗引擎 · 规则结构判定（纯函数）
//
// 为什么单独成模块：规则条目的结构判定**必须在两个地方用同一份**——
//   1. 翻译校验（`ai/skillInterpreter.校验战斗解释`）：垃圾规则不能让整条假装成功；
//   2. 引擎消费（`engine/loop.有效规则`）：结构不完好的规则不能当成"有效但什么都不做"。
//
// 玩家实测（一整屏）：详情面板打出 `undefined → undefined：（无动作）` 重复十几行，
// 同时那些装备/血统的被动**什么都没落进状态** —— 根因就是这里没有判定：
// `{}` 被当成合法规则 → 预览读 `规则.触发` 得到 undefined，引擎执行它得到空结果。
// ================================================================

import type { 规则, 触发点 } from '../types';

/** 引擎真正会执行的 11 个触发点（与 types 的 `触发点` 一致，这里是运行期白名单） */
export const 已知触发点: 触发点[] = [
  '常驻',
  '进入战斗',
  '回合开始',
  '回合结束',
  '攻击时',
  '命中时',
  '受击时',
  '被命中后',
  '击杀时',
  '资源变化时',
  '使用时',
  '转阶段', // BOSS 阶段血条：越过 70/40/20 或被打到 0
];

/**
 * **引擎能机械执行**的规则系效果（世界书里明确给了判定与生效方式的那几个）。
 *
 * 注意：规则系能力**是开放集合**（世界书原文写的是「必中、必定暴击、即死、免疫、无敌、
 * 锁血、必中核心弱点、无视**等**」）。所以这个表只决定"引擎能不能自己动手执行"，
 * **不是白名单** —— 表外的效果照旧掷判定，过了交给叙事/AI（托管），
 * 卡面怎么写都不会被引擎悄悄删掉（玩家反馈：「规则系能力五花八门，不是这几个能完全涵盖的」）。
 */
export const 引擎认得的规则系效果: string[] = ['穿透', '必中', '必暴', '即死', '无敌', '锁血', '无视'];

/**
 * 一个动作**结构完好**吗。
 * 现在只管一种：`规则系判定` 必须**有名字**（非空字符串）——
 * 名字是 `undefined` 时防火墙会拿它去判定，日志里刷一屏 `规则系「undefined」`（玩家实测：完全看不懂）。
 * 名字**认不认得**不在这里管（那是引擎能不能机械执行的问题，见 `引擎认得的规则系效果`）。
 */
export function 动作结构完好(动作: any): boolean {
  if (!动作 || typeof 动作 !== 'object') return false;
  if (动作.类 === '规则系判定') return typeof 动作.效果 === 'string' && 动作.效果.trim().length > 0;
  return true;
}

/**
 * 一条规则**结构完好**吗 —— 三条都要满足：
 * - `触发` 是引擎认识的触发点（不认识的写了也不会被执行 → 当没有）
 * - `动作` 是**非空的数组**（空动作的规则 = 什么都不做，玩家看到的就是「（无动作）」）
 * - 每个动作是对象（模型偶尔塞 null / 字符串）
 *
 * 作用域缺失**不算**不完好（缺省按 `自身` 处理，历史数据里很常见）。
 */
export function 规则结构完好(规则: any): boolean {
  if (!规则 || typeof 规则 !== 'object') return false;
  if (!已知触发点.includes(规则.触发)) return false;
  const 动作 = 规则.动作;
  if (!Array.isArray(动作) || 动作.length === 0) return false;
  return 动作.some(动作结构完好); // 至少得留下一个能执行的动作
}

/**
 * **净化数值修正**：只留有限的量（NaN / Infinity 会顺着 终伤倍率/减伤/护盾 传染到 HP，
 * 而 `NaN <= 0` 恒为 false —— 单位就永远打不死，玩家实测「赖着不死」就是这么来的）。
 * 返回净化后的表与被丢弃的条目说明（供日志）。
 */
export function 净化数值修正(原始: Record<string, number> | undefined): {
  数值: Record<string, number>;
  丢弃: string[];
} {
  const 数值: Record<string, number> = {};
  const 丢弃: string[] = [];
  for (const [名, 量] of Object.entries(原始 ?? {})) {
    if (Number.isFinite(量)) 数值[名] = 量;
    else 丢弃.push(`${名}=${量}`);
  }
  return { 数值, 丢弃 };
}

/**
 * 归一化一组规则：留下结构完好的（顺带**修剪掉坏动作**），并报出丢了几条/几个动作。
 * 返回 规则 / 丢弃（整条丢掉）/ 丢弃动作（条留下但其中某个动作被剪掉）。
 */
export function 归一化规则(原始: any): { 规则: 规则[]; 丢弃: number; 丢弃动作: number } {
  if (!Array.isArray(原始)) return { 规则: [], 丢弃: 0, 丢弃动作: 0 };
  const 规则: 规则[] = [];
  let 丢弃 = 0;
  let 丢弃动作 = 0;
  for (const r of 原始) {
    if (!r || typeof r !== 'object' || !已知触发点.includes(r.触发) || !Array.isArray(r.动作)) {
      丢弃++;
      continue;
    }
    const 留下的 = (r.动作 as any[]).filter(动作结构完好);
    const 剪掉 = r.动作.length - 留下的.length;
    丢弃动作 += 剪掉; // 先记账，再看这条还剩下什么
    if (!留下的.length) {
      // 动作被剪光了 = 这条规则没有意义。**别重复计数**：
      // 有动作被剪掉时已经按"动作"记过了，只有"本来就是空动作"才按整条记 1。
      丢弃 += 剪掉 > 0 ? 0 : 1;
      continue;
    }
    规则.push({ ...(r as 规则), 动作: 留下的 });
  }
  return { 规则, 丢弃, 丢弃动作 };
}
