// ================================================================
// 制造系技能解析（四级回退）+ 分类/等级校验
//
// 解决的问题（v2.1 修订）：制造系技能的判定原本是 `通用技能[行业名]` **精确名**查表 ——
//   `c.通用技能['锻造']`。可主卡里玩家学到的技能叫「锻造术」「高级锻造术」「铸造」……
//   于是「有技能却查不到 → 未掌握生活技能「锻造」」，玩家被迫把技能名改成行业名才能开工。
//
// 本模块把「哪条技能算这个行业的」收口成一条**四级回退链**（首个命中即止，可靠性从高到低）：
//   ① 映射表：聊天变量里玩家自己登记的别名（「铸造」=「锻造」这种无从猜出的关系只能靠它）
//   ② 精确名：技能名 === 行业名（旧行为，零回归）
//   ③ 模糊名：技能名**包含**行业名（「锻造术」「高级锻造」）
//   ④ 效果文本：技能的 效果 record 的 **key 或 value** 里提到行业名（「铁匠之心」的「锻造精通」）
// 全不中 → null，由 checkSkill 报「未掌握」。链上任何一级都**不抛错**：入参直接来自
// 主卡变量（AI/GM 可写任意形状），坏数据只该降级、不该炸掉制作页。
//
// 纯函数、零酒馆依赖（不碰 MVU/聊天变量/toastr）：映射表由调用方（store）从聊天变量读出后喂进来。
// ================================================================
import type { 行业 } from './recipes';

// 行业 由 recipes.ts 定义（'锻造'|'裁缝'|'炼金'|'工程'|'烹饪'）——这里只做类型转出，
// 让消费方能从本模块一并取到；注意 resolveSkill 的 行业 入参是 `string`：
// 聊天变量里的行业名不受 schema 约束，窄化成枚举只会把「AI 手滑写了个别的词」变成编译期问题。
// （type-only re-export：编译后完全擦除，本模块运行时依然零依赖。）
export type { 行业 };

/** 生活技能条目（主卡 `通用技能.<技能名>`）。只声明本模块消费的字段，
 *  其余字段（阶位 等）由调用方自取，故用 catchall 兜住 —— 绝不假设卡面只有这几个键。 */
export interface 技能数据 {
  分类?: string;
  等级?: number;
  效果?: Record<string, unknown>;
  [k: string]: unknown;
}

/** 解析依据：既是「为什么算命中」的审计信息，也是给玩家的可解释性（UI 可据此提示"由映射表认出"） */
export type 技能依据 = '映射表' | '精确名' | '模糊名' | '效果文本';

export interface 技能命中 {
  技能名: string;
  技能: 技能数据;
  依据: 技能依据;
}

/** 客观防御：只有真正是对象的值才算技能条目 —— 变量里写成字符串/数字的坏数据一律不认。
 *  （不用真值判断：`通用技能.锻造 = '精通'` 这种值会让后面 `sk.分类` 静默取到 undefined。） */
function 是技能条目(v: unknown): v is 技能数据 {
  return typeof v === 'object' && v !== null;
}

/** 效果的 key 或 value 文本里是否提到行业名。
 *  value 只认**字符串**：把嵌套值 stringify 进来，会让「恰好含行业名」的任意结构被误判成技能命中。 */
function 效果提及行业(技能: 技能数据, 行业: string): boolean {
  const 效果 = 技能.效果;
  if (!是技能条目(效果)) return false;
  for (const [键, 值] of Object.entries(效果)) {
    if (键.includes(行业)) return true;
    if (typeof 值 === 'string' && 值.includes(行业)) return true;
  }
  return false;
}

/**
 * 从 `通用技能` 里解析出「该行业对应的那条技能」。四级回退，首个命中即止（顺序 = 可靠性从高到低）。
 *
 * @param 通用技能 主卡 `契约者.通用技能`（技能名 → 技能数据）。坏形状不抛错，等价于空表
 * @param 行业     行业名（'锻造' 等）。用 string 而非枚举：变量里的行业名不受 schema 约束
 * @param 映射表   行业 → 别名技能名列表（聊天变量 `wxhl003_crafting.行业技能映射`，缺省 {}）。
 *                  按列表顺序取首个**存在于 通用技能** 的名字；整表落空才继续往下回退
 *                 （不因映射表没命中就返回 null —— 映射表是"补充"，不该遮蔽精确名/模糊名）
 */
export function resolveSkill(
  通用技能: Record<string, any>,
  行业: string,
  映射表?: Record<string, string[]>,
): 技能命中 | null {
  const 表 = 是技能条目(通用技能) ? 通用技能 : {};
  if (!行业) return null;

  // ① 映射表：玩家显式登记的别名优先 —— 它是唯一能表达「铸造 = 锻造」这类无字面关系的手段。
  // 用 hasOwn 而非 `表[名]` 真值判断：技能名来自变量，`constructor`/`toString` 之类
  // 会让原型上的成员冒充命中（仓库同款隐患见 store.同名理由 的注释）。
  const 别名表 = 映射表?.[行业];
  if (Array.isArray(别名表)) {
    for (const 名 of 别名表) {
      if (typeof 名 === 'string' && Object.hasOwn(表, 名) && 是技能条目(表[名])) {
        return { 技能名: 名, 技能: 表[名], 依据: '映射表' };
      }
    }
  }

  // ② 精确名：与 v2 的行为逐字一致（技能名就叫行业名的玩家，解析结果不变）
  if (Object.hasOwn(表, 行业) && 是技能条目(表[行业])) {
    return { 技能名: 行业, 技能: 表[行业], 依据: '精确名' };
  }

  // ③ 模糊名：「锻造术」「高级锻造」等含行业名的技能。多条都含行业名时取**对象键序**首个
  //（= 存档里先出现的那条，可预期、可复现；此处不猜"哪条更强"，那是玩家该用映射表表达的事）
  for (const [名, 技能] of Object.entries(表)) {
    if (名.includes(行业) && 是技能条目(技能)) return { 技能名: 名, 技能, 依据: '模糊名' };
  }

  // ④ 效果文本：连名字都不含行业名，但技能的 效果 里提到了（「铁匠之心」的「锻造精通」）
  for (const [名, 技能] of Object.entries(表)) {
    if (是技能条目(技能) && 效果提及行业(技能, 行业)) return { 技能名: 名, 技能, 依据: '效果文本' };
  }

  return null;
}

/**
 * 技能要求校验：命中技能是否满足配方的 `技能要求`（分类 + 等级）。返回错误列表，空 = 通过。
 *
 * **分类**（v2.1 补漏）：旧版只看等级，`分类` 完全没查 —— 金图纸写着「高级技能 Lv.1」，
 * 一个基础系 Lv.9 的技能照样能开工。
 * 本函数只负责**比较**；「该要哪个分类」由调用方决定（`validateCraft` 按**品质**推导：
 * 白/蓝 = 基础、金/紫 = 高级 —— 不信任配方自带的 `技能要求.分类`，见那里的注释）。
 *   - 要求「高级」→ 命中技能必须是 `分类 === '高级'`
 *   - 要求「基础」→ `基础`、`高级`、`银色` 皆可。**设计决定：高级可代基础，反之不可** ——
 *     能打金图纸的匠人做白板装备不该被拦；这是单向的"上兼容下"，不是放宽门槛。
 *   - **「银色」严格高于「高级」**（主卡 schema 原文
 *     `z.union([z.enum(['基础','高级','银色']), z.string()]).prefault('基础')` —— 银色是合法值），
 *     故**两个闸门都通过**：银色玩家做金图纸与白图纸都不该被拦。
 *   - 分类不在这三档之内（卡面自造词/字段缺失）→ 两种要求都不通过（fail-closed：
 *     宁可让玩家去补 分类，也不要让一个来路不明的技能冒充高级技能骗过金图纸门槛）。
 *
 * **等级**：`技能.等级 < 技能要求.等级` 时报错，文案同时给出「需要 Lv.X / 当前 Lv.Y」。
 *
 * @param 命中      resolveSkill 的结果；null = 没掌握
 * @param 技能要求  配方.技能要求（分类由调用方按品质推导，见 validateCraft）
 * @param 行业      仅用于「未掌握」文案（本模块不持有行业上下文，由调用方喂）
 */
export function checkSkill(
  命中: 技能命中 | null,
  技能要求: { 分类: '基础' | '高级'; 等级: number },
  行业 = '',
): string[] {
  if (!命中) return [`未掌握生活技能「${行业}」`];
  const errs: string[] = [];

  // 分类高低序 —— 判定「上兼容下」的唯一依据（三档都在这里，加新档只需加一行）。
  // 表外取值取到 undefined → 两个要求都过不了（fail-closed，见函数文档）。
  const 分类序: Record<string, number | undefined> = { 基础: 0, 高级: 1, 银色: 2 };
  const 分类 = String(命中.技能?.分类 ?? '');
  const 技能级 = 分类序[分类];
  const 要求级 = 分类序[技能要求.分类];
  if (!(技能级 !== undefined && 要求级 !== undefined && 技能级 >= 要求级)) {
    errs.push(`技能分类不足：需要「${技能要求.分类}」技能，当前为「${分类 || '未知'}」`);
  }

  // 等级缺省按 1 处理：与 store.assembleMaker 的 `Number(sk.等级 ?? 1)` 同口径
  //（卡面没写等级的技能，两边必须给出同一个结论，否则「能开工却被拦」/「被拦却能开工」二选一）
  const 等级 = Number(命中.技能?.等级 ?? 1);
  if (Number.isFinite(等级) && 等级 < 技能要求.等级) {
    errs.push(`技能等级不足：需要 Lv.${技能要求.等级}，当前 Lv.${等级}`);
  }

  return errs;
}
