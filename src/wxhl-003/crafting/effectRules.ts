// ================================================================
// 世界书《装备效果强度限制》移植：常驻数值基准 + 触发/消耗倍率 + 违禁项
// 设计填补（世界书未列明，可调常量）：
//   - 触发/消耗类统一取常驻上限的 2 倍（世界书原文为 1.5~2 倍区间）
//   - 缺触发条件或缺消耗的触发/消耗类 → 降级为常驻并按常驻上限钳制
// 实现注记（与任务书给定的正则有两处不同，方向都是收紧漏判、不放宽禁令）：
//   - 每条违禁项 = 「硬子句」OR「整串条件守卫」：
//       硬子句（无条件即死 / 永久·无限·绝对无敌）不受条件词影响，命中即拒；
//       守卫式保留任务书原意（全串无任何条件/消耗字样才算无条件），但改为整串负向
//       先行断言——原式 `即死(?!.*(条件|…))` 只向 即死 之后看，而条件常写在
//       即死 之前（如「生命低于15%时即死」），会把合法条目误判为违禁。
//   - 「无条件必中核心弱点」改为双向匹配：原式要求 必中 在 核心/弱点/要害 之前，
//     「核心弱点必中」「攻击要害，必中」会漏网。
// 违禁扫描文本 = 「描述」+「触发条件」，**不含「消耗」字段**：条件既可以写在描述里，也可以写在
// 触发条件字段里（Task 4 的 AI 输出契约：描述只写效果本身，条件/消耗写进独立字段）；
// 而消耗字段里的 每场/次数/消耗/冷却 等字样不得豁免即死类禁令，否则「描述=即死 + 消耗=每场1次」
// 会被消耗字段洗白。
// 豁免维度按禁令各取所需：
//   - 即死 / 必中 → 看「何时触发」，认条件类（低于|不足|以上|以下|概率|几率|时|则）
//   - 无敌 → 看「持续多久」，只认单次持续时长（回合|持续）；条件类与发动次数类（每场|次数）都不豁免
// ================================================================

export type EffectKind = '常驻' | '触发' | '消耗';

export interface EffectEntry {
  类型: EffectKind;
  描述: string;
  命中闪避?: number;
  伤害百分比?: number;
  属性加成?: number;
  触发条件?: string;
  消耗?: string;
}

export interface EffectCapRow {
  命中闪避: readonly [number, number];
  伤害百分比: readonly [number, number];
  属性加成: number;
}

/** 下标 = 阶位（0 不用）：世界书《装备效果强度限制》常驻类数值基准 */
export const EFFECT_CAP: readonly EffectCapRow[] = [
  { 命中闪避: [0, 0], 伤害百分比: [0, 0], 属性加成: 0 },
  { 命中闪避: [3, 6], 伤害百分比: [7, 13], 属性加成: 1 },
  { 命中闪避: [5, 10], 伤害百分比: [10, 20], 属性加成: 2 },
  { 命中闪避: [7, 13], 伤害百分比: [13, 27], 属性加成: 3 },
  { 命中闪避: [8, 17], 伤害百分比: [17, 33], 属性加成: 4 },
  { 命中闪避: [10, 20], 伤害百分比: [20, 40], 属性加成: 6 },
];

const TRIGGER_MULT = 2; // 触发/消耗类上限倍率（设计填补）

/** 该阶位该类型的效果数值上限（取区间最大值，再乘类型倍率） */
export function descaleCap(阶位: number, 类型: EffectKind): { 命中闪避: number; 伤害百分比: number; 属性加成: number } {
  const row = EFFECT_CAP[阶位];
  if (!row) throw new Error(`未知阶位：${阶位}`);
  const m = 类型 === '常驻' ? 1 : TRIGGER_MULT;
  return {
    命中闪避: row.命中闪避[1] * m,
    伤害百分比: row.伤害百分比[1] * m,
    属性加成: row.属性加成 * m,
  };
}

/** 单条效果钳制：超上限回钳；触发/消耗类缺条件或缺消耗 → 降级为常驻 */
export function clampEffect(entry: EffectEntry, 阶位: number): { entry: EffectEntry; clamped: string[] } {
  const clamped: string[] = [];
  const e: EffectEntry = { ...entry };

  if ((e.类型 === '触发' || e.类型 === '消耗') && (!e.触发条件 || !e.消耗)) {
    clamped.push(`「${e.描述}」缺少${!e.触发条件 ? '触发条件' : '消耗'}，已降级为常驻类`);
    e.类型 = '常驻';
  }

  const cap = descaleCap(阶位, e.类型);
  const 钳 = (字段: '命中闪避' | '伤害百分比' | '属性加成') => {
    const v = e[字段];
    if (typeof v !== 'number' || !Number.isFinite(v)) return;
    if (v > cap[字段]) {
      clamped.push(`「${e.描述}」${字段} ${v} 超出${阶位}阶${e.类型}类上限，已钳至 ${cap[字段]}`);
      e[字段] = cap[字段];
    }
  };
  钳('命中闪避');
  钳('伤害百分比');
  钳('属性加成');
  return { entry: e, clamped };
}

/**
 * 条件类豁免短语：只有当「描述 + 触发条件」里写明条件时，才豁免「无条件即死 / 无条件必中」类禁令。
 * 消耗类短语（每场|次数|消耗|冷却）**故意不在表内**——消耗不得豁免即死类禁令，否则
 * 「描述=即死 + 消耗=每场1次」会被消耗字段洗白而放行。
 * 另注：单字「条件」也**不在表内**（非遗漏）——按 Task 4 的 AI 输出契约，条件必须写成具体判定
 * （「生命低于15%」等），故 `描述:'即死（有条件）'` 这类含糊措辞按违禁处理，方向为收紧。
 */
const 条件词 = '低于|不足|以上|以下|概率|几率|时|则';
/**
 * 无敌类豁免短语：**只认单次持续时长**（回合|持续）——世界书对无敌的约束是「限定明确回合数且单次≤2回合」，
 * 只有这两个词表达「持续多久」：
 *   - 条件类八词（低于|不足|以上|以下|概率|几率|时|则）不豁免：否则 `{描述:'无敌', 触发条件:'受到攻击时'}`
 *     会放行无时限的无敌，是违禁门缺口。
 *   - 每场|次数 也不豁免：它们限的是「一场能发动几次」，不是单次时长，`'无敌，每场1次'` 仍是无时限无敌。
 */
const 无敌豁免词 = '回合|持续';
/** 守卫前缀：全串（描述 + 触发条件）找不到任何条件字样时成立 */
const 无条件守卫 = `^(?![\\s\\S]*(?:${条件词}))[\\s\\S]*`;
/** 守卫前缀（无敌类）：看的是「单次持续多久」而非「何时触发」，故用无敌自己的时长词表（回合|持续） */
const 无敌守卫 = `^(?![\\s\\S]*(?:${无敌豁免词}))[\\s\\S]*`;

/** 违禁项：命中即整体拒绝（不钳制）。硬子句不受豁免词影响，先命中先拒 */
export const FORBIDDEN_PATTERNS: readonly { 名: string; test: RegExp }[] = [
  // 硬子句「无条件…即死/秒杀」；守卫式 = 全串无条件字样却出现 即死/秒杀（豁免 = 条件类：何时触发）
  { 名: '无条件即死', test: new RegExp(`无条件[\\s\\S]*(?:即死|秒杀)|${无条件守卫}(?:即死|秒杀)`) },
  // 硬子句「永久/无限/绝对无敌」；守卫式 = 全串无时长/次数字样却出现 无敌（豁免 = 时长/次数类）
  { 名: '永久无敌', test: new RegExp(`(?:永久|无限|绝对)\\s*无敌|${无敌守卫}无敌`) },
  { 名: '无限资源/锁血', test: /无限(资源|弹药|MP|HP)|锁血|血量锁定/ },
  // 双向匹配（必中 在前或在后都算），叠加同一个条件守卫
  {
    名: '无条件必中核心弱点',
    test: new RegExp(`${无条件守卫}(?:必中[\\s\\S]*(?:核心|弱点|要害)|(?:核心|弱点|要害)[\\s\\S]*必中)`),
  },
];

/** 违禁扫描文本 = 描述 + 触发条件（**不含「消耗」字段**，故消耗字样无法豁免禁令） */
function 违禁扫描文本(e: EffectEntry): string {
  return [e.描述, e.触发条件].filter(Boolean).join(' ');
}

/** 校验一组效果：条数 ≤2、无违禁项、逐条钳制；返回钳制后的效果列表 */
export function checkEffects(
  效果: EffectEntry[],
  阶位: number,
): { ok: boolean; reasons: string[]; 效果: EffectEntry[]; clamped: string[] } {
  const reasons: string[] = [];
  if (效果.length > 2) {
    reasons.push(`效果条目 ${效果.length} 条，超出世界书上限 2 条`);
  }
  for (const e of 效果) {
    const text = 违禁扫描文本(e);
    for (const p of FORBIDDEN_PATTERNS) {
      if (p.test.test(text)) reasons.push(`「${e.描述}」命中违禁项：${p.名}`);
    }
  }
  if (reasons.length > 0) return { ok: false, reasons, 效果, clamped: [] };

  const clamped: string[] = [];
  const out = 效果.map(e => {
    const r = clampEffect(e, 阶位);
    clamped.push(...r.clamped);
    return r.entry;
  });
  return { ok: true, reasons: [], 效果: out, clamped };
}
