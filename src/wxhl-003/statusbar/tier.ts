// ================================================================
// 状态栏 · 位阶归一（关键词筛选，宽进不出错）
//
// 变量里的阶位写法五花八门：「超脱」「超脱阶」「超脱者」「一阶巅峰」「二阶·觉醒」「2阶」
// 都出现过。原先各调用点用**精确等值**（`rankStr === '三阶'`）判断，一律落到默认值 ——
// 于是超脱被当成一阶、属性修正值/软上限/等级上限全算错。
//
// 这里改用**关键词筛选**：含「超脱」即超脱阶；否则按 五→一 找汉字/阿拉伯数字。
// 契约者、其他契约者、副本角色共用同一套判定（statusbar/core.ts 的实体计算都走 `位阶档位`）。
// ================================================================

/**
 * 位阶档位：0=一阶 … 4=五阶、**5=超脱阶**；认不出返回 `undefined`（调用方各自兜底成一阶）。
 *
 * 顺序要紧：**先「超脱」**（它不含数字，放最前最稳），再按 五→一 从高到低 ——
 * 从高到低是防御性排序，避免「一」先命中把「五阶·极」之类误判成一阶。
 */
const 位阶关键词: readonly (readonly [number, readonly string[]])[] = [
  [5, ['超脱']],
  [4, ['五', '5']],
  [3, ['四', '4']],
  [2, ['三', '3']],
  [1, ['二', '2']],
  [0, ['一', '1']],
];

export function 位阶档位(阶位: unknown): number | undefined {
  const s = String(阶位 ?? '');
  for (const [档, 词表] of 位阶关键词) {
    if (词表.some(w => s.includes(w))) return 档;
  }
  return undefined;
}

/** 位阶修正值系数（规则：1、2、4、7、11 对应 1~5 阶；**超脱 20**，与市场/工坊同表） */
export const 位阶修正值系数 = [1, 2, 4, 7, 11, 20] as const;

/** 属性软上限（一阶 25 / 二阶 40 / 三阶 55 / 四阶 70 / 五阶与超脱无上限） */
export const 位阶属性软上限 = [25, 40, 55, 70, 9999, 9999] as const;

/** 等级上限（一阶 20 / 二阶 40 / 三阶 60 / 四阶 80 / 五阶 100 / 超脱无上限） */
export const 位阶等级上限 = [20, 40, 60, 80, 100, 9999] as const;
