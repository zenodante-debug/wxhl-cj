/**
 * store 从 MVU 变量里摘出来的只读视图（纯函数不去碰 MVU）。
 *
 * **字段名必须与 store 的 `readSettlementSnapshot` 逐字一致** —— 名字对不上不会报错,
 * 只会让这里读到 `undefined`, 而单测因为 fixture 是手写的照样绿。
 */
export interface SettlementSnapshot {
  副本名称: string;
  当前EXP: number;
  当前UP: number;
  当前RP: number;
  当前PEXP: number;
  军衔: string;
  职业等级: number;
  PEXP_升级所需: number;
  当前CR: number;
  /**
   * 当前时刻的**日期**（卡的 `当前时间.现实日期`, 格式 `2025年5月10日`）。
   * 第十一步的「按副本内所待天数更新现实时间」读的就是它。
   *
   * ⚠️ **不要拿 `当前现实时间` 来顶这一格** —— 那是**时刻**（格式 `凌晨00:01`）,
   * `加天数` 的正则锚定 `年月日`, 喂时刻只会恒返回空串（于是现实日期永不更新,
   * 面板还一直印「格式无法识别」）。
   */
  当前现实日期: string;
  /**
   * 当前时刻（卡的 `当前时间.现实时间`, 格式 `凌晨00:01`）。
   * **只做面板 `## 现实时间` 的后缀**（`新现实日期 + ' ' + 当前现实时间`）, 不参与任何算术。
   */
  当前现实时间: string;
  /**
   * 结算前的赛季资格分（卡的 `资格分`）。写进存档的是「它 + 本次」= `computed.新资格分` ——
   * 所以它是 `buildSettlementWrites` 入口必查的字段之一: 读漏了会被静默当成 0,
   * 写进去等于**把玩家的赛季累计清零**。
   */
  旧资格分: number;
  /**
   * 任务名 → 该任务的 `奖励` 原文。**汇总基础奖励 只认这张表**。
   * 必须包含主线（键名固定为 `主线`）、全部支线、全部隐藏任务、全部成就
   * —— 由 `readSettlementSnapshot` 从 `当前副本任务` 的四个容器摊平而来。
   * 世界事件**不放进来**（它的 `奖励` 字段存的是「影响」文本, 不是数值）。
   */
  任务奖励: Record<string, string>;
  /**
   * 背包里**已有**物品的数量（物品名 → 数量）。
   * ⚠️ 掉落写入必须**累加**到它上面, 不能覆盖 —— 否则玩家原有的同名物品会被结算冲掉。
   */
  已有背包: Record<string, number>;
  /**
   * 当前副本任务里的**全部**成就（含未达成的）—— 规则第九步要求公示「本次错过的成就达成条件」。
   * 已达成与否由面板拿 `ai.达成的成就` 的名单去比对（**不读变量的 `状态` 字段**,
   * 口径与 汇总基础奖励 一致: 完成与否看 AI, 数值/条件看变量）。
   */
  成就清单: { 名称: string; 说明: string; 难度: string; 奖励: string }[];
  /** 当前副本任务里的**全部**隐藏任务（含未触发的）—— 同上, 已完否由 `ai.完成的隐藏任务` 比对 */
  隐藏任务清单: { 名称: string; 说明: string; 奖励: string }[];
  小队成员: { 名称: string; 当前EXP: number; 当前UP: number }[];
}

/** `汇总基础奖励` 的产物。`未找到` 是 AI 报告了、但变量里没有的键名 */
export interface 基础奖励汇总 { EXP: number; UP: number; 未找到: string[] }

/**
 * 决定「哪些任务的奖励计入本次结算」：主线 + AI 报告完成的支线 / 隐藏任务 / 成就。
 *
 * 分工与设计一致：**完成与否以 AI 报告为准, 数值以变量里的 `奖励` 原文为准**。
 * 世界事件不计入（它的 `奖励` 字段存的是「影响」文本, 不是数值）。
 *
 * - AI 报告了变量里没有的键名 → 记进 `未找到` 并**以 0 计**（不抛错, 由调用方在画面/提示里展示）
 * - 变量里**存在**的奖励文本解析失败 → **抛错**（绝不静默当 0, 那会让玩家少拿奖励而无人察觉）
 */
export function 汇总基础奖励(快照: SettlementSnapshot, ai: SettlementGenResult): 基础奖励汇总 {
  const 表 = 快照.任务奖励 ?? {};
  const 计入 = ['主线', ...(ai.完成的支线 ?? []), ...(ai.完成的隐藏任务 ?? []), ...(ai.达成的成就 ?? [])];
  const 未找到: string[] = [];
  let EXP = 0;
  let UP = 0;
  for (const 名 of 计入) {
    const 原文 = 表[名];
    // 只判 `undefined` 而不交给 parseRewardText —— 它把 `''` 与 `undefined` 都当「没有奖励」返回 0,
    // 于是「键名不存在」与「这条任务真的没奖励」会被混成一个静默的 0（主线少算一笔是看不出来的）
    if (原文 === undefined) { 未找到.push(名); continue; }
    const 数 = (() => {
      try { return parseRewardText(原文); }
      catch (e: any) {
        // 带上任务名, 否则玩家只知道「格式无法解析」却不知道是哪一条任务的 `奖励`
        throw new Error(`任务「${名}」的奖励文本无法解析: ${e?.message ?? e}`);
      }
    })();
    EXP += 数.EXP;
    UP += 数.UP;
  }
  return { EXP, UP, 未找到 };
}

/**
 * AI 报告的已达成成就 → 星数数组（★=1 … ★★★★★★=6）。
 *
 * 口径与 `汇总基础奖励` 一致: **只算变量（`快照.成就清单`）里真的存在的成就** ——
 * AI 名单里多报的名字**整个不进来**（不是记 0 占位）, 否则资格分的 `成就星数.length × 10`
 * 会给一个不存在的成就记分, 而同一份名单在 `汇总基础奖励` 那边是按 0 计、UI 还明说「按 0 计」。
 *
 * 星数只数 `难度` **开头连续**的 `★`: 格式由 `dungeonRules.ts` 固定为
 * `${成就档位} · <AI 写的难度描述>`。**不能全串数** —— AI 在描述里再写一个 `★`
 * （如「★★★ 噩梦 · 比 ★ 更难」）就会虚增星数, 而星数直接决定写进存档的 RP 与资格分。
 */
export function 成就星数(快照: SettlementSnapshot, 已达成名: string[]): number[] {
  const 难度表 = new Map((快照.成就清单 ?? []).map(a => [a.名称, a.难度]));
  const 星: number[] = [];
  for (const 名 of 已达成名 ?? []) {
    const 难度 = 难度表.get(名);
    if (难度 === undefined) continue;
    星.push((/^★+/.exec(String(难度).trim())?.[0] ?? '').length);
  }
  return 星;
}

/**
 * `名单` 里**变量中确实存在**的条目数 —— 供资格分的「隐藏任务 +20/条」用。
 *
 * 与 `汇总基础奖励` 同一口径（完成与否看 AI, 存不存在看变量）: AI 报告了变量里没有的名字时,
 * 奖励按 0 计、资格分也不该给它记分。
 */
export function 存在条目数(清单: { 名称: string }[] | undefined, 名单: string[]): number {
  const 名集 = new Set((清单 ?? []).map(x => x.名称));
  return (名单 ?? []).filter(名 => 名集.has(名)).length;
}

/**
 * 面板展示用的数字：整数不带小数点, 小数保留一位。
 * `0.1 + 0.2` 那类浮点尾巴不该印给玩家看（CR 是 ±0.5/±0.3 的累加）。
 */
function 显示数字(x: number): string {
  return String(Math.round(x * 10) / 10);
}

/** `ai.称号.效果` → 一行文本（`嗜血：击杀回血`） */
function 称号效果文本(效果: Record<string, string> | undefined): string {
  if (!效果) return '';
  return Object.entries(效果).map(([k, v]) => `${k}：${v}`).join('；');
}

/** 把非空片段用 `｜` 连起来（空片段丢掉, 免得印出 `｜｜`） */
function 连接(...段: string[]): string {
  return 段.filter(s => s !== '').join('｜');
}

/** `标签: 值`；值为空时返回空串（整段随后被 连接 丢掉） */
function 标注(标签: string, 值: string): string {
  return 值 === '' ? '' : `${标签}: ${值}`;
}

/** 空串 / undefined 都算「没写」, 一律换成显式占位 */
function 或占位(值: string | undefined, 占位: string): string {
  const v = 值 ?? '';
  return v === '' ? 占位 : v;
}

/**
 * `说明` 为空时的显式占位。**不能让整段消失** —— 「本次错过的成就达成条件」正是规则第九步
 * 要公示的东西, 静默降级成「只剩名字与奖励」时玩家最需要的那半句就没了
 * （与本模块「宁可难看也不圆上」的口径一致）。
 */
const 无达成条件 = '（变量中未记录达成条件）';
/** `隐藏任务清单` 的 `说明` 为空时的占位（它不是「达成条件」, 用更中性的措辞） */
const 无说明 = '（变量中未记录说明）';

/** 聚合后的掉落：物品名 → { 数量(已相加), 品质, 属性, 效果 } */
type 聚合掉落 = Map<string, { 数量: number; 品质: string; 属性: string; 效果: string }>;

/**
 * 掉落按**物品名**聚合（数量相加）。
 *
 * 面板与写入清单必须同源：AI 报两条同名掉落时, 逐条写会留下两行、而 `_.set` 只有一条路径 ——
 * 后写的那条静默覆盖前一条（1 把 + 2 把 变成 2 把）。先聚合再写, 才是「本次掉落了 3 把」。
 */
function 聚合掉落物品(掉落物品: SettlementGenResult['掉落物品']): 聚合掉落 {
  const 合: 聚合掉落 = new Map();
  for (const d of 掉落物品) {
    const 旧 = 合.get(d.名称);
    if (旧) 旧.数量 += d.数量;
    else 合.set(d.名称, { 数量: d.数量, 品质: d.品质, 属性: d.属性, 效果: d.效果 });
  }
  return 合;
}

/**
 * 严格按规则原文的 `<Settlement Beautification>` 逐行拼装（`## 名称: 值`）。
 *
 * 数值一律取 `computed` —— 这是把面板从 AI 手里拿走的唯一理由：
 * 画面上的数字与写进存档的数字必然同源, 不会出现「画面写 +50 RP、存档写 +30」。
 * 逐项资格分（评价分 / 击杀分 / 任务分）**不在这里** —— 规则模板没有这三行, 由 UI 侧展示。
 */
export function assembleSettlementPanel(
  c: SettlementComputed,
  ai: SettlementGenResult,
  快照: SettlementSnapshot,
): string {
  const 聚合 = 聚合掉落物品(ai.掉落物品);
  const 掉落清单 = 聚合.size
    ? [...聚合].map(([名, d]) => `${名}（${连接(d.品质, d.属性, d.效果)}）×${d.数量}`).join('；')
    : '无';

  // 完成与否拿 `ai` 的名单去比对 `快照` 里**全部**的成就/隐藏任务 —— 缺清单时退化为空, 不假装有
  const 已达成名 = new Set(ai.达成的成就 ?? []);
  const 已完成隐藏 = new Set(ai.完成的隐藏任务 ?? []);
  const 成就清单 = 快照.成就清单 ?? [];
  const 隐藏任务清单 = 快照.隐藏任务清单 ?? [];
  // 已达成: 名称 + 难度 + **说明(完成描述)** + 奖励；未达成: 名称 + **说明(达成条件)** + 奖励
  // —— 规则第九步两边都要「明文展示」，与 未达成 行同构（`标注` 拼法一致）
  const 已达成 = 成就清单.filter(a => 已达成名.has(a.名称))
    .map(a => `${a.名称}（${连接(a.难度, 标注('完成描述', 或占位(a.说明, 无说明)), 标注('奖励', a.奖励))}）`).join('；') || '无';
  const 未达成 = 成就清单.filter(a => !已达成名.has(a.名称))
    .map(a => `${a.名称}（${连接(标注('达成条件', 或占位(a.说明, 无达成条件)), 标注('奖励', a.奖励))}）`).join('；') || '无';
  const 隐藏公示 = 隐藏任务清单
    .map(t => `${t.名称}（${连接(已完成隐藏.has(t.名称) ? '已完成' : '未触发', 或占位(t.说明, 无说明), 标注('奖励', t.奖励))}）`)
    .join('；') || '无';
  // 规则第七步「未达 A 级直接跳过」: prompt 让 AI 在非 A/S 时回 null, 但那是提示词层面的约束,
  // 模块这一侧再兜一道 —— 否则 AI 一次不听话就会把 B 级的称号印出来、还写进备用称号
  const 称号 = (c.评价等级 === 'S' || c.评价等级 === 'A') ? ai.称号 : null;
  const 现实时间 = c.新现实日期
    ? `${c.新现实日期} ${快照.当前现实时间}`
    : `${快照.当前现实时间}（现实日期格式无法识别, 本次未更新现实日期）`;

  const L: string[] = [];
  L.push('<Settlement Beautification>');
  L.push('<基础结算奖励>');
  // 规则原文是 `[评价等级]+[资格分（）]` —— `（）` 是占位符, 输出形如 `S+185`
  L.push(`## 最终评价: ${c.评价等级}+${c.资格分_本次}`);
  L.push(`## 评价倍率: ×${显示数字(c.评价倍率)}`);
  L.push(`## CR态度: ${c.CR态度}`);
  L.push(`## CR奖励倍率: ×${Math.round(c.CR奖励倍率 * 100)}%`);
  L.push(`## 位阶修正: ×${c.位阶修正}`);
  L.push(`## 基础EXP汇总: ${c.基础EXP汇总}`);
  L.push(`## 基础UP汇总: ${c.基础UP汇总}`);
  L.push(`## 最终EXP: ${c.最终EXP}`);
  L.push(`## 最终UP: ${c.最终UP}`);
  L.push(`## RP获得: ${c.RP}`);
  L.push(`## 当前RP余额: ${快照.当前RP + c.RP}`);
  L.push(`## 军衔状态: ${快照.军衔}`);
  L.push('</基础结算奖励>');
  L.push('<特殊结算奖励>');
  L.push(`## PEXP获得: ${c.PEXP}`);
  // 与 `## 当前RP余额` 同口径: 模板里「获得」行的配对行是**结算后的余额**（旧值 + 本次获得）。
  // 印旧值会让「获得 600 / 当前 100」与写进存档的 700 打架。
  L.push(`## 当前PEXP: ${快照.当前PEXP + c.PEXP}`);
  L.push(`## 职业进度: ${快照.职业等级}/${快照.PEXP_升级所需}`);
  L.push(`## 称号获得: ${称号?.名称 ?? ''}`);
  L.push(`## 称号效果: ${称号效果文本(称号?.效果)}`);
  L.push('## 称号选择: 待聊天中决定');
  L.push(`## 掉落清单: ${掉落清单}`);
  L.push(`## 副本成就已达成: ${已达成}`);
  L.push(`## 副本成就未达成: ${未达成}`);
  L.push(`## 隐藏任务公示: ${隐藏公示}`);
  L.push(`## CR变动: ${c.CR变动 === 0 ? '不变' : (c.CR变动 > 0 ? '+' : '') + 显示数字(c.CR变动)}`);
  L.push(`## 更新后CR: ${显示数字(c.更新后CR)}`);
  L.push(`## 回廊态度: ${c.更新后回廊态度}`);
  L.push(`## 史诗记录: ${快照.副本名称} · ${c.评价等级} · ${ai.史诗记录}`);
  L.push(`## 副本周期: ${c.新周期}`);
  L.push(`## 现实时间: ${现实时间}`);
  L.push('</特殊结算奖励>');
  // 规则原文的「结算后流程」一节。模块**不做**这两条流程, 只把选项摆出来由聊天接手;
  // 放在闭合标签之前, 玩家整段复制给聊天时两个选项才会一起被读到。
  L.push('结算后流程（强制二选一, 请在聊天中告知你的选择）:');
  L.push('1. 进入休息周期（回廊主城停留24小时 + 现实世界回归6天）。');
  L.push('2. 花费UP延长副本滞留（50 UP/天，上不封顶）。');
  L.push('</Settlement Beautification>');
  return L.join('\n');
}

/** 一条写入：路径相对 `stat_data.契约者`。路径用**数组**, 因为名字可能含「.」（如 J.K.罗琳） */
export interface SettlementWrite { 路径: string[]; 值: unknown }

/**
 * 结算的写入清单（路径相对 `stat_data.契约者`）。
 *
 * **只返回清单, 不碰 MVU** —— 由 store 逐条 `_.set` 后 `Mvu.replaceMvuData` 并回读校验。
 * 增量一律写成「旧值 + 增量」的**绝对值**（store 拿到的快照就是结算前的快照）,
 * 因为通道是 `_.set` 而不是自增语义, 写成增量会把存档里的余额覆盖成「本次获得」。
 */
export function buildSettlementWrites(
  c: SettlementComputed,
  ai: SettlementGenResult,
  快照: SettlementSnapshot,
): SettlementWrite[] {
  const W: SettlementWrite[] = [];
  const 记 = (路径: string[], 值: unknown) => { W.push({ 路径, 值 }); };

  // 「快照整体没给 `已有背包`」（= 接线漏了, 是 bug）与「该物品不在背包里」（= 正常, 就是 0）是两件事。
  // 前者静默当 0 会让掉落写入把玩家原有的同名物品冲掉, 而且既有的 `数量 === 1` 断言在
  // `0 + 1 === 覆盖写 1` 下照样绿 —— 所以必须在入口挡住。`{}` 是合法的空背包, 只有 `undefined` 才是 bug。
  if (快照.已有背包 === undefined) {
    throw new Error(
      '快照缺少 `已有背包`（物品名 → 已有数量）: 掉落数量会覆盖玩家原有物品, 请检查 readSettlementSnapshot 的接线',
    );
  }

  // ── 入口守卫: 快照字段缺失 = 接线 bug, 不是 0 ─────────────────────────
  // 本函数写的是「旧值 + 增量」的**绝对值**, 而这些字段在 store 侧都经 `取数字()` ——
  // 一旦漏读, 它静默变 0, 写入就成了「0 + 本次获得」= **把玩家的余额清掉, 还弹「写入成功」**。
  // 与 `已有背包` 同款: 只挡 `undefined`（`null` 与 0 在卡里都是合法值, 放行）, 缺失时点名是哪个字段。
  const 必查数字: [string, unknown][] = [
    ['当前EXP', 快照.当前EXP],
    ['当前UP', 快照.当前UP],
    ['当前RP', 快照.当前RP],
    ['当前PEXP', 快照.当前PEXP],
    // `资格分` 的旧值藏在 computed.新资格分 里（= 旧资格分 + 本次）, 读漏同样会把赛季累计清零
    ['旧资格分', 快照.旧资格分],
  ];
  for (const [名, 值] of 必查数字) {
    if (值 === undefined) {
      throw new Error(
        `快照缺少 \`${名}\`: 写入是「旧值 + 增量」, 静默当 0 会把玩家余额清成「本次获得」, 请检查 readSettlementSnapshot 的接线`,
      );
    }
  }
  for (const 成员 of 快照.小队成员 ?? []) {
    for (const 名 of ['当前EXP', '当前UP'] as const) {
      if (成员[名] === undefined) {
        throw new Error(
          `快照的小队成员「${成员.名称}」缺少 \`${名}\`: 同上, 队友的余额会被静默清零`,
        );
      }
    }
  }

  // ── 四个增量（旧值 + 增量）────────────────────────────────────────────
  记(['头部', 'EXP_当前'], 快照.当前EXP + c.最终EXP);
  记(['经济', 'UP'], 快照.当前UP + c.最终UP);
  记(['头部', 'RP_当前'], 快照.当前RP + c.RP);
  记(['职业', 'PEXP_当前'], 快照.当前PEXP + c.PEXP);

  // ── 资格分 / CR / 周期 / 现实日期（规则第十、十一步）──────────────────
  // 新资格分 = 快照.旧资格分 + 本次, 由 computeSettlement 算好 —— 旧值漏读的后果由入口守卫挡
  记(['资格分'], c.新资格分);
  记(['头部', 'CR'], c.更新后CR);
  记(['头部', '回廊态度'], c.更新后回廊态度);
  记(['赛季信息', '当前副本周期'], c.新周期);
  // 格式不认识时 computed 给空串 —— 此时**整条跳过**, 而不是把日期抹成空串（那比不更新更糟）
  if (c.新现实日期 !== '') 记(['当前时间', '现实日期'], c.新现实日期);

  // ── 副本经历 / 称号 ──────────────────────────────────────────────────
  记(['副本经历', 快照.副本名称], { 评价等级: c.评价等级, 简要说明: ai.史诗记录 });
  // 称号交给聊天：只记录备用称号, **绝不碰** `头部.称号.当前称号`（替换与否由玩家在聊天里决定）。
  // 与面板同一道 A/S 守卫 —— 否则「面板留空、存档里却躺着个称号」又会成为一对不同源的数
  const 称号 = (c.评价等级 === 'S' || c.评价等级 === 'A') ? ai.称号 : null;
  记(['头部', '称号', '备用称号（只记录不生效）'], 称号 ?? { 名称: '无', 效果: {} });

  // ── 队友：位阶修正统一用玩家的, 拿到与玩家**完全相同**的最终 EXP / UP ──
  for (const 成员 of 快照.小队成员) {
    记(['小队', '成员', 成员.名称, '头部', 'EXP_当前'], 成员.当前EXP + c.最终EXP);
    // 实体 schema 没有 `经济` 字段, 队友的 UP 落在背包的「现金UP」条目上
    记(['小队', '成员', 成员.名称, '背包', '现金UP', '数量'], 成员.当前UP + c.最终UP);
  }

  // ── 掉落（规则第八步）────────────────────────────────────────────────
  // 同名掉落**先聚合再写**, 且累加到背包里已有的数量上 —— `_.set` 是覆盖语义:
  // 直接写本次数量会把玩家原有的同名物品冲掉（原有 3 把 + 掉落 1 把 应得 4 把, 不是 1 把）
  for (const [名, d] of 聚合掉落物品(ai.掉落物品)) {
    记(['背包', 名, '数量'], (快照.已有背包?.[名] ?? 0) + d.数量);
    记(['背包', 名, '描述'], `${d.品质}｜${d.属性}｜${d.效果}`);
  }

  // ── 副本资料清除（规则第十一步）──────────────────────────────────────
  for (const k of ['其他契约者', '副本角色', '其他契约者名单', '固有角色名单']) 记([k], {});
  for (const k of ['副本名称', '副本来源', '副本类型', '时间限制']) 记(['当前副本元数据', k], '未生成');
  记(['当前副本元数据', '基准等级'], 1);
  for (const k of ['名称', '说明', '奖励']) 记(['当前副本任务', '主线任务', k], '无');
  记(['当前副本任务', '主线任务', '状态'], '进行中');
  for (const k of ['支线任务', '世界事件', '隐藏任务', '副本成就']) 记(['当前副本任务', k], {});

  return W;
}
