/** 算术的全部输入（AI 判定 + 变量快照, 两者都由调用方备好） */
export interface SettlementInputs {
  评价等级: 'S' | 'A' | 'B' | 'C' | 'D' | 'F';
  击杀: { 精英: number; BOSS: number; 隐藏BOSS: number };
  副本天数: number;
  基础EXP汇总: number;
  基础UP汇总: number;
  /** 本次完成的支线任务数（= AI 报告的 `完成的支线`.length）—— 资格分的「支线+5/条」用它, **不是**职业专属支线条数 */
  完成的支线数: number;
  /** 完成的**隐藏任务**数 —— 只计变量（`快照.隐藏任务清单`）里真的存在的那些（`存在条目数` 的产物） */
  隐藏任务数: number;
  /** 每个已达成成就的星数（★=1 … ★★★★★★=6）—— 只含变量里真的存在的成就, 由 `成就星数` 产出 */
  成就星数: number[];
  天赋试炼次数: number;
  /** 只用于第六步 PEXP 的「掷 50~100 × 条数」；**资格分的「支线+5/条」用的是 `完成的支线数`**, 别混 */
  职业专属支线条数: number;
  /** 结算前的 CR */
  CR: number;
  /** 玩家的阶位, 一阶~五阶 */
  阶位: string;
  /** 当前的副本周期, **1~10 的整数**（规则第十一步: +1, 超 10 归 1）。缺失/越界一律抛错, 不静默兜底 */
  旧周期: number;
  旧资格分: number;
  /**
   * 结算前的**现实日期**（= 快照的 `当前现实日期`, 格式 `2025年5月10日`）。
   * ⚠️ 不是快照的 `当前现实时间` —— 那个是**时刻**（`凌晨00:01`）, 喂进来 `加天数` 只会恒返回空串。
   */
  现实日期: string;
}

