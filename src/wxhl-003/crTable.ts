/**
 * CR → 它所在的那一档。
 *
 * 判法是「**取第一个 `上界 >= cr` 的档**」, 不是 floor、也不是 `下界 <= cr <= 上界`
 * 的两头判 —— 后者会让区间**缝隙**落空。
 *
 * - **缝隙**（`2.95` / `4.05` / `6.05` / `8.05` / `9.95`）归**下一档**（保守侧）。
 *   CR 的实际取值是 `k×0.5 + m×0.3`, 即 0.1 的整数倍, 所以这些值**不可达** ——
 *   但行为必须**定义**且被测试钉住, 否则将来 CR 算法一改就会静默错档。
 * - `0` / 负数 → 首档（漠视, 即下限）: 负值走 `cr <= 2.9` 自然落在首档。
 * - `NaN` → 首档。**必须显式挡**: `NaN <= x` 恒为 `false`, 不挡的话它会一路穿到末档
 *   （= 炼狱 ×15.0）—— 把一个「读坏了的值」变成最狠的倍率, 方向正好反了。
 * - 绝不抛错: CR 由卡 clamp 在 1~10, 但函数本身要稳。
 */
export function CR区间(cr: number): CR档 {
  if (Number.isNaN(cr)) return CR表[0];
  for (const 档 of CR表) if (cr <= 档.上界) return 档;
  // ±∞ 之外不可达（10 已是表的上界顶）; 留着只为让返回值恒为 CR档 而非 undefined
  return CR表[CR表.length - 1];
}

/** CR → 回廊态度（漠视/观察/关注/重视/期待/炼狱） */
export function 回廊态度(cr: number): string {
  return CR区间(cr).态度;
}

/** CR → 生机评估（正常运转/略有风险/危机四伏/险象环生/九死一生/十死无生） */
export function 生机评估(cr: number): string {
  return CR区间(cr).生机评估;
}

/** CR → 基准等级偏移（0 / 2 / 4 / 8 / 16 / 32） */
export function 基准等级偏移(cr: number): number {
  return CR区间(cr).基准等级偏移;
}

/** CR → 结算倍率（1.0 / 1.2 / 1.5 / 3.0 / 6.0 / 15.0） */
export function 结算倍率(cr: number): number {
  return CR区间(cr).结算倍率;
}

/**
 * **基准等级 = 玩家等级 + CR 档的基准等级偏移**。
 *
 * 这是「同源」的**唯一实现**。两处调用点都必须经它, 谁也不许自己加一遍偏移:
 * - `dungeonRules.mapToVariables` → 写进 `当前副本元数据.基准等级`
 * - `store.generateEnemies` → 传给 `buildEnemyPrompt`（由它算杂兵/精英/BOSS 三级等级）
 *
 * 此前两处靠「同一个 `readPlayerBrief()` 的同一字段」保证一致; 现在两处各自要加偏移,
 * 各写一遍就会漂移（改规则时只改一处, 于是写进存档的基准等级与敌人实际等级对不上,
 * 而两边的画面「看起来都对」）。抽成一个函数后, 漂移在结构上不可能发生。
 *
 * 注: 这保证的是「**同一组输入**必得同一结果」。两次调用各自读一次 `readPlayerBrief()`,
 * 若玩家在这之间结算过副本（CR 变了）, 结果不同 —— 那是**输入**变了, 不是本函数的问题。
 */
export function 基准等级(玩家等级: number, cr: number): number {
  return 玩家等级 + 基准等级偏移(cr);
}
