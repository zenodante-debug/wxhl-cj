export interface ForumPost {
  id: number
  floor: number
  author: string
  time: string
  content: string
  depth?: number  // 0=OP, 1=comment, 2=nested reply
}

export interface ForumThread {
  id: number
  title: string        // t
  preview: string      // p
  author: string       // a
  replies: number      // r
  time: string         // tm
  hotComment: string   // hc
  hotAuthor: string    // ha
  hotLikes: number     // hl
  section: string
  posts?: ForumPost[]
}

export interface RankItem {
  rank: string      // 名次，字符串，如 '1'
  name: string      // 称号，含书名号，如 '「天榜之首·执剑镇国」'
  lv: string        // 等级，字符串，如 '100'
  team: string      // 势力短名，如 '中国特管局' / 'OETA' —— 供 UI「所属」列与副本生成匹配池使用
  realName: string  // 真名，如 '燕琉璃'
  gender: string    // '女' / '男'
  identity: string  // 身份，即「势力+职务」，如 '中国特管局总局长'
  className: string // 职业，如 '银色唯一职业·太虚剑主'
  bio: string       // 人设一句话，如 '压级五年拒绝终局试炼的摸鱼剑仙'
}

export interface RankBoard {
  key: string
  title: string
  items: RankItem[]
}

