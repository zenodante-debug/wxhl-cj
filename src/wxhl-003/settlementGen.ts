/**
 * 组装副本结算 prompt。
 *
 * `SETTLEMENT_RULES` 整段内联（含末尾的 `<Settlement Beautification>` 输出格式 —— 那套是给
 * 跑团 GM 用的, 这里必须用【优先级声明】点死「不适用于本次生成」并显式禁止 AI 输出面板,
 * 否则面板文本会混进 JSON, 导致 `extractJSON` 解析失败、整次结算白跑 —— 与 `<Panel Enhancement>`
 * 和 `<enemy>` 踩的是同一个坑）。
 *
 * AI 只做「判定」与「写文案」: 一切算术（最终EXP/最终UP/RP/PEXP/倍率/资格分）由系统完成,
 * 你算的数会被丢弃。
 *
 * @param 变量快照文本 从 stat_data 摘出的变量快照文本
 * @param 聊天记录     本次副本的聊天记录, 可为空
 * @param worldbookText 选中的世界书内容, 可为空
 */
export function buildSettlementPrompt(变量快照文本: string, 聊天记录: string, worldbookText: string): string {
  return `============ 任务 ============
为本次副本做结算。你只做「判定」与「写文案」, 一切算术由系统完成。

============ 规则原文 ============
${SETTLEMENT_RULES}

============ 输出格式（只回 JSON） ============
【优先级声明】上文规则原文的「结算格式:必须被<Settlement Beautification></Settlement Beautification>包含」那一整节
是给跑团 GM 用的, **不适用于本次生成** —— 结算画面由系统在收到你的 JSON 后另行拼装。
本次生成只按下面的 JSON 要求输出, 两处要求冲突时以本节为准。
**严禁**在 JSON 前后输出任何 <Settlement Beautification> 面板或结算画面, 那会导致解析失败、整次结算白跑。

只返回一个 JSON 对象, 不要 markdown 代码块, 不要任何解释文字。结构如下:
{
  "评价等级": "S/A/B/C/D/F",
  "评价依据": "字符串（简述你据以定级的依据）",
  "击杀": { "精英": 0, "BOSS": 0, "隐藏BOSS": 0 },
  "濒死次数": 0,
  "副本天数": 0,
  "完成的支线": [ "支线任务名的逐字键名" ],
  "完成的隐藏任务": [ "隐藏任务名的逐字键名" ],
  "达成的成就": [ "成就名的逐字键名" ],
  "职业专属支线条数": 0,
  "天赋试炼次数": 0,
  "掉落物品": [ { "名称": "字符串", "品质": "字符串", "属性": "字符串", "效果": "字符串", "数量": 1 } ],
  "称号": { "名称": "字符串", "效果": { "效果名": "效果内容" } },
  "史诗记录": "副本名称 + 评价 + 一句话史诗总结"
}

- 【不要计算】严禁输出任何算术结果(最终EXP/最终UP/RP/PEXP/倍率/资格分)—— 那些数值由系统计算。
  你只负责判定与文案。你算的数会被丢弃, 且会让系统无法判断你是否理解了任务。
- 【逐字一致】「完成的支线」「完成的隐藏任务」「达成的成就」里的名字, 必须与下面变量快照里的键名**逐字一致**。
  不确定的宁可不填, 也不要写近似的名字。
- 【评价等级】按规则原文第一步的判据给出 S/A/B/C/D。**若主线失败, 填 "F"** —— 系统会据此中止结算。
- 【称号.效果必须是字符串】「称号」的「效果」是 { 字符串: 字符串 } 的映射, **即使内容是数值也要写成字符串**
  （如 {"攻击力": "攻击力+10"}, 不能写 {"攻击力": 10}）。系统做的是严格类型校验, 写成数值会让整次结算 parse 失败、白跑一次。
- 【掉落物品】严格按 <装备与消耗品系统> 生成名称/品质/属性/效果, 并考虑第八步的 CR 掉落加成。
- 【掉落物品.数量】每一项的「数量」是整数且**至少为 1**, 不能填 0; 系统做的是严格校验, 填 0 会让整次结算 parse 失败、白跑一次。
- 【称号】仅当评价为 A 或 S 时给出; 否则填 null。
- 【副本天数】取变量快照里「当前时间.客观时间」的值 —— 它记录的是**本次副本已度过的天数**。
  若该字段缺失、或是「不在副本中」这类非天数内容, 则结合聊天记录判断; 仍判不出就填 0（不要编造）。

============ 变量快照 ============
${变量快照文本}

============ 聊天记录 ============
${聊天记录 || '（未读取到聊天记录）'}

============ 世界观/规则参考 ============
${worldbookText || '（无世界书内容）'}
`;
}

// ================================================================
// 结算空间 · Prompt 构造（结算**已写入存档之后**）
// ================================================================

/** 数字展示: 整数不带小数点, 小数保留一位（与结算面板的 `显示数字` 同口径） */
function 数字(x: number): string {
  return String(Math.round(x * 10) / 10);
}

/** 把非空片段用 `｜` 连起来（空片段丢掉, 免得印出 `｜｜`）—— 与面板的 `连接` 同口径 */
function 连接(段: string[]): string {
  return 段.filter(s => s !== '').join('｜');
}

/** 空串 / undefined 都算「没写」, 一律换成显式占位 —— 与面板的 `或占位` 同口径 */
function 或占位(值: string | undefined, 占位: string): string {
  const v = 值 ?? '';
  return v === '' ? 占位 : v;
}

/** `标签: 值`；值为空时返回空串（整段随后被 连接 丢掉）—— 与面板的 `标注` 同口径 */
function 标注(标签: string, 值: string): string {
  return 值 === '' ? '' : `${标签}: ${值}`;
}

/**
 * `说明` 为空时的显式占位 —— 与面板的两个常量**逐字相同**（`settlementRules.ts` 里各一份）。
 *
 * ⚠️ 这是刻意的重复实现: 面板与叙事 prompt 必须给出**同一份**文案, 否则同一份结算在两处
 * 会显示不同的「达成条件」。本次审查明确「不合并这两份拷贝」（跨模块重构留待专项),
 * 因此这里按面板的原文照抄, 并由测试逐字比对两侧产物 —— 一旦哪边漂开, 测试即红。
 */
const 无达成条件 = '（变量中未记录达成条件）';
/** `隐藏任务清单` 的 `说明` 为空时的占位（它不是「达成条件」, 用更中性的措辞）—— 同面板 */
const 无说明 = '（变量中未记录说明）';

/** `称号.效果` → 一行文本（`嗜血: 击杀回血`）, 与面板的 `称号效果文本` 同口径 */
function 称号效果文本(效果: Record<string, string> | undefined): string {
  if (!效果) return '';
  return Object.entries(效果).map(([k, v]) => `${k}：${v}`).join('；');
}

/**
 * 掉落清单 —— 按物品名聚合、数量相加后再打印（与面板 / 写入清单同一口径:
 * AI 报两条同名掉落时要合成「×3」, 而不是两行）。
 */
function 掉落清单文本(掉落: SettlementGenResult['掉落物品']): string {
  const 合 = new Map<string, { 数量: number; 品质: string; 属性: string; 效果: string }>();
  for (const d of 掉落 ?? []) {
    const 旧 = 合.get(d.名称);
    if (旧) 旧.数量 += d.数量;
    else 合.set(d.名称, { 数量: d.数量, 品质: d.品质 ?? '', 属性: d.属性 ?? '', 效果: d.效果 ?? '' });
  }
  if (合.size === 0) return '无';
  return [...合].map(([名, d]) => `${名}（${连接([d.品质, d.属性, d.效果])}）×${d.数量}`).join('；');
}

/**
 * 组装「进入回廊结算空间」的提示词 —— 填入酒馆输入框（**只填入不发送**）。
 *
 * 用途: 结算**已经写进存档之后**, 把玩家送进回廊的「结算空间」, 让 AI 叙述本次结算发生了什么。
 *
 * ⚠️ 本 prompt 的第一要务是**阻止 AI 再结算一遍**: 规则原文 (`SETTLEMENT_RULES`) 里有一整套
 * 结算流程, 而 AI 看到「结算」二字极可能自己再跑一次 —— 本模块的写入是**累加**语义
 * （写进存档的是「旧值 + 增量」）, 重跑会让玩家数值**在已结算的基础上再加一倍且无法撤销**。
 * 所以硬约束段用「死命令」的措辞把五件事点死（见函数体), 并**刻意不内联规则原文** ——
 * 不在这个 prompt 里给它任何可以照着重跑的材料。
 *
 * 数值一律取自 `computed` / `快照`, 与结算面板**同源**（面板也是只读这两者):
 * 余额类（当前RP余额 / 当前PEXP）取「快照旧值 + 本次获得」, 与面板的一致。
 *
 * @param c   结算算术的产物（`computeSettlement` 的输出）
 * @param ai  AI 的判定与文案
 * @param 快照 结算前的变量只读视图（余额类要拿旧值 + 本次才能得到结算后的余额）
 */
export function buildSettlementEnterPrompt(
  c: SettlementComputed,
  ai: SettlementGenResult,
  快照: SettlementSnapshot,
): string {
  // 称号与面板同一道 A/S 守卫（规则第七步「未达 A 级直接跳过」）:
  // AI 在非 A/S 时本应回 null, 但它一次不听话就会在 prompt 里造出「获得称号」的假象。
  const 称号 = (c.评价等级 === 'S' || c.评价等级 === 'A') ? ai.称号 : null;
  const 称号段 = 称号
    ? `- 称号获得: ${称号.名称}\n- 称号效果: ${称号效果文本(称号.效果) || '无'}`
    : '- 称号获得: 无（本次评价未达 A/S, 按规则第七步「未达 A 级直接跳过」, 本次没有称号）\n- 称号效果: 无';

  // 完成与否拿 `ai` 的名单去比对 `快照` 的**全量清单**（含未达成 / 未触发）。
  const 已达成名 = new Set(ai.达成的成就 ?? []);
  const 已完成隐藏 = new Set(ai.完成的隐藏任务 ?? []);
  const 成就清单 = 快照.成就清单 ?? [];
  const 隐藏清单 = 快照.隐藏任务清单 ?? [];
  // 成就 / 隐藏任务的公示口径与面板**逐字一致**: 同样的列（难度 / 完成描述 / 达成条件 / 奖励）、
  // 同样的分隔符（`；` 分段、`｜` 分段内）、同样的空值占位。
  // 叙事 prompt 里把「你错过了什么（达成条件）」给 AI 是有用的 —— 与面板同一个理由。
  const 成就已达成 = 成就清单.filter(a => 已达成名.has(a.名称))
    .map(a => `${a.名称}（${连接([a.难度, 标注('完成描述', 或占位(a.说明, 无说明)), 标注('奖励', a.奖励)])}）`)
    .join('；') || '无';
  const 成就未达成 = 成就清单.filter(a => !已达成名.has(a.名称))
    .map(a => `${a.名称}（${连接([标注('达成条件', 或占位(a.说明, 无达成条件)), 标注('奖励', a.奖励)])}）`)
    .join('；') || '无';
  const 隐藏公示 = 隐藏清单
    .map(t => `${t.名称}（${连接([已完成隐藏.has(t.名称) ? '已完成' : '未触发', 或占位(t.说明, 无说明), 标注('奖励', t.奖励)])}）`)
    .join('；') || '无';

  // 现实时间 = 新日期 + 快照里的时刻（与面板同口径）; 日期认不出时如实说「未更新」, 不猜。
  const 现实时间 = c.新现实日期
    ? `${c.新现实日期} ${快照.当前现实时间}`
    : `${快照.当前现实时间}（现实日期格式无法识别, 本次未更新现实日期）`;
  const CR变动 = c.CR变动 === 0 ? '不变' : (c.CR变动 > 0 ? '+' : '') + 数字(c.CR变动);

  return `我已经完成了本次副本的结算, 现在被回廊送进了【结算空间】。
这里是契约者离开副本、拿到结算结果之后、尚未选择接下来去向的过渡空间。

============ 【最高优先级 · 死命令】本次结算已经全部完成, 严禁重做 ============
本次副本的结算已经由系统全部执行完毕, 所有变量都已经写进存档了 ——
EXP / UP / RP / PEXP / CR / 赛季资格分 / 副本周期 / 现实日期 / 背包掉落 / 副本经历 / 称号备用记录
全部已经更新完毕; 副本资料（副本元数据、当前副本任务、其他契约者、固有角色、副本角色）也已经清空。

所以下面五条是死命令, 必须逐条遵守:
1. 不要再执行 <副本结算> 的任何结算步骤。结算已经结束了 —— 没有第二次结算。
2. 不要再修改任何变量。不要 insert、不要 replace、不要 delta、不要 set 任何字段, 一个都不要改。
3. 不要再自己重算任何数值。下面「本次结算结果」里的数字就是最终结果; 若需要引用, 只能照抄它们,
   不要按倍率推算、不要重新掷骰、不要四舍五入成别的数。
4. 只输出叙事, 不要输出任何结算面板, 不要输出 <Settlement Beautification> 格式的文本,
   也不要输出「## 名称: 值」式的结算行 —— 那些结算画面已经由系统在别处给出, 不需要你重印一遍。
5. 违反以上任何一条, 会让玩家的 EXP / UP / RP / PEXP / 资格分在已结算的基础上再加一倍,
   而这无法撤销, 会直接毁掉玩家的存档。规则原文里那一整套结算流程是给「尚未结算」的情况用的,
   本次完全不适用, 请彻底忽略它。
（特别提醒: 不要因为你看到的剧情里有「结算」二字, 就再走一遍流程 —— 变量已经改完了。）

============ 本次结算结果（最终值, 仅供你叙述引用, 严禁重算） ============
- 最终评价: ${c.评价等级}（本次资格分 ${c.资格分_本次}）
- 评价倍率: ×${数字(c.评价倍率)}
- CR态度: ${c.CR态度}
- CR奖励倍率: ×${Math.round(c.CR奖励倍率 * 100)}%
- 位阶修正: ×${c.位阶修正}
- 基础EXP汇总: ${c.基础EXP汇总}
- 基础UP汇总: ${c.基础UP汇总}
- 最终EXP: ${c.最终EXP}
- 最终UP: ${c.最终UP}
- RP获得: ${c.RP}
- 当前RP余额: ${快照.当前RP + c.RP}
- PEXP获得: ${c.PEXP}
- 当前PEXP: ${快照.当前PEXP + c.PEXP}
${称号段}
- 掉落清单: ${掉落清单文本(ai.掉落物品)}
- CR变动: ${CR变动}
- 更新后CR: ${数字(c.更新后CR)}
- 回廊态度: ${c.更新后回廊态度}
- 史诗记录: ${快照.副本名称} · ${c.评价等级} · ${ai.史诗记录}
- 副本周期: ${c.新周期}
- 现实时间: ${现实时间}
- 副本成就已达成: ${成就已达成}
- 副本成就未达成: ${成就未达成}
- 隐藏任务公示: ${隐藏公示}

============ 请你做什么 ============
请以【回廊结算空间】为场景写一段开场叙事: 契约者刚结束副本、被回廊接引到这个结算空间,
本次结算已经落定。空间的氛围（光影、声音、悬浮的结算文字、回廊的低语等）你可以自由发挥,
但不要再把上面的结果算一遍, 只需让玩家感受到「结算已经完成、这里是结算空间」。

叙事末尾, 请把接下来的选择摆给玩家（结算后流程, 强制二选一, 等我在聊天里告诉你选择）:
1. 进入休息周期（回廊主城停留 24 小时 + 现实世界回归 6 天）。
2. 花费 UP 延长副本滞留（50 UP/天，上不封顶）。`;
}
