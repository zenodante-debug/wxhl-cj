/**
 * 组装「本次副本获得物品」的 prompt（2026-09-25 改：AI 只生成物品）。
 *
 * 旧版 `buildSettlementPrompt` 让 AI 一次做六件事（评价/击杀/完成判定/掉落/称号/史诗记录）；
 * 现在评价与完成判定已改为**脚本读变量**（见 `settlementRules.判定评价等级`），
 * 称号与副本经历改由**正文 AI** 在结算写入后用提示词完成（见 `buildSettlementEnterPrompt`）。
 * 于是这里只剩一件事：**按规则生成掉落物品清单**。
 *
 * 与其他 prompt 同款的两个坑照旧要挡：
 * - `SETTLEMENT_RULES` 的 `<Settlement Beautification>` 是给跑团 GM 的，必须显式点死「不适用」，
 *   否则面板文本混进 JSON → `extractJSON` 解析失败 → 整次白跑。
 * - 「效果必须是字符串」「数量 ≥1」是严格类型校验，破了就 parse 失败。
 *
 * @param 完成清单文本 本次完成的主线/支线/隐藏/成就清单 + 各自奖励原文（由脚本从变量摘出）
 * @param 评价等级     脚本判定的评价（用于 CR 掉落加成的档位参考）
 * @param CR态度       结算前的回廊态度（决定 CR 掉落加成档）
 * @param 聊天记录     本次副本的聊天记录, 可为空
 * @param worldbookText 选中的世界书内容, 可为空
 */
export function buildItemGenPrompt(
  完成清单文本: string,
  评价等级: string,
  CR态度: string,
  聊天记录: string,
  worldbookText: string,
): string {
  return `============ 任务 ============
为本次副本生成「获得的物品」清单。**只生成物品**, 不要做任何其他事。

============ 规则原文（供你查装备/消耗品的生成规范） ============
${SETTLEMENT_RULES}

============ 输出格式（只回 JSON） ============
【优先级声明】上文规则原文里「结算格式必须被 <Settlement Beautification> 包含」那一整节是给跑团 GM 用的,
**不适用于本次生成**。本次**只生成物品清单**, 结算画面、评价、称号、史诗记录等全部由系统另行处理。
**严禁**输出任何 <Settlement Beautification> 面板或结算画面 —— 那会导致解析失败、整次白跑。

只返回一个 JSON 对象, 不要 markdown 代码块, 不要任何解释文字。结构如下:
{
  "掉落物品": [ { "名称": "字符串", "品质": "字符串", "属性": "字符串", "效果": "字符串", "数量": 1 } ]
}

- 【只做这一件事】**不要**输出评价等级、击杀、濒死、完成名单、称号、史诗记录 ——
  评价与完成情况已由系统从变量判定完毕, 你输出的这些字段会被丢弃。
- 【依据】按 <装备与消耗品系统> 生成名称/品质/属性/效果; 严格参考上面「本次完成的任务与成就」里
  各自的**奖励原文**（那是本次该发放的东西）, 并考虑下面给出的 CR 掉落加成。
- 【技能】技能以**技能书 / 卷轴**这类物品形式发放（名称如「XX技能书」）, 与装备一样作为物品, 不要另立字段。
- 【数量】每一项的「数量」是整数且**至少为 1**, 不能填 0; 系统做严格校验, 填 0 会让整次 parse 失败。
- 【效果】「效果」写成字符串（即使是数值也写成字符串）。
- 【宁缺毋滥】没有掉落就给空数组 []，不要编造。

============ 本次完成的任务与成就（含奖励原文） ============
${完成清单文本}

============ 本次评价 / CR（仅供掉落加成参考, 不要复述） ============
- 评价等级: ${评价等级}
- 结算前回廊态度（CR态）: ${CR态度}

============ 聊天记录 ============
${聊天记录 || '（未读取到聊天记录）'}

============ 世界观/规则参考 ============
${worldbookText || '（无世界书内容）'}
`;
}

