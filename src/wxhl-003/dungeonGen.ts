/** 把掷骰记录排成对齐的锁定骰值表 */
function formatLockedRolls(records: RollRecord[]): string {
  return records.map(r => `| ${r.标签} | ${r.表达式} | ${r.骰值} | ${r.映射 || '—'} |`).join('\n');
}

/**
 * 组装副本生成 prompt。
 * @param playerText   从 stat_data 摘出的玩家数据文本
 * @param worldbookText 选中的世界书内容, 可为空
 * @param 匹配池        按 CR 规则取出的榜单候选, 或「自由生成同阶契约者」指令
 * @param 阶位          契约者当前阶位, 作为物品阶位的硬性约束写进 prompt
 * @param 队伍最高等级   契约者小队的最高等级, 用于「固有角色动态升维机制」判定
 * @param 生机评估      按 CR 档取出的凶险判定（crTable.生机评估）, 作为本次副本的难度氛围上下文。
 *                      它**不参与任何数值**, 只是告诉 AI 这个世界该有多危险 ——
 *                      数值那一半由「基准等级偏移」在敌人生成时落地。
 */
export function buildDungeonPrompt(
  build: BuildRoll,
  records: RollRecord[],
  playerText: string,
  worldbookText: string,
  匹配池: string,
  阶位: string,
  队伍最高等级: number,
  生机评估: string,
  自选世界观?: string,
  队友指定?: { 来源世界观?: string; 人物?: string },
  /**
   * 本次生成的可选附加段与开关。
   * 分组成一个对象而不是三个位置参数: 本函数已有 10 个位置参数, 再散着加会到 13 个。
   */
  附加?: {
    /** 同人契约者开关（CR≥5 时面板上可选）。关闭或缺省 ⇒ 不出现该段 */
    同人契约者?: { 开关: boolean; 性别: string };
    /** 动态事件段（`dungeonEvents.buildEventSection` 的产物）。空串 = 不注入 */
    动态事件段?: string;
    /** 是否触发晋升试炼（等级满了当前位阶上限） */
    晋升试炼?: boolean;
  },
): string {
  const 动态事件段 = 附加?.动态事件段 ?? '';
  const 世界观锚定 = 自选世界观
    ? `
============ 世界观锚定（契约者指定, 强制） ============
本次副本的世界观已由契约者亲自指定为《${自选世界观}》。
- 你必须把上述骰值（副本类型/题材大类/时代背景/核心特色标签/副模块）全部翻译进《${自选世界观}》的世界观里;
  若骰值字面与该世界观冲突, 以该世界观为容器做等价转译, 而不是更换世界观。
- 「IP热度」骰本次失效: 世界观已被指定, 不要据此更换或稀释它。
- 「副本来源」字段填《${自选世界观}》（媒介来源）。
`
    : '';
  const 队友锚定 =
    队友指定 && (队友指定.来源世界观 || 队友指定.人物)
      ? `
============ 队友指定（契约者自选, 强制） ============
${
  队友指定.来源世界观
    ? `- 队友来源世界观固定为《${队友指定.来源世界观}》：本次「其他契约者」必须是来自该世界观的角色（IP 角色队友）。\n`
    : ''
}${
          队友指定.人物
            ? `- 队友具体人物指定为：${队友指定.人物} —— 「其他契约者」数组必须恰好是他们, 不多不少。\n`
            : ''
        }- 本节优先级高于后文「匹配参考」与新手副本的「随机世界观 IP 队友」规则：指定了什么就是什么。
- 若指定人物与本次副本世界观不同, 仍按指定执行 —— 他们作为「跨界降临的契约者」登场, 在说明中体现其穿越者身份。
`
      : '';
  const 队友来源锚定 = `
============ 队友来源锚定（强制） ============
本次【队友标签】= ${build.队友标签}。它只用来圈定「哪些 IP 可以被匹配」这个范围。
- 「其他契约者」里的 **IP / 同人角色**必须取自该标签范围内的**真实 IP 作品**里的**真实角色**，
  真名公开；不得凭空原创、不得跨到标签范围外的作品。
- 其**来源世界观不得与本次副本世界观相同**（副本世界观见上文与本段之后的信息）。
- **等级锚定**：IP 队友都是**资深契约者**，等级必须按匹配规则与玩家相近
  （同 CR → 同阶位 → 等级相近），不要随手给一个数字。
  **例外**：新手副本的那名 IP 队友是 **Lv.1 新人**，与玩家同为新人。
- 回廊原生契约者不受本段约束，仍按后文「匹配参考」的名单与规则走。
`;
  const 同人段 = 附加?.同人契约者?.开关
    ? `
============ 同人契约者（本次开启） ============
本次**恰好匹配 1 名同人契约者**，不多不少。其**性别**为【${附加.同人契约者.性别}】。
该角色同样受上一段的「队友标签 → 世界观 → 真实角色」与「不得与本次副本世界观相同」约束。
`
    : '';
  const 晋升试炼段 = 附加?.晋升试炼
    ? `
============ 晋升试炼（回廊强制 · 不可拒绝） ============
契约者已达到当前位阶上限，回廊强制触发晋升试炼。
- 你生成的**第 3 条支线任务**必须就是【专属晋升任务】，且**恰好是第 3 条**（不改条数）。
- 它的难度必须是**极高**：单杀隐藏BOSS / 收集特定规则道具 / 完成某某仪式 一类，
  不是普通支线能比的；说明里要写清判定方式。
- 它的「物品名」字段填空字符串（本次不给物品奖励）。
- 它的**奖励由系统另行写入**（晋升奖励），你**不要**输出 UP / EXP / RP 相关文字。
- 若本次同时生效了「回廊淘汰赛」等事件：晋升任务仍以支线形式发放，
  **不干涉淘汰赛的生存与排名规则**；队伍中其他未晋升的队友可协助完成它。
- 主线与晋升支线的关系：主线成功但晋升支线未完成 = 晋升失败（**无惩罚**）；主线失败 = 抹杀。
`
    : '';
  return `${DUNGEON_GENERATION_RULES}
${世界观锚定}${队友锚定}${队友来源锚定}${同人段}
============ 本次掷骰已锁定, 严禁改动 ============
以下骰值由系统用密码学随机数掷定, 已经锁定。你**严禁**改动、重掷、忽略、四舍五入或自行编造任何数值。
你唯一的职责是把这些骰值翻译成符合规则的内容。若某条骰值与你的构思冲突, 以骰值为准。

【本次锁定骰值】
- 副本类型: ${build.副本类型}${build.副本类型被日常规则覆盖 ? '（原骰值被日常副本调和规则强制覆盖）' : ''}
- 媒介来源: ${build.媒介来源}
- 题材大类: ${build.题材大类}
- 时代背景: ${build.时代背景}
- 核心特色标签: ${build.核心特色标签}
- 副模块: ${build.副模块}
- IP热度: ${build.IP热度}
- 时间限制: ${build.时间限制天} 天
- 本次为${build.是新手副本 ? '【新手副本】—— 强制和平, 且只匹配 1 名来自随机世界观的 IP 角色队友, 同为新人' : '常规副本'}
${build.是日常副本 ? '- 本次为【日常副本】—— 核心特色标签 ∈ 41~50, 规则 §6 日常副本调和规则强制生效, 优先级高于副本类型与副模块的字面冲突' : ''}

【全部掷骰明细（含奖励骰, 供你核对）】
| 标签 | 表达式 | 骰值 | 映射 |
|------|------|------|------|
${formatLockedRolls(records)}
${动态事件段 ? `
⚠️ 例外（仅在本次有动态事件时生效）: 若下文「本次副本的动态事件」强制要求某个字段
（如副本类型），**以动态事件为准**；其余未被事件点到的骰值仍然严禁改动。
` : ''}
注: UP / EXP / RP / 物品品质 / 物品类型的**数值与档位已由系统掷定**, 你不要输出这些数值,
只需要为每个需要物品的任务给出一个符合本副本世界观的具体物品名。

============ 固有角色锚定规则（强制） ============
${INHERENT_CHARACTER_ANCHOR_RULES}

【本次契约者队伍最高等级】Lv.${队伍最高等级}
请按上述「固有角色动态升维机制」判断：若该世界观的**原著战力天花板**高于 Lv.${队伍最高等级}，
则严格保持原著等级与实力锚点、不执行向上修正；若低于或等于，则对固有角色升维，
强制拉升至契约者同阶或更高，以保证压迫感。

固有角色的「位阶」只能取: 凡人极限 / 一阶 / 二阶 / 三阶 / 四阶 / 五阶 / 超脱。
其「等级」必须落在该阶位对应的等级区间内（凡人极限固定 Lv.1；一阶 1~20；二阶 21~40；
三阶 41~60；四阶 61~80；五阶 81~100；超脱 101 以上）。
请自行确保两者一致 —— 系统会校验并把越界的等级夹回区间，但那会偏离你的本意。

【固有角色的选取与强度锚定 —— 强制】
1. 选取范围: 只从**本次副本剧情实际牵涉到**的原著角色里选 —— 该篇章、该事件、该时间点上
   真正登场或与之直接相关的人物。不要因为某个角色有名就选他; 不要一律挑该世界观的最终BOSS
   或战力天花板。副本发生在哪一段剧情, 就选那一段里该出现的人。
2. 强度锚定: 先回想这个角色在**原著中的真实表现**（他做过什么、被什么伤到过、打不过谁、
   在剧情里处于什么位置）, 再对照上面锚定表的「战力表现」列**反查**他该落在哪一档,
   而不是凭名气或印象直接给高阶。
3. 分布预期: 绝大多数副本的固有角色应集中在**与副本剧情相称**的档位。
   五阶（天灾级）与超脱者是世界观的顶尖存在, **只在副本剧情真的牵涉到他们时才出现**;
   超脱者按规则「不下场」, 通常只作为背景被提及, 不应作为实际登场的固有角色。
4. 升维机制的正确触发: 升维**只在**「契约者队伍最高等级 ≥ 该世界观原著战力天花板」时触发。
   本次队伍最高等级为 Lv.${队伍最高等级} —— 只有当这个数确实 ≥ 该世界观的天花板时才升维;
   绝大多数世界观的天花板都远高于此, 因此通常**不触发**, 请老实照原著锚点。
   触发时按规则是「拉升至契约者同阶或更高」, 但你仍应按第 1~3 条挑人 ——
   不要借升维之名把固有角色一律堆到五阶。
5. 常见误判提醒:
   - 锚定表的「锚点示例」每档只举了一两个代表性角色, **不代表该档就该是这些名角色**。
     一个世界观里, 剧情实际登场的人物绝大多数是中低阶的; 顶端角色只在特定篇章才出现。
   - **同一个角色在不同篇章的强度可能完全不同**（成长前 / 成长后 / 觉醒前后）。
     请按**本次副本所处时间线**的那个状态来锚定, 不要用该角色的最终形态。
   - 判定强度时优先看「这个角色在**本副本对应的那段剧情里**做过什么、被谁压制过」,
     而不是看他在整部作品的巅峰表现。

============ 回廊难度评估 ============
回廊对本次副本的生机评估: 【${生机评估}】
这是回廊系统按契约者当前 CR 给出的凶险判定。本次敌人生成的基准等级也已按**同一档**抬高。
请让本次副本的世界危险度、敌对强度与剧情压迫感与这个评估相称 ——
不要把「九死一生」的副本写成春游, 也不要把「正常运转」的副本写成绞肉机。
${晋升试炼段}${动态事件段 ? '\n' + 动态事件段 + '\n' : ''}
============ 契约者数据 ============
${playerText || '（未读取到玩家数据）'}

============ 匹配参考 ============
${匹配池 || '（无）'}
${worldbookText ? '\n============ 世界观参考 ============\n' + worldbookText : ''}

============ 输出要求 ============
【优先级声明】上面规则原文末尾的「## 输出格式保真」与 \`<Panel Enhancement>\` 模板是给跑团 GM 用的,
**不适用于本次生成**。本次生成只按下面的 JSON 要求输出, 两种要求冲突时以本节为准。
（原因: 规则原文里那套是「把成品面板打印到聊天楼层」的格式; 本次只是产出数据, 面板文本由系统另行拼装。）

只返回一个 JSON 对象, 不要 markdown 代码块, 不要任何解释文字。字段如下:
{
  "副本名称": "字符串",
  "副本来源": "《作品名》（媒介来源）",
  "副本背景": "字符串",
  "日常调和说明": "非日常副本填空字符串",
  "主线任务": { "名称": "字符串", "说明": "字符串" },
  "支线任务": [ { "名称": "字符串", "说明": "字符串", "物品名": "字符串" } ],
  "世界事件": [ { "名称": "字符串", "说明": "字符串", "影响": "字符串" } ],
  "隐藏任务": [ { "名称": "字符串", "说明": "字符串", "物品名": "字符串" } ],
  "副本成就": [ { "名称": "字符串", "说明": "字符串", "难度": "字符串", "物品名": "字符串" } ],
  "固有角色": [ { "名称": "字符串", "位阶": "字符串", "等级": 数字 } ],
  "其他契约者": [ { "真名": "字符串", "称号": "无或称号", "等级": 数字, "阵营": "字符串" } ],
  "事件点名角色": [ "字符串" ]
}

数量硬性要求: 支线任务恰好 3 条, 世界事件恰好 2 条, 隐藏任务恰好 2 条, 副本成就恰好 6 条
（副本成就必须按 ★ 探索级 → ★★ 挑战级 → ★★★ 破局级 → ★★★★ 史诗级 → ★★★★★ 传说级 → ★★★★★★ 世界天花板 的顺序）。
副本成就的「难度」字段只填**该成就的达成难度描述**（如「顺路可完成的环境交互」）,
**不要**把梯度档位名写进去 —— 档位名由系统另行拼接, 你重复写会导致面板显示成「★ 探索级 · ★ 探索级」。
物品名必须出自本副本世界观的具体设定, 禁止通用化（不要写「一把剑」, 要写《作品名》里真实存在的具体物品）。
物品的**品质与类型已由系统掷定, 你无权改动**。
物品的**阶位固定为【${阶位}】**（即该契约者的当前阶位）, 你选择的具体物品名必须确实是该阶位下合理存在的物品：
不要给低阶契约者该世界观里最高阶的专属物、神器或最终BOSS掉落, 也不要给高阶契约者路边随处可见的杂货。
所有契约者真名公开, 禁止代号或假名。
- 「事件点名角色」只填**本次生效的动态事件强制要求在场**的人物**真名**（逐字，与事件正文一致）。
  **绝对不要把契约者本人（{{user}}）列进去** —— 他必然在场，写进去会被系统判成「点名了缺席者」。
  没有事件、或事件没点名任何具体人物时，填空数组 \`[]\`。`;
}

/** 玩家视角的「进入副本」提示词, 填入酒馆输入框（只填入不发送） */
export function buildEnterPrompt(result: DungeonGenResult, build: BuildRoll): string {
  // 容忍 result 缺少 其他契约者（阈值测试传入的是最小对象）; 正常路径下 schema 保证其为数组
  const 队友 = result.其他契约者?.length ?? 0;
  return `传送完成，我踏入了本次副本的降临点。

本次副本【${result.副本名称}】的资料已经写入我的契约者档案——当前副本元数据、当前副本任务、其他契约者名单、固有角色名单。

请读取这些变量，以我进入副本后的开场场景作为回复，需要包含：
1. 我降临的具体地点、时间与当前处境
2. 本次副本的时间限制与阶段进度
3. 主线任务的下达（以回廊系统的口吻呈现）
4. 与我同时降临的 ${队友} 名其他契约者，以及他们在我视野内的样子
5. 出现在我视野内的固有角色

副本类型是【${build.副本类型}】，副模块是【${build.副模块}】，时间限制 ${build.时间限制天} 天。`;
}

