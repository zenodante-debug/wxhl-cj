import { describe, expect, it } from 'vitest';
import { 位阶修正值系数, 位阶属性软上限, 位阶档位, 位阶等级上限 } from '../statusbar/tier';

// 2026-10-08：位阶判定从「精确等值」改为「关键词筛选」——超脱与各种写法都要认。
// 背景：原先 `rankStr === '三阶'` 这类判断遇到「超脱者」「一阶巅峰」「2阶」一律落到默认值，
// 于是超脱被当成一阶、属性修正/软上限/等级上限全算错。
describe('位阶档位 · 关键词筛选', () => {
  it('标准写法', () => {
    expect(位阶档位('一阶')).toBe(0);
    expect(位阶档位('二阶')).toBe(1);
    expect(位阶档位('三阶')).toBe(2);
    expect(位阶档位('四阶')).toBe(3);
    expect(位阶档位('五阶')).toBe(4);
  });

  it('超脱的三种写法都归到超脱阶（原先会被当成一阶）', () => {
    expect(位阶档位('超脱')).toBe(5);
    expect(位阶档位('超脱阶')).toBe(5);
    expect(位阶档位('超脱者')).toBe(5);
  });

  it('带后缀/前缀/混合写法也能认（这正是精确匹配会漏的）', () => {
    expect(位阶档位('一阶巅峰')).toBe(0);
    expect(位阶档位('二阶·觉醒')).toBe(1);
    expect(位阶档位('第3阶')).toBe(2);
    expect(位阶档位(' 五阶 ')).toBe(4);
  });

  it('阿拉伯数字与汉字都认', () => {
    expect(位阶档位('2阶')).toBe(1);
    expect(位阶档位('5')).toBe(4);
  });

  it('超脱优先于数字：不会被里面的字误判', () => {
    expect(位阶档位('超脱')).toBe(5);
    expect(位阶档位('超脱阶')).toBe(5);
  });

  it('认不出返回 undefined（由调用方兜底成一阶），不猜', () => {
    expect(位阶档位('')).toBeUndefined();
    expect(位阶档位('无')).toBeUndefined();
    expect(位阶档位(undefined)).toBeUndefined();
    expect(位阶档位(null)).toBeUndefined();
  });
});

describe('位阶系数表 · 超脱 = 20（与市场/工坊同表）', () => {
  it('修正值系数 1/2/4/7/11/20', () => {
    expect([...位阶修正值系数]).toEqual([1, 2, 4, 7, 11, 20]);
    expect(位阶修正值系数[位阶档位('超脱')!]).toBe(20);
    expect(位阶修正值系数[位阶档位('超脱者')!]).toBe(20);
  });

  it('属性软上限与等级上限：五阶起不再封顶', () => {
    expect([...位阶属性软上限]).toEqual([25, 40, 55, 70, 9999, 9999]);
    expect([...位阶等级上限]).toEqual([20, 40, 60, 80, 100, 9999]);
    expect(位阶属性软上限[位阶档位('五阶')!]).toBe(9999);
    expect(位阶等级上限[位阶档位('超脱')!]).toBe(9999);
  });
});
